# Модели эмбеддингов по ключу: когда выбранная недоступна (404), берём подходящую из списка cloud.ru
_ЭМБЕДДИНГ = re.compile(r"embed|bge|e5|gte", re.I)
_НЕ_ЭМБЕДДИНГ = re.compile(r"rerank|whisper|tts|asr|speech", re.I)
_ПРЕДПОЧТЕНИЕ = ("bge-m3", "qwen3-embedding", "multilingual-e5", "e5", "embed")
_замены: dict[tuple[str, str], str] = {}        # (адрес, выбранная модель) → рабочая замена на время работы программы


def модели_эмбеддингов(адрес: str, ключ: str) -> list[str]:
    """Модели эмбеддингов, доступные по ключу, лучшие для русского — первыми."""
    подходящие = [м["id"] for м in список_моделей(адрес, ключ)
                  if _ЭМБЕДДИНГ.search(м["id"]) and not _НЕ_ЭМБЕДДИНГ.search(м["id"])]

    def вес(имя: str) -> int:
        низ = имя.casefold()
        return next((i for i, п in enumerate(_ПРЕДПОЧТЕНИЕ) if п in низ), len(_ПРЕДПОЧТЕНИЕ))
    return sorted(подходящие, key=lambda м: (вес(м), м.lower()))


def рабочая_модель_эмбеддингов(адрес: str, модель: str) -> str:
    """Выбранная модель или её замена, если выбранной не нашлось у cloud.ru."""
    for _ in range(5):                       # замена могла оказаться недоступной и получить свою замену
        следующая = _замены.get((адрес, модель))
        if not следующая or следующая == модель:
            break
        модель = следующая
    return модель


def замена_модели_эмбеддингов(адрес: str, ключ: str, модель: str, ошибка: ОшибкаИИ) -> str | None:
    """Если cloud.ru ответил 404, ищем у него другую модель эмбеддингов и запоминаем её до перезапуска.
    Если замены нет — ошибка получает подробный текст: что доступно и что сделать."""
    if getattr(ошибка, "код", 0) != 404:
        return None
    try:
        доступные = модели_эмбеддингов(адрес, ключ)
    except ОшибкаИИ:
        return None
    другие = [м for м in доступные if м != модель]
    if другие:
        _замены[(адрес, модель)] = другие[0]
        журнал.warning("Модель эмбеддингов «%s» недоступна по вашему ключу (404). Беру «%s». "
                       "Чтобы не видеть это сообщение, выберите её в настройках ИИ.", модель, другие[0])
        return другие[0]
    if модель in доступные:
        raise ОшибкаИИ(f"cloud.ru не находит адрес {адрес.rstrip('/')}/embeddings (404), хотя модель «{модель}» в списке есть. "
                       "Адрес API должен заканчиваться на /v1. Проверьте его в настройках ИИ.") from None
    raise ОшибкаИИ(f"Модели эмбеддингов «{модель}» нет среди доступных по вашему ключу, и других моделей эмбеддингов у ключа нет. "
                   "Смысловые связи не работают; выберите «не использовать» в настройках ИИ или подключите модель эмбеддингов "
                   "в личном кабинете cloud.ru.") from None


def эмбеддинги(адрес: str, ключ: str, модель: str, тексты: list[str]) -> list[list[float]]:
    """POST /embeddings — по одному вектору на текст (пачками по 32)."""
    итог: list[list[float]] = []
    for начало in range(0, len(тексты), 32):
        пачка = [т[:6000] or " " for т in тексты[начало:начало + 32]]
        with _открыть(адрес, ключ, "/embeddings", {"model": модель, "input": пачка}, таймаут=120) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
        строки = sorted(данные.get("data", []), key=lambda д: д.get("index", 0))
        if len(строки) != len(пачка):
            raise ОшибкаИИ("Модель эмбеддингов вернула не столько векторов, сколько текстов.")
        итог.extend(д["embedding"] for д in строки)
    return итог


