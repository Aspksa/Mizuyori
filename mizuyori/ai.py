_ОБЪЕКТ = re.compile(r"\{.*\}", re.S)


def _задание(система: str, данные: dict, настройки_ии: dict, max_tokens: int) -> str:
    тело = {
        "model": настройки_ии["модель"],
        "messages": [{"role": "system", "content": система},
                     {"role": "user", "content": json.dumps(данные, ensure_ascii=False)}],
        "temperature": 0,
        "max_tokens": max_tokens,
        "stream": False,
    }
    with _открыть(настройки_ии["адрес"], настройки_ии["ключ"], "/chat/completions", тело, таймаут=90) as ответ:
        ответ_json = json.loads(ответ.read().decode("utf-8"))
    return убрать_размышления(ответ_json["choices"][0]["message"].get("content") or "")


def _факт_ок(ф) -> dict | None:
    if not isinstance(ф, dict) or not isinstance(ф.get("факт"), str):
        return None
    текст = ф["факт"].strip()
    if not 3 <= len(текст) <= 300:
        return None
    категория = ф.get("категория") if ф.get("категория") in КАТЕГОРИИ else "другое"
    try:
        важность = max(1, min(5, int(ф.get("важность", 3))))
    except (TypeError, ValueError):
        важность = 3
    return {"факт": текст, "категория": категория, "важность": важность}


def обновить_память(реплика: str, ответ: str, известные: list[dict], рабочая: dict, настройки_ии: dict) -> dict:
    """Что поменять в памяти после хода разговора.

    Возвращает {"добавить": [...], "заменить": [...], "удалить": [...], "рабочая": {...} | None}.
    """
    текст = _задание(_ЗАДАНИЕ_ПАМЯТИ, {
        "известные_факты": [{"id": ф["id"], "факт": ф["факт"], "категория": ф["категория"],
                             "важность": ф["важность"]} for ф in известные],
        "рабочая_память": рабочая or {},
        "реплика_пользователя": реплика[:4000],
        "ответ_ассистента": ответ[:3000],
    }, настройки_ии, max_tokens=800)
    найдено = _ОБЪЕКТ.search(текст)
    итог = {"добавить": [], "заменить": [], "удалить": [], "рабочая": None}
    if not найдено:
        return итог
    try:
        данные = json.loads(найдено.group(0))
    except ValueError:
        return итог
    известные_id = {ф["id"] for ф in известные}
    for ф in (данные.get("добавить") or [])[:5]:
        if (ок := _факт_ок(ф)):
            итог["добавить"].append(ок)
    for ф in (данные.get("заменить") or [])[:5]:
        if isinstance(ф, dict) and ф.get("id") in известные_id and (ок := _факт_ок(ф)):
            итог["заменить"].append({"id": ф["id"], **ок})
    итог["удалить"] = [н for н in (данные.get("удалить") or []) if н in известные_id][:5]
    р = данные.get("рабочая")
    if isinstance(р, dict):
        строки = lambda x: [str(с).strip()[:200] for с in (x or []) if str(с).strip()][:6]
        итог["рабочая"] = {"тема": str(р.get("тема") or "").strip()[:200],
                           "решения": строки(р.get("решения")), "вопросы": строки(р.get("вопросы"))}
    return итог


def сжать(предыдущая: str, сообщения: list[dict], настройки_ии: dict) -> str:
    """Пересказ старой части разговора (вместе с предыдущим пересказом)."""
    диалог = [{"кто": "ассистент" if с["роль"] == "ии" else "пользователь", "текст": с["текст"][:2000]}
              for с in сообщения]
    return _задание(_ЗАДАНИЕ_СЖАТИЯ, {"предыдущий_пересказ": предыдущая or "", "фрагмент": диалог},
                    настройки_ии, max_tokens=900)[:2000]


# ---- Эмбеддинги: смысл текста в виде чисел ---------------------------------

def эмбеддинги(адрес: str, ключ: str, модель: str, тексты: list[str]) -> list[list[float]]:
    """POST /embeddings — по одному вектору на текст (пачками по 32)."""
    итог: list[list[float]] = []
    for начало in range(0, len(тексты), 32):
        пачка = [т[:6000] or " " for т in тексты[начало:начало + 32]]
        with _открыть(адрес, ключ, "/embeddings", {"model": модель, "input": пачка}, таймаут=120) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
        строки = sorted(данные.get("data", []), key=lambda д: д.get("index", 0))
        if len(строки) != len(пачка):
            raise ОшибкаИИ("Модель эмбеддингов вернула не столько векторов, сколько текстов.")
        итог.extend(д["embedding"] for д in строки)
    return итог
