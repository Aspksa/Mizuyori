_ОБЪЕКТ = re.compile(r"\{.*\}", re.S)


def _задание(система: str, данные: dict, настройки_ии: dict, max_tokens: int) -> str:
    тело = {
        "model": настройки_ии["модель"],
        "messages": [{"role": "system", "content": система},
                     {"role": "user", "content": json.dumps(данные, ensure_ascii=False)}],
        "temperature": 0,
        "max_tokens": max_tokens,
        "stream": False,
    }
    with _открыть(настройки_ии["адрес"], настройки_ии["ключ"], "/chat/completions", тело, таймаут=90) as ответ:
        ответ_json = json.loads(ответ.read().decode("utf-8"))
    return убрать_размышления(ответ_json["choices"][0]["message"].get("content") or "")


ПОЛЯ_СМЫСЛА = ["кто", "что", "для_кого", "зачем", "почему", "когда"]


def _строка(х, длина=200) -> str:
    return " ".join(str(х).split())[:длина] if isinstance(х, (str, int, float)) else ""


def _имена(список) -> list[str]:
    return [и for и in (_строка(х, 80) for х in (список or [])[:8]) if и]


def _факт_ок(ф) -> dict | None:
    if not isinstance(ф, dict) or not isinstance(ф.get("факт"), str):
        return None
    текст = ф["факт"].strip()
    if not 3 <= len(текст) <= 300:
        return None
    категория = ф.get("категория") if ф.get("категория") in КАТЕГОРИИ else "другое"
    try:
        важность = max(1, min(5, int(ф.get("важность", 3))))
    except (TypeError, ValueError):
        важность = 3
    смысл_в = ф.get("смысл") if isinstance(ф.get("смысл"), dict) else {}
    смысл = {к: _строка(смысл_в[к]) for к in ПОЛЯ_СМЫСЛА if _строка(смысл_в.get(к))}
    return {"факт": текст, "категория": категория, "важность": важность,
            "смысл": смысл, "сущности": _имена(ф.get("сущности"))}


def обновить_память(реплика: str, ответ: str, известные: list[dict], рабочая: dict, настройки_ии: dict,
                    сущности: list[dict] | None = None, задачи: list[dict] | None = None) -> dict:
    """Что поменять в памяти и понимании после хода разговора."""
    текст = _задание(_ЗАДАНИЕ_ПАМЯТИ, {
        "известные_факты": [{"id": ф["id"], "факт": ф["факт"], "категория": ф["категория"],
                             "важность": ф["важность"]} for ф in известные],
        "известные_сущности": [{"имя": с["имя"], "тип": с["тип"], **({"другие_имена": с["другие_имена"]} if с["другие_имена"] else {})}
                               for с in (сущности or [])],
        "открытые_задачи_без_цели": [{"id": з["id"], "текст": з["текст"]} for з in (задачи or [])],
        "рабочая_память": рабочая or {},
        "реплика_пользователя": реплика[:4000],
        "ответ_ассистента": ответ[:3000],
    }, настройки_ии, max_tokens=1500)
    найдено = _ОБЪЕКТ.search(текст)
    итог = {"добавить": [], "заменить": [], "удалить": [], "рабочая": None,
            "сущности": [], "связи": [], "цели": [], "задачи_к_целям": []}
    if not найдено:
        return итог
    try:
        данные = json.loads(найдено.group(0))
    except ValueError:
        return итог
    известные_id = {ф["id"] for ф in известные}
    for ф in (данные.get("добавить") or [])[:5]:
        if (ок := _факт_ок(ф)):
            итог["добавить"].append(ок)
    for ф in (данные.get("заменить") or [])[:5]:
        if isinstance(ф, dict) and ф.get("id") in известные_id and (ок := _факт_ок(ф)):
            итог["заменить"].append({"id": ф["id"], **ок})
    итог["удалить"] = [н for н in (данные.get("удалить") or []) if н in известные_id][:5]
    for с in (данные.get("сущности") or [])[:10]:
        if isinstance(с, dict) and _строка(с.get("имя"), 80):
            итог["сущности"].append({"имя": _строка(с["имя"], 80), "тип": с.get("тип") if с.get("тип") in ТИПЫ else "другое",
                                     "описание": _строка(с.get("описание"), 300), "другие_имена": _имена(с.get("другие_имена"))})
    for с in (данные.get("связи") or [])[:12]:
        if isinstance(с, dict) and all(_строка(с.get(к), 80) for к in ("от", "отношение", "к")):
            итог["связи"].append({"от": _строка(с["от"], 80), "отношение": _строка(с["отношение"], 40), "к": _строка(с["к"], 80)})
    for ц in (данные.get("цели") or [])[:5]:
        if isinstance(ц, dict) and _строка(ц.get("имя"), 80):
            статус = ц.get("статус") if ц.get("статус") in ("активна", "достигнута", "отменена") else "активна"
            итог["цели"].append({"имя": _строка(ц["имя"], 80), "почему": _строка(ц.get("почему"), 300), "статус": статус})
    for п in (данные.get("задачи_к_целям") or [])[:20]:
        if isinstance(п, dict) and isinstance(п.get("задача_id"), int) and _строка(п.get("цель"), 80):
            итог["задачи_к_целям"].append({"задача_id": п["задача_id"], "цель": _строка(п["цель"], 80)})
    р = данные.get("рабочая")
    if isinstance(р, dict):
        строки = lambda x: [str(с).strip()[:200] for с in (x or []) if str(с).strip()][:6]
        итог["рабочая"] = {"тема": str(р.get("тема") or "").strip()[:200],
                           "решения": строки(р.get("решения")), "вопросы": строки(р.get("вопросы"))}
    return итог


def сжать(предыдущая: str, сообщения: list[dict], настройки_ии: dict) -> str:
    """Пересказ старой части разговора (вместе с предыдущим пересказом)."""
    диалог = [{"кто": "ассистент" if с["роль"] == "ии" else "пользователь", "текст": с["текст"][:2000]}
              for с in сообщения]
    return _задание(_ЗАДАНИЕ_СЖАТИЯ, {"предыдущий_пересказ": предыдущая or "", "фрагмент": диалог},
                    настройки_ии, max_tokens=900)[:2000]


# ---- Эмбеддинги: смысл текста в виде чисел ---------------------------------

def эмбеддинги(адрес: str, ключ: str, модель: str, тексты: list[str]) -> list[list[float]]:
    """POST /embeddings — по одному вектору на текст (пачками по 32)."""
    итог: list[list[float]] = []
    for начало in range(0, len(тексты), 32):
        пачка = [т[:6000] or " " for т in тексты[начало:начало + 32]]
        with _открыть(адрес, ключ, "/embeddings", {"model": модель, "input": пачка}, таймаут=120) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
        строки = sorted(данные.get("data", []), key=lambda д: д.get("index", 0))
        if len(строки) != len(пачка):
            raise ОшибкаИИ("Модель эмбеддингов вернула не столько векторов, сколько текстов.")
        итог.extend(д["embedding"] for д in строки)
    return итог


def привязать_к_целям(цели: list[dict], задачи: list[dict], настройки_ии: dict) -> dict:
    """Какие задачи — шаги к каким целям (одним запросом)."""
    текст = _задание(_ЗАДАНИЕ_ЦЕЛЕЙ, {
        "цели": [{"имя": ц["имя"], "почему": ц.get("причина", "")} for ц in цели],
        "задачи": [{"id": з["id"], "текст": з["текст"]} for з in задачи],
    }, настройки_ии, max_tokens=1200)
    найдено = _ОБЪЕКТ.search(текст)
    if not найдено:
        return {"привязки": [], "новые_цели": []}
    try:
        данные = json.loads(найдено.group(0))
    except ValueError:
        return {"привязки": [], "новые_цели": []}
    привязки = [{"задача_id": п["задача_id"], "цель": _строка(п.get("цель"), 80)}
                for п in (данные.get("привязки") or []) if isinstance(п, dict) and isinstance(п.get("задача_id"), int)
                and _строка(п.get("цель"), 80)]
    новые = [{"имя": _строка(ц.get("имя"), 80), "почему": _строка(ц.get("почему"), 300)}
             for ц in (данные.get("новые_цели") or [])[:5] if isinstance(ц, dict) and _строка(ц.get("имя"), 80)]
    return {"привязки": привязки, "новые_цели": новые}
