def подключён(настройки_ии: dict) -> bool:
    return bool(настройки_ии.get("включён") and настройки_ии.get("ключ") and настройки_ии.get("модель"))


def _сообщения(история: list[dict], настройки_ии: dict, имя: str, контекст: dict | None = None) -> list[dict]:
    """Системная подсказка + история.

    контекст: {"факты": [{факт, категория, важность}], "сводка": "…", "рабочая": {тема, решения, вопросы}}
    """
    контекст = контекст or {}
    сейчас = datetime.now()
    характер = (настройки_ии.get("характер") or "").strip()
    дни = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
    части = []
    if характер:
        части.append(характер)
    части.append(f"Тебя зовут {имя}. Отвечай по-русски, если тебя не просят иначе. "
                 f"Сейчас {сейчас:%d.%m.%Y %H:%M}, {дни[сейчас.weekday()]}.")

    части.append("Если для хорошего ответа важно, для кого или зачем это нужно, а из разговора и памяти "
                 "это не ясно — один раз коротко уточни, а не гадай. Если понятно — не переспрашивай.")

    факты = контекст.get("факты") or []
    if факты:
        по_категориям: dict[str, list[str]] = {}
        подписи = {"для_кого": "для кого", "зачем": "зачем", "почему": "почему", "когда": "когда"}
        for ф in факты:
            метка = " (важно)" if ф.get("важность", 3) >= 4 else ""
            смысл = ф.get("смысл") or {}
            детали = "; ".join(f"{п}: {смысл[к]}" for к, п in подписи.items() if смысл.get(к))
            детали = f" [{детали}]" if детали else ""
            по_категориям.setdefault(ф.get("категория") or "другое", []).append(f"- {ф['факт']}{детали}{метка}")
        блок = "\n".join(f"{к.capitalize()}:\n" + "\n".join(с) for к, с in по_категориям.items())
        части.append("Что ты знаешь о собеседнике из прошлых разговоров (используй к месту, "
                     "не перечисляй без просьбы):\n" + блок)

    if контекст.get("знания"):
        части.append("Понимание (люди, цели, связи и причины):\n" + контекст["знания"])

    if контекст.get("сводка"):
        части.append("Краткое содержание более ранней части этого разговора:\n" + контекст["сводка"])

    рабочая = контекст.get("рабочая") or {}
    строки = []
    if рабочая.get("тема"):
        строки.append(f"Тема: {рабочая['тема']}")
    if рабочая.get("решения"):
        строки.append("Уже решено: " + "; ".join(рабочая["решения"]))
    if рабочая.get("вопросы"):
        строки.append("Открытые вопросы: " + "; ".join(рабочая["вопросы"]))
    if строки:
        части.append("Что сейчас происходит в разговоре:\n" + "\n".join(строки))

    сообщения = [{"role": "system", "content": "\n\n".join(части)}]
    for с in история:
        сообщения.append({"role": "assistant" if с["роль"] == "ии" else "user", "content": с["текст"]})
    return сообщения


def _тело(история, настройки_ии, имя, поток: bool, контекст=None) -> dict:
    return {
        "model": настройки_ии["модель"],
        "messages": _сообщения(история, настройки_ии, имя, контекст),
        "temperature": настройки_ии.get("температура", 0.7),
        "max_tokens": int(настройки_ии.get("длина", 2000)),
        "stream": поток,
    }


_РАЗМЫШЛЕНИЯ = re.compile(r"<think>.*?</think>\s*", re.S)


def убрать_размышления(текст: str) -> str:
    """Модели-«мыслители» (DeepSeek-R1 и др.) пишут ход мыслей в <think>…</think>."""
    return _РАЗМЫШЛЕНИЯ.sub("", текст).strip()


def ответ_потоком(история: list[dict], настройки_ии: dict, имя: str, контекст: dict | None = None):
    """Отдаёт ответ кусочками по мере генерации."""
    начало = time.monotonic()
    тело = _тело(история, настройки_ии, имя, поток=True, контекст=контекст)
    with _открыть(настройки_ии["адрес"], настройки_ии["ключ"], "/chat/completions", тело, таймаут=120) as ответ:
        тип = ответ.headers.get("Content-Type", "")
        if "text/event-stream" not in тип:
            # Сервер ответил целиком, без потока
            данные = json.loads(ответ.read().decode("utf-8"))
            yield данные["choices"][0]["message"].get("content") or ""
            return
        for строка in ответ:
            строка = строка.decode("utf-8", "replace").strip()
            if not строка.startswith("data:"):
                continue
            кусок = строка[5:].strip()
            if кусок == "[DONE]":
                break
            try:
                данные = json.loads(кусок)
            except ValueError:
                continue
            if данные.get("error"):
                ошибка = данные["error"]
                raise ОшибкаИИ(ошибка.get("message", str(ошибка)) if isinstance(ошибка, dict) else str(ошибка))
            for выбор in данные.get("choices", []):
                текст = (выбор.get("delta") or {}).get("content")
                if текст:
                    yield текст
    журнал.info("Ответ ИИ (%s) за %.1f с", настройки_ии["модель"], time.monotonic() - начало)


def проверить(настройки_ии: dict, имя: str) -> dict:
    """Короткий пробный запрос к выбранной модели."""
    начало = time.monotonic()
    тело = _тело([{"роль": "пользователь", "текст": "Ответь одним коротким предложением: ты на связи?"}],
                 {**настройки_ии, "длина": 100}, имя, поток=False)
    with _открыть(настройки_ии["адрес"], настройки_ии["ключ"], "/chat/completions", тело, таймаут=60) as ответ:
        данные = json.loads(ответ.read().decode("utf-8"))
    текст = убрать_размышления(данные["choices"][0]["message"].get("content") or "")
    return {"ответ": текст, "секунд": round(time.monotonic() - начало, 1)}


