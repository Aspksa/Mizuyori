    текст = _задание(_ЗАДАНИЕ_ПАМЯТИ, {
        "известные_факты": [{"id": ф["id"], "факт": ф["факт"], "категория": ф["категория"],
                             "важность": ф["важность"]} for ф in известные],
        "известные_сущности": [{"имя": с["имя"], "тип": с["тип"], **({"другие_имена": с["другие_имена"]} if с["другие_имена"] else {})}
                               for с in (сущности or [])],
        "открытые_задачи_без_цели": [{"id": з["id"], "текст": з["текст"]} for з in (задачи or [])],
        "рабочая_память": рабочая or {},
        "реплика_пользователя": реплика[:4000],
        "ответ_ассистента": ответ[:3000],
    }, настройки_ии, max_tokens=1500)
    найдено = _ОБЪЕКТ.search(текст)
    итог = {"добавить": [], "заменить": [], "удалить": [], "рабочая": None,
            "сущности": [], "связи": [], "цели": [], "задачи_к_целям": []}
    if not найдено:
        return итог
    try:
        данные = json.loads(найдено.group(0))
    except ValueError:
        return итог
    известные_id = {ф["id"] for ф in известные}
    for ф in (данные.get("добавить") or [])[:5]:
        if (ок := _факт_ок(ф)):
            итог["добавить"].append(ок)
    for ф in (данные.get("заменить") or [])[:5]:
        if isinstance(ф, dict) and ф.get("id") in известные_id and (ок := _факт_ок(ф)):
            итог["заменить"].append({"id": ф["id"], **ок})
    итог["удалить"] = [н for н in (данные.get("удалить") or []) if н in известные_id][:5]
    for с in (данные.get("сущности") or [])[:10]:
        if isinstance(с, dict) and _строка(с.get("имя"), 80):
            итог["сущности"].append({"имя": _строка(с["имя"], 80), "тип": с.get("тип") if с.get("тип") in ТИПЫ else "другое",
                                     "описание": _строка(с.get("описание"), 300), "другие_имена": _имена(с.get("другие_имена"))})
    for с in (данные.get("связи") or [])[:12]:
        if isinstance(с, dict) and all(_строка(с.get(к), 80) for к in ("от", "отношение", "к")):
            итог["связи"].append({"от": _строка(с["от"], 80), "отношение": _строка(с["отношение"], 40), "к": _строка(с["к"], 80)})
    for ц in (данные.get("цели") or [])[:5]:
        if isinstance(ц, dict) and _строка(ц.get("имя"), 80):
            статус = ц.get("статус") if ц.get("статус") in ("активна", "достигнута", "отменена") else "активна"
            итог["цели"].append({"имя": _строка(ц["имя"], 80), "почему": _строка(ц.get("почему"), 300), "статус": статус})
    for п in (данные.get("задачи_к_целям") or [])[:20]:
        if isinstance(п, dict) and isinstance(п.get("задача_id"), int) and _строка(п.get("цель"), 80):
            итог["задачи_к_целям"].append({"задача_id": п["задача_id"], "цель": _строка(п["цель"], 80)})
    р = данные.get("рабочая")
    if isinstance(р, dict):
        строки = lambda x: [str(с).strip()[:200] for с in (x or []) if str(с).strip()][:6]
        итог["рабочая"] = {"тема": str(р.get("тема") or "").strip()[:200],
                           "решения": строки(р.get("решения")), "вопросы": строки(р.get("вопросы"))}

    # Явные команды хозяина имеют предсказуемый результат даже у небольшой модели.
    реплика_ключ = реплика.casefold().replace("ё", "е")
    явно_важно = any(метка in реплика_ключ for метка in ("это важно", "важно запомнить"))
    явное_правило = any(метка in реплика_ключ for метка in (
        "это правило", "запомни как правило", "правило для тебя", "считай правилом",
    ))
    for ф in [*итог["добавить"], *итог["заменить"]]:
        if явно_важно or явное_правило:
            ф["важность"] = 5
        if явное_правило:
            if not ф["факт"].casefold().startswith("правило хозяина:"):
                ф["факт"] = "Правило хозяина: " + ф["факт"]
            ф["категория"] = "предпочтения"
    return итог


