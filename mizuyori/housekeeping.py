"""Уборка: старые записи журналов, расхода, кэша и истории агентов удаляются, чтобы база не пухла.
Память (факты), заметки, задачи и поручения не трогаются."""
from __future__ import annotations

import logging
import threading
import time
from pathlib import Path

журнал = logging.getLogger("mizuyori.уборка")

ХРАНИТЬ_ДНЕЙ = 180
# таблица, колонка с датой (текст «ГГГГ-ММ-ДД ЧЧ:ММ:СС»), ограничение: нельзя трогать нужное
_ТАБЛИЦЫ = (
    ("аудит", "создано", ""),
    ("агент_история", "создано", ""),
    ("агент_оценка", "создано", ""),
    ("поиск_прогон", "создано", ""),
    ("доска", "создано", "AND прочитано = 1"),
    ("память_версия", "создано", ""),
)


def убрать(база, дней: int = ХРАНИТЬ_ДНЕЙ, папка_логов: Path | None = None) -> dict:
    """Удаляет старое. Возвращает, сколько записей убрано по таблицам."""
    итог: dict[str, int] = {}
    порог = f"-{int(дней)} days"
    with база.соединение() as связь:
        for таблица, колонка, условие in _ТАБЛИЦЫ:
            итог[таблица] = связь.execute(
                f"DELETE FROM {таблица} WHERE {колонка} < datetime('now', 'localtime', ?) {условие}", (порог,)).rowcount
        итог["агент_расход"] = связь.execute(
            "DELETE FROM агент_расход WHERE день < date('now', 'localtime', ?)", (порог,)).rowcount
        итог["поиск_кэш"] = связь.execute(
            "DELETE FROM поиск_кэш WHERE создано < ?", (time.time() - 7 * 86400,)).rowcount
    if папка_логов and папка_логов.is_dir():
        старше = time.time() - дней * 86400
        убрано = 0
        for файл in папка_логов.iterdir():
            # текущий mizuyori.log не трогаем; убираем только старые ротации и чужие файлы
            if файл.is_file() and файл.name != "mizuyori.log" and файл.stat().st_mtime < старше:
                try:
                    файл.unlink()
                    убрано += 1
                except OSError:
                    pass
        итог["файлы_логов"] = убрано
    всего = sum(итог.values())
    if всего:
        журнал.info("Уборка: убрано записей — %d (%s)", всего, ", ".join(f"{к}: {v}" for к, v in итог.items() if v))
    return итог


def запустить(база, получить_дней, папка_логов: Path | None = None) -> None:
    """Раз в сутки убирает старое; первый раз — через минуту после запуска."""
    def цикл():
        time.sleep(60)
        while True:
            try:
                убрать(база, получить_дней(), папка_логов)
            except Exception:
                журнал.exception("Уборка не удалась")
            time.sleep(86400)
    threading.Thread(target=цикл, daemon=True, name="уборка").start()
