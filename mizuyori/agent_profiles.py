def заполнить() -> int:
    """Записывает профиль агентам, у которых он пуст. Возвращает, сколько заполнено."""
    готово = 0
    for ключ, поля in ПРОФИЛИ.items():
        if ключ not in agents.ИМЕНА:
            continue
        try:
            if not any(agents.профиль(ключ).values()):
                agents.сохранить_профиль(ключ, поля, "готовый профиль")
                готово += 1
        except Exception:
            журнал.exception("Профиль «%s» не записан", ключ)
    return готово
