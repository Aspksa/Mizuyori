"""Справка для чата: точные цифры из базы по вопросам «сколько литров залил Иванов за октябрь?»,
«какие машины без ОСАГО?». ИИ получает готовые числа и пересказывает их, а не придумывает."""

import logging
import re
from datetime import date

from . import printing, smeta, work

журнал = logging.getLogger("mizuyori.справка")

_МЕСЯЦЫ = [("январ", 1), ("феврал", 2), ("март", 3), ("апрел", 4), (r"ма[йяе]\b", 5), ("июн", 6), ("июл", 7),
           ("август", 8), ("сентябр", 9), ("октябр", 10), ("ноябр", 11), ("декабр", 12)]
_ЦИФРЫ = ("литр", "залил", "заправ", "пробег", "км ", "расход", "перерасход", "экономи", "топлив", "гсм", "сколько проех",
          "сколько ездил", "сколько накатал")
_СРОКИ = ("осаго", "страховк", "техосмотр", "диагностическ", "просроч", "шины", "шин ", "сроки то", "когда то",
          "то у ", "истека", "без то", "без осаго")
_РЕМОНТ = ("ремонт", "менял", "замен", "поменял", "чинил", "починил", "обслуживан", "потратили на", "затрат", "что делали",
           "что с машин", "история машин", "стоил ремонт", "стоимость обслуживан")
_МЕСЯЦ_ПОДПИСИ = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]


def _месяцы(текст: str) -> list[str]:
    н = " " + printing._норм(текст) + " "
    сегодня = date.today()
    найдено = []
    for шаблон, номер in _МЕСЯЦЫ:
        if re.search(r"\b" + шаблон, н if шаблон.endswith(r"\b") else н):
            год = сегодня.year if номер <= сегодня.month else сегодня.year - 1
            найдено.append(f"{год}-{номер:02d}")
    if "прошл" in н and "месяц" in н:
        м = сегодня.month - 1 or 12
        найдено = [f"{сегодня.year if сегодня.month > 1 else сегодня.year - 1}-{м:02d}"]
    return sorted(set(найдено)) or [сегодня.strftime("%Y-%m")]


def _строка(р: dict, м: str) -> str:
    части = [f"{р['автомобиль']} (водитель: {р['водитель'] or 'не закреплён'})"]
    ед = lambda з, е: None if з is None else f"{round(з, 1)} {е}"
    for название, значение, е in (("пробег", р.get("пробег"), "км"), ("заправлено", р.get("заправлено"), "л"),
                                  ("норма", р.get("норма"), "л"), ("факт расхода", р.get("факт"), "л"),
                                  ("разница с нормой", р.get("разница"), "л")):
        текст = ед(значение, е)
        if текст:
            части.append(f"{название} {текст}")
    if len(части) == 1:
        части.append("данных за месяц нет" + (f" ({р['причина_нуля']})" if р.get("причина_нуля") else ""))
    return "; ".join(части)


def _назван(а: dict, н: str) -> bool:
    слова = [с for с in printing._норм(f"{а['марка']} {а['модель']}").split() if len(с) > 2]
    return bool(слова) and all(printing._основа(с) in н or printing._латиницей(printing._основа(с)) in н for с in слова)


def _цифры(база, текст: str) -> str:
    н = printing._норм(текст)
    слова = [printing._основа(с) for с in н.split() if len(с) > 3]
    машины = work.список(база, "автомобили")
    нужные_авто = {а["id"] for а in машины
                   if (printing._норм(а["госномер"] or "").replace(" ", "") and printing._норм(а["госномер"]).replace(" ", "") in н.replace(" ", ""))
                   or _назван(а, н)}
    люди = [ч for ч in work.список(база, "сотрудники") if not ч.get("уволен")
            and printing._основа(printing._норм(ч["фамилия"])) in слова]
    месяцы = _месяцы(текст)
    блоки = []
    for м in месяцы:
        строки = work._посчитать_месяц(база, м)
        фио_людей = {work.фио(ч) for ч in люди}
        выбор = [р for р in строки if р["автомобиль_id"] in нужные_авто or (р["водитель"] and р["водитель"] in фио_людей)]
        подпись = f"{_МЕСЯЦ_ПОДПИСИ[int(м[5:]) - 1]} {м[:4]}"
        if выбор:
            блоки.append(f"{подпись}:\n" + "\n".join("- " + _строка(р, м) for р in выбор))
        elif not люди and not нужные_авто:
            с_данными = [р for р in строки if р.get("пробег") is not None or р.get("заправлено")]
            итого = {"пробег": sum(р.get("пробег") or 0 for р in с_данными),
                     "заправлено": sum(р.get("заправлено") or 0 for р in с_данными),
                     "по_карте_руб": sum(р.get("сумма_по_карте") or 0 for р in с_данными)}
            топ = sorted((р for р in с_данными if р.get("разница") is not None), key=lambda р: -р["разница"])[:3]
            блоки.append(f"{подпись}, по всем машинам: пробег {round(итого['пробег'])} км, заправлено "
                         f"{round(итого['заправлено'], 1)} л, по картам на {round(итого['по_карте_руб'])} руб."
                         + ("; больше всего перерасход: " + "; ".join(f"{р['автомобиль']} {round(р['разница'], 1)} л" for р in топ)
                            if топ else ""))
        else:
            блоки.append(f"{подпись}: по названным людям и машинам данных нет.")
    return "\n".join(блоки)


def _ремонты(база, текст: str) -> tuple[str, str]:
    н = printing._норм(текст)
    слова_людей = [printing._основа(с) for с in н.split() if len(с) > 3]
    люди = [ч for ч in work.список(база, "сотрудники") if not ч.get("уволен")
            and printing._основа(printing._норм(ч["фамилия"])) in слова_людей]
    машины = work.список(база, "автомобили")
    названы = [а for а in машины if printing._норм(а.get("госномер") or "").replace(" ", "") and
               printing._норм(а["госномер"]).replace(" ", "") in н.replace(" ", "")]
    # по словам модели и марки: «Прадо» достаточно, если такая машина одна; при равенстве берём все подходящие
    слова_запроса = [с for с in н.split() if len(с) > 2]

    def есть(токен: str) -> bool:
        о = printing._основа(токен)
        return any(о == printing._основа(w) or о == printing._основа(printing._латиницей(w)) or w.startswith(о) for w in слова_запроса)

    очки, только_марка = {}, {}
    for а in машины:
        слова_модели = [с for с in printing._норм(а["модель"] or "").split() if len(с) > 2]
        слова_марки = [с for с in printing._норм(а["марка"] or "").split() if len(с) > 2]
        найдено_модель = sum(1 for с in слова_модели if есть(с))
        найдено_марка = sum(1 for с in слова_марки if есть(с))
        if найдено_модель:
            очки[а["id"]] = найдено_модель * 2 + найдено_марка
        elif найдено_марка:
            только_марка[а["id"]] = найдено_марка
    if not очки:
        очки = только_марка
    if очки:
        лучший = max(очки.values())
        названы += [а for а in машины if очки.get(а["id"]) == лучший and а not in названы][:3]
    for ч in люди:
        for а in машины:
            if ч.get("автомобиль_id") == а["id"] and а not in названы:
                названы.append(а)
    if люди and not названы:
        return ("За названным водителем машина в базе не закреплена, поэтому историю ремонтов по нему показать нельзя. "
                "Спроси, о какой машине речь.", "механик")
    стоимость = any(с in н for с in ("сколько", "стоил", "стоимост", "потратил", "затрат", "руб"))
    агент = "экономист" if стоимость else "механик"
    if названы:
        блоки = []
        for а in названы[:3]:
            список = smeta.ремонты(база, а["id"])
            строки = [f"- {р['дата']}" + (f", пробег {р['пробег']:.0f} км" if р["пробег"] else "") +
                      f", {р['исполнитель'] or 'исполнитель не указан'}, {p_} ₽; работы: {'; '.join(р['работы']) or '—'}; "
                      f"заменено/материалы: {'; '.join(р['материалы']) or '—'}"
                      for р in список[:10] for p_ in [f"{р['итого']:,.0f}".replace(",", " ") if р["итого"] is not None else "?"]]
            итого = sum(р["итого"] or 0 for р in список)
            блоки.append(f"{work.авто_подпись(а)}: " + (f"{len(список)} ремонтов на {итого:,.0f} ₽\n".replace(",", " ") + "\n".join(строки)
                                                       if список else "записей о ремонтах нет"))
        return ("История ремонтов из подтверждённых смет (отвечай только по ней; если записей нет — так и скажи):\n" + "\n".join(блоки), агент)
    список = smeta.ремонты(база, None, 12)
    if not список:
        return ("В базе пока нет ни одной записи о ремонте (смета на ремонт, присланная в чат и подтверждённая, "
                "попадает в историю машины).", агент)
    по_машинам: dict[int, list[dict]] = {}
    for р in список:
        по_машинам.setdefault(р["автомобиль_id"], []).append(р)
    имена = {а["id"]: work.авто_подпись(а) for а in машины}
    строки = [f"- {имена.get(к, 'машина №' + str(к))}: {len(в)} ремонтов на {sum(р['итого'] or 0 for р in в):,.0f} ₽".replace(",", " ")
              for к, в in sorted(по_машинам.items(), key=lambda кв: -sum(р["итого"] or 0 for р in кв[1]))[:10]]
    всего = sum(р["итого"] or 0 for р in список)
    return (f"Ремонты за последние 12 месяцев: всего {всего:,.0f} ₽.\n".replace(",", " ") + "\n".join(строки), агент)


def для_вопроса(база, текст: str) -> tuple[str, str]:
    """(блок с цифрами для подсказки ИИ, ключ агента) — или ('', '')."""
    н = " " + printing._норм(текст) + " "
    if printing.это_печать(текст):
        return "", ""
    try:
        if any(с in н for с in _РЕМОНТ) and not any(с in н for с in ("осаго", "техосмотр", "просроч", "истека")):
            return _ремонты(база, текст)
        if any(с in н for с in _СРОКИ):
            from . import work_agents
            строки = []
            for ключ in ("механик", "юрист"):
                строки += [f"- {з['текст']}" for з in sorted(work_agents.НАБЛЮДАТЕЛИ[ключ](база), key=lambda з: -з["важно"])
                           if з["важно"] >= 1]
            for слово, метки in (("осаго", ("осаго",)), ("страховк", ("осаго", "каско", "страх")),
                                 ("техосмотр", ("техосмотр",)), ("шин", ("шин",)), ("диагностическ", ("диагностическ",))):
                if слово in н:       # спросили про один вид срока — остальные не нужны
                    строки = [с for с in строки if any(м in с.lower() for м in метки)] or ["по этому виду замечаний нет."]
                    break
            строки = строки[:25]
            return ("Точные данные из базы по срокам (отвечай только по ним, ничего не добавляй; "
                    "если машины в списке нет — значит, замечаний по ней нет):\n"
                    + ("\n".join(строки) if строки else "просроченных и близких сроков нет."), "механик")
        if any(с in н for с in _ЦИФРЫ):
            ц = _цифры(база, текст)
            if ц:
                return ("Точные цифры из базы Работы (расчёт как на странице «ГСМ → Путевые»). Отвечай ТОЛЬКО по ним, "
                        "называй цифры как есть и месяц; если данных нет — так и скажи:\n" + ц, "экономист")
    except Exception:
        журнал.exception("Справка для чата не собралась")
    return "", ""
