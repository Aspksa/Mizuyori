"""Журнал решений и оценка качества агентов.

Каждый ответ чата, совещание и поручение кабинету записываются сюда: что спросили, кто участвовал, на чём основан
ответ (какие источники подключались), чем кончилось. По журналу считается качество каждого агента: сколько ответов
принято, сколько хозяин исправил, сколько раз агент честно сказал «нет данных». Хранится последние 300 записей."""
from __future__ import annotations

import logging
import re
import threading
import time

журнал = logging.getLogger("mizuyori.решения")

КЛЮЧ = "журнал_решений"
МАКС_ЗАПИСЕЙ = 300
ОКНО_ПОПРАВКИ_СЕК = 600
ВИДЫ = ("ответ", "совещание", "кабинет", "поручение")
СТАТУСЫ = ("в работе", "принято", "исправлено", "нет данных", "не вышло", "остановлено")
_НЕТ_ДАННЫХ = re.compile(r"\bнет данных\b|\bданных нет\b|не хватает данных|\bне нашёл\b|\bне нашел\b|у меня нет сведений", re.I)

_база = None
_замок = threading.Lock()

# Что агенту нельзя выдумывать: добавляется к правилам ответа в чате и к шагам совещания
ЗАЩИТА_ОТ_ВЫДУМОК = ("Если в данных, которые тебе дали, нет ответа, так и напиши: «нет данных» и одной фразой скажи, чего именно не хватает. "
                     "Цифры, суммы, даты, номера и сроки называй только из данных; не угадывай и не округляй «на глаз».")


def подключить(база) -> None:
    global _база
    _база = база


def без_данных(текст: str) -> bool:
    return bool(_НЕТ_ДАННЫХ.search(текст or ""))


def _читать() -> list[dict]:
    try:
        return list(_база.прочитать(КЛЮЧ, [])) if _база else []
    except Exception:
        return []


def записать(вид: str, вопрос: str, агенты: list[str], источники: list[str] | None = None, итог: str = "",
             статус: str = "принято", **добавка) -> int:
    """Возвращает номер записи (0, если база не подключена). Сбой журнала не ломает основное действие."""
    if not _база:
        return 0
    if статус == "принято" and без_данных(итог):
        статус = "нет данных"
    try:
        with _замок:
            записи = _читать()
            номер = (записи[-1]["id"] + 1) if записи else 1
            записи.append({"id": номер, "время": time.time(), "вид": вид if вид in ВИДЫ else "ответ",
                           "вопрос": " ".join((вопрос or "").split())[:300],
                           "агенты": [а for а in dict.fromkeys(агенты) if а],
                           "источники": list(источники or [])[:12],
                           "итог": " ".join((итог or "").split())[:500],
                           "статус": статус if статус in СТАТУСЫ else "принято", **добавка})
            _база.записать(КЛЮЧ, записи[-МАКС_ЗАПИСЕЙ:])
        return номер
    except Exception:
        журнал.exception("Не удалось записать решение в журнал")
        return 0


def обновить(номер: int, **поля) -> bool:
    if not _база or not номер:
        return False
    with _замок:
        записи = _читать()
        for з in записи:
            if з["id"] == номер:
                з.update(поля)
                if "итог" in поля:
                    з["итог"] = " ".join(str(з["итог"]).split())[:500]
                _база.записать(КЛЮЧ, записи)
                return True
    return False


def найти_по_поручению(поручение: int) -> int:
    for з in reversed(_читать()):
        if з.get("поручение") == поручение:
            return з["id"]
    return 0


def поправка(текст: str, шаблон: re.Pattern) -> int:
    """Хозяин поправил последний ответ чата — помечаем его исправленным. Возвращает номер записи или 0."""
    if not шаблон.search((текст or "").lower().replace("ё", "е")):
        return 0
    for з in reversed(_читать()):
        if з["вид"] in ("ответ", "совещание"):
            if time.time() - з["время"] <= ОКНО_ПОПРАВКИ_СЕК and з["статус"] in ("принято", "нет данных"):
                обновить(з["id"], статус="исправлено")
                return з["id"]
            break
    return 0


def журнал_записей(сколько: int = 50) -> list[dict]:
    return list(reversed(_читать()[-max(1, min(сколько, МАКС_ЗАПИСЕЙ)):]))


def качество() -> dict[str, dict]:
    """По агенту: ответов, исправлено, без данных, не вышло, доля исправлений (None, пока ответов меньше трёх)."""
    итог: dict[str, dict] = {}
    for з in _читать():
        if з["статус"] == "в работе":
            continue
        for ключ in з["агенты"]:
            к = итог.setdefault(ключ, {"ответов": 0, "исправлено": 0, "без_данных": 0, "не_вышло": 0})
            к["ответов"] += 1
            if з["статус"] == "исправлено":
                к["исправлено"] += 1
            elif з["статус"] == "нет данных":
                к["без_данных"] += 1
            elif з["статус"] == "не вышло":
                к["не_вышло"] += 1
    for к in итог.values():
        к["доля_ошибок"] = round((к["исправлено"] + к["не_вышло"]) / к["ответов"], 2) if к["ответов"] >= 3 else None
    return итог
