# ---- Токены и BM25 -----------------------------------------------------------------------------------

def _токены(текст: str) -> list[str]:
    """Слова, артикулы (c-111 → c111 и c-111) и грубые основы русских слов."""
    низ = (текст or "").casefold().replace("ё", "е")
    итог = []
    for сырой in re.findall(r"[\w][\w/\-.]*[\w]|[\w]", низ):
        слитно = re.sub(r"[^\w]", "", сырой)
        if re.search(r"\d", слитно):
            итог.append(слитно)                     # c-111, 265/65, r17 — целиком, без знаков
            итог += [ч for ч in re.split(r"[^\w]", сырой) if ч and ч != слитно]
        else:
            итог.append(слитно[:5] if len(слитно) > 4 else слитно[:3])    # грубая основа: мама/маме, фильтр/фильтры
    return итог


def bm25(запрос: str, документы: list[str], k1: float = 1.5, b: float = 0.75) -> list[float]:
    """Оценка каждого документа по BM25 (документов мало — чистый Python быстрее любой библиотеки)."""
    токены_д = [_токены(д) for д in документы]
    слова_з = set(_токены(запрос))
    n = len(документы)
    if not n or not слова_з:
        return [0.0] * n
    средняя = sum(len(т) for т in токены_д) / n or 1
    частота = {с: sum(1 for т in токены_д if с in т) for с in слова_з}
    оценки = []
    for т in токены_д:
        балл = 0.0
        for с in слова_з:
            f = т.count(с)
            if not f:
                continue
            idf = math.log(1 + (n - частота[с] + 0.5) / (частота[с] + 0.5))
            балл += idf * f * (k1 + 1) / (f + k1 * (1 - b + b * len(т) / средняя))
        оценки.append(балл)
    return оценки


def _ранги(оценки: dict) -> dict:
    """{ключ: ранг с 1} только для ненулевых оценок."""
    порядок = sorted((к for к, з in оценки.items() if з > 0), key=lambda к: -оценки[к])
    return {к: и + 1 for и, к in enumerate(порядок)}


def _дата(текст: str | None) -> datetime | None:
    try:
        return datetime.strptime((текст or "")[:19], "%Y-%m-%d %H:%M:%S")
    except ValueError:
        return None


def намерение_времени(запрос: str) -> str:
    """'сейчас' | 'прошлое' | 'будущее' | '' — по словам вопроса."""
    if _ПРОШЛОЕ.search(запрос or ""):
        return "прошлое"
    if _БУДУЩЕЕ.search(запрос or ""):
        return "будущее"
    if _СЕЙЧАС.search(запрос or ""):
        return "сейчас"
    return ""


# ---- Гибридный поиск --------------------------------------------------------------------------------

def кандидаты(база, намерение: str) -> list[dict]:
    """Активные факты; для «раньше» ещё устаревшие и архивные, для «планирую» ещё факты на будущее."""
    из_памяти = база.память(включая_устаревшие=намерение == "прошлое")
    сегодня = date.today().isoformat()
    итог = []
    for ф in из_памяти:
        состояние = ф.get("состояние", "активен")
        if состояние != "активен":
            if намерение == "прошлое":
                итог.append(ф)
            continue
        c, до = ф.get("действует_с"), ф.get("действует_до")
        будущий = bool(c and c > сегодня)
        закончился = bool(до and до < сегодня)
        if (будущий and намерение != "будущее") or (закончился and намерение != "прошлое"):
            continue
        итог.append(ф)
    return итог


def гибридный_поиск(база, н: dict, запрос: str, факты: list[dict], сколько: int, вектора=None) -> list[dict]:
    """Склеивает ранги трёх каналов (RRF) и поправку по времени. `вектора` — {ключ_факта: похожесть} или None."""
    if not факты or not запрос.strip():
        return []
    по_ключу = {ф["id"]: ф for ф in факты}
    слова = bm25(запрос, [ф["факт"] for ф in факты])
    каналы = [_ранги({ф["id"]: з for ф, з in zip(факты, слова)})]
    if вектора:
        каналы.append(_ранги({ф["id"]: вектора.get(ф["id"], 0.0) for ф in факты}))
    # сущности, названные в вопросе
    try:
        сущности = base_mentioned(база, запрос)
        if сущности:
            каналы.append(_ранги({ф["id"]: 1.0 for ф in факты if set(ф.get("сущности", [])) & сущности}))
    except Exception:
        журнал.exception("Канал сущностей не сработал")
    итог = {}
    for ранги in каналы:
        for к, р in ранги.items():
            итог[к] = итог.get(к, 0.0) + 1.0 / (60 + р)
    намерение = намерение_времени(запрос)
    сейчас = datetime.now()
    for к in итог:
        ф = по_ключу[к]
        когда = _дата(ф.get("изменено")) or _дата(ф.get("создано"))
        возраст = max(0.0, (сейчас - когда).total_seconds() / 86400) if когда else 365.0
        if намерение == "сейчас":
            итог[к] *= 1.0 + 0.6 * math.exp(-возраст / 60)
        elif намерение == "прошлое" and ф.get("состояние") != "активен":
            итог[к] *= 1.4
        elif намерение == "будущее" and (ф.get("действует_с") or "") > date.today().isoformat():
            итог[к] *= 1.4
    лучшие = sorted(итог, key=lambda к: -итог[к])[:сколько]
    return [по_ключу[к] for к in лучшие]


def base_mentioned(база, запрос: str) -> set[int]:
    """id сущностей, названных в вопросе (без обращений к ИИ)."""
    from . import memory
    к = ключ_имени(запрос)
    слова = к.split()
    return {с["id"] for с in база.сущности() if memory._упомянута(с, к, слова)}


# ---- История и архив ----------------------------------------------------------------------------------

def записать_версию(база, факт_id: int, текст: str, причина: str) -> None:
    with база.соединение() as связь:
        связь.execute("INSERT INTO память_версия (факт_id, текст, причина) VALUES (?, ?, ?)", (факт_id, текст, причина[:200]))


def история_факта(база, факт_id: int) -> list[dict]:
    with база.соединение() as связь:
        строки = связь.execute("SELECT id, текст, причина, создано FROM память_версия WHERE факт_id = ? ORDER BY id DESC LIMIT 30",
                               (факт_id,)).fetchall()
    return [dict(с) for с in строки]


def архивировать(база, факт_id: int, причина: str) -> bool:
    ф = база.факт(факт_id)
    if not ф or ф["состояние"] != "активен":
        return False
    записать_версию(база, факт_id, ф["факт"], f"в архив: {причина}")
    база.изменить_факт(факт_id, {"состояние": "архив"})
    return True


def восстановить(база, факт_id: int) -> dict | None:
    ф = база.факт(факт_id)
    if not ф or ф["состояние"] == "активен":
        return None
    записать_версию(база, факт_id, ф["факт"], "возвращён из архива")
    return база.изменить_факт(факт_id, {"состояние": "активен", "заменён_на": None})


def архив(база) -> list[dict]:
    return [ф for ф in база.память(включая_устаревшие=True) if ф["состояние"] != "активен"][::-1][:200]


