"""Память, ступень вторая: гибридный поиск, архив с историей, очередь предложений, затухание и «сон».

Идеи: mem0 (параллельные каналы поиска, ранжирование по времени), loom (архив вместо удаления, слияние дублей,
история правок, очередь предложений), Sibelium (забывание слабого, защита важного, ночное обобщение).

1. Поиск: три канала — смысл (эмбеддинги), слова (BM25: артикул «C-111» находится и как «C111») и сущности
   (факты о людях и вещах, названных в вопросе) — склеиваются по рангам (RRF). Слова вроде «сейчас» поднимают свежие факты,
   «раньше» добавляют устаревшие, «планирую» — факты на будущее.
2. Память ничего не стирает по решению ИИ: забытое уходит в архив, откуда его можно вернуть; у факта хранится история правок.
3. Предложения: при включённом «Спрашивать перед запоминанием» новый факт ждёт вашего «Запомнить».
4. «Сон» раз в сутки: слияние дублей, архивация слабого (давно не нужного и неважного), предложения-обобщения.
   Важное (важность 4–5, работа, даты, ТО, сроки, документы) не забывается никогда.
"""

