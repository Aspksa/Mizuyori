def предложить(база, факт: str, категория: str = "другое", важность: int = 3, источник: int | None = None,
               почему: str = "", заменяет: list[int] | None = None) -> dict | None:
    факт = " ".join((факт or "").split())[:300]
    if not факт:
        return None
    with база.соединение() as связь:
        if связь.execute("SELECT 1 FROM память_предложение WHERE статус = 'ждёт' AND факт = ?", (факт,)).fetchone():
            return None
        номер = связь.execute(
            "INSERT INTO память_предложение (факт, категория, важность, источник, почему, заменяет) VALUES (?, ?, ?, ?, ?, ?)",
            (факт, категория, важность, источник, почему[:200], json.dumps(заменяет or []))).lastrowid
        связь.execute("DELETE FROM память_предложение WHERE статус != 'ждёт' AND id NOT IN "
                      "(SELECT id FROM память_предложение WHERE статус != 'ждёт' ORDER BY id DESC LIMIT 30)")
    return предложение(база, номер)


def предложение(база, номер: int) -> dict | None:
    with база.соединение() as связь:
        с = связь.execute("SELECT * FROM память_предложение WHERE id = ?", (номер,)).fetchone()
    if not с:
        return None
    з = dict(с)
    з["заменяет"] = json.loads(з["заменяет"] or "[]")
    return з


def предложения(база, только_ждущие: bool = True) -> list[dict]:
    with база.соединение() as связь:
        условие = "WHERE статус = 'ждёт'" if только_ждущие else ""
        строки = связь.execute(f"SELECT id FROM память_предложение {условие} ORDER BY id DESC LIMIT 50").fetchall()
    return [предложение(база, с[0]) for с in строки]


def принять(база, номер: int) -> dict | None:
    п = предложение(база, номер)
    if not п or п["статус"] != "ждёт":
        return None
    новый = база.запомнить(п["факт"], п["источник"], п["категория"], п["важность"], None, 1.0)
    for старый in п["заменяет"]:
        архивировать(база, int(старый), "обобщено в новом факте")
    with база.соединение() as связь:
        связь.execute("UPDATE память_предложение SET статус = 'принято', решено = datetime('now', 'localtime') WHERE id = ?", (номер,))
    audit.записать("факт принят в память", п["факт"][:100])
    return {"предложение": предложение(база, номер), "факт": новый}


def отклонить(база, номер: int) -> dict | None:
    п = предложение(база, номер)
    if not п or п["статус"] != "ждёт":
        return None
    with база.соединение() as связь:
        связь.execute("UPDATE память_предложение SET статус = 'отклонено', решено = datetime('now', 'localtime') WHERE id = ?", (номер,))
    audit.записать("факт в память отклонён", п["факт"][:100])
    return предложение(база, номер)


# ---- Затухание и «сон» ---------------------------------------------------------------------------------

def защищён(ф: dict) -> bool:
    if ф["важность"] >= 4 or ф["категория"] in ЗАЩИЩЁННЫЕ_КАТЕГОРИИ or _ЗАЩИЩЁННЫЙ_ТЕКСТ.search(ф["факт"]):
        return True
    до = ф.get("действует_до")
    return bool(до and до >= date.today().isoformat())


def сила(ф: dict, сейчас: datetime | None = None) -> float:
    """1 — только что нужен; падает вдвое за полужизнь (зависит от важности), растёт с каждым использованием."""
    сейчас = сейчас or datetime.now()
    когда = _дата(ф.get("последнее_использование")) or _дата(ф.get("изменено")) or _дата(ф.get("создано")) or сейчас
    возраст = max(0.0, (сейчас - когда).total_seconds() / 86400)
    полужизнь = ПОЛУЖИЗНЬ_ДНЕЙ.get(ф["важность"], 90)
    return min(1.0, 0.5 ** (возраст / полужизнь) * (1 + 0.5 * math.log1p(ф.get("использовано", 0))))


def забыть_слабое(база, сейчас: datetime | None = None) -> list[dict]:
    """Слабые и неважные факты уходят в архив (не удаляются)."""
    сейчас = сейчас or datetime.now()
    ушли = []
    for ф in база.память():
        когда = _дата(ф.get("создано")) or сейчас
        if защищён(ф) or (сейчас - когда).days < МИН_ВОЗРАСТ_ДНЕЙ:
            continue
        if сила(ф, сейчас) < ПОРОГ_ЗАБЫВАНИЯ and архивировать(база, ф["id"], "давно не нужен"):
            ушли.append(ф)
    return ушли


def слить_дубли(база, н: dict | None = None) -> int:
    """Точные повторы (с учётом регистра и знаков) и, если есть эмбеддинги, почти одинаковые по смыслу."""
    из_памяти = sorted(база.память(), key=lambda ф: (-ф["важность"], ф["id"]))
    слито, видели = 0, {}
    for ф in из_памяти:
        ключ = re.sub(r"[^\w]", "", ключ_имени(ф["факт"]))
        if ключ in видели:
            слито += _слить(база, видели[ключ], ф)
        else:
            видели[ключ] = ф
    if н:
        from . import memory
        if memory.можно_эмбеддинги(н):
            try:
                слито += _слить_по_смыслу(база, н, memory)
            except ai.ОшибкаИИ as е:
                журнал.warning("Слияние по смыслу не удалось: %s", е)
    return слито


def _слить(база, основной: dict, повтор: dict) -> int:
    if not база.объединить_факты(основной["id"], повтор["id"]):
        return 0
    записать_версию(база, основной["id"], основной["факт"], f"слит с повтором: {повтор['факт'][:120]}")
    записать_версию(база, повтор["id"], повтор["факт"], f"слит в факт №{основной['id']}")
    return 1


def _слить_по_смыслу(база, н: dict, memory) -> int:
    факты = sorted(база.память(), key=lambda ф: (-ф["важность"], ф["id"]))
    if len(факты) < 2:
        return 0
    ключи, матрица, _ = memory.обеспечить_вектора(база, н, {f"п{ф['id']}": ф["факт"] for ф in факты})
    по_ключу = {f"п{ф['id']}": ф for ф in факты}
    сходство = матрица @ матрица.T
    уже, слито = set(), 0
    for i, к in enumerate(ключи):
        if к in уже:
            continue
        for j in range(i + 1, len(ключи)):
            if ключи[j] in уже or сходство[i][j] < memory.ПОРОГ_ДУБЛЯ:
                continue
            слито += _слить(база, по_ключу[к], по_ключу[ключи[j]])
            уже.add(ключи[j])
    return слито


_СИСТЕМА_ОБОБЩЕНИЯ = (
    "Ты помощник памяти. Среди фактов о хозяине найди до 3 групп из 2–5 близких мелких фактов, которые можно заменить "
    "одним точным обобщающим фактом без потери смысла. Ответь ТОЛЬКО JSON: "
    '{"обобщения": [{"факт": "до 200 знаков", "заменяет": [id, id]}]}. Не выдумывай. Нечего обобщить — {"обобщения": []}.'
)


def обобщить(база, н: dict) -> int:
    """ИИ предлагает обобщения; они попадают в очередь и ждут вашего решения."""
    факты = [ф for ф in база.память() if not защищён(ф)]
    if len(факты) < МИН_ФАКТОВ_ДЛЯ_ОБОБЩЕНИЯ or not ai.подключён(н):
        return 0
    from . import learning
    ответ = learning._спросить(agents.с_правилами(dict(н), "память"), _СИСТЕМА_ОБОБЩЕНИЯ,
                               {"факты": [{"id": ф["id"], "факт": ф["факт"]} for ф in факты[:80]]})
    м = re.search(r"\{.*\}", ответ or "", re.S)
    try:
        данные = json.loads(м.group(0)) if м else {}
    except ValueError:
        return 0
    допустимые = {ф["id"] for ф in факты}
    добавлено = 0
    for о in (данные.get("обобщения") or [])[:3]:
        ids = [int(и) for и in (о.get("заменяет") or []) if str(и).isdigit() and int(и) in допустимые]
        if len(ids) >= 2 and о.get("факт"):
            if предложить(база, str(о["факт"]), "другое", 3, None, "обобщение близких фактов", ids):
                добавлено += 1
    return добавлено


def сон(база, н: dict | None = None) -> dict:
    """Один «ночной» проход: дубли, слабое, обобщения. Возвращает счёт."""
    итог = {"слито": слить_дубли(база, н), "забыто": len(забыть_слабое(база)), "обобщений": 0}
    if н:
        try:
            итог["обобщений"] = обобщить(база, н)
        except ai.ОшибкаИИ as е:
            журнал.warning("Обобщение не удалось: %s", е)
    audit.записать("сон памяти выполнен", "", f"слито: {итог['слито']}, в архив: {итог['забыто']}, обобщений: {итог['обобщений']}", кто="память")
    return итог


def _пора() -> bool:
    з = audit.список(1, "сон памяти выполнен")
    когда = _дата(з[0]["создано"]) if з else None
    return когда is None or (datetime.now() - когда).total_seconds() > ПАУЗА_СНА_ЧАСОВ * 3600


_поток: threading.Thread | None = None


def запустить(база, получить_ии) -> None:
    """Сон раз в сутки, когда ИИ свободен; без ИИ — только слияние точных повторов и забывание."""
    global _поток
    if _поток and _поток.is_alive():
        return

    def цикл():
        time.sleep(240)
        while True:
            try:
                if _пора():
                    н = dict(получить_ии())
                    сон(база, н if ai.подключён(н) else None)
            except Exception:
                журнал.exception("Сон памяти")
            time.sleep(3600)
    _поток = threading.Thread(target=цикл, name="mizuyori-сон-памяти", daemon=True)
    _поток.start()
