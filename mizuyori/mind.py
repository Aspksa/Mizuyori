"""«Второй мозг» на главной: кластеры знаний (разделы памяти и контрагенты с Диска), точки-записи,
какие из них уже «прочитаны» агентами, и рост души от прочитанного.

«Изучено» здесь — отметка, что агент просмотрел запись (видно на карте). Это не разбор текста ИИ:
тот делают фоновые агенты и «Душа» отдельно."""
import json
import re

from . import memory_ring

МИГРАЦИЯ = """
CREATE TABLE изучено_мозгом (
    ключ  TEXT PRIMARY KEY,
    агент TEXT NOT NULL DEFAULT '',
    когда TEXT NOT NULL DEFAULT (datetime('now', 'localtime'))
);
"""

# сколько прочитанных записей нужно до уровня души: 1, 2, 3…
ПОРОГИ_РОСТА = [0, 8, 25, 60, 120, 220, 380, 600, 900, 1300, 1800]
ТОЧЕК_В_КЛАСТЕРЕ = 120
_КЛЮЧ = re.compile(r"^[спнзеф]\d{1,9}$")


def рост(изучено: int) -> dict:
    н = 1
    for i, п in enumerate(ПОРОГИ_РОСТА):
        if изучено >= п:
            н = i + 1
    до = ПОРОГИ_РОСТА[н] if н < len(ПОРОГИ_РОСТА) else None
    return {"изучено": изучено, "уровень": н, "от": ПОРОГИ_РОСТА[н - 1], "до": до}


def карта(база) -> dict:
    with база.соединение() as с:
        изучено = {х[0]: х[1] for х in с.execute("SELECT ключ, агент FROM изучено_мозгом")}
        кластеры = []
        for р in memory_ring.РАЗДЕЛЫ:
            число = с.execute(р["счёт"]).fetchone()[0]
            строки = [(f'{р["префикс"]}{х["id"]}', memory_ring._кратко(х["текст"], 60)) for х in с.execute(р["список"], (ТОЧЕК_В_КЛАСТЕРЕ,))]
            кластеры.append({"ключ": р["ключ"], "имя": р["имя"], "значок": р["значок"], "цвет": р["цвет"], "вид": "память",
                             "число": число, "точки": [[к, 1 if к in изучено else 0, т] for к, т in строки]})
        цвета = ["#6aa9ff", "#3ecf9a", "#f5a34b", "#c58bff", "#ff7aa8", "#5fd4e6", "#e6d35f"]
        try:
            строки = с.execute(
                "SELECT к.id, к.название, COUNT(ф.id) AS н FROM раб_контрагенты к "
                "JOIN раб_файлы ф ON ф.контрагент_id = к.id AND ф.удалён = 0 GROUP BY к.id ORDER BY н DESC LIMIT 14").fetchall()
            for i, к in enumerate(строки):
                строки = [(f'ф{х[0]}', memory_ring._кратко(х[1], 60)) for х in с.execute(
                    "SELECT id, имя FROM раб_файлы WHERE контрагент_id = ? AND удалён = 0 ORDER BY id DESC LIMIT ?", (к["id"], ТОЧЕК_В_КЛАСТЕРЕ))]
                кластеры.append({"ключ": f'д{к["id"]}', "имя": к["название"][:28], "значок": "▤", "цвет": цвета[i % len(цвета)], "вид": "диск",
                                 "число": к["н"], "точки": [[x, 1 if x in изучено else 0, т] for x, т in строки]})
        except Exception:      # диск ещё не настроен
            pass
        рутины = _рутины(с)
    return {"кластеры": [к for к in кластеры if к["число"]], "рост": рост(len(изучено)), "рутины": рутины}


def отметить(база, ключи: list[str], агент: str) -> dict:
    """Записать, что агент просмотрел записи. Ключи — «п12», «ф3»… Повторы игнорируются."""
    чистые = [к for к in dict.fromkeys(ключи) if isinstance(к, str) and _КЛЮЧ.match(к)][:20]
    with база.соединение() as с:
        for к in чистые:
            с.execute("INSERT OR IGNORE INTO изучено_мозгом (ключ, агент) VALUES (?, ?)", (к, (агент or "")[:40]))
        число = с.execute("SELECT COUNT(*) FROM изучено_мозгом").fetchone()[0]
    return рост(число)


_ИКОНКИ_СТАТУСОВ = {"в работе": "▶", "ждёт вас": "!", "готово": "✓", "не вышло": "✕", "остановлено": "■", "новое": "•"}


def _рутины(с) -> list[dict]:
    """Регулярное и повторяемое: повторяющиеся задачи, шаблоны поручений и недавние поручения агентам."""
    итог = []
    try:
        for х in с.execute("SELECT id, текст, повтор FROM задачи WHERE повтор != '' AND готово = 0 AND удалено IS NULL AND архив = 0 "
                           "ORDER BY id DESC LIMIT 12"):
            итог.append({"ключ": f"рз{х['id']}", "вид": "повтор", "имя": memory_ring._кратко(х["текст"], 40), "деталь": f"повтор: {х['повтор']}",
                         "агенты": [], "разделы": ["задачи"], "значок": "⟳"})
        for х in с.execute("SELECT id, название, шаги FROM шаблон_поручения ORDER BY id DESC LIMIT 10"):
            итог.append({"ключ": f"рш{х['id']}", "вид": "шаблон", "имя": memory_ring._кратко(х["название"], 40), "деталь": "шаблон поручения",
                         "агенты": _агенты_шагов(х["шаги"]), "разделы": [], "значок": "▤"})
        for х in с.execute("SELECT id, название, статус, шаги FROM поручение ORDER BY id DESC LIMIT 10"):
            итог.append({"ключ": f"рп{х['id']}", "вид": "поручение", "имя": memory_ring._кратко(х["название"], 40), "деталь": f"поручение · {х['статус']}",
                         "агенты": _агенты_шагов(х["шаги"]), "разделы": [], "значок": _ИКОНКИ_СТАТУСОВ.get(х["статус"], "•"),
                         "работает": х["статус"] == "в работе"})
    except Exception:
        pass
    return итог


def _агенты_шагов(шаги: str) -> list[str]:
    try:
        return list(dict.fromkeys(ш.get("агент", "") for ш in json.loads(шаги) if isinstance(ш, dict) and ш.get("агент")))[:6]
    except Exception:
        return []
