"""Постоянная учёба агентов: думают по событиям, учатся на поправках хозяина и делятся опытом.

Как это устроено:
- События: хозяин поправил агента в чате, пришёл «урок» от коллеги, накопились новые ошибки (обзор раз в несколько часов).
- Одна очередь и один поток: агенты думают по одному, чат всегда важнее — пока идёт разговор, фон ждёт.
- Общий предохранитель: не больше N запросов к ИИ в час на всех агентов (config.json → «агенты»).
- Обмен опытом: агент пишет коллеге на доске «Урок: …»; получатель сам решает, принять ли его в память.
- Выдумывать запрещено: приём пишется только из событий, которые есть в данных."""

import logging
import re
import threading
import time

from . import agents

журнал = logging.getLogger("mizuyori.учёба")

НАСТРОЙКИ: dict = {"учиться_в_фоне": True, "запросов_в_час": 12}
ОБЗОР_МИНУТ = 240          # как часто агент пересматривает свои ошибки
ПАУЗА_ПОСЛЕ_ЧАТА = 90      # секунд тишины в чате, прежде чем думать в фоне
УРОКОВ_В_СУТКИ = 3         # сколько уроков агент может раздать за сутки

_замок = threading.Lock()
_вызовы: list[float] = []
_чат_время = 0.0
_обмен = {"агент": "", "вопрос": "", "ответ": "", "время": 0.0}
_ожидают: dict[str, list[dict]] = {}
_снимок_ошибок: dict[str, int] = {}
_последний_обзор: dict[str, float] = {}
_роздано: dict[str, list[float]] = {}
_сигнал = threading.Event()
_поток = None
_сейчас = ""

_ПОПРАВКА = re.compile(r"^\W*(нет\b|не так|не то\b|неправильн|неверн|ошиб|я имел в виду|я просил|не надо так|"
                       r"не нужно так|опять не|не туда|не тот|не та\b|не то)", re.I)


# ---- Состояние и предохранитель -------------------------------------------------------

def _использовано() -> int:
    граница = time.time() - 3600
    with _замок:
        _вызовы[:] = [в for в in _вызовы if в > граница]
        return len(_вызовы)


def состояние() -> dict:
    with _замок:
        ждут = {к: len(с) for к, с in _ожидают.items()}
    return {"включено": bool(НАСТРОЙКИ["учиться_в_фоне"]), "запросов_в_час": int(НАСТРОЙКИ["запросов_в_час"]),
            "использовано": _использовано(), "очередь": sum(ждут.values()), "думает": _сейчас,
            "ждут": ждут}


def чат_идёт() -> None:
    """Чат вызывает это на каждое сообщение: фон уступает дорогу."""
    global _чат_время
    _чат_время = time.time()


# ---- События ----------------------------------------------------------------------------

def запомнить_обмен(агент: str, вопрос: str, ответ: str) -> None:
    """Последний ответ агента в чате — к нему относится следующая поправка хозяина."""
    _обмен.update({"агент": агент, "вопрос": " ".join(вопрос.split())[:300],
                   "ответ": " ".join(ответ.split())[:500], "время": time.time()})


def проверить_поправку(текст: str) -> str:
    """Если хозяин поправляет агента, запоминает поправку; возвращает ключ агента или ''."""
    ключ = _обмен["агент"]
    if not ключ or time.time() - _обмен["время"] > 600 or not _ПОПРАВКА.search(текст.lower().replace("ё", "е")):
        return ""
    короткая = " ".join(текст.split())[:200]
    try:
        # дёшево и всегда (без ИИ): поправка сразу становится частой ошибкой агента
        agents.запомнить_ошибку(ключ, f"Хозяин поправил: «{короткая}»")
    except Exception:
        журнал.exception("Не удалось записать поправку")
    событие(ключ, "поправка", {"хозяин_написал": текст[:400], "до_этого_я_ответил": _обмен["ответ"],
                              "на_вопрос": _обмен["вопрос"]})
    _обмен["агент"] = ""
    return ключ


def событие(ключ: str, вид: str, данные: dict) -> None:
    with _замок:
        _ожидают.setdefault(ключ, []).append({"вид": вид, **данные})
    _сигнал.set()


def _запланировать_обзоры() -> None:
    сейчас = time.time()
    for а in agents.АГЕНТЫ:
        ключ = а["ключ"]
        if а.get("группа") != "Работа" or сейчас - _последний_обзор.get(ключ, 0) < ОБЗОР_МИНУТ * 60:
            continue
        ошибки = [з for з in agents.заметки(ключ) if з["вид"] == "ошибка"]
        итог = sum(з["счёт"] for з in ошибки)
        новые = итог != _снимок_ошибок.get(ключ, 0)
        _снимок_ошибок[ключ] = итог
        if len(ошибки) >= 2 and новые:
            _последний_обзор[ключ] = сейчас
            событие(ключ, "обзор", {})
        elif ключ not in _последний_обзор:
            _последний_обзор[ключ] = сейчас


# ---- Размышление ----------------------------------------------------------------------------

_СИСТЕМА = (
    "Ты — {имя} ({что}), помощник отдела главного механика автотранспортного предприятия. "
    "Ты учишься на опыте. В данных: события (поправки хозяина, частые замечания), твои записанные правила, "
    "уроки от коллег и список коллег. Опирайся ТОЛЬКО на то, что есть в данных, ничего не выдумывай. "
    "Ответ — один JSON: {{\"приём\": \"...\", \"урок\": {{\"кому\": \"ключ коллеги\", \"текст\": \"...\"}}, "
    "\"принять\": [номера уроков]}}.\n"
    "«приём» — ОДИН новый короткий рабочий приём (до 200 знаков) из событий, не повторяющий записанное; "
    "если поправка хозяина показывает, что ты ошибся, сформулируй, как делать правильно. Нет нового — \"\".\n"
    "«урок» — короткий совет (до 200 знаков) конкретному коллеге, которому он реально пригодится; "
    "нет такого — {{\"кому\": \"\", \"текст\": \"\"}}.\n"
    "«принять» — номера входящих уроков, полезных именно тебе; остальные будут отброшены."
)


def _спросить(н: dict, система: str, данные: dict) -> str:
    from . import ai
    for попытка in range(3):
        try:
            with _замок:
                _вызовы.append(time.time())
            return ai._задание(система, данные, н, 400)
        except Exception as ошибка:
            if попытка < 2 and ("429" in str(ошибка) or "Слишком много" in str(ошибка)):
                time.sleep(30 * (попытка + 1))
                continue
            raise


def _похоже(а: str, б: str) -> bool:
    а, б = re.sub(r"\W+", " ", а.lower()).strip(), re.sub(r"\W+", " ", б.lower()).strip()
    return bool(а) and bool(б) and (а in б or б in а)


def _не_прошёл_проверку(ключ: str, текст: str, н: dict, запись: dict) -> bool:
    """Проверка перед принятием урока (evolve.проверить_урок): хуже прошлого опыта — не записываем, причину сохраняем."""
    try:
        from . import evolve
        п = evolve.проверить_урок(ключ, текст, н)
    except Exception:
        return False
    if п["принять"]:
        return False
    evolve.отклонённый_урок(ключ, текст, п)
    запись["результат"] = f"урок не прошёл проверку: {п['почему']}"[:120]
    return True


def разобрать(ключ: str, события: list[dict], н: dict) -> dict:
    """Один раунд мысли агента. Возвращает {'приём','принято','урок'} — для проверки и журнала."""
    import json
    from . import ai
    итог = {"приём": "", "принято": 0, "урок": ""}
    заметки = agents.заметки(ключ)
    есть = [з["текст"] for з in заметки if з["вид"] in ("правило", "приём")]
    ошибки = [{"замечание": з["текст"], "повторов": з["счёт"]} for з in заметки if з["вид"] == "ошибка"][:15]
    входящие = [з for з in agents.непрочитанные(ключ) if з["текст"].startswith("Урок:")]
    if not события and not входящие:
        return итог
    данные = {"события": [с for с in события if с["вид"] != "обзор"][:5],
              "частые_замечания": ошибки, "уже_записано": есть,
              "входящие_уроки": [{"номер": з["id"], "от": agents.ИМЕНА.get(з["от"], з["от"]), "текст": з["текст"][6:].strip()}
                                 for з in входящие][:5],
              "коллеги": {а["ключ"]: f"{а['имя']} — {а.get('что', '')}" for а in agents.АГЕНТЫ
                          if а.get("группа") == "Работа" and а["ключ"] != ключ}}
    а = next(а for а in agents.АГЕНТЫ if а["ключ"] == ключ)
    система = _СИСТЕМА.format(имя=а["имя"], что=а.get("что", ""))
    причина = ", ".join(sorted({с["вид"] for с in события})) or "уроки от коллег"
    try:
        ответ = _спросить(agents.с_правилами(н, ключ), система, данные)
    except Exception:
        журнал.warning("ИИ недоступен: %s не смог подумать сейчас", ключ)
        return итог                  # сбой связи — не опыт агента; события останутся в очереди
    with agents.работа(ключ, "думаю и учусь", f"по событию: {причина}") as з:
        try:
            разбор = json.loads(ai._ОБЪЕКТ.search(ответ).group(0))
        except Exception:
            разбор = {}
        приём = " ".join(str(разбор.get("приём") or "").split())[:200]
        if приём and not any(_похоже(приём, е) for е in есть) and not _не_прошёл_проверку(ключ, приём, н, з):
            agents.добавить_заметку(ключ, "приём", приём, "поправка" if any(с["вид"] == "поправка" for с in события) else "сам")
            итог["приём"] = приём
        принять = set()
        for номер in разбор.get("принять") or []:
            try:
                принять.add(int(номер))
            except (TypeError, ValueError):
                pass
        for у in входящие:
            if у["id"] in принять:
                текст = у["текст"][6:].strip()[:200]
                if текст and not any(_похоже(текст, е) for е in есть + [итог["приём"]]) and not _не_прошёл_проверку(ключ, текст, н, з):
                    agents.добавить_заметку(ключ, "приём", текст, f"от {agents.ИМЕНА.get(у['от'], у['от'])}")
                    итог["принято"] += 1
        agents.прочитать([у["id"] for у in входящие])
        урок = разбор.get("урок") if isinstance(разбор.get("урок"), dict) else {}
        кому, текст_урока = str(урок.get("кому") or ""), " ".join(str(урок.get("текст") or "").split())[:200]
        граница = time.time() - 86400
        _роздано[ключ] = [т for т in _роздано.get(ключ, []) if т > граница]
        # урок в ответ на чужой урок не пересылаем — иначе агенты начнут перекидываться бесконечно
        if (кому in agents.ИМЕНА and кому != ключ and текст_урока and входящие == []
                and len(_роздано[ключ]) < УРОКОВ_В_СУТКИ):
            agents.написать(ключ, кому, f"Урок: {текст_урока}")
            _роздано[ключ].append(time.time())
            итог["урок"] = f"{agents.ИМЕНА[кому]}: {текст_урока}"
            событие(кому, "урок", {})
        части = ([f"новый приём: {итог['приём']}"] if итог["приём"] else []) + \
                ([f"принял уроков: {итог['принято']}"] if итог["принято"] else []) + \
                ([f"передал урок → {итог['урок']}"] if итог["урок"] else [])
        з["результат"] = "; ".join(части) or "нового не нашёл"
        з["польза"] = 3 if части else 1
    return итог


# ---- Ревизия: что агенты выучили ------------------------------------------------------------

def ревизия() -> list[dict]:
    """Все приёмы, которые агенты записали сами (не вы), с пометками для проверки."""
    список = []
    for а in agents.АГЕНТЫ:
        for з in agents.заметки(а["ключ"]):
            if з["вид"] == "приём" and з["источник"] != "вы":
                список.append({**з, "имя": а["имя"]})
    нормы = [re.sub(r"\W+", " ", з["текст"].lower()).strip() for з in список]
    for i, з in enumerate(список):
        замечания = []
        слов = нормы[i].split()
        if len(слов) < 4:
            замечания.append("слишком общее — мало конкретики")
        for j, другая in enumerate(нормы):
            if i != j and список[j]["агент"] != з["агент"]:
                общие = set(слов) & set(другая.split())
                if len(общие) >= max(4, 0.7 * min(len(слов), len(другая.split()))):
                    замечания.append(f"похоже на приём «{список[j]['имя']}»")
                    break
            elif i != j and j < i and _похоже(нормы[i], другая):
                замечания.append("повторяет другой приём этого агента")
                break
        if з["источник"].startswith("от ") and not замечания:
            pass
        з["замечания"] = замечания
    return sorted(список, key=lambda з: (not з["замечания"], -з["id"]))


# ---- Фоновый поток ----------------------------------------------------------------------------

def _можно_думать() -> bool:
    return (НАСТРОЙКИ["учиться_в_фоне"] and time.time() - _чат_время >= ПАУЗА_ПОСЛЕ_ЧАТА
            and _использовано() < int(НАСТРОЙКИ["запросов_в_час"]))


def _раунд(получить_ии) -> bool:
    """Обрабатывает одного агента из очереди. False — делать нечего или нельзя."""
    global _сейчас
    with _замок:
        ключ = next(iter(_ожидают), None)
        события = list(_ожидают.get(ключ, [])) if ключ else []
    if not ключ or not _можно_думать():
        return False
    from . import ai
    н = dict(получить_ии())
    if not ai.подключён(н):
        return False
    _сейчас = ключ
    try:
        разобрать(ключ, события, н)
    except Exception:
        журнал.exception("Агент %s не смог подумать", ключ)
    finally:
        _сейчас = ""
    with _замок:                        # убираем только то, что обработали; новое остаётся
        осталось = _ожидают.get(ключ, [])[len(события):]
        if осталось:
            _ожидают[ключ] = осталось
        else:
            _ожидают.pop(ключ, None)
    return True


def запустить(база, получить_ии) -> None:
    global _поток
    if _поток and _поток.is_alive():
        return

    def цикл():
        time.sleep(90)
        while True:
            try:
                if НАСТРОЙКИ["учиться_в_фоне"]:
                    _запланировать_обзоры()
                    while _раунд(получить_ии):
                        time.sleep(20)          # агенты думают по одному, не пачкой
            except Exception:
                журнал.exception("Фоновая учёба агентов")
            _сигнал.wait(timeout=120)
            _сигнал.clear()

    _поток = threading.Thread(target=цикл, name="mizuyori-learning", daemon=True)
    _поток.start()
