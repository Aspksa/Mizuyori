"""Чувства агентов: уши (слушают папку «Приёмная»), ноги (ходят по сети и ищут)."""
from __future__ import annotations

import base64
import html
import logging
import re
import threading
import time
import urllib.parse
import urllib.request

from . import agents, archive, paths

журнал = logging.getLogger("mizuyori.чувства")

ПРИЁМНАЯ = paths.ПАПКА_ДАННЫХ / "Приёмная"
ГОТОВО = ПРИЁМНАЯ / "обработано"
ОПРОС_СЕК = 20
_поток = None
_замок = threading.Lock()


# ---- Уши: слушают «Приёмную» ---------------------------------------------------------------

def прослушать(база, настройки_ии: dict | None = None) -> list[str]:
    """Новые файлы из «Приёмной» → Архивариус раскладывает по контрагентам и договорам."""
    ПРИЁМНАЯ.mkdir(parents=True, exist_ok=True)
    итог = []
    for п in sorted(ПРИЁМНАЯ.iterdir()):
        if not п.is_file() or п.name.startswith(("~", ".")):
            continue
        if time.time() - п.stat().st_mtime < 3:           # файл ещё копируется
            continue
        try:
            with agents.работа("архивариус", "услышал новый файл", п.name) as з:
                ф = archive.принять_файл(база, настройки_ии, п.name, п.read_bytes())
                где = ф.get("путь") or ф.get("имя") or п.name
                з["результат"] = f"разложил: {где}"
                з["польза"] = 2
            ГОТОВО.mkdir(exist_ok=True)
            цель = ГОТОВО / п.name
            if цель.exists():
                цель = ГОТОВО / f"{int(time.time())}_{п.name}"
            п.replace(цель)
            agents.написать("архивариус", "смотрящий", f"Принял файл «{п.name}» из приёмной")
            итог.append(f"{п.name} → {где}")
        except Exception:
            журнал.exception("Файл из приёмной не принят: %s", п.name)
    return итог


def запустить_уши(база, получить_настройки_ии) -> None:
    global _поток
    with _замок:
        if _поток and _поток.is_alive():
            return

        def цикл():
            time.sleep(15)
            while True:
                try:
                    прослушать(база, получить_настройки_ии())
                except Exception:
                    журнал.exception("Уши агентов")
                time.sleep(ОПРОС_СЕК)

        _поток = threading.Thread(target=цикл, name="mizuyori-ears", daemon=True)
        _поток.start()


# ---- Ноги: поиск в сети -----------------------------------------------------------------------

# Кому адресована просьба: по имени в начале («Снабженец, …», «снабженец найди …», «Юрист: …»)
_ОБРАЩЕНИЕ = re.compile(r"^\s*(?:(?:снабженец|снабжение|склад|юрист|бухгалтер|экономист)\b|[а-яё\-]+\s*[,:])\s*[,:]?\s*", re.I)
# Глаголы, после которых всё сказанное — запрос в сеть
_ЯВНЫЙ_ПОИСК = re.compile(r"^(?:пожалуйста[, ]+)?(?:найди|найти|поищи|поискать|ищи|загугли|погугли)\b[\s,:-]*(.{3,200})", re.I)
# Глаголы, которые часто значат и «посмотри у нас» — нужен признак, что речь про сеть или покупку
_МЯГКИЙ_ПОИСК = re.compile(r"^(?:пожалуйста[, ]+)?(?:посмотри|глянь|узнай|выясни|подбери|подобрать|сравни|проверь|поспрашивай)\b[\s,:-]*(.{3,200})", re.I)
_ПРИЗНАК_СЕТИ = re.compile(r"в (?:интернете|интернет|сети|гугле|яндексе)|онлайн|\bцен[аыуе]\b|стоимост|сколько стоит|где купить|"
                           r"аналог|поставщик|купить|прайс|в наличии|\bкп\b", re.I)
_СВОЁ = re.compile(r"\bу нас\b|\bнаш|договор|архив|оферт|служебн|табель|путев|заправк", re.I)
_ПРЕДЛОГ_СЕТИ = re.compile(r"^(?:в (?:интернете|интернет|сети|гугле|яндексе)|онлайн)\s*[,:-]?\s*", re.I)


def разобрать_просьбу(текст: str) -> tuple[str, str]:
    """(запрос в сеть, агент или ""). Пусто, если это не просьба что-то найти в интернете.
    Понимает: «найди …», «Снабженец найди …» (без запятой), «поищи в интернете …», «подбери аналоги …»,
    «посмотри в сети сколько стоит …», а Снабженцу ещё и «цены на шины Хайлюкс?», «где купить фильтр»."""
    т = текст.strip()
    агент = ""
    м = _ОБРАЩЕНИЕ.match(т)
    остаток = т
    if м:
        слово = м.group(0).strip(" ,:").casefold()
        агент = слово if слово in ("снабженец", "склад", "юрист", "бухгалтер", "экономист") else ""
        остаток = т[м.end():]
        if not агент and not _ЯВНЫЙ_ПОИСК.match(остаток) and not _МЯГКИЙ_ПОИСК.match(остаток):
            остаток = т          # «Иванов, найди …» — обращение не к агенту: разбираем всё целиком
    за = _ЯВНЫЙ_ПОИСК.match(остаток)
    if not за:
        мягко = _МЯГКИЙ_ПОИСК.match(остаток)
        if мягко and _ПРИЗНАК_СЕТИ.search(мягко.group(1)) and not _СВОЁ.search(мягко.group(1)):
            за = мягко
    if за:
        запрос = _ПРЕДЛОГ_СЕТИ.sub("", за.group(1).strip(" .?!"))
        return (запрос.strip(" .?!") if len(запрос.strip()) >= 3 else за.group(1).strip(" .?!")), агент
    # Снабженцу можно просто назвать, что нужно: «цены на шины Хайлюкс?», «где купить фильтр»
    if агент == "снабженец" and _ПРИЗНАК_СЕТИ.search(остаток) and not _СВОЁ.search(остаток) and len(остаток.strip()) >= 6:
        return _ПРЕДЛОГ_СЕТИ.sub("", остаток.strip(" .?!")), агент
    return "", агент


def просят_поиск(текст: str) -> str:
    return разобрать_просьбу(текст)[0]


def _чистка(т: str) -> str:
    return " ".join(html.unescape(re.sub(r"<[^>]+>", "", т)).split())


def _скачать(адрес: str) -> str:
    з = urllib.request.Request(адрес, headers={"User-Agent": "Mozilla/5.0 (Windows NT 10.0; Win64; x64) Mizuyori",
                                               "Accept-Language": "ru,en;q=0.8"})
    return urllib.request.urlopen(з, timeout=12).read().decode("utf-8", "replace")


def _выдача_duckduckgo(запрос: str, получить) -> list[dict]:
    страница = получить("https://html.duckduckgo.com/html/?" + urllib.parse.urlencode({"q": запрос}))
    итог = []
    for блок in re.findall(r'<div class="result[^"]*results_links.*?(?=<div class="result[^"]*results_links|$)', страница, re.S):
        с = re.search(r'class="result__a"[^>]*href="([^"]+)"[^>]*>(.*?)</a>', блок, re.S)
        if not с:
            continue
        ссылка = html.unescape(с.group(1))
        if "uddg=" in ссылка:
            ссылка = urllib.parse.unquote(ссылка.split("uddg=", 1)[1].split("&", 1)[0])
        о = re.search(r'class="result__snippet"[^>]*>(.*?)</a>', блок, re.S)
        итог.append({"название": _чистка(с.group(2))[:140], "ссылка": ссылка, "кратко": _чистка(о.group(1))[:240] if о else ""})
    if not итог and re.search(r"anomaly|captcha|robot", страница, re.I):
        raise RuntimeError("DuckDuckGo просит проверку (капча)")
    return итог


def _ссылка_bing(ссылка: str) -> str:
    """Bing часто прячет адрес в redirect: …/ck/a?…&u=a1<base64>. Достаём настоящий."""
    ссылка = html.unescape(ссылка)
    if "bing.com/ck/a" in ссылка:
        u = urllib.parse.parse_qs(urllib.parse.urlparse(ссылка).query).get("u", [""])[0]
        if u.startswith("a1"):
            try:
                return base64.urlsafe_b64decode(u[2:] + "=" * (-len(u[2:]) % 4)).decode("utf-8", "replace")
            except ValueError:
                pass
    return ссылка


def _выдача_bing(запрос: str, получить) -> list[dict]:
    страница = получить("https://www.bing.com/search?" + urllib.parse.urlencode({"q": запрос, "setlang": "ru", "cc": "RU"}))
    итог = []
    for блок in re.findall(r'<li class="b_algo".*?(?=<li class="b_algo"|</ol>|$)', страница, re.S):
        с = re.search(r'<h2[^>]*>\s*<a[^>]*href="([^"]+)"[^>]*>(.*?)</a>', блок, re.S)
        if not с:
            continue
        о = re.search(r'<p[^>]*>(.*?)</p>', блок, re.S)
        итог.append({"название": _чистка(с.group(2))[:140], "ссылка": _ссылка_bing(с.group(1)),
                     "кратко": _чистка(о.group(1))[:240] if о else ""})
    return итог


ПОИСКОВИКИ = (("DuckDuckGo", _выдача_duckduckgo), ("Bing", _выдача_bing))


def искать(запрос: str, сколько: int = 5, получить=None) -> list[dict]:
    """Выдача из открытых поисковиков без ключей: сначала DuckDuckGo, не вышло или пусто — Bing.
    Если не ответил ни один — поднимается последняя ошибка сети."""
    получить = получить or _скачать
    последняя_ошибка = None
    ответили = False
    for имя, движок in ПОИСКОВИКИ:
        try:
            найдено = движок(запрос, получить)
        except Exception as ошибка:
            журнал.warning("Поиск через %s не удался: %s", имя, ошибка)
            последняя_ошибка = ошибка
            continue
        ответили = True
        if найдено:
            return найдено[:сколько]
    if not ответили and последняя_ошибка:
        raise последняя_ошибка
    return []


def найти_для_чата(запрос: str, агент: str = "снабженец", получить=None) -> tuple[str, str]:
    """(факты для ИИ, готовое сообщение). Без сети — честное «не дошёл»."""
    with agents.работа(агент, "сходил в интернет", запрос[:80]) as з:
        try:
            результаты = искать(запрос, получить=получить)
        except Exception as ошибка:
            журнал.warning("Поиск не удался: %s", ошибка)
            з["результат"] = "сеть недоступна"
            return ("Хозяин просил найти в интернете, но выйти в сеть не вышло. Скажи об этом одной фразой.",
                    "🦶 Не смог выйти в интернет (нет сети или поиск закрыт). Проверьте подключение.")
        з["результат"] = f"нашёл {len(результаты)}"
        з["польза"] = 2 if результаты else 0
    if not результаты:
        return ("Поиск в интернете ничего не дал. Скажи об этом одной фразой.", f"🦶 По запросу «{запрос}» ничего не нашёл.")
    строки = [f"- [{р['название']}]({р['ссылка']})" + (f" — {р['кратко']}" if р["кратко"] else "") for р in результаты]
    return (f"Агент сходил в интернет по запросу «{запрос}» и принёс ссылки. Скажи одной фразой.",
            f"🦶 Нашёл по запросу «{запрос}»:\n" + "\n".join(строки) + "\n\nЦены и условия проверьте на самих страницах.")
