def _выдача_duckduckgo(запрос: str, получить) -> list[dict]:
    страница = получить("https://html.duckduckgo.com/html/?" + urllib.parse.urlencode({"q": запрос}))
    итог = []
    for блок in re.findall(r'<div class="result[^"]*results_links.*?(?=<div class="result[^"]*results_links|$)', страница, re.S):
        с = re.search(r'class="result__a"[^>]*href="([^"]+)"[^>]*>(.*?)</a>', блок, re.S)
        if not с:
            continue
        ссылка = html.unescape(с.group(1))
        if "uddg=" in ссылка:
            ссылка = urllib.parse.unquote(ссылка.split("uddg=", 1)[1].split("&", 1)[0])
        о = re.search(r'class="result__snippet"[^>]*>(.*?)</a>', блок, re.S)
        итог.append({"название": _чистка(с.group(2))[:140], "ссылка": ссылка, "кратко": _чистка(о.group(1))[:240] if о else ""})
    if not итог and re.search(r"anomaly|captcha|robot", страница, re.I):
        raise RuntimeError("DuckDuckGo просит проверку (капча)")
    return итог


def _ссылка_bing(ссылка: str) -> str:
    """Bing часто прячет адрес в redirect: …/ck/a?…&u=a1<base64>. Достаём настоящий."""
    ссылка = html.unescape(ссылка)
    if "bing.com/ck/a" in ссылка:
        u = urllib.parse.parse_qs(urllib.parse.urlparse(ссылка).query).get("u", [""])[0]
        if u.startswith("a1"):
            try:
                return base64.urlsafe_b64decode(u[2:] + "=" * (-len(u[2:]) % 4)).decode("utf-8", "replace")
            except ValueError:
                pass
    return ссылка


def _выдача_bing(запрос: str, получить) -> list[dict]:
    страница = получить("https://www.bing.com/search?" + urllib.parse.urlencode({"q": запрос, "setlang": "ru", "cc": "RU"}))
    итог = []
    for блок in re.findall(r'<li class="b_algo".*?(?=<li class="b_algo"|</ol>|$)', страница, re.S):
        с = re.search(r'<h2[^>]*>\s*<a[^>]*href="([^"]+)"[^>]*>(.*?)</a>', блок, re.S)
        if not с:
            continue
        о = re.search(r'<p[^>]*>(.*?)</p>', блок, re.S)
        итог.append({"название": _чистка(с.group(2))[:140], "ссылка": _ссылка_bing(с.group(1)),
                     "кратко": _чистка(о.group(1))[:240] if о else ""})
    return итог


def _выдача_mojeek(запрос: str, получить) -> list[dict]:
    страница = получить("https://www.mojeek.com/search?" + urllib.parse.urlencode({"q": запрос}))
    итог = []
    for блок in re.findall(r'<li[^>]*>\s*<a class="ob"[^>]*>.*?(?=<li[^>]*>\s*<a class="ob"|</ul>|$)', страница, re.S):
        с = re.search(r'<a[^>]*class="title"[^>]*href="([^"]+)"[^>]*>(.*?)</a>', блок, re.S) or \
            re.search(r'<a[^>]*href="([^"]+)"[^>]*class="title"[^>]*>(.*?)</a>', блок, re.S)
        if not с:
            continue
        о = re.search(r'<p class="s"[^>]*>(.*?)</p>', блок, re.S)
        итог.append({"название": _чистка(с.group(2))[:140], "ссылка": html.unescape(с.group(1)),
                     "кратко": _чистка(о.group(1))[:240] if о else ""})
    return итог


ПОИСКОВИКИ = (("DuckDuckGo", _выдача_duckduckgo), ("Bing", _выдача_bing), ("Mojeek", _выдача_mojeek))

# Поисковик, который попросил капчу или отказал, на время откладывается: иначе каждый из шести запросов
# заново упирается в ту же капчу и тратит секунды.
ПАУЗА_ПОСЛЕ_ОТКАЗА = 600.0
_отказ_до: dict[str, float] = {}


def _порядок_поисковиков() -> list:
    сейчас = time.monotonic()
    свободные = [п for п in ПОИСКОВИКИ if _отказ_до.get(п[0], 0) <= сейчас]
    return свободные or list(ПОИСКОВИКИ)     # все в паузе — пробуем всё равно


ЖИЗНЬ_КЭША = 6 * 3600          # секунд: выдача и цены со страниц не устаревают за часы, а капчу провоцируют повторы


def _кэш_получить(ключ: str):
    база = agents._база
    if not база:
        return None
    try:
        with база.соединение() as связь:
            с = связь.execute("SELECT данные FROM поиск_кэш WHERE ключ = ? AND создано > ?", (ключ, time.time() - ЖИЗНЬ_КЭША)).fetchone()
        return json.loads(с[0]) if с else None
    except Exception:
        return None


def _кэш_записать(ключ: str, данные) -> None:
    база = agents._база
    if not база:
        return
    try:
        with база.соединение() as связь:
            связь.execute("INSERT OR REPLACE INTO поиск_кэш (ключ, данные, создано) VALUES (?, ?, ?)",
                          (ключ, json.dumps(данные, ensure_ascii=False), time.time()))
            связь.execute("DELETE FROM поиск_кэш WHERE создано < ?", (time.time() - 2 * ЖИЗНЬ_КЭША,))
    except Exception:
        журнал.exception("Не удалось записать кэш поиска")


def искать(запрос: str, сколько: int = 5, получить=None, кэш: bool = True) -> list[dict]:
    """Выдача из открытых поисковиков без ключей: DuckDuckGo → Bing → Mojeek. Не ответил или пусто — следующий.
    Поисковик с капчей откладывается на 10 минут. Если не ответил ни один — поднимается последняя ошибка сети.
    Непустая выдача кэшируется на несколько часов (только для настоящего поиска: с подставным `получить` кэш не трогаем)."""
    ключ_кэша = "поиск:" + " ".join(запрос.casefold().split())
    нужен_кэш = кэш and получить is None
    if нужен_кэш and (в_кэше := _кэш_получить(ключ_кэша)):
        return в_кэше[:сколько]
    получить = получить or _получатель()
    последняя_ошибка = None
    ответили = False
    for имя, движок in _порядок_поисковиков():
        try:
            найдено = движок(запрос, получить)
        except Exception as ошибка:
            if _отказ_до.get(имя, 0) <= time.monotonic():
                журнал.warning("Поиск через %s не удался: %s", имя, ошибка)
            _отказ_до[имя] = time.monotonic() + ПАУЗА_ПОСЛЕ_ОТКАЗА
            последняя_ошибка = ошибка
            continue
        ответили = True
        if найдено:
            if нужен_кэш:
                _кэш_записать(ключ_кэша, найдено)
            return найдено[:сколько]
    if not ответили and последняя_ошибка:
        raise последняя_ошибка
    return []


