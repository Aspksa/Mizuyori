def исправить_раскладку_артикула(запрос: str) -> str:
    """«vic с111» с русской «с» ищется плохо. Короткие артикулы (1–3 буквы + цифры, без пробела) целиком переводим
    на латиницу, но только если все буквы — двойники латинских. Обычные слова («шины 265») не трогаем."""
    def слово(м):
        w = м.group(0)
        латиница = w.translate(_ДВОЙНИКИ)
        return w if re.search(r"[А-Яа-яЁё]", латиница) else латиница
    return re.sub(r"(?<![\wА-Яа-яЁё])[A-Za-zА-Яа-я]{1,3}-?\d{2,5}[A-Za-zА-Яа-я]?(?![\wА-Яа-яЁё])", слово, запрос)


def ключ_артикула(текст: str) -> str:
    """Для сравнения «C-111», «c111» и «С 111» (русская С): без дефисов и пробелов, строчными, латиницей."""
    return re.sub(r"[\s\-]", "", текст).translate(_ДВОЙНИКИ).casefold()     # только для сравнения, на экран не идёт


def артикулы(запрос: str) -> list[str]:
    return [м.group(0).strip() for м in _АРТИКУЛ.finditer(исправить_раскладку_артикула(запрос))]


def уточнить_запрос(запрос: str, агент: str) -> str:
    """Снабженцу и Складу короткий артикул или «фильтр» без контекста поисковик понимает как что угодно (фильтр для воды!).
    Для таких запросов добавляем автомобильный контекст: отдел закупает для машин."""
    if агент not in ("снабженец", "склад"):
        return запрос
    запрос = исправить_раскладку_артикула(запрос)
    if _АВТО_КОНТЕКСТ.search(запрос):
        return запрос
    if _АРТИКУЛ.search(запрос):
        return f"{запрос} автозапчасти артикул"
    if re.search(r"фильтр", запрос, re.I) and not _ВОДА.search(запрос):
        return f"{запрос} автомобильный"
    return запрос


def это_закупка_техники(запрос: str, агент: str) -> bool:
    return агент in ("снабженец", "склад") and bool(_АВТО_КОНТЕКСТ.search(запрос) or _АРТИКУЛ.search(запрос) or re.search(r"фильтр", запрос, re.I))


def построить_запросы(запрос: str, агент: str, доп: list[str] | None = None) -> list[str]:
    """Для закупки техники — несколько заходов: общий, «по магазинам запчастей» (в т. ч. Фарпост), с артикулом в других
    написаниях и подсказки модели. Для остального — один обычный запрос."""
    основной = уточнить_запрос(запрос, агент)
    региональный = []
    if агент in ("снабженец", "склад") and not _РЕГИОН_В_ТЕКСТЕ.search(основной):
        региональный = [f"{основной} {ГЛАВНЫЙ_ГОРОД} {РЕГИОН}" + ("" if re.search(r"купить|цена|заказать", основной, re.I) else " купить")]
    if not это_закупка_техники(основной, агент):
        return [основной, *региональный]
    запросы = [основной, *региональный]
    магазины = МАГАЗИНЫ_ШИН if re.search(r"\bшин|покрышк|\bдиск|колес|колёс", основной, re.I) else МАГАЗИНЫ_ЗАПЧАСТЕЙ[:7]
    запросы.append(f"{основной} ({' OR '.join('site:' + м for м in магазины)})")
    for а in артикулы(основной)[:1]:
        цифры = re.search(r"\d", а)
        if цифры:
            без = re.sub(r"[\s\-]", "", а)
            с_дефисом = f"{без[:цифры.start()]}-{без[цифры.start():]}".upper() if цифры.start() else без
            for вариант in (с_дефисом, без):
                if вариант.casefold() != а.casefold() and вариант not in основной:
                    запросы.append(основной.replace(а, вариант))
                    break
    for д in (доп or [])[:2]:
        if д and д not in запросы:
            запросы.append(д)
    return запросы[:6]


def из_приморья(результат: dict) -> bool:
    """В названии, описании или адресе есть Приморье: Владивосток, Уссурийск, Находка и т. д."""
    return bool(_РЕГИОН_В_ТЕКСТЕ.search(f"{результат['название']} {результат['кратко']}")) or \
        any(м in результат["ссылка"].casefold() for м in _РЕГИОН_В_ССЫЛКЕ)


def _домен(ссылка: str) -> str:
    return urllib.parse.urlparse(ссылка).netloc.casefold().removeprefix("www.")


def цена_из_текста(текст: str) -> str:
    м = _ЦЕНА.search(текст or "")
    if not м:
        return ""
    число = re.sub(r"[\s ]", "", м.group(1))
    return f"{int(число):,}".replace(",", " ") + " ₽"


def цена_со_страницы(снимок: str, запрос: str) -> tuple[str, bool]:
    """(цена, точно ли). Точно — цена рядом со строкой, где есть артикул из запроса; иначе первая цена на странице."""
    строки = снимок.splitlines()
    ключи = [ключ_артикула(а) for а in артикулы(запрос) if ключ_артикула(а)]
    for и, строка in enumerate(строки):
        if ключи and any(к in ключ_артикула(строка) for к in ключи):
            for окно in строки[и:и + 5] + строки[max(0, и - 2):и]:      # цена обычно ниже названия, выше — крайний случай
                if (ц := цена_из_текста(окно)):
                    return ц, True
    for строка in строки:
        if re.search(r"доставк|скидк|от \d+ руб.*заказ", строка, re.I):
            continue
        if (ц := цена_из_текста(строка)):
            return ц, False
    return "", False


def добавить_цены(результаты: list[dict], запрос: str, снимок=None, сколько: int = 3) -> None:
    """Магазины запчастей без цены в выдаче: читаем их страницы (по структуре, через Chrome, если он включён) и достаём цену.
    Результат кэшируется. Меняет `результаты` на месте: р["цена"], р["цена_точно"]."""
    from concurrent.futures import ThreadPoolExecutor
    from . import page_snapshot
    снимок = снимок or page_snapshot.снимок
    цели = [р for р in результаты
            if not цена_из_текста(f"{р['название']} {р['кратко']}")
            and any(_домен(р["ссылка"]) == м or _домен(р["ссылка"]).endswith("." + м) for м in МАГАЗИНЫ_ЗАПЧАСТЕЙ)
            and page_snapshot.адрес_допустим(р["ссылка"])[0]][:сколько]
    if not цели:
        return

    def одна(р):
        ключ = "цена:" + р["ссылка"] + "|" + запрос.casefold()
        if (в_кэше := _кэш_получить(ключ)) is not None:
            return р, tuple(в_кэше)
        try:
            итог = цена_со_страницы(снимок(р["ссылка"]), запрос)
        except Exception as ошибка:
            журнал.info("Цену со страницы %s взять не вышло: %s", р["ссылка"], ошибка)
            return р, ("", False)
        _кэш_записать(ключ, list(итог))
        return р, итог
    with ThreadPoolExecutor(max_workers=len(цели)) as пул:
        for р, (цена, точно) in пул.map(одна, цели):
            if цена:
                р["цена"], р["цена_точно"] = цена, точно


def оценить(результат: dict, запрос: str) -> float:
    """Чем выше, тем лучше: магазин запчастей, в тексте есть артикул, видна цена; википедия и «ответы» — вниз."""
    д = _домен(результат["ссылка"])
    текст = f"{результат['название']} {результат['кратко']}"
    очки = 0.0
    if any(д == м or д.endswith("." + м) for м in МАГАЗИНЫ_ЗАПЧАСТЕЙ):
        очки += 3
    if any(м in д for м in _МУСОР):
        очки -= 3
    for а in артикулы(запрос):
        if ключ_артикула(а) and ключ_артикула(а) in ключ_артикула(текст):
            очки += 4
    if из_приморья(результат):
        очки += 6              # приоритет — Приморский край
    if цена_из_текста(текст):
        очки += 1.5
    if re.search(r"купить|цена|в наличии|заказать", текст, re.I):
        очки += 0.5
    if _АВТО_КОНТЕКСТ.search(запрос) and _ВОДА.search(текст) and not _ВОДА.search(запрос):
        очки -= 3
    return очки


def искать_для_закупки(запрос: str, агент: str, получить=None, доп_запросы: list[str] | None = None, сколько: int = 8, кэш: bool = True) -> tuple[list[dict], list[str]]:
    """(результаты, использованные запросы). Несколько запросов идут параллельно, выдача склеивается без повторов
    и сортируется по пользе. Если все запросы упали — поднимается ошибка сети."""
    запросы = построить_запросы(запрос, агент, доп_запросы)
    if len(запросы) == 1:
        return искать(запросы[0], сколько=сколько, получить=получить, кэш=кэш), запросы
    from concurrent.futures import ThreadPoolExecutor

    def один(з):
        try:
            return искать(з, сколько=8, получить=получить, кэш=кэш), None
        except Exception as ошибка:
            return [], ошибка
    with ThreadPoolExecutor(max_workers=len(запросы)) as пул:
        части = list(пул.map(один, запросы))
    if all(о for _, о in части):
        raise части[0][1]
    видели, склеено = set(), []
    for найдено, _ in части:
        for р in найдено:
            ключ = _домен(р["ссылка"]) + urllib.parse.urlparse(р["ссылка"]).path.rstrip("/")
            if ключ in видели:
                continue
            видели.add(ключ)
            склеено.append(р)
    основной = запросы[0]
    порядок = {id(р): i for i, р in enumerate(склеено)}
    склеено.sort(key=lambda р: (-оценить(р, основной), порядок[id(р)]))
    return склеено[:сколько], запросы


def _из_знаний_модели(запрос: str, настройки_ии: dict | None, причина: str, агент: str) -> tuple[str, str] | None:
    """Интернет не дал ответа — спрашиваем модель по ключу cloud.ru. Это НЕ свежие данные, и в сообщении так и сказано."""
    from . import ai
    if not настройки_ии or not ai.подключён(настройки_ии):
        return None
    try:
        with agents.работа(агент, "ответил из знаний модели", запрос[:80]) as з:
            текст = ai.справка_без_сети(запрос, настройки_ии)
            if not текст:
                return None
            з["результат"] = "интернета нет — ответ из знаний модели"
            з["польза"] = 1
    except Exception as ошибка:
        журнал.warning("Справка из знаний модели не вышла: %s", ошибка)
        return None
    return (f"Интернет не помог ({причина}); агент ответил из знаний модели, без свежих цен и ссылок. Скажи об этом одной фразой.",
            f"🧠 {причина[:1].upper() + причина[1:]}, поэтому отвечаю из знаний модели по вашему ключу. "
            f"Это ориентир, а не свежие данные: цены, наличие и ссылки не проверены.\n\n{текст}")


def найти_для_чата(запрос: str, агент: str = "снабженец", получить=None, настройки_ии: dict | None = None) -> tuple[str, str]:
    """(факты для ИИ, готовое сообщение). Нет сети или пусто — ответ из знаний модели по ключу (если ИИ подключён),
    иначе честное «не дошёл»."""
    причина = ""
    запрос_в_сеть = исправить_раскладку_артикула(уточнить_запрос(запрос, агент))
    с_уточнением = f" (искал: «{запрос_в_сеть}»)" if запрос_в_сеть != запрос else ""
    доп = []
    if настройки_ии and это_закупка_техники(запрос_в_сеть, агент):
        try:
            from . import ai
            if ai.подключён(настройки_ии):
                доп = ai.запросы_для_закупки(запрос_в_сеть, настройки_ии)
        except Exception as ошибка:           # подсказка модели — только бонус
            журнал.info("Модель не подсказала запросы: %s", ошибка)
    with agents.работа(агент, "сходил в интернет", запрос[:80]) as з:
        try:
            результаты, _ = искать_для_закупки(запрос_в_сеть, агент, получить=получить, доп_запросы=доп)
        except Exception as ошибка:
            журнал.warning("Поиск не удался: %s", ошибка)
            з["результат"] = "сеть недоступна"
            результаты = []
            причина = "поисковики недоступны"
        else:
            if результаты and получить is None:              # настоящий поиск: у магазинов без цены в выдаче берём цену со страницы
                try:
                    добавить_цены(результаты, запрос_в_сеть)
                except Exception:
                    журнал.exception("Цены со страниц не добавились")
            з["результат"] = f"нашёл {len(результаты)}"
            з["польза"] = 2 if результаты else 0
            if not результаты:
                причина = "в сети по запросу ничего не нашлось"
    if not результаты:
        запасной = _из_знаний_модели(запрос, настройки_ии, причина, агент)
        if запасной:
            return запасной
        if причина == "поисковики недоступны":
            return ("Хозяин просил найти в интернете, но выйти в сеть не вышло. Скажи об этом одной фразой.",
                    "🦶 Не смог выйти в интернет (нет сети или поиск закрыт). Проверьте подключение "
                    "или подключите ИИ cloud.ru в настройках — тогда отвечу хотя бы из знаний модели.")
        return ("Поиск в интернете ничего не дал. Скажи об этом одной фразой.", f"🦶 По запросу «{запрос}» ничего не нашёл.")
    def строка(р):
        цена = цена_из_текста(f"{р['название']} {р['кратко']}")
        if not цена and р.get("цена"):
            цена = р["цена"] + ("" if р.get("цена_точно") else " (по странице, проверьте)")
        магазин = any(_домен(р["ссылка"]) == м or _домен(р["ссылка"]).endswith("." + м) for м in МАГАЗИНЫ_ЗАПЧАСТЕЙ)
        метки = (["📍 Приморье"] if из_приморья(р) else []) + ([f"**{цена}**"] if цена else []) + (["магазин запчастей"] if магазин else [])
        return f"- [{р['название']}]({р['ссылка']})" + (f" — {' · '.join(метки)}" if метки else "") + (f" · {р['кратко']}" if р["кратко"] else "")
    строки = [строка(р) for р in результаты]
    return (f"Агент сходил в интернет по запросу «{запрос}» и принёс ссылки. Скажи одной фразой.",
            f"🦶 Нашёл по запросу «{запрос}»{с_уточнением}:\n" + "\n".join(строки) + "\n\n📍 Приоритет — Приморский край: местные предложения выше. Цены и условия проверьте на самих страницах. "
            "Не то нашлось — уточните марку машины или добавьте слово из названия детали.")
