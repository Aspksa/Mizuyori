"""Расход токенов по агентам и дням: видно, кто и что тратит, чтобы ограничить лишнее (чат, поручения или фон).

Каждый запрос к ИИ записывается на агента, который в этот момент «в работе» (agents.работа), а если такого нет — на «чат».
Потоковый чат сервер не считает, поэтому его расход — прикидка по длине текста (помечается).
"""

from __future__ import annotations

import logging
from datetime import date, timedelta

from . import agents, ai

журнал = logging.getLogger("mizuyori.расход")
_база = None


def подключить(база) -> None:
    global _база
    _база = база
    ai.при_расходе = записать


def записать(токенов: int, оценка: bool = False) -> None:
    if not _база or токенов <= 0:
        return
    агент = agents.текущий_агент() or "чат"
    с_ = date.today().isoformat()
    with _база.соединение() as связь:
        связь.execute(
            "INSERT INTO агент_расход (день, агент, приоритет, запросов, токенов, оценка) VALUES (?, ?, ?, 1, ?, ?) "
            "ON CONFLICT(день, агент, приоритет) DO UPDATE SET запросов = запросов + 1, токенов = токенов + excluded.токенов, "
            "оценка = оценка + excluded.оценка",
            (с_, агент, ai.приоритет(), токенов, токенов if оценка else 0))
        связь.execute("DELETE FROM агент_расход WHERE день < ?", ((date.today() - timedelta(days=120)).isoformat(),))


def отчёт(дней: int = 14) -> dict:
    с_ = (date.today() - timedelta(days=max(1, дней) - 1)).isoformat()
    with _база.соединение() as связь:
        строки = [dict(с) for с in связь.execute(
            "SELECT день, агент, приоритет, запросов, токенов, оценка FROM агент_расход WHERE день >= ?", (с_,)).fetchall()]
    по_агентам: dict[str, dict] = {}
    по_дням = {(date.today() - timedelta(days=и)).isoformat(): 0 for и in range(max(1, дней) - 1, -1, -1)}
    по_приоритетам = {"чат": 0, "поручение": 0, "фон": 0}
    for с in строки:
        а = по_агентам.setdefault(с["агент"], {"агент": с["агент"], "имя": agents.ИМЕНА.get(с["агент"], с["агент"]),
                                               "токенов": 0, "запросов": 0, "в_фоне": 0})
        а["токенов"] += с["токенов"]
        а["запросов"] += с["запросов"]
        if с["приоритет"] == "фон":
            а["в_фоне"] += с["токенов"]
        по_дням[с["день"]] = по_дням.get(с["день"], 0) + с["токенов"]
        по_приоритетам[с["приоритет"]] = по_приоритетам.get(с["приоритет"], 0) + с["токенов"]
    всего = sum(а["токенов"] for а in по_агентам.values())
    список = sorted(по_агентам.values(), key=lambda а: -а["токенов"])
    for а in список:
        а["доля"] = round(а["токенов"] / всего, 3) if всего else 0
    return {"дней": дней, "всего": всего, "по_агентам": список,
            "по_дням": [{"день": д, "токенов": т} for д, т in sorted(по_дням.items())], "по_приоритетам": по_приоритетам,
            "очередь": ai.состояние_очереди()}
