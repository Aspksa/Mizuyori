def разобрать_неудачи(ключ: str, н: dict) -> dict:
    """Агент (с помощью ИИ) смотрит на свои неудачи и предлагает правку. Возвращает {'предложение': {...}} или {'сообщение': str}."""
    if ключ not in agents.ИМЕНА:
        return {"сообщение": "Нет такого агента."}
    if not ai.подключён(н):
        return {"сообщение": "Нужен подключённый ИИ: добавьте ключ в настройках ИИ."}
    if any(п["статус"] == "ждёт" for п in предложения(ключ, 10)):
        return {"сообщение": "Сначала решите по предыдущему предложению."}
    with _база().соединение() as связь:
        провалы = [dict(с) for с in связь.execute(
            "SELECT описание, замечание, итог, попыток FROM агент_оценка WHERE агент = ? AND балл < 1 ORDER BY id DESC LIMIT 12", (ключ,)).fetchall()]
    if not провалы:
        return {"сообщение": "Неудач нет: все шаги проходили проверку с первого раза."}
    а = next((а for а in agents.АГЕНТЫ if а["ключ"] == ключ), {"имя": ключ, "что": ""})
    уже = [з["текст"] for з in agents.заметки(ключ) if з["вид"] in ("правило", "приём")] + [н_["название"] for н_ in agents.навыки(ключ)]
    with agents.работа(ключ, "разобрал свои неудачи", f"неудачных шагов: {len(провалы)}") as з:
        ответ = _спросить(agents.с_правилами(dict(н), ключ), _СИСТЕМА_НАСТАВНИКА.format(имя=а["имя"], что=а.get("что", "")),
                          {"неудачные_шаги": провалы, "уже_записано": уже, "профиль": agents.профиль(ключ)})
        р = _json(ответ)
        вид = (р or {}).get("вид") if isinstance(р, dict) else ""
        текст = " ".join(str((р or {}).get("текст") or "").split())
        if вид not in ("правило", "роль", "навык") or not текст:
            з["результат"] = "понятной причины не нашёл"
            return {"сообщение": "Единой понятной причины в неудачах не нашлось. Попробуйте позже, когда накопится больше шагов."}
        текст = текст[:600 if вид == "навык" else 250]
        проверка = проверить_урок(ключ, текст, н, вид)
        п = _сохранить_предложение(ключ, вид, текст, str(р.get("почему") or ""), проверка,
                                   str(р.get("название") or "")[:80], str(р.get("когда") or ""))
        з["результат"] = f"предложил {вид}: {текст[:80]}" + ("" if проверка["принять"] else " (не прошло проверку)")
        з["польза"] = 2
    audit.записать("агент предложил улучшение", agents.ИМЕНА[ключ], f"{вид}: {текст[:100]}", кто="агент")
    return {"предложение": п}


def принять_предложение(номер: int) -> dict | None:
    with _база().соединение() as связь:
        с = связь.execute("SELECT * FROM агент_предложение WHERE id = ?", (номер,)).fetchone()
    if not с or с["статус"] not in ("ждёт", "не_прошло_проверку"):
        return None
    ключ, вид, текст = с["агент"], с["вид"], с["текст"]
    до_id = _последняя_оценка_id(ключ)
    оценка_до = _средняя(ключ, до_id)
    if вид == "правило":
        agents.добавить_заметку(ключ, "правило", текст, "улучшение")
    elif вид == "роль":
        п = agents.профиль(ключ)
        agents.сохранить_профиль(ключ, {**п, "указания": f"{п['указания']} {текст}".strip()[:agents.ПРЕДЕЛ_ПОЛЯ]}, "улучшение: роль дополнена")
    else:
        agents.добавить_навык(ключ, с["название"] or текст[:40], с["когда"], текст, "улучшение: новый навык")
    версии = agents.версии(ключ)
    откат_к = версии[1]["id"] if len(версии) > 1 else None          # состояние агента до этого изменения
    with _база().соединение() as связь:
        связь.execute("UPDATE агент_предложение SET статус = 'принято', решено = datetime('now', 'localtime'), "
                      "после_id = ?, откат_к = ?, оценка_до = ? WHERE id = ?", (до_id, откат_к, оценка_до, номер))
    audit.записать("улучшение принято", agents.ИМЕНА.get(ключ, ключ), f"{вид}: {текст[:100]}")
    return _предложение(_получить(номер))


def отклонить_предложение(номер: int) -> dict | None:
    с = _получить(номер)
    if not с or с["статус"] not in ("ждёт", "не_прошло_проверку"):
        return None
    with _база().соединение() as связь:
        связь.execute("UPDATE агент_предложение SET статус = 'отклонено', решено = datetime('now', 'localtime') WHERE id = ?", (номер,))
    audit.записать("улучшение отклонено", agents.ИМЕНА.get(с["агент"], с["агент"]), f"{с['вид']}: {с['текст'][:100]}")
    return _предложение(_получить(номер))


def _получить(номер: int):
    with _база().соединение() as связь:
        return связь.execute("SELECT * FROM агент_предложение WHERE id = ?", (номер,)).fetchone()


# ---- Автооткат: после принятого улучшения оценка упала ---------------------------------------------

ПОРОГ_ПАДЕНИЯ = 0.15
МИН_ШАГОВ_ПОСЛЕ = 5
ШАГОВ_ДЛЯ_ВЫВОДА = 10


def _последняя_оценка_id(ключ: str) -> int:
    with _база().соединение() as связь:
        return связь.execute("SELECT COALESCE(MAX(id), 0) FROM агент_оценка WHERE агент = ?", (ключ,)).fetchone()[0]


def _средняя(ключ: str, до_id: int | None = None, после_id: int | None = None, сколько: int = 10) -> float | None:
    """Средний балл оценённых шагов: до метки (последние `сколько`) или после неё."""
    условие, параметры, порядок = "агент = ? AND (проверен = 1 OR итог != 'прошёл')", [ключ], "DESC"
    if после_id is not None:
        условие += " AND id > ?"
        параметры.append(после_id)
        порядок = "ASC"
    elif до_id is not None:
        условие += " AND id <= ?"
        параметры.append(до_id)
    with _база().соединение() as связь:
        строки = связь.execute(f"SELECT балл FROM агент_оценка WHERE {условие} ORDER BY id {порядок} LIMIT ?", (*параметры, сколько)).fetchall()
    return round(sum(с[0] for с in строки) / len(строки), 2) if len(строки) >= (МИН_ШАГОВ_ПОСЛЕ if после_id is not None else 3) else None


def проверить_откаты(ключ: str | None = None) -> list[dict]:
    """Принятые улучшения без вердикта: хватает новых оценок — сравниваем с тем, что было до. Упало заметно — предлагаем откат."""
    условие, параметры = "статус = 'принято' AND откат_статус = '' AND откат_к IS NOT NULL AND оценка_до IS NOT NULL", []
    if ключ:
        условие += " AND агент = ?"
        параметры.append(ключ)
    with _база().соединение() as связь:
        строки = связь.execute(f"SELECT id, агент, после_id, оценка_до FROM агент_предложение WHERE {условие}", параметры).fetchall()
    итог = []
    for с in строки:
        после = _средняя(с["агент"], после_id=с["после_id"], сколько=ШАГОВ_ДЛЯ_ВЫВОДА)
        if после is None:
            continue
        статус = "предложен" if после < с["оценка_до"] - ПОРОГ_ПАДЕНИЯ else ("оставлено" if _число_после(с["агент"], с["после_id"]) >= ШАГОВ_ДЛЯ_ВЫВОДА else "")
        if статус == "":
            continue
        with _база().соединение() as связь:
            связь.execute("UPDATE агент_предложение SET откат_статус = ?, оценка_после = ? WHERE id = ?", (статус, после, с["id"]))
        if статус == "предложен":
            audit.записать("после улучшения оценка агента упала", agents.ИМЕНА.get(с["агент"], с["агент"]),
                           f"{с['оценка_до']:.0%} → {после:.0%}: предложен откат", кто="агент")
            итог.append(_предложение(_получить(с["id"])))
    return итог


def _число_после(ключ: str, после_id: int) -> int:
    with _база().соединение() as связь:
        return связь.execute("SELECT COUNT(*) FROM агент_оценка WHERE агент = ? AND id > ? AND (проверен = 1 OR итог != 'прошёл')",
                             (ключ, после_id)).fetchone()[0]


def откатить_улучшение(номер: int) -> dict | None:
    с = _получить(номер)
    if not с or с["откат_статус"] != "предложен" or с["откат_к"] is None:
        return None
    итог = agents.откатить(с["откат_к"])
    if not итог:
        return None
    with _база().соединение() as связь:
        связь.execute("UPDATE агент_предложение SET откат_статус = 'выполнен' WHERE id = ?", (номер,))
    audit.записать("улучшение откачено", agents.ИМЕНА.get(с["агент"], с["агент"]), f"{с['вид']}: {с['текст'][:80]}; к версии {итог['к_версии']}")
    return {"предложение": _предложение(_получить(номер)), "агент": итог["агент"]}


def оставить_улучшение(номер: int) -> dict | None:
    с = _получить(номер)
    if not с or с["откат_статус"] != "предложен":
        return None
    with _база().соединение() as связь:
        связь.execute("UPDATE агент_предложение SET откат_статус = 'оставлено' WHERE id = ?", (номер,))
    audit.записать("улучшение оставлено, откат не нужен", agents.ИМЕНА.get(с["агент"], с["агент"]), с["текст"][:100])
    return _предложение(_получить(номер))


# ---- Ежедневный цикл ---------------------------------------------------------------------------------

def _пора() -> bool:
    """Раз в сутки: последняя запись «разбор неудач» в журнале старше 20 часов (переживает перезапуск)."""
    з = audit.список(1, "разбор неудач выполнен")
    if not з:
        return True
    from datetime import datetime
    try:
        когда = datetime.strptime(з[0]["создано"], "%Y-%m-%d %H:%M:%S")
    except ValueError:
        return True
    return (datetime.now() - когда).total_seconds() > ПАУЗА_РАЗБОРА_ЧАСОВ * 3600


def разбор_слабых(н: dict) -> list[dict]:
    """Один проход: слабые агенты без ждущих предложений разбирают неудачи. Здоровых не трогаем."""
    try:
        проверить_откаты()
    except Exception:
        журнал.exception("Проверка откатов")
    итог = []
    for ключ in слабые():
        if any(п["статус"] == "ждёт" for п in предложения(ключ, 10)):
            continue
        try:
            р = разобрать_неудачи(ключ, н)
        except Exception:
            журнал.exception("Разбор неудач агента %s не удался", ключ)
            continue
        if "предложение" in р:
            итог.append(р["предложение"])
    audit.записать("разбор неудач выполнен", "", f"слабых агентов: {len(слабые())}, предложений: {len(итог)}", кто="агент")
    return итог


_поток: threading.Thread | None = None


def запустить(получить_ии) -> None:
    global _поток
    if _поток and _поток.is_alive():
        return

    def цикл():
        from . import learning
        ai.установить_приоритет("фон")
        time.sleep(180)
        while True:
            try:
                н = dict(получить_ии())
                if learning.НАСТРОЙКИ.get("учиться_в_фоне") and ai.подключён(н) and _пора() and learning._можно_думать():
                    разбор_слабых(н)
            except Exception:
                журнал.exception("Ежедневный разбор неудач")
            time.sleep(1800)
    _поток = threading.Thread(target=цикл, name="mizuyori-evolve", daemon=True)
    _поток.start()
