"""Самоулучшение агентов в духе A-Evolve: решил → посмотрел → улучшил → проверил → принял/откатил.

1. Оценка шага: каждый шаг поручения получает балл (1 — с первого раза, 0.6 — со второго, 0.3 — принят вручную,
   0 — отклонён или ошибка), плюс секунды и токены. Это «награда» агента.
2. Проверка перед принятием: новый приём или правило прогоняется на прошлых удачных и неудачных случаях агента.
   Не хуже — принимается, хуже или противоречит записанному — отклоняется с причиной.
3. Раз в сутки агент с низкой средней оценкой разбирает свои неудачи и предлагает ОДНУ правку (правило, роль или навык).
   Предложение проходит проверку из п. 2 и ждёт вашего подтверждения. Без него ничего не меняется.
4. Улучшать стоит только слабых: порог — средняя оценка ниже 0.7 минимум на 5 проверенных шагах за 14 дней.
Каждое принятое изменение попадает в версии агента (agents.версии) и откатывается кнопкой.
"""

from __future__ import annotations

import json
import logging
import re
import threading
import time

from . import agents, ai, audit

журнал = logging.getLogger("mizuyori.улучшение")

ПОРОГ_СЛАБОГО = 0.7
МИН_ШАГОВ = 5
ДНЕЙ_ОКНО = 14
МИН_СЛУЧАЕВ_ДЛЯ_ПРОВЕРКИ = 4
ПАУЗА_РАЗБОРА_ЧАСОВ = 20

БАЛЛЫ = {"прошёл": 1.0, "принят_вручную": 0.3, "отклонён": 0.0, "ошибка": 0.0}


def _база():
    return agents._база


def _json(текст: str):
    м = re.search(r"\{.*\}", текст or "", re.S)
    if not м:
        return None
    try:
        return json.loads(м.group(0))
    except ValueError:
        return None


def _спросить(н: dict, система: str, данные: dict) -> str:
    from . import learning
    return learning._спросить(н, система, данные)


# ---- Оценка шага ---------------------------------------------------------------------------------

def записать_оценку(агент: str, поручение: int, шаг: int, описание: str, итог: str, попыток: int = 1,
                    проверен: bool = True, замечание: str = "", секунд: float = 0, токенов: int = 0) -> None:
    if not _база() or агент not in agents.ИМЕНА:
        return
    балл = БАЛЛЫ.get(итог, 0.0)
    if итог == "прошёл" and проверен and попыток > 1:
        балл = 0.6
    try:
        with _база().соединение() as связь:
            связь.execute(
                "INSERT INTO агент_оценка (агент, поручение, шаг, описание, балл, попыток, итог, проверен, замечание, секунд, токенов) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (агент, поручение, шаг, описание[:200], балл, попыток, итог, 1 if проверен else 0, замечание[:300], round(секунд, 1), токенов))
            связь.execute("DELETE FROM агент_оценка WHERE агент = ? AND id NOT IN "
                          "(SELECT id FROM агент_оценка WHERE агент = ? ORDER BY id DESC LIMIT 300)", (агент, агент))
    except Exception:
        журнал.exception("Не удалось записать оценку шага")


def качество(ключ: str, сколько: int = 30) -> dict:
    with _база().соединение() as связь:
        строки = связь.execute("SELECT балл, итог, попыток, проверен, замечание, описание, секунд, токенов, создано FROM агент_оценка "
                               "WHERE агент = ? ORDER BY id DESC LIMIT ?", (ключ, сколько)).fetchall()
    точки = [dict(с) for с in reversed(строки)]
    учтённые = [т for т in точки if т["проверен"] or т["итог"] != "прошёл"]
    средний = round(sum(т["балл"] for т in учтённые) / len(учтённые), 2) if учтённые else None
    слабый = средний is not None and len(учтённые) >= МИН_ШАГОВ and средний < ПОРОГ_СЛАБОГО
    return {"точки": точки, "средний": средний, "шагов": len(точки), "проверенных": len(учтённые),
            "секунд": round(sum(т["секунд"] for т in точки), 1), "токенов": sum(т["токенов"] for т in точки),
            "слабый": слабый, "порог": ПОРОГ_СЛАБОГО, "мин_шагов": МИН_ШАГОВ}


def слабые() -> list[str]:
    """Агенты, которым стоит помочь: стабильно низкая оценка за последние две недели."""
    итог = []
    with _база().соединение() as связь:
        ключи = [с[0] for с in связь.execute(
            "SELECT DISTINCT агент FROM агент_оценка WHERE создано >= datetime('now', 'localtime', ?)", (f"-{ДНЕЙ_ОКНО} days",)).fetchall()]
        for к in ключи:
            строки = связь.execute(
                "SELECT балл FROM агент_оценка WHERE агент = ? AND создано >= datetime('now', 'localtime', ?) AND (проверен = 1 OR итог != 'прошёл')",
                (к, f"-{ДНЕЙ_ОКНО} days")).fetchall()
            if len(строки) >= МИН_ШАГОВ and sum(с[0] for с in строки) / len(строки) < ПОРОГ_СЛАБОГО:
                итог.append(к)
    return итог


# ---- Проверка перед принятием -------------------------------------------------------------------

_СИСТЕМА_СУДЬИ = (
    "Ты проверяющий. Агент хочет добавить в свою память новое {вид}. Представь, что он следовал бы ему в прошлых случаях. "
    'Ответь ТОЛЬКО JSON: {{"не_хуже": true или false, "помогает": true или false, "почему": "одной фразой"}}. '
    "«не_хуже» = false, если новое противоречит тому, что сработало в удачных случаях, или противоречит уже записанному. "
    "«помогает» = true, если оно исправило бы неудачные случаи."
)


def _случаи(ключ: str) -> tuple[list[dict], list[dict]]:
    удачные, неудачные = [], []
    for з in agents.история(ключ, "", 60):
        к = {"действие": з["действие"], "почему": з["почему"], "результат": з["результат"][:160]}
        (удачные if з["успех"] and з["польза"] else неудачные if not з["успех"] else []).append(к)
    with _база().соединение() as связь:
        for с in связь.execute("SELECT описание, замечание, итог FROM агент_оценка WHERE агент = ? AND балл < 1 ORDER BY id DESC LIMIT 12", (ключ,)).fetchall():
            неудачные.append({"шаг": с["описание"], "замечание_проверяющего": с["замечание"], "чем_кончилось": с["итог"]})
        for с in связь.execute("SELECT описание FROM агент_оценка WHERE агент = ? AND балл = 1 AND проверен = 1 ORDER BY id DESC LIMIT 6", (ключ,)).fetchall():
            удачные.append({"шаг": с["описание"], "чем_кончилось": "прошёл проверку с первого раза"})
    return удачные[:8], неудачные[:8]


def проверить_урок(ключ: str, текст: str, н: dict, вид: str = "правило") -> dict:
    """{'принять': bool, 'проверено': bool, 'не_хуже': …, 'помогает': …, 'почему': str, 'случаев': int}.
    Мало истории или нет ИИ — проверить нечем, и урок принимается как раньше (учёба не должна встать)."""
    удачные, неудачные = _случаи(ключ)
    случаев = len(удачные) + len(неудачные)
    если_нечем = {"принять": True, "проверено": False, "не_хуже": None, "помогает": None, "случаев": случаев}
    if случаев < МИН_СЛУЧАЕВ_ДЛЯ_ПРОВЕРКИ:
        return {**если_нечем, "почему": "мало истории для проверки"}
    if not ai.подключён(н):
        return {**если_нечем, "почему": "ИИ не подключён"}
    уже = [з["текст"] for з in agents.заметки(ключ) if з["вид"] in ("правило", "приём")]
    try:
        ответ = _спросить(н, _СИСТЕМА_СУДЬИ.format(вид=вид),
                          {"новое": текст, "уже_записано": уже, "удачные_случаи": удачные, "неудачные_случаи": неудачные})
    except Exception:
        журнал.warning("Проверка урока не удалась, принимаю без неё")
        return {**если_нечем, "почему": "проверка не удалась"}
    р = _json(ответ)
    if not isinstance(р, dict) or "не_хуже" not in р:
        return {**если_нечем, "почему": "проверяющий ответил не по форме"}
    не_хуже = bool(р["не_хуже"])
    return {"принять": не_хуже, "проверено": True, "не_хуже": не_хуже, "помогает": bool(р.get("помогает")),
            "почему": str(р.get("почему") or "")[:200], "случаев": случаев}


# ---- Предложения ----------------------------------------------------------------------------------

def _предложение(с) -> dict:
    з = dict(с)
    з["проверка"] = json.loads(з["проверка"] or "{}")
    з["имя"] = agents.ИМЕНА.get(з["агент"], з["агент"])
    return з


def предложения(ключ: str | None = None, сколько: int = 30) -> list[dict]:
    with _база().соединение() as связь:
        if ключ:
            строки = связь.execute("SELECT * FROM агент_предложение WHERE агент = ? ORDER BY id DESC LIMIT ?", (ключ, сколько)).fetchall()
        else:
            строки = связь.execute("SELECT * FROM агент_предложение ORDER BY id DESC LIMIT ?", (сколько,)).fetchall()
    return [_предложение(с) for с in строки]


def _сохранить_предложение(ключ: str, вид: str, текст: str, почему: str, проверка: dict, название: str = "", когда: str = "") -> dict:
    статус = "ждёт" if проверка.get("принять", True) else "не_прошло_проверку"
    with _база().соединение() as связь:
        номер = связь.execute(
            "INSERT INTO агент_предложение (агент, вид, название, когда, текст, почему, проверка, статус) VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
            (ключ, вид, название[:80], когда[:200], текст, почему[:300], json.dumps(проверка, ensure_ascii=False), статус)).lastrowid
        связь.execute("DELETE FROM агент_предложение WHERE агент = ? AND id NOT IN "
                      "(SELECT id FROM агент_предложение WHERE агент = ? ORDER BY id DESC LIMIT 40)", (ключ, ключ))
        с = связь.execute("SELECT * FROM агент_предложение WHERE id = ?", (номер,)).fetchone()
    return _предложение(с)


def отклонённый_урок(ключ: str, текст: str, проверка: dict) -> None:
    """Учёба хотела записать приём, но он не прошёл проверку: сохраняем, чтобы вы видели причину и могли принять вручную."""
    _сохранить_предложение(ключ, "правило", текст, "приём из фоновой учёбы", проверка)


