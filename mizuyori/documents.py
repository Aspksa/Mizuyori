"""Документы по подтверждённой смете: служебная записка, дефектовая ведомость, договор или счёт-оферта.

Работают агенты: Делопроизводитель подбирает бланки (свои из «шаблоны/документы» или встроенные),
Старший инженер пишет служебную записку, Механик — дефектовую ведомость, Юрист — договор или счёт-оферту.
Всё — черновики для проверки человеком; чего нет в смете, помечено «[не указано]»."""

import logging
import re
from datetime import date
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

from . import agents
from .paths import ПАПКА_ДАННЫХ, КОРЕНЬ

журнал = logging.getLogger("mizuyori.документы")

ПАПКА_ДОКУМЕНТОВ = ПАПКА_ДАННЫХ / "документы"
ПАПКА_ШАБЛОНОВ = КОРЕНЬ / "шаблоны" / "документы"
НАСТРОЙКИ: dict = {"договор_от_рублей": 100000}
НЕТ = "[не указано]"


def _деньги(з) -> str:
    return НЕТ if з is None else f"{з:,.2f}".replace(",", " ").replace(".", ",")


def _число(з) -> str:
    return "" if з is None else f"{з:g}"


def _дата(з) -> str:
    м = re.fullmatch(r"(\d{4})-(\d{2})-(\d{2})", str(з or ""))
    return f"{м.group(3)}.{м.group(2)}.{м.group(1)}" if м else (з or НЕТ)


def итог_сметы(с: dict):
    return с["итого"] if с.get("итого") is not None else с.get("посчитано")


def _значения(с: dict, доп: dict | None = None) -> dict:
    ндс = {"включён": "в том числе НДС", "сверху": "НДС начисляется сверху", "нет": "НДС не облагается"}.get(с.get("ндс") or "", НЕТ)
    ключи = {"объект": с.get("объект") or НЕТ, "исполнитель": с.get("исполнитель") or НЕТ, "заказчик": с.get("заказчик") or НЕТ,
             "номер": с.get("номер") or НЕТ, "дата": _дата(с.get("дата")), "итого": _деньги(итог_сметы(с)) + " руб.",
             "ндс": ндс, "сегодня": f"{date.today():%d.%m.%Y}"}
    ключи.update(доп or {})
    return ключи


# ---- Общие кирпичики Word ------------------------------------------------------------------------

def _новый() -> Document:
    д = Document()
    стиль = д.styles["Normal"]
    стиль.font.name = "Times New Roman"
    стиль.font.size = Pt(12)
    р = д.sections[0]
    р.page_width, р.page_height = Cm(21), Cm(29.7)
    р.left_margin = р.right_margin = Cm(2)
    return д


def _заголовок(д, текст: str):
    п = д.add_paragraph()
    п.alignment = WD_ALIGN_PARAGRAPH.CENTER
    п.add_run(текст).bold = True
    return п


def _таблица_позиций(д, позиции: list[dict], с_видом: bool = True):
    заголовки = ["№", "Наименование"] + (["Вид"] if с_видом else []) + ["Ед.", "Кол-во", "Цена, руб.", "Сумма, руб."]
    т = д.add_table(rows=1, cols=len(заголовки))
    т.style = "Table Grid"
    т.autofit = False
    ширины = [0.9, 5.6, 2.3, 1.5, 1.5, 2.6, 2.6] if с_видом else [0.9, 8.2, 1.3, 1.5, 2.5, 2.6]
    for я, з in zip(т.rows[0].cells, заголовки):
        я.text = ""
        я.paragraphs[0].add_run(з).bold = True
    def подогнать(строка):
        for я, ш in zip(строка.cells, ширины):
            я.width = Cm(ш)

    for к, ш in zip(т.columns, ширины):
        к.width = Cm(ш)
    подогнать(т.rows[0])
    for i, п in enumerate(позиции, 1):
        значения = [str(i), п["название"]] + ([п["вид"]] if с_видом else []) + [
            п["ед"], _число(п["кол"]), _деньги(п["цена"]) if п["цена"] is not None else "", _деньги(п["сумма"]) if п["сумма"] is not None else ""]
        строка = т.add_row()
        for я, з in zip(строка.cells, значения):
            я.text = з
        подогнать(строка)
    return т


def _подписи(д, *люди: str):
    д.add_paragraph()
    for л in люди:
        д.add_paragraph(f"{л}  ____________________  /____________________/")


# ---- Свои образцы с метками {{…}} ------------------------------------------------------------------

def _шаблон(имя: str) -> Path | None:
    п = ПАПКА_ШАБЛОНОВ / f"{имя}.docx"
    return п if п.is_file() else None


def _из_образца(путь: Path, значения: dict, позиции: list[dict]) -> Document:
    д = Document(путь)

    def заменить(п):
        if "{{" not in п.text:
            return
        текст = re.sub(r"\{\{\s*([^}]+?)\s*\}\}", lambda м: str(значения.get(м.group(1), НЕТ)), п.text)
        for i, р in enumerate(п.runs):
            р.text = текст if i == 0 else ""
        if not п.runs:
            п.add_run(текст)

    метка = None
    for п in list(д.paragraphs):
        if re.fullmatch(r"\s*\{\{\s*таблица\s*\}\}\s*", п.text):
            метка = п
        else:
            заменить(п)
    for т in д.tables:
        for строка in т.rows:
            for я in строка.cells:
                for п in я.paragraphs:
                    заменить(п)
    if метка is not None:
        новая = _таблица_позиций(д, позиции)         # создаётся в конце документа — переносим на место метки
        метка._p.addnext(новая._tbl)
        метка._p.getparent().remove(метка._p)
    return д


def _сохранить(д, имя: str) -> Path:
    ПАПКА_ДОКУМЕНТОВ.mkdir(parents=True, exist_ok=True)
    путь = ПАПКА_ДОКУМЕНТОВ / (re.sub(r"\s+", " ", re.sub(r"[^\w .-]+", " ", имя)).strip() + ".docx")
    д.save(путь)
    return путь


# ---- Встроенные бланки ---------------------------------------------------------------------------------

def дефектовая_ведомость(с: dict) -> Document:
    значения = _значения(с)
    if (о := _шаблон("дефектовая_ведомость")):
        return _из_образца(о, значения, с["позиции"])
    д = _новый()
    _заголовок(д, "ДЕФЕКТОВАЯ ВЕДОМОСТЬ")
    д.add_paragraph(f"на ремонт: {значения['объект']}")
    д.add_paragraph(f"по смете № {значения['номер']} от {значения['дата']} ({значения['исполнитель']})")
    д.add_paragraph(f"Составлена: {значения['сегодня']}")
    д.add_paragraph()
    _таблица_позиций(д, с["позиции"])
    д.add_paragraph()
    д.add_paragraph(f"Итого по смете: {значения['итого']} ({значения['ндс']})")
    д.add_paragraph("Описание неисправностей и результаты осмотра (заполняется по факту дефектовки): "
                    "______________________________________________________________")
    _подписи(д, "Механик по выпуску", "Водитель", "Главный механик")
    return д


def служебная_записка(с: dict, тема: str, текст: str, номер: str, кому: str, от_кого: str) -> Document:
    значения = _значения(с, {"тема": тема, "текст": текст})
    if (о := _шаблон("служебная_записка")):
        return _из_образца(о, значения, с["позиции"])
    д = _новый()
    _заголовок(д, f"СЛУЖЕБНАЯ ЗАПИСКА № {номер}")
    д.add_paragraph(f"от {значения['сегодня']}")
    д.add_paragraph(f"Кому: {кому or '____________________'}")
    д.add_paragraph(f"От кого: {от_кого or '____________________'}")
    д.add_paragraph(f"Тема: {тема}")
    д.add_paragraph()
    for абзац in текст.split("\n"):
        if абзац.strip():
            д.add_paragraph(абзац.strip())
    д.add_paragraph(f"Приложение: смета № {значения['номер']} от {значения['дата']} на {значения['итого']}.")
    _подписи(д, "Старший инженер")
    return д


def договор_или_оферта(с: dict, договор: bool) -> Document:
    значения = _значения(с)
    имя = "договор" if договор else "счёт_оферта"
    if (о := _шаблон(имя)):
        return _из_образца(о, значения, с["позиции"])
    д = _новый()
    п_ = "[заполнить]"
    if договор:
        _заголовок(д, "ДОГОВОР НА ВЫПОЛНЕНИЕ РЕМОНТНЫХ РАБОТ")
        д.add_paragraph("ЧЕРНОВИК. Составлен автоматически по смете, требует проверки юристом.").runs[0].italic = True
        д.add_paragraph(f"г. {НАСТРОЙКИ.get('главный_город', 'Владивосток')}                                                  {значения['сегодня']}")
        д.add_paragraph(f"{значения['заказчик']} (далее — Заказчик) и {значения['исполнитель']} (далее — Исполнитель) "
                        "заключили настоящий договор о нижеследующем:")
        д.add_paragraph("1. Предмет договора").runs[0].bold = True
        д.add_paragraph(f"1.1. Исполнитель обязуется выполнить ремонт: {значения['объект']}, а Заказчик — принять и оплатить работы.")
        д.add_paragraph(f"1.2. Перечень работ и материалов — в смете № {значения['номер']} от {значения['дата']} (приложение 1):")
        _таблица_позиций(д, с["позиции"])
        д.add_paragraph("2. Цена и порядок расчётов").runs[0].bold = True
        д.add_paragraph(f"2.1. Цена договора — {значения['итого']} ({значения['ндс']}).")
        д.add_paragraph(f"2.2. Порядок оплаты: {п_}.")
        д.add_paragraph("3. Сроки").runs[0].bold = True
        д.add_paragraph(f"3.1. Начало работ: {п_}. Окончание работ: {п_}.")
        д.add_paragraph("4. Гарантия и ответственность").runs[0].bold = True
        д.add_paragraph(f"4.1. Гарантийный срок на выполненные работы: {п_} мес. 4.2. Ответственность сторон: {п_}.")
        д.add_paragraph("5. Реквизиты и подписи сторон").runs[0].bold = True
        д.add_paragraph(f"Заказчик: {значения['заказчик']}, реквизиты: {п_}")
        д.add_paragraph(f"Исполнитель: {значения['исполнитель']}, реквизиты: {п_}")
        _подписи(д, "Заказчик", "Исполнитель")
    else:
        _заголовок(д, f"СЧЁТ-ОФЕРТА № {значения['номер']} от {значения['дата']}")
        д.add_paragraph("ЧЕРНОВИК. Составлен автоматически по смете, требует проверки юристом.").runs[0].italic = True
        д.add_paragraph(f"Исполнитель: {значения['исполнитель']}")
        д.add_paragraph(f"Заказчик: {значения['заказчик']}")
        д.add_paragraph(f"Предмет: ремонт {значения['объект']}.")
        _таблица_позиций(д, с["позиции"])
        д.add_paragraph()
        д.add_paragraph(f"Итого к оплате: {значения['итого']} ({значения['ндс']}).")
        д.add_paragraph(f"Условия: оплата в течение {п_} дней; срок выполнения {п_}; гарантия {п_} мес. "
                        "Оплата настоящего счёта означает акцепт условий оферты.")
        _подписи(д, "Исполнитель")
    return д


# ---- Цепочка агентов -------------------------------------------------------------------------------------

def собрать(база, настройки_ии: dict, с: dict) -> dict:
    """Все документы по подтверждённой смете. Возвращает {'документы': [{'агент','название','файл'}], 'предупреждения': []}."""
    from . import work_agents
    метка = f"Смета № {с.get('номер') or с['id']}"
    имя_файла = f"Смета {с.get('номер') or с['id']}"
    сумма = итог_сметы(с)
    договор = сумма is not None and сумма >= int(НАСТРОЙКИ.get("договор_от_рублей", 100000))
    свои = {"служебная_записка": _шаблон("служебная_записка"), "дефектовая_ведомость": _шаблон("дефектовая_ведомость"),
            "договор" if договор else "счёт_оферта": _шаблон("договор" if договор else "счёт_оферта")}
    документы, предупреждения = [], []

    with agents.работа("делопроизводитель", "подбираю бланки", метка) as з:
        описание = "; ".join(f"{к.replace('_', ' ')} — {'ваш образец' if п else 'встроенный бланк'}" for к, п in свои.items())
        з["результат"] = описание
        з["польза"] = 2
    for кому, ключ_бланка, текст in (("инженер", "служебная_записка", "бланк служебной записки"),
                                     ("механик", "дефектовая_ведомость", "бланк дефектовой ведомости"),
                                     ("юрист", "договор" if договор else "счёт_оферта",
                                      "бланк договора" if договор else "бланк счёта-оферты")):
        agents.написать("делопроизводитель", кому, f"{метка}: {текст} готов — {'ваш образец' if свои[ключ_бланка] else 'встроенный'}.")

    def сделать(агент: str, действие: str, название: str, построить):
        with agents.работа(агент, действие, метка) as з:
            try:
                файл = _сохранить(построить(), f"{имя_файла} - {название}")
                з["результат"] = название
                з["польза"] = 3
                документы.append({"агент": агент, "название": название, "файл": файл.name})
                agents.написать(агент, "делопроизводитель", f"{метка}: {название} готов(а), лежит в чате.")
            except Exception as ошибка:
                журнал.exception("Не получилось: %s", название)
                предупреждения.append(f"{название}: {ошибка}")
                raise

    def записка():
        тема = f"О проведении ремонта: {с.get('объект') or 'автомобиль'}"
        пояснение = (f"Прошу согласовать ремонт «{с.get('объект') or НЕТ}» силами {с.get('исполнитель') or НЕТ}. "
                     f"Смета № {с.get('номер') or НЕТ} на сумму {_деньги(сумма)} руб.; работ: "
                     f"{sum(1 for п in с['позиции'] if п['вид'] == 'работа')}, материалов: "
                     f"{sum(1 for п in с['позиции'] if п['вид'] == 'материал')}.")
        з = work_agents.написать_записку(база, настройки_ии, тема, пояснение, "", "")
        return служебная_записка(с, з["тема"], з["текст"], з["номер"], з["кому"], з["от_кого"])

    for агент, действие, название, построить in (
            ("инженер", "пишу служебную записку по смете", "Служебная записка", записка),
            ("механик", "составляю дефектовую ведомость", "Дефектовая ведомость", lambda: дефектовая_ведомость(с)),
            ("юрист", "готовлю договор" if договор else "готовлю счёт-оферту", "Договор" if договор else "Счёт-оферта",
             lambda: договор_или_оферта(с, договор))):
        try:
            сделать(агент, действие, название, построить)
        except Exception:
            pass
    return {"документы": документы, "предупреждения": предупреждения, "договор": договор}
