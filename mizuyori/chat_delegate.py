"""Передача просьб из чата агентам.
Чат сам ничего не запускает. Если хозяин просит что-то сделать, здесь определяется исполнитель и создаётся
настоящее поручение (шаги, проверка, оценка). Безопасное запускается сразу, рискованное — после «да».
Когда поручение остановится, итог приходит в чат отдельным сообщением."""
from __future__ import annotations

import logging
import re
import threading
import time

from . import agents, ai, audit, missions, tools

журнал = logging.getLogger("mizuyori.передача")

НАСТРОЙКИ: dict = {"поручения_из_чата": "авто"}      # авто | всегда_спрашивать | выкл
ЖДАТЬ_ОТВЕТА_СЕК = 30 * 60
НЕ_ИСПОЛНИТЕЛИ = ("смысл", "чат", "память", "сводка", "мнения")
КЛЮЧ_СОСТОЯНИЯ = "чат_поручения"

_база = None
_замок = threading.Lock()
_ждёт: dict | None = None            # решение, ждущее «да» / «нет»: {"решение": {...}, "создан": время}
_решения_хозяина: list[int] = []     # поручения, которые ждут «да» / «нет» от хозяина

# Сообщение похоже на просьбу что-то сделать: только тогда тратим вызов ИИ на разбор
_ПРОСЬБА = re.compile(
    r"пуска[йю]|пусть|передай|поручи|попроси|спроси|запроси|узна[йт]|узгать|выясни|найд[иь]|найти|поищи|посмотр|псомтр|проверь|проверить|"
    r"посчитай|подсчитай|составь|подготов|сделай|напиши|сверь|разберись|займись|закажи|подбери|сравни|"
    r"\bнужно\b|\bнадо\b|\bнада\b|\bпрошу\b|\bможешь\b|\bпомоги\b|хочу, чтобы|хочу чтобы", re.I)
_ДА = re.compile(r"^\s*(да|ок|окей|давай|запускай|запускаю|делай|подтверждаю|верно|да, запускай|да запускай|ага|угу)[.! ]*$", re.I)
_НЕТ = re.compile(r"^\s*(нет|не надо|не нужно|отмена|отмени(ть)?|стоп|не запускай)[.! ]*$", re.I)
# Обещание от чата без дела: «передала», «запущу», «сообщу, когда ответит»
_ОБЕЩАНИЕ = re.compile(r"\b(?:передал[аи]?|передам|переда[юё]т?|запущу|запустил[аи]?|поручил[аи]?|поручу|отправил[аи]? (?:запрос|заявку)|"
                       r"сообщу,? (?:как|когда)|скажу,? (?:как|когда)|как (?:ответит|принесёт|принесет|найдёт|найдет)|добавил[аи]? в заявку|добавлю в заявку)\b", re.I)


def подключить(база) -> None:
    global _база
    _база = база
    if _при_остановке not in missions.ПРИ_ОСТАНОВКЕ:
        missions.ПРИ_ОСТАНОВКЕ.append(_при_остановке)


def ложное_обещание(ответ: str) -> bool:
    return bool(_ОБЕЩАНИЕ.search(ответ or ""))


ПРИМЕЧАНИЕ_БЕЗ_ДЕЛА = ("\n\n⚠ Это слова, а не запуск: ничего не передано и не начато. Скажите, что сделать, например «найди …» "
                       "или «пускай снабженец найдёт цену на …», или опишите поручение в окне «Поручения».")


def _имя(ключ: str) -> str:
    return agents.ИМЕНА.get(ключ, ключ)


# ---- Какие поручения принадлежат чату ------------------------------------------------------------

def _мои() -> list[int]:
    try:
        return [int(и) for и in _база.прочитать(КЛЮЧ_СОСТОЯНИЯ, [])]
    except Exception:
        return []


def _запомнить(номер: int) -> None:
    с = _мои()
    if номер not in с:
        _база.записать(КЛЮЧ_СОСТОЯНИЯ, (с + [номер])[-50:])


def _забыть(номер: int) -> None:
    _база.записать(КЛЮЧ_СОСТОЯНИЯ, [и for и in _мои() if и != номер])


# ---- Разбор просьбы ------------------------------------------------------------------------------

def похоже_на_просьбу(текст: str, адресовано: str | None = None) -> bool:
    низ = " ".join(текст.lower().replace("ё", "е").split())
    if len(низ) < 6:
        return False
    if адресовано or _ПРОСЬБА.search(низ):
        return True
    return any(а[:6] in низ for а in ("снабженец", "бухгалтер", "экономист", "юрист", "механик", "диспетчер"))


def _исполнители() -> list[dict]:
    return [{"ключ": ключ, "имя": имя, "умеет": next((а.get("что", "") for а in agents.АГЕНТЫ if а["ключ"] == ключ), "")}
            for ключ, имя in agents.ИМЕНА.items() if ключ not in НЕ_ИСПОЛНИТЕЛИ]


_СИСТЕМА_РАЗБОРА = (
    "Ты разбираешь реплику хозяина отдела главного механика: просит ли он СДЕЛАТЬ что-то кому-то из агентов (поручение) "
    "или это вопрос, разговор, мнение, объяснение. Поручение — когда нужно действие: найти, проверить, посчитать, "
    "подготовить документ, составить записку, свериться с данными. Вопросы «почему», «как работает», болтовня, "
    "благодарность и жалобы — не поручение. Если не уверен — false. "
    "Если реплика короткая («пускай посмотрит», «да, найди»), предмет возьми из прошлых реплик. "
    "Исполнителя выбирай только из списка. Если хозяин назвал агента — бери его. Инструмент «поиск» — интернет "
    "(только для тех, кому он разрешён), «замечания» — данные приложения, «страница» — прочитать указанный адрес. "
    "Для остального оставь инструмент пустым. Не придумывай фактов: в описание — только то, что сказал хозяин. "
    'Ответь ТОЛЬКО JSON: {"поручение": true|false, "агент": "ключ", "название": "до 80 знаков", '
    '"описание": "что сделать, самодостаточно: с предметом, артикулом, машиной", "ожидание": "что считать готовым", '
    '"инструмент": "поиск|замечания|страница|"}.')


def определить(текст: str, прошлые: list[str], н: dict, адресовано: str | None = None) -> dict | None:
    """Решение вида {"агент", "название", "описание", "ожидание", "инструмент"} или None, если это не просьба."""
    исполнители = _исполнители()
    допустимые = {и["ключ"] for и in исполнители}
    данные = {"реплика": текст, "прошлые_реплики": прошлые[-6:], "исполнители": исполнители,
              "инструменты": [{"имя": и["имя"], "что": и["что"]} for и in tools.список() if и["имя"] in ("поиск", "замечания", "страница")],
              "обратился_к": адресовано or ""}
    try:
        with ai.измерять():
            ответ = ai._задание(_СИСТЕМА_РАЗБОРА, данные, dict(н), 500)
    except Exception:
        журнал.warning("Разбор просьбы не удался", exc_info=True)
        return None
    разбор = missions._json_из_текста(ответ)
    if not isinstance(разбор, dict) or разбор.get("поручение") is not True:
        return None
    агент = str(разбор.get("агент") or "")
    описание = " ".join(str(разбор.get("описание") or "").split())[:1000]
    if агент not in допустимые or len(описание) < 5:
        return None
    инструмент = str(разбор.get("инструмент") or "")
    if инструмент and (инструмент not in tools.ИНСТРУМЕНТЫ or not tools.разрешён(инструмент, агент)[0]):
        инструмент = ""
    if инструмент == "страница" and not re.search(r"https?://", описание):
        инструмент = ""
    return {"агент": агент, "инструмент": инструмент, "описание": описание,
            "название": " ".join(str(разбор.get("название") or описание).split())[:80],
            "ожидание": " ".join(str(разбор.get("ожидание") or "").split())[:300]}


def _нужно_спросить(решение: dict) -> bool:
    режим = НАСТРОЙКИ.get("поручения_из_чата", "авто")
    return режим == "всегда_спрашивать" or tools.рискованный(решение["инструмент"])


def _описание(решение: dict) -> str:
    инструмент = f" (инструмент: {решение['инструмент']})" if решение["инструмент"] else ""
    ожидание = f"\nГотовым считаю: {решение['ожидание']}" if решение["ожидание"] else ""
    return f"Понял так: {_имя(решение['агент'])} — {решение['описание']}{инструмент}.{ожидание}"


def _запустить(решение: dict, н: dict) -> str:
    """Создаёт и запускает поручение. Возвращает сообщение для чата."""
    шаг = {"агент": решение["агент"], "описание": решение["описание"], "ожидание": решение["ожидание"],
           "инструмент": решение["инструмент"], "подтверждать": False}
    try:
        м = missions.создать(решение["название"], [шаг])
        _запомнить(м["id"])
        audit.записать("поручение из чата", решение["название"], f"исполнитель: {решение['агент']}", кто="чат")
        missions.запустить(м["id"], н)
    except missions.ОшибкаПоручения as ошибка:
        return f"🧭 Не получилось начать: {ошибка}"
    return (f"🧭 Передал: {_имя(решение['агент'])} — {решение['описание']}\n"
            f"Результат пришлю сюда, как будет готов (ход работы — в окне «Поручения», №{м['id']}).")


# ---- Вход из чата ---------------------------------------------------------------------------------

def из_чата(база, н: dict, текст: str, прошлые: list[str], адресовано: str | None = None) -> tuple[str, str] | None:
    """(подсказка ИИ, готовое сообщение системы) или None, если это не для передачи."""
    global _ждёт
    if НАСТРОЙКИ.get("поручения_из_чата", "авто") == "выкл":
        return None
    с_ожиданием = _ждёт if _ждёт and time.time() - _ждёт["создан"] < ЖДАТЬ_ОТВЕТА_СЕК else None
    if not с_ожиданием:
        _ждёт = None

    # Ответ «да» / «нет» на решение по шагу уже идущего поручения (подтверждение, непринятый результат)
    if _решения_хозяина and (_ДА.match(текст) or _НЕТ.match(текст)) and not с_ожиданием:
        номер = _решения_хозяина.pop(0)
        try:
            if _ДА.match(текст):
                missions.подтвердить(номер, н)
                return ("Хозяин подтвердил шаг поручения. Скажи одной фразой.", f"🧭 Продолжаю поручение №{номер}.")
            missions.отклонить(номер)
            return ("Хозяин отклонил поручение. Скажи одной фразой.", f"🧭 Остановил поручение №{номер}.")
        except missions.ОшибкаПоручения as ошибка:
            return ("Поручение уже не ждёт решения. Скажи одной фразой.", f"🧭 Это поручение уже не ждёт решения ({ошибка})")

    if с_ожиданием:
        if _ДА.match(текст):
            решение, _ждёт = с_ожиданием["решение"], None
            return ("Хозяин подтвердил поручение, система его запустила. Скажи одной фразой.", _запустить(решение, н))
        if _НЕТ.match(текст):
            _ждёт = None
            return ("Хозяин отменил поручение. Скажи одной фразой.", "🧭 Отменено, ничего не запускал.")
        _ждёт = None            # заговорили о другом: старое решение сгорает

    if not ai.подключён(н) or not похоже_на_просьбу(текст, адресовано):
        return None
    решение = определить(текст, прошлые, н, адресовано)
    if not решение:
        return None
    if _нужно_спросить(решение):
        _ждёт = {"решение": решение, "создан": time.time()}
        return ("Система разобрала просьбу хозяина и ждёт ответа «да» или «нет». Скажи одной фразой.",
                f"🧭 {_описание(решение)}\nЗапускаю? да / нет")
    return ("Система передала просьбу агенту, поручение запущено. Скажи одной фразой.", _запустить(решение, н))


# ---- Итог поручения — в чат -----------------------------------------------------------------------

def _при_остановке(м: dict) -> None:
    if not _база or м["id"] not in _мои():
        return
    ход = м["ход"][м["шаг"]] if m_ждёт(м) and м["шаг"] < len(м["ход"]) else {}
    имя = _имя(м["шаги"][0]["агент"]) if м["шаги"] else "Агент"
    итог = (м.get("итог") or "").strip()
    if м["статус"] == "готово":
        _забыть(м["id"])
        текст = f"🧭 {имя} закончил: {м['название']}\n\n{итог or 'Результата нет.'}"
    elif м["статус"] == "не вышло":
        _забыть(м["id"])
        текст = f"🧭 {имя} не справился с поручением «{м['название']}»: {итог or 'причина не указана'}"
    elif м["статус"] == "остановлено":
        _забыть(м["id"])
        текст = f"🧭 Поручение «{м['название']}» остановлено."
    elif м["статус"] == "ждёт вас":
        состояние = ход.get("состояние")
        if м["id"] not in _решения_хозяина:
            _решения_хозяина.append(м["id"])
        if состояние == "не принято":
            замечание = (ход.get("проверка") or {}).get("замечание") or "результат не прошёл проверку"
            текст = (f"🧭 {имя}: результат по «{м['название']}» не прошёл проверку ({замечание}).\n\n"
                     f"{(ход.get('результат') or '')[:1500]}\n\nПринять как есть? да / нет")
        else:
            текст = f"🧭 Поручению «{м['название']}» нужно ваше разрешение: {м['шаги'][м['шаг']]['описание'][:300]}\nРазрешаете? да / нет"
    else:
        return
    _база.добавить_сообщение("ии", текст)


def m_ждёт(м: dict) -> bool:
    return м["статус"] == "ждёт вас"
