# ---- Мнения ----------------------------------------------------------------

def прочитать_мнения(база) -> dict:
    данные = база.прочитать("мнения", {}) or {}
    return {"список": данные.get("список", []), "обновлено": данные.get("обновлено", "")}


def обновить_мнения(база, н: dict) -> dict:
    """Спросить ИИ, что он думает о целях и проектах. Старые мнения о других вещах сохраняются."""
    from . import ai

    цели = [и for и in важное(база, 20) if и["тип"] in ("цель", "проект")][:10]
    if not цели:
        return прочитать_мнения(база)
    факты = база.память()
    задачи = база.задачи()
    данные = {
        "душа": блок_характера(прочитать(база)),
        "сегодня": date.today().isoformat(),
        "цели_и_проекты": [{
            "имя": ц["имя"], "тип": ц["тип"],
            "почему": (база.сущность(ц["id"]) or {}).get("причина", ""),
            "факты": [ф["факт"] for ф in факты if ц["id"] in (ф.get("сущности") or [])][:8],
            "шаги": [{"текст": з["текст"], "готово": з["готово"], "срок": з.get("срок")}
                     for з in задачи if з.get("цель_id") == ц["id"]][:12],
        } for ц in цели],
    }
    from . import agents
    записки = agents.непрочитанные("мнения")
    почему = f"записка: {записки[-1]['текст']}" if записки else "раз в день"
    with agents.работа("мнения", "обновила мнения о целях и проектах", почему) as запись:
        новые = ai.сформировать_мнения(данные, agents.с_правилами(н, "мнения"))
        запись["результат"] = f"мнений: {len(новые)}"
        запись["польза"] = len(новые)
    agents.прочитать([з["id"] for з in записки])
    старые = прочитать_мнения(база)["список"]
    ключи = {ключ_имени(м["о"]) for м in новые}
    сейчас = datetime.now().isoformat(timespec="seconds")
    for м in новые:
        м["когда"] = сейчас
    список = новые + [м for м in старые if ключ_имени(м["о"]) not in ключи]
    итог = {"список": список[:16], "обновлено": сейчас}
    база.записать("мнения", итог)
    журнал.info("Мнения души обновлены: %s", len(новые))
    return итог


def нужно_обновить_мнения(база, часов: float = 24) -> bool:
    from . import agents
    if agents.непрочитанные("мнения"):
        return True
    обновлено = _время(прочитать_мнения(база)["обновлено"]) if прочитать_мнения(база)["обновлено"] else None
    if обновлено and (datetime.now() - обновлено).total_seconds() < часов * 3600:
        return False
    return any(и["тип"] in ("цель", "проект") for и in важное(база))


def убрать_мнение(база, о: str) -> bool:
    данные = прочитать_мнения(база)
    осталось = [м for м in данные["список"] if ключ_имени(м["о"]) != ключ_имени(о)]
    if len(осталось) == len(данные["список"]):
        return False
    база.записать("мнения", {**данные, "список": осталось})
    return True


def блок_характера(д: dict) -> str:
    return "; ".join(filter(None, [д["суть"], ", ".join(д["черты"]), "ценности: " + ", ".join(д["ценности"])]))
