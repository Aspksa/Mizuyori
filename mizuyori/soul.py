# ---- Важное для души: цели, проекты и люди ---------------------------------

def важное(база, сколько: int = 12) -> list[dict]:
    """Активные цели, проекты и люди — с весом по числу фактов, связей и шагов."""
    сущности = база.сущности()
    вес: dict[int, float] = {с["id"]: 0.0 for с in сущности}
    for ф in база.память():
        for сид in ф.get("сущности") or []:
            if сид in вес:
                вес[сид] += ф.get("важность", 3) / 3
    for о in база.отношения():
        for сид in (о["от_id"], о["к_id"]):
            if сид in вес:
                вес[сид] += 0.5
    шаги: dict[int, list[bool]] = {}
    for з in база.задачи():
        if з.get("цель_id"):
            шаги.setdefault(з["цель_id"], []).append(з["готово"])
    итог = []
    for с in сущности:
        if с["тип"] == "цель" and с.get("статус") in ("", "активна"):
            ш = шаги.get(с["id"], [])
            итог.append({"id": с["id"], "тип": "цель", "имя": с["имя"], "вес": вес[с["id"]] + 2 + len(ш) * 0.5,
                         "шагов": len(ш), "сделано": sum(ш)})
        elif с["тип"] in ("проект", "человек") and с["имя"] != "Я":
            итог.append({"id": с["id"], "тип": с["тип"], "имя": с["имя"], "вес": вес[с["id"]] + (1 if с["тип"] == "проект" else 0)})
    итог = [и for и in итог if и["тип"] != "человек" or и["вес"] > 0]
    итог.sort(key=lambda и: -и["вес"])
    return итог[:сколько]


