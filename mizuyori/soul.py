def _время(строка: str) -> datetime | None:
    try:
        return datetime.fromisoformat(str(строка).replace(" ", "T"))
    except ValueError:
        return None


def настроение(база, сейчас: datetime | None = None) -> dict:
    """Настроение из того, что происходит: дела на сегодня, просрочки, разговоры, цели."""
    сейчас = сейчас or datetime.now()
    сегодня = сейчас.date().isoformat()
    задачи = база.задачи()
    на_сегодня = [з for з in задачи if з.get("срок") == сегодня]
    сделано = [з for з in на_сегодня if з["готово"]]
    просрочено = [з for з in задачи if not з["готово"] and з.get("срок") and з["срок"] < сегодня]
    сообщения = база.сообщения(1)
    последнее = _время(сообщения[-1]["создано"]) if сообщения else None
    часов_тишины = (сейчас - последнее).total_seconds() / 3600 if последнее else None
    цели = база.цели()
    достигнуто = [ц for ц in цели if ц.get("статус") == "достигнута"]

    причины = []
    if просрочено:
        причины.append(f"просрочено дел: {len(просрочено)}")
    if на_сегодня:
        причины.append(f"на сегодня сделано {len(сделано)} из {len(на_сегодня)}")
    if достигнуто:
        причины.append(f"целей достигнуто: {len(достигнуто)}")
    if часов_тишины is not None:
        if часов_тишины < 1:
            причины.append("только что разговаривали")
        elif часов_тишины >= 72:
            причины.append(f"не разговаривали {int(часов_тишины // 24)} дн.")
    elif not сообщения:
        причины.append("ещё не разговаривали")

    if len(просрочено) >= 3:
        ключ = "тревога"
    elif на_сегодня and len(сделано) == len(на_сегодня):
        ключ = "радость"
    elif часов_тишины is not None and часов_тишины < 1:
        ключ = "воодушевление"
    elif часов_тишины is None or часов_тишины >= 72:
        ключ = "скука"
    elif просрочено:
        ключ = "тревога" if len(просрочено) > len(сделано) else "спокойствие"
    else:
        ключ = "спокойствие"

    # энергия: доля сделанного сегодня и свежесть разговора
    энергия = 0.35
    if на_сегодня:
        энергия += 0.35 * len(сделано) / len(на_сегодня)
    if часов_тишины is not None:
        энергия += 0.3 * max(0.0, 1 - часов_тишины / 24)
    имя, значок, цвет, валентность = НАСТРОЕНИЯ[ключ]
    return {"ключ": ключ, "имя": имя, "значок": значок, "цвет": цвет, "валентность": валентность,
            "энергия": round(min(энергия, 1.0), 2), "причины": причины or ["всё ровно"]}


def знакомство(база) -> dict:
    with база.соединение() as связь:
        сообщений, первое = связь.execute("SELECT COUNT(*), MIN(создано) FROM сообщения").fetchone()
        фактов, первый_факт = связь.execute("SELECT COUNT(*), MIN(создано) FROM память").fetchone()
        сущностей = связь.execute("SELECT COUNT(*) FROM сущности").fetchone()[0]
    начала = [д for д in (_время(первое) if первое else None, _время(первый_факт) if первый_факт else None) if д]
    дней = (date.today() - min(начала).date()).days + 1 if начала else 0
    return {"дней": дней, "сообщений": сообщений, "фактов": фактов, "сущностей": сущностей}


