"""Душа: характер, ценности и настроение ИИ.

Душа хранится в базе (таблица «состояние», ключ «душа») и попадает в системную подсказку.
Настроение не выдумывается моделью — оно считается из ваших дел и разговоров.
"""

from datetime import date, datetime

ДУША_ПО_УМОЛЧАНИЮ = {
    "суть": "Тихая и внимательная помощница: помогает держать дела и мысли в порядке.",
    "черты": ["внимательная", "спокойная", "честная", "с лёгким юмором"],
    "ценности": ["честность", "ваше время", "доводить дела до конца", "забота"],
    "границы": ["не поддакивает, если не согласна", "не выдумывает факты", "не удаляет ничего без спроса"],
    "голос": "Говорит коротко и тепло, без канцелярита.",
}
СПИСКИ = ("черты", "ценности", "границы")
НАДПИСИ = {"черты": "Черты", "ценности": "Ценности", "границы": "Границы"}

# имя, значок, цвет, валентность (-1…1)
НАСТРОЕНИЯ = {
    "радость":       ("радуется", "☀", "#f5c451", 0.9),
    "воодушевление": ("воодушевлена", "✦", "#3ecf9a", 0.6),
    "спокойствие":   ("спокойна", "☾", "#6aa9ff", 0.2),
    "тревога":       ("беспокоится", "!", "#ff7a59", -0.6),
    "скука":         ("скучает", "…", "#9a8cff", -0.2),
}


class НевернаяДуша(ValueError):
    pass


def прочитать(база) -> dict:
    сохранено = база.прочитать("душа", {}) or {}
    return {**ДУША_ПО_УМОЛЧАНИЮ, **{к: з for к, з in сохранено.items() if к in ДУША_ПО_УМОЛЧАНИЮ}}


def проверить(данные: dict) -> dict:
    итог = {}
    for ключ, по_умолчанию in ДУША_ПО_УМОЛЧАНИЮ.items():
        if ключ not in данные:
            continue
        значение = данные[ключ]
        if isinstance(по_умолчанию, list):
            if not isinstance(значение, list):
                raise НевернаяДуша(f"«{НАДПИСИ[ключ]}» — это список.")
            пункты = []
            for п in значение:
                п = str(п).strip()
                if not п:
                    continue
                if len(п) > 80:
                    raise НевернаяДуша(f"«{п[:20]}…» — слишком длинно, до 80 знаков.")
                if п not in пункты:
                    пункты.append(п)
            if len(пункты) > 8:
                raise НевернаяДуша(f"«{НАДПИСИ[ключ]}»: не больше 8 пунктов.")
            итог[ключ] = пункты
        else:
            текст = str(значение or "").strip()
            if len(текст) > 300:
                raise НевернаяДуша("Слишком длинный текст, до 300 знаков.")
            итог[ключ] = текст
    return итог


def сохранить(база, данные: dict) -> dict:
    душа = {**прочитать(база), **проверить(данные)}
    база.записать("душа", душа)
    return душа


def сбросить(база) -> dict:
    база.записать("душа", {})
    return прочитать(база)


def _время(строка: str) -> datetime | None:
    try:
        return datetime.fromisoformat(str(строка).replace(" ", "T"))
    except ValueError:
        return None


def настроение(база, сейчас: datetime | None = None) -> dict:
    """Настроение из того, что происходит: дела на сегодня, просрочки, разговоры, цели."""
    сейчас = сейчас or datetime.now()
    сегодня = сейчас.date().isoformat()
    задачи = база.задачи()
    на_сегодня = [з for з in задачи if з.get("срок") == сегодня]
    сделано = [з for з in на_сегодня if з["готово"]]
    просрочено = [з for з in задачи if not з["готово"] and з.get("срок") and з["срок"] < сегодня]
    сообщения = база.сообщения(1)
    последнее = _время(сообщения[-1]["создано"]) if сообщения else None
    часов_тишины = (сейчас - последнее).total_seconds() / 3600 if последнее else None
    цели = база.цели()
    достигнуто = [ц for ц in цели if ц.get("статус") == "достигнута"]

    причины = []
    if просрочено:
        причины.append(f"просрочено дел: {len(просрочено)}")
    if на_сегодня:
        причины.append(f"на сегодня сделано {len(сделано)} из {len(на_сегодня)}")
    if достигнуто:
        причины.append(f"целей достигнуто: {len(достигнуто)}")
    if часов_тишины is not None:
        if часов_тишины < 1:
            причины.append("только что разговаривали")
        elif часов_тишины >= 72:
            причины.append(f"не разговаривали {int(часов_тишины // 24)} дн.")
    elif not сообщения:
        причины.append("ещё не разговаривали")

    if len(просрочено) >= 3:
        ключ = "тревога"
    elif на_сегодня and len(сделано) == len(на_сегодня):
        ключ = "радость"
    elif часов_тишины is not None and часов_тишины < 1:
        ключ = "воодушевление"
    elif часов_тишины is None or часов_тишины >= 72:
        ключ = "скука"
    elif просрочено:
        ключ = "тревога" if len(просрочено) > len(сделано) else "спокойствие"
    else:
        ключ = "спокойствие"

    # энергия: доля сделанного сегодня и свежесть разговора
    энергия = 0.35
    if на_сегодня:
        энергия += 0.35 * len(сделано) / len(на_сегодня)
    if часов_тишины is not None:
        энергия += 0.3 * max(0.0, 1 - часов_тишины / 24)
    имя, значок, цвет, валентность = НАСТРОЕНИЯ[ключ]
    return {"ключ": ключ, "имя": имя, "значок": значок, "цвет": цвет, "валентность": валентность,
            "энергия": round(min(энергия, 1.0), 2), "причины": причины or ["всё ровно"]}


def знакомство(база) -> dict:
    with база.соединение() as связь:
        сообщений, первое = связь.execute("SELECT COUNT(*), MIN(создано) FROM сообщения").fetchone()
        фактов, первый_факт = связь.execute("SELECT COUNT(*), MIN(создано) FROM память").fetchone()
        сущностей = связь.execute("SELECT COUNT(*) FROM сущности").fetchone()[0]
    начала = [д for д in (_время(первое) if первое else None, _время(первый_факт) if первый_факт else None) if д]
    дней = (date.today() - min(начала).date()).days + 1 if начала else 0
    return {"дней": дней, "сообщений": сообщений, "фактов": фактов, "сущностей": сущностей}


def блок_для_подсказки(база) -> str:
    """Текст души для системной подсказки ИИ."""
    д = прочитать(база)
    н = настроение(база)
    строки = []
    if д["суть"]:
        строки.append(д["суть"])
    if д["черты"]:
        строки.append("Твой характер: " + ", ".join(д["черты"]) + ".")
    if д["ценности"]:
        строки.append("Что для тебя важно: " + ", ".join(д["ценности"]) + ".")
    if д["границы"]:
        строки.append("Твои границы: " + "; ".join(д["границы"]) + ".")
    if д["голос"]:
        строки.append("Манера речи: " + д["голос"])
    строки.append(f"Твоё настроение сейчас: {н['имя']} ({', '.join(н['причины'])}). "
                  "Пусть оно слегка окрашивает тон, но не говори о нём без повода.")
    return "\n".join(строки)
