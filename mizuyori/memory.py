"""Память ИИ: что подать модели в ответ и как обновить память после ответа.

Долговременная память — факты о пользователе (таблица «память»):
  у каждого есть категория и важность 1–5. В ответ идут не все факты, а
  важные (4–5) плюс самые близкие по смыслу к вопросу (эмбеддинги cloud.ru).
  После каждого хода ИИ решает: добавить, заменить (уточнение/противоречие)
  или удалить факт. Почти одинаковые факты не дублируются.

Краткосрочная память:
  - сводка — старые сообщения чата сжимаются в пересказ, чтобы ИИ не терял нить;
  - рабочая память — тема разговора, принятые решения, открытые вопросы.
"""

import hashlib
import logging
import threading
from datetime import date

from . import agents, ai
from .database import ключ_имени

журнал = logging.getLogger("mizuyori.память")

ВСЕГДА_ВСЕ = 15        # если фактов не больше — подаём все
ВАЖНЫХ_НЕ_БОЛЬШЕ = 10  # важных (4–5) берём всегда, но не больше
ПОХОЖИХ = 12           # плюс столько самых похожих на вопрос
ПОРОГ_ДУБЛЯ = 0.93     # похожесть, выше которой новый факт считается повтором
СЖИМАТЬ_ОТ = 10        # сжимать, когда вне окна накопилось столько сообщений

_замок_векторов = threading.Lock()
_замок_памяти = threading.Lock()

ПРЕФИКС_ПРАВИЛА = "правило хозяина:"


def активные_факты(база) -> list[dict]:
    """Только актуальные сейчас факты; устаревшие остаются в базе как история."""
    сегодня = date.today().isoformat()
    return [ф for ф in база.память()
            if ф.get("состояние", "активен") == "активен"
            and (not ф.get("действует_с") or ф["действует_с"] <= сегодня)
            and (not ф.get("действует_до") or ф["действует_до"] >= сегодня)]


def правила_хозяина(база) -> list[str]:
    """Только явно названные хозяином постоянные правила, от новых к старым."""
    итог = []
    for факт in reversed(активные_факты(база)):
        текст = str(факт.get("факт") or "").strip()
        if текст.casefold().replace("ё", "е").startswith(ПРЕФИКС_ПРАВИЛА):
            правило = текст.split(":", 1)[1].strip() if ":" in текст else текст
            if правило and правило not in итог:
                итог.append(правило)
    return итог[:20]


# ---- Вектора ---------------------------------------------------------------

def можно_эмбеддинги(н: dict) -> bool:
    return bool(н.get("ключ") and н.get("модель_эмбеддингов"))


def обеспечить_вектора(база, н: dict, тексты: dict[str, str]):
    """Нормированные вектора для текстов {ключ: текст}. Считает только новые и изменённые.

    Возвращает (ключи, матрица numpy, сколько посчитано заново). Если выбранной модели эмбеддингов нет у cloud.ru (404),
    берётся доступная (вектора хранятся отдельно для каждой модели, так что перепутать их нельзя)."""
    выбранная = н["модель_эмбеддингов"]
    модель = ai.рабочая_модель_эмбеддингов(н["адрес"], выбранная)
    try:
        return _обеспечить_вектора(база, н, тексты, модель)
    except ai.ОшибкаИИ as ошибка:
        замена = ai.замена_модели_эмбеддингов(н["адрес"], н["ключ"], модель, ошибка)
        if not замена:
            raise
        return _обеспечить_вектора(база, н, тексты, замена)


def _обеспечить_вектора(база, н: dict, тексты: dict[str, str], модель: str):
    """Нормированные вектора для текстов {ключ: текст}. Считает только новые и изменённые.

    Возвращает (ключи, матрица numpy, сколько посчитано заново)."""
    import numpy as np

    отпечаток = lambda т: hashlib.sha1(f"{модель}\n{т}".encode("utf-8")).hexdigest()
    with _замок_векторов:
        есть = база.вектора(модель)
        нужно = [к for к, т in тексты.items() if есть.get(к, ("",))[0] != отпечаток(т)]
        if нужно:
            with agents.работа("смысл", "посчитал смысл текстов", f"новых или изменённых текстов: {len(нужно)}") as запись:
                вектора = ai.эмбеддинги(н["адрес"], н["ключ"], модель, [тексты[к] for к in нужно])
                запись["результат"] = f"векторов: {len(вектора)}"
                запись["польза"] = 1
            база.сохранить_вектора(модель, [(к, отпечаток(тексты[к]), np.asarray(в, dtype=np.float32).tobytes())
                                            for к, в in zip(нужно, вектора)])
            есть = база.вектора(модель)
    ключи = [к for к in тексты if к in есть]
    if not ключи:
        return [], np.zeros((0, 1), dtype=np.float32), len(нужно)
    матрица = np.stack([np.frombuffer(есть[к][1], dtype=np.float32) for к in ключи])
    матрица = матрица / (np.linalg.norm(матрица, axis=1, keepdims=True) + 1e-9)
    return ключи, матрица, len(нужно)


def _вектор_запроса(н: dict, текст: str):
    import numpy as np

    модель = ai.рабочая_модель_эмбеддингов(н["адрес"], н["модель_эмбеддингов"])
    try:
        сырой = ai.эмбеддинги(н["адрес"], н["ключ"], модель, [текст[:4000]])[0]
    except ai.ОшибкаИИ as ошибка:
        замена = ai.замена_модели_эмбеддингов(н["адрес"], н["ключ"], модель, ошибка)
        if not замена:
            raise
        сырой = ai.эмбеддинги(н["адрес"], н["ключ"], замена, [текст[:4000]])[0]
    в = np.asarray(сырой, dtype=np.float32)
    return в / (np.linalg.norm(в) + 1e-9)


# ---- Какие факты подать модели --------------------------------------------

def выбрать_факты(база, н: dict, запрос: str, сколько_похожих: int = ПОХОЖИХ) -> list[dict]:
    """Важные всегда + лучшие по трём каналам (смысл, слова, сущности), склеенным по рангам; см. memory_plus."""
    from . import memory_plus
    факты = активные_факты(база)
    if len(факты) <= ВСЕГДА_ВСЕ:
        база.отметить_использование_фактов([ф["id"] for ф in факты])
        return факты
    намерение = memory_plus.намерение_времени(запрос)
    важные = [ф for ф in факты if ф["важность"] >= 4][:ВАЖНЫХ_НЕ_БОЛЬШЕ]
    ид_важных = {ф["id"] for ф in важные}
    остальные = [ф for ф in memory_plus.кандидаты(база, намерение) if ф["id"] not in ид_важных]
    вектора = None
    if можно_эмбеддинги(н) and запрос.strip() and остальные:
        try:
            ключи, матрица, _ = обеспечить_вектора(база, н, {f"п{ф['id']}": ф["факт"] for ф in остальные})
            if ключи:
                похожесть = матрица @ _вектор_запроса(н, запрос)
                вектора = {int(к[1:]): float(п) for к, п in zip(ключи, похожесть)}
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Не удалось выбрать факты по смыслу: %s", ошибка)
    выбранные = memory_plus.гибридный_поиск(база, н, запрос, остальные, сколько_похожих, вектора) if запрос.strip() else []
    if not выбранные:
        # ни слов, ни смысла — самые важные и свежие
        выбранные = sorted([ф for ф in остальные if ф.get("состояние", "активен") == "активен"],
                           key=lambda ф: (-ф["важность"], -ф["id"]))[:сколько_похожих + 8]
    итог = важные + [ф if ф.get("состояние", "активен") == "активен" else {**ф, "факт": f"(устарело) {ф['факт']}"} for ф in выбранные]
    база.отметить_использование_фактов([ф["id"] for ф in итог if ф.get("состояние", "активен") == "активен"])
    return итог


# ---- Понимание: какие сущности относятся к разговору ----------------------

def _упомянута(сущность: dict, текст_ключ: str, слова: list[str]) -> bool:
    for имя in [сущность["имя"], *сущность["другие_имена"]]:
        к = ключ_имени(имя)
        if not к:
            continue
        if к in текст_ключ:
            return True
        # «маме», «мамой» → «мама»: сравниваем по основе слова
        if " " not in к and len(к) >= 4:
            основа = к[:max(3, len(к) - 2)]
            if any(с.startswith(основа) for с in слова):
                return True
    return False


def нужные_сущности(база, н: dict, текст: str, похожих: int = 5) -> list[dict]:
    """Упомянутые в тексте + активные цели + близкие по смыслу (если есть эмбеддинги)."""
    сущности = база.сущности()
    if not сущности:
        return []
    к = ключ_имени(текст)
    слова = к.split()
    итог = {с["id"]: с for с in сущности if _упомянута(с, к, слова)}
    for с in сущности:
        if с["тип"] == "цель" and с["статус"] in ("", "активна") and len(итог) < 30:
            итог.setdefault(с["id"], с)
    if можно_эмбеддинги(н) and текст.strip() and len(сущности) > len(итог):
        try:
            тексты = {f"е{с['id']}": f"{с['имя']} ({с['тип']}): {с['описание']} {с['причина']}".strip() for с in сущности}
            ключи, матрица, _ = обеспечить_вектора(база, н, тексты)
            if ключи:
                похожесть = матрица @ _вектор_запроса(н, текст)
                по_ключу = {f"е{с['id']}": с for с in сущности}
                for i in похожесть.argsort()[::-1][:похожих]:
                    if похожесть[i] > 0.3:
                        с = по_ключу[ключи[i]]
                        итог.setdefault(с["id"], с)
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Не удалось подобрать сущности по смыслу: %s", ошибка)
    return list(итог.values())


def цепочка_причин(база, начало_id: int, отношения=None, сущности=None, глубина: int = 4) -> list[tuple[str, dict]]:
    """«Поездка → потому что → Мечта …»: идём по связям «потому что» / «чтобы» / «для»."""
    отношения = отношения if отношения is not None else база.отношения()
    сущности = сущности if сущности is not None else {с["id"]: с for с in база.сущности()}
    путь, текущий, видели = [], начало_id, {начало_id}
    for _ in range(глубина):
        следующее = next((о for о in отношения if о["от_id"] == текущий
                          and ключ_имени(о["отношение"]) in ("потому что", "чтобы", "для", "ради")), None)
        if not следующее or следующее["к_id"] in видели or следующее["к_id"] not in сущности:
            break
        путь.append((следующее["отношение"], сущности[следующее["к_id"]]))
        текущий = следующее["к_id"]
        видели.add(текущий)
    return путь


def блок_понимания(база, н: dict, вопрос: str) -> str:
    нужные = нужные_сущности(база, н, вопрос)
    все = {с["id"]: с for с in база.сущности()}
    отношения = база.отношения()
    задачи = база.задачи()
    факты = активные_факты(база)
    строки_целей, строки_прочих = [], []
    for с in нужные:
        связи = []
        for о in отношения:
            if о["от_id"] == с["id"] and о["к_id"] in все:
                связи.append(f"{о['отношение']} → {все[о['к_id']]['имя']}")
            elif о["к_id"] == с["id"] and о["от_id"] in все:
                связи.append(f"← {все[о['от_id']]['имя']} {о['отношение']}")
        свои_факты = [ф["факт"] for ф in факты if с["id"] in ф.get("сущности", [])][:4]
        if с["тип"] == "цель":
            шаги = [з for з in задачи if з.get("цель_id") == с["id"]]
            сделано = sum(з["готово"] for з in шаги)
            причины = цепочка_причин(база, с["id"], отношения, все)
            части = [f"статус: {с['статус'] or 'активна'}"]
            if с["причина"]:
                части.append(f"почему: {с['причина']}")
            if причины:
                части.append("цепочка: " + " → ".join(f"{о} {ц['имя']}" for о, ц in причины))
            if шаги:
                части.append(f"шаги ({сделано} из {len(шаги)} сделано): " +
                             ", ".join(f"«{з['текст']}»{' ✓' if з['готово'] else ''}" for з in шаги[:8]))
            строки_целей.append(f"- {с['имя']} ({'; '.join(части)})")
        else:
            части = [с["описание"]] if с["описание"] else []
            if связи:
                части.append("; ".join(связи[:6]))
            if свои_факты:
                части.append("факты: " + "; ".join(свои_факты))
            упоминания = [з for з in задачи if not з["готово"] and _упомянута(с, ключ_имени(з["текст"]), ключ_имени(з["текст"]).split())]
            if упоминания:
                части.append("задачи: " + ", ".join(f"«{з['текст']}»" for з in упоминания[:4]))
            строки_прочих.append(f"- {с['имя']} [{с['тип']}]" + (f": {' | '.join(части)}" if части else ""))
    блоки = []
    if строки_целей:
        блоки.append("Цели:\n" + "\n".join(строки_целей))
    if строки_прочих:
        блоки.append("Люди, места и прочее:\n" + "\n".join(строки_прочих))
    задачи_по_id = {з["id"]: з for з in задачи}
    блокировки = []
    for зависимость in база.зависимости_задач():
        задача = задачи_по_id.get(зависимость["задача_id"])
        препятствие = задачи_по_id.get(зависимость["зависит_от_id"])
        if задача and препятствие and not задача["готово"] and not препятствие["готово"]:
            причина = f" ({зависимость['причина']})" if зависимость["причина"] else ""
            блокировки.append(f"- «{задача['текст']}» ждёт «{препятствие['текст']}»{причина}")
    if блокировки:
        блоки.append("Зависимости задач:\n" + "\n".join(блокировки[:12]))
    return "\n".join(блоки)


def контекст_для_ответа(база, н: dict, вопрос: str) -> dict:
    контекст = {}
    try:
        from . import soul
        контекст["душа"] = soul.блок_для_подсказки(база)
        контекст["мысли"] = soul.прочитать(база)["мысли"]
        контекст["правила"] = agents.правила("чат", вопрос)
        контекст["правила_хозяина"] = правила_хозяина(база)
    except Exception:
        журнал.exception("Не удалось собрать душу для ответа")
    if н.get("память"):
        контекст["факты"] = выбрать_факты(база, н, вопрос)
        контекст["рабочая"] = база.прочитать("рабочая", {})
        try:
            контекст["знания"] = блок_понимания(база, н, вопрос)
        except Exception:
            журнал.exception("Не удалось собрать понимание для ответа")
        наблюдения = [н for н in база.наблюдения()
                      if н["состояние"] == "открыто" and н["уверенность"] >= 0.8
                      and н["вид"] in ("привычка", "исправление", "обещание", "цель_без_шага")]
        if наблюдения:
            контекст["наблюдения"] = [
                {"вид": н["вид"], "текст": н["текст"], "уверенность": н["уверенность"]}
                for н in наблюдения[:12]]
    сводка = база.сводка()
    if сводка:
        контекст["сводка"] = сводка["текст"]
    return контекст


# ---- После ответа ------------------------------------------------------------

def _это_дубль(база, н: dict, факт: str) -> bool:
    """Почти такой же факт уже есть (по смыслу)."""
    if not можно_эмбеддинги(н):
        return False
    import numpy as np

    факты = активные_факты(база)
    if not факты:
        return False
    try:
        ключи, матрица, _ = обеспечить_вектора(база, н, {f"п{ф['id']}": ф["факт"] for ф in факты})
        if not ключи:
            return False
        return float(np.max(матрица @ _вектор_запроса(н, факт))) >= ПОРОГ_ДУБЛЯ
    except ai.ОшибкаИИ:
        return False


def после_ответа(база, н: dict, реплика: str, ответ: str, сообщение_id: int) -> None:
    """Обновить долговременную и рабочую память, при надобности сжать старую часть чата."""
    with _замок_памяти:
        if н.get("память"):
            try:
                _обновить(база, н, реплика, ответ, сообщение_id)
            except ai.ОшибкаИИ as ошибка:
                журнал.warning("Память не обновилась: %s", ошибка)
            except Exception:
                журнал.exception("Ошибка при обновлении памяти")
        # Стратег берёт записки от Памяти: появились цели — разложить задачи
        try:
            записки = agents.непрочитанные("цели")
            if записки:
                agents.прочитать([з["id"] for з in записки])
                привязать_задачи_к_целям(база, н, f"записка от Памяти: {записки[-1]['текст']}")
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Стратег не разложил задачи: %s", ошибка)
        except Exception:
            журнал.exception("Ошибка Стратега")
        try:
            from . import soul
            if soul.нужно_обновить_мнения(база):
                soul.обновить_мнения(база, н)
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Мнения души не обновились: %s", ошибка)
        except Exception:
            журнал.exception("Ошибка при обновлении мнений души")
        try:
            сжать_если_нужно(база, н)
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Сводка чата не обновилась: %s", ошибка)
        except Exception:
            журнал.exception("Ошибка при сжатии чата")


def _сущность_по_имени(база, имя: str, тип: str = "другое") -> dict:
    if ключ_имени(имя) in ("я", "пользователь", "меня", "мне"):
        return база.сущность_или_новая("Я", "человек", "сам пользователь")
    return база.найти_сущность(имя) or база.сущность_или_новая(имя, тип)


def _обновить(база, н, реплика, ответ, сообщение_id):
    известные = выбрать_факты(база, н, реплика, сколько_похожих=25)
    рабочая = база.прочитать("рабочая", {})
    сущности = нужные_сущности(база, н, реплика + "\n" + ответ, похожих=15)
    без_цели = [з for з in база.задачи() if not з["готово"] and not з.get("цель_id")][:30]
    кратко = " ".join(реплика.split())[:60]
    with agents.работа("память", "обновила память", f"после ответа на «{кратко}»") as запись:
        изменения = ai.обновить_память(реплика, ответ, известные, рабочая, agents.с_правилами(н, "память"),
                                       сущности, без_цели)
        счёт = _применить(база, н, изменения, сообщение_id)
        части = [f"{подпись}: {счёт[к]}" for к, подпись in (
            ("добавлено", "новых фактов"), ("заменено", "уточнено"), ("удалено", "забыто"),
            ("сущностей", "людей и вещей"), ("целей", "целей"), ("связей", "связей"), ("к_целям", "задач к целям"))
            if счёт[к]]
        запись["результат"] = ", ".join(части) or "ничего нового"
        запись["польза"] = sum(счёт[к] for к in ("добавлено", "заменено", "удалено", "целей", "связей", "к_целям"))
        # записки другим агентам
        for имя in счёт["новые_цели"]:
            agents.написать("память", "цели", f"Появилась цель «{имя}» — разложи по ней задачи.")
            agents.написать("память", "мнения", f"Появилась цель «{имя}» — что ты о ней думаешь?")
        if счёт["удалено"] or счёт["заменено"]:
            agents.написать("память", "все", f"Память поменялась: уточнено {счёт['заменено']}, забыто {счёт['удалено']}.")


def _применить(база, н, изменения, сообщение_id) -> dict:
    счёт = {"добавлено": 0, "заменено": 0, "удалено": 0, "сущностей": 0, "целей": 0, "связей": 0, "к_целям": 0,
            "новые_цели": []}
    # сущности и цели — раньше фактов, чтобы факты было к чему привязать
    for с in изменения["сущности"]:
        if not база.найти_сущность(с["имя"]):
            счёт["сущностей"] += 1
        база.сущность_или_новая(с["имя"], с["тип"], с["описание"], с["другие_имена"])
    for ц in изменения["цели"]:
        if not база.найти_сущность(ц["имя"]):
            счёт["новые_цели"].append(ц["имя"])
        счёт["целей"] += 1
        цель = база.сущность_или_новая(ц["имя"], "цель")
        поля = {"статус": ц["статус"]}
        if ц["почему"]:
            поля["причина"] = ц["почему"]
        база.изменить_сущность(цель["id"], поля)
        журнал.info("Цель: %s (%s)", цель["имя"], ц["статус"])
    for с in изменения["связи"]:
        от, к = _сущность_по_имени(база, с["от"]), _сущность_по_имени(база, с["к"])
        база.связать(от["id"], с["отношение"], к["id"])
        счёт["связей"] += 1
    for п in изменения["задачи_к_целям"]:
        задача = база.задача(п["задача_id"])
        if задача and not задача["готово"]:
            цель = _сущность_по_имени(база, п["цель"], "цель")
            база.изменить_задачу(задача["id"], {"цель_id": цель["id"]})
            счёт["к_целям"] += 1
            журнал.info("Задача «%s» → цель «%s»", задача["текст"], цель["имя"])

    from . import memory_plus
    for номер in изменения["удалить"]:
        if memory_plus.архивировать(база, номер, "ИИ счёл неактуальным"):      # не стираем: можно вернуть из архива
            счёт["удалено"] += 1
            журнал.info("ИИ убрал факт #%s в архив", номер)
    for ф in изменения["заменить"]:
        старый = база.факт(ф["id"])
        if старый:
            база.изменить_факт(ф["id"], {"факт": ф["факт"], "категория": ф["категория"], "важность": ф["важность"],
                                         "источник": сообщение_id, "смысл": ф["смысл"] or старый["смысл"],
                                         "уверенность": max(float(старый.get("уверенность", 0.75)), 0.85),
                                         "состояние": "активен", "заменён_на": None}, "уточнено ИИ")
            for имя in ф["сущности"]:
                база.привязать_факт(ф["id"], _сущность_по_имени(база, имя)["id"])
            счёт["заменено"] += 1
            журнал.info("ИИ уточнил факт: «%s» → «%s»", старый["факт"], ф["факт"])
    for ф in изменения["добавить"]:
        if _это_дубль(база, н, ф["факт"]):
            журнал.info("Пропущен повтор факта: %s", ф["факт"])
            continue
        if memory_plus.нужно_подтверждение(база):
            if memory_plus.предложить(база, ф["факт"], ф["категория"], ф["важность"], сообщение_id, "из разговора"):
                счёт["предложено"] = счёт.get("предложено", 0) + 1
            continue
        новый = база.запомнить(ф["факт"], сообщение_id, ф["категория"], ф["важность"], ф["смысл"], 0.8)
        if новый:
            for имя in ф["сущности"]:
                база.привязать_факт(новый["id"], _сущность_по_имени(база, имя)["id"])
            счёт["добавлено"] += 1
            журнал.info("ИИ запомнил [%s, %s]: %s", ф["категория"], ф["важность"], ф["факт"])
    if изменения["рабочая"] is not None:
        база.записать("рабочая", изменения["рабочая"])
    return счёт


def сжать_если_нужно(база, н: dict) -> bool:
    """Сообщения, вышедшие за «память чата», сжимаются в пересказ."""
    окно = база.сообщения(max(н.get("история", 20), 1))
    if not окно:
        return False
    первое_в_окне = окно[0]["id"]
    сводка = база.сводка()
    до = сводка["до_сообщения"] if сводка else 0
    старые = база.сообщения_между(до, первое_в_окне - 1)
    старые = [с for с in старые if с["текст"] != ai.ЗАГЛУШКА]
    if len(старые) < СЖИМАТЬ_ОТ:
        return False
    with agents.работа("сводка", "сжал старую часть чата", f"за окно памяти вышло сообщений: {len(старые)}") as запись:
        текст = ai.сжать(сводка["текст"] if сводка else "", старые, agents.с_правилами(н, "сводка"))
        запись["результат"] = f"пересказ {len(текст.strip())} знаков" if текст.strip() else "пустой пересказ"
        запись["польза"] = 1 if текст.strip() else 0
        if текст.strip():
            agents.написать("сводка", "все", f"Сжал {len(старые)} старых сообщений чата в пересказ.")
    if текст.strip():
        база.сохранить_сводку(старые[-1]["id"], текст.strip())
        журнал.info("Старая часть чата сжата (%s сообщений).", len(старые))
        return True
    return False


def привязать_задачи_к_целям(база, н: dict, почему: str = "вы нажали «Разложить по целям»") -> dict:
    """ИИ раскладывает открытые задачи по целям (по кнопке или по записке Памяти)."""
    цели = [ц for ц in база.цели() if ц["статус"] in ("", "активна")]
    задачи = [з for з in база.задачи() if not з["готово"] and not з.get("цель_id")][:80]
    if not задачи:
        return {"привязано": 0, "новых_целей": 0}
    with agents.работа("цели", "разложил задачи по целям", почему) as запись:
        итог = ai.привязать_к_целям(цели, задачи, agents.с_правилами(н, "цели"))
        счёт = _разложить(база, задачи, итог)
        запись["результат"] = f"привязано задач: {счёт['привязано']}, новых целей: {счёт['новых_целей']}"
        запись["польза"] = счёт["привязано"] + счёт["новых_целей"]
        if счёт["новых_целей"]:
            agents.написать("цели", "мнения", f"Предложил новых целей: {счёт['новых_целей']}.")
    return счёт


def _разложить(база, задачи, итог) -> dict:
    новых = 0
    for ц in итог["новые_цели"]:
        if not база.найти_сущность(ц["имя"]):
            цель = база.сущность_или_новая(ц["имя"], "цель")
            if ц["почему"]:
                база.изменить_сущность(цель["id"], {"причина": ц["почему"]})
            новых += 1
    номера = {з["id"] for з in задачи}
    привязано = 0
    for п in итог["привязки"]:
        if п["задача_id"] in номера:
            цель = база.найти_сущность(п["цель"])
            if цель and цель["тип"] == "цель":
                база.изменить_задачу(п["задача_id"], {"цель_id": цель["id"]})
                привязано += 1
    журнал.info("Задачи привязаны к целям: %s, новых целей: %s", привязано, новых)
    return {"привязано": привязано, "новых_целей": новых}
