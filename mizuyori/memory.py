"""Память ИИ: что подать модели в ответ и как обновить память после ответа.

Долговременная память — факты о пользователе (таблица «память»):
  у каждого есть категория и важность 1–5. В ответ идут не все факты, а
  важные (4–5) плюс самые близкие по смыслу к вопросу (эмбеддинги cloud.ru).
  После каждого хода ИИ решает: добавить, заменить (уточнение/противоречие)
  или удалить факт. Почти одинаковые факты не дублируются.

Краткосрочная память:
  - сводка — старые сообщения чата сжимаются в пересказ, чтобы ИИ не терял нить;
  - рабочая память — тема разговора, принятые решения, открытые вопросы.
"""

import hashlib
import logging
import threading

from . import ai

журнал = logging.getLogger("mizuyori.память")

ВСЕГДА_ВСЕ = 15        # если фактов не больше — подаём все
ВАЖНЫХ_НЕ_БОЛЬШЕ = 10  # важных (4–5) берём всегда, но не больше
ПОХОЖИХ = 12           # плюс столько самых похожих на вопрос
ПОРОГ_ДУБЛЯ = 0.93     # похожесть, выше которой новый факт считается повтором
СЖИМАТЬ_ОТ = 10        # сжимать, когда вне окна накопилось столько сообщений

_замок_векторов = threading.Lock()
_замок_памяти = threading.Lock()


# ---- Вектора ---------------------------------------------------------------

def можно_эмбеддинги(н: dict) -> bool:
    return bool(н.get("ключ") and н.get("модель_эмбеддингов"))


def обеспечить_вектора(база, н: dict, тексты: dict[str, str]):
    """Нормированные вектора для текстов {ключ: текст}. Считает только новые и изменённые.

    Возвращает (ключи, матрица numpy, сколько посчитано заново)."""
    import numpy as np

    модель = н["модель_эмбеддингов"]
    отпечаток = lambda т: hashlib.sha1(f"{модель}\n{т}".encode("utf-8")).hexdigest()
    with _замок_векторов:
        есть = база.вектора(модель)
        нужно = [к for к, т in тексты.items() if есть.get(к, ("",))[0] != отпечаток(т)]
        if нужно:
            вектора = ai.эмбеддинги(н["адрес"], н["ключ"], модель, [тексты[к] for к in нужно])
            база.сохранить_вектора(модель, [(к, отпечаток(тексты[к]), np.asarray(в, dtype=np.float32).tobytes())
                                            for к, в in zip(нужно, вектора)])
            есть = база.вектора(модель)
    ключи = [к for к in тексты if к in есть]
    if not ключи:
        return [], np.zeros((0, 1), dtype=np.float32), len(нужно)
    матрица = np.stack([np.frombuffer(есть[к][1], dtype=np.float32) for к in ключи])
    матрица = матрица / (np.linalg.norm(матрица, axis=1, keepdims=True) + 1e-9)
    return ключи, матрица, len(нужно)


def _вектор_запроса(н: dict, текст: str):
    import numpy as np

    в = np.asarray(ai.эмбеддинги(н["адрес"], н["ключ"], н["модель_эмбеддингов"], [текст[:4000]])[0], dtype=np.float32)
    return в / (np.linalg.norm(в) + 1e-9)


# ---- Какие факты подать модели --------------------------------------------

def выбрать_факты(база, н: dict, запрос: str, сколько_похожих: int = ПОХОЖИХ) -> list[dict]:
    факты = база.память()
    if len(факты) <= ВСЕГДА_ВСЕ:
        return факты
    важные = [ф for ф in факты if ф["важность"] >= 4][:ВАЖНЫХ_НЕ_БОЛЬШЕ]
    остальные = [ф for ф in факты if ф not in важные]
    выбранные: list[dict] = []
    if можно_эмбеддинги(н) and запрос.strip():
        try:
            ключи, матрица, _ = обеспечить_вектора(база, н, {f"п{ф['id']}": ф["факт"] for ф in остальные})
            if ключи:
                похожесть = матрица @ _вектор_запроса(н, запрос)
                по_ключу = {f"п{ф['id']}": ф for ф in остальные}
                порядок = похожесть.argsort()[::-1][:сколько_похожих]
                выбранные = [по_ключу[ключи[i]] for i in порядок]
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Не удалось выбрать факты по смыслу: %s", ошибка)
    if not выбранные:
        # без эмбеддингов — самые важные и свежие
        выбранные = sorted(остальные, key=lambda ф: (-ф["важность"], -ф["id"]))[:сколько_похожих + 8]
    return важные + выбранные


def контекст_для_ответа(база, н: dict, вопрос: str) -> dict:
    контекст = {}
    if н.get("память"):
        контекст["факты"] = выбрать_факты(база, н, вопрос)
        контекст["рабочая"] = база.прочитать("рабочая", {})
    сводка = база.сводка()
    if сводка:
        контекст["сводка"] = сводка["текст"]
    return контекст


# ---- После ответа ------------------------------------------------------------

def _это_дубль(база, н: dict, факт: str) -> bool:
    """Почти такой же факт уже есть (по смыслу)."""
    if not можно_эмбеддинги(н):
        return False
    import numpy as np

    факты = база.память()
    if not факты:
        return False
    try:
        ключи, матрица, _ = обеспечить_вектора(база, н, {f"п{ф['id']}": ф["факт"] for ф in факты})
        if not ключи:
            return False
        return float(np.max(матрица @ _вектор_запроса(н, факт))) >= ПОРОГ_ДУБЛЯ
    except ai.ОшибкаИИ:
        return False


def после_ответа(база, н: dict, реплика: str, ответ: str, сообщение_id: int) -> None:
    """Обновить долговременную и рабочую память, при надобности сжать старую часть чата."""
    with _замок_памяти:
        if н.get("память"):
            try:
                _обновить(база, н, реплика, ответ, сообщение_id)
            except ai.ОшибкаИИ as ошибка:
                журнал.warning("Память не обновилась: %s", ошибка)
            except Exception:
                журнал.exception("Ошибка при обновлении памяти")
        try:
            сжать_если_нужно(база, н)
        except ai.ОшибкаИИ as ошибка:
            журнал.warning("Сводка чата не обновилась: %s", ошибка)
        except Exception:
            журнал.exception("Ошибка при сжатии чата")


def _обновить(база, н, реплика, ответ, сообщение_id):
    известные = выбрать_факты(база, н, реплика, сколько_похожих=25)
    рабочая = база.прочитать("рабочая", {})
    изменения = ai.обновить_память(реплика, ответ, известные, рабочая, н)

    for номер in изменения["удалить"]:
        if база.забыть(номер):
            журнал.info("ИИ забыл факт #%s", номер)
    for ф in изменения["заменить"]:
        старый = база.факт(ф["id"])
        if старый:
            база.изменить_факт(ф["id"], {"факт": ф["факт"], "категория": ф["категория"],
                                         "важность": ф["важность"], "источник": сообщение_id})
            журнал.info("ИИ уточнил факт: «%s» → «%s»", старый["факт"], ф["факт"])
    for ф in изменения["добавить"]:
        if _это_дубль(база, н, ф["факт"]):
            журнал.info("Пропущен повтор факта: %s", ф["факт"])
            continue
        if база.запомнить(ф["факт"], сообщение_id, ф["категория"], ф["важность"]):
            журнал.info("ИИ запомнил [%s, %s]: %s", ф["категория"], ф["важность"], ф["факт"])
    if изменения["рабочая"] is not None:
        база.записать("рабочая", изменения["рабочая"])


def сжать_если_нужно(база, н: dict) -> bool:
    """Сообщения, вышедшие за «память чата», сжимаются в пересказ."""
    окно = база.сообщения(max(н.get("история", 20), 1))
    if not окно:
        return False
    первое_в_окне = окно[0]["id"]
    сводка = база.сводка()
    до = сводка["до_сообщения"] if сводка else 0
    старые = база.сообщения_между(до, первое_в_окне - 1)
    старые = [с for с in старые if с["текст"] != ai.ЗАГЛУШКА]
    if len(старые) < СЖИМАТЬ_ОТ:
        return False
    текст = ai.сжать(сводка["текст"] if сводка else "", старые, н)
    if текст.strip():
        база.сохранить_сводку(старые[-1]["id"], текст.strip())
        журнал.info("Старая часть чата сжата (%s сообщений).", len(старые))
        return True
    return False
