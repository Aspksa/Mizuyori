def _прочитать(имя: str, данные: bytes, настройки_ии: dict | None = None) -> tuple[str, str]:
    """(текст, пометка). Скан или фото читает модель зрения, если она выбрана в настройках ИИ."""
    from . import smeta
    try:
        return smeta.извлечь_текст(имя, данные)[:30000], ""
    except smeta.НужноЗрение:
        if настройки_ии and настройки_ии.get("модель_зрения"):
            try:
                from . import ai
                картинки = smeta.страницы_картинками(имя, данные)
                return ai.прочитать_картинки(настройки_ии, картинки, _ЗАДАНИЕ_ЗРЕНИЯ)[:30000], "прочитано моделью зрения"
            except Exception as ошибка:
                журнал.warning("Скан «%s» не прочитан моделью: %s", имя, ошибка)
                return "", "скан или фото: текст не прочитан"
        return "", "скан или фото: текст не прочитан (выберите модель для сканов в настройках ИИ)"
    except Exception as ошибка:
        return "", f"текст не прочитан ({str(ошибка)[:60]})"


def опознать(база, настройки_ии: dict | None, имя: str, данные: bytes) -> dict:
    текст, пометка = _прочитать(имя, данные, настройки_ии)
    итог = {"вид": _вид_по_тексту(имя, текст), "номер": _номер_из_текста(текст[:3000]),
            "дата": _дата_из_текста(текст[:3000]), "сумма": _сумма_из_текста(текст), "описание": "",
            "контрагент": "", "текст": текст, "пометка": пометка}
    if настройки_ии and текст:
        from . import ai
        if ai.подключён(настройки_ии):
            try:
                ответ = ai._задание(_СИСТЕМА_ОПОЗНАНИЯ,
                                    {"файл": имя, "текст": текст[:6000], "виды": list(ВИДЫ),
                                     "известные_контрагенты": [к["название"] for к in контрагенты(база)][:100]},
                                    настройки_ии, 500)
                р = json.loads(ai._ОБЪЕКТ.search(ответ).group(0))
                if р.get("вид") in ВИДЫ:
                    итог["вид"] = р["вид"]
                if str(р.get("номер") or "").strip():
                    итог["номер"] = str(р["номер"]).strip()[:40]
                if re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(р.get("дата") or "")):
                    итог["дата"] = р["дата"]
                сум = р.get("сумма")
                if isinstance(сум, (int, float)) and сум > 0:
                    итог["сумма"] = float(сум)
                итог["контрагент"] = str(р.get("контрагент") or "").strip()[:120]
                итог["описание"] = " ".join(str(р.get("описание") or "").split())[:300]
            except Exception:
                журнал.warning("ИИ не опознал документ «%s», беру по признакам", имя)
    if not итог["описание"]:
        итог["описание"] = (f"{итог['вид']}" + (f" №{итог['номер']}" if итог["номер"] else "") +
                            (f" на {_деньги(итог['сумма'])} ₽" if итог["сумма"] else "") + (f" — {пометка}" if пометка else ""))
    return итог


