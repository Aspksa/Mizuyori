def искать(база, запрос: str, лимит: int = 8) -> list[dict]:
    слова = [с for с in re.split(r"[^0-9a-zа-я№]+", (запрос or "").lower().replace("ё", "е")) if len(с) > 2]
    if not слова:
        return []
    with база.соединение() as связь:
        строки = связь.execute(_ВЫБОРКА.replace("ф.описание,", "ф.описание, ф.текст,")).fetchall()
    оценки = []
    for р in строки:
        р = dict(р)
        поля = " ".join(str(р.get(п) or "") for п in ("имя", "вид", "контрагент", "номер", "описание", "раздел")).lower().replace("ё", "е")
        текст = (р.get("текст") or "").lower().replace("ё", "е")
        очки = sum(3 for с in слова if с in поля) + sum(1 for с in слова if с in текст)
        if очки:
            оценки.append((очки, р))
    оценки.sort(key=lambda ц: -ц[0])
    return [_с_местом({к: v for к, v in р.items() if к != "текст"}) for _, р in оценки[:лимит]]


def _строка_файла(ф: dict) -> str:
    return (f"{ф['где']} / {ф['имя']} — {ф['вид']}" + (f" №{ф['номер']}" if ф["номер"] else "") +
            (f" от {ф['дата']}" if ф["дата"] else "") + (f", {ф['сумма']:,.0f} ₽".replace(",", " ") if ф["сумма"] else "") +
            (f". {ф['описание']}" if ф["описание"] else "") + ("" if ф["на_диске"] else " [ФАЙЛА НЕТ НА ДИСКЕ]"))


_СЛОВА_АРХИВА = ("где лежит", "где находится", "найди", "найти", "файл", "документ", "папк", "архив", "комплект", "согласован",
                 "контрагент", "поставщик", "подрядчик", "реквизит", "договор с", "договор №", "договоры", "оферт", "переименов",
                 "что приложено", "чего не хватает", "что не хватает")


def для_вопроса(база, текст: str) -> tuple[str, str]:
    """Справка по архиву для ответа в чате: ('', '') если вопрос не про документы."""
    низ = " " + (текст or "").lower().replace("ё", "е") + " "
    if not any(с in низ for с in _СЛОВА_АРХИВА):
        return "", ""
    список = контрагенты(база)
    названы = [к for к in список if len(_норм_название(к["название"])) >= 3 and f" {_норм_название(к['название'])} " in
               " " + _норм_название(текст) + " "]
    строки = [f"В архиве контрагентов: {len(список)}, файлов: {дерево(база)['всего_файлов']}. "
              "Структура: Контрагент → Договор → раздел (" + ", ".join(РАЗДЕЛЫ) + ")."]
    for к in названы[:2]:
        строки.append(f"Контрагент «{к['название']}»: ИНН {к['инн'] or 'не указан'}, КПП {к['кпп'] or '—'}, адрес {к['адрес'] or '—'}, "
                      f"тел. {к['телефон'] or '—'}, почта {к['email'] or '—'}, контакт {к['контакт'] or '—'}, банк {к['банк'] or '—'}.")
        with база.соединение() as связь:
            договоры = [dict(р) for р in связь.execute("SELECT * FROM раб_договоры WHERE контрагент_id = ?", (к["id"],))]
        for д in договоры[:6]:
            км = комплект(база, д["id"])
            строки.append(f"- {_папка_договора(д)}" + (f", {д['сумма']:,.0f} ₽".replace(",", " ") if д["сумма"] else "") +
                          f"; закупка: {км['статус'] or 'не начата'}; " +
                          ("комплект полный" if км["готов"] else "не хватает: " + ", ".join(км["не_хватает"])))
        for ф in файлы(база, контрагент_id=к["id"])[:10]:
            строки.append("  файл: " + _строка_файла(ф))
    попадания = искать(база, текст, 6)
    if попадания and not названы:
        строки.append("Подходящие файлы:")
        строки += ["- " + _строка_файла(ф) for ф in попадания]
    elif not названы and not попадания:
        строки.append("По этому запросу ничего не найдено.")
    блок = ("Архив документов (отвечай только по этой справке; если чего-то в ней нет — так и скажи; "
            "пути называй как написано):\n" + "\n".join(строки))
    if any(с in низ for с in ("комплект", "согласован", "не хватает", "закуп")):
        агент = "снабженец"
    elif any(с in низ for с in ("контрагент", "поставщик", "подрядчик", "реквизит", "инн")):
        агент = "контрагенты"
    else:
        агент = "архивариус"
    return блок, агент


