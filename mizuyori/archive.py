# ---- Мелочи ---------------------------------------------------------------------------

def _норм_название(название: str) -> str:
    н = (название or "").lower().replace("ё", "е")
    н = re.sub(r"[«»\"'`().,]", " ", н)
    слова = [с for с in re.split(r"[^0-9a-zа-я]+", н) if с and с not in _ФОРМЫ]
    return " ".join(слова)


def _безопасно(текст: str, длина: int = 60) -> str:
    т = re.sub(r'[\\/:*?"<>|\r\n\t]', "", текст or "").strip(" .")
    return re.sub(r"\s+", " ", т)[:длина].strip(" .") or "без названия"


def _короткое(название: str, длина: int = 22) -> str:
    н = re.sub(r"[«»\"'`]", "", название or "")
    слова = [с for с in н.split() if с.lower().strip(".") not in _ФОРМЫ]
    return _безопасно("-".join(слова) or название, длина).replace(" ", "-")


def _деньги(ч) -> str:
    return f"{round(ч):d}" if ч is not None else ""


def имя_по_схеме(дата_: str | None, вид: str, контрагент: str, номер: str, сумма, расширение: str) -> str:
    """Дата_Вид_Контрагент_№_Сумма.расширение — части, которых нет, пропускаются."""
    части = [дата_ or date.today().isoformat(), вид.replace(" ", "-")]
    if контрагент:
        части.append(_короткое(контрагент))
    if номер:
        части.append("№" + _безопасно(номер, 20).replace(" ", ""))
    if сумма is not None:
        части.append(_деньги(сумма))
    return "_".join(части) + (("." + расширение.lower().lstrip(".")) if расширение else "")


def _уникальное(папка: Path, имя: str) -> str:
    if not (папка / имя).exists():
        return имя
    основа, точка, расш = имя.rpartition(".")
    if not точка:
        основа, расш = имя, ""
    n = 2
    while (папка / f"{основа}_{n}{'.' + расш if расш else ''}").exists():
        n += 1
    return f"{основа}_{n}{'.' + расш if расш else ''}"


def _расширение(имя: str) -> str:
    return имя.rsplit(".", 1)[-1].lower() if "." in имя else ""


