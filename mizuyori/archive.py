def _вид_по_тексту(имя: str, текст: str) -> str:
    для_имени = " " + имя.lower().replace("ё", "е").replace("_", " ") + " "
    для_текста = " " + (текст or "")[:1500].lower().replace("ё", "е") + " "
    for проход in (для_имени, для_текста):
        for вид, признаки in _ПРАВИЛА:
            if any(п.replace("ё", "е") in проход for п in признаки):
                return вид
    return "Прочее"


def _дата_из_текста(текст: str) -> str | None:
    м = re.search(r"(?<!\d)(\d{1,2})\.(\d{1,2})\.(\d{4})(?!\d)", текст or "")
    if м:
        try:
            return date(int(м[3]), int(м[2]), int(м[1])).isoformat()
        except ValueError:
            pass
    м = re.search(r"[«\"]?(\d{1,2})[»\"]?\s+(" + "|".join(_МЕСЯЦЫ) + r")\s+(\d{4})", (текст or "").lower())
    if м:
        try:
            return date(int(м[3]), _МЕСЯЦЫ[м[2]], int(м[1])).isoformat()
        except ValueError:
            pass
    return None


def _число(т: str) -> float | None:
    т = re.sub(r"[\s ]", "", т or "").replace(",", ".")
    try:
        return float(т)
    except ValueError:
        return None


def _сумма_из_текста(текст: str) -> float | None:
    найдено = re.findall(r"(?:итого|всего к оплате|всего|на сумму|стоимость работ|цена договора)[^0-9\n]{0,40}"
                         r"([0-9][0-9\s ]*(?:[.,][0-9]{1,2})?)", (текст or "").lower())
    значения = [з for з in (_число(н) for н in найдено) if з and з > 0]
    return значения[-1] if значения else None


def _номер_из_текста(текст: str) -> str:
    м = re.search(r"№\s*([A-Za-zА-Яа-я0-9][A-Za-zА-Яа-я0-9\-/_.]*)", текст or "")
    return м[1].rstrip(".-/") if м else ""


