def файлы(база, контрагент_id: int | None = None, договор_id: int | None = None, без_контрагента: bool = False) -> list[dict]:
    условия, параметры = [], []
    if без_контрагента:
        условия.append("ф.контрагент_id IS NULL")
    if контрагент_id:
        условия.append("ф.контрагент_id = ?"); параметры.append(контрагент_id)
    if договор_id == -1:
        условия.append("ф.договор_id IS NULL")
    elif договор_id:
        условия.append("ф.договор_id = ?"); параметры.append(договор_id)
    with база.соединение() as связь:
        строки = связь.execute(_ВЫБОРКА + (" WHERE " + " AND ".join(условия) if условия else "") + " ORDER BY ф.раздел, ф.дата DESC, ф.id DESC",
                               параметры).fetchall()
    return [_с_местом(dict(р)) for р in строки]


def комплект(база, договор_id: int) -> dict:
    д = _договор(база, договор_id)
    if not д:
        raise ОшибкаАрхива("Такого договора нет.")
    список = файлы(база, договор_id=договор_id)
    нужен_дефект = "ремонт" in " ".join([д.get("предмет") or ""] + [ф["имя"] + " " + ф["описание"] for ф in список]).lower()
    пункты = []
    for название, виды in КОМПЛЕКТ:
        есть = [ф for ф in список if ф["вид"] in виды]
        обязателен = название != "Дефектовая ведомость" or нужен_дефект
        пункты.append({"название": название, "есть": bool(есть), "обязателен": обязателен,
                       "файлы": [{"id": ф["id"], "имя": ф["имя"]} for ф in есть]})
    прочее = [{"id": ф["id"], "имя": ф["имя"], "вид": ф["вид"]} for ф in список
              if ф["раздел"] == "Закупка (согласование)" and ф["вид"] not in sum((list(в) for _, в in КОМПЛЕКТ), [])]
    не_хватает = [п["название"] for п in пункты if п["обязателен"] and not п["есть"]]
    return {"договор_id": договор_id, "пункты": пункты, "приложено_вручную": прочее, "не_хватает": не_хватает,
            "готов": not не_хватает, "статус": д.get("закупка") or ""}


