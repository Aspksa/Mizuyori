def найти_контрагента(база, текст: str = "", имя_файла: str = "", название: str = "") -> dict | None:
    """По ИНН из текста, затем по названию (в тексте, названии файла или явном названии)."""
    список = контрагенты(база)
    if not список:
        return None
    инны = set(re.findall(r"(?<!\d)(\d{10}|\d{12})(?!\d)", текст or ""))
    # ИНН берём только рядом со словом «ИНН», чтобы не поймать номер счёта
    рядом = set(re.findall(r"инн[^0-9]{0,12}(\d{10}|\d{12})", (текст or "").lower()))
    for к in список:
        if к["инн"] and к["инн"] in (рядом or инны):
            return к
    искомое = _норм_название(название)
    если_точно = [к for к in список if искомое and _норм_название(к["название"]) == искомое]
    if если_точно:
        return если_точно[0]
    поля = " " + _норм_название((текст or "")[:6000] + " " + имя_файла) + " "
    лучший = None
    for к in список:
        н = _норм_название(к["название"])
        if len(н) >= 3 and f" {н} " in поля and (лучший is None or len(н) > len(_норм_название(лучший["название"]))):
            лучший = к
    if not лучший and искомое:
        for к in список:
            н = _норм_название(к["название"])
            if len(н) >= 3 and (н in искомое or искомое in н):
                return к
    return лучший


def привязать_договоры(база) -> int:
    """Договоры без контрагента получают его по ИНН или названию."""
    привязано = 0
    список = контрагенты(база)
    with база.соединение() as связь:
        строки = связь.execute("SELECT id, контрагент, инн FROM раб_договоры WHERE контрагент_id IS NULL "
                               "OR контрагент_id NOT IN (SELECT id FROM раб_контрагенты)").fetchall()
        for д in строки:
            найден = next((к for к in список if д["инн"] and к["инн"] == д["инн"]), None)
            if not найден:
                н = _норм_название(д["контрагент"])
                найден = next((к for к in список if н and _норм_название(к["название"]) == н), None)
            if найден:
                связь.execute("UPDATE раб_договоры SET контрагент_id = ? WHERE id = ?", (найден["id"], д["id"]))
                привязано += 1
    return привязано


