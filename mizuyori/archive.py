def принять_документы_сметы(база, с: dict, итог: dict) -> list[str]:
    """Подтверждённая смета и черновики агентов ложатся в архив: контрагент → договор (на согласовании) → раздел.
    Если контрагента нет в базе — в «Входящие», а после добавления карточки они разложатся сами."""
    from . import documents
    сообщения = []
    название = (с.get("исполнитель") or "").strip()
    к = найти_контрагента(база, "", "", название) if название else None
    сумма = documents.итог_сметы(с)
    договор = None
    if к:
        with база.соединение() as связь:
            р = связь.execute("SELECT * FROM раб_договоры WHERE смета_id = ?", (с["id"],)).fetchone()
        договор = dict(р) if р else создать_договор(
            база, к["id"], "договор" if итог.get("договор") else "оферта", "", date.today().isoformat(),
            сумма, f"Ремонт: {с.get('объект') or 'по смете'}", смета_id=с["id"])
    положено = 0
    пары = []
    with база.соединение() as связь:
        р_ = связь.execute("SELECT файл FROM раб_сметы WHERE id = ?", (с["id"],)).fetchone()
    исходник = Path(р_[0]) if р_ and р_[0] else None
    if исходник and исходник.is_file():
        пары.append((исходник.name, исходник.read_bytes(), "Смета"))
    for д in итог.get("документы", []):
        п = documents.ПАПКА_ДОКУМЕНТОВ / д["файл"]
        вид = next((в for ключ, в in _ВИД_ПО_НАЗВАНИЮ if ключ in д["название"].lower()), "Прочее")
        if п.is_file():
            пары.append((п.name, п.read_bytes(), вид))
    for имя, данные, вид in пары:
        try:
            _записать(база, имя_исх=имя, данные=данные, контрагент_=к, договор=договор, вид=вид, раздел=None,
                      номер=str(с.get("номер") or ""), дата_=date.today().isoformat(), сумма=сумма,
                      описание=f"{вид} по смете «{с.get('объект') or с['имя']}»", текст="")
            положено += 1
        except ОшибкаАрхива:
            continue
        except Exception:
            журнал.exception("Не удалось положить «%s» в архив", имя)
    if положено:
        if к:
            км = комплект(база, договор["id"])
            сообщения.append(f"📁 В архив ({к['название']} → {_папка_договора(договор)}) положено файлов: {положено}. "
                             + ("Комплект закупки полный." if км["готов"] else "Для согласования не хватает: " + ", ".join(км["не_хватает"]) + "."))
        else:
            сообщения.append(f"📁 Файлов положено во «{ВХОДЯЩИЕ}»: {положено}. Контрагента «{название or 'не указан'}» нет в базе — "
                             "добавьте его карточку в «Архив», и я разложу документы по папкам.")
    return сообщения


def комплект_zip(база, договор_id: int) -> tuple[str, bytes]:
    """Комплект на согласование одним архивом: файлы договора в папках разделов и «Опись.txt» с тем, чего не хватает."""
    import io
    import zipfile
    д = _договор(база, договор_id)
    км = комплект(база, договор_id)
    список = файлы(база, договор_id=договор_id)
    строки = [f"Комплект на согласование закупки: {_папка_договора(д)} — {д['контрагент']}",
              f"Статус закупки: {км['статус'] or 'не начата'}", f"Дата: {date.today():%d.%m.%Y}", ""]
    for п in км["пункты"]:
        строки.append(f"[{'x' if п['есть'] else ('-' if not п['обязателен'] else ' ')}] {п['название']}"
                      + (": " + ", ".join(ф["имя"] for ф in п["файлы"]) if п["файлы"] else ""))
    if км["приложено_вручную"]:
        строки += ["", "Приложено вручную: " + ", ".join(ф["имя"] for ф in км["приложено_вручную"])]
    строки += ["", "Всё нужное есть." if км["готов"] else "НЕ ХВАТАЕТ: " + ", ".join(км["не_хватает"])]
    буфер = io.BytesIO()
    with zipfile.ZipFile(буфер, "w", zipfile.ZIP_DEFLATED) as z:
        z.writestr("Опись.txt", "\n".join(строки))
        for ф in список:
            п = ПАПКА / ф["путь"]
            if п.is_file():
                z.write(п, f"{ф['раздел']}/{ф['имя']}")
    return _безопасно(f"Комплект {_папка_договора(д)} {_короткое(д['контрагент'])}", 80) + ".zip", буфер.getvalue()
