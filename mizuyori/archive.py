def _путь_файла(база, контрагент_: dict | None, договор: dict | None, раздел: str, имя: str) -> Path:
    if not контрагент_:
        return Path(ВХОДЯЩИЕ) / имя
    return Path(_безопасно(контрагент_["название"], 80)) / _папка_договора(договор) / раздел / имя


def _записать(база, *, имя_исх: str, данные: bytes, контрагент_: dict | None, договор: dict | None, вид: str, раздел: str | None,
              номер: str, дата_: str | None, сумма, описание: str, текст: str, по_схеме: bool = True) -> dict:
    хеш = hashlib.sha256(данные).hexdigest()
    with база.соединение() as связь:
        копия = связь.execute("SELECT id, имя FROM раб_файлы WHERE хеш = ?", (хеш,)).fetchone()
    if копия:
        raise ОшибкаАрхива(f"Такой файл уже есть в архиве: «{копия['имя']}».")
    раздел = раздел if раздел in РАЗДЕЛЫ else ВИДЫ.get(вид, "Прочее")
    расш = _расширение(имя_исх)
    имя = (имя_по_схеме(дата_, вид, контрагент_["название"] if контрагент_ else "", номер, сумма, расш)
           if по_схеме else _безопасно(имя_исх, 120))
    относительный = _путь_файла(база, контрагент_, договор, раздел, имя)
    папка = ПАПКА / относительный.parent
    папка.mkdir(parents=True, exist_ok=True)
    имя = _уникальное(папка, имя)
    относительный = относительный.with_name(имя)
    (ПАПКА / относительный).write_bytes(данные)
    with база.соединение() as связь:
        id_ = связь.execute(
            "INSERT INTO раб_файлы (контрагент_id, договор_id, раздел, вид, имя, исходное_имя, путь, дата, номер, сумма, описание, "
            "текст, размер, хеш, по_схеме) VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
            (контрагент_["id"] if контрагент_ else None, договор["id"] if договор else None, раздел, вид, имя, имя_исх,
             относительный.as_posix(), дата_, номер, сумма, описание, текст[:30000], len(данные), хеш, int(по_схеме))).lastrowid
    return файл(база, id_)


def принять_файл(база, настройки_ии: dict | None, имя: str, данные: bytes, контрагент_id: int | None = None,
                 договор_id: int | None = None, раздел: str | None = None, вид: str | None = None,
                 переименовать: bool = True) -> dict:
    """Загрузка файла: опознать → найти контрагента → положить в папку → переименовать → записать в индекс."""
    if not данные:
        raise ОшибкаАрхива("Файл пустой.")
    инфо = опознать(база, настройки_ии, имя, данные)
    договор = _договор(база, договор_id)
    к = None
    if контрагент_id:
        к = контрагент(база, контрагент_id)
    elif договор and договор.get("контрагент_id"):
        к = контрагент(база, договор["контрагент_id"])
    else:
        к = найти_контрагента(база, инфо["текст"], имя, инфо["контрагент"])
    итоговый_вид = вид if вид in ВИДЫ else инфо["вид"]
    создан_договор = False
    if к and not договор:
        # сам документ-договор: найти запись по номеру или завести
        if итоговый_вид in ВИДЫ_ДОГОВОРА:
            with база.соединение() as связь:
                р = связь.execute("SELECT * FROM раб_договоры WHERE контрагент_id = ? AND номер = ? AND номер != ''",
                                  (к["id"], инфо["номер"])).fetchone() if инфо["номер"] else None
            договор = dict(р) if р else создать_договор(база, к["id"], итоговый_вид, инфо["номер"], инфо["дата"], инфо["сумма"],
                                                         инфо["описание"][:200])
            создан_договор = not р
    запись = _записать(база, имя_исх=имя, данные=данные, контрагент_=к, договор=договор, вид=итоговый_вид, раздел=раздел,
                       номер=инфо["номер"], дата_=инфо["дата"], сумма=инфо["сумма"], описание=инфо["описание"],
                       текст=инфо["текст"], по_схеме=переименовать)
    запись["создан_договор"] = создан_договор
    запись["контрагент_найден"] = bool(к)
    запись["подсказка_контрагента"] = инфо["контрагент"]
    return запись


def файл(база, id_: int) -> dict:
    with база.соединение() as связь:
        р = связь.execute(_ВЫБОРКА + " WHERE ф.id = ?", (id_,)).fetchone()
    if not р:
        raise ОшибкаАрхива("Такого файла нет.")
    return _с_местом(dict(р))


_ВЫБОРКА = ("SELECT ф.id, ф.контрагент_id, ф.договор_id, ф.раздел, ф.вид, ф.имя, ф.исходное_имя, ф.путь, ф.дата, ф.номер, ф.сумма, "
            "ф.описание, ф.размер, ф.по_схеме, ф.создано, к.название AS контрагент, "
            "д.номер AS договор_номер, д.вид AS договор_вид, д.дата AS договор_дата FROM раб_файлы ф "
            "LEFT JOIN раб_контрагенты к ON к.id = ф.контрагент_id LEFT JOIN раб_договоры д ON д.id = ф.договор_id")


def _с_местом(р: dict) -> dict:
    р["на_диске"] = (ПАПКА / р["путь"]).is_file()
    р["где"] = " / ".join(Path(р["путь"]).parent.parts) or "корень"
    return р


def путь_на_диске(база, id_: int) -> Path:
    ф = файл(база, id_)
    п = ПАПКА / ф["путь"]
    if not п.is_file():
        raise ОшибкаАрхива("Файл пропал с диска.")
    return п


def удалить_файл(база, id_: int) -> None:
    ф = файл(база, id_)
    п = ПАПКА / ф["путь"]
    if п.is_file():
        п.unlink()
    with база.соединение() as связь:
        связь.execute("DELETE FROM раб_файлы WHERE id = ?", (id_,))
    _убрать_пустые(п.parent)


def _убрать_пустые(папка: Path) -> None:
    try:
        while папка != ПАПКА and папка.is_dir() and not any(папка.iterdir()):
            папка.rmdir()
            папка = папка.parent
    except OSError:
        pass


def _переложить(база, f: dict, *, контрагент_id, договор_id, раздел: str, имя: str | None = None, вид: str | None = None,
                по_схеме: int | None = None) -> dict:
    к = контрагент(база, контрагент_id) if контрагент_id else None
    д = _договор(база, договор_id)
    if д and к and д.get("контрагент_id") not in (None, к["id"]):
        raise ОшибкаАрхива("Этот договор принадлежит другому контрагенту.")
    ст = ПАПКА / f["путь"]
    новое_имя = имя or f["имя"]
    относительный = _путь_файла(база, к, д, раздел, новое_имя)
    цель_папка = ПАПКА / относительный.parent
    цель_папка.mkdir(parents=True, exist_ok=True)
    if (ПАПКА / относительный) != ст:
        новое_имя = _уникальное(цель_папка, новое_имя)
        относительный = относительный.with_name(новое_имя)
        if ст.is_file():
            shutil.move(str(ст), str(ПАПКА / относительный))
    with база.соединение() as связь:
        связь.execute("UPDATE раб_файлы SET контрагент_id = ?, договор_id = ?, раздел = ?, имя = ?, путь = ?, вид = COALESCE(?, вид), "
                      "по_схеме = COALESCE(?, по_схеме) WHERE id = ?",
                      (к["id"] if к else None, д["id"] if д else None, раздел, новое_имя, относительный.as_posix(), вид, по_схеме, f["id"]))
    if ст.parent != ПАПКА / относительный.parent:
        _убрать_пустые(ст.parent)
    return файл(база, f["id"])


def изменить_файл(база, id_: int, данные: dict) -> dict:
    """Переименовать и/или перенести: контрагент_id, договор_id, раздел, вид, имя, номер, дата, сумма, описание."""
    f = файл(база, id_)
    контрагент_id = данные["контрагент_id"] if "контрагент_id" in данные else f["контрагент_id"]
    договор_id = данные["договор_id"] if "договор_id" in данные else f["договор_id"]
    if "контрагент_id" in данные and "договор_id" not in данные and контрагент_id != f["контрагент_id"]:
        договор_id = None
    вид = данные.get("вид") if данные.get("вид") in ВИДЫ else None
    раздел = данные.get("раздел") if данные.get("раздел") in РАЗДЕЛЫ else (ВИДЫ[вид] if вид else f["раздел"])
    поля, значения = [], []
    for к_, тип in (("номер", str), ("дата", str), ("сумма", float), ("описание", str)):
        if к_ in данные:
            з = данные[к_]
            if тип is float:
                з = _число(str(з)) if з not in (None, "") else None
            elif з in ("", None):
                з = "" if к_ != "дата" else None
            else:
                з = str(з).strip()[:300]
            поля.append(f"{к_} = ?"); значения.append(з)
    if поля:
        with база.соединение() as связь:
            связь.execute(f"UPDATE раб_файлы SET {', '.join(поля)} WHERE id = ?", значения + [id_])
    имя, по_схеме = None, None
    if данные.get("имя"):
        расш = _расширение(f["имя"])
        имя = _безопасно(str(данные["имя"]), 120)
        if расш and not имя.lower().endswith("." + расш):
            имя += "." + расш
        по_схеме = 0
    return _переложить(база, файл(база, id_), контрагент_id=контрагент_id, договор_id=договор_id, раздел=раздел, имя=имя, вид=вид,
                       по_схеме=по_схеме)


def переименовать_по_схеме(база, id_: int) -> dict:
    f = файл(база, id_)
    новое = имя_по_схеме(f["дата"], f["вид"], f["контрагент"] or "", f["номер"], f["сумма"], _расширение(f["имя"]))
    return _переложить(база, f, контрагент_id=f["контрагент_id"], договор_id=f["договор_id"], раздел=f["раздел"], имя=новое, по_схеме=1)


def _переложить_папку_контрагента(база, id_: int) -> None:
    with база.соединение() as связь:
        ид = [р[0] for р in связь.execute("SELECT id FROM раб_файлы WHERE контрагент_id = ?", (id_,))]
    for i in ид:
        f = файл(база, i)
        try:
            _переложить(база, f, контрагент_id=f["контрагент_id"], договор_id=f["договор_id"], раздел=f["раздел"],
                        имя=переименовать_имя(f), по_схеме=f["по_схеме"])
        except Exception:
            журнал.exception("Не удалось переложить файл %s", i)


def переименовать_имя(f: dict) -> str:
    if f["по_схеме"]:
        return имя_по_схеме(f["дата"], f["вид"], f["контрагент"] or "", f["номер"], f["сумма"], _расширение(f["имя"]))
    return f["имя"]


def разобрать_входящие(база, настройки_ии: dict | None = None) -> int:
    """Файлы из «Входящих» получают контрагента, если его карточку уже завели."""
    with база.соединение() as связь:
        ид = [р[0] for р in связь.execute("SELECT id FROM раб_файлы WHERE контрагент_id IS NULL")]
    разложено = 0
    for i in ид:
        f = файл(база, i)
        with база.соединение() as связь:
            текст = связь.execute("SELECT текст FROM раб_файлы WHERE id = ?", (i,)).fetchone()[0]
        к = найти_контрагента(база, текст, f["исходное_имя"])
        if not к:
            continue
        договор_id = None
        try:
            изменить_файл(база, i, {"контрагент_id": к["id"], "договор_id": договор_id,
                                    "имя": None, "вид": f["вид"]})
            if f["по_схеме"]:
                переименовать_по_схеме(база, i)
            разложено += 1
        except Exception:
            журнал.exception("Не удалось разложить входящий файл %s", i)
    return разложено


