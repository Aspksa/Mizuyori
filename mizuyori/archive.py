    без_контрагента = [{"id": д["id"], "название": _папка_договора(д), "контрагент": д["контрагент"]} for д in договоры
                       if not д["контрагент_id"]]
    return {"контрагенты": итог, "входящих": входящих, "всего_файлов": всего, "договоры_без_контрагента": без_контрагента,
            "разделы": РАЗДЕЛЫ, "виды": list(ВИДЫ), "статусы_закупки": СТАТУСЫ_ЗАКУПКИ}


