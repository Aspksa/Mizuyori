"""Статистика и контроль ГСМ за период: куда уходит топливо и где цифры не сходятся.

Это статистические признаки для проверки, а не доказательство: перерасход бывает из-за холодного пуска,
простоя с работающим двигателем, неточной нормы или ошибки в показаниях одометра. Сначала смотрим
путевые листы и чеки, потом делаем выводы о людях.
"""
from __future__ import annotations

import math
import re
import statistics
from collections import Counter, defaultdict
from datetime import date, datetime, timedelta

ДОПУСК = 0.05                         # допустимое отклонение факта от нормы
НОЧЬ = set(range(23, 24)) | set(range(0, 5))
ОТСУТСТВИЕ = {"ОТ": "отпуск", "Б": "больничный", "ДО": "отпуск без сохранения"}
РАБОТА_В_ВЫХОДНОЙ = {"РВ", "К"}
ДНИ = ["пн", "вт", "ср", "чт", "пт", "сб", "вс"]

ПРИЗНАКИ = {
    "перерасход": "Перерасход к норме",
    "без_пробега": "Топливо при нулевом пробеге",
    "больше_бака": "Заправка больше бака",
    "отпуск": "Заправка в отпуске или на больничном",
    "не_то_топливо": "Не то топливо",
    "рядом": "Две заправки подряд за короткое время",
    "маршрут": "Невозможный маршрут",
    "ночью": "Ночные заправки",
    "выходные": "Заправки в выходные и праздники",
    "редкий_пробег": "Много заправок на малый пробег",
    "выбивается": "Выбивается из парка",
    "растёт": "Перерасход растёт",
}
БАЛЛЫ = {"перерасход": (1, 2, 3), "без_пробега": 2, "больше_бака": 3, "отпуск": 3, "не_то_топливо": 3, "рядом": 2,
         "маршрут": 3, "ночью": 1, "выходные": 1, "редкий_пробег": 1, "выбивается": 1, "растёт": 1}
СИЛЬНЫЕ = {"больше_бака", "отпуск", "не_то_топливо", "рядом", "маршрут", "без_пробега"}   # их литры считаются «подозрительными»


def _окр(з, знаков=2):
    return None if з is None else round(з, знаков)


def _азс(название: str) -> str:
    return re.sub(r"\s+", " ", (название or "").replace(" ,", ",")).strip() or "—"


def _город(азс: str) -> str:
    м = re.search(r"(?:^|[\s,])(?:г|с|п|пгт|ст|д)\.\s*([А-ЯЁA-Z][\w\-]+)", азс or "")
    return м.group(1).casefold() if м else ""


def _момент(о: dict) -> datetime | None:
    try:
        return datetime.fromisoformat(f"{о['дата']}T{(о['время'] or '').strip()[:8] or '00:00:00'}")
    except ValueError:
        return None


def _час(о: dict) -> int | None:
    м = re.match(r"(\d{1,2}):", (о["время"] or "").strip())
    return int(м.group(1)) if м and 0 <= int(м.group(1)) < 24 else None


def _класс_топлива(т: str) -> str:
    """бензин / дизель / газ — для проверки «не то топливо»."""
    т = (т or "").upper()
    if re.search(r"ДТ|ДИЗЕЛ", т):
        return "дизель"
    if re.search(r"АИ|БЕНЗИН", т):
        return "бензин"
    if re.search(r"ГАЗ|ПРОПАН|СУГ", т):
        return "газ"
    return ""


def _регрессия(точки: list[tuple[float, float]]) -> dict | None:
    """Литры = a·км + b по месяцам. a·100 — реальный расход на 100 км, b — литры, не связанные с пробегом."""
    if len(точки) < 3:
        return None
    xs, ys = [т[0] for т in точки], [т[1] for т in точки]
    mx, my = statistics.fmean(xs), statistics.fmean(ys)
    sxx = sum((x - mx) ** 2 for x in xs)
    if sxx == 0:
        return None
    sxy = sum((x - mx) * (y - my) for x, y in точки)
    a = sxy / sxx
    b = my - a * mx
    syy = sum((y - my) ** 2 for y in ys)
    r2 = (sxy * sxy) / (sxx * syy) if syy else 1.0
    return {"расход_100": _окр(a * 100), "свободно_л": _окр(b, 1), "r2": _окр(r2, 3), "точек": len(точки)}


def _тренд(ряд: list[float]) -> float:
    """Наклон прямой по точкам (п.п. в месяц)."""
    if len(ряд) < 2:
        return 0.0
    xs = list(range(len(ряд)))
    mx, my = statistics.fmean(xs), statistics.fmean(ряд)
    return sum((x - mx) * (y - my) for x, y in zip(xs, ряд)) / sum((x - mx) ** 2 for x in xs)


def статистика(база, с: str, по: str) -> dict:
    from . import work as w

    месяцы = w._месяцы_между(с, по)
    первый, последний = w._дни_месяца(месяцы[0])[0], w._дни_месяца(месяцы[-1])[-1]
    for м in месяцы:
        w.перенести_путевые(база, м)
    операции = [о for о in w._разнести_операции(база, первый, последний) if (о["количество"] or 0) > 0]
    машины, люди = w._все(база, "раб_автомобили"), w._все(база, "раб_сотрудники")
    помесячно = {м: {р["автомобиль_id"]: р for р in w._посчитать_месяц(база, м)} for м in месяцы}

    # табель: кто в какие дни был в отпуске, на больничном, работал в выходной
    with база.соединение() as связь:
        табель = {(р[0], р[1]): р[2] for р in связь.execute(
            "SELECT сотрудник_id, день, код FROM раб_табель WHERE день BETWEEN ? AND ?", (первый.isoformat(), последний.isoformat()))}
        периоды = [dict(р) for р in связь.execute("SELECT сотрудник_id, код, с, по FROM раб_периоды WHERE с <= ? AND по >= ?",
                                                  (последний.isoformat(), первый.isoformat()))]

    def отсутствие(сотрудник, день: str) -> str | None:
        к = табель.get((сотрудник, день))
        if к in ОТСУТСТВИЕ:
            return ОТСУТСТВИЕ[к]
        for п in периоды:
            if п["сотрудник_id"] == сотрудник and п["код"] in ОТСУТСТВИЕ and п["с"] <= день <= п["по"]:
                return ОТСУТСТВИЕ[п["код"]]
        return None

    def имя_сотрудника(сотрудник_id):
        return w.фио(люди.get(сотрудник_id)) or "—"

    def имя_карты(н):
        return f"карта …{''.join(ч for ч in н if ч.isdigit())[-4:]}"

    # ---- средние цены по видам топлива (для сравнения АЗС и оценки ₽) ------------------------
    литры_по_виду, сумма_по_виду = defaultdict(float), defaultdict(float)
    for о in операции:
        вид = w.вид_топлива(о["топливо"])
        литры_по_виду[вид] += о["количество"]
        сумма_по_виду[вид] += о["сумма"] or 0
    цена_вида = {в: сумма_по_виду[в] / литры_по_виду[в] for в in литры_по_виду if литры_по_виду[в]}
    общая_цена = (sum(сумма_по_виду.values()) / sum(литры_по_виду.values())) if литры_по_виду else 0.0

    # ---- итоги -----------------------------------------------------------------------------
    литров = sum(о["количество"] for о in операции)
    сумма = sum(о["сумма"] or 0 for о in операции)
    дни_заправок = {о["дата"] for о in операции}
    итого = {"операций": len(операции), "литров": _окр(литров), "сумма": _окр(сумма), "цена": _окр(общая_цена),
             "заправка_литров": _окр(литров / len(операции), 1) if операции else None,
             "карт": len({о["карта"] for о in операции}), "азс": len({_азс(о["азс"]) for о in операции}),
             "дней": len(дни_заправок), "дней_в_периоде": (последний - первый).days + 1}

    # ---- по машинам ------------------------------------------------------------------------
    по_авто = defaultdict(list)
    for о in операции:
        if о["авто_id"]:
            по_авто[о["авто_id"]].append(о)

    карточки, контроль, откл_парка = [], [], []
    for авто_id, а in sorted(машины.items(), key=lambda кв: (кв[1]["марка"], кв[1]["модель"])):
        ops = по_авто.get(авто_id, [])
        ряды = [(м, помесячно[м][авто_id]) for м in месяцы if авто_id in помесячно[м] and w._заполнен(помесячно[м][авто_id])]
        пробег = sum(р["пробег"] or 0 for _, р in ряды)
        с_разницей = [(м, р) for м, р in ряды if р["разница"] is not None and р["норма"]]
        норма_сум = sum(р["норма"] for _, р in с_разницей)
        разница = sum(р["разница"] for _, р in с_разницей)
        откл = разница / норма_сум * 100 if норма_сум else None
        цена = (sum(о["сумма"] or 0 for о in ops) / sum(о["количество"] for о in ops)) if ops else общая_цена
        превышение = sum(max(0.0, р["разница"] - ДОПУСК * р["норма"]) for _, р in с_разницей)
        регрессия = _регрессия([(р["пробег"], р["факт"]) for _, р in ряды if р["пробег"] and р["факт"] is not None])
        динамика = [{"месяц": м, "откл": _окр(р["разница"] / р["норма"] * 100, 1)} for м, р in с_разницей]
        сумма_авто = sum(о["сумма"] or 0 for о in ops)
        литры_авто = sum(о["количество"] for о in ops)
        водители = list(dict.fromkeys(имя_сотрудника(о["сотрудник_id"]) for о in ops if о["сотрудник_id"]))
        водитель = " → ".join(водители) or w.фио(люди.get(а["водитель_id"])) or "не закреплён"
        карточки.append({
            "автомобиль_id": авто_id, "название": w.авто_подпись(а), "водитель": водитель, "топливо": а["топливо"] or "",
            "бак": а.get("бак"), "заправок": len(ops), "литров": _окр(литры_авто), "сумма": _окр(сумма_авто),
            "цена": _окр(цена), "пробег": _окр(пробег, 1), "рубли_км": _окр(сумма_авто / пробег) if пробег else None,
            "расход_факт_100": _окр(sum(р["факт"] or 0 for _, р in ряды) / пробег * 100) if пробег else None,
            "расход_норма_100": _окр(sum(р["норма"] or 0 for _, р in ряды) / пробег * 100) if пробег else None,
            "откл": _окр(откл, 1), "откл_л": _окр(разница), "регрессия": регрессия, "динамика": динамика,
            "км_на_заправку": _окр(пробег / len(ops), 0) if ops and пробег else None,
            "азс": len({_азс(о["азс"]) for о in ops}), "месяцев_с_данными": len(ряды)})
        if откл is not None:
            откл_парка.append((авто_id, откл))

        # --- признаки для проверки ---
        признаки: dict[str, dict] = {}
        помечены: dict[int, set[str]] = defaultdict(set)      # id операции → признаки

        def признак(код, пояснение, ops_=(), литры_=None, баллы=None, рубли=None):
            п = признаки.setdefault(код, {"код": код, "название": ПРИЗНАКИ[код], "пояснения": [], "операций": 0, "литров": 0.0,
                                         "рубли": 0.0, "баллы": 0})
            п["пояснения"].append(пояснение)
            for о in ops_:
                if о["id"] not in помечены or код not in помечены[о["id"]]:
                    п["операций"] += 1
                    п["литров"] += о["количество"]
                    п["рубли"] += о["сумма"] or 0
                помечены[о["id"]].add(код)
            if литры_ is not None:
                п["литров"] += литры_
                п["рубли"] += литры_ * цена if рубли is None else рубли
            if баллы is not None:
                п["баллы"] = max(п["баллы"], баллы)

        if откл is not None and откл > ДОПУСК * 100:
            уровень = 3 if откл > 20 else 2 if откл > 10 else 1
            месячные = [d["откл"] for d in динамика]
            устойчиво = ""
            if len(месячные) >= 3:
                ср, сд = statistics.fmean(месячные), statistics.pstdev(месячные)
                if сд and ср / (сд / math.sqrt(len(месячные))) > 2:
                    устойчиво = " Перерасход повторяется из месяца в месяц — это не случайность."
                elif not сд and ср > 0:
                    устойчиво = " Перерасход одинаков во все месяцы."
            признак("перерасход", f"Расход по факту выше нормы на {откл:.1f} % ({разница:+.1f} л за период, сверх допуска {ДОПУСК * 100:.0f} %: "
                                  f"{превышение:.1f} л).{устойчиво}", литры_=превышение, баллы=уровень)
        if ops and а.get("бак"):
            большие = [о for о in ops if о["количество"] > а["бак"] * 1.02]
            if большие:
                лишне = sum(о["количество"] - а["бак"] for о in большие)
                признак("больше_бака", f"{len(большие)} заправок больше объёма бака {а['бак']:g} л (сверх бака — {лишне:.1f} л). "
                                       f"Наибольшая: {max(о['количество'] for о in большие):g} л.", большие, баллы=3)
        for о in ops:
            if о["сотрудник_id"]:
                причина = отсутствие(о["сотрудник_id"], о["дата"])
                if причина:
                    признак("отпуск", f"{w._рус(о['дата'])} {о['время'][:5]}: {о['количество']:g} л по карте сотрудника, который в этот день — {причина}.",
                            [о], баллы=3)
        класс_авто = _класс_топлива(а["топливо"])
        if класс_авто in ("бензин", "дизель"):
            чужое = [о for о in ops if _класс_топлива(о["топливо"]) and _класс_топлива(о["топливо"]) != класс_авто]
            if чужое:
                признак("не_то_топливо", f"{len(чужое)} заправок не тем топливом: у машины {а['топливо']}, залито "
                                         f"{', '.join(sorted({w.вид_топлива(о['топливо']) for о in чужое}))}. Возможно, заправлена другая машина или канистры.",
                        чужое, баллы=3)
        по_картам_день = defaultdict(list)
        for о in ops:
            по_картам_день[(о["карта"], о["дата"])].append(о)
        рядом = []
        for гр in по_картам_день.values():
            гр = sorted(гр, key=lambda о: о["время"])
            for первый_о, второй_о in zip(гр, гр[1:]):
                m1, m2 = _момент(первый_о), _момент(второй_о)
                if m1 and m2 and (m2 - m1) < timedelta(hours=3):
                    рядом.append(второй_о)
        if рядом:
            признак("рядом", f"{len(рядом)} повторных заправок по той же карте в течение 3 часов — бак столько не примет, если нет канистр.",
                    рядом, баллы=2)
        for гр in по_картам_день.values():
            гр = sorted(гр, key=lambda о: о["время"])
            for а1, б1 in zip(гр, гр[1:]):
                г1, г2 = _город(а1["азс"]), _город(б1["азс"])
                m1, m2 = _момент(а1), _момент(б1)
                if г1 and г2 and г1 != г2 and m1 and m2 and (m2 - m1) < timedelta(minutes=90):
                    признак("маршрут", f"{w._рус(а1['дата'])}: {а1['время'][:5]} — {г1.title()}, {б1['время'][:5]} — {г2.title()}: за {int((m2 - m1).total_seconds() // 60)} мин "
                                       f"между городами не доехать. Карту могли использовать разные люди.", [б1], баллы=3)
        # без пробега
        for м in месяцы:
            р = помесячно[м].get(авто_id)
            заправлено_в_месяце = [о for о in ops if о["дата"].startswith(м)]
            if р and w._заполнен(р) and заправлено_в_месяце and (р["пробег"] or 0) <= 0 and р["пробег"] is not None:
                признак("без_пробега", f"{w._месяц_рус(м)}: заправлено {sum(о['количество'] for о in заправлено_в_месяце):g} л, а пробег по путевым — 0.",
                        заправлено_в_месяце, баллы=2)
        # слабые признаки
        ночью = [о for о in ops if _час(о) in НОЧЬ]
        if len(ночью) >= 2 and len(ночью) >= len(ops) * 0.3:
            признак("ночью", f"{len(ночью)} из {len(ops)} заправок — с 23:00 до 5:00.", ночью, баллы=1)
        выходные = []
        for о in ops:
            д = date.fromisoformat(о["дата"])
            if w.выходной(д) and табель.get((о["сотрудник_id"], о["дата"])) not in РАБОТА_В_ВЫХОДНОЙ and not отсутствие(о["сотрудник_id"], о["дата"]):
                выходные.append(о)
        if len(выходные) >= 3 or (len(выходные) >= 2 and len(выходные) >= len(ops) * 0.3):
            признак("выходные", f"{len(выходные)} заправок в выходные и праздники без отметки «работа в выходной» в табеле.", выходные, баллы=1)
        if len(ops) >= 3 and пробег > 0 and пробег / len(ops) < 60:
            признак("редкий_пробег", f"В среднем {пробег / len(ops):.0f} км на одну заправку — машина почти не ездит, а заправляется часто.", баллы=1)
        if len(динамика) >= 3 and _тренд([d["откл"] for d in динамика[-4:]]) >= 1.5 and динамика[-1]["откл"] > ДОПУСК * 100:
            признак("растёт", f"Отклонение растёт: {' → '.join(f'{d['откл']:+.0f}%' for d in динамика[-4:])}.", баллы=1)

        if признаки:
            для_оценки = [о for о in ops if помечены.get(о["id"], set()) & СИЛЬНЫЕ]
            баллы = 0
            for п in признаки.values():
                п["литров"], п["рубли"] = _окр(п["литров"], 1), _окр(п["рубли"], 0)
                баллы += п["баллы"]
            контроль.append({
                "автомобиль_id": авто_id, "название": w.авто_подпись(а), "водитель": водитель, "баллы": баллы,
                "признаки": sorted(признаки.values(), key=lambda п: -п["баллы"]),
                "подозрительно_л": _окр(sum(о["количество"] for о in для_оценки), 1),
                "подозрительно_руб": _окр(sum(о["сумма"] or 0 for о in для_оценки), 0),
                "перерасход_л": _окр(признаки["перерасход"]["литров"], 1) if "перерасход" in признаки else 0,
                "перерасход_руб": _окр(признаки["перерасход"]["рубли"], 0) if "перерасход" in признаки else 0})

    # выбивается из парка: робастный z-счёт по отклонению
    if len(откл_парка) >= 4:
        значения = [з for _, з in откл_парка]
        мед = statistics.median(значения)
        мад = statistics.median([abs(з - мед) for з in значения]) or 1.0
        for авто_id, з in откл_парка:
            z = 0.6745 * (з - мед) / мад
            if z > 2.5 and з > ДОПУСК * 100:
                к = next((к for к in контроль if к["автомобиль_id"] == авто_id), None)
                п = {"код": "выбивается", "название": ПРИЗНАКИ["выбивается"], "операций": 0, "литров": 0.0, "рубли": 0.0, "баллы": 1,
                     "пояснения": [f"Отклонение {з:+.1f} % при медиане по парку {мед:+.1f} % (z = {z:.1f})."]}
                if к:
                    к["признаки"].append(п)
                    к["баллы"] += 1
                else:
                    a = машины[авто_id]
                    контроль.append({"автомобиль_id": авто_id, "название": w.авто_подпись(a), "водитель": w.фио(люди.get(a["водитель_id"])) or "не закреплён",
                                     "баллы": 1, "признаки": [п], "подозрительно_л": 0, "подозрительно_руб": 0, "перерасход_л": 0, "перерасход_руб": 0})
    for к in контроль:
        к["уровень"] = "высокий" if к["баллы"] >= 6 else "средний" if к["баллы"] >= 3 else "низкий"
        к["всего_л"] = _окр(к["подозрительно_л"] + к["перерасход_л"], 1)
        к["всего_руб"] = _окр(к["подозрительно_руб"] + к["перерасход_руб"], 0)
    контроль.sort(key=lambda к: (-к["баллы"], -(к["всего_руб"] or 0)))

    # заправки, которые не удалось отнести к машине
    без_машины = defaultdict(lambda: {"литров": 0.0, "сумма": 0.0, "операций": 0})
    for о in операции:
        if not о["авто_id"]:
            к = без_машины[о["карта"]]
            к["литров"] += о["количество"]; к["сумма"] += о["сумма"] or 0; к["операций"] += 1
            к["сотрудник"] = имя_сотрудника(о["сотрудник_id"]) if о["сотрудник_id"] else "карта не закреплена"
    без_машины_список = sorted(({"карта": имя_карты(н), **{k: (_окр(v) if isinstance(v, float) else v) for k, v in д.items()}}
                                for н, д in без_машины.items()), key=lambda д: -д["литров"])

    # ---- сотрудники и карты: кто как заправляется -------------------------------------------
    по_людям = defaultdict(list)
    for о in операции:
        по_людям[о["сотрудник_id"] or ("карта", о["карта"])].append(о)
    дней_в_периоде = max(1, итого["дней_в_периоде"])
    сотрудники = []
    for ключ, ops in по_людям.items():
        дни = sorted({o["дата"] for o in ops})
        интервалы = [(date.fromisoformat(b) - date.fromisoformat(a)).days for a, b in zip(дни, дни[1:])]
        азс_счёт = Counter(_азс(o["азс"]) for o in ops)
        литры_ = sum(o["количество"] for o in ops)
        сум_ = sum(o["сумма"] or 0 for o in ops)
        переплата = sum(((o["сумма"] or 0) - o["количество"] * цена_вида.get(w.вид_топлива(o["топливо"]), 0)) for o in ops)
        сотрудники.append({
            "имя": имя_сотрудника(ключ) if not isinstance(ключ, tuple) else f"карта …{''.join(ч for ч in ключ[1] if ч.isdigit())[-4:]} (не закреплена)",
            "заправок": len(ops), "литров": _окр(литры_), "сумма": _окр(сум_), "средняя": _окр(литры_ / len(ops), 1),
            "раз_в_неделю": _окр(len(ops) / дней_в_периоде * 7, 1),
            "интервал_дней": _окр(statistics.fmean(интервалы), 1) if интервалы else None,
            "азс": len(азс_счёт), "любимая_азс": азс_счёт.most_common(1)[0][0], "любимая_раз": азс_счёт.most_common(1)[0][1],
            "ночью": sum(1 for o in ops if _час(o) in НОЧЬ), "переплата": _окр(переплата, 0),
            "ср_час": _окр(statistics.fmean([h for h in (_час(o) for o in ops) if h is not None]), 1) if any(_час(o) is not None for o in ops) else None})
    сотрудники.sort(key=lambda с_: -с_["заправок"])

    # ---- АЗС ---------------------------------------------------------------------------------
    группа_азс = defaultdict(list)
    for о in операции:
        группа_азс[_азс(о["азс"])].append(о)
    азс = []
    for название, ops in группа_азс.items():
        л = sum(o["количество"] for o in ops)
        сум_ = sum(o["сумма"] or 0 for o in ops)
        ожидаемо = sum(o["количество"] * цена_вида.get(w.вид_топлива(o["топливо"]), 0) for o in ops)
        азс.append({"название": название, "заправок": len(ops), "литров": _окр(л), "сумма": _окр(сум_),
                    "цена": _окр(сум_ / л) if л else None, "отличие_цены": _окр((сум_ / ожидаемо - 1) * 100, 1) if ожидаемо else None,
                    "карт": len({o["карта"] for o in ops}), "город": _город(название).title()})
    азс.sort(key=lambda а_: -а_["заправок"])
    города = Counter(a["город"] for a in азс for _ in range(a["заправок"]) if a["город"])

    # ---- время заправок ----------------------------------------------------------------------
    часы = [0] * 24
    часы_л = [0.0] * 24
    дни_недели = [0] * 7
    for о in операции:
        h = _час(о)
        if h is not None:
            часы[h] += 1
            часы_л[h] += о["количество"]
        дни_недели[date.fromisoformat(о["дата"]).weekday()] += 1

    # ---- динамика по месяцам и по топливу --------------------------------------------------
    по_месяцам = []
    for м in месяцы:
        ops = [о for о in операции if о["дата"].startswith(м)]
        л = sum(o["количество"] for o in ops)
        сум_ = sum(o["сумма"] or 0 for o in ops)
        по_месяцам.append({"месяц": м, "подпись": w._месяц_рус(м), "заправок": len(ops), "литров": _окр(л), "сумма": _окр(сум_),
                           "цена": _окр(сум_ / л) if л else None})
    топливо = sorted(({"вид": в, "литров": _окр(литры_по_виду[в]), "сумма": _окр(сумма_по_виду[в]), "цена": _окр(цена_вида.get(в)),
                       "доля": _окр(литры_по_виду[в] / литров * 100, 1) if литров else None} for в in литры_по_виду), key=lambda т: -т["литров"])

    # ---- рекорды -----------------------------------------------------------------------------
    def описание(o):
        return {"дата": o["дата"], "время": (o["время"] or "")[:5], "литров": _окр(o["количество"]), "сумма": _окр(o["сумма"]),
                "цена": _окр(o["цена"]), "азс": _азс(o["азс"]), "кто": имя_сотрудника(o["сотрудник_id"]) if o["сотрудник_id"] else имя_карты(o["карта"])}
    рекорды = {}
    if операции:
        рекорды["самая_большая"] = описание(max(операции, key=lambda o: o["количество"]))
        рекорды["самая_дорогая"] = описание(max(операции, key=lambda o: o["сумма"] or 0))
        с_временем = [o for o in операции if _час(o) is not None]
        if с_временем:
            рекорды["самая_ранняя"] = описание(min(с_временем, key=lambda o: o["время"]))
            рекорды["самая_поздняя"] = описание(max(с_временем, key=lambda o: o["время"]))
        с_ценой = [o for o in операции if o["цена"]]
        if с_ценой:
            рекорды["дороже_всего_литр"] = описание(max(с_ценой, key=lambda o: o["цена"] / (цена_вида.get(w.вид_топлива(o["топливо"])) or o["цена"])))

    # ---- общая регрессия «факт ≈ норма» по всему парку --------------------------------------
    пары = [(р["норма"], р["факт"]) for м in месяцы for р in помесячно[м].values()
            if w._заполнен(р) and р["норма"] and р["факт"] is not None and р["разница"] is not None]
    парк = _регрессия(пары) if len(пары) >= 3 else None
    если_нет = []
    без_бака = sum(1 for a in машины.values() if not a.get("бак"))
    if без_бака:
        если_нет.append(f"Объём бака не указан у машин: {без_бака}. Проверка «заправка больше бака» для них не работает — впишите «Объём бака» в карточке автомобиля.")
    нет_путевых = sum(1 for к in карточки if not к["месяцев_с_данными"])
    if нет_путевых:
        если_нет.append(f"У машин без путевых за период ({нет_путевых}) нельзя сравнить расход с нормой — заполните «Анализ движения ГСМ».")
    if not операции:
        если_нет.append("За выбранный период нет операций по топливным картам — загрузите выписку.")
    with база.соединение() as связь:
        месяцы_гсм = [р[0] for р in связь.execute("SELECT DISTINCT substr(дата, 1, 7) FROM раб_гсм ORDER BY 1")]
    return {
        "месяцы_гсм": месяцы_гсм, "месяцы_данных": w._месяцы_данных(база),
        "месяцы": месяцы, "подпись": w.название_периода(месяцы), "итого": итого, "машины": карточки, "контроль": контроль,
        "без_машины": без_машины_список, "сотрудники": сотрудники, "азс": азс[:20], "азс_всего": len(азс), "города": города.most_common(6),
        "часы": часы, "часы_литры": [_окр(х, 1) for х in часы_л], "дни_недели": дни_недели, "дни_названия": ДНИ,
        "по_месяцам": по_месяцам, "топливо": топливо, "рекорды": рекорды, "парк": парк, "допуск": ДОПУСК * 100, "замечания": если_нет}
