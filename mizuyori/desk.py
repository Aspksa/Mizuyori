def _первая_фраза(текст: str, предел: int = 70) -> str:
    т = " ".join((текст or "").split())
    первая = re.split(r"(?<=[.!?])\s", т, maxsplit=1)[0]
    return первая[:предел].rstrip(" .,;:") if первая else ""


def _тип_аудита(з: dict) -> str:
    д = (з["действие"] or "").casefold()
    if "заблокирован" in д or з["кто"] == "файрвол":
        return "защита"
    if "подтвержд" in д or "принят" in д:
        return "да"
    if "отклон" in д or "остановл" in д:
        return "нет"
    if "поручение" in д:
        return "поручение"
    return "аудит"


