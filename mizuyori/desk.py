def события(база, сколько: int = 40) -> list[dict]:
    """Единая лента: журнал аудита и дела агентов, новое сверху."""
    лента = []
    for з in audit.список(сколько):
        лента.append({"когда": з["создано"], "тип": _тип_аудита(з), "текст": f"{з['действие']}: {з['объект']}".strip(": ")[:140]})
    with база.соединение() as связь:
        строки = связь.execute("SELECT агент, действие, результат, успех, создано FROM агент_история ORDER BY id DESC LIMIT ?", (сколько,)).fetchall()
        записки = связь.execute("SELECT от, кому, текст, создано FROM доска ORDER BY id DESC LIMIT ?", (сколько // 2,)).fetchall()
    for с in строки:
        лента.append({"когда": с["создано"], "тип": "дело" if с["успех"] else "сбой",
                      "текст": f"{agents.ИМЕНА.get(с['агент'], с['агент'])}: {с['действие']}" + (f" — {с['результат'][:60]}" if с["результат"] else "")})
    for с in записки:
        лента.append({"когда": с["создано"], "тип": "записка",
                      "текст": f"{agents.ИМЕНА.get(с['от'], с['от'])} → {agents.ИМЕНА.get(с['кому'], с['кому'])}: {с['текст'][:80]}"})
    лента.sort(key=lambda е: е["когда"], reverse=True)
    return лента[:сколько]


