def _зам(текст: str, важно: int = 1, кому: str | None = None) -> dict:
    return {"текст": текст, "важно": важно, "кому": кому}


def _рус(iso: str | None) -> str:
    return ".".join(reversed(iso.split("-"))) if iso else ""


def _руб(ч) -> str:
    return f"{round(ч or 0):,}".replace(",", " ") + " ₽"


def _договоры(база) -> list[dict]:
    with база.соединение() as связь:
        return [dict(р) for р in связь.execute("SELECT * FROM раб_договоры")]


def _сметы(база, статус: str | None = None) -> list[dict]:
    with база.соединение() as связь:
        if статус:
            return [dict(р) for р in связь.execute("SELECT * FROM раб_сметы WHERE статус = ?", (статус,))]
        return [dict(р) for р in связь.execute("SELECT * FROM раб_сметы")]


def _дней(метка: str | None) -> int | None:
    try:
        return (date.today() - date.fromisoformat((метка or "")[:10])).days
    except ValueError:
        return None


def наблюдать_снабженца(база) -> list[dict]:
    итог = []
    for с in _сметы(база, "на проверке"):
        д = _дней(с["создано"])
        if д is not None and д >= 2:
            итог.append(_зам(f"Смета «{с['имя']}» ждёт подтверждения {д} дн. — без неё закупка не начнётся", 1, "инженер"))
    подтверждённые = _сметы(база, "подтверждена")
    договоры = _договоры(база)
    имена = " ".join((д["контрагент"] or "").lower() for д in договоры)
    названы = set()
    for с in подтверждённые[-30:]:
        try:
            данные = json.loads(с["данные"])
        except ValueError:
            continue
        исп = str(данные.get("исполнитель") or "").strip().lower()
        if исп and исп not in имена and исп not in названы:
            названы.add(исп)
            итог.append(_зам(f"По смете «{с['имя']}» нет договора или счёта-оферты с «{данные.get('исполнитель')}» в базе", 1, "юрист"))
    if подтверждённые:
        итог.append(_зам(f"Подтверждённых смет: {len(подтверждённые)}; на проверке: {len(_сметы(база, 'на проверке'))}", 0))
    return итог


def наблюдать_архивариуса(база) -> list[dict]:
    from .documents import ПАПКА_ДОКУМЕНТОВ as папка
    итог = []
    файлы = [ф for ф in папка.iterdir() if ф.is_file()] if папка.exists() else []
    чужие = [ф.name for ф in файлы if not ф.name.lower().startswith(("смета ", "договор ", "оферта ", "дефектовая ", "записка "))]
    if чужие:
        итог.append(_зам(f"{len(чужие)} файлов в папке документов названы не по схеме («Вид номер - название»): "
                         f"{', '.join(чужие[:3])}", 1))
    имена = defaultdict(int)
    for ф in файлы:
        имена[ф.stem.lower()] += 1
    повторы = [н for н, ч in имена.items() if ч > 1]
    if повторы:
        итог.append(_зам(f"В папке документов повторяются названия: {', '.join(повторы[:3])}", 1))
    известные = {с["файл"] for с in _сметы(база)}
    нет_в_базе = [с["имя"] for с in _сметы(база) if с["файл"] and not Path(с["файл"]).exists()]
    if нет_в_базе:
        итог.append(_зам(f"Файлы смет пропали с диска: {', '.join(нет_в_базе[:3])}", 2, "инженер"))
    if файлы:
        итог.append(_зам(f"В архиве документов {len(файлы)} файлов, смет в базе {len(известные)}", 0))
    return итог


def наблюдать_контрагентов(база) -> list[dict]:
    итог = []
    по_имени = defaultdict(list)
    for д in _договоры(база):
        имя = (д["контрагент"] or "").strip()
        if not имя:
            итог.append(_зам(f"{'Договор' if д['вид'] == 'договор' else 'Оферта'} №{д['номер'] or 'б/н'}: не указан контрагент", 1))
            continue
        по_имени[имя.lower()].append(д)
    for _, список in по_имени.items():
        имя = список[0]["контрагент"]
        инны = {д["инн"] for д in список if д["инн"]}
        if len(инны) > 1:
            итог.append(_зам(f"У «{имя}» в документах разные ИНН: {', '.join(sorted(инны))}", 2, "проверяющий"))
        if not инны:
            итог.append(_зам(f"У «{имя}» нигде не указан ИНН", 0))
        if len(список) >= 3:
            итог.append(_зам(f"«{имя}»: уже {len(список)} документов — стоит заключить рамочный договор", 0, "снабженец"))
    if по_имени:
        итог.append(_зам(f"Контрагентов в базе: {len(по_имени)}", 0))
    return итог


