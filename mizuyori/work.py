def _строки_таблицы(данные: bytes, имя: str) -> list[list[str]]:
    if данные[:4] == b"PK\x03\x04" or имя.lower().endswith(".xlsx"):
        import openpyxl
        книга = openpyxl.load_workbook(io.BytesIO(данные), read_only=True, data_only=True)
        лист = книга.worksheets[0]
        return [["" if з is None else (з.strftime("%d.%m.%Y") if isinstance(з, (datetime, date)) else str(з))
                 for з in ряд] for ряд in лист.iter_rows(values_only=True)]
    import xlrd
    книга = xlrd.open_workbook(file_contents=данные)
    лист = книга.sheet_by_index(0)
    итог = []
    for р in range(лист.nrows):
        ряд = []
        for к in range(лист.ncols):
            ячейка = лист.cell(р, к)
            if ячейка.ctype == xlrd.XL_CELL_DATE:
                ряд.append(xlrd.xldate_as_datetime(ячейка.value, книга.datemode).strftime("%d.%m.%Y"))
            elif ячейка.ctype == xlrd.XL_CELL_NUMBER and float(ячейка.value).is_integer():
                ряд.append(str(int(ячейка.value)) if abs(ячейка.value) > 1e6 else str(ячейка.value))
            else:
                ряд.append(str(ячейка.value))
        итог.append(ряд)
    return итог


def _число(т) -> float | None:
    try:
        return float(str(т).replace(",", ".").replace(" ", "").replace("\xa0", ""))
    except ValueError:
        return None


def разобрать_выписку(данные: bytes, имя: str) -> dict:
    """Выписка по топливным картам: «Карта № …», затем строки «Отгрузка / Возврат | дата | время | АЗС | топливо | цена | кол-во | сумма»."""
    строки = _строки_таблицы(данные, имя)
    карта, период, поставщик = None, "", ""
    операции = []
    for ряд in строки:
        ряд = [str(я).strip() for я in ряд] + [""] * 8
        первая = ряд[0]
        if not поставщик and (м := re.search(r"картам\s+(.+)$", первая, re.I)):
            поставщик = м.group(1).strip()
        if м := re.search(r"Период\s+с\s+(\S+)\s+по\s+(\S+)", первая):
            период = f"{м.group(1)} – {м.group(2)}"
            continue
        if м := re.search(r"Карта\s*№?\s*([\d ]{6,})", первая):
            карта = м.group(1).replace(" ", "")
            continue
        if первая in ("Отгрузка", "Возврат", "Продажа", "Покупка") and карта:
            try:
                день = _дата(ряд[1])
            except ОшибкаРаботы:
                continue
            количество, сумма = _число(ряд[6]), _число(ряд[7])
            if первая == "Возврат":
                количество = -abs(количество or 0)
                сумма = -abs(сумма or 0)
            операции.append({"карта": карта, "операция": первая, "дата": день, "время": ряд[2][:8], "азс": ряд[3][:200],
                             "топливо": ряд[4][:200], "цена": _число(ряд[5]), "количество": количество, "сумма": сумма})
    if not операции:
        raise ОшибкаРаботы("В файле не нашлось операций по картам. Нужна выписка вида «Карта № …» и строки «Отгрузка».")
    return {"период": период, "поставщик": поставщик, "операции": операции}


def загрузить_выписку(база, данные: bytes, имя: str) -> dict:
    разбор = разобрать_выписку(данные, имя)
    with база.соединение() as связь:
        выписка = связь.execute("INSERT INTO раб_гсм_выписки (файл, период) VALUES (?, ?)", (имя[:200], разбор["период"])).lastrowid
        новых = 0
        for о in разбор["операции"]:
            новых += связь.execute(
                "INSERT OR IGNORE INTO раб_гсм (выписка_id, карта, операция, дата, время, азс, топливо, цена, количество, сумма) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?)",
                (выписка, о["карта"], о["операция"], о["дата"], о["время"], о["азс"], о["топливо"], о["цена"],
                 о["количество"], о["сумма"])).rowcount
        связь.execute("UPDATE раб_гсм_выписки SET операций = ?, новых = ? WHERE id = ?", (len(разбор["операции"]), новых, выписка))
        # карты из выписки, которых ещё нет в справочнике, — добавить
        есть = {номер_карты(р[0]) for р in связь.execute("SELECT номер FROM раб_карты")}
        новые_карты = sorted({номер_карты(о["карта"]) for о in разбор["операции"]} - есть)
        for н in новые_карты:
            связь.execute("INSERT INTO раб_карты (номер, поставщик, заметка) VALUES (?, ?, 'добавлена из выписки')",
                          (н, разбор["поставщик"]))
    даты = [о["дата"] for о in разбор["операции"]]
    журнал.info("Выписка ГСМ «%s»: операций %s, новых %s, новых карт %s", имя, len(разбор["операции"]), новых, len(новые_карты))
    return {"операций": len(разбор["операции"]), "новых": новых, "повторов": len(разбор["операции"]) - новых,
            "новых_карт": len(новые_карты), "период": разбор["период"], "с": min(даты), "по": max(даты)}


