    @app.post("/api/work/gsm/import")
    async def импорт_гсм(request: Request):
        данные = await request.body()
        if not данные:
            raise StarletteHTTPException(400, "Файл пустой.")
        if len(данные) > 20 * 1024 * 1024:
            raise StarletteHTTPException(400, "Файл больше 20 МБ.")
        from urllib.parse import unquote
        имя = unquote(request.headers.get("x-filename", "выписка.xls"))
        try:
            return загрузить_выписку(база, данные, имя)
        except ОшибкаРаботы as е:
            raise StarletteHTTPException(400, str(е))
        except Exception:
            журнал.exception("Не удалось прочитать выписку")
            raise StarletteHTTPException(400, "Не удалось прочитать файл. Нужна выписка в Excel (.xls или .xlsx).")

