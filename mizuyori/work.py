def вид_топлива(т: str) -> str:
    """«Бензин … (АИ-95-К5) …» → «АИ-95», «… (ДТ-Л-К5)» → «ДТ летнее»."""
    if м := re.search(r"АИ-?(\d{2,3})", т):
        return f"АИ-{м.group(1)}"
    if м := re.search(r"ДТ-([ЛЗЕА])", т):
        return {"Л": "ДТ летнее", "З": "ДТ зимнее", "Е": "ДТ межсезонное", "А": "ДТ арктическое"}[м.group(1)]
    if re.search(r"дизел|ДТ", т, re.I):
        return "ДТ"
    if re.search(r"газ|пропан|СУГ|LPG", т, re.I):
        return "Газ"
    return т[:30] or "—"


def свод(база, с: str | None, по: str | None) -> dict:
    условие, параметры = [], []
    if с:
        условие.append("дата >= ?"); параметры.append(с)
    if по:
        условие.append("дата <= ?"); параметры.append(по)
    где = f"WHERE {' AND '.join(условие)}" if условие else ""
    with база.соединение() as связь:
        операции = [dict(р) for р in связь.execute(f"SELECT * FROM раб_гсм {где} ORDER BY карта, дата, время", параметры)]
        крайние = связь.execute("SELECT MIN(дата), MAX(дата) FROM раб_гсм").fetchone()
        выписки = [dict(р) for р in связь.execute("SELECT * FROM раб_гсм_выписки ORDER BY id DESC LIMIT 10")]
    # одна и та же карта могла попасть в справочник дважды (из выписки и руками) — берём закреплённую
    закреплённые = {ч["карта_id"] for ч in _все(база, "раб_сотрудники").values() if ч["карта_id"]}
    карты: dict[str, dict] = {}
    for к_ in sorted(_все(база, "раб_карты").values(), key=lambda к_: к_["id"] in закреплённые):
        карты[номер_карты(к_["номер"])] = к_
    люди = _все(база, "раб_сотрудники")
    машины = _все(база, "раб_автомобили")
    по_картам: dict[str, dict] = {}
    виды = []
    for о in операции:
        вид = вид_топлива(о["топливо"])
        о["вид"] = вид
        if вид not in виды:
            виды.append(вид)
        к = по_картам.setdefault(о["карта"], {"карта": о["карта"], "литры": 0.0, "сумма": 0.0, "операций": 0,
                                               "возвратов": 0, "по_видам": {}, "операции": []})
        к["литры"] += о["количество"] or 0
        к["сумма"] += о["сумма"] or 0
        к["операций"] += 1
        к["возвратов"] += о["операция"] == "Возврат"
        в = к["по_видам"].setdefault(вид, {"литры": 0.0, "сумма": 0.0})
        в["литры"] += о["количество"] or 0
        в["сумма"] += о["сумма"] or 0
        к["операции"].append(о)
    строки = []
    for номер, к in по_картам.items():
        карта = карты.get(номер_карты(номер))
        человек = next((ч for ч in люди.values() if карта and ч["карта_id"] == карта["id"]), None)
        авто = next((а for а in машины.values() if человек and а["водитель_id"] == человек["id"]), None)
        к.update({"карта_id": карта["id"] if карта else None, "лимит": карта.get("лимит") if карта else None,
                  "сотрудник": фио(человек), "сотрудник_id": человек["id"] if человек else None,
                  "должность": (человек or {}).get("должность", ""), "автомобиль": авто_подпись(авто),
                  "госномер": (авто or {}).get("госномер", ""), "расход_лето": (авто or {}).get("расход_лето"),
                  "расход_зима": (авто or {}).get("расход_зима"),
                  "литры": round(к["литры"], 2), "сумма": round(к["сумма"], 2)})
        строки.append(к)
    строки.sort(key=lambda к: (not к["сотрудник"], к["сотрудник"] or к["карта"]))
    итог_видов = {в: {"литры": round(sum(к["по_видам"].get(в, {}).get("литры", 0) for к in строки), 2),
                      "сумма": round(sum(к["по_видам"].get(в, {}).get("сумма", 0) for к in строки), 2)} for в in виды}
    return {"карты": строки, "виды": виды, "итого": {"литры": round(sum(к["литры"] for к in строки), 2),
                                                      "сумма": round(sum(к["сумма"] for к in строки), 2),
                                                      "операций": len(операции), "по_видам": итог_видов},
            "с": с, "по": по, "данные_с": крайние[0], "данные_по": крайние[1], "выписки": выписки}


# ---- ГСМ: расчёт по путевым листам ---------------------------------------------------
# Пробег = км конец (последняя путевая) − км начало (первая путевая).
# По норме, л = пробег × норма (лето или зима, из карточки автомобиля) / 100.
# По факту, л = как записано в путевых; если не записано — равен норме.
# Остаток на конец считается сам: остаток на начало + заправлено − расход по факту.
# Заправлено = по карте водителя за месяц + не по карте. Отклонение = факт − норма.

ПОЛЯ_ПУТЕВЫХ = ("сезон", "км_начало", "км_конец", "остаток_начало", "расход_факт", "заправлено_доп", "заметка")


def сезоны(база) -> dict:
    з = база.прочитать("работа.сезоны", {}) or {}
    return {**СЕЗОНЫ_ПО_УМОЛЧАНИЮ, **{к: в for к, в in з.items() if к in СЕЗОНЫ_ПО_УМОЛЧАНИЮ}}


def сохранить_сезоны(база, данные: dict) -> dict:
    итог = сезоны(база)
    for к in СЕЗОНЫ_ПО_УМОЛЧАНИЮ:
        if к in данные:
            т = str(данные[к]).strip()
            м = re.fullmatch(r"(\d{1,2})\.(\d{1,2})", т) or re.fullmatch(r"(\d{1,2})-(\d{1,2})", т)
            if not м:
                raise ОшибкаРаботы("Дата сезона — день и месяц, например 15.11.")
            день, мес = (int(м.group(1)), int(м.group(2))) if "." in т else (int(м.group(2)), int(м.group(1)))
            try:
                date(2024, мес, день)
            except ValueError:
                raise ОшибкаРаботы("Нет такой даты.")
            итог[к] = f"{мес:02d}-{день:02d}"
    база.записать("работа.сезоны", итог)
    return итог


def зимний_день(д: date, с: dict) -> bool:
    начало, конец = с["зима_с"], с["зима_по"]
    мд = д.strftime("%m-%d")
    return мд >= начало or мд <= конец if начало > конец else начало <= мд <= конец


def _сезон_по_умолчанию(месяц: str) -> str:
    return "зима" if int(месяц[5:7]) in ЗИМНИЕ_МЕСЯЦЫ else "лето"


def _посчитать_месяц(база, месяц: str) -> list[dict]:
    дни = _дни_месяца(месяц)
    с, по = дни[0].isoformat(), дни[-1].isoformat()
    машины = sorted(_все(база, "раб_автомобили").values(), key=lambda а: (а["марка"], а["модель"], а["госномер"]))
    люди = _все(база, "раб_сотрудники")
    карты = _все(база, "раб_карты")
    with база.соединение() as связь:
        записи = {р["автомобиль_id"]: dict(р) for р in связь.execute("SELECT * FROM раб_путевые WHERE месяц = ?", (месяц,))}
        заправки = {}
        for карта, литры_, сумма_ in связь.execute(
                "SELECT карта, SUM(количество), SUM(сумма) FROM раб_гсм WHERE дата BETWEEN ? AND ? GROUP BY карта", (с, по)):
            заправки[номер_карты(карта)] = (литры_ or 0, сумма_ or 0)
        месяцы_карт: dict[str, list[str]] = {}
        for карта, м_ in связь.execute("SELECT DISTINCT карта, substr(дата, 1, 7) FROM раб_гсм ORDER BY 2"):
            месяцы_карт.setdefault(номер_карты(карта), []).append(м_)
    настройки_сезонов = сезоны(база)
    дней_зимы = sum(1 for д in дни if зимний_день(д, настройки_сезонов))
    строки = []
    for а in машины:
        з = записи.get(а["id"], {})
        водитель = люди.get(а["водитель_id"])
        карта = карты.get(водитель["карта_id"]) if водитель else None
        по_карте, сумма = заправки.get(номер_карты(карта["номер"]), (0.0, 0.0)) if карта else (0.0, 0.0)
        выбран = з.get("сезон") or ""
        сезон = выбран or ("зима" if дней_зимы == len(дни) else "лето" if дней_зимы == 0 else "смешанный")
        if сезон == "смешанный":
            # граница сезона внутри месяца: пробег делится по дням, норма — частями
            лето, зима = а["расход_лето"] or а["расход_зима"], а["расход_зима"] or а["расход_лето"]
            норма_100 = round((зима * дней_зимы + лето * (len(дни) - дней_зимы)) / len(дни), 3) if лето and зима else None
            сезон_подпись = f"зима {дней_зимы} дн. + лето {len(дни) - дней_зимы} дн."
        else:
            норма_100 = а["расход_зима"] if сезон == "зима" else а["расход_лето"]
            сезон_подпись = сезон + ("" if выбран else " (по датам)")
        замена_нормы = ""
        if not норма_100 and сезон != "смешанный":
            # нет нормы на этот сезон — берём другую, чтобы считалось, и предупреждаем
            другая = а["расход_лето"] if сезон == "зима" else а["расход_зима"]
            if другая:
                норма_100 = другая
                замена_нормы = f"нет {'зимней' if сезон == 'зима' else 'летней'} нормы — взята {'летняя' if сезон == 'зима' else 'зимняя'}"
        р = {"автомобиль_id": а["id"], "автомобиль": авто_подпись(а), "топливо": а["топливо"],
             "водитель": фио(водитель), "карта": карта["номер"] if карта else "",
             "сезон": выбран or "авто", "сезон_подпись": сезон_подпись, "норма_100": норма_100, "есть_запись": bool(з),
             **{к: з.get(к) for к in ПОЛЯ_ПУТЕВЫХ if к != "сезон"},
             "по_карте": round(по_карте, 2), "сумма_по_карте": round(сумма, 2)}
        р["заметка"] = р["заметка"] or ""
        # почему по карте 0 — чтобы было видно, что поправить
        if not водитель:
            р["причина_нуля"] = "водитель не закреплён"
        elif not карта:
            р["причина_нуля"] = "у водителя нет топливной карты"
        elif not по_карте:
            есть = месяцы_карт.get(номер_карты(карта["номер"]), [])
            р["причина_нуля"] = (f"за этот месяц заправок нет, есть за: {', '.join(_месяц_рус(м_) for м_ in есть[-3:])}" if есть
                                 else "по этой карте нет заправок в загруженных выписках")
        else:
            р["причина_нуля"] = ""
        заправлено = по_карте + (р["заправлено_доп"] or 0)
        р["заправлено"] = round(заправлено, 2)
        р["пробег"] = (round(р["км_конец"] - р["км_начало"], 1)
                       if р["км_начало"] is not None and р["км_конец"] is not None else None)
        р["норма"] = round(р["пробег"] * норма_100 / 100, 2) if р["пробег"] is not None and норма_100 else None
        р["факт_введён"] = р["расход_факт"] is not None
        р["факт"] = р["расход_факт"] if р["факт_введён"] else р["норма"]
        р["остаток_конец"] = (round(р["остаток_начало"] + заправлено - р["факт"], 2)
                              if р["остаток_начало"] is not None and р["факт"] is not None else None)
        р["разница"] = round(р["факт"] - р["норма"], 2) if р["факт_введён"] and р["норма"] is not None else None
        р["процент"] = round(р["разница"] / р["норма"] * 100, 1) if р["разница"] is not None and р["норма"] else None
        р["ошибка"] = ("км на конец меньше, чем на начало" if р["пробег"] is not None and р["пробег"] < 0
                       else "остаток на конец меньше нуля — проверьте" if р["остаток_конец"] is not None and р["остаток_конец"] < 0
                       else "нет нормы расхода в карточке автомобиля" if not норма_100
                       else замена_нормы)
        # чего не хватает для расчёта — подсказка в строке
        нужно = [название for условие, название in (
            (р["км_начало"] is None, "км на начало"), (р["км_конец"] is None, "км на конец"),
            (р["остаток_начало"] is None, "остаток на начало")) if условие]
        р["не_хватает"] = нужно
        строки.append(р)
    return строки


def _месяц_рус(м_: str) -> str:
    return f"{МЕСЯЦЫ[int(м_[5:7]) - 1]} {м_[:4]}"


def путевые(база, месяц: str, перенос: bool = True) -> dict:
    if перенос:
        перенести_путевые(база, месяц)     # начало месяца = конец прошлого — само, где ещё пусто
    строки = _посчитать_месяц(база, месяц)
    with база.соединение() as связь:
        месяцы_гсм = [р[0] for р in связь.execute("SELECT DISTINCT substr(дата, 1, 7) FROM раб_гсм ORDER BY 1")]
    первый = _дни_месяца(месяц)[0]
    прошлые = {р["автомобиль_id"]: р for р in _посчитать_месяц(база, (первый - timedelta(days=1)).strftime("%Y-%m"))
               if р["есть_запись"]}
    итог = {"пробег": 0.0, "норма": 0.0, "факт": 0.0, "заправлено": 0.0, "сумма": 0.0, "остаток_начало": 0.0, "остаток_конец": 0.0}
    for р in строки:
        п = прошлые.get(р["автомобиль_id"], {})
        # подсказки: конец прошлого месяца = начало этого
        р["подсказка_км"] = п.get("км_конец")
        р["подсказка_остаток"] = п.get("остаток_конец")
        for к in ("пробег", "норма", "факт", "заправлено", "остаток_начало", "остаток_конец"):
            итог[к] += р[к] or 0
        итог["сумма"] += р["сумма_по_карте"]
    итог = {к: round(з, 2) for к, з in итог.items()}
    итог["разница"] = round(sum(р["разница"] or 0 for р in строки), 2)
    с = сезоны(база)
    return {"месяц": месяц, "строки": строки, "итого": итог, "сезоны": с,
            "сезоны_подпись": f"зима с {с['зима_с'][3:]}.{с['зима_с'][:2]} по {с['зима_по'][3:]}.{с['зима_по'][:2]}",
            "месяцы_гсм": месяцы_гсм}


def сохранить_путевой(база, месяц: str, автомобиль_id: int, данные: dict) -> None:
    _дни_месяца(месяц)
    поля = {}
    for к in ПОЛЯ_ПУТЕВЫХ:
        if к not in данные:
            continue
        з = данные[к]
        if к == "сезон":
            з = "" if з == "авто" else з
            if з not in ("", "лето", "зима"):
                raise ОшибкаРаботы("Сезон — лето или зима.")
        elif к == "заметка":
            з = str(з or "")[:300]
        else:
            з = None if з in (None, "") else _число(з)
            if з is None and данные[к] not in (None, ""):
                raise ОшибкаРаботы("Нужно число.")
            if з is not None and з < 0:
                raise ОшибкаРаботы("Не может быть меньше нуля.")
        поля[к] = з
    if not поля:
        return
    with база.соединение() as связь:
        связь.execute("INSERT OR IGNORE INTO раб_путевые (месяц, автомобиль_id) VALUES (?, ?)", (месяц, автомобиль_id))
        связь.execute(f"UPDATE раб_путевые SET {', '.join(f'{к} = ?' for к in поля)} WHERE месяц = ? AND автомобиль_id = ?",
                      (*поля.values(), месяц, автомобиль_id))


def перенести_путевые(база, месяц: str) -> int:
    """Начало месяца = конец прошлого: км и посчитанный остаток — где начало ещё не заполнено."""
    первый = _дни_месяца(месяц)[0]
    прошлые = _посчитать_месяц(база, (первый - timedelta(days=1)).strftime("%Y-%m"))
    перенесено = 0
    with база.соединение() as связь:
        for р in прошлые:
            if not р["есть_запись"] or (р["км_конец"] is None and р["остаток_конец"] is None):
                continue
            связь.execute("INSERT OR IGNORE INTO раб_путевые (месяц, автомобиль_id) VALUES (?, ?)", (месяц, р["автомобиль_id"]))
            перенесено += связь.execute(
                "UPDATE раб_путевые SET км_начало = COALESCE(км_начало, ?), остаток_начало = COALESCE(остаток_начало, ?) "
                "WHERE месяц = ? AND автомобиль_id = ? AND (км_начало IS NULL OR остаток_начало IS NULL)",
                (р["км_конец"], р["остаток_конец"], месяц, р["автомобиль_id"])).rowcount
    return перенесено


