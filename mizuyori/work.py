# ---- Общие помощники ---------------------------------------------------------------

def фио(с: dict | None, коротко: bool = False) -> str:
    if not с:
        return ""
    if коротко:
        инициалы = "".join(f"{ч[0]}." for ч in (с.get("имя"), с.get("отчество")) if ч)
        return f"{с.get('фамилия', '')} {инициалы}".strip()
    return " ".join(ч for ч in (с.get("фамилия"), с.get("имя"), с.get("отчество")) if ч)


def авто_подпись(а: dict | None) -> str:
    if not а:
        return ""
    имя = " ".join(ч for ч in (а.get("марка"), а.get("модель")) if ч)
    return f"{имя} {а['госномер']}".strip() if а.get("госномер") else имя


def _дата(значение) -> str | None:
    if значение in (None, ""):
        return None
    т = str(значение).strip()
    for формат in ("%Y-%m-%d", "%d.%m.%Y"):
        try:
            return datetime.strptime(т, формат).date().isoformat()
        except ValueError:
            pass
    raise ОшибкаРаботы(f"Неверная дата: «{т}».")


def проверить(схема: dict, данные: dict, новая: bool) -> dict:
    итог = {}
    for п in схема["поля"]:
        к = п["ключ"]
        if к not in данные:
            if новая and п.get("нужно"):
                raise ОшибкаРаботы(f"Заполните поле «{п['подпись']}».")
            continue
        з = данные[к]
        т = п["тип"]
        if т in ("текст", "длинный"):
            з = str(з or "").strip()
            if len(з) > (10000 if т == "длинный" else 300):
                raise ОшибкаРаботы(f"«{п['подпись']}»: слишком длинно.")
            if п.get("нужно") and not з:
                raise ОшибкаРаботы(f"Заполните поле «{п['подпись']}».")
        elif т == "число":
            if з in (None, ""):
                з = None
            else:
                try:
                    з = float(str(з).replace(",", ".").replace(" ", ""))
                except ValueError:
                    raise ОшибкаРаботы(f"«{п['подпись']}»: нужно число.")
        elif т == "дата":
            з = _дата(з)
        elif т == "выбор":
            з = str(з or "")
            if з and з not in п["варианты"]:
                raise ОшибкаРаботы(f"«{п['подпись']}»: нет такого варианта.")
        elif т == "ссылка":
            з = int(з) if з not in (None, "", 0, "0") else None
        elif т == "да_нет":
            з = 1 if з in (True, 1, "1", "да", "true") else 0
        итог[к] = з
    return итог


def номер_карты(т) -> str:
    """Номер топливной карты без пробелов и чёрточек — чтобы «5019 8010…» и «50198010…» совпадали."""
    return re.sub(r"[\s\-]", "", str(т or ""))


# ---- Справочники: чтение и запись ------------------------------------------------

def список(база, вид: str) -> list[dict]:
    с = СПРАВОЧНИКИ[вид]
    условие, параметры = ("WHERE вид = ?", (с["вид"],)) if с.get("вид") else ("", ())
    with база.соединение() as связь:
        строки = [dict(р) for р in связь.execute(f"SELECT * FROM {с['таблица']} {условие} ORDER BY id DESC", параметры)]
    return _дополнить(база, вид, строки)


def _все(база, таблица: str) -> dict[int, dict]:
    with база.соединение() as связь:
        return {р["id"]: dict(р) for р in связь.execute(f"SELECT * FROM {таблица}")}


def _дополнить(база, вид: str, строки: list[dict]) -> list[dict]:
    """Подписи связей и предупреждения (страховка, сроки договоров, оплата)."""
    сегодня = date.today()
    скоро = (сегодня + timedelta(days=30)).isoformat()
    if вид == "сотрудники":
        карты = _все(база, "раб_карты")
        машины = _все(база, "раб_автомобили")
        for р in строки:
            р["фио"] = фио(р)
            р["карта"] = карты.get(р["карта_id"], {}).get("номер", "")
            авто = next((а for а in машины.values() if а["водитель_id"] == р["id"]), None)
            р["автомобиль_id"] = авто["id"] if авто else None
            р["автомобиль"] = авто_подпись(авто)
    elif вид == "автомобили":
        люди = _все(база, "раб_сотрудники")
        км = пробеги(база)
        с = сезоны(база)
        for р in строки:
            р["водитель"] = фио(люди.get(р["водитель_id"]))
            р["название"] = авто_подпись(р)
            р["пробег_сейчас"] = км.get(р["id"])
            р["напоминания"] = напоминания_авто(р, сегодня, с)
            if р["то_интервал"] and р["то_пробег"] is not None and р["пробег_сейчас"] is not None:
                р["до_то"] = round(р["то_пробег"] + р["то_интервал"] - р["пробег_сейчас"])
            else:
                р["до_то"] = None
            if р["напоминания"]:
                р["предупреждение"] = р["напоминания"][0]["текст"]
                р["уровень"] = р["напоминания"][0]["уровень"]
    elif вид == "карты":
        люди = _все(база, "раб_сотрудники")
        for р in строки:
            владелец = next((ч for ч in люди.values() if ч["карта_id"] == р["id"]), None)
            р["сотрудник"] = фио(владелец)
            р["сотрудник_id"] = владелец["id"] if владелец else None
    elif вид == "договоры":
        for р in строки:
            if р["окончание"] and р["статус"] in ("", "действует", "на согласовании"):
                if р["окончание"] < сегодня.isoformat():
                    р["предупреждение"] = "срок истёк"
                elif р["окончание"] <= скоро:
                    р["предупреждение"] = f"заканчивается {_рус(р['окончание'])}"
    elif вид == "оферты":
        for р in строки:
            if not р["оплачено"] and р["срок_оплаты"] and р["статус"] not in ("отменён", "исполнен"):
                if р["срок_оплаты"] < сегодня.isoformat():
                    р["предупреждение"] = "оплата просрочена"
                elif р["срок_оплаты"] <= (сегодня + timedelta(days=5)).isoformat():
                    р["предупреждение"] = f"оплатить до {_рус(р['срок_оплаты'])}"
    for р in строки:
        for к in ("уволен", "оплачено"):
            if к in р:
                р[к] = bool(р[к])
    return строки


