def _лист_анализа(лист, д: dict, заголовок: str, ст) -> None:
    """Лист анализа: все числа записаны значениями, чтобы они видны в любой программе и на телефоне."""
    from openpyxl.styles import Font
    from openpyxl.utils import get_column_letter
    красный, зелёный = Font(color="C0392B", bold=True), Font(color="1E8449", bold=True)
    лист["A1"] = заголовок; лист["A1"].font = ст["заголовок"]
    итог = д["итого"]
    лист["A2"] = ("Расход по норме = пробег × норма/100. Остаток на конец из путевой — вписан; нет — считается: остаток на начало + "
                  "заправлено − расход. Отклонение «+» — перерасход, «−» — экономия.")
    if итог["без_машины_литров"]:
        лист["A3"] = f"Заправки по картам без автомобиля: {итог['без_машины_литров']:.2f} л ({итог['без_машины_карт']} карт) — в расчёт не входят."
