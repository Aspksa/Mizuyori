def _дни_месяца(месяц: str) -> list[date]:
    try:
        год, м = map(int, месяц.split("-"))
        первый = date(год, м, 1)
    except ValueError:
        raise ОшибкаРаботы("Месяц нужен в виде ГГГГ-ММ.")
    дни, д = [], первый
    while д.month == м:
        дни.append(д)
        д += timedelta(days=1)
    return дни


def обновить_календарь(база) -> None:
    """Текущий и следующий год — из встроенных данных; прошедшие годы удаляются."""
    import json
    год = date.today().year
    with база.соединение() as связь:
        for г, д in ПРОИЗВОДСТВЕННЫЙ.items():
            if г >= год:
                связь.execute("INSERT OR IGNORE INTO раб_календарь (год, данные, источник) VALUES (?, ?, ?)",
                              (г, json.dumps({к: д[к] for к in ("нерабочие", "рабочие", "сокращённые")}), д["источник"]))
        удалено = связь.execute("DELETE FROM раб_календарь WHERE год < ?", (год,)).rowcount
        строки = связь.execute("SELECT год, данные, источник FROM раб_календарь").fetchall()
    if удалено:
        журнал.info("Производственный календарь: удалены прошедшие годы (%s).", удалено)
    _КАЛЕНДАРЬ.clear()
    for г, данные, источник in строки:
        д = json.loads(данные)
        _КАЛЕНДАРЬ[г] = {к: {date(г, int(х[:2]), int(х[3:])) for х in д.get(к, [])} for к in ("нерабочие", "рабочие", "сокращённые")}
        _КАЛЕНДАРЬ[г]["источник"] = источник


def выходной(д: date) -> bool:
    к = _КАЛЕНДАРЬ.get(д.year)
    if к:
        return (д.weekday() >= 5 and д not in к["рабочие"]) or д in к["нерабочие"]
    return д.weekday() >= 5 or (д.month, д.day) in ПРАЗДНИКИ


def сокращённый(д: date) -> bool:
    к = _КАЛЕНДАРЬ.get(д.year)
    return bool(к and д in к["сокращённые"])


def норма_месяца(месяц: str) -> dict:
    дни = _дни_месяца(месяц)
    рабочих = [д for д in дни if not выходной(д)]
    return {"дней": len(рабочих), "часов": len(рабочих) * 8 - sum(1 for д in рабочих if сокращённый(д)),
            "по_календарю": дни[0].year in _КАЛЕНДАРЬ}


def табель(база, месяц: str) -> dict:
    дни = _дни_месяца(месяц)
    with база.соединение() as связь:
        люди = [dict(р) for р in связь.execute("SELECT * FROM раб_сотрудники ORDER BY фамилия, имя")]
        отметки = связь.execute("SELECT сотрудник_id, день, код, часы FROM раб_табель WHERE день BETWEEN ? AND ?",
                                (дни[0].isoformat(), дни[-1].isoformat())).fetchall()
    есть = {о[0] for о in отметки}
    люди = [ч for ч in люди if not ч["уволен"] or ч["id"] in есть]
    сетка: dict[int, dict] = {}
    for сид, день, код, часы in отметки:
        сетка.setdefault(сид, {})[день] = {"код": код, "часы": часы}
    сотрудники = []
    for ч in люди:
        свои = сетка.get(ч["id"], {})
        итоги = {"дней": sum(1 for о in свои.values() if о["код"] in ("Я", "К", "РВ")),
                 "часов": round(sum(о["часы"] or 0 for о in свои.values()), 1)}
        for код in ("ОТ", "Б", "К", "НН", "ДО"):
            итоги[код] = sum(1 for о in свои.values() if о["код"] == код)
        сотрудники.append({"id": ч["id"], "фио": фио(ч), "коротко": фио(ч, True), "должность": ч["должность"],
                           "табельный": ч["табельный"], "отметки": свои, "итоги": итоги})
    к = _КАЛЕНДАРЬ.get(дни[0].year)
    return {"месяц": месяц, "дни": [{"день": д.isoformat(), "число": д.day, "выходной": выходной(д), "сокращённый": сокращённый(д),
                                     "праздник": bool(к and д in к["нерабочие"]),
                                     "нед": "пн вт ср чт пт сб вс".split()[д.weekday()]} for д in дни],
            "сотрудники": сотрудники, "коды": КОДЫ_ТАБЕЛЯ, "норма": норма_месяца(месяц),
            "календарь": {"годы": sorted(_КАЛЕНДАРЬ), "источник": к["источник"] if к else ""},
            "периоды": периоды(база, месяц), "виды_периодов": КОДЫ_ПЕРИОДОВ}


def отметить(база, сотрудник_id: int, день: str, код: str, часы) -> None:
    день = _дата(день)
    if код and код not in КОДЫ_ТАБЕЛЯ:
        raise ОшибкаРаботы("Нет такого кода табеля.")
    with база.соединение() as связь:
        if not код:
            связь.execute("DELETE FROM раб_табель WHERE сотрудник_id = ? AND день = ?", (сотрудник_id, день))
            return
        if часы in (None, ""):
            часы = КОДЫ_ТАБЕЛЯ[код]["часы"]
        связь.execute("INSERT OR REPLACE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                      (сотрудник_id, день, код, float(часы)))


def заполнить_табель(база, месяц: str, сотрудник_id: int | None = None) -> int:
    """Пустые клетки: будни — «Я» 8 ч, выходные и праздники — «В». Уже отмеченное не трогается."""
    дни = _дни_месяца(месяц)
    with база.соединение() as связь:
        люди = [р[0] for р in связь.execute("SELECT id FROM раб_сотрудники WHERE уволен = 0" +
                                             (" AND id = ?" if сотрудник_id else ""), (сотрудник_id,) if сотрудник_id else ())]
        сделано = 0
        for сид in люди:
            for д in дни:
                код = "В" if выходной(д) else "Я"
                часы = 0 if код == "В" else (7 if сокращённый(д) else 8)
                сделано += связь.execute("INSERT OR IGNORE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                                         (сид, д.isoformat(), код, часы)).rowcount
    return сделано


# ---- Табель: отпуска, больничные, командировки периодом ---------------------------------

КОДЫ_ПЕРИОДОВ = {"ОТ": "отпуск", "Б": "больничный", "К": "командировка", "ДО": "без сохранения"}


def _код_дня(код: str, д: date) -> tuple[str, float]:
    """Какой код и сколько часов ставить в день периода."""
    if код == "ОТ" and (д.month, д.day) in ПРАЗДНИКИ:
        return "В", 0                     # нерабочие праздники (ст. 112 ТК) в отпуск не входят, перенесённые выходные — входят
    if код == "К":
        return ("К", 7 if сокращённый(д) else 8) if not выходной(д) else ("К", 0)
    return код, 0


def периоды(база, месяц: str | None = None) -> list[dict]:
    with база.соединение() as связь:
        if месяц:
            дни = _дни_месяца(месяц)
            строки = связь.execute("SELECT * FROM раб_периоды WHERE с <= ? AND по >= ? ORDER BY с",
                                   (дни[-1].isoformat(), дни[0].isoformat())).fetchall()
        else:
            строки = связь.execute("SELECT * FROM раб_периоды ORDER BY с DESC").fetchall()
    люди = _все(база, "раб_сотрудники")
    return [{**dict(р), "сотрудник": фио(люди.get(р["сотрудник_id"]), True), "вид": КОДЫ_ПЕРИОДОВ.get(р["код"], р["код"])}
            for р in строки]


def добавить_период(база, сотрудник_id: int, код: str, с: str, по: str, заметка: str = "") -> dict:
    if код not in КОДЫ_ПЕРИОДОВ:
        raise ОшибкаРаботы("Период: отпуск, больничный, командировка или без сохранения.")
    с, по = _дата(с), _дата(по)
    if not с or not по:
        raise ОшибкаРаботы("Укажите даты «с» и «по».")
    if по < с:
        raise ОшибкаРаботы("Дата «по» раньше даты «с».")
    начало, конец = date.fromisoformat(с), date.fromisoformat(по)
    if (конец - начало).days > 366:
        raise ОшибкаРаботы("Период больше года.")
    with база.соединение() as связь:
        if not связь.execute("SELECT 1 FROM раб_сотрудники WHERE id = ?", (сотрудник_id,)).fetchone():
            raise ОшибкаРаботы("Нет такого сотрудника.")
        номер = связь.execute("INSERT INTO раб_периоды (сотрудник_id, код, с, по, заметка) VALUES (?, ?, ?, ?, ?)",
                              (сотрудник_id, код, с, по, str(заметка or "")[:200])).lastrowid
        д = начало
        while д <= конец:
            к, ч = _код_дня(код, д)
            связь.execute("INSERT OR REPLACE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                          (сотрудник_id, д.isoformat(), к, ч))
            д += timedelta(days=1)
    return {"id": номер, "дней": (конец - начало).days + 1}


def удалить_период(база, номер: int) -> bool:
    """Убирает период и возвращает в эти дни обычный график (будни «Я», выходные «В»)."""
    with база.соединение() as связь:
        р = связь.execute("SELECT * FROM раб_периоды WHERE id = ?", (номер,)).fetchone()
        if not р:
            return False
        связь.execute("DELETE FROM раб_периоды WHERE id = ?", (номер,))
        д, конец = date.fromisoformat(р["с"]), date.fromisoformat(р["по"])
        while д <= конец:
            код = "В" if выходной(д) else "Я"
            связь.execute("INSERT OR REPLACE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                          (р["сотрудник_id"], д.isoformat(), код, 0 if код == "В" else (7 if сокращённый(д) else 8)))
            д += timedelta(days=1)
    return True


