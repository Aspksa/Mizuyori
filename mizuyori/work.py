УРОВНИ = {"просрочено": 0, "сегодня": 1, "срочно": 2, "скоро": 3}


def пробеги(база) -> dict[int, float]:
    """Последний известный пробег машины — по путевым листам (самый большой км)."""
    with база.соединение() as связь:
        return {р[0]: р[1] for р in связь.execute(
            "SELECT автомобиль_id, MAX(MAX(COALESCE(км_конец, 0)), MAX(COALESCE(км_начало, 0))) FROM раб_путевые "
            "GROUP BY автомобиль_id HAVING MAX(MAX(COALESCE(км_конец, 0)), MAX(COALESCE(км_начало, 0))) > 0")}


def _по_сроку(что: str, до: str | None, сегодня: date) -> dict | None:
    """Срок: за 30, 14 и 3 дня — напоминание, после — «просрочено»."""
    if not до:
        return None
    дней = (date.fromisoformat(до) - сегодня).days
    if дней < 0:
        return {"текст": f"{что}: просрочено с {_рус(до)}", "уровень": "просрочено", "дней": дней}
    if дней <= 3:
        return {"текст": f"{что}: {'сегодня' if дней == 0 else f'через {дней} дн.'} ({_рус(до)})", "уровень": "сегодня", "дней": дней}
    if дней <= 14:
        return {"текст": f"{что}: через {дней} дн. ({_рус(до)})", "уровень": "срочно", "дней": дней}
    if дней <= 30:
        return {"текст": f"{что}: до {_рус(до)}", "уровень": "скоро", "дней": дней}
    return None


def напоминания_авто(р: dict, сегодня: date, с: dict) -> list[dict]:
    итог = [н for н in (_по_сроку("ОСАГО", р.get("страховка_до"), сегодня),
                        _по_сроку("Техосмотр", р.get("техосмотр_до"), сегодня)) if н]
    # ТО по пробегу
    if р.get("то_интервал") and р.get("то_пробег") is not None and р.get("пробег_сейчас") is not None:
        осталось = р["то_пробег"] + р["то_интервал"] - р["пробег_сейчас"]
        запас = max(1000, р["то_интервал"] * 0.1)
        if осталось <= 0:
            итог.append({"текст": f"ТО просрочено на {abs(осталось):,.0f} км".replace(",", " "), "уровень": "просрочено", "дней": -1})
        elif осталось <= запас:
            итог.append({"текст": f"до ТО {осталось:,.0f} км".replace(",", " "),
                         "уровень": "срочно" if осталось <= запас / 2 else "скоро", "дней": 10})
    # шины по сезону
    шины = р.get("шины") or ""
    if шины in ("летние", "зимние"):
        нужно = "зимние" if шины == "летние" else "летние"
        граница = с["зима_с"] if нужно == "зимние" else f"{с['зима_по'][:2]}-{с['зима_по'][3:]}"
        if нужно == "летние":   # лето начинается на следующий день после конца зимы
            граница = (date(2001, int(с["зима_по"][:2]), int(с["зима_по"][3:])) + timedelta(days=1)).strftime("%m-%d")
        дата_смены = date(сегодня.year, int(граница[:2]), int(граница[3:]))
        if дата_смены < сегодня - timedelta(days=200):
            дата_смены = date(сегодня.year + 1, дата_смены.month, дата_смены.day)
        сейчас_зима = зимний_день(сегодня, с)
        if (нужно == "зимние") == сейчас_зима:
            итог.append({"текст": f"пора сменить шины на {нужно}", "уровень": "срочно", "дней": 0})
        else:
            н = _по_сроку(f"смена шин на {нужно}", дата_смены.isoformat(), сегодня)
            if н and н["дней"] <= 14:
                итог.append(н)
    итог.sort(key=lambda н: (УРОВНИ[н["уровень"]], н["дней"]))
    return итог


def история_авто(база, автомобиль_id: int, месяцев: int = 12) -> dict:
    """Помесячно: пробег, норма, факт, заправки, остаток — по путевым и выпискам."""
    авто = одна(база, "автомобили", автомобиль_id)
    with база.соединение() as связь:
        месяцы = {р[0] for р in связь.execute("SELECT месяц FROM раб_путевые WHERE автомобиль_id = ?", (автомобиль_id,))}
        месяцы |= {р[0] for р in связь.execute("SELECT DISTINCT substr(дата, 1, 7) FROM раб_гсм")}
    месяцы = sorted(месяцы)[-месяцев:]
    итог = []
    for м_ in месяцы:
        р = next((х for х in _посчитать_месяц(база, м_) if х["автомобиль_id"] == автомобиль_id), None)
        if not р or not (р["есть_запись"] or р["по_карте"]):
            continue
        итог.append({"месяц": м_, "подпись": _месяц_рус(м_), "пробег": р["пробег"], "норма": р["норма"], "факт": р["факт"],
                     "заправлено": р["заправлено"], "сумма": р["сумма_по_карте"], "остаток_конец": р["остаток_конец"],
                     "разница": р["разница"], "сезон": р["сезон_подпись"]})
    return {"автомобиль": авто, "месяцы": итог}


def _рус(iso: str) -> str:
    return datetime.strptime(iso, "%Y-%m-%d").strftime("%d.%m.%Y") if iso else ""


def _проверить_карту(база, поля: dict, номер_записи: int | None = None) -> None:
    if "номер" not in поля:
        return
    поля["номер"] = номер_карты(поля["номер"])
    with база.соединение() as связь:
        for id_, н in связь.execute("SELECT id, номер FROM раб_карты"):
            if id_ != номер_записи and номер_карты(н) == поля["номер"]:
                raise ОшибкаРаботы("Такая карта уже есть в списке «Топливные карты» — откройте её и закрепите там.")


def создать(база, вид: str, данные: dict) -> dict:
    с = СПРАВОЧНИКИ[вид]
    поля = проверить(с, данные, новая=True)
    if вид == "карты":
        _проверить_карту(база, поля)
    if с.get("вид"):
        поля["вид"] = с["вид"]
    if вид == "записки" and not поля.get("номер"):
        поля["номер"] = следующий_номер(база)
    if вид == "записки" and not поля.get("дата"):
        поля["дата"] = date.today().isoformat()
    with база.соединение() as связь:
        номер = связь.execute(f"INSERT INTO {с['таблица']} ({', '.join(поля)}) VALUES ({', '.join('?' * len(поля))})",
                              tuple(поля.values())).lastrowid
    if вид == "сотрудники" and "автомобиль_id" in данные:
        закрепить_авто(база, номер, данные["автомобиль_id"])
    return одна(база, вид, номер)


def изменить(база, вид: str, номер: int, данные: dict) -> dict:
    с = СПРАВОЧНИКИ[вид]
    поля = проверить(с, данные, новая=False)
    if вид == "карты":
        _проверить_карту(база, поля, номер)
    if поля:
        with база.соединение() as связь:
            if not связь.execute(f"UPDATE {с['таблица']} SET {', '.join(f'{к} = ?' for к in поля)} WHERE id = ?",
                                 (*поля.values(), номер)).rowcount:
                raise ОшибкаРаботы("Запись не найдена.")
    if вид == "сотрудники" and "автомобиль_id" in данные:
        закрепить_авто(база, номер, данные["автомобиль_id"])
    if вид == "карты" and "сотрудник_id" in данные:
        закрепить_карту(база, номер, данные["сотрудник_id"])
    return одна(база, вид, номер)


