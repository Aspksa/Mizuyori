def вид_топлива(т: str) -> str:
    """«Бензин … (АИ-95-К5) …» → «АИ-95», «… (ДТ-Л-К5)» → «ДТ летнее»."""
    if м := re.search(r"АИ-?(\d{2,3})", т):
        return f"АИ-{м.group(1)}"
    if м := re.search(r"ДТ-([ЛЗЕА])", т):
        return {"Л": "ДТ летнее", "З": "ДТ зимнее", "Е": "ДТ межсезонное", "А": "ДТ арктическое"}[м.group(1)]
    if re.search(r"дизел|ДТ", т, re.I):
        return "ДТ"
    if re.search(r"газ|пропан|СУГ|LPG", т, re.I):
        return "Газ"
    return т[:30] or "—"


def свод(база, с: str | None, по: str | None) -> dict:
    условие, параметры = [], []
    if с:
        условие.append("дата >= ?"); параметры.append(с)
    if по:
        условие.append("дата <= ?"); параметры.append(по)
    где = f"WHERE {' AND '.join(условие)}" if условие else ""
    with база.соединение() as связь:
        операции = [dict(р) for р in связь.execute(f"SELECT * FROM раб_гсм {где} ORDER BY карта, дата, время", параметры)]
        крайние = связь.execute("SELECT MIN(дата), MAX(дата) FROM раб_гсм").fetchone()
        выписки = [dict(р) for р in связь.execute("SELECT * FROM раб_гсм_выписки ORDER BY id DESC LIMIT 10")]
    # одна и та же карта могла попасть в справочник дважды (из выписки и руками) — берём закреплённую
    закреплённые = {ч["карта_id"] for ч in _все(база, "раб_сотрудники").values() if ч["карта_id"]}
    карты: dict[str, dict] = {}
    for к_ in sorted(_все(база, "раб_карты").values(), key=lambda к_: к_["id"] in закреплённые):
        карты[номер_карты(к_["номер"])] = к_
    люди = _все(база, "раб_сотрудники")
    машины = _все(база, "раб_автомобили")
    по_картам: dict[str, dict] = {}
    виды = []
    for о in операции:
        вид = вид_топлива(о["топливо"])
        о["вид"] = вид
        if вид not in виды:
            виды.append(вид)
        к = по_картам.setdefault(о["карта"], {"карта": о["карта"], "литры": 0.0, "сумма": 0.0, "операций": 0,
                                               "возвратов": 0, "по_видам": {}, "операции": []})
        к["литры"] += о["количество"] or 0
        к["сумма"] += о["сумма"] or 0
        к["операций"] += 1
        к["возвратов"] += о["операция"] == "Возврат"
        в = к["по_видам"].setdefault(вид, {"литры": 0.0, "сумма": 0.0})
        в["литры"] += о["количество"] or 0
        в["сумма"] += о["сумма"] or 0
        к["операции"].append(о)
    строки = []
    for номер, к in по_картам.items():
        карта = карты.get(номер_карты(номер))
        человек = next((ч for ч in люди.values() if карта and ч["карта_id"] == карта["id"]), None)
        авто = next((а for а in машины.values() if человек and а["водитель_id"] == человек["id"]), None)
        к.update({"карта_id": карта["id"] if карта else None, "лимит": карта.get("лимит") if карта else None,
                  "сотрудник": фио(человек), "сотрудник_id": человек["id"] if человек else None,
                  "должность": (человек or {}).get("должность", ""), "автомобиль": авто_подпись(авто),
                  "госномер": (авто or {}).get("госномер", ""), "расход_лето": (авто or {}).get("расход_лето"),
                  "расход_зима": (авто or {}).get("расход_зима"),
                  "литры": round(к["литры"], 2), "сумма": round(к["сумма"], 2)})
        строки.append(к)
    строки.sort(key=lambda к: (not к["сотрудник"], к["сотрудник"] or к["карта"]))
    итог_видов = {в: {"литры": round(sum(к["по_видам"].get(в, {}).get("литры", 0) for к in строки), 2),
                      "сумма": round(sum(к["по_видам"].get(в, {}).get("сумма", 0) for к in строки), 2)} for в in виды}
    return {"карты": строки, "виды": виды, "итого": {"литры": round(sum(к["литры"] for к in строки), 2),
                                                      "сумма": round(sum(к["сумма"] for к in строки), 2),
                                                      "операций": len(операции), "по_видам": итог_видов},
            "с": с, "по": по, "данные_с": крайние[0], "данные_по": крайние[1], "выписки": выписки}


# ---- ГСМ: расчёт по путевым листам ---------------------------------------------------
# Пробег = км конец (последняя путевая) − км начало (первая путевая).
# По норме, л = пробег × норма (лето или зима, из карточки автомобиля) / 100.
# По факту, л = как записано в путевых; если не записано — равен норме.
# Остаток на конец считается сам: остаток на начало + заправлено − расход по факту.
# Заправлено = по карте водителя за месяц + не по карте. Отклонение = факт − норма.

ПОЛЯ_ПУТЕВЫХ = ("сезон", "км_начало", "км_конец", "остаток_начало", "остаток_конец", "расход_факт", "заправлено_доп", "заметка")


# Водители пишут остаток в путевых целыми литрами (42,26 → 42) — остаток на конец округляется так же,
# а расход по факту (если не записан) получается из округлённого остатка, чтобы совпадало с бумагой.
ОКРУГЛЕНИЕ = {"целые": 0, "десятые": 1, "нет": None}


def округление(база) -> str:
    з = база.прочитать("работа.округление", "целые")
    return з if з in ОКРУГЛЕНИЕ else "целые"


def _округлить(ч: float, знаков: int | None) -> float:
    if знаков is None:
        return round(ч, 2)
    from decimal import ROUND_HALF_UP, Decimal
    return float(Decimal(str(ч)).quantize(Decimal(1).scaleb(-знаков), rounding=ROUND_HALF_UP))


def сезоны(база) -> dict:
    з = база.прочитать("работа.сезоны", {}) or {}
    return {**СЕЗОНЫ_ПО_УМОЛЧАНИЮ, **{к: в for к, в in з.items() if к in СЕЗОНЫ_ПО_УМОЛЧАНИЮ}}


def сохранить_сезоны(база, данные: dict) -> dict:
    итог = сезоны(база)
    for к in СЕЗОНЫ_ПО_УМОЛЧАНИЮ:
        if к in данные:
            т = str(данные[к]).strip()
            м = re.fullmatch(r"(\d{1,2})\.(\d{1,2})", т) or re.fullmatch(r"(\d{1,2})-(\d{1,2})", т)
            if not м:
                raise ОшибкаРаботы("Дата сезона — день и месяц, например 15.11.")
            день, мес = (int(м.group(1)), int(м.group(2))) if "." in т else (int(м.group(2)), int(м.group(1)))
            try:
                date(2024, мес, день)
            except ValueError:
                raise ОшибкаРаботы("Нет такой даты.")
            итог[к] = f"{мес:02d}-{день:02d}"
    база.записать("работа.сезоны", итог)
    return итог


def зимний_день(д: date, с: dict) -> bool:
    начало, конец = с["зима_с"], с["зима_по"]
    мд = д.strftime("%m-%d")
    return мд >= начало or мд <= конец if начало > конец else начало <= мд <= конец


def _сезон_по_умолчанию(месяц: str) -> str:
    return "зима" if int(месяц[5:7]) in ЗИМНИЕ_МЕСЯЦЫ else "лето"


def сверить_закрепления(база) -> None:
    """Текущий водитель машины = открытое закрепление. Сменили водителя — старое закрывается вчерашним днём,
    новое начинается сегодня (дату можно поправить в карточке автомобиля)."""
    сегодня = date.today()
    с_, вчера = сегодня.isoformat(), (сегодня - timedelta(days=1)).isoformat()
    with база.соединение() as связь:
        for авто_id, водитель_id in [(р[0], р[1]) for р in связь.execute("SELECT id, водитель_id FROM раб_автомобили")]:
            открытое = связь.execute("SELECT id, сотрудник_id, с FROM раб_закрепления WHERE автомобиль_id = ? AND по IS NULL",
                                     (авто_id,)).fetchone()
            if открытое and открытое["сотрудник_id"] == водитель_id:
                continue
            if открытое:
                if открытое["с"] >= с_:
                    связь.execute("DELETE FROM раб_закрепления WHERE id = ?", (открытое["id"],))
                else:
                    связь.execute("UPDATE раб_закрепления SET по = ? WHERE id = ?", (вчера, открытое["id"]))
            if водитель_id:
                связь.execute("INSERT INTO раб_закрепления (автомобиль_id, сотрудник_id, с) VALUES (?, ?, ?)", (авто_id, водитель_id, с_))


def _закрепления(база) -> list[dict]:
    сверить_закрепления(база)
    with база.соединение() as связь:
        return [dict(р) for р in связь.execute("SELECT * FROM раб_закрепления ORDER BY с, id")]


def _раздать_заправки(база, с: date, по: date) -> dict:
    """Заправки по карте относятся к машине, на которой сотрудник ездил в день заправки.
    Остаток в баке при этом остаётся у машины: сменил машину — на новой считается её остаток."""
    карты, люди = _все(база, "раб_карты"), _все(база, "раб_сотрудники")
    человек_по_карте = {номер_карты(карты[ч["карта_id"]]["номер"]): ч["id"] for ч in люди.values() if ч["карта_id"] in карты}
    по_человеку: dict[int, list[dict]] = {}
    for з in _закрепления(база):
        по_человеку.setdefault(з["сотрудник_id"], []).append(з)
    итог = {"по_авто": {}, "общие": set(), "лишнее_литров": 0.0, "лишние_карты": set()}
    with база.соединение() as связь:
        операции = связь.execute("SELECT карта, дата, количество, сумма FROM раб_гсм WHERE дата BETWEEN ? AND ?",
                                 (с.isoformat(), по.isoformat())).fetchall()
    for карта, день, литры_, сумма_ in операции:
        н = номер_карты(карта)
        машины = sorted(з["автомобиль_id"] for з in по_человеку.get(человек_по_карте.get(н), [])
                        if з["с"] <= день and (з["по"] is None or з["по"] >= день))
        if not машины:
            итог["лишнее_литров"] += литры_ or 0
            итог["лишние_карты"].add(н)
            continue
        if len(машины) > 1:
            итог["общие"].update(машины)       # у сотрудника две машины сразу — относим на первую и предупреждаем
        л, сум = итог["по_авто"].get(машины[0], (0.0, 0.0))
        итог["по_авто"][машины[0]] = (л + (литры_ or 0), сум + (сумма_ or 0))
    return итог


def _посчитать_месяц(база, месяц: str) -> list[dict]:
    дни = _дни_месяца(месяц)
    с, по = дни[0].isoformat(), дни[-1].isoformat()
    машины = sorted(_все(база, "раб_автомобили").values(), key=lambda а: (а["марка"], а["модель"], а["госномер"]))
    люди = _все(база, "раб_сотрудники")
    карты = _все(база, "раб_карты")
    with база.соединение() as связь:
        записи = {р["автомобиль_id"]: dict(р) for р in связь.execute("SELECT * FROM раб_путевые WHERE месяц = ?", (месяц,))}
        месяцы_карт: dict[str, list[str]] = {}
        for карта, м_ in связь.execute("SELECT DISTINCT карта, substr(дата, 1, 7) FROM раб_гсм ORDER BY 2"):
            месяцы_карт.setdefault(номер_карты(карта), []).append(м_)
    раздано = _раздать_заправки(база, дни[0], дни[-1])
    интервалы = _закрепления(база)
    настройки_сезонов = сезоны(база)
    знаков = ОКРУГЛЕНИЕ[округление(база)]
    дней_зимы = sum(1 for д in дни if зимний_день(д, настройки_сезонов))
    строки = []
    for а in машины:
        з = записи.get(а["id"], {})
        # кто ездил на машине в этом месяце (при смене водителя — несколько); заправки — по дням закрепления
        закрепы = sorted((i for i in интервалы if i["автомобиль_id"] == а["id"] and i["с"] <= по and (i["по"] is None or i["по"] >= с)),
                         key=lambda i: i["с"])
        водители = [люди[i["сотрудник_id"]] for i in закрепы if i["сотрудник_id"] in люди]
        водитель = водители[-1] if водители else None
        карта = карты.get(водитель["карта_id"]) if водитель else None
        по_карте, сумма = раздано["по_авто"].get(а["id"], (0.0, 0.0))
        выбран = з.get("сезон") or ""
        сезон = выбран or ("зима" if дней_зимы == len(дни) else "лето" if дней_зимы == 0 else "смешанный")
        if сезон == "смешанный":
            # граница сезона внутри месяца: пробег делится по дням, норма — частями
            лето, зима = а["расход_лето"] or а["расход_зима"], а["расход_зима"] or а["расход_лето"]
            норма_100 = round((зима * дней_зимы + лето * (len(дни) - дней_зимы)) / len(дни), 3) if лето and зима else None
            сезон_подпись = f"зима {дней_зимы} дн. + лето {len(дни) - дней_зимы} дн."
        else:
            норма_100 = а["расход_зима"] if сезон == "зима" else а["расход_лето"]
            сезон_подпись = сезон + ("" if выбран else " (по датам)")
        замена_нормы = ""
        if not норма_100 and сезон != "смешанный":
            # нет нормы на этот сезон — берём другую, чтобы считалось, и предупреждаем
            другая = а["расход_лето"] if сезон == "зима" else а["расход_зима"]
            if другая:
                норма_100 = другая
                замена_нормы = f"нет {'зимней' if сезон == 'зима' else 'летней'} нормы — взята {'летняя' if сезон == 'зима' else 'зимняя'}"
        р = {"автомобиль_id": а["id"], "автомобиль": авто_подпись(а), "топливо": а["топливо"],
             "водитель": " → ".join(dict.fromkeys(фио(в) for в in водители)), "карта": карта["номер"] if карта else "",
             "сезон": выбран or "авто", "сезон_подпись": сезон_подпись, "норма_100": норма_100, "есть_запись": bool(з),
             **{к: з.get(к) for к in ПОЛЯ_ПУТЕВЫХ if к != "сезон"},
             "по_карте": round(по_карте, 2), "сумма_по_карте": round(сумма, 2)}
        р["заметка"] = р["заметка"] or ""
        р["км_начало_авто"] = bool(з.get("км_начало_авто")) and р["км_начало"] is not None
        р["остаток_начало_авто"] = bool(з.get("остаток_начало_авто")) and р["остаток_начало"] is not None
        р["общая_карта"] = а["id"] in раздано["общие"]
        # почему по карте 0 — чтобы было видно, что поправить
        if not водители:
            р["причина_нуля"] = "водитель не закреплён"
        elif not any(карты.get(в["карта_id"]) for в in водители):
            р["причина_нуля"] = "у водителя нет топливной карты"
        elif not по_карте:
            есть = sorted({м_ for в in водители if карты.get(в["карта_id"])
                           for м_ in месяцы_карт.get(номер_карты(карты[в["карта_id"]]["номер"]), [])})
            р["причина_нуля"] = (f"за этот месяц заправок нет, есть за: {', '.join(_месяц_рус(м_) for м_ in есть[-3:])}" if есть
                                 else "по этой карте нет заправок в загруженных выписках")
        else:
            р["причина_нуля"] = ""
        заправлено = по_карте + (р["заправлено_доп"] or 0)
        р["заправлено"] = round(заправлено, 2)
        р["пробег"] = (round(р["км_конец"] - р["км_начало"], 1)
                       if р["км_начало"] is not None and р["км_конец"] is not None else None)
        р["норма"] = round(р["пробег"] * норма_100 / 100, 2) if р["пробег"] is not None and норма_100 else None
        # остаток на конец из последней путевой: если вписан — факт считается из него
        р["остаток_введён"] = р.pop("остаток_конец")
        р["факт_из_остатка"] = р["остаток_введён"] is not None and р["остаток_начало"] is not None
        р["факт_введён"] = р["расход_факт"] is not None or р["факт_из_остатка"]
        if р["факт_из_остатка"]:
            р["факт"] = round(р["остаток_начало"] + заправлено - р["остаток_введён"], 2)
        else:
            р["факт"] = р["расход_факт"] if р["расход_факт"] is not None else р["норма"]
        р["округлено"] = None
        if р["факт_из_остатка"]:
            р["остаток_конец"] = р["остаток_введён"]
        elif р["остаток_начало"] is not None and р["факт"] is not None:
            точно = р["остаток_начало"] + заправлено - р["факт"]
            р["остаток_конец"] = _округлить(точно, знаков)
            р["округлено"] = round(р["остаток_конец"] - точно, 2) or None
            if not р["факт_введён"] and р["округлено"]:
                # факт по бумаге: из округлённого остатка (отличается от нормы на доли литра)
                р["факт"] = round(р["остаток_начало"] + заправлено - р["остаток_конец"], 2)
        else:
            р["остаток_конец"] = None
        р["разница"] = round(р["факт"] - р["норма"], 2) if р["факт_введён"] and р["норма"] is not None else None
        р["процент"] = round(р["разница"] / р["норма"] * 100, 1) if р["разница"] is not None and р["норма"] else None
        р["ошибка"] = ("км на конец меньше, чем на начало" if р["пробег"] is not None and р["пробег"] < 0
                       else "остаток на конец меньше нуля — проверьте" if р["остаток_конец"] is not None and р["остаток_конец"] < 0
                       else "нет нормы расхода в карточке автомобиля" if not норма_100
                       else замена_нормы)
        # чего не хватает для расчёта — подсказка в строке
        нужно = [название for условие, название in (
            (р["км_начало"] is None, "км на начало"), (р["км_конец"] is None, "км на конец"),
            (р["остаток_начало"] is None, "остаток на начало")) if условие]
        р["не_хватает"] = нужно
        строки.append(р)
    return строки


def _месяц_рус(м_: str) -> str:
    return f"{МЕСЯЦЫ[int(м_[5:7]) - 1]} {м_[:4]}"


def _заполнен(р: dict) -> bool:
    """В месяце по машине есть хоть что-то из путевых (иначе в анализ за период он не входит)."""
    return any(р.get(к) is not None for к in ("км_начало", "км_конец", "остаток_начало", "остаток_введён", "расход_факт"))


def _месяцы_данных(база) -> list[str]:
    with база.соединение() as связь:
        из_гсм = {р[0] for р in связь.execute("SELECT DISTINCT substr(дата, 1, 7) FROM раб_гсм")}
        из_путевых = {р[0] for р in связь.execute(
            "SELECT DISTINCT месяц FROM раб_путевые WHERE км_начало IS NOT NULL OR км_конец IS NOT NULL "
            "OR остаток_начало IS NOT NULL OR остаток_конец IS NOT NULL OR расход_факт IS NOT NULL")}
    return sorted(из_гсм | из_путевых)


def _итоги(база, строки: list[dict], с: date, по: date) -> dict:
    """Итоги по строкам."""
    итог = {"пробег": 0.0, "норма": 0.0, "факт": 0.0, "заправлено_доп": 0.0, "по_карте": 0.0, "сумма": 0.0,
            "остаток_начало": 0.0, "остаток_конец": 0.0}
    for р in строки:
        for к in ("пробег", "норма", "факт", "остаток_начало", "остаток_конец", "заправлено_доп", "по_карте"):
            итог[к] += р[к] or 0
        итог["сумма"] += р["сумма_по_карте"]
    итог["заправлено"] = итог["по_карте"] + итог["заправлено_доп"]
    # заправки, которые не удалось отнести ни к одной машине (карта не закреплена или сотрудник в тот день без машины)
    раздано = _раздать_заправки(база, с, по)
    лишнее, лишних_карт = раздано["лишнее_литров"], len(раздано["лишние_карты"])
    с_разницей = [р for р in строки if р["разница"] is not None]
    итог = {к: round(з, 2) for к, з in итог.items()}
    итог["разница"] = round(sum(р["разница"] for р in с_разницей), 2)
    база_нормы = sum(р["норма"] or 0 for р in с_разницей)
    итог["процент"] = round(итог["разница"] / база_нормы * 100, 1) if база_нормы else None
    итог["машин"] = len(строки)
    итог["перерасход"] = sum(1 for р in с_разницей if р["разница"] > 0)
    итог["экономия"] = sum(1 for р in с_разницей if р["разница"] < 0)
    итог["без_данных"] = sum(1 for р in строки if р["пробег"] is None)
    итог["без_машины_литров"] = round(лишнее, 2)
    итог["без_машины_карт"] = лишних_карт
    return итог


def путевые(база, месяц: str, перенос: bool = True) -> dict:
    if перенос:
        перенести_путевые(база, месяц)     # начало месяца = конец прошлого — само, где не вписано вручную
    строки = _посчитать_месяц(база, месяц)
    первый = _дни_месяца(месяц)[0]
    прошлые = {р["автомобиль_id"]: р for р in _посчитать_месяц(база, (первый - timedelta(days=1)).strftime("%Y-%m"))
               if р["есть_запись"]}
    for р in строки:
        п = прошлые.get(р["автомобиль_id"], {})
        # подсказки: конец прошлого месяца = начало этого
        р["подсказка_км"] = п.get("км_конец")
        р["подсказка_остаток"] = п.get("остаток_конец")
    дни = _дни_месяца(месяц)
    return _оформить(база, строки, _итоги(база, строки, дни[0], дни[-1]), [месяц])


def _оформить(база, строки, итог, месяцы, **доп) -> dict:
    с = сезоны(база)
    with база.соединение() as связь:
        месяцы_гсм = [р[0] for р in связь.execute("SELECT DISTINCT substr(дата, 1, 7) FROM раб_гсм ORDER BY 1")]
    return {"месяц": месяцы[0], "месяцы": месяцы, "период": len(месяцы) > 1, "строки": строки, "итого": итог,
            "сезоны": с, "округление": округление(база),
            "сезоны_подпись": f"зима с {с['зима_с'][3:]}.{с['зима_с'][:2]} по {с['зима_по'][3:]}.{с['зима_по'][:2]}",
            "месяцы_гсм": месяцы_гсм, "месяцы_данных": _месяцы_данных(база), **доп}


def _месяцы_между(с: str, по: str) -> list[str]:
    _дни_месяца(с); _дни_месяца(по)
    if с > по:
        с, по = по, с
    г, м = int(с[:4]), int(с[5:7])
    итог = []
    while f"{г:04d}-{м:02d}" <= по:
        итог.append(f"{г:04d}-{м:02d}")
        г, м = (г + 1, 1) if м == 12 else (г, м + 1)
        if len(итог) > 60:
            raise ОшибкаРаботы("Период слишком длинный — не больше пяти лет.")
    return итог


def _свернуть_машину(ряды: list[tuple[str, dict]]) -> dict:
    """Одна машина за несколько месяцев: суммы по месяцам, где есть путевые; начало — из первого, конец — из последнего."""
    заполненные = [(м, р) for м, р in ряды if _заполнен(р)]
    шаблон = ряды[-1][1]

    def сумма(к):
        з = [р[к] for _, р in заполненные if р[к] is not None]
        return round(sum(з), 2) if з else None

    def первое(к):
        return next((р[к] for _, р in заполненные if р[к] is not None), None)

    def последнее(к):
        return next((р[к] for _, р in reversed(заполненные) if р[к] is not None), None)

    р = {к: шаблон[к] for к in ("автомобиль_id", "автомобиль", "топливо", "водитель", "карта", "общая_карта")}
    р.update(
        период=True, сезон="авто", сезон_подпись="", есть_запись=bool(заполненные), заметка="",
        км_начало=первое("км_начало"), км_конец=последнее("км_конец"),
        остаток_начало=первое("остаток_начало"), остаток_конец=последнее("остаток_конец"),
        остаток_введён=последнее("остаток_введён"),
        пробег=сумма("пробег"), норма=сумма("норма"), факт=сумма("факт"),
        по_карте=round(sum(r["по_карте"] for _, r in заполненные), 2),
        сумма_по_карте=round(sum(r["сумма_по_карте"] for _, r in заполненные), 2),
        заправлено_доп=сумма("заправлено_доп") or 0.0)
    р["заправлено"] = round(р["по_карте"] + р["заправлено_доп"], 2)
    с_разницей = [r for _, r in заполненные if r["разница"] is not None]
    р["разница"] = round(sum(r["разница"] for r in с_разницей), 2) if с_разницей else None
    нормы = sum(r["норма"] or 0 for r in с_разницей)
    р["процент"] = round(р["разница"] / нормы * 100, 1) if р["разница"] is not None and нормы else None
    р["норма_100"] = round(р["норма"] / р["пробег"] * 100, 2) if р["норма"] and р["пробег"] else None
    ошибки = list(dict.fromkeys(r["ошибка"] for _, r in заполненные if r["ошибка"]))
    р["ошибка"] = "; ".join(ошибки)
    р["причина_нуля"] = ""
    р["не_хватает"] = []
    # стык месяцев: начало + заправлено − расход должно дать конец; расхождение — значит, где-то остаток не сходится
    можно = all(х is not None for х in (р["остаток_начало"], р["остаток_конец"], р["факт"]))
    р["невязка"] = round(р["остаток_начало"] + р["заправлено"] - р["факт"] - р["остаток_конец"], 2) if можно else None
    р["по_месяцам"] = [{"месяц": м, "подпись": _месяц_рус(м), "заполнен": _заполнен(r), "пробег": r["пробег"], "норма": r["норма"],
                        "факт": r["факт"], "разница": r["разница"], "заправлено": r["заправлено"], "остаток_конец": r["остаток_конец"]}
                       for м, r in ряды]
    р["месяцев_с_данными"] = len(заполненные)
    р["месяцев_всего"] = len(ряды)
    return р


def анализ(база, с: str, по: str) -> dict:
    """Анализ движения ГСМ за месяц или за период из нескольких месяцев."""
    месяцы = _месяцы_между(с, по)
    if len(месяцы) == 1:
        return путевые(база, месяцы[0])
    for м in месяцы:                       # по порядку: конец каждого месяца становится началом следующего
        перенести_путевые(база, м)
    помесячно = {м: {р["автомобиль_id"]: р for р in _посчитать_месяц(база, м)} for м in месяцы}
    порядок = [р["автомобиль_id"] for р in _посчитать_месяц(база, месяцы[-1])]
    строки = [_свернуть_машину([(м, помесячно[м][а]) for м in месяцы if а in помесячно[м]]) for а in порядок]
    итог = _итоги(база, строки, _дни_месяца(месяцы[0])[0], _дни_месяца(месяцы[-1])[-1])
    итог["невязка"] = round(sum(р["невязка"] or 0 for р in строки), 2)
    return _оформить(база, строки, итог, месяцы)


def сохранить_путевой(база, месяц: str, автомобиль_id: int, данные: dict) -> None:
    _дни_месяца(месяц)
    поля = {}
    for к in ПОЛЯ_ПУТЕВЫХ:
        if к not in данные:
            continue
        з = данные[к]
        if к == "сезон":
            з = "" if з == "авто" else з
            if з not in ("", "лето", "зима"):
                raise ОшибкаРаботы("Сезон — лето или зима.")
        elif к == "заметка":
            з = str(з or "")[:300]
        else:
            з = None if з in (None, "") else _число(з)
            if з is None and данные[к] not in (None, ""):
                raise ОшибкаРаботы("Нужно число.")
            if з is not None and з < 0:
                raise ОшибкаРаботы("Не может быть меньше нуля.")
        поля[к] = з
    if not поля:
        return
    for к in ("км_начало", "остаток_начало"):
        if к in поля:
            поля[f"{к}_авто"] = 0          # вписали руками — больше не перезаписывается переносом
    with база.соединение() as связь:
        связь.execute("INSERT OR IGNORE INTO раб_путевые (месяц, автомобиль_id) VALUES (?, ?)", (месяц, автомобиль_id))
        связь.execute(f"UPDATE раб_путевые SET {', '.join(f'{к} = ?' for к in поля)} WHERE месяц = ? AND автомобиль_id = ?",
                      (*поля.values(), месяц, автомобиль_id))


def перенести_путевые(база, месяц: str) -> int:
    """Начало месяца = конец прошлого: км и посчитанный остаток. Вписанное руками не трогаем;
    подставленное раньше — обновляем, если в прошлом месяце цифры поменялись."""
    первый = _дни_месяца(месяц)[0]
    прошлые = _посчитать_месяц(база, (первый - timedelta(days=1)).strftime("%Y-%m"))
    перенесено = 0
    with база.соединение() as связь:
        for р in прошлые:
            if not р["есть_запись"] or (р["км_конец"] is None and р["остаток_конец"] is None):
                continue
            связь.execute("INSERT OR IGNORE INTO раб_путевые (месяц, автомобиль_id) VALUES (?, ?)", (месяц, р["автомобиль_id"]))
            текущая = dict(связь.execute("SELECT * FROM раб_путевые WHERE месяц = ? AND автомобиль_id = ?",
                                         (месяц, р["автомобиль_id"])).fetchone())
            for поле, новое in (("км_начало", р["км_конец"]), ("остаток_начало", р["остаток_конец"])):
                if новое is None:
                    continue
                было, авто = текущая[поле], текущая[f"{поле}_авто"]
                if было is None or (авто and было != новое):
                    связь.execute(f"UPDATE раб_путевые SET {поле} = ?, {поле}_авто = 1 WHERE месяц = ? AND автомобиль_id = ?",
                                  (новое, месяц, р["автомобиль_id"]))
                    перенесено += 1
    return перенесено


