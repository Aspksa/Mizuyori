КОДЫ_ПЕРИОДОВ = {"ОТ": "отпуск", "Б": "больничный", "К": "командировка", "ДО": "без сохранения"}


def _код_дня(код: str, д: date) -> tuple[str, float]:
    """Какой код и сколько часов ставить в день периода."""
    if код == "ОТ" and (д.month, д.day) in ПРАЗДНИКИ:
        return "В", 0                     # нерабочие праздники (ст. 112 ТК) в отпуск не входят, перенесённые выходные — входят
    if код == "К":
        return ("К", 7 if сокращённый(д) else 8) if not выходной(д) else ("К", 0)
    return код, 0


def периоды(база, месяц: str | None = None) -> list[dict]:
    with база.соединение() as связь:
        if месяц:
            дни = _дни_месяца(месяц)
            строки = связь.execute("SELECT * FROM раб_периоды WHERE с <= ? AND по >= ? ORDER BY с",
                                   (дни[-1].isoformat(), дни[0].isoformat())).fetchall()
        else:
            строки = связь.execute("SELECT * FROM раб_периоды ORDER BY с DESC").fetchall()
    люди = _все(база, "раб_сотрудники")
    return [{**dict(р), "сотрудник": фио(люди.get(р["сотрудник_id"]), True), "вид": КОДЫ_ПЕРИОДОВ.get(р["код"], р["код"])}
            for р in строки]


def добавить_период(база, сотрудник_id: int, код: str, с: str, по: str, заметка: str = "") -> dict:
    if код not in КОДЫ_ПЕРИОДОВ:
        raise ОшибкаРаботы("Период: отпуск, больничный, командировка или без сохранения.")
    с, по = _дата(с), _дата(по)
    if not с or not по:
        raise ОшибкаРаботы("Укажите даты «с» и «по».")
    if по < с:
        raise ОшибкаРаботы("Дата «по» раньше даты «с».")
    начало, конец = date.fromisoformat(с), date.fromisoformat(по)
    if (конец - начало).days > 366:
        raise ОшибкаРаботы("Период больше года.")
    with база.соединение() as связь:
        if not связь.execute("SELECT 1 FROM раб_сотрудники WHERE id = ?", (сотрудник_id,)).fetchone():
            raise ОшибкаРаботы("Нет такого сотрудника.")
        номер = связь.execute("INSERT INTO раб_периоды (сотрудник_id, код, с, по, заметка) VALUES (?, ?, ?, ?, ?)",
                              (сотрудник_id, код, с, по, str(заметка or "")[:200])).lastrowid
        д = начало
        while д <= конец:
            к, ч = _код_дня(код, д)
            связь.execute("INSERT OR REPLACE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                          (сотрудник_id, д.isoformat(), к, ч))
            д += timedelta(days=1)
    return {"id": номер, "дней": (конец - начало).days + 1}


def удалить_период(база, номер: int) -> bool:
    """Убирает период и возвращает в эти дни обычный график (будни «Я», выходные «В»)."""
    with база.соединение() as связь:
        р = связь.execute("SELECT * FROM раб_периоды WHERE id = ?", (номер,)).fetchone()
        if not р:
            return False
        связь.execute("DELETE FROM раб_периоды WHERE id = ?", (номер,))
        д, конец = date.fromisoformat(р["с"]), date.fromisoformat(р["по"])
        while д <= конец:
            код = "В" if выходной(д) else "Я"
            связь.execute("INSERT OR REPLACE INTO раб_табель (сотрудник_id, день, код, часы) VALUES (?, ?, ?, ?)",
                          (р["сотрудник_id"], д.isoformat(), код, 0 if код == "В" else (7 if сокращённый(д) else 8)))
            д += timedelta(days=1)
    return True


