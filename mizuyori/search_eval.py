"""Тест качества поиска: фиксированный набор запросов с ожидаемым результатом.

Кнопка «Проверить поиск» прогоняет набор через тот же поиск, что у снабженца, и сравнивает с прошлым прогоном:
если выдача стала заметно хуже (сменился движок, капча, правка ранжирования), это видно сразу, а не через месяц.
Балл запроса: 1 — ожидаемое в первых трёх результатах, 0.5 — в первых восьми, 0 — нет или поиск упал.
"""

from __future__ import annotations

import json
import logging

from . import senses

журнал = logging.getLogger("mizuyori.проверка_поиска")

# запрос -> что считаем попаданием: артикул (в любом написании) в названии/описании, или домен, или слово
НАБОР = [
    {"запрос": "фильтр VIC C-111", "артикул": "C-111", "слова": ["vic", "фильтр"]},
    {"запрос": "фильтр VIC C-110 воздушный", "артикул": "C-110", "слова": ["vic"]},
    {"запрос": "шины 265/65 R17", "слова": ["265/65", "r17"]},
    {"запрос": "шины 215/65 R16 летние", "слова": ["215/65", "r16"]},
    {"запрос": "аккумулятор 6СТ-190 для грузовика", "слова": ["190", "аккумулятор"]},
    {"запрос": "колодки тормозные КАМАЗ 5320", "слова": ["колодк", "камаз"]},
    {"запрос": "масло моторное 10W-40 дизель 20 л", "слова": ["10w-40", "10w40"]},
    {"запрос": "ремень ГРМ Toyota Hilux", "слова": ["hilux", "ремень", "грм"]},
    {"запрос": "фильтр масляный Mann W 940", "артикул": "W 940", "слова": ["mann"]},
    {"запрос": "свечи зажигания NGK BKR6E", "артикул": "BKR6E", "слова": ["ngk"]},
    {"запрос": "антифриз G12 красный 5 кг", "слова": ["g12", "антифриз"]},
    {"запрос": "лампа H7 12V 55W Osram", "слова": ["h7", "osram"]},
]

ПОРОГ_УХУДШЕНИЯ = 0.1


def _база():
    from . import agents
    return agents._база


def _норма(текст: str) -> str:
    return "".join(ч for ч in (текст or "").casefold() if ч.isalnum() or ч in "/")


def оценить_запрос(пример: dict, результаты: list[dict]) -> float:
    def попало(р: dict) -> bool:
        текст = f"{р.get('название', '')} {р.get('кратко', '')} {р.get('ссылка', '')}"
        текст_н = _норма(текст)
        if пример.get("артикул"):
            return _норма(пример["артикул"]) in текст_н
        слова = [_норма(с) for с in пример.get("слова", [])]
        нужно = (len(слова) + 1) // 2          # хотя бы половина ожидаемых слов
        return bool(слова) and sum(1 for с in слова if с in текст_н) >= нужно
    for и, р in enumerate(результаты[:8]):
        if попало(р):
            return 1.0 if и < 3 else 0.5
    return 0.0


def прогнать(получить=None, набор: list[dict] | None = None) -> dict:
    """Один прогон. Возвращает итог и сравнение с предыдущим."""
    набор = набор or НАБОР
    подробности, ошибок = [], 0
    for пример in набор:
        try:
            результаты, _ = senses.искать_для_закупки(пример["запрос"], "снабженец", получить=получить, сколько=8, кэш=False)
            балл = оценить_запрос(пример, результаты)
            подробности.append({"запрос": пример["запрос"], "балл": балл, "найдено": len(результаты),
                                "первый": (результаты[0]["название"] if результаты else "")})
        except Exception as е:
            ошибок += 1
            журнал.warning("Тест поиска: «%s» не удался: %s", пример["запрос"], е)
            подробности.append({"запрос": пример["запрос"], "балл": 0.0, "найдено": 0, "первый": "", "ошибка": str(е)[:120]})
    общий = round(sum(п["балл"] for п in подробности) / len(подробности), 2)
    прошлый = последний()
    with _база().соединение() as связь:
        номер = связь.execute("INSERT INTO поиск_прогон (балл, запросов, ошибок, подробности) VALUES (?, ?, ?, ?)",
                              (общий, len(подробности), ошибок, json.dumps(подробности, ensure_ascii=False))).lastrowid
        связь.execute("DELETE FROM поиск_прогон WHERE id NOT IN (SELECT id FROM поиск_прогон ORDER BY id DESC LIMIT 30)")
    итог = {"id": номер, "балл": общий, "запросов": len(подробности), "ошибок": ошибок, "подробности": подробности}
    итог["вердикт"] = _вердикт(общий, ошибок, len(подробности), прошлый)
    итог["прошлый"] = прошлый["балл"] if прошлый else None
    return итог


def _вердикт(балл: float, ошибок: int, всего: int, прошлый: dict | None) -> str:
    if ошибок == всего:
        return "Поиск не отвечает: все запросы упали (сеть, капча или блокировка)."
    if прошлый is None:
        return "Первый прогон: это точка отсчёта для следующих проверок."
    разница = round(балл - прошлый["балл"], 2)
    if разница <= -ПОРОГ_УХУДШЕНИЯ:
        return f"Поиск стал хуже: {прошлый['балл']:.0%} → {балл:.0%}."
    if разница >= ПОРОГ_УХУДШЕНИЯ:
        return f"Поиск стал лучше: {прошлый['балл']:.0%} → {балл:.0%}."
    return f"Без заметных изменений: {прошлый['балл']:.0%} → {балл:.0%}."


def последний() -> dict | None:
    с = история(1)
    return с[0] if с else None


def история(сколько: int = 12) -> list[dict]:
    with _база().соединение() as связь:
        строки = связь.execute("SELECT * FROM поиск_прогон ORDER BY id DESC LIMIT ?", (сколько,)).fetchall()
    итог = []
    for с in строки:
        з = dict(с)
        з["подробности"] = json.loads(з["подробности"] or "[]")
        итог.append(з)
    return итог
