"""Реестр инструментов агентов: новый навык подключается одной функцией с декоратором.

    @инструмент("поиск", "ищет в интернете", рискованный=False)
    def поиск(задание: dict) -> str: ...

Шаг поручения может назвать инструмент; тогда агент сначала вызывает его, а результат
отдаёт модели как факты. Рискованный инструмент (отправка, оформление) всегда ждёт подтверждения человека.
Функция получает словарь: {"описание", "агент", "настройки_ии", "база", "до_этого"} и возвращает текст.
"""

from __future__ import annotations

import hashlib
import logging
import re
from dataclasses import dataclass
from typing import Callable

журнал = logging.getLogger("mizuyori.инструменты")


@dataclass(frozen=True)
class Инструмент:
    имя: str
    что: str
    рискованный: bool
    вызвать: Callable[[dict], str]
    кому: Callable[[str], bool] | None = None      # кто из агентов вправе вызывать; None — любой


ИНСТРУМЕНТЫ: dict[str, Инструмент] = {}


def инструмент(имя: str, что: str, рискованный: bool = False, кому: Callable[[str], bool] | None = None):
    """Декоратор: @инструмент("поиск", "ищет в интернете", кому=lambda агент: ...)."""
    def обернуть(функция: Callable[[dict], str]):
        ИНСТРУМЕНТЫ[имя] = Инструмент(имя, что, рискованный, функция, кому)
        return функция
    return обернуть


def список() -> list[dict]:
    return [{"имя": и.имя, "что": и.что, "рискованный": и.рискованный} for и in ИНСТРУМЕНТЫ.values()]


def рискованный(имя: str) -> bool:
    и = ИНСТРУМЕНТЫ.get(имя or "")
    return bool(и and и.рискованный)


# ---- Файрвол вызовов -------------------------------------------------------------------------

_УПРАВЛЯЮЩИЕ = re.compile(r"[\x00-\x08\x0b\x0c\x0e-\x1f]")
МАКС_ДЛИНА_ЗАДАНИЯ = 2000


def разрешён(имя: str, агент: str) -> tuple[bool, str]:
    """Вправе ли этот агент вызывать этот инструмент. Причина — человеческим языком."""
    и = ИНСТРУМЕНТЫ.get(имя or "")
    if not и:
        return False, f"нет инструмента «{имя}»"
    if и.кому is not None and not и.кому(агент):
        return False, f"агенту «{агент}» нельзя пользоваться инструментом «{имя}»"
    return True, ""


def проверить_аргументы(описание: str) -> tuple[bool, str]:
    if not (описание or "").strip():
        return False, "пустое задание для инструмента"
    if len(описание) > МАКС_ДЛИНА_ЗАДАНИЯ:
        return False, f"задание длиннее {МАКС_ДЛИНА_ЗАДАНИЯ} знаков"
    if _УПРАВЛЯЮЩИЕ.search(описание):
        return False, "в задании есть управляющие символы"
    return True, ""


def проверить_вызов(имя: str, агент: str, описание: str) -> tuple[bool, str]:
    ок, причина = разрешён(имя, агент)
    return (ок, причина) if not ок else проверить_аргументы(описание)


def отпечаток(агент: str, имя: str, описание: str) -> str:
    """Подпись конкретного вызова: подтверждение действует только на него, а не «вообще»."""
    return hashlib.sha1(f"{агент}|{имя}|{описание}".encode("utf-8")).hexdigest()[:12]


def вызвать(имя: str, задание: dict) -> str:
    и = ИНСТРУМЕНТЫ.get(имя)
    if not и:
        raise KeyError(f"Нет инструмента «{имя}»")
    ок, причина = проверить_вызов(имя, задание.get("агент") or "", задание.get("описание") or "")
    if not ок:
        raise PermissionError(f"Вызов заблокирован: {причина}")
    return str(и.вызвать(задание) or "")


# ---- Встроенные инструменты ---------------------------------------------------------

def _умеет_искать(агент: str) -> bool:
    from . import agents
    return "🦶" in agents.СПОСОБНОСТИ.get(агент, "")


def _наблюдает(агент: str) -> bool:
    from . import work_agents
    return агент in dict(work_agents.НАБЛЮДАТЕЛИ)


@инструмент("поиск", "ищет в интернете: запчасти, цены, аналоги (приоритет — Приморский край)", кому=_умеет_искать)
def _поиск(задание: dict) -> str:
    from . import senses
    факты, _сообщение = senses.найти_для_чата(задание["описание"], задание.get("агент") or "снабженец",
                                              настройки_ии=задание.get("настройки_ии"))
    return факты


@инструмент("замечания", "берёт свежие замечания агента по данным: ТО, сроки, ГСМ, документы", кому=_наблюдает)
def _замечания(задание: dict) -> str:
    from . import work_agents
    ключ = задание.get("агент") or ""
    набор = dict(work_agents.НАБЛЮДАТЕЛИ)
    наблюдатель = набор.get(ключ)
    if not наблюдатель:
        return ""
    строки = наблюдатель(задание["база"])
    return "\n".join(f"- {з['текст']}" for з in строки[:15]) or "Замечаний нет."
