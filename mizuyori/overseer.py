"""Смотрящий: читает чат, понимает, что хозяин просит, и раздаёт задания другим агентам.

«Сделай служебку на выходные в Кихтев, суббота 14, Иванов Петров» →
  Старший инженер пишет служебную записку, Кадровик ставит «работу в выходной» в табель,
  Контролёр сроков заводит напоминание. Сначала показывается план, делается — после «да».
"""
from __future__ import annotations

import logging
import re
import time
from datetime import date, timedelta

from . import agents, work

журнал = logging.getLogger("mizuyori.смотрящий")

АГЕНТ = {"ключ": "смотрящий", "имя": "Смотрящий", "значок": "глаз", "группа": "Основа",
         "что": "читает чат и раздаёт задания другим агентам"}

МЕСЯЦЫ = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября",
          "октября", "ноября", "декабря"]
ДНИ = ["понедельник", "вторник", "сред", "четверг", "пятниц", "суббот", "воскресень"]
ДНИ_РУС = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
ГЛАГОЛЫ = ("сдела", "напиш", "подготов", "оформ", "постав", "отмет", "составь", "создай", "заведи", "организуй")
ЖДАТЬ_СЕК = 3 * 3600

_план: dict | None = None          # ждущее подтверждения задание (хозяин один, хватает одного)


def наблюдать(база) -> list[dict]:
    """Смотрящий не ищет замечаний сам — его работа идёт через чат."""
    return [{"текст": "Жду заданий в чате: «сделай служебку …», «поставь в табель …»", "важно": 0, "кому": None}] \
        if _план is None else [{"текст": "Есть задание, жду ответа «да» или фамилий", "важно": 1, "кому": None}]


# ---- разбор ----------------------------------------------------------------------------

def _нормально(текст: str) -> str:
    return " ".join(текст.lower().replace("ё", "е").split())


def намерения(текст: str) -> list[str]:
    н = _нормально(текст)
    итог = []
    if re.search(r"служебк|записк", н):
        итог.append("записка")
    if re.search(r"табел|выходн|суббот|воскресен|отмет", н):
        итог.append("табель")
    if re.search(r"напомн", н):
        итог.append("напоминание")
    if re.search(r"отпуск|больничн|командировк", н):
        итог.append("отсутствие")
    if re.search(r"\bзадач|в дела\b|добавь в дел", н):
        итог.append("задача")
    return итог


def это_для_смотрящего(текст: str, адресовано: str | None) -> bool:
    н = _нормально(текст)
    список = намерения(текст)
    if адресовано == "смотрящий":
        return True
    if адресовано:                       # назвали другого агента — это его работа
        return False
    глагол = any(г in н for г in ГЛАГОЛЫ + ("добавь", "запиши", "оформи", "уйд", "ухо"))
    if глагол and any(и in список for и in ("отсутствие", "задача")):
        return True
    return len(список) >= 2 and глагол


def дата_из_текста(текст: str, сегодня: date | None = None) -> date | None:
    сегодня = сегодня or date.today()
    н = _нормально(текст)
    if "послезавтра" in н:
        return сегодня + timedelta(days=2)
    if "завтра" in н:
        return сегодня + timedelta(days=1)
    if re.search(r"\bсегодня\b", н):
        return сегодня
    м = re.search(r"\b(\d{1,2})\s+(" + "|".join(МЕСЯЦЫ) + r")\b", н)
    if м:
        день, месяц = int(м.group(1)), МЕСЯЦЫ.index(м.group(2)) + 1
        год = сегодня.year + (1 if (месяц, день) < (сегодня.month, сегодня.day) else 0)
        return _дата(год, месяц, день)
    м = re.search(r"\b(\d{1,2})\.(\d{1,2})(?:\.(\d{2,4}))?\b", н)
    if м:
        год = int(м.group(3)) if м.group(3) else сегодня.year
        год += 2000 if год < 100 else 0
        return _дата(год, int(м.group(2)), int(м.group(1)))
    for номер, основа in enumerate(ДНИ):
        м = re.search(основа + r"\w*[ ,]*(\d{1,2})?\b(?!\.)", н)
        if not м:
            continue
        if м.group(1):                   # «суббота 14» — число в ближайшем месяце, где день недели сходится
            for сдвиг in range(0, 3):
                месяц = (сегодня.month - 1 + сдвиг) % 12 + 1
                год = сегодня.year + (сегодня.month - 1 + сдвиг) // 12
                д = _дата(год, месяц, int(м.group(1)))
                if д and д >= сегодня and д.weekday() == номер:
                    return д
        return сегодня + timedelta(days=(номер - сегодня.weekday()) % 7)
    return None


def период_из_текста(текст: str, сегодня: date | None = None) -> tuple[date, date] | None:
    """«с 10 по 15 ноября», «с 10.11 по 15.11», «10-15 ноября» → (начало, конец)."""
    сегодня = сегодня or date.today()
    н = _нормально(текст)
    м = re.search(r"\b(?:с\s+)?(\d{1,2})(?:\s*(?:по|-|–)\s*)(\d{1,2})\s+(" + "|".join(МЕСЯЦЫ) + r")\b", н)
    if м:
        месяц = МЕСЯЦЫ.index(м.group(3)) + 1
        год = сегодня.year + (1 if (месяц, int(м.group(2))) < (сегодня.month, сегодня.day) else 0)
        a, b = _дата(год, месяц, int(м.group(1))), _дата(год, месяц, int(м.group(2)))
        return (a, b) if a and b and a <= b else None
    м = re.search(r"\bс\s+(\d{1,2})\.(\d{1,2})(?:\.\d{2,4})?\s+по\s+(\d{1,2})\.(\d{1,2})(?:\.(\d{2,4}))?", н)
    if м:
        год = int(м.group(5)) if м.group(5) else сегодня.year
        год += 2000 if год < 100 else 0
        a, b = _дата(год, int(м.group(2)), int(м.group(1))), _дата(год, int(м.group(4)), int(м.group(3)))
        return (a, b) if a and b and a <= b else None
    return None


def код_отсутствия(текст: str) -> str:
    н = _нормально(текст)
    return "Б" if "больничн" in н else "К" if "командировк" in н else "ОТ"


def текст_задачи(текст: str) -> str:
    т = re.split(r"(?i)\bзадач[уаи]?\b[:,]?\s*|\bв дела\b[:,]?\s*", текст, maxsplit=1)
    т = (т[1] if len(т) > 1 else текст).strip(" .")
    т = re.sub(r"(?i)^(смотрящий[,:]?\s*)?(добавь|запиши|поставь|создай)\s*", "", т).strip()
    return (т[:1].upper() + т[1:])[:200]


def _дата(г: int, м: int, д: int) -> date | None:
    try:
        return date(г, м, д)
    except ValueError:
        return None


def объект_из_текста(текст: str) -> str:
    """«…в Кихтев» → «Кихтев»: слово после «в/на/по», не похожее на день или месяц."""
    for м in re.finditer(r"\b(?:в|на|по|для)\s+([А-Яа-яЁё][А-Яа-яЁё\-]{2,})", текст):
        слово = м.group(1)
        н = _нормально(слово)
        if any(н.startswith(о) for о in ДНИ) or н in МЕСЯЦЫ or н.startswith(("выходн", "праздн", "завтр", "сегодн", "табел")):
            continue
        return слово[:1].upper() + слово[1:]
    return ""


def сотрудники_в_тексте(база, текст: str) -> list[dict]:
    слова = re.findall(r"[а-яё\-]+", текст.lower().replace("ё", "е"))
    найдено = []
    with база.соединение() as связь:
        строки = связь.execute("SELECT id, фамилия, имя, отчество FROM раб_сотрудники WHERE уволен = 0").fetchall()
    for с in строки:
        ф = (с["фамилия"] or "").lower().replace("ё", "е")
        основа = ф[:-1] if len(ф) > 5 else ф
        if len(основа) >= 3 and any(с_.startswith(основа) for с_ in слова):
            найдено.append({"id": с["id"], "ФИО": f"{с['фамилия']} {(с['имя'] or '')[:1]}.".strip()})
    return найдено


def _день(д: date) -> str:
    return f"{ДНИ_РУС[д.weekday()]}, {д.strftime('%d.%m.%Y')}"


def построить(база, текст: str) -> dict:
    список = намерения(текст)
    д = дата_из_текста(текст)
    период = период_из_текста(текст) if "отсутствие" in список else None
    if период:
        д = период[0]
    return {"текст": текст, "создан": time.time(), "намерения": список, "дата": д, "объект": объект_из_текста(текст),
            "люди": сотрудники_в_тексте(база, текст), "период": период, "код": код_отсутствия(текст)}


def вопросы(план: dict) -> list[str]:
    итог = []
    if not план["дата"] and set(план["намерения"]) != {"задача"}:
        итог.append("На какую дату? (например: «суббота 14» или «15.11»)")
    if {"табель", "отсутствие"} & set(план["намерения"]) and not план["люди"]:
        итог.append("Кого отметить в табеле? Напишите фамилии.")
    return итог


def описание(план: dict) -> str:
    д = план["дата"]
    шапка = "🧭 Смотрящий разобрал задание" + (f": {_день(д)}" if д else "") + (f", объект {план['объект']}" if план["объект"] else "")
    строки = []
    люди = ", ".join(л["ФИО"] for л in план["люди"]) or "—"
    if "записка" in план["намерения"]:
        строки.append("- Старший инженер: служебная записка (черновик)")
    if "табель" in план["намерения"]:
        код = "работа в выходной" if д and work.выходной(д) else "явка"
        строки.append(f"- Кадровик: табель — {код}: {люди}")
    if "отсутствие" in план["намерения"]:
        п = план.get("период") or (д, д)
        срок = f"{п[0].strftime('%d.%m')}–{п[1].strftime('%d.%m')}" if п[0] and п[0] != п[1] else (п[0].strftime("%d.%m") if п[0] else "?")
        строки.append(f"- Кадровик: табель — {work.КОДЫ_ТАБЕЛЯ[план['код']]['подпись']} {срок}: {люди}")
    if "задача" in план["намерения"]:
        строки.append(f"- Смотрящий: задача в «Делах»: {текст_задачи(план['текст'])}")
    if "напоминание" in план["намерения"]:
        строки.append("- Контролёр сроков: напоминание за день до даты" if д else "- Контролёр сроков: напоминание")
    в = вопросы(план)
    хвост = ("\n\n❓ " + "\n❓ ".join(в)) if в else "\n\nЕсли всё верно, напишите «да». «Отмена» — не делать."
    return шапка + "\n" + "\n".join(строки) + хвост


# ---- выполнение ------------------------------------------------------------------------

def _поручить(кому: str, что: str) -> None:
    try:
        agents.написать("смотрящий", кому, что)
    except Exception:
        журнал.exception("Не удалось положить задание на доску")


def _отчитаться(от: str, что: str) -> None:
    try:
        agents.написать(от, "смотрящий", что)
    except Exception:
        журнал.exception("Не удалось положить отчёт на доску")


def выполнить(база, настройки_ии: dict, план: dict) -> list[str]:
    from . import work_agents
    д: date = план["дата"] or date.today()
    где = f" ({план['объект']})" if план["объект"] else ""
    итог = []
    выходной = work.выходной(д)
    тема = (f"О привлечении к работе в выходной день {д.strftime('%d.%m.%Y')}{где}" if выходной
            else f"О выезде {д.strftime('%d.%m.%Y')}{где}")
    with agents.работа("смотрящий", "раздал задания", план["текст"][:80]) as з:
        if "записка" in план["намерения"]:
            _поручить("инженер", f"Служебная записка: {тема}")
            запись = work_agents.написать_записку(база, настройки_ии, тема, план["текст"])
            _отчитаться("инженер", f"Записка №{запись['номер']} готова")
            итог.append(f"📄 Служебная записка №{запись['номер']} «{запись['тема']}» — в «Работа → Служебные записки» (черновик)")
        if "табель" in план["намерения"]:
            код = "РВ" if выходной else "Я"
            _поручить("кадровик", f"Табель {д.strftime('%d.%m')}: {код} — " + ", ".join(л["ФИО"] for л in план["люди"]))
            with agents.работа("кадровик", "отметил в табеле", f"{д.strftime('%d.%m')} · {len(план['люди'])} чел.") as к:
                for л in план["люди"]:
                    work.отметить(база, л["id"], д.isoformat(), код, None)
                к["результат"] = f"{код}: " + ", ".join(л["ФИО"] for л in план["люди"])
                к["польза"] = 2
            _отчитаться("кадровик", "Табель заполнен")
            итог.append(f"🗓 Табель: {код} ({work.КОДЫ_ТАБЕЛЯ[код]['подпись']}) {д.strftime('%d.%m')} — " + ", ".join(л["ФИО"] for л in план["люди"]))
        if "отсутствие" in план["намерения"]:
            п = план.get("период") or (д, д)
            код = план["код"]
            _поручить("кадровик", f"Табель {п[0].strftime('%d.%m')}–{п[1].strftime('%d.%m')}: {код} — " + ", ".join(л["ФИО"] for л in план["люди"]))
            with agents.работа("кадровик", "отметил отсутствие", f"{код} · {len(план['люди'])} чел.") as к:
                день = п[0]
                while день <= п[1]:
                    if not work.выходной(день):                  # выходные в отпуск не считаем
                        for л in план["люди"]:
                            work.отметить(база, л["id"], день.isoformat(), код, None)
                    день += timedelta(days=1)
                к["результат"] = f"{код}: " + ", ".join(л["ФИО"] for л in план["люди"])
                к["польза"] = 2
            _отчитаться("кадровик", "Отсутствие отмечено")
            итог.append(f"🗓 Табель: {work.КОДЫ_ТАБЕЛЯ[код]['подпись']} {п[0].strftime('%d.%m')}–{п[1].strftime('%d.%m')} (будни) — " + ", ".join(л["ФИО"] for л in план["люди"]))
        if "задача" in план["намерения"]:
            задача = текст_задачи(план["текст"])
            with база.соединение() as связь:
                связь.execute("INSERT INTO задачи (текст) VALUES (?)", (задача,))
            итог.append(f"✅ Задача в «Делах»: {задача}")
        if "напоминание" in план["намерения"]:
            когда = max(д - timedelta(days=1), date.today())
            текст = f"{когда.strftime('%d.%m')}: напомнить про {тема[0].lower() + тема[1:]}"
            _поручить("сроки", f"Напоминание на {когда.strftime('%d.%m')}")
            with agents.работа("сроки", "завёл напоминание", текст[:80]) as к:
                with база.соединение() as связь:
                    связь.execute("INSERT INTO задачи (текст) VALUES (?)", (текст,))
                к["результат"] = текст
                к["польза"] = 1
            _отчитаться("сроки", "Напоминание заведено")
            итог.append(f"⏰ Напоминание в «Делах»: {текст}")
        з["результат"] = f"{len(итог)} поручений"
        з["польза"] = 3
    return итог


# ---- вход из чата ----------------------------------------------------------------------

def из_чата(база, настройки_ии: dict, текст: str, адресовано: str | None) -> tuple[str, str] | None:
    """(подсказка ИИ, готовое сообщение) или None, если это не для Смотрящего."""
    global _план
    н = _нормально(текст)
    ждёт = _план and time.time() - _план["создан"] < ЖДАТЬ_СЕК
    if not ждёт:
        _план = None
    if ждёт and re.fullmatch(r"(отмена|отмени(ть)?|не надо|не нужно|стоп)[.! ]*", н):
        _план = None
        return ("Хозяин отменил задание Смотрящего. Скажи одной фразой.", "🧭 Задание отменено, ничего не делал.")
    if ждёт and re.fullmatch(r"(да|ок|давай|делай|выполняй|подтверждаю|верно|все верно)[.! ]*", н):
        if вопросы(_план):
            return ("Смотрящему не хватает данных. Скажи об этом одной фразой.", "🧭 Ещё не хватает данных:\n❓ " + "\n❓ ".join(вопросы(_план)))
        план, _план = _план, None
        итог = выполнить(база, настройки_ии, план)
        return ("Смотрящий раздал задания агентам. Скажи одной фразой.", "✅ Готово, агенты сделали:\n" + "\n".join(итог)
                + "\nВсё это черновики и отметки — проверьте перед подписью.")
    if ждёт and not это_для_смотрящего(текст, адресовано):
        # ответ на вопрос Смотрящего: дата и/или фамилии
        д = дата_из_текста(текст)
        люди = сотрудники_в_тексте(база, текст)
        if д or люди:
            if д:
                _план["дата"] = д
            for л in люди:
                if all(л["id"] != х["id"] for х in _план["люди"]):
                    _план["люди"].append(л)
            if not _план["объект"]:
                _план["объект"] = объект_из_текста(текст)
            return ("Смотрящий уточнил задание. Скажи одной фразой.", описание(_план))
        return None
    if это_для_смотрящего(текст, адресовано) and намерения(текст):
        _план = построить(база, текст)
        return ("Смотрящий разобрал задание хозяина и ждёт подтверждения. Скажи одной фразой.", описание(_план))
    return None
