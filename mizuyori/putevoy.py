"""Заполнение путевого листа: берёт шаблон Excel, подставляет из базы машину, госномер, водителя
(ФИО и номер водительского удостоверения) и дату выдачи. Результат — готовый .xlsx для печати."""

import logging
import re
from datetime import date
from pathlib import Path

import openpyxl

from . import printing, work
from .paths import ПАПКА_ДАННЫХ

журнал = logging.getLogger("mizuyori.путевой")

ПАПКА_ГОТОВЫХ = ПАПКА_ДАННЫХ / "путевые_готовые"
МЕСЯЦЫ_РОД = ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября",
              "ноября", "декабря"]


def _ключ(с) -> str:
    return re.sub(r"[^0-9a-zа-я]+", "", str(с or "").lower().replace("ё", "е"))


def _анкер(ws, ячейка):
    """Верхняя левая ячейка объединения (в остальные писать нельзя)."""
    for м in ws.merged_cells.ranges:
        if ячейка.coordinate in м:
            return ws.cell(м.min_row, м.min_col), м
    return ячейка, None


def _справа(ws, ячейка, пропустить_пустые_одиночные: bool = False):  # noqa: C901
    """Ячейка значения справа от подписи: первая за объединением подписи."""
    _, м = _анкер(ws, ячейка)
    колонка = (м.max_col if м else ячейка.column) + 1
    запасной = None
    for к in range(колонка, колонка + 70):
        c = ws.cell(ячейка.row, к)
        а, м2 = _анкер(ws, c)
        запасной = запасной or а
        if not м2 and (пропустить_пустые_одиночные or not isinstance(c.value, str)):
            continue                 # пустая одиночная клетка — это отступ, значение лежит в объединённой справа
        return а
    return запасной


def _инициалы(фио: str) -> str:
    части = фио.split()
    return " ".join([части[0]] + [ч[0] + "." for ч in части[1:3]]) if части else ""


def _инициалы_ключ(фио: str) -> str:
    return _ключ(_инициалы(фио))


def заполнить(шаблон: Path, водитель: dict | None, авто: dict | None, день: date) -> dict:
    """Возвращает {'файл': Path, 'подставлено': [...], 'предупреждения': [...]}."""
    книга = openpyxl.load_workbook(шаблон)
    лист = книга.worksheets[0]
    подставлено, предупреждения = [], []
    старый_фио = ""
    # первый проход: старые значения из шаблона (чтобы заменить их же в подписях «Фамилия И. О.»)
    for строка in лист.iter_rows(max_row=24):
        for c in строка:
            if isinstance(c.value, str) and c.value.strip() == "Водитель":
                з = _справа(лист, c)
                if з is not None and isinstance(з.value, str) and len(з.value.split()) >= 2:
                    старый_фио = з.value.strip()
                    break
        if старый_фио:
            break
    новый_фио = work.фио(водитель) if водитель else ""
    марка = f"{авто['марка']} {авто['модель']}".strip() if авто else ""
    номер = (авто.get("госномер") or "").strip() if авто else ""
    права = (водитель.get("удостоверение") or "").strip() if водитель else ""

    # строки с прицепами идут ниже удостоверения — их госномер не трогаем
    граница = min((c.row for строка in лист.iter_rows(max_row=24) for c in строка
                   if isinstance(c.value, str) and c.value.strip().startswith("Удостоверение")), default=99)
    for строка in лист.iter_rows(max_row=24):
        for c in строка:
            if not isinstance(c.value, str):
                continue
            текст = c.value.strip()
            цель = None
            значение = None
            if текст.startswith("Марка автомобиля") and марка:
                цель, значение = _справа(лист, c), марка
            elif текст.startswith("Государственный номерной знак") and номер and c.row < граница:
                цель, значение = _справа(лист, c), номер
            elif текст == "Водитель" and новый_фио:
                цель, значение = _справа(лист, c), новый_фио
            elif текст.startswith("Удостоверение") and права:
                цель, значение = _справа(лист, c), права
            if цель is not None and значение is not None:
                цель.value = значение
    # подписи «Фамилия И. О.» внизу листа — по старому ФИО из шаблона
    if старый_фио and новый_фио:
        старые = {_инициалы_ключ(старый_фио), _ключ(старый_фио)}
        новые_инициалы = _инициалы(новый_фио)
        for строка in лист.iter_rows():
            for c in строка:
                if isinstance(c.value, str) and _ключ(c.value) in старые and c.value.strip() != новый_фио:
                    c.value = новые_инициалы if len(c.value.split()) <= 3 and "." in c.value else новый_фио
    # дата выдачи: «__» месяц ____ г.
    for строка in лист.iter_rows(max_row=24):
        for c in строка:
            if isinstance(c.value, str) and c.value.strip() == "«":
                try:
                    день_ячейка = _справа(лист, c)
                    закрывающая = _справа(лист, день_ячейка)
                    месяц_ячейка = _справа(лист, закрывающая, пропустить_пустые_одиночные=True)
                    год_ячейка = _справа(лист, месяц_ячейка, пропустить_пустые_одиночные=False)
                    for к in range(месяц_ячейка.column + 1, месяц_ячейка.column + 6):
                        кандидат = лист.cell(c.row, к)
                        if re.fullmatch(r"\d{4}", str(кандидат.value or "").strip()):
                            год_ячейка = кандидат
                            break
                    день_ячейка.value = день.day
                    месяц_ячейка.value = МЕСЯЦЫ_РОД[день.month - 1]
                    год_ячейка.value = str(день.year)
                except Exception:
                    предупреждения.append("дату в этом бланке не удалось подставить — впишите вручную")
                    break
    if водитель:
        подставлено.append(f"водитель: {новый_фио}")
        подставлено.append(f"удостоверение: {права}" if права else "удостоверение №: не заполнено в карточке сотрудника")
        if not права:
            предупреждения.append("у водителя не указан номер водительского удостоверения (Работа → Сотрудники)")
    else:
        предупреждения.append("водитель не найден в базе — оставлен из шаблона")
    if авто:
        подставлено.append(f"машина: {марка} {номер}".strip())
    else:
        предупреждения.append("машина не найдена в базе — оставлена из шаблона")
    ПАПКА_ГОТОВЫХ.mkdir(parents=True, exist_ok=True)
    имя = re.sub(r"[^\w .-]+", "", f"Путевой {марка or шаблон.stem} {новый_фио or ''} {день:%d.%m.%Y}").strip() + ".xlsx"
    файл = ПАПКА_ГОТОВЫХ / имя
    книга.save(файл)
    return {"файл": файл, "подставлено": подставлено, "предупреждения": предупреждения}


# ---- Подбор водителя и машины в базе -------------------------------------------------------

def _из_шаблона(шаблон: Path) -> tuple[str, str]:
    """(номер машины из бланка, водитель из бланка)."""
    ws = openpyxl.load_workbook(шаблон, read_only=False).worksheets[0]
    номер = старый = ""
    for строка in ws.iter_rows(max_row=24):
        for c in строка:
            if isinstance(c.value, str):
                т = c.value.strip()
                if т.startswith("Государственный номерной знак") and not номер:
                    з = _справа(ws, c)
                    номер = str(з.value or "") if з is not None else ""
                elif т == "Водитель" and not старый:
                    з = _справа(ws, c)
                    старый = str(з.value or "") if з is not None else ""
    return номер, старый


def подобрать(база, шаблон: Path, запрос: str = "") -> tuple[dict | None, dict | None]:
    """Водитель и машина из базы для этого шаблона."""
    номер, из_бланка = _из_шаблона(шаблон)
    левая, _, правая = шаблон.stem.partition(" - ")
    водитель_в_имени = правая or левая
    люди = [ч for ч in work.список(база, "сотрудники") if not ч.get("уволен")]
    слова = [printing._основа(printing._норм(с)) for с in (водитель_в_имени + " " + из_бланка).split() if len(с) > 3]
    водитель = next((ч for ч in люди if printing._основа(printing._норм(ч["фамилия"])) in слова), None)
    машины = work.список(база, "автомобили")
    авто = None
    if номер and _ключ(номер):
        авто = next((а for а in машины if а.get("госномер") and _ключ(а["госномер"])[:6] == _ключ(номер)[:6]), None)
    if not авто:
        ключ_имени = printing._норм(левая)
        for а in машины:
            слова_авто = [с for с in printing._норм(f"{а['марка']} {а['модель']}").split() if len(с) > 2]
            if слова_авто and all(с in ключ_имени or printing._латиницей(с) in ключ_имени for с in слова_авто):
                авто = а
                break
    return водитель, авто
