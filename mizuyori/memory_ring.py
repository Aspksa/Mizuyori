def _кратко(т: str, n: int = 140) -> str:
    т = " ".join(str(т or "").split())
    return т if len(т) <= n else т[: n - 1] + "…"


def сводка(база) -> list[dict]:
    итог = []
    with база.соединение() as с:
        for р in РАЗДЕЛЫ:
            число = с.execute(р["счёт"]).fetchone()[0]
            последние = [_кратко(х["текст"], 70) for х in с.execute(р["список"], (3,))]
            итог.append({"ключ": р["ключ"], "имя": р["имя"], "значок": р["значок"], "цвет": р["цвет"], "число": число, "последние": последние})
    return итог


def раздел(база, ключ: str, лимит: int = 60, запрос: str = "") -> dict | None:
    р = next((х for х in РАЗДЕЛЫ if х["ключ"] == ключ), None)
    if not р:
        return None
    с_запросом = (запрос or "").strip().lower().replace("ё", "е")
    with база.соединение() as с:
        строки = [dict(х) for х in с.execute(р["список"], (500 if с_запросом else лимит,))]
    if с_запросом:
        строки = [х for х in строки if с_запросом in str(х["текст"]).lower().replace("ё", "е")][:лимит]
    return {"ключ": р["ключ"], "имя": р["имя"], "значок": р["значок"], "цвет": р["цвет"],
            "записи": [{"id": х["id"], "текст": _кратко(х["текст"], 400), "создано": х["создано"]} for х in строки]}
