def наблюдать_кадровика(база) -> list[dict]:
    сегодня = date.today()
    итог = []
    люди = [ч for ч in work._все(база, "раб_сотрудники").values() if not ч["уволен"]]
    for ч in люди:
        if not ч["табельный"]:
            итог.append(_зам(f"{work.фио(ч, True)}: не указан табельный номер", 0))
        if not ч["должность"]:
            итог.append(_зам(f"{work.фио(ч, True)}: не указана должность", 0))
    # табель за прошедшие рабочие дни текущего месяца
    начало = сегодня.replace(day=1)
    дни = [начало + timedelta(days=i) for i in range((сегодня - начало).days)]
    рабочие = [д for д in дни if not work.выходной(д)]
    if рабочие and люди:
        with база.соединение() as связь:
            есть = {(р[0], р[1]) for р in связь.execute(
                "SELECT сотрудник_id, день FROM раб_табель WHERE день >= ? AND день < ?",
                (начало.isoformat(), сегодня.isoformat()))}
        пустых = [ч for ч in люди if sum(1 for д in рабочие if (ч["id"], д.isoformat()) not in есть) > 0]
        if пустых:
            итог.append(_зам(f"Табель за {начало.strftime('%m.%Y')} заполнен не полностью у {len(пустых)} сотрудников — нажмите «Заполнить»", 1))
    with база.соединение() as связь:
        скоро = связь.execute("SELECT сотрудник_id, код, с, по FROM раб_периоды WHERE с BETWEEN ? AND ? ORDER BY с",
                              (сегодня.isoformat(), (сегодня + timedelta(days=14)).isoformat())).fetchall()
    ид = work._все(база, "раб_сотрудники")
    for сид, код, с, по in скоро:
        итог.append(_зам(f"{work.фио(ид.get(сид), True)}: {код} с {_рус(с)} по {_рус(по)} — проверьте, кто заменит", 1, "диспетчер"))
    return итог


