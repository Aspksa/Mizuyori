def _кому_адресовано(текст: str) -> str | None:
    """«Механик, что по ТО?» / «юрист: проверь договор» — обращение в начале сообщения по имени агента."""
    начало = " ".join(текст.lower().replace("ё", "е").split())[:60]
    for а in РАБОЧИЕ_АГЕНТЫ:
        имя = а["имя"].lower().replace("ё", "е")
        основа = имя.split()[0] if а["ключ"] != "инженер" else "старший инженер"
        for вариант in (имя, основа, основа[:-1] if len(основа) > 6 else основа, а["ключ"]):
            if вариант and начало.startswith(вариант) and not начало[len(вариант):len(вариант) + 1].isalpha():
                return а["ключ"]
    return None


def _печать_путевых(база, текст: str) -> tuple[str, str]:
    """Просьба «оформи путевой на Лушкина»: Диспетчер заполняет бланк из базы и кладёт Excel в чат;
    на принтер файл уходит, только если об этом попросили («распечатай»)."""
    from datetime import timedelta
    from urllib.parse import quote
    найдено = printing.найти(текст)
    все = "все" in printing._норм(текст).split() and len(найдено) > 1
    if not printing.все_шаблоны():
        return ("Просьба хозяина: путевой лист. Но папка «шаблоны/путевые» пуста — скажи, что шаблонов нет."), \
            "📄 Шаблонов путевых листов нет в папке «шаблоны/путевые»."
    if not найдено:
        return ("Просьба хозяина: путевой лист, но подходящего шаблона не нашлось. Попроси назвать фамилию водителя или машину."), \
            "📄 Не нашёл такой путевой лист. Назовите фамилию водителя или машину."
    if len(найдено) > 1 and not все:
        список = "\n".join(f"- {printing.подпись(п)}" for п in найдено[:12])
        return (("Просьба хозяина: путевой лист. Подходит несколько шаблонов, НИЧЕГО НЕ СОЗДАНО:\n"
                 f"{список}\nКоротко спроси, какой именно (можно добавить марку машины или слово «все»)."),
                "📄 Ничего не создано — подходит несколько путевых, уточните:\n" + список + "\n(добавьте марку машины или слово «все»)")
    день = date.today() + timedelta(days=1 if "завтра" in printing._норм(текст).split() else 0)
    готовые, строки, замечания = [], [], []
    for шаблон in найдено[:5]:
        водитель, авто = putevoy.подобрать(база, шаблон, текст)
        р = putevoy.заполнить(шаблон, водитель, авто, день)
        готовые.append(р["файл"])
        строки.append(f"- [{р['файл'].name}](/api/work-agents/putevoy/{quote(р['файл'].name)}) — " + "; ".join(р["подставлено"]))
        замечания += [f"{printing.подпись(шаблон)}: {з}" for з in р["предупреждения"]]
    печатать = printing.просят_печать(текст)
    if печатать:
        printing.отправить_в_фоне(готовые, при_ошибке=_ошибка_печати)
    сообщение = f"📄 Путевой лист заполнен на {день:%d.%m.%Y} (Excel, лицевая сторона и оборот):\n" + "\n".join(строки)
    if замечания:
        сообщение += "\n⚠ " + "\n⚠ ".join(замечания)
    if печатать:
        сообщение += "\n🖨 Отправлено на принтер" + (" (двусторонняя печать)" if printing.НАСТРОЙКИ.get("двусторонняя", True) else "")
    return ("Просьба хозяина: оформить путевой лист. Задача выполнена: Диспетчер по выпуску заполнил бланк из базы "
            "(машина, госномер, водитель, номер удостоверения), файл Excel уже лежит в чате. Скажи об этом одной фразой."), сообщение


def _смета_в_чате(база, настройки_ии: dict, текст: str) -> tuple[str, str] | None:
    """Слова хозяина о только что присланной смете: подтвердить, отклонить или поправить разбор."""
    с = smeta.последняя(база, "на проверке")
    if not с:
        return None
    н = " ".join(текст.lower().replace("ё", "е").split())
    if "смет" not in н and not re.fullmatch(r"(да|верно|все верно|подтверждаю)[.! ]*", н):
        return None
    if re.search(r"(подтвержд|верно|утвержд|принима|согласен)", н) and not re.search(r"(не верно|неверно|не так)", н):
        smeta.изменить_статус(база, с["id"], "подтверждена")
        итог = documents.собрать(база, настройки_ии, с)
        строки = [f"- {д['название']} ({agents.ИМЕНА[д['агент']]}): [{д['файл']}](/api/work-agents/doc/{quote(д['файл'])})"
                  for д in итог["документы"]]
        сообщение = f"✅ Смета «{с['имя']}» подтверждена. Агенты подготовили черновики (Word):\n" + "\n".join(строки)
        сообщение += ("\n\nСчёт-оферта выбрана потому, что сумма меньше порога договора." if not итог["договор"] else
                      "\n\nДоговор выбран, потому что сумма не меньше порога.")
        if итог["предупреждения"]:
            сообщение += "\n⚠ " + "\n⚠ ".join(итог["предупреждения"])
        сообщение += "\nВсё это черновики: проверьте реквизиты, сроки и условия, прежде чем подписывать."
        return ("Хозяин подтвердил смету, агенты подготовили документы. Скажи одной фразой.", сообщение)
    if re.search(r"(отклон|отмени|удали|не надо|не нужн)", н):
        smeta.изменить_статус(база, с["id"], "отклонена")
        return ("Хозяин отклонил смету. Скажи одной фразой.", f"🗑 Смета «{с['имя']}» отклонена, ничего по ней не делаю.")
    if re.search(r"(поправ|исправ|измен|замен|не так|ошиб|итого|исполнител|заказчик|объект|номер|дата|позици)", н):
        try:
            р = smeta.поправить(база, настройки_ии, с, текст)
        except Exception:
            журнал.exception("Поправка сметы не удалась")
            return ("Поправку сметы не удалось применить. Скажи об этом одной фразой.",
                    "⚠ Не получилось применить поправку — скажите точнее, что заменить.")
        if not р["принято"]:
            return ("Поправка сметы не распознана. Скажи об этом одной фразой.",
                    "⚠ Не понял, что именно исправить. Например: «исполнитель — ООО Ромашка», «итого 125 000».")
        return ("Хозяин поправил разбор сметы. Скажи одной фразой, что изменилось.",
                f"✏ Исправил: {', '.join(р['принято'])}.\n\n" + smeta.описание(р["смета"]))
    return None


