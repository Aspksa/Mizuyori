def запустить_фоновое_развитие(база, получить_настройки_ии) -> None:
    """Раз в несколько часов: обход данных всеми агентами (учёба с ИИ — в learning.py)."""
    global _поток
    with _замок:
        if _поток and _поток.is_alive():
            return

        def цикл():
            time.sleep(60)
            while True:
                try:
                    обойти_всех(база)
                except Exception:
                    журнал.exception("Фоновое развитие агентов Работы")
                time.sleep(ИНТЕРВАЛ_ЧАСОВ * 3600)

        _поток = threading.Thread(target=цикл, name="mizuyori-work-agents", daemon=True)
        _поток.start()


