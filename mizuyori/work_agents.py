_СИСТЕМА_ЗАПИСКИ = (
    "Ты — старший инженер отдела главного механика АО «Примавтодор». Пиши деловую служебную записку по-русски, "
    "кратко и по делу, без выдумывания фактов: используй только данные из задания. "
    "Ответ — JSON: {\"тема\": \"...\", \"текст\": \"...\"}. Текст — 3-6 предложений, без обращения и подписи."
)


def написать_записку(база, настройки_ии: dict, тема: str, пояснение: str = "", кому: str = "", от_кого: str = "") -> dict:
    """Черновик служебной записки → таблица «Служебные записки» (статус «черновик»)."""
    тема = " ".join(тема.split())[:200] or "Служебная записка"
    данные = {"тема": тема, "пояснение": пояснение[:1500],
              "замечания_агентов": [н["текст"] for к in КЛЮЧИ if к != "инженер" for н in НАБЛЮДАТЕЛИ[к](база)
                                    if н["важно"] >= 1][:12]}
    from . import ai
    текст = ""
    with agents.работа("инженер", "пишу служебную записку", тема) as з:
        if ai.подключён(настройки_ии):
            try:
                ответ = ai._задание(_СИСТЕМА_ЗАПИСКИ, данные, agents.с_правилами(настройки_ии, "инженер"), 900)
                р = json.loads(ai._ОБЪЕКТ.search(ответ).group(0))
                текст = str(р.get("текст", "")).strip()
                тема = " ".join(str(р.get("тема") or тема).split())[:200]
            except Exception:
                журнал.exception("Записка без ИИ")
        if not текст:
            пункты = данные["замечания_агентов"] if not пояснение.strip() else [пояснение.strip()]
            текст = (пояснение.strip() or "По результатам проверки выявлено:\n" + "\n".join(f"— {п}" for п in пункты)
                     or "Прошу рассмотреть вопрос.")
        номер = work.следующий_номер(база)
        with база.соединение() as связь:
            id_ = связь.execute(
                "INSERT INTO раб_записки (номер, дата, кому, от_кого, тема, текст, статус) VALUES (?, ?, ?, ?, ?, ?, 'черновик')",
                (номер, date.today().isoformat(), кому, от_кого, тема, текст)).lastrowid
            строка = dict(связь.execute("SELECT * FROM раб_записки WHERE id = ?", (id_,)).fetchone())
        з["результат"] = f"черновик «{тема}»"
        з["польза"] = 3
    return строка


