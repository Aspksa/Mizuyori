# ---- Обход: замечания → память → доска ------------------------------------------------

def обойти(база, ключ: str) -> list[dict]:
    """Один агент смотрит на данные: опыт за найденное, повторяющиеся замечания в памяти,
    срочное — записками на доску."""
    нашёл: list[dict] = []
    with agents.работа(ключ, "обход данных", "по расписанию") as з:
        нашёл = НАБЛЮДАТЕЛИ[ключ](база)
        _последние[ключ] = нашёл
        важных = [н for н in нашёл if н["важно"] >= 1]
        з["результат"] = f"замечаний: {len(важных)}" if важных else "всё в порядке"
        з["польза"] = 1 + min(len(важных), 3)
        for н in важных:
            # одинаковое замечание склеивается со счётчиком — так агент знает «хронические» проблемы
            agents.запомнить_ошибку(ключ, н["текст"])
            if н["важно"] >= 2:
                agents.написать(ключ, н["кому"] or "инженер", н["текст"])
            elif н["кому"]:
                agents.написать(ключ, н["кому"], н["текст"])
        if ключ == "инженер":      # записки прочитаны: замечания из них уже в памяти
            agents.прочитать([з["id"] for з in agents.непрочитанные("инженер")])
    return нашёл


def замечания(база, ключ: str) -> list[dict]:
    return НАБЛЮДАТЕЛИ[ключ](база)


def обойти_всех(база) -> None:
    for к in КЛЮЧИ:
        try:
            обойти(база, к)
        except Exception:
            журнал.exception("Обход агента %s не удался", к)


