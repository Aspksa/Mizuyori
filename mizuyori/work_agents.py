    for попытка in range(3):        # 429 «слишком много запросов» проходит сам — ждём и пробуем снова
        try:
            ответ = ai._задание(_СИСТЕМА_УЧЁБЫ.format(имя=agents.ИМЕНА[ключ]),
                                {"частые_замечания": ошибки, "уже_записано": есть}, настройки_ии, 300)
            break
        except Exception as ошибка:
            if попытка < 2 and ("429" in str(ошибка) or "Слишком много" in str(ошибка)):
                time.sleep(30 * (попытка + 1))
                continue
            журнал.warning("ИИ недоступен: %s не смог научиться сейчас", ключ)
            return ""
    if ответ is None:
        return ""          # сбой связи — не опыт агента, в его ошибки не пишем
    итог = ""
    with agents.работа(ключ, "учусь на опыте", "раз в сутки") as з:
        try:
            приём = str(json.loads(ai._ОБЪЕКТ.search(ответ).group(0)).get("приём", "")).strip()
        except Exception:
            приём = ""
        приём = " ".join(приём.split())[:200]
        if приём and приём not in есть:
            agents.добавить_заметку(ключ, "приём", приём, "сам")
            итог = приём
            з["польза"] = 3
        з["результат"] = f"новый приём: {приём}" if итог else "нового не нашёл"
    return итог


