def для_чата(база, настройки_ии: dict, текст: str) -> dict:
    """Что агенты Работы добавляют в ответ чата: {"текст": блок для подсказки, "правила": …, "агент": ключ}.
    Пусто, если разговор не про работу; не пересчитывает данные — берёт замечания с последнего обхода."""
    кому = _кому_адресовано(текст)
    низ = " " + текст.lower() + " "
    печать = сообщение = None
    if printing.это_печать(текст):
        кому = кому or "диспетчер"
        печать, сообщение = _печать_путевых(база, текст)
    по_смете = _смета_в_чате(база, настройки_ии, текст)
    if по_смете:
        кому = кому or "инженер"
        печать, сообщение = по_смете
    факты, агент_справки = reference.для_вопроса(база, текст)
    if факты:
        кому = кому or агент_справки
    if not кому and not any(т in низ for т in ТЕМЫ_РАБОТЫ):
        return {}
    for к in КЛЮЧИ:
        if к not in _последние:
            try:
                _последние[к] = НАБЛЮДАТЕЛИ[к](база)
            except Exception:
                журнал.exception("Агент %s не смог посмотреть данные для чата", к)
                _последние[к] = []
    части = ["Рабочие агенты отдела главного механика (ты можешь опираться на их замечания и называть, "
             "кто что заметил; отвечай коротко и по делу):"]
    for к in КЛЮЧИ:
        зам = [н["текст"] for н in sorted(_последние.get(к, []), key=lambda н: -н["важно"]) if н["важно"] >= 1][:3]
        if зам:
            части.append(f"- {agents.ИМЕНА[к]}: " + " | ".join(зам))
    итог = {"текст": "\n".join(части) if len(части) > 1 else "Рабочие агенты замечаний сейчас не видят.", "агент": кому}
    if кому:
        а = next(а for а in РАБОЧИЕ_АГЕНТЫ if а["ключ"] == кому)
        итог["текст"] += (f"\n\nХозяин обратился к агенту «{а['имя']}» ({а['что']}). Отвечай от его лица, "
                          f"в его роли, опираясь на его замечания.")
        итог["правила"] = agents.правила(кому)
        if кому == "инженер" and "записк" in низ and any(г in низ for г in ("напиши", "составь", "подготовь", "сделай")):
            import re
            тема = re.split(r"\b(?:про|о|об|по|насчёт|насчет)\b\s+", текст, maxsplit=1)
            тема = (тема[1] if len(тема) > 1 and тема[1].strip() else текст).strip()[:200]
            з = написать_записку(база, настройки_ии, тема[:1].upper() + тема[1:], текст)
            итог["записка"] = з
            итог["текст"] += (f"\nЧерновик служебной записки №{з['номер']} «{з['тема']}» уже создан в «Работа → "
                             f"Служебные записки». Скажи об этом и коротко перескажи текст:\n{з['текст']}")
    if факты:
        итог["текст"] += "\n\n" + факты
    if печать:
        итог["текст"] += "\n\n" + печать + "\nЭту строку про принтер система допишет сама — свою не повторяй."
        итог["сообщение"] = сообщение
        итог["агент"] = кому
    return итог
