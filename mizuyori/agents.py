# ---- Обмен: как агенты передают друг другу работу, знания и опыт --------------------------------

def обмен(сколько: int = 60) -> dict:
    """Лента событий между агентами. Типы:
    «работа» — замечание или поручение, переданное коллеге записной;
    «знание» — урок, который агент предложил коллеге (принял или ещё нет — поле «принято»);
    «опыт» — приём, который агент принял от коллеги в свою память."""
    ключ_по_имени = {и: к for к, и in ИМЕНА.items()}
    события = []
    with _база.соединение() as связь:
        for з in связь.execute("SELECT id, от, кому, текст, прочитано, создано FROM доска ORDER BY id DESC LIMIT ?", (сколько,)).fetchall():
            урок = з["текст"].startswith("Урок:")
            события.append({"id": f"д{з['id']}", "время": з["создано"], "от": з["от"], "кому": з["кому"],
                            "тип": "знание" if урок else "работа", "текст": (з["текст"][5:].strip() if урок else з["текст"]),
                            "принято": bool(з["прочитано"])})
        for н in связь.execute("SELECT id, агент, текст, источник, создано FROM агент_заметки WHERE источник LIKE 'от %' "
                               "ORDER BY id DESC LIMIT ?", (сколько,)).fetchall():
            автор = ключ_по_имени.get(н["источник"][3:].strip())
            if автор:
                события.append({"id": f"н{н['id']}", "время": н["создано"], "от": автор, "кому": н["агент"],
                                "тип": "опыт", "текст": н["текст"], "принято": True})
    события = [е for е in события if е["от"] != е["кому"]]        # записка самому себе — не обмен
    события.sort(key=lambda е: е["время"], reverse=True)
    события = события[:сколько]
    пары: dict[tuple, int] = {}
    счёт = {"работа": 0, "знание": 0, "опыт": 0}
    for е in события:
        счёт[е["тип"]] += 1
        if е["от"] in ИМЕНА and е["кому"] in ИМЕНА:
            пары[(е["от"], е["кому"])] = пары.get((е["от"], е["кому"]), 0) + 1
    топ = sorted(пары.items(), key=lambda п: -п[1])[:6]
    return {"события": события, "счёт": счёт, "имена": ИМЕНА,
            "пары": [{"от": о, "кому": к, "число": ч} for (о, к), ч in топ]}
