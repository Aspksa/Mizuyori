"""Агенты — фоновые помощники Mizuyori и их активность.

Каждый агент — реальная работа сайта: ответ в чате, обновление памяти, сводка, смысловые
вектора, раскладка задач по целям, мнения души. Здесь считается, кто работает сейчас,
сколько раз сработал сегодня, когда последний раз и чем закончилось.
"""

import logging
import threading
import time
from contextlib import contextmanager
from datetime import date, datetime

журнал = logging.getLogger("mizuyori.агенты")

АГЕНТЫ = [
    {"ключ": "чат", "имя": "Собеседник", "значок": "чат", "что": "отвечает в чате"},
    {"ключ": "память", "имя": "Память", "значок": "память", "что": "запоминает факты, людей и цели после ответа"},
    {"ключ": "сводка", "имя": "Летописец", "значок": "сводка", "что": "сжимает длинный чат в краткий пересказ"},
    {"ключ": "смысл", "имя": "Смысл", "значок": "смысл", "что": "считает смысловые вектора для связей и поиска"},
    {"ключ": "цели", "имя": "Стратег", "значок": "цели", "что": "раскладывает задачи по целям"},
    {"ключ": "мнения", "имя": "Душа", "значок": "мнения", "что": "высказывает мнения о целях и проектах"},
]
_ИЗВЕСТНЫЕ = {а["ключ"] for а in АГЕНТЫ}

_замок = threading.Lock()
_база = None
_работают: dict[str, int] = {}          # ключ → сколько сейчас запусков идёт
_начато: dict[str, float] = {}


def подключить(база) -> None:
    global _база
    _база = база


def _состояние() -> dict:
    данные = (_база.прочитать("агенты", {}) if _база else {}) or {}
    if данные.get("день") != date.today().isoformat():
        данные = {"день": date.today().isoformat(), "агенты": данные.get("агенты", {})}
        for а in данные["агенты"].values():
            а["сегодня"] = 0
            а["ошибок"] = 0
    данные.setdefault("агенты", {})
    return данные


@contextmanager
def работа(ключ: str):
    """with агенты.работа("память"): … — отмечает начало, конец, время и ошибку."""
    if ключ not in _ИЗВЕСТНЫЕ:
        yield
        return
    with _замок:
        _работают[ключ] = _работают.get(ключ, 0) + 1
        _начато[ключ] = time.monotonic()
    ошибка = ""
    try:
        yield
    except Exception as е:
        ошибка = str(е)[:200] or е.__class__.__name__
        raise
    finally:
        with _замок:
            _работают[ключ] = max(0, _работают.get(ключ, 1) - 1)
            секунд = round(time.monotonic() - _начато.get(ключ, time.monotonic()), 1)
            try:
                данные = _состояние()
                а = данные["агенты"].setdefault(ключ, {"сегодня": 0, "всего": 0, "ошибок": 0})
                а["сегодня"] = а.get("сегодня", 0) + 1
                а["всего"] = а.get("всего", 0) + 1
                а["последний"] = datetime.now().isoformat(sep=" ", timespec="seconds")
                а["секунд"] = секунд
                а["ошибка"] = ошибка
                if ошибка:
                    а["ошибок"] = а.get("ошибок", 0) + 1
                if _база:
                    _база.записать("агенты", данные)
            except Exception:
                журнал.exception("Не удалось записать активность агента")


def сводка() -> dict:
    with _замок:
        данные = _состояние()
        работают = dict(_работают)
        начато = dict(_начато)
    итог = []
    for а in АГЕНТЫ:
        с = данные["агенты"].get(а["ключ"], {})
        идёт = работают.get(а["ключ"], 0) > 0
        итог.append({**а,
                     "работает": идёт,
                     "идёт_секунд": round(time.monotonic() - начато[а["ключ"]], 1) if идёт else 0,
                     "сегодня": с.get("сегодня", 0), "всего": с.get("всего", 0),
                     "последний": с.get("последний", ""), "секунд": с.get("секунд"),
                     "ошибка": с.get("ошибка", ""), "ошибок": с.get("ошибок", 0)})
    return {"агенты": итог,
            "работают": sum(1 for а in итог if а["работает"]),
            "сегодня": sum(а["сегодня"] for а in итог)}
