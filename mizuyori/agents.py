"""Агенты — фоновые помощники Mizuyori: активность, история решений, своя память, доска, опыт.

Каждый агент — реальная работа сайта: ответ в чате, обновление памяти, сводка, смысловые
вектора, раскладка задач по целям, мнения души.

- История решений: что сделал, почему, чем кончилось (таблица «агент_история»).
- Своя память: правила и приёмы (их пишете вы или агент) и частые ошибки (агент собирает сам).
  Правила и приёмы добавляются в задание агента для ИИ.
- Доска: агенты оставляют записки друг другу (Память → Стратегу: «появилась цель…»).
- Опыт: растёт от полезных действий; уровень — звёздочки на кружке.
"""

