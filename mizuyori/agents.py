# ---- Работа ------------------------------------------------------------------

@contextmanager
def работа(ключ: str, действие: str = "", почему: str = ""):
    """with агенты.работа("память", "обновил память", "после ответа") as з:
           …; з["результат"] = "добавлено 2 факта"; з["польза"] = 2
    Отмечает начало и конец, пишет историю, считает опыт, запоминает ошибки."""
    запись = {"действие": действие or ИМЕНА.get(ключ, ключ), "почему": почему, "результат": "", "польза": 0}
    if ключ not in ИМЕНА:
        yield запись
        return
    with _замок:
        _работают[ключ] = _работают.get(ключ, 0) + 1
        _начато[ключ] = time.monotonic()
    _стек.__dict__.setdefault("значение", []).append(ключ)
    начало = time.monotonic()
    ошибка = ""
    try:
        yield запись
    except Exception as е:
        ошибка = str(е)[:200] or е.__class__.__name__
        raise
    finally:
        секунд = round(time.monotonic() - начало, 1)
        try:
            _стек.значение.pop()
        except (AttributeError, IndexError):
            pass
        with _замок:
            _работают[ключ] = max(0, _работают.get(ключ, 1) - 1)
        try:
            _записать(ключ, запись, ошибка, секунд)
        except Exception:
            журнал.exception("Не удалось записать работу агента")


def _записать(ключ: str, запись: dict, ошибка: str, секунд: float) -> None:
    if not _база:
        return
    результат = f"ошибка: {ошибка}" if ошибка else (запись.get("результат") or "готово")
    польза = 0 if ошибка else max(0, int(запись.get("польза") or 0))
    with _база.соединение() as связь:
        связь.execute(
            "INSERT INTO агент_история (агент, действие, почему, результат, успех, польза, секунд) VALUES (?, ?, ?, ?, ?, ?, ?)",
            (ключ, запись["действие"][:120], (запись.get("почему") or "")[:200], результат[:300],
             0 if ошибка else 1, польза, секунд))
        # история не растёт бесконечно: последние 500 записей на агента
        связь.execute("DELETE FROM агент_история WHERE агент = ? AND id NOT IN "
                      "(SELECT id FROM агент_история WHERE агент = ? ORDER BY id DESC LIMIT 500)", (ключ, ключ))
    if ошибка:
        запомнить_ошибку(ключ, ошибка)


def запомнить_ошибку(ключ: str, текст: str) -> None:
    """Частые ошибки агент собирает сам: одинаковые склеиваются со счётчиком."""
    текст = " ".join(текст.split())[:200]
    with _база.соединение() as связь:
        есть = связь.execute("SELECT id FROM агент_заметки WHERE агент = ? AND вид = 'ошибка' AND текст = ?",
                             (ключ, текст)).fetchone()
        if есть:
            связь.execute("UPDATE агент_заметки SET счёт = счёт + 1, изменено = datetime('now', 'localtime') "
                          "WHERE id = ?", (есть[0],))
        else:
            связь.execute("INSERT INTO агент_заметки (агент, вид, текст, источник) VALUES (?, 'ошибка', ?, 'сам')",
                          (ключ, текст))


