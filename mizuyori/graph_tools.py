ТИПЫ = {"е": "сущность", "п": "факт", "з": "задача"}


def _построить(база) -> tuple[dict[str, list[tuple[str, str]]], dict[str, dict]]:
    """Соседи и подписи: сущности, факты, задачи; рёбра — отношения, упоминания, «для цели», зависимости."""
    узлы: dict[str, dict] = {}
    соседи: dict[str, list[tuple[str, str]]] = {}

    def узел(ключ, тип, текст, **доп):
        узлы[ключ] = {"ключ": ключ, "тип": тип, "текст": текст, **доп}
        соседи.setdefault(ключ, [])

    def ребро(а, б, подпись, обратная=None):
        if а in узлы and б in узлы:
            соседи[а].append((б, подпись))
            соседи[б].append((а, обратная or подпись))

    for с in база.сущности():
        узел(f"е{с['id']}", "сущность", с["имя"], подтип=с["тип"], другие=list(с.get("другие_имена") or []))
    for ф in база.память():
        узел(f"п{ф['id']}", "факт", ф["факт"])
    задачи = база.задачи()
    for з in задачи:
        узел(f"з{з['id']}", "задача", з["текст"])
    with база.соединение() as связь:
        for о in связь.execute("SELECT от_id, отношение, к_id FROM отношения").fetchall():
            ребро(f"е{о['от_id']}", f"е{о['к_id']}", о["отношение"], f"← {о['отношение']}")
        for ф, с in связь.execute("SELECT факт_id, сущность_id FROM факт_сущность").fetchall():
            ребро(f"п{ф}", f"е{с}", "упоминает", "упомянут в факте")
        for з in связь.execute("SELECT id, цель_id FROM задачи WHERE цель_id IS NOT NULL").fetchall():
            ребро(f"з{з['id']}", f"е{з['цель_id']}", "для цели", "цель задачи")
        for з, от in связь.execute("SELECT задача_id, зависит_от_id FROM задача_зависимости").fetchall():
            ребро(f"з{з}", f"з{от}", "зависит от", "блокирует")
    return соседи, узлы


def найти_узел(база, запрос: str, узлы: dict | None = None) -> str | None:
    """Ключ узла по имени сущности или фрагменту факта/задачи."""
    if re.fullmatch(r"[епз]\d+", запрос or ""):
        return запрос
    _, узлы = (None, узлы) if узлы else _построить(база)
    к = ключ_имени(запрос).strip(" .,!?\"«»")
    if not к:
        return None
    точные = [у for у in узлы.values() if у["тип"] == "сущность" and ключ_имени(у["текст"]) == к]
    if точные:
        return точные[0]["ключ"]
    for у in узлы.values():
        if у["тип"] == "сущность" and any(ключ_имени(д) == к for д in у.get("другие", [])):
            return у["ключ"]
    # с учётом падежей: совпадение по началу слова (мама → маму, маме)
    основа = к[:-1] if len(к) > 4 else к
    частичные = [у for у in узлы.values() if у["тип"] == "сущность" and (основа in ключ_имени(у["текст"]) or ключ_имени(у["текст"]) in к)]
    if частичные:
        return min(частичные, key=lambda у: len(у["текст"]))["ключ"]
    любые = [у for у in узлы.values() if основа in ключ_имени(у["текст"])]
    return любые[0]["ключ"] if любые else None


def путь(база, а: str, б: str, макс_шагов: int = 6) -> dict:
    """Кратчайшая цепочка между двумя узлами и её объяснение словами."""
    соседи, узлы = _построить(база)
    ка, кб = найти_узел(база, а, узлы), найти_узел(база, б, узлы)
    if not ка or not кб:
        return {"найден": False, "причина": f"Не нашёл в графе: {', '.join(x for x, к in ((а, ка), (б, кб)) if not к)}."}
    if ка == кб:
        return {"найден": False, "причина": "Это одна и та же точка."}
    пред = {ка: None}
    очередь = deque([(ка, 0)])
    while очередь:
        текущий, глубина = очередь.popleft()
        if текущий == кб:
            break
        if глубина >= макс_шагов:
            continue
        for сосед, подпись in соседи.get(текущий, []):
            if сосед not in пред:
                пред[сосед] = (текущий, подпись)
                очередь.append((сосед, глубина + 1))
    if кб not in пред:
        return {"найден": False, "причина": "Прямой цепочки между ними нет: в графе они не связаны."}
    цепочка, к = [], кб
    while к:
        из = пред[к]
        цепочка.append({"узел": {**узлы[к]}, "связь": из[1] if из else ""})
        к = из[0] if из else None
    цепочка.reverse()
    # подпись ребра относится к переходу в этот узел от предыдущего
    слова = [цепочка[0]["узел"]["текст"]]
    for шаг in цепочка[1:]:
        слова.append(f"—{шаг['связь']}→ {шаг['узел']['текст']}")
    return {"найден": True, "шаги": цепочка, "объяснение": " ".join(слова)[:600], "длина": len(цепочка) - 1}


