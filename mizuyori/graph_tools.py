def аудит(база) -> dict:
    соседи, узлы = _построить(база)
    одиночки = [{"ключ": к, "текст": у["текст"], "подтип": у.get("подтип", "")} for к, у in узлы.items()
                if у["тип"] == "сущность" and not соседи[к]]
    факты_без_людей = [{"ключ": к, "текст": у["текст"]} for к, у in узлы.items() if у["тип"] == "факт" and not соседи[к]]
    сущности = [у for у in узлы.values() if у["тип"] == "сущность"]
    дубли = []
    видели = set()
    for i, у in enumerate(сущности):
        for в in сущности[i + 1:]:
            ка, кб = ключ_имени(у["текст"]), ключ_имени(в["текст"])
            похоже = difflib.SequenceMatcher(None, ка, кб).ratio()
            if (похоже >= 0.86 or (len(ка) > 3 and (ка in кб or кб in ка) and abs(len(ка) - len(кб)) <= 3)) and (у["ключ"], в["ключ"]) not in видели:
                видели.add((у["ключ"], в["ключ"]))
                основной, повтор = (у, в) if len(соседи[у["ключ"]]) >= len(соседи[в["ключ"]]) else (в, у)
                дубли.append({"основной": основной["ключ"], "повтор": повтор["ключ"], "основной_текст": основной["текст"],
                              "повтор_текст": повтор["текст"], "похожесть": round(похоже, 2)})
    цели = []
    for с in база.сущности():
        if с["тип"] == "цель" and (с.get("статус") or "активна") == "активна":
            ключ = f"е{с['id']}"
            if not any(узлы[н]["тип"] == "задача" for н, _ in соседи.get(ключ, [])):
                цели.append({"ключ": ключ, "текст": с["имя"]})
    return {"одиночки": одиночки[:40], "факты_без_связей": факты_без_людей[:40], "дубли": дубли[:30], "цели_без_задач": цели,
            "всего": len(одиночки) + len(факты_без_людей) + len(дубли) + len(цели)}


def предложить_связи(база, настройки_ии: dict, порог: float = 0.8, сколько: int = 15) -> dict:
    """Пары, похожие по смыслу, но не связанные в графе в пределах двух шагов."""
    import numpy as np

    from . import ai, memory
    if not настройки_ии.get("ключ") or not настройки_ии.get("модель_эмбеддингов"):
        return {"доступно": False, "причина": "Нужен ключ cloud.ru и модель для связей (настройки проекта → ИИ).", "предложения": []}
    соседи, узлы = _построить(база)
    тексты = {к: у["текст"] for к, у in узлы.items() if у["тип"] in ("сущность", "факт")}
    if len(тексты) < 2:
        return {"доступно": True, "предложения": []}
    try:
        ключи, матрица, _ = memory.обеспечить_вектора(база, настройки_ии, тексты)
    except ai.ОшибкаИИ as ошибка:
        return {"доступно": False, "причина": str(ошибка), "предложения": []}
    сходство = матрица @ матрица.T
    np.fill_diagonal(сходство, -1)
    итог = []
    for i in range(len(ключи)):
        for j in range(i + 1, len(ключи)):
            п = float(сходство[i, j])
            if п < порог:
                continue
            а, б = ключи[i], ключи[j]
            близко = {н for н, _ in соседи.get(а, [])} | {н for с_, _ in соседи.get(а, []) for н, _ in соседи.get(с_, [])}
            if б in близко:
                continue
            тип = ("факты" if а[0] == "п" and б[0] == "п" else "сущности" if а[0] == "е" and б[0] == "е" else "факт_и_сущность")
            итог.append({"а": а, "б": б, "а_текст": узлы[а]["текст"], "б_текст": узлы[б]["текст"], "похожесть": round(п, 3), "вид": тип})
    итог.sort(key=lambda х: -х["похожесть"])
    return {"доступно": True, "предложения": итог[:сколько]}


def применить(база, действие: str, а: str = "", б: str = "", отношение: str = "связано с") -> dict:
    """Действия над графом: объединить сущности/факты, связать, привязать факт, удалить одиночку."""
    def номер(ключ, префикс):
        if not re.fullmatch(rf"{префикс}\d+", ключ or ""):
            raise ValueError("Неверная точка графа.")
        return int(ключ[1:])

    if действие == "объединить_сущности":
        return {"ок": база.объединить_сущности(номер(а, "е"), номер(б, "е"))}
    if действие == "объединить_факты":
        return {"ок": база.объединить_факты(номер(а, "п"), номер(б, "п"))}
    if действие == "связать":
        база.связать(номер(а, "е"), отношение, номер(б, "е"))
        return {"ок": True}
    if действие == "привязать_факт":
        ф, с = (а, б) if а.startswith("п") else (б, а)
        база.привязать_факт(номер(ф, "п"), номер(с, "е"))
        return {"ок": True}
    if действие == "удалить_одиночку":
        return {"ок": база.удалить_сущность(номер(а, "е"))}
    raise ValueError("Неизвестное действие.")


def для_чата(база, текст: str) -> tuple[str, str] | None:
    """«Как связаны Мама и подарок?» → цепочка из графа."""
    м = re.search(r"как(?:им образом)?\s+связан\w*\s+(.+?)\s+(?:и|с)\s+(.+?)[?.! ]*$", текст.strip(), re.I)
    if not м:
        return None
    р = путь(база, м.group(1), м.group(2))
    if not р["найден"]:
        return ("Хозяин спросил, как связаны две вещи в графе, но цепочки нет. Скажи об этом одной фразой.",
                f"🕸 {р['причина']}")
    return ("Хозяин спросил, как связаны две вещи; цепочка из графа найдена. Скажи одной фразой.",
            f"🕸 Связь в графе (шагов: {р['длина']}):\n{р['объяснение']}")
