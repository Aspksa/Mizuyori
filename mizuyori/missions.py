def _json_из_текста(текст: str) -> dict | list | None:
    for шаблон in (r"\{.*\}", r"\[.*\]"):
        м = re.search(шаблон, текст or "", re.S)
        if м:
            try:
                return json.loads(м.group(0))
            except ValueError:
                continue
    return None


def _имя(ключ: str) -> str:
    return agents.ИМЕНА.get(ключ, ключ)


def _выполнить_шаг(м: dict, номер: int, замечание: str, предыдущие: list[str], н: dict, исполнитель: str = "",
                   можно_передать: bool = False) -> tuple[str, dict]:
    ш = м["шаги"][номер]
    ключ = исполнитель or ш["агент"]
    факты = ""
    if ш["инструмент"]:
        ок, причина = tools.проверить_вызов(ш["инструмент"], ключ, ш["описание"])
        if not ок:
            audit.записать("вызов инструмента заблокирован", f"{_имя(ключ)} → {ш['инструмент']}", причина, кто="файрвол")
            raise ОшибкаПоручения(f"Вызов заблокирован: {причина}.")
        факты = tools.вызвать(ш["инструмент"], {"описание": ш["описание"], "агент": ключ, "настройки_ии": н, "база": _база,
                                                "до_этого": предыдущие})
    if not ai.подключён(н):
        if факты:
            return факты, {"запросов": 0, "токенов": 0}
        raise ОшибкаПоручения("ИИ не подключён: добавьте ключ в настройках ИИ.")
    система = (f"Ты — агент «{_имя(ключ)}». Выполни один шаг поручения. Отвечай по-русски, по делу, не длиннее 12 строк. "
               "Опирайся на факты и результаты предыдущих шагов. Если данных не хватает — так и скажи, ничего не выдумывай.")
    if ш["ожидание"]:
        система += f"\nРезультат должен соответствовать: {ш['ожидание']}"
    if можно_передать:
        система += ("\nЕсли шаг явно не по вашей части, не выдумывай, а ответь ОДНОЙ строкой: «ПЕРЕДАЮ: ключ_агента: причина». "
                    "Ключи: " + ", ".join(f"{к} ({имя})" for к, имя in agents.ИМЕНА.items() if к not in ("смысл", "чат", "память", "сводка", "мнения", ключ)))
    данные = {"поручение": м["название"], "шаг": ш["описание"], "факты": факты, "результаты_предыдущих_шагов": предыдущие[-3:]}
    if замечание:
        данные["замечание_проверяющего"] = замечание
    with ai.измерять() as учёт:
        текст = ai._задание(система, данные, agents.с_правилами(dict(н), ключ, ш["описание"]), 900)
    return (текст or "").strip(), dict(учёт)


def _проверить_результат(ш: dict, текст: str, н: dict) -> tuple[bool, str, dict]:
    if not ш["ожидание"] or not ai.подключён(н):
        return True, "", {"запросов": 0, "токенов": 0}
    ключ = ш["проверяющий"] or (ПРОВЕРЯЮЩИЙ if ПРОВЕРЯЮЩИЙ in agents.ИМЕНА else РУКОВОДИТЕЛЬ)
    система = ("Ты проверяющий. Сверь результат шага с ожиданием. Ответь ТОЛЬКО JSON: "
               '{"подходит": true или false, "замечание": "что исправить, одной фразой; пусто, если подходит"}. '
               "Придирайся только к существенному: к отсутствию нужного, а не к стилю.")
    with ai.измерять() as учёт:
        ответ = ai._задание(система, {"задача": ш["описание"], "ожидание": ш["ожидание"], "результат": текст},
                            agents.с_правилами(dict(н), ключ), 300)
    р = _json_из_текста(ответ)
    if not isinstance(р, dict) or "подходит" not in р:
        return True, "", dict(учёт)          # проверяющий не ответил по форме — не мешаем работе
    return bool(р["подходит"]), str(р.get("замечание") or "")[:300], dict(учёт)


def запустить(номер: int, настройки_ии: dict) -> dict:
    м = получить(номер)
    if not м:
        raise ОшибкаПоручения("Такого поручения нет.")
    if м["статус"] in ("готово",):
        raise ОшибкаПоручения("Поручение уже выполнено.")
    if м["статус"] == "ждёт вас":
        raise ОшибкаПоручения("Поручение ждёт вашего решения: подтвердите или отклоните.")
    audit.записать("поручение запущено", м["название"], "продолжено" if м["шаг"] else "")
    _запустить_поток(номер, настройки_ии)
    return получить(номер)


def _запустить_поток(номер: int, н: dict) -> None:
    with _замок:
        if номер in _идут:
            raise ОшибкаПоручения("Поручение уже выполняется.")
        _идут.add(номер)
        _стоп.discard(номер)
    _сохранить(номер, статус="в работе")
    threading.Thread(target=_ход, args=(номер, dict(н)), daemon=True, name=f"поручение-{номер}").start()


def _оценить_срыв(номер: int) -> None:
    м = получить(номер)
    if not м or м["шаг"] >= len(м["шаги"]):
        return
    ход = list(м["ход"])
    и = м["шаг"]
    запись = dict(ход[и]) if и < len(ход) else {}
    _оценить(м, и, запись, "ошибка")


def _ход(номер: int, н: dict) -> None:
    ai.установить_приоритет("поручение")
    try:
        _идти(номер, н)
    except ОшибкаПоручения as е:
        _оценить_срыв(номер)
        журнал.warning("Поручение %s остановилось: %s", номер, е)
        _сохранить(номер, статус="не вышло", итог=f"Ошибка: {е}"[:300])
    except Exception as е:
        _оценить_срыв(номер)
        журнал.exception("Поручение %s сорвалось", номер)
        _сохранить(номер, статус="не вышло", итог=f"Ошибка: {е}"[:300])
    finally:
        with _замок:
            _идут.discard(номер)


def _идти(номер: int, н: dict) -> None:
    м = получить(номер)
    ход = list(м["ход"])
    while len(ход) < len(м["шаги"]):
        ход.append({})
    предыдущие = [х.get("результат", "") for х in ход[:м["шаг"]] if х.get("результат")]
    for и in range(м["шаг"], len(м["шаги"])):
        if номер in _стоп:
            _сохранить(номер, статус="остановлено", ход=ход, шаг=и)
            return
        ш = м["шаги"][и]
        запись = ход[и] = {"агент": ш["агент"], **ход[и]}
        печать = tools.отпечаток(ш["агент"], ш["инструмент"], ш["описание"])
        нужно_подтверждение = (ш["подтверждать"] or tools.рискованный(ш["инструмент"])) and запись.get("подтверждено_для") != печать
        if нужно_подтверждение:
            запись["состояние"] = "ждёт подтверждения"
            запись["отпечаток"] = печать
            запись["ждёт_с"] = time.time()
            _сохранить(номер, статус="ждёт вас", ход=ход, шаг=и)
            return
        замечание = ""
        итог_запроса = {"запросов": 0, "токенов": 0}
        начало = time.monotonic()
        результат, проверка = запись.get("результат", ""), {}
        if not запись.get("принято"):
            for попытка in range(1, ПОПЫТОК + 1):
                запись.update({"состояние": "работает", "попытка": попытка})
                _сохранить(номер, ход=ход, шаг=и)
                while True:
                    исполнитель = запись.get("агент") or ш["агент"]
                    с_передачей = len(запись.get("передачи", [])) < ПЕРЕДАЧ_МАКС
                    with agents.работа(исполнитель, "выполнил шаг поручения", м["название"]) as з:
                        результат, учёт = _выполнить_шаг(м, и, замечание, предыдущие, н, исполнитель, с_передачей)
                        з["результат"] = результат[:120] or "пусто"
                        з["польза"] = 1
                    итог_запроса = {к: итог_запроса[к] + учёт.get(к, 0) for к in итог_запроса}
                    передача = _разобрать_передачу(результат) if с_передачей else None
                    if not передача:
                        break
                    if _передать(м, и, запись, исполнитель, *передача):
                        _сохранить(номер, ход=ход, шаг=и)
                    # отказ или передача принята — выполняем шаг заново (число передач ограничено ПЕРЕДАЧ_МАКС)
                подходит, замечание, учёт2 = _проверить_результат(ш, результат, н)
                итог_запроса = {к: итог_запроса[к] + учёт2.get(к, 0) for к in итог_запроса}
                проверка = {"подходит": подходит, "замечание": замечание}
                if подходит:
                    break
            запись.update({"результат": результат, "проверка": проверка, "запросов": запись.get("запросов", 0) + итог_запроса["запросов"],
                           "токенов": запись.get("токенов", 0) + итог_запроса["токенов"],
                           "секунд": round(запись.get("секунд", 0) + time.monotonic() - начало, 1)})
            if not проверка.get("подходит", True):
                запись["состояние"] = "не принято"
                _сохранить(номер, статус="ждёт вас", ход=ход, шаг=и)
                return
        запись["состояние"] = "готово"
        _оценить(м, и, запись, "принят_вручную" if запись.get("принято") else "прошёл")
        ход[и] = запись
        _сохранить(номер, ход=ход, шаг=и + 1)
        предыдущие.append(запись["результат"])
        if и + 1 < len(м["шаги"]) and м["шаги"][и + 1]["агент"] != ш["агент"]:
            try:
                agents.написать(ш["агент"], м["шаги"][и + 1]["агент"], f"Поручение «{м['название']}»: шаг {и + 1} готов, ваша очередь.")
            except Exception:
                pass
    итог = предыдущие[-1] if предыдущие else ""
    if м["режим"] == "руководитель" and ai.подключён(н):
        итог = _приёмка(м, предыдущие, н) or итог
    _сохранить(номер, статус="готово", ход=ход, шаг=len(м["шаги"]), итог=итог)


def _разобрать_передачу(текст: str) -> tuple[str, str] | None:
    с = _ПЕРЕДАЮ.match((текст or "").strip())
    return (с.group(1).strip().casefold(), " ".join(с.group(2).split())[:200]) if с else None


def _передать(м: dict, и: int, запись: dict, от: str, кому: str, причина: str) -> bool:
    """Агент отдал шаг коллеге. Принимается, только если коллега есть, это не он сам и ему можно пользоваться инструментом шага."""
    ш = м["шаги"][и]
    передачи = запись.setdefault("передачи", [])
    отказ = ""
    if кому not in agents.ИМЕНА or кому in ("смысл", "чат", "память", "сводка", "мнения"):
        отказ = "нет такого исполнителя"
    elif кому == от:
        отказ = "передача самому себе"
    elif ш["инструмент"] and not tools.проверить_вызов(ш["инструмент"], кому, ш["описание"])[0]:
        отказ = f"{_имя(кому)} не может пользоваться инструментом «{ш['инструмент']}»"
    передачи.append({"от": от, "кому": кому, "причина": причина, "принята": not отказ, **({"отказ": отказ} if отказ else {})})
    audit.записать("шаг передан" if not отказ else "передача шага отклонена", м["название"],
                   f"шаг {и + 1}: {_имя(от)} → {_имя(кому) if кому in agents.ИМЕНА else кому}. {причина or отказ}", кто="агент")
    if отказ:
        return False
    запись["агент"] = кому
    try:
        agents.написать(от, кому, f"Поручение «{м['название']}», шаг {и + 1}: передаю вам. {причина}")
    except Exception:
        pass
    return True


def _оценить(м: dict, и: int, запись: dict, итог: str, замечание: str = "") -> None:
    """Балл шага для самоулучшения агента (evolve): один раз на шаг."""
    if запись.get("оценено"):
        return
    запись["оценено"] = True
    ш = м["шаги"][и]
    try:
        from . import evolve
        evolve.записать_оценку(запись.get("агент") or ш["агент"], м["id"], и, ш["описание"], итог, запись.get("попытка", 1) or 1,
                               bool(ш["ожидание"]), замечание or (запись.get("проверка") or {}).get("замечание", ""),
                               запись.get("секунд", 0), запись.get("токенов", 0))
    except Exception:
        журнал.exception("Не удалось оценить шаг")


def _приёмка(м: dict, результаты: list[str], н: dict) -> str:
    система = ("Ты руководитель. Прими работу команды: коротко (до 8 строк) напиши итог для хозяина по его цели "
               "и отметь, чего не хватило, если не хватило.")
    try:
        with agents.работа(РУКОВОДИТЕЛЬ, "принял итог поручения", м["название"]) as з:
            текст = ai._задание(система, {"цель": м["название"], "результаты_шагов": результаты}, agents.с_правилами(dict(н), РУКОВОДИТЕЛЬ), 700)
            з["результат"] = текст[:120]
            з["польза"] = 2
        return (текст or "").strip()
    except Exception:
        журнал.exception("Руководитель не смог принять итог")
        return ""


def подтвердить(номер: int, настройки_ии: dict, отпечаток: str = "") -> dict:
    """Человек разрешил шаг (или принял результат, не прошедший проверку) — работа продолжается."""
    м = получить(номер)
    if not м or м["статус"] != "ждёт вас":
        raise ОшибкаПоручения("Это поручение ничего не ждёт.")
    ход = list(м["ход"])
    и = м["шаг"]
    запись = {**ход[и]}
    if запись.get("состояние") == "не принято":
        запись["принято"] = True
    печать = tools.отпечаток(м["шаги"][и]["агент"], м["шаги"][и]["инструмент"], м["шаги"][и]["описание"])
    if отпечаток and запись.get("отпечаток") and отпечаток != запись["отпечаток"]:
        raise ОшибкаПоручения("Подтверждение относится к другому шагу или вызову. Обновите окно и посмотрите, что ждёт решения.")
    запись["подтверждено_для"] = печать
    запись["подтверждено"] = True
    if запись.get("ждёт_с"):
        запись["ждал"] = round(запись.get("ждал", 0) + time.time() - запись.pop("ждёт_с"), 1)
    ход[и] = запись
    _сохранить(номер, ход=ход)
    audit.записать("шаг подтверждён" if запись.get("состояние") != "не принято" else "результат принят как есть",
                   м["название"], f"шаг {и + 1}: {_имя(м['шаги'][и]['агент'])} — {м['шаги'][и]['описание'][:100]}")
    _запустить_поток(номер, настройки_ии)
    return получить(номер)


def отклонить(номер: int) -> dict:
    м = получить(номер)
    if not м or м["статус"] not in ("ждёт вас", "в работе"):
        raise ОшибкаПоручения("Нечего отклонять.")
    audit.записать("поручение отклонено" if м["статус"] == "ждёт вас" else "поручение остановлено", м["название"],
                   f"на шаге {м['шаг'] + 1}")
    if м["идёт"]:
        _стоп.add(номер)
        return получить(номер)
    if м["статус"] == "ждёт вас" and м["шаг"] < len(м["ход"]) and м["ход"][м["шаг"]].get("состояние") == "не принято":
        ход = list(м["ход"])
        запись = dict(ход[м["шаг"]])
        _оценить(м, м["шаг"], запись, "отклонён")
        ход[м["шаг"]] = запись
        _сохранить(номер, ход=ход)
    _сохранить(номер, статус="остановлено")
    return получить(номер)


def остановить(номер: int) -> dict:
    return отклонить(номер)


