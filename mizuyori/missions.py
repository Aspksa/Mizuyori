"""Поручения агентам: шаги с ожидаемым результатом, проверка, подтверждение человеком, шаблоны и руководитель.

Поручение — цепочка шагов. У шага есть исполнитель (агент), описание, «что считать готовым» (ожидание),
необязательный инструмент (см. tools.py), проверяющий и флажок «ждать подтверждения».

- Исполнитель выполняет шаг с учётом результатов предыдущих шагов.
- Проверяющий сверяет результат с ожиданием; не подошло — одна повторная попытка с замечанием,
  потом поручение останавливается и ждёт вашего решения: принять как есть или отклонить.
- Режим «руководитель»: Стратег сам раскладывает цель на шаги и в конце принимает итог.
- Шаблоны: в тексте можно писать {параметр}, значения подставляются при запуске.
- Каждый шаг записывает секунды, запросы к ИИ и токены.
"""

from __future__ import annotations

import json
import logging
import re
import threading
import time

from . import agents, ai, audit, tools

журнал = logging.getLogger("mizuyori.поручения")

МАКС_ШАГОВ = 8
РУКОВОДИТЕЛЬ = "цели"           # Стратег
ПРОВЕРЯЮЩИЙ = "проверяющий"
ПОПЫТОК = 2
ПЕРЕДАЧ_МАКС = 2          # сколько раз шаг может переходить от агента к агенту
_ПЕРЕДАЮ = re.compile(r"^\s*ПЕРЕДАЮ\s*:\s*([^\s:]+)\s*:?\s*(.*)$", re.S | re.I)

_база = None
_замок = threading.Lock()
_идут: set[int] = set()
_стоп: set[int] = set()


def подключить(база) -> None:
    global _база
    _база = база


class ОшибкаПоручения(ValueError):
    pass


# ---- Шаги и параметры -----------------------------------------------------------------------

_ПАРАМЕТР = re.compile(r"\{([^{}\s][^{}]{0,40})\}")


def параметры_шагов(название: str, шаги: list[dict]) -> list[str]:
    найдено: list[str] = []
    for текст in [название] + [str(ш.get(п) or "") for ш in шаги for п in ("описание", "ожидание")]:
        for п in _ПАРАМЕТР.findall(текст):
            if п not in найдено:
                найдено.append(п)
    return найдено


def _подставить(текст: str, значения: dict) -> str:
    return _ПАРАМЕТР.sub(lambda м: str(значения.get(м.group(1), м.group(0))), текст)


def _проверить_шаги(шаги) -> list[dict]:
    if not isinstance(шаги, list) or not шаги:
        raise ОшибкаПоручения("Добавьте хотя бы один шаг.")
    if len(шаги) > МАКС_ШАГОВ:
        raise ОшибкаПоручения(f"Шагов не больше {МАКС_ШАГОВ}.")
    итог = []
    for н, ш in enumerate(шаги, 1):
        агент = str(ш.get("агент") or "")
        if агент not in agents.ИМЕНА or агент == "смысл":
            raise ОшибкаПоручения(f"Шаг {н}: неизвестный исполнитель «{агент}».")
        описание = " ".join(str(ш.get("описание") or "").split())[:2000]
        if not описание:
            raise ОшибкаПоручения(f"Шаг {н}: опишите, что сделать.")
        инструмент = str(ш.get("инструмент") or "")
        if инструмент and инструмент not in tools.ИНСТРУМЕНТЫ:
            raise ОшибкаПоручения(f"Шаг {н}: нет инструмента «{инструмент}».")
        if инструмент:
            ок, причина = tools.проверить_вызов(инструмент, агент, описание)
            if not ок:
                audit.записать("вызов инструмента заблокирован", f"{_имя(агент)} → {инструмент}", причина, кто="файрвол")
                raise ОшибкаПоручения(f"Шаг {н}: {причина}.")
        проверяющий = str(ш.get("проверяющий") or "")
        if проверяющий and проверяющий not in agents.ИМЕНА:
            raise ОшибкаПоручения(f"Шаг {н}: неизвестный проверяющий «{проверяющий}».")
        итог.append({"агент": агент, "описание": описание,
                     "ожидание": " ".join(str(ш.get("ожидание") or "").split())[:600],
                     "инструмент": инструмент, "проверяющий": проверяющий,
                     "подтверждать": bool(ш.get("подтверждать"))})
    return итог


# ---- Хранение ------------------------------------------------------------------------------

def _строка(с) -> dict:
    м = dict(с)
    м["шаги"] = json.loads(м["шаги"])
    м["ход"] = json.loads(м["ход"])
    м["идёт"] = м["id"] in _идут
    м["секунд"] = round(sum(х.get("секунд", 0) for х in м["ход"]), 1)
    м["токенов"] = sum(х.get("токенов", 0) for х in м["ход"])
    м["запросов"] = sum(х.get("запросов", 0) for х in м["ход"])
    return м


def получить(номер: int) -> dict | None:
    with _база.соединение() as связь:
        с = связь.execute("SELECT * FROM поручение WHERE id = ?", (номер,)).fetchone()
    return _строка(с) if с else None


def список(сколько: int = 50) -> list[dict]:
    with _база.соединение() as связь:
        строки = связь.execute("SELECT * FROM поручение ORDER BY id DESC LIMIT ?", (сколько,)).fetchall()
    return [_строка(с) for с in строки]


def _сохранить(номер: int, **поля) -> None:
    поля = {к: (json.dumps(з, ensure_ascii=False) if к in ("ход", "шаги") else з) for к, з in поля.items()}
    набор = ", ".join(f"{к} = ?" for к in поля)
    with _база.соединение() as связь:
        связь.execute(f"UPDATE поручение SET {набор}, изменено = datetime('now', 'localtime') WHERE id = ?",
                      (*поля.values(), номер))


def создать(название: str, шаги: list[dict], значения: dict | None = None, режим: str = "по порядку") -> dict:
    название = " ".join((название or "").split())[:120]
    if not название:
        raise ОшибкаПоручения("Дайте поручению название.")
    шаги = _проверить_шаги(шаги)
    значения = {к: " ".join(str(з).split())[:200] for к, з in (значения or {}).items()}
    нет = [п for п in параметры_шагов(название, шаги) if not значения.get(п)]
    if нет:
        raise ОшибкаПоручения("Заполните: " + ", ".join(нет) + ".")
    название = _подставить(название, значения)
    шаги = [{**ш, "описание": _подставить(ш["описание"], значения), "ожидание": _подставить(ш["ожидание"], значения)} for ш in шаги]
    with _база.соединение() as связь:
        номер = связь.execute("INSERT INTO поручение (название, шаги, режим) VALUES (?, ?, ?)",
                              (название, json.dumps(шаги, ensure_ascii=False),
                               режим if режим in ("по порядку", "руководитель") else "по порядку")).lastrowid
        связь.execute("DELETE FROM поручение WHERE id NOT IN (SELECT id FROM поручение ORDER BY id DESC LIMIT 200)")
    audit.записать("поручение создано", название, f"шагов: {len(шаги)}, режим: {режим}")
    return получить(номер)


def удалить(номер: int) -> bool:
    if номер in _идут:
        raise ОшибкаПоручения("Поручение сейчас выполняется. Сначала остановите его.")
    м = получить(номер)
    with _база.соединение() as связь:
        удалено = связь.execute("DELETE FROM поручение WHERE id = ?", (номер,)).rowcount > 0
    if удалено and м:
        audit.записать("поручение удалено", м["название"])
    return удалено


# ---- Шаблоны -------------------------------------------------------------------------------

def шаблоны() -> list[dict]:
    with _база.соединение() as связь:
        строки = связь.execute("SELECT * FROM шаблон_поручения ORDER BY название").fetchall()
    итог = []
    for с in строки:
        ш = json.loads(с["шаги"])
        итог.append({"id": с["id"], "название": с["название"], "шаги": ш, "режим": с["режим"],
                     "параметры": параметры_шагов(с["название"], ш)})
    return итог


def сохранить_шаблон(название: str, шаги: list[dict], режим: str = "по порядку") -> dict:
    название = " ".join((название or "").split())[:120]
    if not название:
        raise ОшибкаПоручения("Дайте шаблону название.")
    шаги = _проверить_шаги(шаги)
    with _база.соединение() as связь:
        связь.execute("INSERT INTO шаблон_поручения (название, шаги, режим) VALUES (?, ?, ?) "
                      "ON CONFLICT(название) DO UPDATE SET шаги = excluded.шаги, режим = excluded.режим",
                      (название, json.dumps(шаги, ensure_ascii=False), режим))
    return next(ш for ш in шаблоны() if ш["название"] == название)


def удалить_шаблон(номер: int) -> bool:
    with _база.соединение() as связь:
        строка = связь.execute("SELECT название FROM шаблон_поручения WHERE id = ?", (номер,)).fetchone()
        удалён = связь.execute("DELETE FROM шаблон_поручения WHERE id = ?", (номер,)).rowcount > 0
    if удалён and строка:
        # готовый шаблон, который вы убрали, при обновлении не возвращается
        названия = list(_база.прочитать("шаблоны_удалены", []))
        if строка[0] not in названия:
            _база.записать("шаблоны_удалены", названия + [строка[0]])
    return удалён


