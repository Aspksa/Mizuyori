def спланировать(цель: str, н: dict) -> dict:
    цель = " ".join((цель or "").split())[:500]
    if not цель:
        raise ОшибкаПоручения("Опишите цель.")
    if not ai.подключён(н):
        raise ОшибкаПоручения("Руководителю нужен ИИ: добавьте ключ в настройках ИИ.")
    исполнители = [{"ключ": к, "умеет": next((а["что"] for а in agents.АГЕНТЫ if а["ключ"] == к), "")}
                   for к in agents.ИМЕНА if к not in ("смысл", "чат", "память", "сводка", "мнения")]
    # работники «Работы» и «Закупок» лежат в других списках
    try:
        from . import work_agents
        исполнители += [{"ключ": а["ключ"], "умеет": а["что"]} for а in work_agents.РАБОЧИЕ_АГЕНТЫ if а["ключ"] not in {и["ключ"] for и in исполнители}]
    except Exception:
        pass
    система = ("Ты Стратег, руководитель команды агентов. Раздели цель хозяина на 2–%d шагов и назначь исполнителей ТОЛЬКО из списка. "
               'Ответь ТОЛЬКО JSON: {"название": "...", "шаги": [{"агент": "ключ", "описание": "что сделать", "ожидание": "что считать готовым", '
               '"инструмент": "поиск или замечания или пусто"}]}. Инструмент «поиск» — интернет, «замечания» — данные приложения.') % МАКС_ШАГОВ
    with ai.измерять():
        ответ = ai._задание(система, {"цель": цель, "исполнители": исполнители, "инструменты": tools.список()},
                            agents.с_правилами(dict(н), РУКОВОДИТЕЛЬ), 1200)
    план = _json_из_текста(ответ)
    if not isinstance(план, dict) or not isinstance(план.get("шаги"), list):
        raise ОшибкаПоручения("Руководитель не смог составить план. Попробуйте переформулировать цель.")
    допустимые = {и["ключ"] for и in исполнители}
    шаги = [{"агент": ш.get("агент"), "описание": ш.get("описание"), "ожидание": ш.get("ожидание"),
             "инструмент": ш.get("инструмент") if ш.get("инструмент") in tools.ИНСТРУМЕНТЫ else ""}
            for ш in план["шаги"][:МАКС_ШАГОВ] if isinstance(ш, dict) and ш.get("агент") in допустимые]
    for ш in шаги:                       # Стратег мог назначить инструмент тому, кому он не положен — снимаем
        if ш["инструмент"] and not tools.разрешён(ш["инструмент"], ш["агент"])[0]:
            ш["инструмент"] = ""
    if not шаги:
        raise ОшибкаПоручения("В плане нет подходящих исполнителей. Попробуйте переформулировать цель.")
    return создать(str(план.get("название") or цель)[:120], шаги, режим="руководитель")
