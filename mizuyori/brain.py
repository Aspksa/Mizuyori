журнал = logging.getLogger("mizuyori.мозг")

_замок = threading.Lock()
_СОСТОЯНИЕ = "обслуживание_мозга"
_ИНТЕРВАЛ = timedelta(hours=12)
_ПУНКТУАЦИЯ = re.compile(r"[^\w\s]+", re.UNICODE)


def _время(значение) -> datetime | None:
    if not значение:
        return None
    try:
        return datetime.fromisoformat(str(значение).replace(" ", "T"))
    except (TypeError, ValueError):
        return None


def _дата(значение) -> str | None:
    if not значение:
        return None
    try:
        return date.fromisoformat(str(значение)[:10]).isoformat()
    except (TypeError, ValueError):
        return None


def _ключ_текста(текст: str) -> str:
    return " ".join(_ПУНКТУАЦИЯ.sub(" ", ключ_имени(текст)).split())


def пора(база, сейчас: datetime | None = None) -> bool:
    сейчас = сейчас or datetime.now()
    состояние = база.прочитать(_СОСТОЯНИЕ, {}) or {}
    последнее = _время(состояние.get("последнее")) if isinstance(состояние, dict) else None
    return not последнее or сейчас - последнее >= _ИНТЕРВАЛ


def _активные_факты(база) -> list[dict]:
    сегодня = date.today().isoformat()
    return [ф for ф in база.память()
            if ф.get("состояние", "активен") == "активен"
            and (not ф.get("действует_с") or ф["действует_с"] <= сегодня)
            and (not ф.get("действует_до") or ф["действует_до"] >= сегодня)]


def _устарить_истёкшие(база) -> int:
    сегодня = date.today().isoformat()
    счёт = 0
    for факт in база.память():
        if (факт.get("состояние", "активен") == "активен" and факт.get("действует_до")
                and факт["действует_до"] < сегодня):
            база.изменить_факт(факт["id"], {"состояние": "устарел"})
            счёт += 1
    return счёт


def _объединить_точные_повторы(база) -> int:
    группы: dict[str, list[dict]] = {}
    for факт in _активные_факты(база):
        ключ = _ключ_текста(факт["факт"])
        if ключ:
            группы.setdefault(ключ, []).append(факт)
    счёт = 0
    for группа in группы.values():
        if len(группа) < 2:
            continue
        основной = max(группа, key=lambda ф: (ф.get("уверенность", 0.75), ф["важность"], ф["id"]))
        for повтор in группа:
            if повтор["id"] != основной["id"] and база.объединить_факты(основной["id"], повтор["id"]):
                счёт += 1
    return счёт


def _объединить_смысловые_повторы(база, настройки: dict) -> int:
    if not memory.можно_эмбеддинги(настройки):
        return 0
    import numpy as np

    факты = _активные_факты(база)
    if len(факты) < 2:
        return 0
    тексты = {f"п{ф['id']}": ф["факт"] for ф in факты}
    ключи, матрица, _ = memory.обеспечить_вектора(база, настройки, тексты)
    по_ключу = {f"п{ф['id']}": ф for ф in факты}
    похожесть = матрица @ матрица.T
    np.fill_diagonal(похожесть, -1)
    использованы, счёт = set(), 0
    for i, ключ in enumerate(ключи):
        if ключ in использованы:
            continue
        j = int(np.argmax(похожесть[i]))
        if float(похожесть[i, j]) < 0.965:
            continue
        другой = ключи[j]
        а, б = по_ключу[ключ], по_ключу[другой]
        if а["категория"] != б["категория"]:
            continue
        основной, повтор = sorted(
            (а, б), key=lambda ф: (ф.get("уверенность", 0.75), ф["важность"], ф["id"]), reverse=True)
        if база.объединить_факты(основной["id"], повтор["id"]):
            использованы.update((ключ, другой))
            счёт += 1
    return счёт


def _восстановить_связи_фактов(база) -> int:
    сущности = база.сущности()
    счёт = 0
    for факт in _активные_факты(база):
        связанные = set(факт.get("сущности") or [])
        текст = ключ_имени(" ".join([факт["факт"], *map(str, (факт.get("смысл") or {}).values())]))
        слова = текст.split()
        for сущность in сущности:
            if сущность["id"] in связанные:
                continue
            if memory._упомянута(сущность, текст, слова):
                база.привязать_факт(факт["id"], сущность["id"])
                связанные.add(сущность["id"])
                счёт += 1
    return счёт


def _объединить_дубли_сущностей(база) -> int:
    сущности = база.сущности()
    счёт, исчезли = 0, set()
    for i, первая in enumerate(сущности):
        if первая["id"] in исчезли:
            continue
        имена_первой = {ключ_имени(первая["имя"]), *(ключ_имени(и) for и in первая["другие_имена"])} - {""}
        for вторая in сущности[i + 1:]:
            if вторая["id"] in исчезли or первая["тип"] != вторая["тип"]:
                continue
            имена_второй = {ключ_имени(вторая["имя"]), *(ключ_имени(и) for и in вторая["другие_имена"])} - {""}
            if имена_первой & имена_второй and база.объединить_сущности(первая["id"], вторая["id"]):
                исчезли.add(вторая["id"])
                имена_первой |= имена_второй
                счёт += 1
    return счёт


def _почистить_граф(база) -> int:
    """Удаляет петли, пустые подписи и нормализованные повторы связей."""
    удалено = 0
    with база.соединение() as связь:
        строки = связь.execute("SELECT id, от_id, отношение, к_id FROM отношения ORDER BY id").fetchall()
        видели = set()
        for строка in строки:
            ключ = (строка["от_id"], ключ_имени(строка["отношение"]), строка["к_id"])
            if строка["от_id"] == строка["к_id"] or not ключ[1] or ключ in видели:
                связь.execute("DELETE FROM отношения WHERE id = ?", (строка["id"],))
                удалено += 1
            else:
                видели.add(ключ)
        # Выполненная задача больше не блокирует следующую; завершённой задаче зависимость тоже не нужна.
        удалено += связь.execute(
            "DELETE FROM задача_зависимости WHERE "
            "задача_id IN (SELECT id FROM задачи WHERE готово = 1 OR удалено IS NOT NULL) OR "
            "зависит_от_id IN (SELECT id FROM задачи WHERE готово = 1 OR удалено IS NOT NULL)"
        ).rowcount
    return удалено


def _ослабить_неиспользуемое(база, сейчас: datetime) -> int:
    """Раз в фоне осторожно снижает важность забытых низкоуверенных фактов."""
    счёт = 0
    граница = сейчас - timedelta(days=180)
    for факт in _активные_факты(база):
        if факт["важность"] >= 5 or ключ_имени(факт["факт"]).startswith("правило хозяина:"):
            continue
        последнее = _время(факт.get("последнее_использование")) or _время(факт.get("изменено")) or _время(факт["создано"])
        if последнее and последнее < граница and факт.get("использовано", 0) < 2:
            новая_важность = max(1, факт["важность"] - 1)
            новая_уверенность = max(0.35, float(факт.get("уверенность", 0.75)) - 0.05)
            база.изменить_факт(факт["id"], {"важность": новая_важность, "уверенность": новая_уверенность})
            счёт += 1
    return счёт


def _цели_без_шага(база) -> int:
    задачи = база.задачи()
    счёт = 0
    база.закрыть_наблюдения("цель_без_шага")
    for цель in база.цели():
        if цель.get("статус") not in ("", "активна"):
            continue
        открытые = [з for з in задачи if з.get("цель_id") == цель["id"] and not з["готово"]]
        if not открытые:
            база.сохранить_наблюдение(
                "цель_без_шага", str(цель["id"]), f"У цели «{цель['имя']}» нет следующего открытого действия.",
                {"цель_id": цель["id"]}, 0.95)
            счёт += 1
    return счёт


def _наблюдать_разговор(база) -> dict:
    """Консервативные локальные признаки обещаний, исправлений и устойчивых привычек."""
    сообщения = база.сообщения(300)
    обещаний = исправлений = привычек = 0
    кандидаты: dict[str, list[int]] = {}
    шаблон_обещания = re.compile(r"\b(?:я\s+)?(?:обещаю|сделаю|подготовлю|проверю|напомню|вернусь)\b", re.I)
    шаблон_исправления = re.compile(r"\b(?:нет[, ]|неправильно|на самом деле|точнее|я имел[аи]? в виду)\b", re.I)
    шаблон_привычки = re.compile(r"\b(?:я\s+)?(?:всегда|обычно|часто|предпочитаю|люблю|не люблю)\b(.{3,160})", re.I)
    for сообщение in сообщения:
        текст = " ".join(сообщение["текст"].split())
        if шаблон_обещания.search(текст):
            база.сохранить_наблюдение("обещание", str(сообщение["id"]), текст[:600],
                                     {"сообщение_id": сообщение["id"], "роль": сообщение["роль"]}, 0.6)
            обещаний += 1
        if сообщение["роль"] == "пользователь" and шаблон_исправления.search(текст):
            база.сохранить_наблюдение("исправление", str(сообщение["id"]), текст[:600],
                                     {"сообщение_id": сообщение["id"]}, 0.7)
            исправлений += 1
        if сообщение["роль"] == "пользователь" and (найдено := шаблон_привычки.search(текст)):
            ключ = _ключ_текста(найдено.group(1))[:120]
            if ключ:
                кандидаты.setdefault(ключ, []).append(сообщение["id"])
    for ключ, номера in кандидаты.items():
        if len(номера) >= 2:
            база.сохранить_наблюдение("привычка", ключ, ключ,
                                     {"сообщения": номера[-10:], "подтверждений": len(номера)},
                                     min(0.95, 0.6 + len(номера) * 0.1))
            привычек += 1
    return {"обещания": обещаний, "исправления": исправлений, "привычки": привычек}


def _обеспечить_все_вектора(база, настройки: dict) -> int:
    if not memory.можно_эмбеддинги(настройки):
        return 0
    тексты = {}
    for задача in база.задачи():
        тексты[f"з{задача['id']}"] = задача["текст"]
    for заметка in база.заметки():
        тексты[f"н{заметка['id']}"] = заметка["текст"][:4000]
    for факт in _активные_факты(база):
        тексты[f"п{факт['id']}"] = факт["факт"]
    for сущность in база.сущности():
        тексты[f"е{сущность['id']}"] = (
            f"{сущность['имя']} ({сущность['тип']}): {сущность['описание']} {сущность['причина']}".strip())
    if not тексты:
        return 0
    _, _, новых = memory.обеспечить_вектора(база, настройки, тексты)
    база.убрать_лишние_вектора(set(тексты))
    return новых


def _данные_для_ии(база) -> dict:
    факты = _активные_факты(база)
    сущности = база.сущности()
    задачи = [з for з in база.задачи() if not з["готово"]]
    return {
        "сегодня": date.today().isoformat(),
        "факты": [{"id": ф["id"], "текст": ф["факт"], "категория": ф["категория"],
                   "смысл": ф.get("смысл") or {}, "сущности": ф.get("сущности") or [],
                   "создано": ф["создано"]} for ф in факты[:100]],
        "сущности": [{"id": с["id"], "имя": с["имя"], "тип": с["тип"],
                      "псевдонимы": с["другие_имена"], "статус": с["статус"]} for с in сущности[:100]],
        "связи": база.отношения()[:200],
        "задачи": [{"id": з["id"], "текст": з["текст"], "цель_id": з.get("цель_id"),
                    "срок": з.get("срок")} for з in задачи[:100]],
        "последний_разговор": [{"id": с["id"], "роль": с["роль"], "текст": с["текст"][:700]}
                               for с in база.сообщения(80)],
    }


def _применить_анализ(база, анализ: dict) -> dict:
    факты = {ф["id"]: ф for ф in база.память()}
    сущности = {с["id"]: с for с in база.сущности()}
    задачи = {з["id"]: з for з in база.задачи()}
    счёт = {"факты": 0, "сущности": 0, "связи": 0, "зависимости": 0, "наблюдения": 0}

    for запись in анализ.get("duplicates", []):
        if запись["confidence"] >= 0.94 and запись["primary_id"] in факты and запись["duplicate_id"] in факты:
            счёт["факты"] += int(база.объединить_факты(запись["primary_id"], запись["duplicate_id"]))
    for запись in анализ.get("contradictions", []):
        старый, новый = запись["older_id"], запись["newer_id"]
        if запись["confidence"] >= 0.9 and старый in факты and новый in факты and старый != новый:
            база.изменить_факт(старый, {"состояние": "устарел", "заменён_на": новый})
            база.сохранить_наблюдение("противоречие", f"{старый}:{новый}",
                                     запись.get("explanation", "Новый факт заменяет прежний."), запись,
                                     запись["confidence"])
            счёт["факты"] += 1
    for запись in анализ.get("validity", []):
        if запись["confidence"] < 0.85 or запись["fact_id"] not in факты:
            continue
        поля = {}
        if начало := _дата(запись.get("valid_from")):
            поля["действует_с"] = начало
        if конец := _дата(запись.get("valid_to")):
            поля["действует_до"] = конец
        if поля:
            поля["уверенность"] = max(факты[запись["fact_id"]].get("уверенность", 0.75), запись["confidence"])
            база.изменить_факт(запись["fact_id"], поля)
            счёт["факты"] += 1
    for запись in анализ.get("aliases", []):
        сущность = сущности.get(запись["entity_id"])
        псевдоним = запись.get("alias", "")
        if запись["confidence"] >= 0.9 and сущность and псевдоним and not база.найти_сущность(псевдоним):
            база.изменить_сущность(сущность["id"], {"другие_имена": [*сущность["другие_имена"], псевдоним]})
            счёт["сущности"] += 1
    for запись in анализ.get("entity_merges", []):
        а, б = сущности.get(запись["primary_id"]), сущности.get(запись["duplicate_id"])
        if запись["confidence"] >= 0.97 and а and б and а["тип"] == б["тип"]:
            счёт["сущности"] += int(база.объединить_сущности(а["id"], б["id"]))
    for запись in анализ.get("missing_links", []):
        if запись["confidence"] >= 0.85 and запись["fact_id"] in факты and запись["entity_id"] in сущности:
            база.привязать_факт(запись["fact_id"], запись["entity_id"])
            счёт["связи"] += 1
    for запись in анализ.get("dependencies", []):
        if (запись["confidence"] >= 0.8 and запись["task_id"] in задачи
                and запись["depends_on_id"] in задачи and not задачи[запись["task_id"]]["готово"]
                and not задачи[запись["depends_on_id"]]["готово"]):
            счёт["зависимости"] += int(база.сохранить_зависимость(
                запись["task_id"], запись["depends_on_id"], запись.get("reason", ""), запись["confidence"]))
    виды = {
        "goal_gaps": ("цель_без_шага", "goal_id"), "promises": ("обещание", "message_id"),
        "habits": ("привычка", None), "corrections": ("исправление", "message_id"),
        "code_suggestions": ("предложение_кода", None),
    }
    for ключ, (вид, поле_id) in виды.items():
        for номер, запись in enumerate(анализ.get(ключ, [])):
            if запись["confidence"] < 0.7:
                continue
            идентификатор = str(запись.get(поле_id)) if поле_id else _ключ_текста(
                запись.get("text") or запись.get("suggestion") or str(номер))[:160]
            текст = запись.get("text") or запись.get("suggestion") or запись.get("reason") or запись.get("explanation")
            if идентификатор and текст:
                база.сохранить_наблюдение(вид, идентификатор, текст, запись, запись["confidence"])
                счёт["наблюдения"] += 1
    for запись in анализ.get("corrections", []):
        if запись["confidence"] >= 0.92 and запись.get("fact_id") in факты:
            база.изменить_факт(запись["fact_id"], {
                "уверенность": min(float(факты[запись["fact_id"]].get("уверенность", 0.75)), 0.35),
                "состояние": "устарел",
            })
    return счёт


def обслужить_в_фоне(база, настройки: dict, сейчас: datetime | None = None, принудительно: bool = False) -> dict:
    """Один идемпотентный проход. Без ИИ выполняет безопасную механическую часть."""
    сейчас = сейчас or datetime.now()
    if not принудительно and not пора(база, сейчас):
        return база.прочитать(_СОСТОЯНИЕ, {}) or {}
    if not _замок.acquire(blocking=False):
        return база.прочитать(_СОСТОЯНИЕ, {}) or {}
    try:
        итог = {
            "истекло": 0, "повторов_фактов": 0, "повторов_сущностей": 0, "связей_восстановлено": 0,
            "граф_очищен": 0, "ослаблено": 0, "целей_без_шага": 0, "новых_векторов": 0,
            "обещания": 0, "исправления": 0, "привычки": 0, "ии": {},
        }
        with agents.работа("смысл", "обслужил память и граф", "хозяин неактивен больше часа") as запись:
            итог["истекло"] = _устарить_истёкшие(база)
            итог["повторов_фактов"] = _объединить_точные_повторы(база)
            итог["повторов_сущностей"] = _объединить_дубли_сущностей(база)
            итог["связей_восстановлено"] = _восстановить_связи_фактов(база)
            итог["граф_очищен"] = _почистить_граф(база)
            итог["ослаблено"] = _ослабить_неиспользуемое(база, сейчас)
            итог["целей_без_шага"] = _цели_без_шага(база)
            итог.update(_наблюдать_разговор(база))
            if memory.можно_эмбеддинги(настройки):
                итог["новых_векторов"] = _обеспечить_все_вектора(база, настройки)
                итог["повторов_фактов"] += _объединить_смысловые_повторы(база, настройки)
            if ai.подключён(настройки):
                # Модель заново определяет, какие обещания всё ещё не выполнены.
                база.закрыть_наблюдения("обещание")
                анализ = ai.осмыслить_мозг(_данные_для_ии(база), agents.с_правилами(настройки, "смысл"))
                итог["ии"] = _применить_анализ(база, анализ)
            итог["последнее"] = сейчас.isoformat(timespec="seconds")
            итог["следующее_не_раньше"] = (сейчас + _ИНТЕРВАЛ).isoformat(timespec="seconds")
            база.записать(_СОСТОЯНИЕ, итог)
            польза = sum(значение for ключ, значение in итог.items() if isinstance(значение, int))
            запись["результат"] = f"изменений и наблюдений: {польза}"
            запись["польза"] = min(польза, 10)
        журнал.info("Фоновое обслуживание мозга завершено: %s", итог)
        return итог
    finally:
        _замок.release()
