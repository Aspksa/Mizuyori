"use strict";

// =============================================================================
// Разметка ответов ИИ: **жирный**, *курсив*, `код`, ```блоки```, заголовки, списки, цитаты, ссылки.
// Сначала всё экранируется, потом превращается в теги — чужой HTML из ответа не выполнится.
// Незакрытые ** и ` (пока ответ ещё печатается) просто не показываются.
// =============================================================================

const _экран = (т) => т.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

function _строчная(т) {
  const коды = [];
  т = т.replace(/`([^`\n]+)`/g, (_, к) => { коды.push(к); return `\u0000${коды.length - 1}\u0000`; });
  т = _экран(т);
  т = т.replace(/\[([^\]\n]+)\]\((https?:\/\/[^\s)]+)\)/g, (_, текст, адрес) => `<a href="${адрес}" target="_blank" rel="noopener noreferrer">${текст}</a>`);
  т = т.replace(/\*\*\*([^*\n]+?)\*\*\*/g, "<strong><em>$1</em></strong>");
  т = т.replace(/\*\*([^\n]+?)\*\*/g, "<strong>$1</strong>");
  т = т.replace(/__([^_\n]+?)__/g, "<strong>$1</strong>");
  т = т.replace(/(^|[^*\w])\*(?!\s)([^*\n]+?)\*(?!\w)/g, "$1<em>$2</em>");
  т = т.replace(/~~([^~\n]+?)~~/g, "<s>$1</s>");
  т = т.replace(/\*\*|`/g, "");                       // хвосты незакрытой разметки
  т = т.replace(/(^|\s)\*(?=\S)/g, "$1").replace(/(\S)\*(?=\s|$)/g, "$1");
  т = т.replace(/\u0000(\d+)\u0000/g, (_, н) => `<code>${_экран(коды[+н])}</code>`);
  return т;
}

function разметка(текст) {
  const блоки = [];
  // блоки кода ``` (незакрытый — до конца текста)
  текст = String(текст || "").replace(/```([\w+-]*)\n?([\s\S]*?)(```|$)/g, (_, язык, код) => {
    блоки.push({ язык, код: код.replace(/\n$/, "") });
    return `\n\u0001${блоки.length - 1}\u0001\n`;
  });
  const строки = текст.split("\n");
  const итог = [];
  let список = null, абзац = [];
  const закрытьАбзац = () => { if (абзац.length) { итог.push(`<p>${абзац.map(_строчная).join("<br>")}</p>`); абзац = []; } };
  const закрытьСписок = () => { if (список) { итог.push(`<${список.тег}>${список.пункты.join("")}</${список.тег}>`); список = null; } };

  for (const сырая of строки) {
    const строка = сырая.replace(/\s+$/, "");
    let м;
    if ((м = строка.match(/^\u0001(\d+)\u0001$/))) {
      закрытьАбзац(); закрытьСписок();
      const б = блоки[+м[1]];
      итог.push(`<div class="код-блок"><div class="код-шапка"><span>${_экран(б.язык || "код")}</span>` +
        `<button type="button" class="копировать-код">Копировать</button></div><pre><code>${_экран(б.код)}</code></pre></div>`);
    } else if (!строка.trim()) {
      закрытьАбзац(); закрытьСписок();
    } else if ((м = строка.match(/^(#{1,4})\s+(.+)$/))) {
      закрытьАбзац(); закрытьСписок();
      const уровень = Math.min(м[1].length + 2, 6);
      итог.push(`<h${уровень}>${_строчная(м[2].replace(/#+$/, ""))}</h${уровень}>`);
    } else if (/^\s*(-{3,}|\*{3,}|_{3,})\s*$/.test(строка)) {
      закрытьАбзац(); закрытьСписок();
      итог.push("<hr>");
    } else if ((м = строка.match(/^\s*(?:[-*•+])\s+(.*)$/)) || (м = строка.match(/^\s*(\d+)[.)]\s+(.*)$/))) {
      закрытьАбзац();
      const нумерованный = /^\s*\d/.test(строка);
      const тег = нумерованный ? "ol" : "ul";
      if (!список || список.тег !== тег) { закрытьСписок(); список = { тег, пункты: [] }; }
      const текстПункта = нумерованный ? м[2] : м[1];
      const флажок = текстПункта.match(/^\[( |x|X)\]\s+(.*)$/);
      список.пункты.push(флажок
        ? `<li class="пункт-флажок"><span class="флажок-md">${флажок[1].trim() ? "☑" : "☐"}</span>${_строчная(флажок[2])}</li>`
        : `<li>${_строчная(текстПункта)}</li>`);
    } else if ((м = строка.match(/^>\s?(.*)$/))) {
      закрытьАбзац(); закрытьСписок();
      итог.push(`<blockquote>${_строчная(м[1])}</blockquote>`);
    } else if (/^\s*\|.*\|\s*$/.test(строка)) {
      // таблица — строки «| a | b |»; строку-разделитель «|---|» пропускаем
      закрытьАбзац(); закрытьСписок();
      if (/^\s*\|[\s:|-]+\|\s*$/.test(строка)) continue;
      const ячейки = строка.trim().slice(1, -1).split("|").map((я) => `<td>${_строчная(я.trim())}</td>`).join("");
      const последний = итог[итог.length - 1];
      if (последний && последний.startsWith("<table")) итог[итог.length - 1] = последний.replace("</table>", `<tr>${ячейки}</tr></table>`);
      else итог.push(`<table><tr>${ячейки}</tr></table>`);
    } else {
      закрытьСписок();
      абзац.push(строка);
    }
  }
  закрытьАбзац(); закрытьСписок();
  return итог.join("");
}

// Тот же текст без разметки — для копирования, задач и заметок
function простойТекст(текст) {
  return String(текст || "")
    .replace(/```[\w+-]*\n?/g, "")
    .replace(/`([^`]*)`/g, "$1")
    .replace(/\*\*\*|\*\*|__|~~/g, "")
    .replace(/(^|[^*\w])\*(?!\s)([^*\n]+?)\*(?!\w)/g, "$1$2")
    .replace(/^#{1,6}\s+/gm, "")
    .replace(/^>\s?/gm, "")
    .replace(/\[([^\]]+)\]\((https?:\/\/[^)]+)\)/g, "$1 ($2)")
    .trim();
}
