"use strict";

// =============================================================================
// Слои главной: один экран вместо двух визуализаций.
//   ◎ Агенты — круг агентов (agents_graph.js)
//   ✺ Память — граф памяти ИИ вместе с агентами (бывшие «Мозги», brain.js)
//   ♡ Душа   — характер, ценности, настроение (soul.js)
//   ☰ Список — агенты с уровнями и ростом (brain_list.js)
// Слои лежат друг над другом и переключаются здесь; Обмен, Доска, Журнал и Поручения всегда под рукой в шапке.
// =============================================================================
{
  const переключатель = $("слои-главной");
  const мозги = $("экран-мозги");
  const вкладкиМозгов = $("мозги-вкладки");
  if (переключатель && мозги && вкладкиМозгов) {
    let слой = "круг";
    let своё = false;            // событие экрана отправили мы сами
    let панельСвёрнута = false;
    let очередь = 0;

    const послать = (имя) => { своё = true; document.dispatchEvent(new CustomEvent("mizuyori:экран", { detail: имя })); своё = false; };
    const вкладка = (слой_) => {
      if (слой_ === "список") return [...вкладкиМозгов.querySelectorAll("button")].find((к) => !к.dataset.вкладка);
      return вкладкиМозгов.querySelector(`button[data-вкладка="${слой_ === "душа" ? "душа" : "граф"}"]`);
    };

    function показать(новый) {
      if (!["круг", "мозг", "память", "душа", "список"].includes(новый)) новый = "круг";
      слой = новый;
      очередь++;
      for (const к of переключатель.querySelectorAll("button[data-слой]")) к.setAttribute("aria-selected", String(к.dataset.слой === слой));
      document.body.dataset.слой = слой;
      const мозг2 = $("экран-мозг2");
      if (мозг2) { мозг2.hidden = слой !== "мозг"; document.dispatchEvent(new CustomEvent("mizuyori:мозг2", { detail: слой === "мозг" })); }
      if (слой === "мозг") {
        мозги.hidden = true;
        послать("главная");
        return;
      }
      if (слой === "круг") {
        мозги.hidden = true;
        послать("главная");
        return;
      }
      мозги.hidden = false;
      // в узком окне панель настроек графа закрывает половину картинки — по умолчанию сворачиваем
      if (!панельСвёрнута) {
        панельСвёрнута = true;
        const панель = $("мозги-панель");
        if (панель && !панель.classList.contains("скрыта")) $("мозги-панель-кнопка")?.click();
      }
      // вкладка «Список» не меняет вид графа, поэтому для «Памяти» возвращаем вкладку «Граф»
      if (слой === "список") {
        // сначала уходим с «Души», если она была открыта (её слой сам не прячется), потом открываем список
        вкладка("память")?.click();
        const номер = ++очередь;
        setTimeout(() => { if (номер === очередь && слой === "список") { вкладка("список")?.click(); послать("мозги"); } }, мозги.dataset.вкладка === "душа" ? 900 : 60);
        return;
      }
      вкладка(слой)?.click();
      послать("мозги");
    }

    переключатель.addEventListener("click", (с) => {
      const к = с.target.closest("button[data-слой]");
      if (к) показать(к.dataset.слой);
    });
    document.addEventListener("mizuyori:слой", (с) => показать(с.detail));
    // Ушли на другой экран и вернулись — слой нужно разбудить заново
    document.addEventListener("mizuyori:экран", (с) => {
      if (своё) return;
      if (с.detail === "главная" && слой !== "круг" && слой !== "мозг") setTimeout(() => послать("мозги"), 0);
    });
    document.body.dataset.слой = "круг";
  }
}
