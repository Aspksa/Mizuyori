// «Мозги → Список»: все агенты списком — уровень, умения, чему научились; клик раскрывает подробности
(() => {
  const экран = $("экран-мозги"), вкладки = $("мозги-вкладки");
  if (!экран || !вкладки) return;
  const ЦВЕТА = ["#3ecf9a", "#6aa9ff", "#f5a34b", "#c58bff", "#ff7aa8", "#5fd4e6", "#e6d35f"];
  const кнопка = создать("button", { type: "button", role: "tab", "aria-selected": "false" }, "☰ Список");
  вкладки.append(кнопка);
  const поиск = создать("input", { type: "search", placeholder: "Найти агента или знание", класс: "список-поиск", autocomplete: "off" });
  const тело = создать("div", { класс: "список-тело" });
  const слой = создать("div", { класс: "мозги-список", id: "мозги-список", hidden: true },
    создать("div", { класс: "список-шапка" }, создать("h2", {}, "Агенты и их знания"), поиск), тело);
  экран.append(слой);
  let данные = null, открыт = null, подробно = {};

  const показан = () => !слой.hidden;
  function показать(да) {
    слой.hidden = !да;
    кнопка.setAttribute("aria-selected", String(да));
    if (да) {
      for (const к of вкладки.querySelectorAll("button[data-вкладка]")) к.setAttribute("aria-selected", "false");
      загрузить();
    }
  }
  кнопка.addEventListener("click", () => показать(true));
  вкладки.addEventListener("click", (с) => { if (с.target.closest("button[data-вкладка]")) показать(false); });
  document.addEventListener("mizuyori:экран", () => { if (показан()) загрузить(); });
  поиск.addEventListener("input", рисовать);

  async function загрузить() {
    try { данные = await запрос("/api/agents"); } catch (e) { тело.textContent = `Не удалось загрузить: ${e.message}`; return; }
    рисовать();
  }

  function шкала(а) {
    const доля = а.до ? Math.min(1, Math.max(0, (а.опыт - а.от) / Math.max(1, а.до - а.от))) : 1;
    return создать("span", { класс: "список-шкала", title: `опыт ${а.опыт}${а.до ? ` из ${а.до}` : ""}` },
      создать("i", { style: `width:${Math.round(доля * 100)}%` }));
  }

  function строка(а, цвет) {
    const ряд = создать("div", { класс: "список-агент" + (открыт === а.ключ ? " открыт" : ""), style: `--гц:${цвет}` },
      создать("button", { type: "button", класс: "список-ряд", "aria-expanded": String(открыт === а.ключ) },
        создать("span", { класс: "список-имя" }, а.имя, а.умеет ? создать("small", {}, ` ${а.умеет}`) : ""),
        создать("span", { класс: "список-что" }, а.что || ""),
        создать("span", { класс: "список-ур" }, `ур. ${а.уровень}`),
        шкала(а),
        создать("span", { класс: "список-счёт", title: "заметок / выучено за неделю" },
          `🧠 ${а.заметок || 0}` + (а.выучил_за_неделю ? ` · +${а.выучил_за_неделю}` : ""))));
    ряд.firstChild.addEventListener("click", async () => {
      открыт = открыт === а.ключ ? null : а.ключ;
      if (открыт && !подробно[открыт]) {
        try { подробно[открыт] = await запрос(`/api/agents/${encodeURIComponent(открыт)}`); } catch { подробно[открыт] = { заметки: [] }; }
      }
      рисовать();
    });
    if (открыт === а.ключ) {
      const п = подробно[а.ключ] || { заметки: [] };
      const виды = { правило: "Правила", приём: "Приёмы", ошибка: "Частые ошибки" };
      const блок = создать("div", { класс: "список-подробно" });
      блок.append(создать("p", { класс: "список-последнее" },
        а.последнее_действие ? `Последнее: ${а.последнее_действие} — ${а.последний_результат || ""} (${дата(а.последний)})` : "Пока ничего не делал.",
        ` Сегодня: ${а.сегодня}, всего: ${а.всего}.`));
      for (const [вид, название] of Object.entries(виды)) {
        const список = (п.заметки || []).filter((з) => з.вид === вид);
        if (!список.length) continue;
        блок.append(создать("h4", {}, `${название} (${список.length})`),
          создать("ul", {}, ...список.slice(0, 12).map((з) => создать("li", {}, з.текст + (з.источник && з.источник !== "вы" ? ` — ${з.источник}` : "") + (з.счёт > 1 ? ` ×${з.счёт}` : "")))));
      }
      if (!(п.заметки || []).length) блок.append(создать("p", { класс: "список-пусто" }, "Знаний пока нет — агент научится по ходу работы."));
      ряд.append(блок);
    }
    return ряд;
  }

  function рисовать() {
    if (!данные) return;
    const слово = поиск.value.trim().toLowerCase();
    const группы = new Map();
    for (const а of данные.агенты) {
      if (слово && !`${а.имя} ${а.что}`.toLowerCase().includes(слово) &&
          !(подробно[а.ключ]?.заметки || []).some((з) => з.текст.toLowerCase().includes(слово))) continue;
      const г = а.группа || "Другие";
      if (!группы.has(г)) группы.set(г, []);
      группы.get(г).push(а);
    }
    const названия = [...new Set(данные.агенты.map((а) => а.группа || "Другие"))];
    тело.replaceChildren(...[...группы].map(([г, список]) => создать("section", { класс: "список-группа" },
      создать("h3", { style: `color:${ЦВЕТА[названия.indexOf(г) % ЦВЕТА.length]}` }, `${г} · ${список.length}`),
      ...список.map((а) => строка(а, ЦВЕТА[названия.indexOf(г) % ЦВЕТА.length])))));
    if (!группы.size) тело.replaceChildren(создать("p", { класс: "список-пусто" }, "Ничего не найдено."));
  }
})();
