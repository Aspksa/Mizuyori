  // ---- графика --------------------------------------------------------------------------

  let счётчик = 0;
  function область(значения, цвет, ш, в, { подписи = false, точки = false } = {}) {
    const ид = `гр${++счётчик}`, поле = подписи ? { л: 22, п: 10, в: 14, н: 22 } : { л: 2, п: 2, в: 4, н: 3 };
    const макс = Math.max(1, ...значения), n = значения.length;
    const x = (i) => поле.л + (i / (n - 1)) * (ш - поле.л - поле.п);
    const y = (з) => в - поле.н - (з / макс) * (в - поле.н - поле.в);
    const линия = значения.map((з, i) => `${i ? "L" : "M"}${x(i).toFixed(1)} ${y(з).toFixed(1)}`).join(" ");
    const г = svg("svg", { viewBox: `0 0 ${ш} ${в}`, class: подписи ? "график большой" : "график", preserveAspectRatio: "none", role: "img",
      "aria-label": `Действий по дням: ${значения.join(", ")}` });
    const градиент = svg("linearGradient", { id: ид, x1: 0, y1: 0, x2: 0, y2: 1 },
      svg("stop", { offset: "0%", "stop-color": цвет, "stop-opacity": ".55" }), svg("stop", { offset: "100%", "stop-color": цвет, "stop-opacity": "0" }));
    г.append(svg("defs", {}, градиент));
    if (подписи) {
      for (const доля of [0, .5, 1]) {
        const yy = y(макс * доля);
        г.append(svg("line", { x1: поле.л, x2: ш - поле.п, y1: yy, y2: yy, class: "сетка" }),
          Object.assign(svg("text", { x: 2, y: yy + 3, class: "ось" }), { textContent: String(Math.round(макс * доля)) }));
      }
      const шаг = n <= 7 ? 1 : Math.ceil(n / 6);
      значения.forEach((_, i) => {
        if ((n - 1 - i) % шаг !== 0 && i !== n - 1) return;
        const д = дняНазад(n - 1 - i);
        const подпись = i === n - 1 ? "сегодня" : n <= 7 ? ДНИ[д.getDay()] : `${String(д.getDate()).padStart(2, "0")}.${String(д.getMonth() + 1).padStart(2, "0")}`;
        г.append(Object.assign(svg("text", { x: x(i), y: в - 6, class: "ось", "text-anchor": i === n - 1 ? "end" : "middle" }), { textContent: подпись }));
      });
    }
    г.append(svg("path", { d: `${линия} L${x(n - 1)} ${в - поле.н} L${x(0)} ${в - поле.н} Z`, fill: `url(#${ид})` }),
      svg("path", { d: линия, fill: "none", stroke: цвет, "stroke-width": подписи ? 2.2 : 1.8, "stroke-linejoin": "round", "stroke-linecap": "round" }));
    if (точки) значения.forEach((з, i) => г.append(svg("circle", { cx: x(i), cy: y(з), r: 3, fill: цвет }),
      ...(з ? [Object.assign(svg("text", { x: x(i), y: y(з) - 7, class: "число", "text-anchor": "middle" }), { textContent: String(з) })] : [])));
    return г;
  }

