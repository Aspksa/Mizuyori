  function нарисоватьСводку(названия) {
    const а_ = данные.агенты;
    const неделяВсего = Array.from({ length: 7 }, (_, i) => а_.reduce((с, а) => с + ((а.неделя || [])[i] || 0), 0));
    const знаний = а_.reduce((с, а) => с + (а.заметок || 0), 0);
    const выучено = а_.reduce((с, а) => с + (а.выучил_за_неделю || 0), 0);
    const карта = (подпись, число, дополнение = "") => создать("div", { класс: "список-карта" }, создать("small", {}, подпись), создать("b", {}, String(число)), дополнение);
    const суммы = названия.map((г) => [г, а_.filter((а) => (а.группа || "Другие") === г).reduce((с, а) => с + (а.неделя || []).reduce((x, y) => x + y, 0), 0)]);
    const максГр = Math.max(1, ...суммы.map(([, з]) => з));
    сводка.replaceChildren(
      карта("Агентов", а_.length), карта("Знаний", знаний, создать("em", {}, выучено ? `+${выучено} за неделю` : "")),
      карта("Действий сегодня", данные.сегодня),
      создать("div", { класс: "список-карта широкая" }, создать("small", {}, "Работа всех агентов за 7 дней"), область(неделяВсего, "#3ecf9a", 300, 60)),
      создать("div", { класс: "список-карта широкая" }, создать("small", {}, "Действий по группам за неделю"),
        ...суммы.map(([г, з], i) => создать("div", { класс: "полоса", style: `--гц:${ЦВЕТА[i % ЦВЕТА.length]}` },
          создать("span", {}, г), создать("i", {}, создать("u", { style: `width:${Math.round(з / максГр * 100)}%` })), создать("em", {}, String(з))))));
  }

