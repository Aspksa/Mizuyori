  async function загрузить(файлы) {
    if (!файлы.length) return;
    сообщения = [];
    for (const ф of файлы) {
      const ч = [`name=${encodeURIComponent(ф.name)}`];
      if (выбрано.тип === "контрагент") ч.push(`kontragent=${выбрано.id}`);
      if (выбрано.тип === "договор") ч.push(`dogovor=${выбрано.id}`);
      try {
        const о = await fetch(`/api/archive/upload?${ч.join("&")}`, { method: "POST", body: await ф.arrayBuffer() });
        const д = await о.json().catch(() => ({}));
        if (!о.ok) throw new Error(д.ошибка || `Ошибка ${о.status}`);
        сообщения.push({ ок: true, текст: `✓ ${ф.name} → ${д.где} / ${д.имя}${д.создан_договор ? " (создан договор)" : ""}` +
          (!д.контрагент_найден ? ` — контрагент${д.подсказка_контрагента ? ` «${д.подсказка_контрагента}»` : ""} не найден, файл во «Входящих»` : "") });
      } catch (e) {
        сообщения.push({ ок: false, текст: `✗ ${ф.name}: ${e.message}` });
      }
    }
    await обновить();
  }

