  // Файлы из выбора, папки или перетаскивания → [{ файл, папка }]; папка (имя ближайшей папки) подсказывает контрагента
  async function собрать(список, элементы) {
    const итог = [];
    const читать = (запись, путь) => new Promise((готово) => {
      if (запись.isFile) { запись.file((ф) => { итог.push({ файл: ф, папка: путь[путь.length - 1] || "" }); готово(); }, () => готово()); return; }
      if (!запись.isDirectory) { готово(); return; }
      const чтец = запись.createReader(), все = [];
      const порция = () => чтец.readEntries(async (п) => {
        if (!п.length) { await Promise.all(все.map((э) => читать(э, [...путь, запись.name]))); готово(); return; }
        все.push(...п); порция();
      }, () => готово());
      порция();
    });
    if (элементы && [...элементы].some((э) => э.webkitGetAsEntry?.()?.isDirectory)) {
      const записи = [...элементы].map((э) => э.webkitGetAsEntry?.()).filter(Boolean);
      for (const з of записи) await читать(з, []);
      return итог;
    }
    for (const ф of список) {
      const части = (ф.webkitRelativePath || "").split("/");
      итог.push({ файл: ф, папка: части.length > 1 ? части[части.length - 2] : "" });
    }
    return итог;
  }

  async function загрузить(список, элементы) {
    const файлы = (await собрать(список, элементы)).filter((х) => !/^(~\$|\.)/.test(х.файл.name) && х.файл.name !== "Thumbs.db" && х.файл.name !== "desktop.ini");
    if (!файлы.length) return;
    сообщения = [];
    const счёт = { принято: 0, дубли: 0, контрагентов: 0, договоров: 0, входящие: 0, ошибки: 0 };
    const проблемы = [];
    const строка_прогресса = создать("div", { класс: "архив-подсказка", role: "status" });
    $("архив-содержимое")?.prepend(строка_прогресса);
    const учесть = (д, имя) => {
      счёт.принято++;
      if (д.создан_контрагент) счёт.контрагентов++;
      if (д.создан_договор) счёт.договоров++;
      if (!д.контрагент_найден && !д.создан_контрагент) { счёт.входящие++; проблемы.push({ ок: true, текст: `📥 ${имя} → во «Входящие»: не нашёл контрагента` }); }
    };
    let n = 0;
    for (const { файл: ф, папка } of файлы) {
      строка_прогресса.textContent = `Загружаю и разбираю: ${++n} из ${файлы.length} — ${ф.name}`;
      const ч = [`name=${encodeURIComponent(ф.name)}`];
      if (папка) ч.push(`folder=${encodeURIComponent(папка)}`);
      if (выбрано.тип === "контрагент") ч.push(`kontragent=${выбрано.id}`);
      if (выбрано.тип === "договор") ч.push(`dogovor=${выбрано.id}`);
      try {
        const о = await fetch(`/api/archive/upload?${ч.join("&")}`, { method: "POST", body: await ф.arrayBuffer() });
        const д = await о.json().catch(() => ({}));
        if (!о.ok) throw new Error(д.ошибка || `Ошибка ${о.status}`);
        if (д.архив) {
          for (const х of д.результаты) {
            if (х.ок) учесть(х, х.имя);
            else if (/уже (есть|был)/.test(х.ошибка)) счёт.дубли++;
            else { счёт.ошибки++; проблемы.push({ ок: false, текст: `✗ ${х.имя}: ${х.ошибка}` }); }
          }
        } else учесть(д, ф.name);
      } catch (e) {
        if (/уже (есть|был)/.test(e.message)) счёт.дубли++;
        else { счёт.ошибки++; проблемы.push({ ок: false, текст: `✗ ${ф.name}: ${e.message}` }); }
      }
    }
    const части = [`Принято: ${счёт.принято}`, счёт.контрагентов && `новых контрагентов: ${счёт.контрагентов}`, счёт.договоров && `новых договоров: ${счёт.договоров}`,
      счёт.дубли && `уже были (пропущено): ${счёт.дубли}`, счёт.входящие && `во «Входящих»: ${счёт.входящие}`, счёт.ошибки && `ошибок: ${счёт.ошибки}`].filter(Boolean);
    сообщения = [{ ок: !счёт.ошибки, текст: `✓ ${части.join(" · ")}` + (счёт.контрагентов ? ". Проверьте карточки новых контрагентов — реквизиты можно дополнить." : "") }, ...проблемы.slice(0, 20)];
    await обновить();
  }

