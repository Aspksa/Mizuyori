  function окно(заголовок, тело, кнопки) {
    const фон = создать("div", { класс: "затемнение" });
    const закрыть = () => фон.remove();
    const форма = создать("form", { класс: "окно архив-окно", role: "dialog", "aria-modal": "true" },
      создать("div", { класс: "окно-шапка" }, создать("h2", { текст: заголовок }),
        создать("button", { type: "button", класс: "кнопка-значок", "aria-label": "Закрыть", текст: "✕", onclick: закрыть })),
      создать("div", { класс: "окно-тело архив-форма" }, ...тело),
      создать("div", { класс: "окно-низ" }, ...кнопки(закрыть)));
    фон.append(форма);
    фон.addEventListener("mousedown", (с) => { if (с.target === фон) закрыть(); });
    document.body.append(фон);
    return { форма, закрыть };
  }

