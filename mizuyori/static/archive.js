  async function содержимое() {
    const место = $("архив-содержимое");
    if (!место) return;
    try {
      if (поиск) {
        const д = await api(`/api/archive/files?q=${encodeURIComponent(поиск)}`);
        место.replaceChildren(путь(["Поиск: " + поиск]), ...(сообщения.length ? [плашка()] : []),
          д.файлы.length ? списокФайлов(д.файлы, true) : создать("p", { класс: "пусто", текст: "Ничего не нашлось." }));
        return;
      }
      if (выбрано.тип === "контрагент") return await страницаКонтрагента(место);
      if (выбрано.тип === "договор") return await страницаДоговора(место);
      const д = await api(выбрано.тип === "входящие" ? "/api/archive/files?inbox=true" : "/api/archive/files");
      место.replaceChildren(
        путь([выбрано.тип === "входящие" ? "Входящие (не разобрано)" : "Все файлы"]),
        ...(сообщения.length ? [плашка()] : []),
        ...(выбрано.тип === "входящие" ? [создать("div", { класс: "архив-подсказка" },
          "Сюда попадают файлы, у которых не нашёлся контрагент. Заведите карточку контрагента — файлы разложатся по папкам сами. ",
          создать("button", { type: "button", класс: "ссылка", текст: "Разобрать сейчас", onclick: async () => {
            const р = await api("/api/archive/sort-inbox", "POST"); сообщения = [{ ок: true, текст: `Разложено файлов: ${р.разложено}` }]; await обновить();
          } }))] : [зонаЗагрузки("Перетащите файлы, папку или ZIP — Архивариус прочитает документы, заведёт контрагентов и договоры и разложит по папкам")]),
        д.файлы.length ? списокФайлов(д.файлы, true) : создать("p", { класс: "пусто", текст: "Здесь пока пусто." }));
    } catch (e) {
      место.replaceChildren(создать("p", { класс: "пусто", текст: `Не удалось загрузить: ${e.message}` }));
    }
  }

  function путь(части) {
    return создать("div", { класс: "архив-путь" }, ...части.flatMap((ч, i) => [
      ...(i ? [создать("span", { класс: "архив-путь-стрелка", текст: "›" })] : []),
      typeof ч === "string" ? создать("span", { текст: ч }) : ч]));
  }

  function плашка() {
    return создать("div", { класс: "архив-итоги" },
      ...сообщения.map((с) => создать("div", { класс: `архив-итог ${с.ок ? "ок" : "ошибка"}` }, с.текст)),
      создать("button", { type: "button", класс: "ссылка", текст: "Скрыть", onclick: () => { сообщения = []; содержимое(); } }));
  }

  function зонаЗагрузки(текст) {
    return создать("div", { класс: "архив-зона" }, создать("span", { текст: "⬆" }), создать("span", { текст }));
  }

