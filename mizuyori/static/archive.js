    правая.addEventListener("dragleave", (с) => { if (!правая.contains(с.relatedTarget)) правая.classList.remove("над"); });
    правая.addEventListener("drop", (с) => { с.preventDefault(); правая.classList.remove("над"); загрузить([...с.dataTransfer.files], с.dataTransfer.items); });
    корень.replaceChildren(шапка, создать("div", { класс: "архив-тело" }, левая, правая));
