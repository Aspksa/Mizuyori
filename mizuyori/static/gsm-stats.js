"use strict";

// =============================================================================
// ГСМ → «Статистика и контроль»: километраж и топливо, признаки подозрительных заправок,
// кто и где заправляется, время заправок. Данные приходят готовыми с /api/work/gsm/stats.
// =============================================================================
window.рисоватьСтатистикуГСМ = function (д) {
  const ч = (з, знаков = 2) => (з == null ? "—" : Number(з).toLocaleString("ru-RU", { maximumFractionDigits: знаков }));
  const со_знаком = (з, знаков = 1) => (з == null ? "—" : `${з > 0 ? "+" : з < 0 ? "−" : ""}${ч(Math.abs(з), знаков)}`);
  const руб = (з) => (з == null ? "—" : `${ч(з, 0)} ₽`);
  const рус = (iso) => iso.split("-").reverse().join(".");

  const блок = (заголовок, пояснение, ...внутри) => создать("section", { класс: "стат-блок" },
    создать("h3", { текст: заголовок }), пояснение ? создать("p", { класс: "стат-пояснение", текст: пояснение }) : "", ...внутри);
  const карточка = (метка, значение, пояснение, тон = "") => создать("div", { класс: `гсм-итог${тон ? ` ${тон}` : ""}` },
    создать("small", { текст: метка }), создать("strong", { текст: значение }), создать("span", { текст: пояснение ?? "" }));
  const таблица = (шапка, строки, класс = "") => создать("div", { класс: "работа-таблица-обёртка стат-таблица" },
    создать("table", { класс: `работа-таблица ${класс}` },
      создать("thead", {}, создать("tr", {}, ...шапка.map((т, i) => создать("th", { класс: i ? "число" : "", текст: т })))),
      создать("tbody", {}, ...строки)));
  const ячейка = (текст, класс = "число", title) => создать("td", { класс, текст: String(текст ?? ""), ...(title ? { title } : {}) });
  const столбики = (значения, подписи, { высота = 90, подсветка = () => false, подсказка = (з) => ч(з) } = {}) => {
    const макс = Math.max(1, ...значения);
    return создать("div", { класс: "стат-столбики", style: `height:${высота + 22}px` },
      ...значения.map((з, i) => создать("div", { класс: `стат-столбик${подсветка(i) ? " ночь" : ""}`, title: `${подписи[i]}: ${подсказка(з)}` },
        создать("i", { style: `height:${Math.max(з ? 3 : 0, з / макс * высота)}px` }),
        создать("small", { текст: подписи[i] }))));
  };

  const и = д.итого;
  const уровень = (к) => ({ высокий: "плохо", средний: "внимание", низкий: "" })[к];

  // ---- сводка -------------------------------------------------------------------------------
  const сводка = создать("div", { класс: "гсм-кпи" },
    карточка("Заправок", ч(и.операций, 0), `за ${и.дней} из ${и.дней_в_периоде} дн.`),
    карточка("Литров", `${ч(и.литров)} л`, `в среднем ${ч(и.заправка_литров, 1)} л за заправку`),
    карточка("Потрачено", руб(и.сумма), `средняя цена ${ч(и.цена)} ₽/л`),
    карточка("Карт и АЗС", `${и.карт} / ${и.азс}`, "карт в работе / разных АЗС"));
  const замечания = д.замечания.length
    ? создать("div", { класс: "гсм-предупреждения" }, ...д.замечания.map((т) => создать("span", { класс: "гсм-пред", текст: `⚠ ${т}` })))
    : "";

  // ---- контроль -----------------------------------------------------------------------------
  const суммаПодозр = д.контроль.reduce((с, к) => ({ л: с.л + к.подозрительно_л, р: с.р + к.подозрительно_руб, пл: с.пл + к.перерасход_л, пр: с.пр + к.перерасход_руб }), { л: 0, р: 0, пл: 0, пр: 0 });
  const контроль = блок("Контроль: на что обратить внимание",
    "Это статистические признаки, а не доказательство. Перерасход бывает из-за холодного пуска, простоя с работающим двигателем, неточной нормы или ошибки в показаниях одометра. Сначала проверьте путевые листы и чеки АЗС, потом делайте выводы о людях. Подозрительные операции и перерасход могут частично пересекаться.",
    д.контроль.length ? создать("div", { класс: "гсм-кпи" },
      карточка("Машин с признаками", `${д.контроль.length} из ${д.машины.length}`, `высокий уровень: ${д.контроль.filter((к) => к.уровень === "высокий").length}`, д.контроль.some((к) => к.уровень === "высокий") ? "плохо" : ""),
      карточка("Перерасход сверх допуска", `${ч(суммаПодозр.пл, 1)} л`, `≈ ${руб(суммаПодозр.пр)} (допуск ${д.допуск} %)`, суммаПодозр.пл ? "плохо" : ""),
      карточка("Подозрительные операции", `${ч(суммаПодозр.л, 1)} л`, `≈ ${руб(суммаПодозр.р)}: бак, отпуск, не то топливо, маршрут`, суммаПодозр.л ? "плохо" : ""),
      карточка("Литров не отнесено к машине", `${ч(д.без_машины.reduce((с, к) => с + к.литров, 0), 1)} л`, `карт: ${д.без_машины.length}`))
      : создать("p", { класс: "стат-ок", текст: "✓ Явных признаков не найдено. Если перерасход всё же ощущается — проверьте, заполнены ли путевые листы и указан ли объём бака у машин." }),
    ...д.контроль.map((к) => создать("article", { класс: `стат-контроль ${уровень(к.уровень)}` },
      создать("header", {},
        создать("div", { класс: "гсм-машина-имя" }, создать("strong", { текст: к.название }), создать("small", { текст: к.водитель })),
        создать("span", { класс: `гсм-статус ${уровень(к.уровень) || "нет"}`, текст: `${к.уровень} · ${к.баллы} ${к.баллы === 1 ? "балл" : к.баллы < 5 ? "балла" : "баллов"}` }),
        создать("span", { класс: "стат-оценка", title: "Перерасход сверх допуска + литры подозрительных операций (могут пересекаться)",
          текст: к.всего_л ? `до ${ч(к.всего_л, 1)} л ≈ ${руб(к.всего_руб)}` : "" })),
      создать("ul", { класс: "стат-признаки" }, ...к.признаки.map((п) => создать("li", {},
        создать("strong", { текст: п.название }),
        п.литров ? создать("span", { класс: "стат-литры", текст: ` · ${ч(п.литров, 1)} л${п.рубли ? ` ≈ ${руб(п.рубли)}` : ""}` }) : "",
        создать("div", { класс: "стат-пояснения" }, ...п.пояснения.slice(0, 2).map((т) => создать("p", { текст: т })),
          п.пояснения.length > 2 ? создать("details", {}, создать("summary", { текст: `ещё ${п.пояснения.length - 2}` }),
            ...п.пояснения.slice(2).map((т) => создать("p", { текст: т }))) : "")))))),
    д.без_машины.length ? создать("details", { класс: "стат-без-машины" },
      создать("summary", { текст: `Заправки, которые не удалось отнести к машине (${д.без_машины.length} карт)` }),
      таблица(["Карта", "Кто", "Заправок", "Литров", "Сумма"], д.без_машины.map((к) => создать("tr", {},
        ячейка(к.карта, ""), ячейка(к.сотрудник, ""), ячейка(к.операций, "число"), ячейка(ч(к.литров), "число"), ячейка(руб(к.сумма), "число"))))) : "");

  // ---- километраж и топливо по машинам --------------------------------------------------------
  const спарк = (динамика) => {
    if (динамика.length < 2) return "";
    const макс = Math.max(1, ...динамика.map((х) => Math.abs(х.откл)));
    return создать("span", { класс: "стат-спарк", title: динамика.map((х) => `${х.месяц}: ${со_знаком(х.откл)} %`).join("\n") },
      ...динамика.map((х) => создать("i", { класс: х.откл > д.допуск ? "плохо" : х.откл < 0 ? "хорошо" : "", style: `height:${Math.max(3, Math.abs(х.откл) / макс * 16)}px` })));
  };
  const машины = блок("Километраж и топливо по машинам",
    "Расход на 100 км по факту против нормы, стоимость километра и «реальная норма» по методу наименьших квадратов (литры = расход × км + свободная часть по месяцам). Свободная часть — литры, которые не зависят от пробега.",
    таблица(["Машина", "Пробег, км", "Заправок", "Литров", "Сумма", "₽ за км", "Расход факт, л/100", "Норма, л/100", "Откл., %", "Динамика", "Реальная норма по месяцам", "Км на заправку"],
      д.машины.map((м) => создать("tr", {},
        создать("td", { класс: "стат-имя" }, создать("strong", { текст: м.название }), создать("small", { текст: м.водитель })),
        ячейка(ч(м.пробег, 1)), ячейка(м.заправок), ячейка(ч(м.литров)), ячейка(руб(м.сумма)), ячейка(ч(м.рубли_км)),
        ячейка(ч(м.расход_факт_100)), ячейка(ч(м.расход_норма_100)),
        ячейка(м.откл == null ? "—" : `${со_знаком(м.откл)} %`, `число ${м.откл > д.допуск ? "перерасход" : м.откл < 0 ? "экономия" : ""}`),
        создать("td", { класс: "число" }, спарк(м.динамика)),
        ячейка(м.регрессия ? `${ч(м.регрессия.расход_100)} (свободно ${ч(м.регрессия.свободно_л, 0)} л, R² ${ч(м.регрессия.r2, 2)})` : "нужно 3+ месяца",
          "число", m_регрессия_подсказка(м)),
        ячейка(ч(м.км_на_заправку, 0))))),
    д.парк ? создать("p", { класс: "стат-пояснение", текст: `По всему парку: факт ≈ ${ч(д.парк.расход_100 / 100, 2)} × норма + ${ч(д.парк.свободно_л, 0)} л, R² = ${ч(д.парк.r2, 2)} (точек: ${д.парк.точек}). Если наклон заметно больше 1 — парк в целом расходует больше нормы.` }) : "");

  function m_регрессия_подсказка(м) {
    return м.регрессия ? "Литры по месяцам = расход × км + свободная часть. Большая свободная часть при малом R² — топливо не следует за пробегом." : "";
  }

  // ---- кто и как заправляется -----------------------------------------------------------------
  const людиБлок = блок("Кто и как заправляется", "Частота, средний интервал, любимая АЗС и часы заправок.",
    таблица(["Сотрудник / карта", "Заправок", "В неделю", "Раз в … дн.", "Средняя, л", "Литров", "Сумма", "АЗС", "Любимая АЗС", "Ночью", "Ср. час", "Цена к средней"],
      д.сотрудники.map((с) => создать("tr", {},
        ячейка(с.имя, "стат-имя"), ячейка(с.заправок), ячейка(ч(с.раз_в_неделю, 1)), ячейка(ч(с.интервал_дней, 1)), ячейка(ч(с.средняя, 1)),
        ячейка(ч(с.литров)), ячейка(руб(с.сумма)), ячейка(с.азс), ячейка(`${с.любимая_азс} (${с.любимая_раз})`, "стат-азс"),
        ячейка(с.ночью || ""), ячейка(с.ср_час == null ? "" : `${ч(с.ср_час, 0)}:00`),
        ячейка(с.переплата ? `${со_знаком(с.переплата, 0)} ₽` : "0", `число ${с.переплата > 50 ? "перерасход" : с.переплата < -50 ? "экономия" : ""}`, "Во сколько раз дороже или дешевле средней цены по тому же топливу")))));

  // ---- АЗС и время ------------------------------------------------------------------------------
  const азсБлок = блок("Где заправляются", `Всего АЗС: ${д.азс_всего}. Цена сравнивается со средней по тому же виду топлива.`,
    д.города.length ? создать("div", { класс: "стат-чипы" }, ...д.города.map(([г, н]) => создать("span", { класс: "стат-чип", текст: `${г[0].toUpperCase()}${г.slice(1)} · ${н}` }))) : "",
    таблица(["АЗС", "Заправок", "Литров", "Сумма", "Цена, ₽/л", "К средней, %", "Карт"],
      д.азс.slice(0, 12).map((а) => создать("tr", {},
        ячейка(а.название, "стат-азс"), ячейка(а.заправок), ячейка(ч(а.литров)), ячейка(руб(а.сумма)), ячейка(ч(а.цена)),
        ячейка(а.отличие_цены == null ? "" : `${со_знаком(а.отличие_цены)} %`, `число ${а.отличие_цены > 1 ? "перерасход" : а.отличие_цены < -1 ? "экономия" : ""}`), ячейка(а.карт)))));
  const время = блок("Когда заправляются", "Ночные часы (23:00–5:00) подсвечены.",
    создать("div", { класс: "стат-две" },
      создать("div", {}, создать("h4", { текст: "По часам суток" }),
        столбики(д.часы, д.часы.map((_, i) => String(i)), { подсветка: (i) => i >= 23 || i < 5, подсказка: (з) => `${з} заправок` })),
      создать("div", {}, создать("h4", { текст: "По дням недели" }),
        столбики(д.дни_недели, д.дни_названия, { подсветка: (i) => i >= 5, подсказка: (з) => `${з} заправок` }))));
  const месяцыБлок = д.по_месяцам.length > 1 ? блок("По месяцам", "Литры, расходы и средняя цена литра.",
    таблица(["Месяц", "Заправок", "Литров", "Сумма", "Цена, ₽/л"], д.по_месяцам.map((м) => создать("tr", {},
      ячейка(м.подпись, ""), ячейка(м.заправок), ячейка(ч(м.литров)), ячейка(руб(м.сумма)), ячейка(ч(м.цена)))))) : "";
  const топливоБлок = блок("Виды топлива", "",
    таблица(["Топливо", "Литров", "Доля, %", "Сумма", "Цена, ₽/л"], д.топливо.map((т) => создать("tr", {},
      ячейка(т.вид, ""), ячейка(ч(т.литров)), ячейка(ч(т.доля, 1)), ячейка(руб(т.сумма)), ячейка(ч(т.цена))))));

  // ---- рекорды -------------------------------------------------------------------------------------
  const р = д.рекорды;
  const рекорд = (метка, з) => з ? карточка(метка, `${ч(з.литров)} л · ${руб(з.сумма)}`, `${рус(з.дата)} ${з.время} · ${з.кто} · ${з.азс}`) : "";
  const рекорды = Object.keys(р).length ? блок("Рекорды периода", "",
    создать("div", { класс: "гсм-кпи стат-рекорды" },
      рекорд("Самая большая заправка", р.самая_большая), рекорд("Самая дорогая заправка", р.самая_дорогая),
      рекорд("Самая ранняя", р.самая_ранняя), рекорд("Самая поздняя", р.самая_поздняя), рекорд("Самый дорогой литр", р.дороже_всего_литр))) : "";

  const как = создать("details", { класс: "стат-как" },
    создать("summary", { текст: "Как считается контроль" }),
    создать("ul", {},
      ...[
        `Перерасход — разница факта и нормы по путевым, допуск ${д.допуск} %; ≥10 % и ≥20 % дают больше баллов, повторение из месяца в месяц усиливает вывод.`,
        "Заправка больше бака — нужен «Объём бака» в карточке автомобиля.",
        "Отпуск и больничный — заправка по карте сотрудника в день, когда в табеле у него ОТ, Б или ДО.",
        "Не то топливо — у дизельной машины залит бензин или наоборот.",
        "Невозможный маршрут — по одной карте две заправки в разных городах с разницей менее 90 минут.",
        "Две заправки подряд — по одной карте менее чем через 3 часа. Топливо при нулевом пробеге — в месяце есть заправки, а пробег по путевым 0.",
        "Ночью (23:00–5:00), в выходные без отметки в табеле, много заправок на малый пробег, рост перерасхода, «выбивается из парка» (робастный z-счёт > 2,5) — слабые признаки по 1 баллу.",
        "Уровень: 1–2 балла — низкий, 3–5 — средний, 6 и больше — высокий.",
      ].map((т) => создать("li", { текст: т }))));

  return [сводка, замечания, контроль, машины, людиБлок, азсБлок, время, месяцыБлок, топливоБлок, рекорды, как];
};
