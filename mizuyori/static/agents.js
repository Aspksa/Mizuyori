"use strict";

// =============================================================================
// Агенты на главной: фоновые помощники Mizuyori.
// Кружок с символом, вокруг кольцо: крутится, пока агент работает, а дуга — сколько
// раз он сработал сегодня. Точка снизу: зелёная — всё хорошо, красная — последняя ошибка.
// =============================================================================
{
  const сетка = $("агенты-сетка");
  const итог = $("агенты-итог");
  const ЗНАЧКИ = {
    чат: "M4 5h16v10H9l-5 4z",
    память: "M12 3a6 6 0 0 0-6 6c0 2.2 1.2 3.5 2 4.5V17h8v-3.5c.8-1 2-2.3 2-4.5a6 6 0 0 0-6-6zM9 20h6",
    сводка: "M5 4h14v16H5zM8 8h8M8 12h8M8 16h5",
    смысл: "M6 6a2 2 0 1 0 0 .1M18 6a2 2 0 1 0 0 .1M12 18a2 2 0 1 0 0 .1M7.5 7.5l3.5 9M16.5 7.5l-3.5 9M8 6h8",
    цели: "M12 12m-8 0a8 8 0 1 0 16 0a8 8 0 1 0-16 0M12 12m-4 0a4 4 0 1 0 8 0a4 4 0 1 0-8 0M12 12h.01",
    мнения: "M12 20s-7-4.4-7-10a4 4 0 0 1 7-2.6A4 4 0 0 1 19 10c0 5.6-7 10-7 10z",
  };
  const NS = "http://www.w3.org/2000/svg";
  const svg = (тег, атрибуты) => {
    const э = document.createElementNS(NS, тег);
    for (const [к, з] of Object.entries(атрибуты)) э.setAttribute(к, з);
    return э;
  };
  const ячейки = new Map();
  let таймер = 0;

  function ячейка(а) {
    const кольцо = svg("svg", { viewBox: "0 0 48 48", class: "агент-кольцо", "aria-hidden": "true" });
    кольцо.append(
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-фон" }),
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-дуга", pathLength: 100 }),
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-бег", pathLength: 100 }),
    );
    const значок = svg("svg", { viewBox: "0 0 24 24", class: "агент-значок", "aria-hidden": "true",
      fill: "none", stroke: "currentColor", "stroke-width": "1.8", "stroke-linecap": "round", "stroke-linejoin": "round" });
    значок.append(svg("path", { d: ЗНАЧКИ[а.значок] || ЗНАЧКИ.чат }));
    const элемент = создать("div", { класс: "агент", tabindex: "0" },
      создать("div", { класс: "агент-круг" }, кольцо, значок, создать("span", { класс: "агент-точка" })),
      создать("span", { класс: "агент-имя", текст: а.имя }),
      создать("span", { класс: "агент-счёт" }));
    сетка.append(элемент);
    ячейки.set(а.ключ, элемент);
    return элемент;
  }

  function показать(данные) {
    const максимум = Math.max(1, ...данные.агенты.map((а) => а.сегодня));
    for (const а of данные.агенты) {
      const э = ячейки.get(а.ключ) || ячейка(а);
      э.classList.toggle("работает", а.работает);
      э.classList.toggle("ошибка", Boolean(а.ошибка));
      э.classList.toggle("спит", !а.работает && !а.сегодня);
      э.querySelector(".агент-дуга").style.strokeDasharray = `${Math.round((а.сегодня / максимум) * 100)} 100`;
      э.querySelector(".агент-счёт").textContent = а.работает ? "работает…" : а.сегодня ? `${а.сегодня} сегодня` : "ждёт";
      const строки = [`${а.имя} — ${а.что}`];
      if (а.работает) строки.push(`Работает уже ${а.идёт_секунд} с`);
      if (а.последний) строки.push(`Последний раз: ${дата(а.последний)}${а.секунд != null ? ` · ${а.секунд} с` : ""}`);
      строки.push(`Сегодня: ${а.сегодня} · всего: ${а.всего}`);
      if (а.ошибка) строки.push(`Ошибка: ${а.ошибка}`);
      э.title = строки.join("\n");
      э.setAttribute("aria-label", строки.join(". "));
    }
    итог.textContent = `${данные.работают} ${данные.работают === 1 ? "работает" : "работают"} · ${данные.сегодня} за сегодня`;
    итог.classList.toggle("активно", данные.работают > 0);
  }

  async function обновить() {
    clearTimeout(таймер);
    const видно = !document.hidden && !сетка.closest("main").hidden;
    if (видно) {
      try {
        const данные = await запрос("/api/agents");
        показать(данные);
        // пока кто-то работает — чаще
        таймер = setTimeout(обновить, данные.работают || Date.now() < частоДо ? 500 : 3000);
        return;
      } catch {
        итог.textContent = "нет связи";
      }
    }
    таймер = setTimeout(обновить, 3000);
  }

  document.addEventListener("visibilitychange", () => { if (!document.hidden) обновить(); });
  document.addEventListener("mizuyori:экран", (с) => { if (с.detail === "главная") обновить(); });
  // отправили сообщение — сразу смотрим, кто взялся за работу
  let частоДо = 0;
  document.addEventListener("mizuyori:чат-отправлено", () => { частоДо = Date.now() + 15000; setTimeout(обновить, 200); });
  обновить();
}
