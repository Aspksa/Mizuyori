  // Вкладка «Навыки»: короткие инструкции, которые подключаются только к подходящему запросу
  function графикКачества(к) {
    const точки = к.точки || [];
    const ширина = Math.max(240, точки.length * 14), высота = 70;
    const NS = "http://www.w3.org/2000/svg";
    const svg = document.createElementNS(NS, "svg");
    svg.setAttribute("viewBox", `0 0 ${ширина} ${высота}`);
    svg.setAttribute("class", "качество-график");
    svg.setAttribute("role", "img");
    svg.setAttribute("aria-label", "Оценка последних шагов");
    const линия = document.createElementNS(NS, "line");
    for (const [а, знач] of Object.entries({ x1: 0, x2: ширина, y1: высота * (1 - к.порог), y2: высота * (1 - к.порог) })) линия.setAttribute(а, знач);
    линия.setAttribute("class", "качество-порог");
    svg.append(линия);
    точки.forEach((т, и) => {
      const р = document.createElementNS(NS, "rect");
      const в = Math.max(3, т.балл * (высота - 6));
      р.setAttribute("x", и * 14 + 2); р.setAttribute("width", 10); р.setAttribute("y", высота - в); р.setAttribute("height", в); р.setAttribute("rx", 2);
      р.setAttribute("class", т.балл >= 1 ? "кач-хорошо" : т.балл >= 0.6 ? "кач-средне" : "кач-плохо");
      const н = document.createElementNS(NS, "title");
      н.textContent = `${т.описание || "шаг"} — ${т.итог}${т.попыток > 1 ? `, попыток: ${т.попыток}` : ""}${т.замечание ? `. ${т.замечание}` : ""}`;
      р.append(н); svg.append(р);
    });
    return svg;
  }

