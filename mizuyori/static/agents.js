"use strict";

// =============================================================================
// Агенты под чатом — конвейер.
//
// Агенты стоят в ряд по ходу работы: Собеседник → Память → Смысл → Летописец → Стратег → Душа.
// Когда один берётся за дело после другого, по дорожке между ними летит искра.
// Кружок: кольцо крутится, пока агент работает; дуга — сколько раз за сегодня; точка — всё ли хорошо;
// звёздочки — уровень опыта. Клик — окно агента: история решений, своя память, записки.
// =============================================================================
{
  const ряд = $("агенты-сетка");
  const итог = $("агенты-итог");
  const холст = $("конвейер-холст");
  const к = холст.getContext("2d");
  const безАнимаций = () => matchMedia("(prefers-reduced-motion: reduce)").matches;

  const ЗНАЧКИ = {
    чат: "M4 5h16v10H9l-5 4z",
    память: "M12 3a6 6 0 0 0-6 6c0 2.2 1.2 3.5 2 4.5V17h8v-3.5c.8-1 2-2.3 2-4.5a6 6 0 0 0-6-6zM9 20h6",
    сводка: "M5 4h14v16H5zM8 8h8M8 12h8M8 16h5",
    смысл: "M6 6a2 2 0 1 0 0 .1M18 6a2 2 0 1 0 0 .1M12 18a2 2 0 1 0 0 .1M7.5 7.5l3.5 9M16.5 7.5l-3.5 9M8 6h8",
    цели: "M12 12m-8 0a8 8 0 1 0 16 0a8 8 0 1 0-16 0M12 12m-4 0a4 4 0 1 0 8 0a4 4 0 1 0-8 0M12 12h.01",
    мнения: "M12 20s-7-4.4-7-10a4 4 0 0 1 7-2.6A4 4 0 0 1 19 10c0 5.6-7 10-7 10z",
  };
  const NS = "http://www.w3.org/2000/svg";
  const svg = (тег, атрибуты) => {
    const э = document.createElementNS(NS, тег);
    for (const [ключ, з] of Object.entries(атрибуты)) э.setAttribute(ключ, з);
    return э;
  };
  const ячейки = new Map();
  const прошлое = new Map();     // ключ → { работает, всего }
  let последнийАктивный = null, когдаАктивен = 0;
  let имена = {};
  let таймер = 0, частоДо = 0;

  function круг(а, большой = false) {
    const кольцо = svg("svg", { viewBox: "0 0 48 48", class: "агент-кольцо", "aria-hidden": "true" });
    кольцо.append(
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-фон" }),
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-дуга", pathLength: 100 }),
      svg("circle", { cx: 24, cy: 24, r: 21, class: "агент-бег", pathLength: 100 }),
    );
    const значок = svg("svg", { viewBox: "0 0 24 24", class: "агент-значок", "aria-hidden": "true",
      fill: "none", stroke: "currentColor", "stroke-width": "1.8", "stroke-linecap": "round", "stroke-linejoin": "round" });
    значок.append(svg("path", { d: ЗНАЧКИ[а.значок] || ЗНАЧКИ.чат }));
    return создать("div", { класс: `агент-круг${большой ? " большой" : ""}` }, кольцо, значок, создать("span", { класс: "агент-точка" }));
  }

  const звёзды = (н) => "★".repeat(н) + "☆".repeat(Math.max(0, 5 - н));

  function ячейка(а) {
    const элемент = создать("button", { type: "button", класс: "агент", данные: { агент: а.ключ },
      onclick: () => открыть(а.ключ) },
      круг(а),
      создать("span", { класс: "агент-имя", текст: а.имя }),
      создать("span", { класс: "агент-звёзды" }),
      создать("span", { класс: "агент-счёт" }),
      создать("span", { класс: "агент-записки", hidden: "" }));
    ряд.append(элемент);
    ячейки.set(а.ключ, элемент);
    return элемент;
  }

  function показать(данные) {
    имена = Object.fromEntries(данные.агенты.map((а) => [а.ключ, а.имя]));
    const максимум = Math.max(1, ...данные.агенты.map((а) => а.сегодня));
    for (const а of данные.агенты) {
      const э = ячейки.get(а.ключ) || ячейка(а);
      const было = прошлое.get(а.ключ);
      // искра: агент взялся за дело — летит от того, кто работал перед ним
      if (было && !было.работает && а.работает) {
        if (последнийАктивный && последнийАктивный !== а.ключ && Date.now() - когдаАктивен < 8000) искра(последнийАктивный, а.ключ);
        else искра(null, а.ключ);
      }
      if (а.работает) { последнийАктивный = а.ключ; когдаАктивен = Date.now(); }
      // закончил: вспышка успеха или ошибки
      if (было && было.всего < а.всего && !а.работает) {
        вспышка(а.ключ, !а.ошибка);
        последнийАктивный = а.ключ; когдаАктивен = Date.now();
      }
      прошлое.set(а.ключ, { работает: а.работает, всего: а.всего });

      э.classList.toggle("работает", а.работает);
      э.classList.toggle("ошибка", Boolean(а.ошибка));
      э.classList.toggle("спит", !а.работает && !а.сегодня);
      э.querySelector(".агент-дуга").style.strokeDasharray = `${Math.round((а.сегодня / максимум) * 100)} 100`;
      э.querySelector(".агент-счёт").textContent = а.работает ? "работает…" : а.сегодня ? `${а.сегодня} сегодня` : "ждёт";
      const з = э.querySelector(".агент-звёзды");
      з.textContent = звёзды(а.уровень);
      з.title = `Уровень ${а.уровень} · опыт ${а.опыт}${а.до ? ` из ${а.до}` : ""}`;
      const записки = э.querySelector(".агент-записки");
      записки.hidden = !а.записок;
      записки.textContent = а.записок ? `✉ ${а.записок}` : "";
      const строки = [`${а.имя} — ${а.что}`, `Уровень ${а.уровень} · опыт ${а.опыт}`];
      if (а.работает) строки.push(`Работает уже ${а.идёт_секунд} с`);
      if (а.последний) строки.push(`Последнее: ${а.последнее_действие} — ${а.последний_результат} (${дата(а.последний)})`);
      строки.push(`Сегодня: ${а.сегодня} · всего: ${а.всего}`, "Клик — история, память, записки");
      э.title = строки.join("\n");
      э.setAttribute("aria-label", строки.join(". "));
    }
    итог.textContent = `${данные.работают} ${данные.работают === 1 ? "работает" : "работают"} · ${данные.сегодня} за сегодня`;
    итог.classList.toggle("активно", данные.работают > 0);
    $("доска-счёт").hidden = !данные.записок;
    $("доска-счёт").textContent = данные.записок || "";
    if (!кадр) кадр = requestAnimationFrame(рисовать);
  }

  async function обновить() {
    clearTimeout(таймер);
    if (!document.hidden && !ряд.closest("main").hidden) {
      try {
        const данные = await запрос("/api/agents");
        показать(данные);
        таймер = setTimeout(обновить, данные.работают || Date.now() < частоДо ? 450 : 3000);
        return;
      } catch {
        итог.textContent = "нет связи";
      }
    }
    таймер = setTimeout(обновить, 3000);
  }
  document.addEventListener("visibilitychange", () => { if (!document.hidden) обновить(); });
  document.addEventListener("mizuyori:экран", (с) => { if (с.detail === "главная") обновить(); });
  document.addEventListener("mizuyori:чат-отправлено", () => { частоДо = Date.now() + 20000; setTimeout(обновить, 150); });

  // ---- Дорожка, искры, вспышки ---------------------------------------------------

  const искры = [], вспышки = [];
  let кадр = 0, время = 0, прошлый = 0;

  function центр(ключ) {
    const э = ячейки.get(ключ)?.querySelector(".агент-круг");
    if (!э) return null;
    const р = э.getBoundingClientRect(), л = холст.getBoundingClientRect();
    return [р.left + р.width / 2 - л.left, р.top + р.height / 2 - л.top, р.width / 2];
  }
  function искра(от, кому) {
    if (безАнимаций()) return;
    искры.push({ от, кому, t: 0 });
    if (!кадр) кадр = requestAnimationFrame(рисовать);
  }
  function вспышка(ключ, успех) {
    const э = ячейки.get(ключ);
    if (э) { э.classList.remove("успех", "провал"); void э.offsetWidth; э.classList.add(успех ? "успех" : "провал"); }
    if (безАнимаций()) return;
    вспышки.push({ ключ, успех, t: 0 });
    if (!кадр) кадр = requestAnimationFrame(рисовать);
  }

  function рисовать(t) {
    const dt = Math.max(0, Math.min((t - прошлый) / 1000 || 0.016, 0.1));
    прошлый = t; время += dt;
    const dpr = Math.min(window.devicePixelRatio || 1, 2);
    const ш = холст.clientWidth, в = холст.clientHeight;
    if (холст.width !== Math.round(ш * dpr) || холст.height !== Math.round(в * dpr)) {
      холст.width = Math.round(ш * dpr); холст.height = Math.round(в * dpr);
    }
    к.setTransform(dpr, 0, 0, dpr, 0, 0);
    к.clearRect(0, 0, ш, в);
    const акцент = getComputedStyle(document.documentElement).getPropertyValue("--акцент").trim() || "#3ecf9a";
    const точки = [...ячейки.keys()].map(центр).filter(Boolean);
    if (точки.length > 1) {
      // дорожка между кругами
      к.strokeStyle = акцент; к.globalAlpha = 0.22; к.lineWidth = 1.5;
      к.setLineDash([3, 6]); к.lineDashOffset = безАнимаций() ? 0 : -время * 12;
      к.beginPath();
      for (let i = 0; i < точки.length - 1; i++) {
        к.moveTo(точки[i][0] + точки[i][2] + 4, точки[i][1]);
        к.lineTo(точки[i + 1][0] - точки[i + 1][2] - 4, точки[i + 1][1]);
      }
      к.stroke(); к.setLineDash([]); к.globalAlpha = 1;
    }
    // искры
    for (let i = искры.length - 1; i >= 0; i--) {
      const и = искры[i];
      и.t += dt / 0.7;
      const куда = центр(и.кому);
      const откуда = и.от ? центр(и.от) : куда && [куда[0] - 70, куда[1], 0];
      if (!куда || !откуда || и.t >= 1) { искры.splice(i, 1); continue; }
      const е = 1 - Math.pow(1 - и.t, 2);
      const дуга = (ее) => [откуда[0] + (куда[0] - откуда[0]) * ее, откуда[1] + (куда[1] - откуда[1]) * ее - Math.sin(ее * Math.PI) * 10];
      for (let х = 0; х < 6; х++) {                       // хвост
        const [xx, yy] = дуга(Math.max(0, е - х * 0.03));
        к.globalAlpha = (1 - х / 6) * 0.6; к.fillStyle = акцент;
        к.beginPath(); к.arc(xx, yy, 3 - х * 0.4, 0, Math.PI * 2); к.fill();
      }
      const [x, y] = дуга(е);
      к.globalAlpha = 1; к.fillStyle = "#fff";
      к.beginPath(); к.arc(x, y, 2.4, 0, Math.PI * 2); к.fill();
    }
    // вспышки: расходящееся кольцо и искры-лучи
    for (let i = вспышки.length - 1; i >= 0; i--) {
      const вс = вспышки[i];
      вс.t += dt / 0.9;
      const ц = центр(вс.ключ);
      if (!ц || вс.t >= 1) { вспышки.splice(i, 1); continue; }
      const цвет = вс.успех ? акцент : "#ff6b5b";
      к.strokeStyle = цвет; к.globalAlpha = 1 - вс.t; к.lineWidth = 2;
      к.beginPath(); к.arc(ц[0], ц[1], ц[2] + вс.t * 22, 0, Math.PI * 2); к.stroke();
      к.fillStyle = цвет;
      for (let л = 0; л < 8; л++) {
        const а = (л / 8) * Math.PI * 2 + 0.3;
        const р = ц[2] + 4 + вс.t * 26;
        к.beginPath(); к.arc(ц[0] + Math.cos(а) * р, ц[1] + Math.sin(а) * р, 1.8 * (1 - вс.t), 0, Math.PI * 2); к.fill();
      }
      к.globalAlpha = 1;
    }
    const дальше = !ряд.closest("main").hidden && !document.hidden;
    кадр = дальше ? requestAnimationFrame(рисовать) : 0;
  }

  // ---- Окно агента -----------------------------------------------------------------

  const окно = $("окно-агента");
  const тело = $("агент-тело");
  let открыт = null, вкладка = "история", поиск = "", таймерПоиска = 0;

  const кто = (ключ) => (ключ === "вы" ? "Вы" : ключ === "все" ? "Всем" : (имена[ключ] || ключ));

  async function открыть(ключ, новая = true) {
    открыт = ключ;
    if (новая) { вкладка = "история"; поиск = ""; }
    окно.hidden = false;
    try {
      const д = await запрос(`/api/agents/${encodeURIComponent(ключ)}?q=${encodeURIComponent(поиск)}&limit=60`);
      if (открыт !== ключ) return;
      имена = { ...имена, ...д.имена };
      const новыйКруг = круг(д, true);
      новыйКруг.id = "агент-круг-окна";
      новыйКруг.classList.toggle("работает", д.работает);
      $("агент-круг-окна").replaceWith(новыйКруг);
      $("агент-имя-окна").textContent = д.имя;
      $("агент-что-окна").textContent = д.что;
      const доля = д.до ? Math.round(((д.опыт - д.от) / (д.до - д.от)) * 100) : 100;
      const полоска = создать("span", { класс: "агент-опыт" }, создать("span", {}));
      полоска.firstChild.style.width = `${доля}%`;
      $("агент-уровень-окна").replaceChildren(
        создать("span", { класс: "агент-звёзды", текст: звёзды(д.уровень) }),
        создать("span", { текст: `уровень ${д.уровень} · опыт ${д.опыт}${д.до ? ` / ${д.до}` : " · максимум"}` }),
        полоска);
      for (const кн of $("агент-вкладки").querySelectorAll("button")) кн.setAttribute("aria-selected", String(кн.dataset.вкладка === вкладка));
      if (вкладка === "история") нарисоватьИсторию(д);
      else if (вкладка === "память") нарисоватьПамять(д);
      else нарисоватьЗаписки(д);
    } catch (e) {
      тело.replaceChildren(создать("p", { класс: "пусто", текст: `Не удалось загрузить: ${e.message}` }));
    }
  }

  function нарисоватьИсторию(д) {
    const поле = создать("input", { type: "search", класс: "агент-поиск", placeholder: "Искать в истории решений…",
      "aria-label": "Поиск по истории", value: поиск });
    поле.addEventListener("input", () => {
      clearTimeout(таймерПоиска);
      таймерПоиска = setTimeout(async () => {
        поиск = поле.value;
        await открыть(открыт, false);
        const п = тело.querySelector(".агент-поиск");
        if (п) { п.focus(); п.setSelectionRange(п.value.length, п.value.length); }
      }, 300);
    });
    const список = д.история.length
      ? создать("ul", { класс: "агент-история" }, ...д.история.map((з) => создать("li", { класс: з.успех ? "" : "неудача" },
          создать("span", { класс: "агент-итог-значок", текст: з.успех ? (з.польза ? "✓" : "·") : "✗" }),
          создать("div", {},
            создать("div", { класс: "агент-строка" },
              создать("strong", { текст: з.действие }),
              создать("time", { текст: `${дата(з.создано)} · ${з.секунд} с` })),
            ...(з.почему ? [создать("div", { класс: "агент-почему", текст: `почему: ${з.почему}` })] : []),
            создать("div", { класс: "агент-результат", текст: з.результат }),
            ...(з.польза ? [создать("span", { класс: "агент-польза", текст: `+${з.польза} опыта` })] : [])))))
      : создать("p", { класс: "пусто", текст: поиск ? "Ничего не нашлось." : "Пока ничего не делал." });
    тело.replaceChildren(поле, список);
  }

  function нарисоватьПамять(д) {
    const вид = создать("select", { "aria-label": "Вид заметки" },
      создать("option", { value: "правило", текст: "Правило" }), создать("option", { value: "приём", текст: "Приём" }));
    const поле = создать("input", { type: "text", maxlength: "300", placeholder: "Например: не запоминать погоду", "aria-label": "Текст" });
    const форма = создать("form", { класс: "агент-форма" }, вид, поле,
      создать("button", { type: "submit", класс: "кнопка главная малая", текст: "Добавить" }));
    форма.addEventListener("submit", async (с) => {
      с.preventDefault();
      if (!поле.value.trim()) return поле.focus();
      try {
        await запрос(`/api/agents/${encodeURIComponent(открыт)}/notes`, { method: "POST", body: JSON.stringify({ вид: вид.value, текст: поле.value }) });
        открыть(открыт, false);
      } catch (e) { alert(e.message); }
    });
    const группа = (название, пояснение, пункты) => создать("section", { класс: "агент-группа" },
      создать("h3", { текст: `${название} · ${пункты.length}` }),
      пункты.length
        ? создать("ul", { класс: "агент-заметки" }, ...пункты.map((з) => создать("li", {},
            создать("span", { текст: з.текст }),
            создать("small", { текст: `${з.источник === "вы" ? "вы" : "сам"}${з.счёт > 1 ? ` · ×${з.счёт}` : ""} · ${дата(з.изменено)}` }),
            создать("button", { type: "button", класс: "душа-убрать", "aria-label": "Удалить", текст: "×",
              onclick: async () => {
                try { await запрос(`/api/agents/notes/${з.id}`, { method: "DELETE" }); открыть(открыт, false); }
                catch (e) { alert(e.message); }
              } }))))
        : создать("p", { класс: "пусто", текст: пояснение }));
    const з = д.заметки;
    тело.replaceChildren(
      создать("p", { класс: "агент-пояснение", текст: д.ключ === "смысл"
        ? "Смысл не пишет текстов для ИИ — правила здесь только для заметки."
        : "Правила и приёмы добавляются к заданию агента: он соблюдает их в работе. Ошибки он собирает сам." }),
      форма,
      группа("Правила", "Что агенту делать или не делать.", з.filter((х) => х.вид === "правило")),
      группа("Приёмы", "Что у агента хорошо получается.", з.filter((х) => х.вид === "приём")),
      группа("Частые ошибки", "Ошибок пока не было.", з.filter((х) => х.вид === "ошибка")));
  }

  function записка(з) {
    return создать("li", { класс: з.прочитано ? "" : "новая" },
      создать("div", { класс: "агент-строка" },
        создать("strong", { текст: `${кто(з.от)} → ${кто(з.кому)}` }),
        создать("time", { текст: дата(з.создано) })),
      создать("div", { текст: з.текст }),
      ...(з.прочитано ? [] : [создать("small", { текст: "ещё не прочитана" })]));
  }

  function нарисоватьЗаписки(д) {
    const поле = создать("input", { type: "text", maxlength: "300", placeholder: `Записка для «${д.имя}»…`, "aria-label": "Текст записки" });
    const форма = создать("form", { класс: "агент-форма" }, поле,
      создать("button", { type: "submit", класс: "кнопка главная малая", текст: "Написать" }));
    форма.addEventListener("submit", async (с) => {
      с.preventDefault();
      if (!поле.value.trim()) return поле.focus();
      try {
        await запрос("/api/agents/board", { method: "POST", body: JSON.stringify({ кому: открыт, текст: поле.value }) });
        открыть(открыт, false);
      } catch (e) { alert(e.message); }
    });
    тело.replaceChildren(форма,
      д.записки.length ? создать("ul", { класс: "записки" }, ...д.записки.map(записка))
        : создать("p", { класс: "пусто", текст: "Записок пока нет. Агенты пишут друг другу, когда что-то меняется." }));
  }

  $("агент-вкладки").addEventListener("click", (с) => {
    const кн = с.target.closest("button[data-вкладка]");
    if (!кн || !открыт) return;
    вкладка = кн.dataset.вкладка;
    открыть(открыт, false);
  });
  const закрыть = () => { окно.hidden = true; открыт = null; };
  $("закрыть-агента").addEventListener("click", закрыть);
  окно.addEventListener("click", (с) => { if (с.target === окно) закрыть(); });

  // ---- Доска ---------------------------------------------------------------------

  const доска = $("окно-доски");
  async function открытьДоску() {
    доска.hidden = false;
    try {
      const д = await запрос("/api/agents/board");
      имена = { ...имена, ...д.имена };
      const кому = $("доска-кому");
      if (!кому.options.length) {
        кому.append(создать("option", { value: "все", текст: "Всем" }),
          ...Object.entries(д.имена).map(([ключ, имя]) => создать("option", { value: ключ, текст: имя })));
      }
      $("доска-список").replaceChildren(...(д.записки.length ? д.записки.map(записка)
        : [создать("li", { класс: "пусто", текст: "Доска пуста. Здесь агенты оставляют записки друг другу." })]));
    } catch (e) {
      $("доска-список").replaceChildren(создать("li", { текст: e.message }));
    }
  }
  $("агенты-доска").addEventListener("click", открытьДоску);
  $("закрыть-доску").addEventListener("click", () => (доска.hidden = true));
  доска.addEventListener("click", (с) => { if (с.target === доска) доска.hidden = true; });
  $("доска-форма").addEventListener("submit", async (с) => {
    с.preventDefault();
    const поле = $("доска-текст");
    if (!поле.value.trim()) return поле.focus();
    try {
      await запрос("/api/agents/board", { method: "POST", body: JSON.stringify({ кому: $("доска-кому").value, текст: поле.value }) });
      поле.value = "";
      открытьДоску();
      обновить();
    } catch (e) { alert(e.message); }
  });
  $("доска-очистить").addEventListener("click", async () => {
    if (!confirm("Удалить все записки с доски?")) return;
    try { await запрос("/api/agents/board", { method: "DELETE" }); открытьДоску(); обновить(); } catch (e) { alert(e.message); }
  });
  document.addEventListener("keydown", (с) => {
    if (с.key !== "Escape") return;
    if (!окно.hidden) закрыть();
    if (!доска.hidden) доска.hidden = true;
  });

  обновить();
}
