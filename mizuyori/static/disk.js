"use strict";

// =============================================================================
// Экран «Диск»: файлы по контрагентам и договорам, реестры договоров и счёт-оферт, корзина, копии.
// Файлы рисует archive.js, реестры — work.js; здесь меню, корзина и резервные копии.
// =============================================================================
{
  const экран = $("экран-диск");
  const меню = $("диск-меню");
  const место = $("диск-содержимое");
  const размер = (б) => (б > 1073741824 ? `${(б / 1073741824).toFixed(1)} ГБ` : б > 1048576 ? `${(б / 1048576).toFixed(1)} МБ` : `${Math.max(1, Math.round(б / 1024))} КБ`);
  let раздел = "файлы";
  try { раздел = localStorage.getItem("mizuyori.диск.раздел") || раздел; } catch {}
  if (!["файлы", "договоры", "оферты", "корзина", "копии"].includes(раздел)) раздел = "файлы";
  let поколение = 0;

  const api = (адрес, метод = "GET") => запрос(адрес, { method: метод });

  function выбрать(новый) {
    раздел = новый;
    try { localStorage.setItem("mizuyori.диск.раздел", раздел); } catch {}
    for (const к of меню.querySelectorAll("button[data-раздел]")) {
      const он = к.dataset.раздел === раздел;
      к.setAttribute("aria-current", String(он));
      if (он) экран.style.setProperty("--рц", к.style.getPropertyValue("--рц"));
    }
    экран.dataset.раздел = раздел;
    нарисовать();
  }
  меню.addEventListener("click", (с) => {
    const к = с.target.closest("button[data-раздел]");
    if (к) выбрать(к.dataset.раздел);
  });
  document.addEventListener("mizuyori:экран", (с) => { if (с.detail === "диск") выбрать(раздел); });

  async function нарисовать() {
    const мой = ++поколение;
    try {
      if (раздел === "файлы") await window.нарисоватьАрхив(место);
      else if (раздел === "договоры" || раздел === "оферты") await window.реестрНаДиске(раздел, место);
      else if (раздел === "корзина") await корзина(мой);
      else if (раздел === "копии") await копии(мой);
      счётчики();
    } catch (е) {
      if (мой === поколение) место.replaceChildren(создать("p", { класс: "пусто", текст: `Не удалось загрузить: ${е.message}` }));
    }
  }

  // Число файлов в корзине рядом с пунктом меню
  async function счётчики() {
    try {
      const д = await api("/api/archive/tree");
      const к = меню.querySelector('button[data-раздел="корзина"] b');
      if (к) к.textContent = д.в_корзине ? `Корзина · ${д.в_корзине}` : "Корзина";
    } catch {}
  }

  // ---- Корзина ------------------------------------------------------------------------------

  async function корзина(мой) {
    const д = await api("/api/archive/trash");
    if (мой !== поколение) return;
    const строки = д.файлы.map((ф) => создать("li", { класс: "архив-файл" },
      создать("span", { класс: "архив-файл-значок", текст: "📄" }),
      создать("div", { класс: "архив-файл-текст" },
        создать("span", { класс: "архив-файл-имя", текст: ф.имя }),
        создать("div", { класс: "архив-файл-мелко" }, создать("span", { класс: "архив-вид", текст: ф.вид }),
          создать("span", { текст: `удалён ${ф.удалён}` }), создать("span", { класс: "архив-где", текст: ф.было_в ? ф.было_в.split("/").slice(0, -1).join(" / ") : "" }))),
      создать("div", { класс: "архив-файл-действия" },
        создать("button", { type: "button", класс: "кнопка второстепенная малая", текст: "Восстановить", onclick: async () => {
          try { await запрос(`/api/archive/file/${ф.id}/restore`, { method: "POST" }); } catch (е) { alert(е.message); }
          нарисовать();
        } }),
        создать("button", { type: "button", класс: "кнопка-значок", title: "Удалить навсегда", "aria-label": "Удалить навсегда", текст: "✕", onclick: async () => {
          if (!confirm(`Удалить «${ф.имя}» навсегда? Вернуть будет нельзя.`)) return;
          await api(`/api/archive/file/${ф.id}?forever=true`, "DELETE"); нарисовать();
        } }))));
    место.replaceChildren(
      создать("div", { класс: "работа-шапка" }, создать("h2", { текст: "Корзина" }),
        создать("span", { класс: "работа-счёт", текст: `${д.файлы.length} файлов · хранятся ${д.хранить_дней} дней` }), создать("span", { класс: "растяжка" }),
        ...(д.файлы.length ? [создать("button", { type: "button", класс: "кнопка опасная", текст: "Очистить корзину", onclick: async () => {
          if (!confirm("Удалить из корзины всё навсегда?")) return;
          await api("/api/archive/trash/empty", "POST"); нарисовать();
        } })] : [])),
      строки.length ? создать("ul", { класс: "архив-файлы" }, ...строки) : создать("p", { класс: "пусто", текст: "Корзина пуста. Удалённые файлы лежат здесь 30 дней — их можно вернуть на прежнее место." }));
  }

  // ---- Копии и проверка -------------------------------------------------------------------------

  async function копии(мой) {
    const д = await api("/api/disk/summary");
    if (мой !== поколение) return;
    const п = д.проверка;
    const сделать = создать("button", { type: "button", класс: "кнопка главная", текст: "Сделать копию сейчас", onclick: async () => {
      сделать.disabled = true; сделать.textContent = "Копирую…";
      try { await запрос("/api/disk/backup", { method: "POST" }); } catch (е) { alert(е.message); }
      нарисовать();
    } });
    место.replaceChildren(
      создать("div", { класс: "работа-шапка" }, создать("h2", { текст: "Копии и проверка" }), создать("span", { класс: "растяжка" }), сделать),
      создать("div", { класс: "диск-карточки" },
        карточка("Файлов на Диске", String(д.всего), `${размер(д.размер)}${д.в_корзине ? ` · в корзине ${д.в_корзине}` : ""}`),
        карточка("Не прочитан текст", String(д.без_текста), д.без_текста ? "по ним агенты найдут только название" : "агенты видят содержимое всех файлов"),
        карточка("Пропали с диска", String(п.пропали_с_диска.length), п.пропали_с_диска.length ? п.пропали_с_диска.slice(0, 3).map((х) => х.имя).join(", ") : "всё на месте"),
        карточка("Лишние файлы", String(п.лишние_файлы.length), п.лишние_файлы.length ? п.лишние_файлы.slice(0, 2).join(", ") : "порядок")),
      создать("h4", { класс: "архив-подзаголовок", текст: "Состав по видам" }),
      создать("div", { класс: "диск-виды" }, ...Object.entries(д.по_видам).map(([в, н]) => создать("span", { класс: "диск-вид", текст: `${в} · ${н}` }))),
      создать("h4", { класс: "архив-подзаголовок", текст: "Резервные копии (база и все файлы, раз в сутки сами, хранятся 7 последних)" }),
      д.копии.length ? создать("ul", { класс: "архив-файлы" }, ...д.копии.map((к) => создать("li", { класс: "архив-файл" },
        создать("span", { класс: "архив-файл-значок", текст: "💾" }),
        создать("div", { класс: "архив-файл-текст" }, создать("span", { класс: "архив-файл-имя", текст: к.имя }),
          создать("div", { класс: "архив-файл-мелко" }, создать("span", { текст: к.создано }), создать("span", { текст: размер(к.размер) }))),
        создать("div", { класс: "архив-файл-действия" }, создать("a", { href: `/api/disk/backup/${encodeURIComponent(к.имя)}`, класс: "кнопка второстепенная малая", текст: "⬇ Скачать", download: к.имя })))))
        : создать("p", { класс: "пусто", текст: "Копий пока нет — первая сделается сама, или нажмите «Сделать копию сейчас»." }));
  }

  const карточка = (название, число, мелко) => создать("div", { класс: "диск-карточка" },
    создать("span", { класс: "диск-карточка-название", текст: название }), создать("b", { класс: "диск-карточка-число", текст: число }),
    создать("span", { класс: "диск-карточка-мелко", текст: мелко }));
}
