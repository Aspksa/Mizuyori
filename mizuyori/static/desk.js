"use strict";

// «Стол»: вкладка рядом с чатом. Вся команда на одном экране: схема со вспышками записок, «Вы» с подтверждением,
// таймер следующего обхода, правила в силе и журнал событий. Данные — GET /api/desk.
{
  const панель = document.querySelector("section.чат");
  const вкладки = $("чат-вкладки"), граф = $("стол-граф");
  const NS = "http://www.w3.org/2000/svg";
  const эл = (тег, атрибуты = {}, ...дети) => {
    const э = document.createElementNS(NS, тег);
    for (const [к, з] of Object.entries(атрибуты)) э.setAttribute(к, з);
    э.append(...дети);
    return э;
  };
  const ЦВЕТА = ["#3ecf9a", "#6aa9ff", "#f5a34b", "#c58bff", "#ff7aa8", "#5fd4e6", "#e6d35f"];
  let вид = "чат", таймер = 0, последняяЗаписка = null, данные = null, тикОт = 0, тикЧерез = null;
  const координаты = new Map();
  const ВЫ = { x: 738, y: 335 };

  function вкладка(новая) {
    вид = новая;
    панель.classList.toggle("вид-стол", вид === "стол");
    $("стол").hidden = вид !== "стол";
    for (const к of вкладки.children) к.setAttribute("aria-selected", String(к.dataset.вид === вид));
    if (вид === "стол") обновить(); else clearTimeout(таймер);
  }
  вкладки.addEventListener("click", (с) => { const к = с.target.closest("button[data-вид]"); if (к) вкладка(к.dataset.вид); });

  const время = (с) => (с || "").slice(11, 16);
  const мин = (с) => `${Math.floor(с / 3600) ? Math.floor(с / 3600) + " ч " : ""}${Math.floor((с % 3600) / 60)} мин ${с % 60} с`;

  function расставить(агенты) {
    координаты.clear();
    const лидер = агенты.find((а) => а.лидер);
    координаты.set(лидер.ключ, { x: 360, y: 190 });
    const внутри = агенты.filter((а) => а.поддержка && !а.лидер), снаружи = агенты.filter((а) => !а.поддержка && !а.лидер);
    внутри.forEach((а, i) => { const у = (i / внутри.length) * 2 * Math.PI - Math.PI / 2; координаты.set(а.ключ, { x: 360 + Math.cos(у) * 95, y: 190 + Math.sin(у) * 70 }); });
    снаружи.forEach((а, i) => { const у = (i / снаружи.length) * 2 * Math.PI - Math.PI / 2; координаты.set(а.ключ, { x: 360 + Math.cos(у) * 290, y: 190 + Math.sin(у) * 150 }); });
  }

  const цветА = (а) => window.ЦВЕТ_ТАЛИСМАНА(а.ключ);
  const есть = (т) => (т || "").toUpperCase();

  function нарисоватьГраф(д) {
    расставить(д.агенты);
    const лидер = д.агенты.find((а) => а.лидер);
    const слой = эл("g");
    const л = координаты.get(лидер.ключ);
    const ждёт = д.ждёт.length > 0;
    слой.append(эл("circle", { class: "гало", cx: л.x, cy: л.y, r: 46 }));
    for (const а of д.агенты) if (!а.лидер) {
      const т = координаты.get(а.ключ);
      слой.append(эл("line", { class: "линия", x1: л.x, y1: л.y, x2: т.x, y2: т.y, stroke: цветА(а) }));
    }
    слой.append(эл("path", { id: "стол-путь-вы", class: ждёт ? "линия-вы ждёт" : "линия-вы", d: `M${л.x} ${л.y} L${ВЫ.x} ${ВЫ.y}` }));
    for (const а of д.агенты) {
      const т = координаты.get(а.ключ), р = а.лидер ? 25 : 17;
      const г = эл("g", { class: `узел${а.работает ? " работает" : ""}${а.ошибка ? " ошибка" : ""}${!а.работает && !а.сегодня ? " спит" : ""}`,
        transform: `translate(${т.x} ${т.y})`, tabindex: 0, role: "button", "aria-label": `${а.имя}: ${а.роль}` });
      г.append(эл("title", {}, `${а.имя}\n${а.роль}${а.правило ? `\nПравило: ${а.правило}` : ""}`),
        эл("circle", { class: "кольцо", r: р + 3, stroke: цветА(а) }), эл("circle", { class: "тело", r: р }));
      const м = window.талисман(а.ключ, { работает: а.работает });
      м.setAttribute("x", -р * .78); м.setAttribute("y", -р * .78); м.setAttribute("width", р * 1.56); м.setAttribute("height", р * 1.56);
      г.append(м, эл("text", { y: р + 13 }, а.лидер ? "" : а.имя.split(" ")[0]));
      г.addEventListener("click", () => document.dispatchEvent(new CustomEvent("mizuyori:открыть-агента", { detail: а.ключ })));
      слой.append(г);
    }
    const вы = эл("g", { class: `вы узел${ждёт ? " ждёт" : ""}`, transform: `translate(${ВЫ.x} ${ВЫ.y})` },
      эл("circle", { class: "кольцо-вы", r: 31 }), эл("circle", { class: "тело", r: 24 }), эл("text", { y: 5 }, "вы"));
    слой.append(вы);
    if (ждёт) слой.append(эл("g", { transform: `translate(${ВЫ.x - 84} ${ВЫ.y - 62})` },
      эл("g", { class: "пузырь" }, эл("rect", { width: 104, height: 22, rx: 11 }), эл("text", { x: 52, y: 15, "text-anchor": "middle" }, "подтвердить?"))));
    граф.replaceChildren(слой);
    // фишки записок бегут по линиям (SMIL), пока кто-то работает; к «вам» — если что-то ждёт
    if (!matchMedia("(prefers-reduced-motion: reduce)").matches) {
      const бегущие = d_бегущие(д);
      бегущие.forEach(([путь, цвет, задержка], i) => {
        const ф = эл("rect", { class: "фишка", width: 9, height: 9, rx: 2.5, x: -4.5, y: -4.5, fill: цвет });
        ф.append(эл("animateMotion", { dur: `${1.8 + (i % 3) * .4}s`, begin: `${задержка}s`, repeatCount: "indefinite", path: путь }));
        слой.append(ф);
      });
    }
  }
  function d_бегущие(д) {
    const л = координаты.get(д.агенты.find((а) => а.лидер).ключ), итог = [];
    const живые = д.агенты.filter((а) => !а.лидер && (а.работает || а.сегодня));
    живые.slice(0, 7).forEach((а, i) => {
      const т = координаты.get(а.ключ);
      итог.push([а.работает ? `M${т.x} ${т.y} L${л.x} ${л.y}` : `M${л.x} ${л.y} L${т.x} ${т.y}`, цветА(а), (i * .45).toFixed(2)]);
    });
    if (д.ждёт.length) итог.push([`M${л.x} ${л.y} L${ВЫ.x} ${ВЫ.y}`, "#ff6b5b", "0"], [`M${л.x} ${л.y} L${ВЫ.x} ${ВЫ.y}`, "#ff6b5b", "1"]);
    return итог;
  }

  function искра(от, кому) {
    const а = координаты.get(от) || координаты.get("смотрящий"), б = координаты.get(кому) || ВЫ;
    if (!а || !б || matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const точка = эл("circle", { class: "искра", r: 5, cx: а.x, cy: а.y });
    точка.append(эл("animate", { attributeName: "cx", from: а.x, to: б.x, dur: "1.1s", fill: "freeze" }), эл("animate", { attributeName: "cy", from: а.y, to: б.y, dur: "1.1s", fill: "freeze" }));
    граф.append(точка);
    setTimeout(() => точка.remove(), 1300);
  }

  function мини(п) {
    if (п.вид === "полоса") return создать("div", { класс: "мини полоса" }, создать("i", { style: `width:${Math.max(4, Math.round(п.доля * 100))}%` }), создать("small", { текст: п.подпись }));
    if (п.вид === "квадраты") return создать("div", { класс: "мини квадраты" }, ...п.квадраты.map((в) => создать("i", { класс: в ? "горит" : "" })), создать("small", { текст: п.подпись }));
    if (п.вид === "линия") {
      const т = п.точки.length ? п.точки : [0], макс = Math.max(1, ...т), шаг = 100 / Math.max(1, т.length - 1);
      const пт = т.map((в, i) => `${(i * шаг).toFixed(1)},${(22 - (в / макс) * 20).toFixed(1)}`).join(" ");
      const св = эл("svg", { viewBox: "0 0 100 24", preserveAspectRatio: "none", class: "спарк" }, эл("polyline", { points: пт }));
      return создать("div", { класс: "мини линия" }, св, создать("small", { текст: п.подпись }));
    }
    return "";
  }

  function нарисовать(д) {
    данные = д;
    const ждут = д.ждёт.length;
    const лидер = д.агенты.find((а) => а.лидер);
    $("стол-лидер").replaceChildren(window.талисман(лидер.ключ, { работает: лидер.работает }));
    $("стол-итоги").replaceChildren(
      ...[["идёт", д.работают, "работают"], ["", д.агенты.length, "в команде"], ["ждёт", ждут, "ждут «да»"],
        ["", `${д.в_час.использовано}/${д.в_час.запросов_в_час}`, "запросов/час"]].map(([к, ч, п]) => создать("div", { класс: к }, создать("b", { текст: String(ч) }), создать("small", { текст: п }))));
    const с = $("стол-счёт"); с.hidden = !ждут; с.textContent = ждут || "";
    if (вид !== "стол") return;
    нарисоватьГраф(д);
    $("стол-команда").replaceChildren(...д.агенты.map((а) => {
      const ли = создать("li", { класс: `${а.работает ? "работает" : ""}${а.ошибка ? " ошибка" : ""}`, tabindex: 0, role: "button" },
        создать("span", { класс: "значок-стол" }, window.талисман(а.ключ, { работает: а.работает })),
        создать("div", {}, создать("b", { текст: есть(а.имя) }), создать("small", { текст: а.роль, title: а.роль }),
          создать("i", { класс: "правило-линия", style: `background:${цветА(а)}`, title: а.правило || "" })));
      ли.addEventListener("click", () => document.dispatchEvent(new CustomEvent("mizuyori:открыть-агента", { detail: а.ключ })));
      return ли;
    }));
    // искры для новых записок
    const новые = д.записки.filter((з) => з.id > (последняяЗаписка ?? Infinity)).reverse();
    if (д.записки.length) последняяЗаписка = Math.max(...д.записки.map((з) => з.id), последняяЗаписка ?? 0); else последняяЗаписка ??= 0;
    for (const з of новые.slice(-6)) искра(з.от, з.кому === "все" ? "смотрящий" : з.кому);
    const последняя = д.записки[0];
    $("стол-карточки").replaceChildren(
      создать("div", { класс: "карточка" }, создать("span", { класс: "метка", текст: "тема" }),
        создать("b", { текст: последняя ? `${последняя.от} → ${последняя.кому}` : "тихо" }),
        создать("small", { текст: последняя ? последняя.текст : "ничего нового" })),
      ...д.ждёт.slice(0, 3).map((ж) => создать("div", { класс: "карточка красная" },
        создать("span", { класс: "метка красная", текст: "ваш ok · ждёт" }),
        создать("b", { текст: ж.текст, title: ж.текст }),
        создать("small", { текст: `окно 30 мин${ж.ждёт_секунд != null ? ` · ждёт ${Math.max(1, Math.round(ж.ждёт_секунд / 60))} мин` : ""}` }))),
      ...(ждут ? [] : [создать("div", { класс: "карточка тихая" }, создать("span", { класс: "метка", текст: "ваш ok" }), создать("small", { текст: "ничего не ждёт вашего «да»" }))]));
    тикЧерез = д.тик.через; тикОт = Date.now();
    нарисоватьТик();
    $("стол-правила").replaceChildren(создать("h3", { текст: "Правила в силе" }),
      создать("ul", {}, ...д.правила.filter((п) => п.текст).map((п) => создать("li", { класс: п.цвет },
        создать("i"), создать("span", { текст: п.текст }), мини(п)))));
    $("стол-журнал").replaceChildren(...(д.события.length ? д.события.slice(0, 14).map((е, i) => создать("div", { класс: `строка ${е.тип}${i === 0 ? " свежая" : ""}` },
      создать("time", { текст: время(е.когда) }), создать("b", { текст: е.тип }), создать("span", { текст: е.текст, title: е.текст }))) : [создать("div", { класс: "пусто", текст: "Пока тихо: событий нет." })]));
  }

  function нарисоватьТик() {
    const место = $("стол-тик");
    if (!данные) return;
    const ост = тикЧерез == null ? null : Math.max(0, tикОсталось());
    const всего = данные.тик.интервал_часов * 3600;
    место.replaceChildren(создать("h3", { текст: "следующий тик" }),
      создать("div", { класс: "время-тика", текст: ост == null ? "—" : мин(ост) }),
      создать("div", { класс: "полоса" }, создать("i", { style: `width:${ост == null ? 0 : Math.round((1 - ост / всего) * 100)}%` })),
      создать("small", { текст: `Раз в ${данные.тик.интервал_часов} ч агенты сами смотрят данные: сроки, ТО, ГСМ.` }));
  }
  const tикОсталось = () => тикЧерез - Math.floor((Date.now() - тикОт) / 1000);
  setInterval(() => { if (вид === "стол" && !document.hidden) нарисоватьТик(); }, 1000);

  async function обновить() {
    clearTimeout(таймер);
    if (!document.hidden && !панель.closest("main").hidden) {
      try { нарисовать(await запрос("/api/desk")); } catch { /* сервер занят */ }
    }
    таймер = setTimeout(обновить, вид === "стол" ? (данные && данные.работают ? 1500 : 3000) : 20000);
  }
  document.addEventListener("visibilitychange", () => { if (!document.hidden) обновить(); });
  document.addEventListener("mizuyori:экран", (с) => { if (с.detail === "главная") обновить(); });
  document.addEventListener("mizuyori:открыть-стол", () => вкладка("стол"));
  обновить();
}
