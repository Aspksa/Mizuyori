"use strict";

// ---- Настройки проекта → вкладка «ИИ · cloud.ru» ------------------------------
//
// Ключ вставляется сюда, проверяется запросом списка моделей, модель выбирается
// из того, что доступно по ключу. Сохраняется в config.json на этом компьютере;
// на страницу ключ целиком больше не возвращается — только «••••1234».
{
  let сохранённые = null;   // как сейчас в config.json (без ключа)
  let модели = [];
  let загружаются = false;

  function статус(текст, ошибка = false) {
    $("ии-статус").textContent = текст;
    $("ии-статус").classList.toggle("несохранено", ошибка);
  }
  function итогКлюча(текст, хорошо) {
    const п = $("ии-ключ-итог");
    п.textContent = текст;
    п.className = `подсказка-поля ${хорошо === true ? "хорошо" : хорошо === false ? "плохо" : ""}`;
  }

  function показатьСостояние() {
    const н = сохранённые;
    const п = $("ии-состояние");
    if (н.подключён) {
      п.textContent = `Подключён · ${н.модель}`;
      п.className = "пояснение хорошо";
    } else {
      п.textContent = !н.есть_ключ ? "Не подключён: нет ключа"
        : !н.модель ? "Не подключён: не выбрана модель"
        : "Выключен";
      п.className = "пояснение";
    }
  }

  function заполнить() {
    const н = сохранённые;
    $("ии-включён").setAttribute("aria-checked", String(н.включён));
    $("ии-ключ").value = "";
    $("ии-ключ").placeholder = н.есть_ключ ? `Сохранён ${н.ключ_маска}` : "Вставьте ключ (Key Secret)";
    $("ии-температура").value = н.температура;
    $("ии-история").value = н.история;
    $("ии-характер").value = н.характер;
    $("ии-адрес").value = н.адрес;
    выбратьДлину(н.длина);
    обновитьЗначения();
    нарисоватьМодели(н.модель);
    $("ии-удалить-ключ").hidden = !н.есть_ключ;
    показатьСостояние();
  }

  function обновитьЗначения() {
    $("ии-температура-знач").textContent = Number($("ии-температура").value).toFixed(2);
    const и = Number($("ии-история").value);
    $("ии-история-знач").textContent = и === 0 ? "не помнит" : String(и);
  }

  // Длина: ближайшая из трёх кнопок
  let длина = 2000;
  function выбратьДлину(значение) {
    длина = Number(значение);
    const кнопки = [...$("ии-длина").children];
    const ближайшая = кнопки.reduce((а, б) =>
      Math.abs(Number(б.dataset.значение) - длина) < Math.abs(Number(а.dataset.значение) - длина) ? б : а);
    for (const к of кнопки) к.setAttribute("aria-checked", String(к === ближайшая));
  }
  $("ии-длина").addEventListener("click", (с) => {
    const к = с.target.closest("button");
    if (к) выбратьДлину(к.dataset.значение);
  });

  function нарисоватьМодели(выбранная) {
    const выбор = $("ии-модель");
    if (!модели.length) {
      выбор.replaceChildren(создать("option", { value: выбранная || "", текст: выбранная || "Сначала проверьте ключ" }));
      выбор.disabled = !выбранная;
      return;
    }
    const чат = модели.filter((м) => м.для_чата);
    const другие = модели.filter((м) => !м.для_чата);
    const вариант = (м) => создать("option", { value: м.id, текст: м.id });
    const группы = [создать("optgroup", { label: `Для чата (${чат.length})` }, ...чат.map(вариант))];
    if (другие.length) группы.push(создать("optgroup", { label: "Другие (эмбеддинги, речь…)" }, ...другие.map(вариант)));
    выбор.replaceChildren(создать("option", { value: "", текст: "— выберите модель —" }), ...группы);
    if (выбранная && !модели.some((м) => м.id === выбранная)) {
      выбор.prepend(создать("option", { value: выбранная, текст: `${выбранная} (нет в списке)` }));
    }
    выбор.value = выбранная || "";
    выбор.disabled = false;
  }

  async function загрузитьМодели() {
    if (загружаются) return;
    загружаются = true;
    const кнопка = $("ии-проверить-ключ");
    кнопка.disabled = true;
    итогКлюча("Проверяю ключ…");
    try {
      const ответ = await запрос("/api/ai/models", {
        method: "POST",
        body: JSON.stringify({ ключ: $("ии-ключ").value.trim() || null, адрес: $("ии-адрес").value.trim() || null }),
      });
      модели = ответ.модели;
      const чат = модели.filter((м) => м.для_чата).length;
      итогКлюча(`✓ Ключ работает. Доступно моделей: ${модели.length} (для чата: ${чат}).`, true);
      нарисоватьМодели($("ии-модель").value || сохранённые.модель);
      if (!$("ии-модель").value) $("ии-модель").focus();
    } catch (e) {
      итогКлюча(`✕ ${e.message}`, false);
    } finally {
      загружаются = false;
      кнопка.disabled = false;
    }
  }

  async function загрузить() {
    try {
      сохранённые = await запрос("/api/ai");
      заполнить();
      // Ключ уже есть — сразу подтянуть список моделей
      if (сохранённые.есть_ключ && !модели.length) загрузитьМодели();
    } catch (e) {
      статус(`Не удалось загрузить настройки ИИ: ${e.message}`, true);
    }
  }

  async function сохранить() {
    const кнопка = $("ии-сохранить");
    кнопка.disabled = true;
    try {
      const ключ = $("ии-ключ").value.trim();
      сохранённые = await запрос("/api/ai", {
        method: "PUT",
        body: JSON.stringify({
          ии: {
            включён: $("ии-включён").getAttribute("aria-checked") === "true",
            ...(ключ ? { ключ } : {}),
            модель: $("ии-модель").value,
            температура: Number($("ии-температура").value),
            длина,
            история: Number($("ии-история").value),
            характер: $("ии-характер").value,
            адрес: $("ии-адрес").value.trim() || сохранённые.по_умолчанию.адрес,
          },
        }),
      });
      заполнить();
      статус(сохранённые.подключён ? "Сохранено. ИИ подключён к чату." : "Сохранено.");
      document.dispatchEvent(new CustomEvent("mizuyori:ии-изменён", { detail: сохранённые }));
    } catch (e) {
      статус(`Не сохранилось: ${e.message}`, true);
    } finally {
      кнопка.disabled = false;
    }
  }

  async function проверитьОтвет() {
    const кнопка = $("ии-проверить");
    кнопка.disabled = true;
    статус("Спрашиваю модель…");
    try {
      const ответ = await запрос("/api/ai/test", { method: "POST" });
      const время = ответ.секунд < 1 ? "меньше секунды" : `${ответ.секунд} с`;
      статус(`✓ Модель ответила за ${время}: «${ответ.ответ}»`);
    } catch (e) {
      статус(`✕ ${e.message}`, true);
    } finally {
      кнопка.disabled = false;
    }
  }

  // Включение: без ключа и модели не даём включить
  $("ии-включён").addEventListener("click", () => {
    const станет = $("ии-включён").getAttribute("aria-checked") !== "true";
    if (станет && !($("ии-ключ").value.trim() || сохранённые?.есть_ключ)) {
      итогКлюча("Сначала вставьте ключ и нажмите «Проверить».", false);
      $("ии-ключ").focus();
      return;
    }
    if (станет && !$("ии-модель").value) {
      итогКлюча("Выберите модель из списка.", false);
      return;
    }
    $("ии-включён").setAttribute("aria-checked", String(станет));
  });

  // Выбрали модель впервые — сразу включаем
  $("ии-модель").addEventListener("change", () => {
    if ($("ии-модель").value && !сохранённые?.модель) $("ии-включён").setAttribute("aria-checked", "true");
  });

  $("ии-показать-ключ").addEventListener("click", () => {
    const поле = $("ии-ключ");
    поле.type = поле.type === "password" ? "text" : "password";
  });
  $("ии-ключ").addEventListener("keydown", (с) => { if (с.key === "Enter") загрузитьМодели(); });
  // Вставили ключ — сразу проверяем
  $("ии-ключ").addEventListener("paste", () => setTimeout(загрузитьМодели, 50));
  $("ии-проверить-ключ").addEventListener("click", загрузитьМодели);
  $("ии-температура").addEventListener("input", обновитьЗначения);
  $("ии-история").addEventListener("input", обновитьЗначения);
  $("ии-сохранить").addEventListener("click", сохранить);
  $("ии-проверить").addEventListener("click", проверитьОтвет);
  $("ии-удалить-ключ").addEventListener("click", async () => {
    if (!confirm("Удалить сохранённый ключ cloud.ru? ИИ отключится.")) return;
    try {
      сохранённые = await запрос("/api/ai", { method: "PUT", body: JSON.stringify({ ии: { удалить_ключ: true, включён: false } }) });
      модели = [];
      заполнить();
      итогКлюча("Ключ удалён.");
      document.dispatchEvent(new CustomEvent("mizuyori:ии-изменён", { detail: сохранённые }));
    } catch (e) {
      статус(e.message, true);
    }
  });

  document.addEventListener("mizuyori:настройки-ии", () => { статус(""); загрузить(); });
}
