"use strict";

// =============================================================================
// «Работа» → «Агенты»: семь помощников отдела главного механика.
// У каждого — уровень, свои замечания по вашим данным, память (правила, приёмы, частые замечания),
// история решений и доска записок (всё это открывается в окне агента). Они сами обходят данные
// в фоне раз в несколько часов и учатся на своём опыте. Старший инженер пишет служебные записки.
// =============================================================================
window.рисоватьАгентовРаботы = async function (место, тост, выбрать) {
  const данные = await запрос("/api/work-agents");
  const звёзды = (н) => "★".repeat(н) + "☆".repeat(Math.max(0, 5 - н));
  const ВАЖНО = { 2: "срочно", 1: "внимание", 0: "к сведению" };

  function значок(а) {
    const NS = "http://www.w3.org/2000/svg";
    const э = document.createElementNS(NS, "svg");
    э.setAttribute("viewBox", "0 0 24 24"); э.setAttribute("class", "агент-значок"); э.setAttribute("aria-hidden", "true");
    for (const [к, з] of Object.entries({ fill: "none", stroke: "currentColor", "stroke-width": "1.8", "stroke-linecap": "round", "stroke-linejoin": "round" })) э.setAttribute(к, з);
    const п = document.createElementNS(NS, "path");
    п.setAttribute("d", window.ЗНАЧКИ_АГЕНТОВ?.[а.значок] || "");
    э.append(п);
    э.style.cssText = "width:36px;height:36px;flex:none";
    return э;
  }

  async function проверить(а, кнопка) {
    кнопка.disabled = true;
    try {
      const р = await запрос(`/api/work-agents/${encodeURIComponent(а.ключ)}/run`, { method: "POST" });
      тост(р.новый_приём ? `${а.имя}: записал новый приём — ${р.новый_приём}` : `${а.имя}: замечаний ${р.замечаний}`);
    } catch (е) { тост(е.message); }
    window.рисоватьАгентовРаботы(место, тост, выбрать);
  }

  function запискаИнженера() {
    const тема = создать("input", { type: "text", placeholder: "Тема, например: просрочено ТО у ГАЗели", maxlength: 200 });
    const пояснение = создать("textarea", { rows: 3, placeholder: "Что важно учесть (необязательно). Без этого возьму замечания агентов.", maxlength: 1500 });
    const кому = создать("input", { type: "text", placeholder: "Кому (необязательно)", maxlength: 200 });
    const кнопка = создать("button", { type: "submit", класс: "кнопка", текст: "Написать черновик записки" });
    const форма = создать("form", { класс: "аг-записка" }, тема, пояснение, кому, кнопка);
    форма.addEventListener("submit", async (с) => {
      с.preventDefault();
      if (!тема.value.trim()) { тост("Укажите тему записки."); return; }
      кнопка.disabled = true;
      try {
        await запрос("/api/work-agents/memo", { method: "POST", headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ тема: тема.value, пояснение: пояснение.value, кому: кому.value }) });
        тост("Черновик записки готов — он в «Служебных записках».");
        выбрать("записки");
      } catch (е) { тост(е.message); кнопка.disabled = false; }
    });
    return форма;
  }

  function карточка(а) {
    const важных = а.замечания.filter((н) => н.важно >= 1).length;
    const список = а.замечания.length
      ? создать("ul", { класс: "аг-замечания" }, ...а.замечания.slice(0, 8).map((н) =>
          создать("li", { класс: `в${н.важно}`, title: ВАЖНО[н.важно], текст: н.текст })))
      : создать("p", { класс: "аг-порядок", текст: "Замечаний нет — всё в порядке." });
    const кнопки = создать("div", { класс: "аг-кнопки" },
      создать("button", { type: "button", класс: "кнопка", текст: "Проверить сейчас", onclick: (с) => проверить(а, с.currentTarget) }),
      создать("button", { type: "button", класс: "кнопка", текст: "Память и история", onclick: () => window.открытьАгента?.(а.ключ) }));
    return создать("article", { класс: "аг-карта" },
      создать("div", { класс: "аг-карта-верх" }, значок(а),
        создать("div", {}, создать("h3", { текст: а.имя }), создать("p", { класс: "что", текст: а.что }))),
      создать("div", { класс: "аг-метки" },
        создать("span", { текст: `Уровень ${а.уровень} ${звёзды(а.уровень)}` }),
        создать("span", { текст: `Опыт ${а.опыт}` }),
        создать("span", { текст: `В памяти ${а.заметок}` }),
        создать("span", { текст: важных ? `Замечаний: ${важных}` : "Всё хорошо" }),
        ...(а.записок ? [создать("span", { текст: `Записок: ${а.записок}` })] : [])),
      список,
      ...(а.ключ === "инженер" ? [запискаИнженера()] : []),
      кнопки);
  }

  место.replaceChildren(создать("div", { класс: "аг-раб" },
    создать("div", { класс: "аг-раб-шапка" },
      создать("h2", { текст: "Агенты" }),
      создать("p", { текст: `Каждый агент помнит свой опыт, сам обходит ваши данные раз в несколько часов и учится${данные.ии_подключён ? " (ИИ подключён — раз в сутки записывают себе новые приёмы)" : " (подключите ИИ в настройках — тогда они ещё и пишут себе приёмы)"}. Свои правила агенту можно записать в «Памяти и истории».` })),
    ...данные.агенты.map(карточка)));
};
