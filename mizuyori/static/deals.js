  function нарисоватьНеделю() {
    нарисоватьФильтры($("неделя-фильтры"));
    const сегодня = сдвиг(0);
    const дни = Array.from({ length: 7 }, (_, i) => сдвиг(i, неделя));
    const опции = { day: "numeric", month: "long" };
    $("неделя-даты").textContent =
      `${изISO(дни[0]).toLocaleDateString("ru-RU", опции)} — ${изISO(дни[6]).toLocaleDateString("ru-RU", опции)}`;
    const все = видимые();
    const колонки = [];
    // просроченные — отдельной колонкой, если смотрим текущую неделю
    const просрочено = все.filter((з) => !з.готово && з.срок && з.срок < сегодня && з.срок < дни[0]);
    if (просрочено.length && дни.includes(сегодня)) {
      колонки.push(колонка("просрочено", "Просрочено", просрочено, { класс: "просроченная" }));
    }
    for (const день of дни) {
      const задачиДня = все.filter((з) => з.срок === день)
        .sort((а, б) => а.готово - б.готово || б.id - а.id);
      const дата = изISO(день);
      const к = колонка(`день-${день}`, дата.toLocaleDateString("ru-RU", { weekday: "short" }), задачиДня, {
        класс: `${день === сегодня ? "сегодняшняя" : ""} ${день < сегодня ? "прошедшая" : ""} ${дата.getDay() % 6 === 0 ? "выходная" : ""}`,
        подпись: дата.toLocaleDateString("ru-RU", { day: "numeric", month: "short" }),
      });
      приёмник(к, () => ({ срок: день }));
      быстроеДобавление(к, { срок: день });
      колонки.push(к);
    }
    const без = все.filter((з) => !з.срок && !з.готово).sort((а, б) => б.id - а.id);
    const к = колонка("без-срока", "Без срока", без, { класс: "без-срока" });
    приёмник(к, () => ({ срок: null }));
    быстроеДобавление(к, { срок: null });
    колонки.push(к);
    $("неделя").replaceChildren(...колонки);
  }

