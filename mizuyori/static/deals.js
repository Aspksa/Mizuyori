  function нарисоватьДоску() {
    нарисоватьФильтры($("доска-фильтры"));
    const сегодня = сдвиг(0), завтра = сдвиг(1), черезНеделю = сдвиг(7);
    const поСроку = (а, б) => (а.срок || "9999").localeCompare(б.срок || "9999") || б.id - а.id;
    const все = видимые();
    const открытые = все.filter((з) => !з.готово).sort(поСроку);
    const группы = {
      просрочено: открытые.filter((з) => з.срок && з.срок < сегодня),
      сегодня: открытые.filter((з) => з.срок === сегодня),
      завтра: открытые.filter((з) => з.срок === завтра),
      неделя: открытые.filter((з) => з.срок > завтра && з.срок <= черезНеделю),
      позже: открытые.filter((з) => з.срок > черезНеделю),
      "без-срока": открытые.filter((з) => !з.срок),
      выполнено: все.filter((з) => з.готово).sort((а, б) => б.id - а.id).slice(0, 30),
    };
    const описание = [
      ["просрочено", "Просрочено", null, "просроченная"],
      ["сегодня", "Сегодня", () => ({ срок: сегодня, готово: false })],
      ["завтра", "Завтра", () => ({ срок: завтра, готово: false })],
      ["неделя", "На неделе", (з) => ({ срок: з.срок > завтра && з.срок <= черезНеделю ? з.срок : сдвиг(2), готово: false })],
      ["позже", "Позже", (з) => ({ срок: з.срок > черезНеделю ? з.срок : сдвиг(8), готово: false })],
      ["без-срока", "Без срока", () => ({ срок: null, готово: false })],
      ["выполнено", "Выполнено", (з) => (з.готово ? null : { готово: true }), "выполненная"],
    ];
    const колонки = описание
      .filter(([ключ]) => ключ !== "просрочено" || группы.просрочено.length)
      .map(([ключ, название, куда, класс]) => {
        const к = колонка(ключ, название, группы[ключ], { класс: класс || "" });
        if (куда) приёмник(к, куда);
        const срокНовой = { сегодня, завтра, неделя: сдвиг(2), позже: сдвиг(8), "без-срока": null }[ключ];
        if (срокНовой !== undefined) быстроеДобавление(к, { срок: срокНовой });
        return к;
      });
    $("доска").replaceChildren(...колонки);
  }

