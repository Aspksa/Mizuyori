  // Окно правки задачи
  // =========================================================================

  const окно = $("окно-задачи");
  let правка = null;

  function открытьПравку(задача) {
    правка = задача;
    $("задача-текст-окна").value = задача.текст;
    $("задача-срок-окна").value = задача.срок || "";
    $("задача-список-окна").replaceChildren(
      создать("option", { value: "", текст: "Без списка" }),
      ...списки.map((с) => создать("option", { value: String(с.id), текст: `${с.значок} ${с.название}` })));
    $("задача-список-окна").value = задача.список_id ? String(задача.список_id) : "";
    $("задача-цель-окна").replaceChildren(
      создать("option", { value: "", текст: "Без цели" }),
      ...цели.filter((ц) => ц.статус !== "отменена" || ц.id === задача.цель_id)
        .map((ц) => создать("option", { value: String(ц.id), текст: `🎯 ${ц.имя}` })));
    $("задача-цель-окна").value = задача.цель_id ? String(задача.цель_id) : "";
    $("задача-готово-окна").checked = задача.готово;
    окно.hidden = false;
    $("задача-текст-окна").focus();
  }
  function закрытьПравку() { окно.hidden = true; правка = null; }

  $("быстрые-сроки").addEventListener("click", (с) => {
    const к = с.target.closest("button[data-дней]");
    if (!к) return;
    const д = к.dataset.дней;
    $("задача-срок-окна").value = д === "" ? "" : д === "выходные" ? выходные() : сдвиг(Number(д));
  });
  $("форма-задачи").addEventListener("submit", async (с) => {
    с.preventDefault();
    if (!правка) return;
    const текст = $("задача-текст-окна").value.trim();
    if (!текст) { $("задача-текст-окна").focus(); return; }
    try {
      await изменить(правка, {
        текст,
        срок: $("задача-срок-окна").value || null,
        список_id: $("задача-список-окна").value ? Number($("задача-список-окна").value) : null,
        цель_id: $("задача-цель-окна").value ? Number($("задача-цель-окна").value) : null,
        готово: $("задача-готово-окна").checked,
      });
      закрытьПравку();
    } catch (e) { сообщить(e.message); }
  });
  $("удалить-задачу-окна").addEventListener("click", async () => {
    if (!правка || !confirm("Удалить задачу?")) return;
    try {
      await запрос(`/api/tasks/${правка.id}`, { method: "DELETE" });
      закрытьПравку();
      обновитьЗадачи();
    } catch (e) { сообщить(e.message); }
  });
  $("закрыть-задачу").addEventListener("click", закрытьПравку);
  $("отмена-задачи").addEventListener("click", закрытьПравку);
  окно.addEventListener("click", (с) => { if (с.target === окно) закрытьПравку(); });
  document.addEventListener("keydown", (с) => { if (с.key === "Escape" && !окно.hidden) закрытьПравку(); });
  $("задача-текст-окна").addEventListener("keydown", (с) => {
    if (с.key === "Enter" && !с.shiftKey) { с.preventDefault(); $("форма-задачи").requestSubmit(); }
  });

  // ---- Короткие сообщения ----
  let таймер;
  function сообщить(текст) {
    let место = document.querySelector(".тост");
    if (!место) { место = создать("div", { класс: "тост", role: "status" }); document.body.append(место); }
    место.textContent = текст;
    место.classList.add("виден");
    clearTimeout(таймер);
    таймер = setTimeout(() => место.classList.remove("виден"), 3000);
  }

