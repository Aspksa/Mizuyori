  function кольцо(доля, текст) {
    const длина = 2 * Math.PI * 26;
    const svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    svg.setAttribute("viewBox", "0 0 64 64");
    svg.setAttribute("class", "кольцо-цели");
    svg.innerHTML = `<circle class="фон-кольца" cx="32" cy="32" r="26"/>` +
      `<circle class="кольцо" cx="32" cy="32" r="26" style="stroke-dasharray:${длина * доля} ${длина}"/>`;
    return создать("div", { класс: "прогресс-цели" }, svg, создать("span", { текст }));
  }

  function нарисоватьЦели() {
    const порядок = { активна: 0, "": 0, достигнута: 1, отменена: 2 };
    const отсортированные = [...цели].sort((а, б) => порядок[а.статус] - порядок[б.статус] || а.id - б.id);
    const безЦели = задачи.filter((з) => !з.готово && !з.цель_id).length;

    const карточки = отсортированные.map((ц) => {
      const шаги = задачи.filter((з) => з.цель_id === ц.id).sort((а, б) => а.готово - б.готово || а.id - б.id);
      const сделано = шаги.filter((з) => з.готово).length;
      const доля = шаги.length ? сделано / шаги.length : 0;
      const достигнута = ц.статус === "достигнута";

      const форма = создать("form", { класс: "новый-шаг" },
        создать("input", { type: "text", maxlength: "2000", placeholder: "+ шаг к цели", "aria-label": `Новый шаг к цели «${ц.имя}»` }));
      форма.addEventListener("submit", async (с) => {
        с.preventDefault();
        const текст = форма.firstChild.value.trim();
        if (!текст) return;
        try {
          await запрос("/api/tasks", { method: "POST", body: JSON.stringify({ текст, цель_id: ц.id }) });
          обновитьЗадачи();
        } catch (e) { сообщить(e.message); }
      });

      return создать("article", { класс: `карточка-цели${достигнута ? " достигнута" : ""}${ц.статус === "отменена" ? " отменена" : ""}` },
        создать("div", { класс: "цель-шапка" },
          создать("div", { класс: "цель-заголовок" },
            создать("h3", { текст: `🎯 ${ц.имя}` }),
            ...(ц.причина ? [создать("p", { класс: "цель-зачем", текст: `Зачем: ${ц.причина}` })] : []),
            создать("span", { класс: "статус-цели", текст: ц.статус || "активна" })),
          кольцо(достигнута ? 1 : доля, шаги.length ? `${сделано}/${шаги.length}` : достигнута ? "✓" : "—")),
        создать("ul", { класс: "шаги" }, ...шаги.map((з) => {
          const флажок = создать("button", { type: "button", класс: "флажок-задачи", role: "checkbox",
            "aria-checked": String(з.готово), "aria-label": з.готово ? "Не сделано" : "Сделано" }, значок("M5 12l5 5L20 7"));
          флажок.addEventListener("click", () => изменить(з, { готово: !з.готово }).catch((e) => сообщить(e.message)));
          return создать("li", { класс: з.готово ? "готово" : "" }, флажок,
            создать("button", { type: "button", класс: "текст-шага", onclick: () => открытьПравку(з) },
              создать("span", { класс: "строка-текста" }, создать("span", { класс: "текст-задачи", текст: з.текст })),
              ...(з.срок ? [создать("span", { класс: "срок-шага", текст: подписьСрока(з.срок) })] : [])));
        }),
        ...(шаги.length ? [] : [создать("li", { класс: "пусто-шагов", текст: "Шагов пока нет" })])),
        форма,
        создать("div", { класс: "цель-кнопки" },
          создать("button", { type: "button", класс: "ссылка", текст: достигнута ? "Вернуть в активные" : "Цель достигнута ✓",
            onclick: () => статусЦели(ц, достигнута ? "активна" : "достигнута") }),
          создать("button", { type: "button", класс: "ссылка тихая", текст: "Удалить",
            onclick: () => удалитьЦель(ц) })),
      );
    });

    // Новая цель
    const новая = создать("form", { класс: "карточка-цели новая-цель" },
      создать("h3", { текст: "＋ Новая цель" }),
      создать("input", { type: "text", maxlength: "80", placeholder: "Чего хотите достичь?", "aria-label": "Название цели", required: "" }),
      создать("input", { type: "text", maxlength: "300", placeholder: "Зачем это вам? (необязательно)", "aria-label": "Зачем" }),
      создать("button", { type: "submit", класс: "кнопка главная", текст: "Создать цель" }));
    новая.addEventListener("submit", async (с) => {
      с.preventDefault();
      const [имя, почему] = [...новая.querySelectorAll("input")].map((п) => п.value.trim());
      if (!имя) return;
      try {
        await запрос("/api/goals", { method: "POST", body: JSON.stringify({ имя, почему }) });
        await загрузитьСправочники();
        нарисовать();
      } catch (e) { сообщить(e.message); }
    });

    const подсказка = создать("div", { класс: "цели-подсказка" },
      создать("span", { текст: безЦели ? `Задач без цели: ${безЦели}` : "Все открытые задачи привязаны к целям" }),
      ...(безЦели ? [создать("button", { type: "button", класс: "кнопка второстепенная малая", текст: "🎯 Разложить по целям (ИИ)",
        onclick: async (с) => {
          с.currentTarget.disabled = true;
          с.currentTarget.textContent = "🎯 Думаю…";
          try {
            const итог = await запрос("/api/tasks/link-goals", { method: "POST" });
            сообщить(`Привязано задач: ${итог.привязано}${итог.новых_целей ? `, новых целей: ${итог.новых_целей}` : ""}`);
            await загрузитьСправочники();
            обновитьЗадачи();
          } catch (e) { сообщить(e.message); нарисовать(); }
        } })] : []));

    $("цели-сетка").replaceChildren(подсказка, ...карточки, новая);
  }

  async function статусЦели(ц, статус) {
    try {
      await запрос(`/api/knowledge/entity/${ц.id}`, { method: "PATCH", body: JSON.stringify({ статус }) });
      await загрузитьСправочники();
      нарисовать();
      if (статус === "достигнута") сообщить(`Цель «${ц.имя}» достигнута!`);
    } catch (e) { сообщить(e.message); }
  }
  async function удалитьЦель(ц) {
    if (!confirm(`Удалить цель «${ц.имя}»? Её шаги-задачи останутся, но без цели.`)) return;
    try {
      await запрос(`/api/knowledge/entity/${ц.id}`, { method: "DELETE" });
      await загрузитьСправочники();
      обновитьЗадачи();
    } catch (e) { сообщить(e.message); }
  }

