"use strict";

// ---- Дела: задачи и заметки -----------------------------------------------
{
  const ошибка = $("дела-ошибка");
  let таймерОшибки;

  function показатьОшибку(текст) {
    ошибка.textContent = текст;
    ошибка.hidden = false;
    clearTimeout(таймерОшибки);
    таймерОшибки = setTimeout(() => (ошибка.hidden = true), 4000);
  }

  // ---- Вкладки ----

  const вкладки = { задачи: $("вкладка-задачи"), заметки: $("вкладка-заметки") };
  const разделы = { задачи: $("дела-задачи"), заметки: $("дела-заметки") };

  function открытьВкладку(имя) {
    for (const к of Object.keys(вкладки)) {
      вкладки[к].setAttribute("aria-selected", String(к === имя));
      разделы[к].hidden = к !== имя;
    }
    try { localStorage.setItem("mizuyori.дела.вкладка", имя); } catch {}
  }

  вкладки.задачи.addEventListener("click", () => открытьВкладку("задачи"));
  вкладки.заметки.addEventListener("click", () => открытьВкладку("заметки"));
  try {
    const сохранённая = localStorage.getItem("mizuyori.дела.вкладка");
    if (сохранённая in вкладки) открытьВкладку(сохранённая);
  } catch {}

  // =========================================================================
  // Задачи
  // =========================================================================

  let задачи = [];

  function нарисоватьЗадачи() {
    const осталось = задачи.filter((з) => !з.готово).length;
    const выполнено = задачи.length - осталось;
    $("счёт-задач").textContent = осталось ? String(осталось) : "";
    $("задач-нет").hidden = задачи.length > 0;
    $("задачи-низ").hidden = задачи.length === 0;
    $("задач-осталось").textContent = осталось ? `Осталось: ${осталось}` : "Всё сделано";
    $("убрать-выполненные").hidden = выполнено === 0;
    $("список-задач").replaceChildren(...задачи.map(строкаЗадачи));
  }

  function строкаЗадачи(задача) {
    const флажок = создать("button", {
      type: "button",
      класс: "флажок-задачи",
      role: "checkbox",
      "aria-checked": String(задача.готово),
      "aria-label": задача.готово ? "Отметить как невыполненную" : "Отметить как выполненную",
      onclick: () => изменитьЗадачу(задача, { готово: !задача.готово }),
    }, значок("M5 12l5 5L20 7"));

    const текст = создать("span", { класс: "текст-задачи", текст: задача.текст, title: "Двойной клик — изменить" });
    текст.addEventListener("dblclick", () => редактироватьЗадачу(задача, текст));

    const удалить = создать("button", {
      type: "button",
      класс: "кнопка-значок малая удалить",
      "aria-label": "Удалить задачу",
      onclick: () => удалитьЗадачу(задача),
    }, значок("M6 6l12 12M18 6L6 18"));

    return создать("li", { класс: задача.готово ? "готово" : "" }, флажок, текст, удалить);
  }

  function редактироватьЗадачу(задача, текстЭлемент) {
    const поле = создать("input", { type: "text", класс: "правка", maxlength: "2000", "aria-label": "Текст задачи" });
    поле.value = задача.текст;
    let готово = false;
    const завершить = async (сохранить) => {
      if (готово) return;
      готово = true;
      const новый = поле.value.trim();
      if (сохранить && новый && новый !== задача.текст) await изменитьЗадачу(задача, { текст: новый });
      else нарисоватьЗадачи();
    };
    поле.addEventListener("keydown", (с) => {
      if (с.key === "Enter") завершить(true);
      if (с.key === "Escape") { с.stopPropagation(); завершить(false); }
    });
    поле.addEventListener("blur", () => завершить(true));
    текстЭлемент.replaceWith(поле);
    поле.focus();
    поле.select();
  }

  async function загрузитьЗадачи() {
    try {
      задачи = await запрос("/api/tasks");
      нарисоватьЗадачи();
    } catch (e) {
      показатьОшибку(`Не удалось загрузить задачи: ${e.message}`);
    }
  }

  async function изменитьЗадачу(задача, изменение) {
    try {
      await запрос(`/api/tasks/${задача.id}`, { method: "PATCH", body: JSON.stringify(изменение) });
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
      нарисоватьЗадачи();
    }
  }

  async function удалитьЗадачу(задача) {
    try {
      await запрос(`/api/tasks/${задача.id}`, { method: "DELETE" });
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    }
  }

  $("задача-форма").addEventListener("submit", async (событие) => {
    событие.preventDefault();
    const поле = $("задача-поле");
    const текст = поле.value.trim();
    if (!текст) return;
    try {
      await запрос("/api/tasks", { method: "POST", body: JSON.stringify({ текст }) });
      поле.value = "";
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    }
    поле.focus();
  });

  $("убрать-выполненные").addEventListener("click", async () => {
    const выполненные = задачи.filter((з) => з.готово);
    try {
      for (const з of выполненные) await запрос(`/api/tasks/${з.id}`, { method: "DELETE" });
    } catch (e) {
      показатьОшибку(e.message);
    }
    await загрузитьЗадачи();
  });

  // =========================================================================
  // Заметки
  // =========================================================================

  let заметки = [];
  let открытая = null;  // заметка в редакторе; null — новая

  function заголовокЗаметки(текст) {
    return текст.split("\n").find((с) => с.trim())?.trim() || "Без названия";
  }
  function началоЗаметки(текст) {
    const строки = текст.split("\n").filter((с) => с.trim());
    return строки.slice(1).join(" ").trim();
  }

  function нарисоватьЗаметки() {
    $("счёт-заметок").textContent = заметки.length ? String(заметки.length) : "";
    $("заметок-нет").hidden = заметки.length > 0;
    $("список-заметок").replaceChildren(...заметки.map((заметка) =>
      создать("li", {},
        создать("button", { type: "button", класс: "карточка-заметки", onclick: () => открытьРедактор(заметка) },
          создать("span", { класс: "заголовок-заметки", текст: заголовокЗаметки(заметка.текст) }),
          создать("span", { класс: "начало-заметки", текст: началоЗаметки(заметка.текст) }),
          создать("time", { класс: "когда", текст: дата(заметка.изменено) }),
        ))));
  }

  async function загрузитьЗаметки() {
    try {
      заметки = await запрос("/api/notes");
      нарисоватьЗаметки();
    } catch (e) {
      показатьОшибку(`Не удалось загрузить заметки: ${e.message}`);
    }
  }

  function открытьРедактор(заметка) {
    открытая = заметка;
    $("заметки-список-вид").hidden = true;
    $("заметка-редактор").hidden = false;
    $("заметка-удалить").hidden = !заметка;
    const поле = $("заметка-поле");
    поле.value = заметка ? заметка.текст : "";
    поле.focus();
  }

  function закрытьРедактор() {
    открытая = null;
    $("заметка-редактор").hidden = true;
    $("заметки-список-вид").hidden = false;
  }

  $("новая-заметка").addEventListener("click", () => открытьРедактор(null));
  $("заметка-отмена").addEventListener("click", закрытьРедактор);

  $("заметка-редактор").addEventListener("submit", async (событие) => {
    событие.preventDefault();
    const текст = $("заметка-поле").value.trim();
    if (!текст) { показатьОшибку("Заметка пустая."); return; }
    try {
      if (открытая) {
        await запрос(`/api/notes/${открытая.id}`, { method: "PATCH", body: JSON.stringify({ текст }) });
      } else {
        await запрос("/api/notes", { method: "POST", body: JSON.stringify({ текст }) });
      }
      закрытьРедактор();
      await загрузитьЗаметки();
    } catch (e) {
      показатьОшибку(e.message);
    }
  });

  // Ctrl+Enter в заметке — сохранить, Esc — отмена
  $("заметка-поле").addEventListener("keydown", (событие) => {
    if (событие.key === "Enter" && (событие.ctrlKey || событие.metaKey)) {
      $("заметка-редактор").requestSubmit();
    }
    if (событие.key === "Escape") { событие.stopPropagation(); закрытьРедактор(); }
  });

  $("заметка-удалить").addEventListener("click", async () => {
    if (!открытая || !confirm("Удалить заметку?")) return;
    try {
      await запрос(`/api/notes/${открытая.id}`, { method: "DELETE" });
      закрытьРедактор();
      await загрузитьЗаметки();
    } catch (e) {
      показатьОшибку(e.message);
    }
  });

  загрузитьЗадачи();
  загрузитьЗаметки();
}
