"use strict";

// ---- Дела: задачи и заметки -----------------------------------------------
//
// Задачи связаны с календарём через события на document:
//   «mizuyori:задачи»     — задачи загрузились (календарь ставит точки на дни);
//   «mizuyori:день»       — выбран день (или null — показать все дни);
//   «mizuyori:новый-день» — наступила полночь (группы «Сегодня/Завтра» сдвигаются).
{
  const ошибка = $("дела-ошибка");
  let таймерОшибки;

  function показатьОшибку(текст) {
    ошибка.textContent = текст;
    ошибка.hidden = false;
    clearTimeout(таймерОшибки);
    таймерОшибки = setTimeout(() => (ошибка.hidden = true), 4000);
  }

  function запомнить(ключ, значение) {
    try { localStorage.setItem(`mizuyori.${ключ}`, JSON.stringify(значение)); } catch {}
  }
  function вспомнить(ключ, поУмолчанию) {
    try {
      const з = localStorage.getItem(`mizuyori.${ключ}`);
      return з === null ? поУмолчанию : JSON.parse(з);
    } catch { return поУмолчанию; }
  }

  const безАнимаций = () => matchMedia("(prefers-reduced-motion: reduce)").matches;
  const пауза = (мс) => new Promise((готово) => setTimeout(готово, мс));

  // ---- Вкладки ----

  const вкладки = { задачи: $("вкладка-задачи"), заметки: $("вкладка-заметки") };
  const разделы = { задачи: $("дела-задачи"), заметки: $("дела-заметки") };

  function открытьВкладку(имя) {
    for (const к of Object.keys(вкладки)) {
      вкладки[к].setAttribute("aria-selected", String(к === имя));
      разделы[к].hidden = к !== имя;
    }
    запомнить("дела.вкладка", имя);
  }

  вкладки.задачи.addEventListener("click", () => открытьВкладку("задачи"));
  вкладки.заметки.addEventListener("click", () => открытьВкладку("заметки"));
  {
    const сохранённая = вспомнить("дела.вкладка", "задачи");
    if (сохранённая in вкладки) открытьВкладку(сохранённая);
  }

  // =========================================================================
  // Даты
  // =========================================================================

  const двузначное = (ч) => String(ч).padStart(2, "0");
  const деньISO = (д) => `${д.getFullYear()}-${двузначное(д.getMonth() + 1)}-${двузначное(д.getDate())}`;
  const изISO = (iso) => { const [г, м, д] = iso.split("-").map(Number); return new Date(г, м - 1, д); };
  function сдвиг(дней) { const д = new Date(); д.setDate(д.getDate() + дней); return деньISO(д); }

  function подписьСрока(iso) {
    if (iso === сдвиг(0)) return "Сегодня";
    if (iso === сдвиг(1)) return "Завтра";
    if (iso === сдвиг(-1)) return "Вчера";
    const д = изISO(iso);
    const опции = { weekday: "short", day: "numeric", month: "short" };
    if (д.getFullYear() !== new Date().getFullYear()) опции.year = "numeric";
    return д.toLocaleDateString("ru-RU", опции);
  }
  const сБольшой = (т) => т.charAt(0).toUpperCase() + т.slice(1);
  const длиннаяДата = (iso) => изISO(iso).toLocaleDateString("ru-RU", { weekday: "long", day: "numeric", month: "long" });

  // =========================================================================
  // Задачи
  // =========================================================================

  let задачи = [];
  let списки = [];
  let цели = [];
  let цвета = {};
  let значки = [];
  let фильтрСписка = вспомнить("задачи.список", null);   // null — все списки
  let выбранныйДень = null;                                // «ГГГГ-ММ-ДД» или null
  let правка = null;                                       // id задачи, которую правим
  let выполненныеСвёрнуты = вспомнить("задачи.выполненные-свёрнуты", false);

  const списокПоId = (id) => списки.find((с) => с.id === id);
  const цветСписка = (список) => (список ? цвета[список.цвет] : "transparent");

  // ---- Загрузка ----

  async function загрузитьЦели() {
    try { цели = await запрос("/api/goals"); } catch { цели = []; }
  }
  const цельПоId = (id) => цели.find((ц) => ц.id === id);

  async function загрузитьСписки() {
    const ответ = await запрос("/api/lists");
    списки = ответ.списки;
    цвета = ответ.цвета;
    значки = ответ.значки;
    if (фильтрСписка !== null && !списокПоId(фильтрСписка)) фильтрСписка = null;
  }

  async function загрузитьЗадачи() {
    try {
      [задачи] = await Promise.all([запрос("/api/tasks"), загрузитьЦели()]);
      нарисоватьЗадачи();
      document.dispatchEvent(new CustomEvent("mizuyori:задачи", { detail: задачи }));
    } catch (e) {
      показатьОшибку(`Не удалось загрузить задачи: ${e.message}`);
    }
  }

  async function загрузитьВсё() {
    try {
      await загрузитьСписки();
    } catch (e) {
      показатьОшибку(`Не удалось загрузить списки: ${e.message}`);
    }
    нарисоватьФильтры();
    нарисоватьВыборСписка();
    await загрузитьЗадачи();
  }

  // ---- Фильтр по спискам (фишки сверху) ----

  function нарисоватьФильтры() {
    const фишка = (id, значок, название, цвет) => создать("button", {
      type: "button",
      класс: "фишка",
      role: "radio",
      "aria-checked": String(фильтрСписка === id),
      style: цвет ? `--цвет-списка: ${цвет}` : "",
      onclick: () => {
        фильтрСписка = id;
        запомнить("задачи.список", id);
        нарисоватьФильтры();
        нарисоватьВыборСписка();
        нарисоватьЗадачи();
      },
    }, ...(значок ? [создать("span", { класс: "значок-списка", текст: значок, "aria-hidden": "true" })] : []), название);

    $("фильтры-списков").replaceChildren(
      фишка(null, "", "Все", ""),
      ...списки.map((с) => фишка(с.id, с.значок, с.название, цвета[с.цвет])),
    );
  }

  // Выпадающий список у поля новой задачи
  function нарисоватьВыборСписка() {
    const выбор = $("задача-список");
    выбор.replaceChildren(
      создать("option", { value: "", текст: "Без списка" }),
      ...списки.map((с) => создать("option", { value: String(с.id), текст: `${с.значок} ${с.название}` })),
    );
    выбор.value = фильтрСписка === null ? "" : String(фильтрСписка);
  }

  // ---- Группы по сроку ----

  function группы(видимые) {
    const сегодня = сдвиг(0), завтра = сдвиг(1);
    const поСроку = (а, б) => (а.срок || "9999").localeCompare(б.срок || "9999") || б.id - а.id;
    const открытые = видимые.filter((з) => !з.готово).sort(поСроку);
    const сделанные = видимые.filter((з) => з.готово).sort((а, б) => б.id - а.id);

    if (выбранныйДень) {
      return [
        { ключ: "день", название: сБольшой(длиннаяДата(выбранныйДень)), задачи: открытые },
        { ключ: "выполнено", название: "Выполнено", задачи: сделанные },
      ];
    }
    return [
      { ключ: "просрочено", название: "Просрочено", задачи: открытые.filter((з) => з.срок && з.срок < сегодня) },
      { ключ: "сегодня", название: "Сегодня", задачи: открытые.filter((з) => з.срок === сегодня) },
      { ключ: "завтра", название: "Завтра", задачи: открытые.filter((з) => з.срок === завтра) },
      { ключ: "позже", название: "Позже", задачи: открытые.filter((з) => з.срок && з.срок > завтра) },
      { ключ: "без-срока", название: "Без срока", задачи: открытые.filter((з) => !з.срок) },
      { ключ: "выполнено", название: "Выполнено", задачи: сделанные },
    ];
  }

  function нарисоватьЗадачи() {
    const видимые = задачи.filter((з) =>
      (фильтрСписка === null || з.список_id === фильтрСписка) &&
      (!выбранныйДень || з.срок === выбранныйДень));
    const осталось = видимые.filter((з) => !з.готово).length;

    $("счёт-задач").textContent = String(задачи.filter((з) => !з.готово).length || "");
    $("задач-нет").hidden = видимые.length > 0;
    $("задач-нет").textContent = выбранныйДень ? "На этот день задач нет" : "Задач нет";
    $("задачи-низ").hidden = видимые.length === 0;
    $("задач-осталось").textContent = осталось ? `Осталось: ${осталось}` : "Всё сделано";
    $("убрать-выполненные").hidden = выполненные(видимые).length === 0;

    const блоки = группы(видимые).filter((г) => г.задачи.length).map((г) => {
      const свёрнута = г.ключ === "выполнено" && выполненныеСвёрнуты;
      const шапка = г.ключ === "выполнено"
        ? создать("button", {
            type: "button", класс: "шапка-группы раскрывашка", "aria-expanded": String(!свёрнута),
            onclick: () => {
              выполненныеСвёрнуты = !выполненныеСвёрнуты;
              запомнить("задачи.выполненные-свёрнуты", выполненныеСвёрнуты);
              нарисоватьЗадачи();
            },
          }, значок("M9 6l6 6-6 6"), г.название, создать("span", { класс: "счёт", текст: String(г.задачи.length) }))
        : создать("h3", { класс: "шапка-группы" }, г.название, создать("span", { класс: "счёт", текст: String(г.задачи.length) }));
      return создать("section", { класс: "группа", данные: { группа: г.ключ } },
        шапка,
        ...(свёрнута ? [] : [создать("ul", { класс: "список задачи" }, ...г.задачи.map(строкаЗадачи))]),
      );
    });
    $("группы-задач").replaceChildren(...блоки);
  }

  const выполненные = (видимые) => видимые.filter((з) => з.готово);

  // ---- Строка задачи ----

  function строкаЗадачи(задача) {
    if (правка === задача.id) return редакторЗадачи(задача);
    const список = списокПоId(задача.список_id);
    const сегодня = сдвиг(0);

    const флажок = создать("button", {
      type: "button",
      класс: "флажок-задачи",
      role: "checkbox",
      "aria-checked": String(задача.готово),
      "aria-label": задача.готово ? "Отметить как невыполненную" : "Отметить как выполненную",
    }, значок("M5 12l5 5L20 7"));

    const мета = [];
    if (задача.срок) {
      const просрочена = !задача.готово && задача.срок < сегодня;
      мета.push(создать("span", { класс: `срок${просрочена ? " просрочен" : ""}` },
        значок("M8 3v3M16 3v3M4 9h16M5 5h14a1 1 0 0 1 1 1v13a1 1 0 0 1-1 1H5a1 1 0 0 1-1-1V6a1 1 0 0 1 1-1z"),
        подписьСрока(задача.срок)));
    }
    if (список) {
      мета.push(создать("span", { класс: "метка-списка" }, `${список.значок} ${список.название}`));
    }
    const цель = задача.цель_id && цельПоId(задача.цель_id);
    if (цель) {
      мета.push(создать("span", { класс: "метка-цели", title: цель.причина ? `Зачем: ${цель.причина}` : "Цель" }, `🎯 ${цель.имя}`));
    }

    const тело = создать("button", { type: "button", класс: "тело-задачи", title: "Изменить" },
      // Обёртка нужна, чтобы зачёркивание шло по каждой строке текста, а не по всей ширине
      создать("span", { класс: "строка-текста" }, создать("span", { класс: "текст-задачи", текст: задача.текст })),
      ...(мета.length ? [создать("span", { класс: "мета" }, ...мета)] : []),
    );
    тело.addEventListener("click", () => { правка = задача.id; нарисоватьЗадачи(); });

    const удалить = создать("button", {
      type: "button",
      класс: "кнопка-значок малая удалить",
      "aria-label": "Удалить задачу",
      onclick: () => удалитьЗадачу(задача),
    }, значок("M6 6l12 12M18 6L6 18"));

    const строка = создать("li", {
      класс: `задача${задача.готово ? " готово" : ""}`,
      style: `--цвет-списка: ${цветСписка(список)}`,
    }, флажок, тело, удалить);
    флажок.addEventListener("click", () => отметить(задача, строка, флажок));
    return строка;
  }

  // Отметка с анимацией: галочка рисуется, текст зачёркивается, строка уезжает
  async function отметить(задача, строка, флажок) {
    const станет = !задача.готово;
    флажок.disabled = true;
    const сохранение = запрос(`/api/tasks/${задача.id}`, { method: "PATCH", body: JSON.stringify({ готово: станет }) });

    if (станет && !безАнимаций()) {
      флажок.setAttribute("aria-checked", "true");
      строка.classList.add("готово", "выполняется");
      await пауза(550);
      const высота = строка.offsetHeight;
      await строка.animate(
        [{ height: `${высота}px`, opacity: 1 }, { height: "0px", opacity: 0, paddingTop: "0px", paddingBottom: "0px", borderWidth: "0px" }],
        { duration: 260, easing: "ease-in", fill: "forwards" },
      ).finished;
    }
    try {
      await сохранение;
    } catch (e) {
      показатьОшибку(e.message);
    }
    await загрузитьЗадачи();
  }

  // ---- Правка задачи прямо в списке ----

  function редакторЗадачи(задача) {
    const текст = создать("input", { type: "text", класс: "правка-текст", maxlength: "2000", "aria-label": "Текст задачи" });
    текст.value = задача.текст;
    const срок = создать("input", { type: "date", "aria-label": "Срок" });
    срок.value = задача.срок || "";
    const выбор = создать("select", { "aria-label": "Список" },
      создать("option", { value: "", текст: "Без списка" }),
      ...списки.map((с) => создать("option", { value: String(с.id), текст: `${с.значок} ${с.название}` })));
    выбор.value = задача.список_id === null ? "" : String(задача.список_id);
    const выборЦели = создать("select", { "aria-label": "Цель", класс: "выбор-цели" },
      создать("option", { value: "", текст: "Без цели" }),
      ...цели.filter((ц) => ц.статус !== "отменена" || ц.id === задача.цель_id)
        .map((ц) => создать("option", { value: String(ц.id), текст: `🎯 ${ц.имя}` })),
      создать("option", { value: "новая", текст: "＋ Новая цель…" }));
    выборЦели.value = задача.цель_id ? String(задача.цель_id) : "";
    выборЦели.addEventListener("change", async () => {
      if (выборЦели.value !== "новая") return;
      const имя = prompt("Новая цель (ради чего эта задача):");
      const почему = имя ? prompt("Почему это важно? (можно пропустить)") || "" : "";
      if (!имя?.trim()) { выборЦели.value = задача.цель_id ? String(задача.цель_id) : ""; return; }
      try {
        const цель = await запрос("/api/goals", { method: "POST", body: JSON.stringify({ имя: имя.trim(), почему }) });
        await загрузитьЦели();
        выборЦели.insertBefore(создать("option", { value: String(цель.id), текст: `🎯 ${цель.имя}` }), выборЦели.lastChild);
        выборЦели.value = String(цель.id);
      } catch (e) { показатьОшибку(e.message); }
    });

    const отмена = () => { правка = null; нарисоватьЗадачи(); };
    const форма = создать("form", { класс: "редактор-задачи" },
      текст,
      создать("div", { класс: "строка-опций" }, срок, выбор),
      выборЦели,
      создать("div", { класс: "редактор-кнопки" },
        создать("button", { type: "button", класс: "кнопка второстепенная опасная", текст: "Удалить",
          onclick: () => удалитьЗадачу(задача) }),
        создать("span", { класс: "растяжка" }),
        создать("button", { type: "button", класс: "кнопка второстепенная", текст: "Отмена", onclick: отмена }),
        создать("button", { type: "submit", класс: "кнопка главная", текст: "Сохранить" }),
      ),
    );
    форма.addEventListener("submit", async (событие) => {
      событие.preventDefault();
      const новыйТекст = текст.value.trim();
      if (!новыйТекст) { показатьОшибку("Текст задачи пустой."); return; }
      try {
        await запрос(`/api/tasks/${задача.id}`, {
          method: "PATCH",
          body: JSON.stringify({
            текст: новыйТекст,
            срок: срок.value || null,
            список_id: выбор.value ? Number(выбор.value) : null,
            цель_id: выборЦели.value && выборЦели.value !== "новая" ? Number(выборЦели.value) : null,
          }),
        });
        правка = null;
        await загрузитьЗадачи();
      } catch (e) {
        показатьОшибку(e.message);
      }
    });
    форма.addEventListener("keydown", (событие) => {
      if (событие.key === "Escape") { событие.stopPropagation(); отмена(); }
    });
    setTimeout(() => { текст.focus(); текст.select(); });
    return создать("li", { класс: "задача правится", style: `--цвет-списка: ${цветСписка(списокПоId(задача.список_id))}` }, форма);
  }

  async function удалитьЗадачу(задача) {
    try {
      await запрос(`/api/tasks/${задача.id}`, { method: "DELETE" });
      if (правка === задача.id) правка = null;
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    }
  }

  // ---- Добавление ----

  $("задача-форма").addEventListener("submit", async (событие) => {
    событие.preventDefault();
    const поле = $("задача-поле");
    const текст = поле.value.trim();
    if (!текст) return;
    try {
      await запрос("/api/tasks", {
        method: "POST",
        body: JSON.stringify({
          текст,
          срок: $("задача-срок").value || null,
          список_id: $("задача-список").value ? Number($("задача-список").value) : null,
        }),
      });
      поле.value = "";
      if (!выбранныйДень) $("задача-срок").value = "";
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    }
    поле.focus();
  });

  $("привязать-цели").addEventListener("click", async (с) => {
    const кнопка = с.currentTarget;
    кнопка.disabled = true;
    const было = кнопка.textContent;
    кнопка.textContent = "🎯 Думаю…";
    try {
      const итог = await запрос("/api/tasks/link-goals", { method: "POST" });
      показатьОшибку(итог.привязано || итог.новых_целей
        ? `Привязано задач: ${итог.привязано}${итог.новых_целей ? `, новых целей: ${итог.новых_целей}` : ""}`
        : "Подходящих целей для задач не нашлось");
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    } finally {
      кнопка.disabled = false;
      кнопка.textContent = было;
    }
  });

  $("убрать-выполненные").addEventListener("click", async () => {
    const видимые = задачи.filter((з) =>
      (фильтрСписка === null || з.список_id === фильтрСписка) && (!выбранныйДень || з.срок === выбранныйДень));
    try {
      for (const з of выполненные(видимые)) await запрос(`/api/tasks/${з.id}`, { method: "DELETE" });
    } catch (e) {
      показатьОшибку(e.message);
    }
    await загрузитьЗадачи();
  });

  // ---- Связь с календарём ----

  document.addEventListener("mizuyori:день", (событие) => {
    выбранныйДень = событие.detail;
    правка = null;
    $("выбран-день").hidden = !выбранныйДень;
    if (выбранныйДень) {
      $("выбран-день-текст").textContent = `Задачи на ${длиннаяДата(выбранныйДень)}`;
      $("задача-срок").value = выбранныйДень;
      открытьВкладку("задачи");
      // Клик по дню в календаре на главной — переходим к делам этого дня
      document.dispatchEvent(new CustomEvent("mizuyori:вид-дел", { detail: "список" }));
      if (location.hash !== "#дела" && decodeURIComponent(location.hash) !== "#дела") location.hash = "#дела";
    } else {
      $("задача-срок").value = "";
    }
    нарисоватьЗадачи();
  });

  $("сбросить-день").addEventListener("click", () =>
    document.dispatchEvent(new CustomEvent("mizuyori:день", { detail: null })));

  document.addEventListener("mizuyori:новый-день", () => нарисоватьЗадачи());

  // =========================================================================
  // Окно «Списки задач»
  // =========================================================================

  const окноСписков = $("окно-списков");
  let правкаСписка = null;   // id списка, «новый» или null

  function строкаСписка(список) {
    return создать("li", { класс: "строка-списка", style: `--цвет-списка: ${цвета[список.цвет]}` },
      создать("span", { класс: "кружок-списка", текст: список.значок, "aria-hidden": "true" }),
      создать("span", { класс: "название-списка", текст: список.название }),
      создать("span", { класс: "сколько", текст: String(задачи.filter((з) => з.список_id === список.id && !з.готово).length || "") }),
      создать("button", { type: "button", класс: "кнопка-значок малая", "aria-label": `Изменить список «${список.название}»`,
        onclick: () => { правкаСписка = список.id; нарисоватьСписки(); } },
        значок("M4 20h4L19 9l-4-4L4 16v4zM14 6l4 4")),
      создать("button", { type: "button", класс: "кнопка-значок малая удалить-список", "aria-label": `Удалить список «${список.название}»`,
        onclick: () => удалитьСписок(список) },
        значок("M4 7h16M10 11v6M14 11v6M5 7l1 12a2 2 0 0 0 2 2h8a2 2 0 0 0 2-2l1-12M9 7V4h6v3")),
    );
  }

  function редакторСписка(список) {
    let цвет = список?.цвет || "синий";
    let выбранныйЗначок = список?.значок || "📋";
    const название = создать("input", { type: "text", maxlength: "60", placeholder: "Название списка", "aria-label": "Название списка" });
    название.value = список?.название || "";

    const сеткаЗначков = создать("div", { класс: "сетка-значков", role: "radiogroup", "aria-label": "Значок" });
    const сеткаЦветов = создать("div", { класс: "сетка-цветов", role: "radiogroup", "aria-label": "Цвет" });
    const образец = создать("span", { класс: "кружок-списка большой", "aria-hidden": "true" });

    function обновить() {
      образец.textContent = выбранныйЗначок;
      образец.style.setProperty("--цвет-списка", цвета[цвет]);
      сеткаЗначков.replaceChildren(...значки.map((з) => создать("button", {
        type: "button", role: "radio", "aria-checked": String(з === выбранныйЗначок), текст: з,
        onclick: () => { выбранныйЗначок = з; обновить(); },
      })));
      сеткаЦветов.replaceChildren(...Object.entries(цвета).map(([ключ, hex]) => создать("button", {
        type: "button", role: "radio", "aria-checked": String(ключ === цвет), "aria-label": ключ, title: ключ,
        style: `--цвет-списка: ${hex}`,
        onclick: () => { цвет = ключ; обновить(); },
      })));
    }
    обновить();

    const форма = создать("form", { класс: "редактор-списка" },
      создать("div", { класс: "строка-ввода" }, образец, название),
      создать("span", { класс: "поле-название", текст: "Значок" }), сеткаЗначков,
      создать("span", { класс: "поле-название", текст: "Цвет" }), сеткаЦветов,
      создать("div", { класс: "редактор-кнопки" },
        создать("span", { класс: "растяжка" }),
        создать("button", { type: "button", класс: "кнопка второстепенная", текст: "Отмена",
          onclick: () => { правкаСписка = null; нарисоватьСписки(); } }),
        создать("button", { type: "submit", класс: "кнопка главная", текст: список ? "Сохранить" : "Создать" }),
      ),
    );
    форма.addEventListener("submit", async (событие) => {
      событие.preventDefault();
      const имя = название.value.trim();
      if (!имя) { название.focus(); return; }
      try {
        const тело = JSON.stringify({ название: имя, цвет, значок: выбранныйЗначок });
        if (список) await запрос(`/api/lists/${список.id}`, { method: "PATCH", body: тело });
        else await запрос("/api/lists", { method: "POST", body: тело });
        правкаСписка = null;
        await обновитьСписки();
      } catch (e) {
        показатьОшибку(e.message);
      }
    });
    setTimeout(() => название.focus());
    return создать("li", { класс: "строка-списка правится" }, форма);
  }

  function нарисоватьСписки() {
    const строки = списки.map((с) => (правкаСписка === с.id ? редакторСписка(с) : строкаСписка(с)));
    if (правкаСписка === "новый") строки.push(редакторСписка(null));
    $("списки-тело").replaceChildren(
      строки.length ? создать("ul", { класс: "список-списков" }, ...строки)
                    : создать("p", { класс: "пустой-список", текст: "Списков пока нет" }));
    $("новый-список").closest(".окно-низ").hidden = правкаСписка === "новый";
  }

  async function обновитьСписки() {
    await загрузитьСписки();
    нарисоватьСписки();
    нарисоватьФильтры();
    нарисоватьВыборСписка();
    нарисоватьЗадачи();
  }

  async function удалитьСписок(список) {
    if (!confirm(`Удалить список «${список.название}»? Задачи из него останутся, но без списка.`)) return;
    try {
      await запрос(`/api/lists/${список.id}`, { method: "DELETE" });
      await обновитьСписки();
      await загрузитьЗадачи();
    } catch (e) {
      показатьОшибку(e.message);
    }
  }

  function открытьСписки() {
    правкаСписка = null;
    нарисоватьСписки();
    окноСписков.hidden = false;
    $("новый-список").focus();
  }
  function закрытьСписки() {
    окноСписков.hidden = true;
    $("открыть-списки").focus();
  }

  $("открыть-списки").addEventListener("click", открытьСписки);
  $("закрыть-списки").addEventListener("click", закрытьСписки);
  $("новый-список").addEventListener("click", () => { правкаСписка = "новый"; нарисоватьСписки(); });
  окноСписков.addEventListener("click", (событие) => {
    if (событие.target === окноСписков && правкаСписка === null) закрытьСписки();
  });
  document.addEventListener("keydown", (событие) => {
    if (событие.key !== "Escape" || окноСписков.hidden) return;
    if (правкаСписка !== null) { правкаСписка = null; нарисоватьСписки(); }
    else закрытьСписки();
  });

  // =========================================================================
  // Заметки
  // =========================================================================

  let заметки = [];
  let открытая = null;  // заметка в редакторе; null — новая

  function заголовокЗаметки(текст) {
    return текст.split("\n").find((с) => с.trim())?.trim() || "Без названия";
  }
  function началоЗаметки(текст) {
    const строки = текст.split("\n").filter((с) => с.trim());
    return строки.slice(1).join(" ").trim();
  }

  function нарисоватьЗаметки() {
    $("счёт-заметок").textContent = заметки.length ? String(заметки.length) : "";
    $("заметок-нет").hidden = заметки.length > 0;
    $("список-заметок").replaceChildren(...заметки.map((заметка) =>
      создать("li", {},
        создать("button", { type: "button", класс: "карточка-заметки", onclick: () => открытьРедактор(заметка) },
          создать("span", { класс: "заголовок-заметки", текст: заголовокЗаметки(заметка.текст) }),
          создать("span", { класс: "начало-заметки", текст: началоЗаметки(заметка.текст) }),
          создать("time", { класс: "когда", текст: дата(заметка.изменено) }),
        ))));
  }

  async function загрузитьЗаметки() {
    try {
      заметки = await запрос("/api/notes");
      нарисоватьЗаметки();
    } catch (e) {
      показатьОшибку(`Не удалось загрузить заметки: ${e.message}`);
    }
  }

  function открытьРедактор(заметка) {
    открытая = заметка;
    $("заметки-список-вид").hidden = true;
    $("заметка-редактор").hidden = false;
    $("заметка-удалить").hidden = !заметка;
    const поле = $("заметка-поле");
    поле.value = заметка ? заметка.текст : "";
    поле.focus();
  }

  function закрытьРедактор() {
    открытая = null;
    $("заметка-редактор").hidden = true;
    $("заметки-список-вид").hidden = false;
  }

  $("новая-заметка").addEventListener("click", () => открытьРедактор(null));
  $("заметка-отмена").addEventListener("click", закрытьРедактор);

  $("заметка-редактор").addEventListener("submit", async (событие) => {
    событие.preventDefault();
    const текст = $("заметка-поле").value.trim();
    if (!текст) { показатьОшибку("Заметка пустая."); return; }
    try {
      if (открытая) {
        await запрос(`/api/notes/${открытая.id}`, { method: "PATCH", body: JSON.stringify({ текст }) });
      } else {
        await запрос("/api/notes", { method: "POST", body: JSON.stringify({ текст }) });
      }
      закрытьРедактор();
      await загрузитьЗаметки();
    } catch (e) {
      показатьОшибку(e.message);
    }
  });

  // Ctrl+Enter в заметке — сохранить, Esc — отмена
  $("заметка-поле").addEventListener("keydown", (событие) => {
    if (событие.key === "Enter" && (событие.ctrlKey || событие.metaKey)) {
      $("заметка-редактор").requestSubmit();
    }
    if (событие.key === "Escape") { событие.stopPropagation(); закрытьРедактор(); }
  });

  $("заметка-удалить").addEventListener("click", async () => {
    if (!открытая || !confirm("Удалить заметку?")) return;
    try {
      await запрос(`/api/notes/${открытая.id}`, { method: "DELETE" });
      закрытьРедактор();
      await загрузитьЗаметки();
    } catch (e) {
      показатьОшибку(e.message);
    }
  });

  // ---- Обновить по просьбе других экранов (доска, неделя, цели) ----
  document.addEventListener("mizuyori:обновить-задачи", () => загрузитьЗадачи());
  document.addEventListener("mizuyori:экран", (с) => { if (с.detail === "дела") загрузитьЗадачи(); });

  // ---- Переход из «Мозгов»: открыть задачу, заметку или чат ----

  document.addEventListener("mizuyori:открыть", async (событие) => {
    const { тип, ид } = событие.detail;
    if (тип === "задача") {
      открытьВкладку("задачи");
      if (выбранныйДень) document.dispatchEvent(new CustomEvent("mizuyori:день", { detail: null }));
      фильтрСписка = null;
      запомнить("задачи.список", null);
      нарисоватьФильтры();
      нарисоватьВыборСписка();
      await загрузитьЗадачи();
      правка = ид;
      нарисоватьЗадачи();
      $("группы-задач").querySelector(".правится")?.scrollIntoView({ block: "center" });
    } else if (тип === "заметка") {
      открытьВкладку("заметки");
      await загрузитьЗаметки();
      const заметка = заметки.find((з) => з.id === ид);
      if (заметка) открытьРедактор(заметка);
    } else {
      $("чат-поле").focus();
    }
  });

  загрузитьВсё();
  загрузитьЗаметки();
}
