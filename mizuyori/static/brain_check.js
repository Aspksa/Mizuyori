// «Мозги → Проверка»: путь между точками графа, одиночки, дубли и предложения связей с применением
(() => {
  const экран = $("экран-мозги"), вкладки = $("мозги-вкладки");
  if (!экран || !вкладки) return;
  const кнопка = создать("button", { type: "button", role: "tab", "aria-selected": "false" }, "🔍 Проверка");
  вкладки.append(кнопка);
  const а = создать("input", { type: "text", placeholder: "Откуда: мама, проект…", класс: "список-поиск", autocomplete: "off" });
  const б = создать("input", { type: "text", placeholder: "Куда: подарок, склад…", класс: "список-поиск", autocomplete: "off" });
  const найти = создать("button", { type: "button", класс: "кнопка малая" }, "Как связаны?");
  const итогПути = создать("div", { класс: "проверка-путь" });
  const тело = создать("div", { класс: "список-тело" });
  const слой = создать("div", { класс: "мозги-список", id: "мозги-проверка", hidden: true },
    создать("div", { класс: "список-шапка" }, создать("h2", {}, "Проверка графа")),
    создать("div", { класс: "проверка-форма" }, а, б, найти), итогПути, тело);
  экран.append(слой);

  function показать(да) {
    слой.hidden = !да;
    кнопка.setAttribute("aria-selected", String(да));
    if (да) {
      const список = $("мозги-список");
      if (список) список.hidden = true;
      for (const к of вкладки.querySelectorAll("button")) if (к !== кнопка) к.setAttribute("aria-selected", "false");
      загрузить();
    }
  }
  кнопка.addEventListener("click", () => показать(true));
  вкладки.addEventListener("click", (с) => { const к = с.target.closest("button"); if (к && к !== кнопка) слой.hidden = true, кнопка.setAttribute("aria-selected", "false"); });

  const ТИП = { сущность: "●", факт: "◆", задача: "✓" };
  async function искатьПуть() {
    итогПути.textContent = "";
    if (!а.value.trim() || !б.value.trim()) return;
    let р;
    try { р = await запрос(`/api/brain/path?a=${encodeURIComponent(а.value)}&b=${encodeURIComponent(б.value)}`); }
    catch (e) { итогПути.textContent = e.message; return; }
    if (!р.найден) { итогПути.append(создать("p", { класс: "пусто" }, р.причина)); return; }
    const цепь = создать("div", { класс: "путь-цепь" });
    р.шаги.forEach((ш, и) => {
      if (и) цепь.append(создать("span", { класс: "путь-связь" }, `— ${ш.связь} →`));
      цепь.append(создать("span", { класс: `путь-узел путь-${ш.узел.тип}` }, `${ТИП[ш.узел.тип]} ${ш.узел.текст.slice(0, 60)}`));
    });
    итогПути.append(создать("p", {}, `Шагов: ${р.длина}`), цепь);
  }
  найти.addEventListener("click", искатьПуть);
  for (const п of [а, б]) п.addEventListener("keydown", (с) => { if (с.key === "Enter") искатьПуть(); });

  async function действие(тело_, кнопкаДа) {
    кнопкаДа.disabled = true;
    try { await запрос("/api/brain/apply", { method: "POST", body: JSON.stringify(тело_) }); } catch (e) { кнопкаДа.textContent = e.message; return; }
    document.dispatchEvent(new CustomEvent("mizuyori:экран"));
    загрузить();
  }
  const строка = (текст, ...кнопки) => создать("div", { класс: "проверка-строка" }, создать("span", {}, текст), ...кнопки);
  const действие_кнопка = (подпись, данные) => { const к = создать("button", { type: "button", класс: "кнопка малая" }, подпись); к.addEventListener("click", () => действие(данные, к)); return к; };
  const раздел = (заголовок, строки, пусто) => создать("section", { класс: "проверка-раздел" }, создать("h3", {}, `${заголовок} (${строки.length})`),
    ...(строки.length ? строки : [создать("p", { класс: "пусто" }, пусто)]));

  async function загрузить() {
    тело.textContent = "Проверяю…";
    let ауд, пред;
    try { ауд = await запрос("/api/brain/audit"); } catch (e) { тело.textContent = e.message; return; }
    тело.textContent = "";
    тело.append(
      раздел("Дубли", ауд.дубли.map((д) => строка(`«${д.повтор_текст}» похоже на «${д.основной_текст}» (${Math.round(д.похожесть * 100)}%)`,
        действие_кнопка("Объединить", { действие: "объединить_сущности", а: д.основной, б: д.повтор }))), "Дублей нет."),
      раздел("Одиночки: ни с чем не связаны", ауд.одиночки.map((о) => строка(о.текст,
        действие_кнопка("Убрать", { действие: "удалить_одиночку", а: о.ключ }))), "Одиночек нет."),
      раздел("Цели без задач", ауд.цели_без_задач.map((ц) => строка(ц.текст)), "У всех целей есть шаги."),
    );
    const место = создать("section", { класс: "проверка-раздел" }, создать("h3", {}, "Предложения связей"), создать("p", { класс: "пусто" }, "Считаю по смыслу…"));
    тело.append(место);
    try { пред = await запрос("/api/brain/suggest"); } catch (e) { место.lastChild.textContent = e.message; return; }
    место.lastChild.remove();
    if (!пред.доступно) { место.append(создать("p", { класс: "пусто" }, пред.причина)); return; }
    if (!пред.предложения.length) { место.append(создать("p", { класс: "пусто" }, "Новых связей не нашла.")); return; }
    for (const п of пред.предложения) {
      const кнопки = [];
      if (п.вид === "сущности") { кнопки.push(действие_кнопка("Связать", { действие: "связать", а: п.а, б: п.б })); кнопки.push(действие_кнопка("Объединить", { действие: "объединить_сущности", а: п.а, б: п.б })); }
      else if (п.вид === "факты") кнопки.push(действие_кнопка("Объединить", { действие: "объединить_факты", а: п.а, б: п.б }));
      else кнопки.push(действие_кнопка("Привязать", { действие: "привязать_факт", а: п.а, б: п.б }));
      место.append(строка(`${п.а_текст.slice(0, 60)} ↔ ${п.б_текст.slice(0, 60)} (${Math.round(п.похожесть * 100)}%)`, ...кнопки));
    }
  }
})();
