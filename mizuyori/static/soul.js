  // ---- Рисование ---------------------------------------------------------

  function подогнать() {
    const р = холст.getBoundingClientRect();
    dpr = Math.min(window.devicePixelRatio || 1, 2);
    ширина = р.width; высота = р.height;
    холст.width = Math.max(1, Math.round(ширина * dpr));
    холст.height = Math.max(1, Math.round(высота * dpr));
  }
  new ResizeObserver(() => { if (активна) подогнать(); }).observe(холст);

  // искры, летящие от ядра
  const искры = Array.from({ length: 70 }, () => новаяИскра(true));
  function новаяИскра(случайно = false) {
    return { угол: Math.random() * Math.PI * 2, путь: случайно ? Math.random() : 0,
             скорость: 0.05 + Math.random() * 0.12, размер: 0.6 + Math.random() * 1.6, сдвиг: Math.random() * 10 };
  }
  // пятна внутри ядра
  const пятна = Array.from({ length: 6 }, (_, i) => ({ ф: i * 1.7, с: 0.3 + (i % 3) * 0.17, р: 0.35 + (i % 2) * 0.15 }));

  function цикл(t) {
    if (!активна) { кадр = 0; return; }
    const dt = Math.max(0, Math.min((t - прошлый) / 1000 || 0.016, 0.1));
    прошлый = t;
    время += безАнимаций() ? 0 : dt;
    if (раскрытие < цельРаскрытия) раскрытие = Math.min(1, раскрытие + dt / 1.1);
    if (раскрытие > цельРаскрытия) {
      раскрытие = Math.max(0, раскрытие - dt / 0.38);
      if (раскрытие === 0 && послеУхода) { const г = послеУхода; послеУхода = null; setTimeout(г, 0); }
    }
    const п = 1 - Math.pow(0.02, dt);
    цвет.r += (цель.r - цвет.r) * п; цвет.g += (цель.g - цвет.g) * п; цвет.b += (цель.b - цвет.b) * п;
    нарисовать(dt);
    кадр = requestAnimationFrame(цикл);
  }

  function нарисовать(dt) {
    к.setTransform(dpr, 0, 0, dpr, 0, 0);
    к.clearRect(0, 0, ширина, высота);
    const cx = ширина / 2, cy = высота / 2;
    const R0 = Math.max(26, Math.min(ширина / 7, высота * 0.13));
    const е = 1 - Math.pow(1 - раскрытие, 3);                 // плавное раскрытие
    const R = R0 * (0.25 + 0.75 * е);
    const орб = е;                                            // орбиты вырастают из ядра
    const темп = 0.6 + энергия * 0.9;                        // чем больше энергии — тем чаще дыхание
    const вдох = (Math.sin(время * темп * 1.6) + 1) / 2;
    const Rд = R * (1 + 0.06 * вдох);

    // ореол
    let г = к.createRadialGradient(cx, cy, 0, cx, cy, R * 4.2);
    г.addColorStop(0, цв(0.22 + 0.08 * вдох)); г.addColorStop(0.4, цв(0.07)); г.addColorStop(1, цв(0));
    к.fillStyle = г; к.fillRect(0, 0, ширина, высота);

    // орбиты: дальняя половина — за ядром
    const слова = [];
    for (const о of ОРБИТЫ) {
      const пункты = (данные && (правка || данные.душа)[о.раздел]) || [];
      const ро = R0 * о.радиус * орб;
      const ярко = (подсвечено ? (подсвечено === о.раздел ? 1 : 0.25) : 1) * е;
      к.beginPath();
      к.ellipse(cx, cy, ро, ро * о.наклон, 0, 0, Math.PI * 2);
      к.strokeStyle = цв(0.16 * ярко); к.lineWidth = 1; к.stroke();
      пункты.forEach((текст, i) => {
        const у = время * о.скорость + (i / пункты.length) * Math.PI * 2;
        const глубина = Math.sin(у);                         // -1 сзади, 1 спереди
        слова.push({ x: cx + Math.cos(у) * ро, y: cy + глубина * ро * о.наклон, глубина, текст, о, ярко,
                     масштаб: Math.min(1, Math.max(0.72, R0 / 95)) });
      });
    }
    нарисоватьВажное(cx, cy, R0, Rд, Math.max(0, (раскрытие - 0.35) / 0.65));
    const сзади = слова.filter((с) => с.глубина < 0), спереди = слова.filter((с) => с.глубина >= 0);
    сзади.forEach(слово);

    // искры
    к.globalCompositeOperation = "lighter";
    for (const и of искры) {
      и.путь += и.скорость * dt * (0.5 + энергия);
      if (и.путь > 1) Object.assign(и, новаяИскра());
      const д = Rд * (0.9 + и.путь * 2.6);
      const x = cx + Math.cos(и.угол + время * 0.05) * д;
      const y = cy + Math.sin(и.угол + время * 0.05) * д * 0.8 + Math.sin(время + и.сдвиг) * 3;
      к.fillStyle = цв((1 - и.путь) * 0.8);
      к.beginPath(); к.arc(x, y, и.размер * (1 - и.путь * 0.5), 0, Math.PI * 2); к.fill();
    }

    // ядро
    г = к.createRadialGradient(cx, cy, 0, cx, cy, Rд * 1.6);
    г.addColorStop(0, "rgba(255,255,255,0.95)");
    г.addColorStop(0.25, цв(0.9)); г.addColorStop(0.6, цв(0.35)); г.addColorStop(1, цв(0));
    к.fillStyle = г; к.beginPath(); к.arc(cx, cy, Rд * 1.6, 0, Math.PI * 2); к.fill();

    // переливы внутри
    for (const п of пятна) {
      const x = cx + Math.cos(время * п.с + п.ф) * Rд * п.р;
      const y = cy + Math.sin(время * п.с * 1.3 + п.ф) * Rд * п.р;
      const гп = к.createRadialGradient(x, y, 0, x, y, Rд * 0.7);
      гп.addColorStop(0, "rgba(255,255,255,0.18)"); гп.addColorStop(1, "rgba(255,255,255,0)");
      к.fillStyle = гп; к.beginPath(); к.arc(x, y, Rд * 0.7, 0, Math.PI * 2); к.fill();
    }
    к.globalCompositeOperation = "source-over";

    // кольца дыхания
    for (let i = 0; i < 3; i++) {
      const ф = ((время * темп * 0.35 + i / 3) % 1);
      к.beginPath(); к.arc(cx, cy, Rд * (1.1 + ф * 1.8), 0, Math.PI * 2);
      к.strokeStyle = цв(0.35 * (1 - ф)); к.lineWidth = 1.5; к.stroke();
    }

    спереди.forEach(слово);

    // подписи орбит
    к.font = "600 10px ui-monospace, Consolas, monospace";
    к.textAlign = "center"; к.textBaseline = "middle";
    for (const о of ОРБИТЫ) {
      const ярко = (подсвечено ? (подсвечено === о.раздел ? 1 : 0.3) : 0.7) * е;
      к.fillStyle = цв(0.6 * ярко);
      к.fillText(ПОДПИСИ[о.раздел].toUpperCase(), cx, cy + R0 * о.радиус * орб * о.наклон + 9);
    }
    подсказкаВажного();
  }

  // ---- Нити к важному: цели, проекты, люди -----------------------------------

  const ЦВЕТА_ВАЖНОГО = { цель: "#f5c451", проект: "#3ecf9a", человек: "#ff8fb1" };
  const ЗНАЧКИ_ВАЖНОГО = { цель: "🎯", проект: "📁", человек: "👤" };
  const ключ = (т) => String(т).toLowerCase().replaceAll("ё", "е").trim();
  const мнениеО = (имя) => данные?.мнения.список.find((м) => ключ(м.о) === ключ(имя));

  function нарисоватьВажное(cx, cy, R0, Rд, видно) {
    узлыВажного = [];
    const важное = данные?.важное || [];
    if (!важное.length || видно <= 0) return;
    const рх = Math.min(R0 * 3.55, ширина / 2 - 70), ру = Math.min(R0 * 2.5, высота / 2 - 60);
    const максВес = Math.max(...важное.map((и) => и.вес), 1);
    важное.forEach((и, i) => {
      const угол = -Math.PI / 2 + (i / важное.length) * Math.PI * 2 + 0.35 + Math.sin(время * 0.1 + i) * 0.03;
      const д = 0.55 + 0.45 * видно;
      const x = cx + Math.cos(угол) * рх * д, y = cy + Math.sin(угол) * ру * д;
      const сила = 0.35 + 0.65 * (и.вес / максВес);
      const с = rgb(ЦВЕТА_ВАЖНОГО[и.тип]);
      const над = мышь && Math.hypot(мышь.x - x, мышь.y - y) < 16;
      // нить: изгиб к центру, по ней бегут огоньки
      const мx = (cx + x) / 2 + (cy - y) * 0.18, мy = (cy + y) / 2 + (x - cx) * 0.18;
      к.beginPath(); к.moveTo(cx, cy); к.quadraticCurveTo(мx, мy, x, y);
      к.strokeStyle = цв((над ? 0.6 : 0.22) * сила * видно, с); к.lineWidth = над ? 2 : 1 + сила; к.stroke();
      к.globalCompositeOperation = "lighter";
      for (let н = 0; н < 2; н++) {
        const t = (время * (0.18 + сила * 0.15) + i * 0.37 + н / 2) % 1;
        const px = (1 - t) ** 2 * cx + 2 * (1 - t) * t * мx + t * t * x;
        const py = (1 - t) ** 2 * cy + 2 * (1 - t) * t * мy + t * t * y;
        к.fillStyle = цв(0.85 * Math.sin(t * Math.PI) * видно, с);
        к.beginPath(); к.arc(px, py, 1.6 + сила, 0, Math.PI * 2); к.fill();
      }
      // узел
      const г = к.createRadialGradient(x, y, 0, x, y, 18);
      г.addColorStop(0, цв(0.55 * видно, с)); г.addColorStop(1, цв(0, с));
      к.fillStyle = г; к.beginPath(); к.arc(x, y, 18, 0, Math.PI * 2); к.fill();
      к.globalCompositeOperation = "source-over";
      к.beginPath(); к.arc(x, y, над ? 7 : 5 + сила * 1.5, 0, Math.PI * 2);
      к.fillStyle = цв(видно, с); к.fill();
      if (и.тип === "цель" && и.шагов) {            // кольцо прогресса цели
        к.beginPath(); к.arc(x, y, 10, -Math.PI / 2, -Math.PI / 2 + (и.сделано / и.шагов) * Math.PI * 2);
        к.strokeStyle = цв(0.9 * видно, с); к.lineWidth = 2; к.stroke();
      }
      // подпись
      const подпись = `${ЗНАЧКИ_ВАЖНОГО[и.тип]} ${и.имя.length > 22 ? и.имя.slice(0, 21) + "…" : и.имя}`
        + (и.тип === "цель" && и.шагов ? ` ${и.сделано}/${и.шагов}` : "") + (мнениеО(и.имя) ? " 💬" : "");
      к.font = `${над ? 600 : 500} 12px system-ui, "Segoe UI", sans-serif`;
      к.textAlign = "center"; к.textBaseline = "top";
      к.fillStyle = `rgba(255,255,255,${(над ? 0.95 : 0.7) * видно})`;
      к.fillText(подпись, x, y + 15);
      узлыВажного.push({ x, y, и, над });
    });
  }

  function подсказкаВажного() {
    const у = узлыВажного.find((у) => у.над);
    холст.style.cursor = у ? "pointer" : "";
    if (!у) return;
    const м = мнениеО(у.и.имя);
    const строки = м ? [м.мнение, м.почему ? `— ${м.почему}` : ""].filter(Boolean)
                     : [у.и.тип === "цель" ? "Цель. Мнения пока нет — «Обновить» в карточке «Мнения»." : "Важно для неё по вашим разговорам."];
    к.font = '13px system-ui, "Segoe UI", sans-serif';
    const ш = 260, перенос = [];
    for (const с of строки) {
      let строка = "";
      for (const слово of с.split(" ")) {
        if (к.measureText(`${строка} ${слово}`).width > ш - 20 && строка) { перенос.push(строка); строка = слово; }
        else строка = строка ? `${строка} ${слово}` : слово;
      }
      перенос.push(строка);
    }
    const в = 30 + перенос.length * 17;
    let x = у.x + 18, y = у.y - в / 2;
    if (x + ш > ширина - 8) x = у.x - 18 - ш;
    y = Math.max(8, Math.min(высота - в - 8, y));
    к.beginPath(); к.roundRect(x, y, ш, в, 10);
    к.fillStyle = "rgba(12,16,15,0.94)"; к.fill();
    к.strokeStyle = цв(0.6, rgb(ЦВЕТА_ВАЖНОГО[у.и.тип])); к.lineWidth = 1; к.stroke();
    к.textAlign = "left"; к.textBaseline = "top";
    к.font = '600 13px system-ui, "Segoe UI", sans-serif'; к.fillStyle = "#fff";
    к.fillText(`${ЗНАЧКИ_ВАЖНОГО[у.и.тип]} ${у.и.имя}${м ? ` · ${м.тон}` : ""}`, x + 10, y + 9);
    к.font = '13px system-ui, "Segoe UI", sans-serif'; к.fillStyle = "rgba(255,255,255,0.78)";
    перенос.forEach((с, i) => к.fillText(с, x + 10, y + 28 + i * 17));
  }

  холст.addEventListener("pointermove", (с) => {
    const р = холст.getBoundingClientRect();
    мышь = { x: с.clientX - р.left, y: с.clientY - р.top };
  });
  холст.addEventListener("pointerleave", () => (мышь = null));
  холст.addEventListener("click", () => {
    const у = узлыВажного.find((у) => у.над);
    if (!у) return;
    const карта = панель.querySelector(`[data-мнение="${CSS.escape(ключ(у.и.имя))}"]`) || панель.querySelector(".душа-мнения");
    карта?.scrollIntoView({ behavior: "smooth", block: "center" });
    карта?.classList.remove("вспышка"); void карта?.offsetWidth; карта?.classList.add("вспышка");
  });

  function слово(с) {
    const м = (0.75 + 0.25 * (с.глубина + 1) / 2) * с.масштаб;  // спереди — крупнее
    const а = (0.35 + 0.65 * (с.глубина + 1) / 2) * с.ярко;
    к.font = `500 ${Math.round(с.о.размер * м)}px system-ui, "Segoe UI", sans-serif`;
    к.textAlign = "center"; к.textBaseline = "middle";
    const ш = к.measureText(с.текст).width + 16 * с.масштаб, в = с.о.размер * м + 10;
    к.beginPath();
    к.roundRect(с.x - ш / 2, с.y - в / 2, ш, в, в / 2);
    к.fillStyle = `rgba(10,14,13,${0.75 * а})`; к.fill();
    к.strokeStyle = цв(0.55 * а); к.lineWidth = 1; к.stroke();
    к.fillStyle = `rgba(255,255,255,${0.92 * а})`;
    к.fillText(с.текст, с.x, с.y + 0.5);
  }
