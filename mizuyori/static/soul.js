"use strict";

// =============================================================================
// Вкладка «Душа» на экране «Мозги».
//
// В центре — светящееся ядро: дышит в такт энергии, цвет — от настроения.
// Вокруг по трём орбитам летают черты (ближе), ценности и границы (дальше).
// Справа — карточки: суть, настроение и почему, черты, ценности, границы, голос, знакомство.
// =============================================================================

{
  const экран = $("экран-мозги");
  const слой = $("душа");
  const холст = $("душа-холст");
  const к = холст.getContext("2d");
  const панель = $("душа-панель");
  const безАнимаций = () => matchMedia("(prefers-reduced-motion: reduce)").matches;

  let данные = null;          // ответ /api/soul
  let правка = null;          // копия души во время правки
  let активна = false;
  let кадр = 0, прошлый = 0, время = 0;
  let ширина = 0, высота = 0, dpr = 1;
  let подсвечено = null;      // раздел, на который навели в панели

  // текущий цвет плавно идёт к цвету настроения
  const цвет = { r: 106, g: 169, b: 255 };
  let цель = { r: 106, g: 169, b: 255 };
  let энергия = 0.5;

  const ОРБИТЫ = [
    { раздел: "черты", радиус: 1.55, скорость: 0.16, наклон: 0.38, размер: 13 },
    { раздел: "ценности", радиус: 2.15, скорость: -0.11, наклон: 0.38, размер: 13 },
    { раздел: "границы", радиус: 2.75, скорость: 0.075, наклон: 0.38, размер: 12 },
  ];
  const ПОДПИСИ = { черты: "Черты", ценности: "Ценности", границы: "Границы" };

  function rgb(hex) {
    const ч = parseInt(hex.replace("#", ""), 16);
    return { r: (ч >> 16) & 255, g: (ч >> 8) & 255, b: ч & 255 };
  }
  const цв = (а, с = цвет) => `rgba(${с.r | 0},${с.g | 0},${с.b | 0},${а})`;

  // ---- Вкладки -----------------------------------------------------------

  function вкладка(имя, запомнить = true) {
    экран.dataset.вкладка = имя;
    for (const к of $("мозги-вкладки").querySelectorAll("button")) {
      к.setAttribute("aria-selected", String(к.dataset.вкладка === имя));
    }
    слой.hidden = имя !== "душа";
    if (запомнить) { try { localStorage.setItem("mizuyori.мозги.вкладка", имя); } catch {} }
    document.dispatchEvent(new CustomEvent("mizuyori:вкладка-мозгов", { detail: имя }));
    обновитьАктивность();
  }
  $("мозги-вкладки").addEventListener("click", (с) => {
    const к = с.target.closest("button[data-вкладка]");
    if (к) вкладка(к.dataset.вкладка);
  });
  let сохранённая = "граф";
  try { сохранённая = localStorage.getItem("mizuyori.мозги.вкладка") || "граф"; } catch {}
  экран.dataset.вкладка = сохранённая;
  вкладка(сохранённая, false);

  function обновитьАктивность() {
    const надо = !экран.hidden && экран.dataset.вкладка === "душа";
    if (надо && !активна) {
      активна = true;
      подогнать();
      загрузить();
      if (!кадр) { прошлый = performance.now(); кадр = requestAnimationFrame(цикл); }
    } else if (!надо) {
      активна = false;
    }
  }
  document.addEventListener("mizuyori:экран", () => обновитьАктивность());
  document.addEventListener("mizuyori:задачи", () => { if (активна) загрузить(); });

  // ---- Данные ------------------------------------------------------------

  async function загрузить() {
    try {
      данные = await запрос("/api/soul");
      цель = rgb(данные.настроение.цвет);
      энергия = данные.настроение.энергия;
      if (!правка) нарисоватьПанель();
      подписать();
    } catch (e) {
      панель.replaceChildren(создать("p", { класс: "душа-ошибка", текст: `Не удалось загрузить душу: ${e.message}` }));
    }
  }

  function подписать() {
    $("душа-имя").textContent = данные.имя;
    const н = данные.настроение;
    $("душа-настроение").replaceChildren(
      создать("span", { класс: "душа-значок", текст: н.значок }),
      создать("span", { текст: н.имя }));
    $("душа-настроение").style.setProperty("--цвет-души", н.цвет);
  }

  // ---- Панель ------------------------------------------------------------

  function карточка(заголовок, ...дети) {
    return создать("section", { класс: "душа-карточка" }, создать("h3", { текст: заголовок }), ...дети);
  }

  function нарисоватьПанель() {
    if (!данные) return;
    const д = правка || данные.душа;
    const н = данные.настроение;
    const з = данные.знакомство;
    const части = [];

    части.push(создать("div", { класс: "душа-шапка" },
      создать("h2", { текст: "Душа" }),
      правка
        ? создать("div", { класс: "душа-кнопки" },
            создать("button", { класс: "кнопка второстепенная малая", type: "button", текст: "Отмена",
              onclick: () => { правка = null; нарисоватьПанель(); } }),
            создать("button", { класс: "кнопка главная малая", type: "button", текст: "Сохранить", onclick: сохранить }))
        : создать("button", { класс: "кнопка второстепенная малая", type: "button", текст: "Изменить",
            onclick: () => { правка = structuredClone(данные.душа); нарисоватьПанель(); } })));

    // Суть
    части.push(карточка("Суть", правка
      ? создать("textarea", { класс: "душа-поле", rows: "3", maxlength: "300", "aria-label": "Суть",
          oninput: (с) => (правка.суть = с.target.value) }, document.createTextNode(д.суть))
      : создать("p", { класс: "душа-суть", текст: д.суть || "—" })));

    // Настроение
    const полоска = создать("div", { класс: "душа-энергия" }, создать("span", {}));
    полоска.firstChild.style.width = `${Math.round(н.энергия * 100)}%`;
    const карта = карточка("Настроение",
      создать("div", { класс: "душа-настрой" },
        создать("span", { класс: "душа-значок большой", текст: н.значок }),
        создать("div", {},
          создать("strong", { текст: н.имя[0].toUpperCase() + н.имя.slice(1) }),
          создать("ul", { класс: "душа-причины" }, ...н.причины.map((п) => создать("li", { текст: п }))))),
      создать("div", { класс: "душа-энергия-строка" }, создать("span", { текст: "Энергия" }), полоска));
    карта.style.setProperty("--цвет-души", н.цвет);
    части.push(карта);

    // Черты, ценности, границы
    for (const раздел of ["черты", "ценности", "границы"]) {
      const фишки = создать("div", { класс: "душа-фишки" }, ...д[раздел].map((т, i) => создать("span", { класс: "душа-фишка" },
        создать("span", { текст: т }),
        ...(правка ? [создать("button", { type: "button", класс: "душа-убрать", "aria-label": `Убрать «${т}»`, текст: "×",
          onclick: () => { правка[раздел].splice(i, 1); нарисоватьПанель(); } })] : []))));
      if (правка && д[раздел].length < 8) {
        const поле = создать("input", { класс: "душа-поле душа-добавить", type: "text", maxlength: "80",
          placeholder: "+ добавить", "aria-label": `Добавить: ${ПОДПИСИ[раздел]}` });
        поле.addEventListener("keydown", (с) => {
          if (с.key !== "Enter") return;
          с.preventDefault();
          const т = поле.value.trim();
          if (т && !правка[раздел].includes(т)) { правка[раздел].push(т); нарисоватьПанель(); $("душа-панель").querySelector(`[data-раздел="${раздел}"] .душа-добавить`)?.focus(); }
        });
        фишки.append(поле);
      }
      const к = карточка(ПОДПИСИ[раздел], фишки);
      к.dataset.раздел = раздел;
      к.addEventListener("mouseenter", () => (подсвечено = раздел));
      к.addEventListener("mouseleave", () => (подсвечено = null));
      части.push(к);
    }

    // Голос
    части.push(карточка("Манера речи", правка
      ? создать("textarea", { класс: "душа-поле", rows: "2", maxlength: "300", "aria-label": "Манера речи",
          oninput: (с) => (правка.голос = с.target.value) }, document.createTextNode(д.голос))
      : создать("p", { текст: д.голос || "—" })));

    // Знакомство
    const число = (н, подпись) => создать("div", { класс: "душа-число" },
      создать("strong", { текст: String(н) }), создать("span", { текст: подпись }));
    части.push(карточка("Мы знакомы",
      создать("div", { класс: "душа-числа" },
        число(з.дней, склонение(з.дней, ["день", "дня", "дней"])),
        число(з.сообщений, склонение(з.сообщений, ["сообщение", "сообщения", "сообщений"])),
        число(з.фактов, склонение(з.фактов, ["факт", "факта", "фактов"])),
        число(з.сущностей, "в понимании"))));

    if (правка) {
      части.push(создать("button", { класс: "ссылка душа-сброс", type: "button", текст: "Вернуть исходную душу",
        onclick: async () => {
          if (!confirm("Вернуть характер, ценности и границы к исходным?")) return;
          try { данные = await запрос("/api/soul", { method: "DELETE" }); правка = null; нарисоватьПанель(); }
          catch (e) { alert(e.message); }
        } }));
    }
    части.push(создать("p", { класс: "душа-примечание",
      текст: "Душа добавляется к каждому ответу ИИ. Настроение считается из ваших дел и разговоров." }));
    панель.replaceChildren(...части);
  }

  function склонение(н, [один, два, пять]) {
    const м10 = н % 10, м100 = н % 100;
    if (м10 === 1 && м100 !== 11) return один;
    if (м10 >= 2 && м10 <= 4 && (м100 < 10 || м100 >= 20)) return два;
    return пять;
  }

  async function сохранить() {
    try {
      данные = await запрос("/api/soul", { method: "PUT", body: JSON.stringify({ душа: правка }) });
      правка = null;
      нарисоватьПанель();
    } catch (e) {
      alert(e.message);
    }
  }

  // ---- Рисование ---------------------------------------------------------

  function подогнать() {
    const р = холст.getBoundingClientRect();
    dpr = Math.min(window.devicePixelRatio || 1, 2);
    ширина = р.width; высота = р.height;
    холст.width = Math.max(1, Math.round(ширина * dpr));
    холст.height = Math.max(1, Math.round(высота * dpr));
  }
  new ResizeObserver(() => { if (активна) подогнать(); }).observe(холст);

  // искры, летящие от ядра
  const искры = Array.from({ length: 70 }, () => новаяИскра(true));
  function новаяИскра(случайно = false) {
    return { угол: Math.random() * Math.PI * 2, путь: случайно ? Math.random() : 0,
             скорость: 0.05 + Math.random() * 0.12, размер: 0.6 + Math.random() * 1.6, сдвиг: Math.random() * 10 };
  }
  // пятна внутри ядра
  const пятна = Array.from({ length: 6 }, (_, i) => ({ ф: i * 1.7, с: 0.3 + (i % 3) * 0.17, р: 0.35 + (i % 2) * 0.15 }));

  function цикл(t) {
    if (!активна) { кадр = 0; return; }
    const dt = Math.min((t - прошлый) / 1000 || 0.016, 0.1);
    прошлый = t;
    время += безАнимаций() ? 0 : dt;
    const п = 1 - Math.pow(0.02, dt);
    цвет.r += (цель.r - цвет.r) * п; цвет.g += (цель.g - цвет.g) * п; цвет.b += (цель.b - цвет.b) * п;
    нарисовать(dt);
    кадр = requestAnimationFrame(цикл);
  }

  function нарисовать(dt) {
    к.setTransform(dpr, 0, 0, dpr, 0, 0);
    к.clearRect(0, 0, ширина, высота);
    const cx = ширина / 2, cy = высота / 2;
    const R = Math.max(26, Math.min(ширина / 7, высота * 0.13));
    const темп = 0.6 + энергия * 0.9;                        // чем больше энергии — тем чаще дыхание
    const вдох = (Math.sin(время * темп * 1.6) + 1) / 2;
    const Rд = R * (1 + 0.06 * вдох);

    // ореол
    let г = к.createRadialGradient(cx, cy, 0, cx, cy, R * 4.2);
    г.addColorStop(0, цв(0.22 + 0.08 * вдох)); г.addColorStop(0.4, цв(0.07)); г.addColorStop(1, цв(0));
    к.fillStyle = г; к.fillRect(0, 0, ширина, высота);

    // орбиты: дальняя половина — за ядром
    const слова = [];
    for (const о of ОРБИТЫ) {
      const пункты = (данные && (правка || данные.душа)[о.раздел]) || [];
      const ро = R * о.радиус;
      const ярко = подсвечено ? (подсвечено === о.раздел ? 1 : 0.25) : 1;
      к.beginPath();
      к.ellipse(cx, cy, ро, ро * о.наклон, 0, 0, Math.PI * 2);
      к.strokeStyle = цв(0.16 * ярко); к.lineWidth = 1; к.stroke();
      пункты.forEach((текст, i) => {
        const у = время * о.скорость + (i / пункты.length) * Math.PI * 2;
        const глубина = Math.sin(у);                         // -1 сзади, 1 спереди
        слова.push({ x: cx + Math.cos(у) * ро, y: cy + глубина * ро * о.наклон, глубина, текст, о, ярко,
                     масштаб: Math.min(1, Math.max(0.72, R / 95)) });
      });
    }
    const сзади = слова.filter((с) => с.глубина < 0), спереди = слова.filter((с) => с.глубина >= 0);
    сзади.forEach(слово);

    // искры
    к.globalCompositeOperation = "lighter";
    for (const и of искры) {
      и.путь += и.скорость * dt * (0.5 + энергия);
      if (и.путь > 1) Object.assign(и, новаяИскра());
      const д = Rд * (0.9 + и.путь * 2.6);
      const x = cx + Math.cos(и.угол + время * 0.05) * д;
      const y = cy + Math.sin(и.угол + время * 0.05) * д * 0.8 + Math.sin(время + и.сдвиг) * 3;
      к.fillStyle = цв((1 - и.путь) * 0.8);
      к.beginPath(); к.arc(x, y, и.размер * (1 - и.путь * 0.5), 0, Math.PI * 2); к.fill();
    }

    // ядро
    г = к.createRadialGradient(cx, cy, 0, cx, cy, Rд * 1.6);
    г.addColorStop(0, "rgba(255,255,255,0.95)");
    г.addColorStop(0.25, цв(0.9)); г.addColorStop(0.6, цв(0.35)); г.addColorStop(1, цв(0));
    к.fillStyle = г; к.beginPath(); к.arc(cx, cy, Rд * 1.6, 0, Math.PI * 2); к.fill();

    // переливы внутри
    for (const п of пятна) {
      const x = cx + Math.cos(время * п.с + п.ф) * Rд * п.р;
      const y = cy + Math.sin(время * п.с * 1.3 + п.ф) * Rд * п.р;
      const гп = к.createRadialGradient(x, y, 0, x, y, Rд * 0.7);
      гп.addColorStop(0, "rgba(255,255,255,0.18)"); гп.addColorStop(1, "rgba(255,255,255,0)");
      к.fillStyle = гп; к.beginPath(); к.arc(x, y, Rд * 0.7, 0, Math.PI * 2); к.fill();
    }
    к.globalCompositeOperation = "source-over";

    // кольца дыхания
    for (let i = 0; i < 3; i++) {
      const ф = ((время * темп * 0.35 + i / 3) % 1);
      к.beginPath(); к.arc(cx, cy, Rд * (1.1 + ф * 1.8), 0, Math.PI * 2);
      к.strokeStyle = цв(0.35 * (1 - ф)); к.lineWidth = 1.5; к.stroke();
    }

    спереди.forEach(слово);

    // подписи орбит
    к.font = "600 10px ui-monospace, Consolas, monospace";
    к.textAlign = "center"; к.textBaseline = "middle";
    for (const о of ОРБИТЫ) {
      const ярко = подсвечено ? (подсвечено === о.раздел ? 1 : 0.3) : 0.7;
      к.fillStyle = цв(0.6 * ярко);
      к.fillText(ПОДПИСИ[о.раздел].toUpperCase(), cx, cy + R * о.радиус * о.наклон + 9);
    }
  }

  function слово(с) {
    const м = (0.75 + 0.25 * (с.глубина + 1) / 2) * с.масштаб;  // спереди — крупнее
    const а = (0.35 + 0.65 * (с.глубина + 1) / 2) * с.ярко;
    к.font = `500 ${Math.round(с.о.размер * м)}px system-ui, "Segoe UI", sans-serif`;
    к.textAlign = "center"; к.textBaseline = "middle";
    const ш = к.measureText(с.текст).width + 16 * с.масштаб, в = с.о.размер * м + 10;
    к.beginPath();
    к.roundRect(с.x - ш / 2, с.y - в / 2, ш, в, в / 2);
    к.fillStyle = `rgba(10,14,13,${0.75 * а})`; к.fill();
    к.strokeStyle = цв(0.55 * а); к.lineWidth = 1; к.stroke();
    к.fillStyle = `rgba(255,255,255,${0.92 * а})`;
    к.fillText(с.текст, с.x, с.y + 0.5);
  }
}
