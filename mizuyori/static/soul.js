    if (раскрытие > цельРаскрытия) {
      раскрытие = Math.max(0, раскрытие - dt / 0.38);
      if (раскрытие === 0 && послеУхода) { const г = послеУхода; послеУхода = null; setTimeout(г, 0); }
    }
    const п = 1 - Math.pow(0.02, dt);
    цвет.r += (цель.r - цвет.r) * п; цвет.g += (цель.g - цвет.g) * п; цвет.b += (цель.b - цвет.b) * п;
