  let таймерСтатуса;
  function показатьСтатус(текст) {
    $("мозги-статус").textContent = текст;
    clearTimeout(таймерСтатуса);
    if (текст) таймерСтатуса = setTimeout(() => ($("мозги-статус").textContent = ""), 3000);
  }

  function обновитьПанель() {
    for (const [id, ключ] of [["мозги-раскладка", "раскладка"], ["мозги-вид", "вид"]]) {
      for (const кнопка of $(id).children) кнопка.setAttribute("aria-checked", String(кнопка.dataset.значение === настройки[ключ]));
    }
    for (const ключ of ["вращение", "пружины", "размер"]) {
      $(`мозги-${ключ}`).value = настройки[ключ];
      $(`мозги-${ключ}-знач`).textContent = настройки[ключ].toFixed(ключ === "пружины" ? 3 : 2);
    }
    $("мозги-названия").checked = настройки.названия;
    $("мозги-связи").checked = настройки.связи;
    $("мозги-порог").value = настройки.порог;
    $("мозги-порог-знач").textContent = `${Math.round(настройки.порог * 100)}%`;
  }

  function выборКнопкой(id, ключ, перестроить) {
    $(id).addEventListener("click", (с) => {
      const кнопка = с.target.closest("button");
      if (!кнопка || !настройки) return;
      настройки[ключ] = кнопка.dataset.значение;
      обновитьПанель();
      if (перестроить) построить(); else разложить();
      if (ключ === "раскладка") setTimeout(() => вЦентр(), 50);
    });
  }
  выборКнопкой("мозги-раскладка", "раскладка", false);
  выборКнопкой("мозги-вид", "вид", true);

  for (const ключ of ["вращение", "пружины", "размер"]) {
    $(`мозги-${ключ}`).addEventListener("input", (с) => {
      if (!настройки) return;
      настройки[ключ] = Number(с.target.value);
      обновитьПанель();
      if (ключ === "размер") разложить();
    });
  }
  $("мозги-названия").addEventListener("change", (с) => { if (настройки) настройки.названия = с.target.checked; });
  $("мозги-связи").addEventListener("change", (с) => { if (!настройки) return; настройки.связи = с.target.checked; загрузитьСвязи(true); });
  $("мозги-порог").addEventListener("input", (с) => {
    if (!настройки) return;
    настройки.порог = Number(с.target.value);
    обновитьПанель();
    загрузитьСвязи();
  });
  $("мозги-связи-обновить").addEventListener("click", (с) => {
    if (с.target.dataset.настройки) document.dispatchEvent(new CustomEvent("mizuyori:открыть-настройки-ии"));
    else загрузитьСвязи(true);
  });
  // Настройки ИИ поменялись (например, выбрали модель эмбеддингов) — пересчитать связи
  document.addEventListener("mizuyori:ии-изменён", () => { if (загружено) загрузитьСвязи(true); });

