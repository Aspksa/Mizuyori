  // Сила: якоря разделов и точки на пружинах (считается каждый кадр)
  function разложитьСилу() {
    разделы.forEach((раздел, i) => {
      const а = (i / разделы.length) * Math.PI * 2 - Math.PI / 2;
      if (!раздел.якорь.x && !раздел.якорь.y) {
        раздел.якорь.x = Math.cos(а) * 280; раздел.якорь.y = Math.sin(а) * 280;
      }
      раздел.пузырь = свёрнуты.has(раздел.ключ) ? раздел.якорь : null;
    });
  }

  function шагСилы(dt) {
    const k = настройки.пружины;
    const длина = 300 * масштабРазмера();
    const я = разделы.map((р) => р.якорь);
    // якоря: пружина к ядру + отталкивание друг от друга
    for (let i = 0; i < я.length; i++) {
      const а = я[i];
      const d = Math.hypot(а.x, а.y) || 1;
      const f = (d - длина) * 0.02;
      а.vx -= (а.x / d) * f; а.vy -= (а.y / d) * f;
      for (let j = i + 1; j < я.length; j++) {
        const б = я[j];
        let dx = а.x - б.x, dy = а.y - б.y;
        const d2 = dx * dx + dy * dy + 1;
        const сила = 60000 / d2;
        const dd = Math.sqrt(d2);
        dx /= dd; dy /= dd;
        а.vx += dx * сила; а.vy += dy * сила; б.vx -= dx * сила; б.vy -= dy * сила;
      }
    }
    for (const а of я) {
      а.vx *= 0.8; а.vy *= 0.8;
      а.x += а.vx * dt * 60; а.y += а.vy * dt * 60;
    }
    // точки: пружина к якорю своего раздела + отталкивание внутри раздела
    for (const раздел of разделы) {
      const а = раздел.якорь;
      const список = раздел.узлы;
      const скрыт = свёрнуты.has(раздел.ключ);
      for (let i = 0; i < список.length; i++) {
        const у = список[i];
        if (скрыт) { у.x += (а.x - у.x) * 0.2; у.y += (а.y - у.y) * 0.2; continue; }
        у.vx += (а.x - у.x) * k; у.vy += (а.y - у.y) * k;
        for (let j = i + 1; j < список.length; j++) {
          const в = список[j];
          let dx = у.x - в.x, dy = у.y - в.y;
          const d2 = dx * dx + dy * dy;
          if (d2 > 6400) continue;
          const сила = 30 / (d2 + 4);
          у.vx += dx * сила; у.vy += dy * сила; в.vx -= dx * сила; в.vy -= dy * сила;
        }
        // не заходить в ядро
        const dц = Math.hypot(у.x, у.y);
        if (dц < 110) { у.vx += (у.x / (dц || 1)) * 0.8; у.vy += (у.y / (dц || 1)) * 0.8; }
      }
      for (const у of список) {
        у.vx *= 0.82; у.vy *= 0.82;
        у.x += у.vx * dt * 60; у.y += у.vy * dt * 60;
      }
      // подпись — над облаком точек раздела
      let край = 0;
      if (!скрыт) for (const у of список) край = Math.max(край, Math.hypot(у.x - а.x, у.y - а.y));
      раздел.метка.x = а.x; раздел.метка.y = а.y - Math.min(край, 400) - 18;
    }
  }

