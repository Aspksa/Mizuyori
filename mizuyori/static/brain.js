  // Понимание: в центре — «Я», вокруг — цели, у целей — их задачи (шаги),
  // дальше — люди и прочее, связанные с целями; остальные сущности — на внешнем кольце.
  // Факты — спутники своих сущностей. Всё прочее (заметки, чат) скрыто.
  function разложитьПонимание() {
    const м = масштабРазмера();
    const отношения = данные.отношения || [];
    const сущностьУзел = (id) => поId.get(`е${id}`);
    for (const у of узлы) { у.скрытВПонимании = !у.орбита; у.цх = 0; у.цу = 0; }

    const цели = узлы.filter((у) => у.тип === "сущность" && у.подтип === "цель")
      .sort((а, б) => (а.статус === "достигнута") - (б.статус === "достигнута") || а.ид - б.ид);
    const R1 = 250 * м, R2 = 470 * м, R3 = 650 * м;
    const угол = new Map();
    цели.forEach((ц, i) => {
      const а = -Math.PI / 2 + (i / Math.max(цели.length, 1)) * Math.PI * 2;
      угол.set(ц, а);
      ц.цх = Math.cos(а) * R1; ц.цу = Math.sin(а) * R1; ц.скрытВПонимании = false;
      // задачи-шаги веером наружу от цели
      const шаги = узлы.filter((у) => у.тип === "задача" && у.цель_id === ц.ид);
      шаги.forEach((ш, j) => {
        const ряд = Math.floor(j / 7), в_ряду = Math.min(7, шаги.length - ряд * 7);
        const а2 = а + ((j % 7) - (в_ряду - 1) / 2) * 0.13;
        const r = R1 + (70 + ряд * 34) * м;
        ш.цх = Math.cos(а2) * r; ш.цу = Math.sin(а2) * r; ш.скрытВПонимании = false;
      });
    });

    // сущности, связанные с целями (в любую сторону), — между целями и внешним кольцом
    const прочие = узлы.filter((у) => у.тип === "сущность" && у.подтип !== "цель");
    const связанные = [], одинокие = [];
    for (const с of прочие) {
      const углы = [];
      for (const о of отношения) {
        const другой = о.от_id === с.ид ? сущностьУзел(о.к_id) : о.к_id === с.ид ? сущностьУзел(о.от_id) : null;
        if (другой && угол.has(другой)) углы.push(угол.get(другой));
      }
      if (углы.length) {
        const x = углы.reduce((а, б) => а + Math.cos(б), 0), y = углы.reduce((а, б) => а + Math.sin(б), 0);
        связанные.push([с, Math.atan2(y, x)]);
      } else одинокие.push(с);
    }
    связанные.sort((а, б) => а[1] - б[1]);
    let прошлый = -Infinity;
    for (const [с, а0] of связанные) {
      const а = Math.max(а0, прошлый + 0.3);    // не налезать друг на друга (и подписями)
      прошлый = а;
      с.цх = Math.cos(а) * R2; с.цу = Math.sin(а) * R2; с.скрытВПонимании = false;
    }
    одинокие.sort((а, б) => а.подтип.localeCompare(б.подтип) || а.ид - б.ид);
    одинокие.forEach((с, i) => {
      const а = -Math.PI / 2 + ((i + 0.5) / одинокие.length) * Math.PI * 2;
      const R = (связанные.length || цели.length) ? R3 : R1;
      с.цх = Math.cos(а) * R; с.цу = Math.sin(а) * R; с.скрытВПонимании = false;
    });

    // факты — спутники первой своей сущности
    const спутники = new Map();
    for (const ф of узлы.filter((у) => у.тип === "факт" && у.сущности?.length)) {
      const хозяин = ф.сущности.map(сущностьУзел).find((х) => х && !х.скрытВПонимании);
      if (!хозяин) continue;
      const n = спутники.get(хозяин) || 0;
      спутники.set(хозяин, n + 1);
      const а = n * 0.9 + 0.4;
      ф.цх = хозяин.цх + Math.cos(а) * (26 + Math.floor(n / 7) * 10);
      ф.цу = хозяин.цу + Math.sin(а) * (26 + Math.floor(n / 7) * 10);
      ф.скрытВПонимании = false;
    }
    for (const р of разделы) { р.метка.цх = 0; р.метка.цу = 0; р.пузырь = null; }
  }

  // Сила: якоря разделов и точки на пружинах (считается каждый кадр)
  function разложитьСилу() {
    разделы.forEach((раздел, i) => {
      const а = (i / разделы.length) * Math.PI * 2 - Math.PI / 2;
      if (!раздел.якорь.x && !раздел.якорь.y) {
        раздел.якорь.x = Math.cos(а) * 280; раздел.якорь.y = Math.sin(а) * 280;
      }
      раздел.пузырь = свёрнуты.has(раздел.ключ) ? раздел.якорь : null;
    });
  }

  function шагСилы(dt) {
    const k = настройки.пружины;
    const длина = 300 * масштабРазмера();
    const я = разделы.map((р) => р.якорь);
    // якоря: пружина к ядру + отталкивание друг от друга
    for (let i = 0; i < я.length; i++) {
      const а = я[i];
      const d = Math.hypot(а.x, а.y) || 1;
      const f = (d - длина) * 0.02;
      а.vx -= (а.x / d) * f; а.vy -= (а.y / d) * f;
      for (let j = i + 1; j < я.length; j++) {
        const б = я[j];
        let dx = а.x - б.x, dy = а.y - б.y;
        const d2 = dx * dx + dy * dy + 1;
        const сила = 60000 / d2;
        const dd = Math.sqrt(d2);
        dx /= dd; dy /= dd;
        а.vx += dx * сила; а.vy += dy * сила; б.vx -= dx * сила; б.vy -= dy * сила;
      }
    }
    for (const а of я) {
      а.vx *= 0.8; а.vy *= 0.8;
      а.x += а.vx * dt * 60; а.y += а.vy * dt * 60;
    }
    // точки: пружина к якорю своего раздела + отталкивание внутри раздела
    for (const раздел of разделы) {
      const а = раздел.якорь;
      const список = раздел.узлы;
      const скрыт = свёрнуты.has(раздел.ключ);
      for (let i = 0; i < список.length; i++) {
        const у = список[i];
        if (скрыт) { у.x += (а.x - у.x) * 0.2; у.y += (а.y - у.y) * 0.2; continue; }
        у.vx += (а.x - у.x) * k; у.vy += (а.y - у.y) * k;
        for (let j = i + 1; j < список.length; j++) {
          const в = список[j];
          let dx = у.x - в.x, dy = у.y - в.y;
          const d2 = dx * dx + dy * dy;
          if (d2 > 6400) continue;
          const сила = 30 / (d2 + 4);
          у.vx += dx * сила; у.vy += dy * сила; в.vx -= dx * сила; в.vy -= dy * сила;
        }
        // не заходить в ядро
        const dц = Math.hypot(у.x, у.y);
        if (dц < 110) { у.vx += (у.x / (dц || 1)) * 0.8; у.vy += (у.y / (dц || 1)) * 0.8; }
      }
      for (const у of список) {
        у.vx *= 0.82; у.vy *= 0.82;
        у.x += у.vx * dt * 60; у.y += у.vy * dt * 60;
      }
      // подпись — над облаком точек раздела
      let край = 0;
      if (!скрыт) for (const у of список) край = Math.max(край, Math.hypot(у.x - а.x, у.y - а.y));
      раздел.метка.x = а.x; раздел.метка.y = а.y - Math.min(край, 400) - 18;
    }
  }

