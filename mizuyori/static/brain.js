  function найти(sx, sy) {
    for (const м of меткиНаЭкране) {
      if (sx >= м.x && sx <= м.x + м.w && sy >= м.y && sy <= м.y + м.h) return { тип: "раздел", объект: м.раздел };
    }
    const [wx, wy] = вМир(sx, sy);
    for (const раздел of разделы) {
      if (!свёрнуты.has(раздел.ключ)) continue;
      const [x, y] = позицияПузыря(раздел);
      if (Math.hypot(wx - x, wy - y) < 18) return { тип: "раздел", объект: раздел };
    }
    let лучший = null, лучшее = (8 / камера.z) ** 2;
    for (const у of узлы) {
      if (видимость(у) < 0.15) continue;
      const d = (у.x - wx) ** 2 + (у.y - wy) ** 2;
      if (d < лучшее) { лучшее = d; лучший = у; }
    }
    if (лучший) return { тип: "узел", объект: лучший };
    if (Math.hypot(wx, wy) < 56) return { тип: "ядро" };
    return null;
  }

