  $("мозги-свернуть").addEventListener("click", () => { for (const р of разделы) свёрнуты.add(р.ключ); фильтр = null; разложить(); setTimeout(() => вЦентр(), 50); });
  $("мозги-центр").addEventListener("click", () => вЦентр());
  $("мозги-обновить").addEventListener("click", () => загрузить());

