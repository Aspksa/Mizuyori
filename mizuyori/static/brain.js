  // Кольца: разделы — секторы вокруг ядра, группы — сетки точек по дуге
  function разложитьКольца() {
    const зазор = 0.07;
    const веса = разделы.map((р) => (свёрнуты.has(р.ключ) ? 1.3 : 1 + Math.sqrt(р.узлы.length)));
    const сумма = веса.reduce((а, б) => а + б, 0) || 1;
    const всего = Math.PI * 2 - зазор * разделы.length;
    let угол = -Math.PI / 2;

    разделы.forEach((раздел, i) => {
      const сектор = всего * веса[i] / сумма;
      const середина = угол + сектор / 2;
      раздел.сектор = [угол, угол + сектор];

      if (свёрнуты.has(раздел.ключ)) {
        for (const у of раздел.узлы) { у.пр = R0 + 24; у.пу = середина; }
        раздел.метка.пр = R0 + 62; раздел.метка.пу = середина;
        раздел.пузырь = { пр: R0 + 24, пу: середина };
      } else {
        const колонокЕсть = Math.max(1, Math.floor((сектор * R0) / ШАГ));
        const группы = раздел.группы;
        // Сначала пробуем «плотную» сетку, как участки на коре: строк ≈ √n / 1.6
        let строк = Math.max(1, Math.round(Math.sqrt(раздел.узлы.length) / 1.6)), колонокНадо = 0;
        for (; строк < 60; строк++) {
          колонокНадо = группы.reduce((с, г) => с + Math.ceil(г.узлы.length / строк), 0) + группы.length - 1;
          if (колонокНадо <= колонокЕсть) break;
        }
        const шагУгла = Math.min(ШАГ / R0, сектор / Math.max(колонокНадо, 1));
        let колонка = 0;
        const начало = угол + (сектор - колонокНадо * шагУгла) / 2;
        for (const г of группы) {
          const колонок = Math.ceil(г.узлы.length / строк);
          г.узлы.forEach((у, к) => {
            у.пу = начало + (колонка + Math.floor(к / строк) + 0.5) * шагУгла;
            у.пр = R0 + (к % строк) * ШАГ;
          });
          г.пу = начало + (колонка + колонок / 2) * шагУгла;
          г.пр = R0 + строк * ШАГ + 4;
          колонка += колонок + 1;
        }
        раздел.строк = строк;
        раздел.метка.пр = R0 + строк * ШАГ + 46;
        раздел.метка.пу = середина;
        раздел.пузырь = null;
      }
      угол += сектор + зазор;
    });
  }

  // Круг: все точки на одной окружности, разделы — дугами
  function разложитьКруг() {
    const видимых = разделы.reduce((с, р) => с + (свёрнуты.has(р.ключ) ? 3 : р.узлы.length + 6), 0) || 1;
    const R = Math.max(220, (видимых * 9) / (Math.PI * 2)) * масштабРазмера();
    let место = 0;
    for (const раздел of разделы) {
      const начало = место;
      if (свёрнуты.has(раздел.ключ)) {
        место += 3;
        const а = ((начало + 1.5) / видимых) * Math.PI * 2 - Math.PI / 2;
        for (const у of раздел.узлы) { у.пр = R; у.пу = а; }
        раздел.пузырь = { пр: R, пу: а };
      } else {
        раздел.группы.forEach((г, ги) => {
          for (const у of г.узлы) {
            у.пу = ((место + 0.5) / видимых) * Math.PI * 2 - Math.PI / 2;
            у.пр = R + (ги % 3 - 1) * 9;
            место += 1;
          }
        });
        место += 6;
        раздел.пузырь = null;
      }
      const середина = ((начало + (место - начало - (свёрнуты.has(раздел.ключ) ? 0 : 6)) / 2) / видимых) * Math.PI * 2 - Math.PI / 2;
      раздел.метка.пр = R + 52; раздел.метка.пу = середина;
      раздел.дуга = [начало / видимых * Math.PI * 2 - Math.PI / 2, (место - 6) / видимых * Math.PI * 2 - Math.PI / 2];
      for (const г of раздел.группы) { г.пр = 0; }
    }
    раздел_радиусКруга = R;
  }
  let раздел_радиусКруга = 300;

  // Соты: каждый раздел — шестиугольник вокруг ядра
  function разложитьСоты() {
    const S = 190 * масштабРазмера();
    const ячейки = спиральСот(разделы.length);
    разделы.forEach((раздел, i) => {
      const [q, r] = ячейки[i];
      const cx = S * Math.sqrt(3) * (q + r / 2);
      const cy = S * 1.5 * r;
      раздел.соты = { cx, cy, S };
      const n = раздел.узлы.length;
      const скрыт = свёрнуты.has(раздел.ключ);
      раздел.узлы.forEach((у, к) => {
        if (скрыт) { у.цх = cx; у.цу = cy; return; }
        const рад = 0.7 * S * Math.sqrt((к + 0.5) / n);
        const а = к * 2.39996 + хеш(раздел.ключ) * 6.28;
        у.цх = cx + Math.cos(а) * рад;
        у.цу = cy + Math.sin(а) * рад * 0.92;
      });
      раздел.метка.цх = cx; раздел.метка.цу = cy - S * 0.58;
      раздел.пузырь = скрыт ? { x: cx, y: cy } : null;
    });
  }
  // Ячейки сот по спирали от центра (центр занят ядром)
  function спиральСот(сколько) {
    const итог = [];
    const направления = [[1, 0], [1, -1], [0, -1], [-1, 0], [-1, 1], [0, 1]];
    for (let кольцо = 1; итог.length < сколько; кольцо++) {
      let q = -кольцо, r = кольцо;  // старт слева снизу
      for (let сторона = 0; сторона < 6; сторона++) {
        for (let ш = 0; ш < кольцо; ш++) {
          итог.push([q, r]);
          q += направления[сторона][0]; r += направления[сторона][1];
        }
      }
    }
    return итог.slice(0, сколько);
  }

  // Плата: разделы — микросхемы слева и справа от ядра, точки — выводы,
  // от ядра к микросхемам идут дорожки под прямым углом
  function разложитьПлату() {
    // До 6 разделов — по одному столбику справа и слева, больше — по два
    const столбиков = разделы.length > 6 ? 4 : 2;
    const колонки = [[], [], [], []];       // справа-1, слева-1, справа-2, слева-2
    разделы.forEach((р, i) => колонки[i % столбиков].push(р));
    for (const раздел of разделы) {
      const скрыт = свёрнуты.has(раздел.ключ);
      const n = раздел.узлы.length;
      const кол = скрыт ? 0 : Math.max(5, Math.ceil(Math.sqrt(n * 1.8)));
      const стр = скрыт ? 0 : Math.max(1, Math.ceil(n / кол));
      // корпус не уже подписи
      const подпись = раздел.название.length * 9 + 30;
      раздел.плата = { w: Math.max(скрыт ? 130 : кол * ШАГ + 28, подпись), h: скрыт ? 54 : стр * ШАГ + 46, кол };
    }
    const ширинаЯдра = 92, зазор = 80, межКолонками = 70;
    const ширины = колонки.map((к) => Math.max(0, ...к.map((р) => р.плата.w)));
    const лево = [ширинаЯдра + зазор, -(ширинаЯдра + зазор)];
    колонки.forEach((колонка, ki) => {
      const справа = ki % 2 === 0;
      const ряд = ki < 2 ? 0 : 1;
      let x;
      if (справа) x = ряд === 0 ? лево[0] : лево[0] + ширины[0] + межКолонками;
      else x = ряд === 0 ? лево[1] : лево[1] - ширины[1] - межКолонками;
      const всего = колонка.reduce((с, р) => с + р.плата.h, 0) + (колонка.length - 1) * 34;
      let y = -всего / 2;
      колонка.forEach((раздел, ci) => {
        const п = раздел.плата;
        п.x = справа ? x : x - п.w;
        п.y = y;
        п.справа = справа;
        п.номер = ci - (колонка.length - 1) / 2;
        y += п.h + 34;
        раздел.узлы.forEach((у, к) => {
          if (свёрнуты.has(раздел.ключ)) { у.цх = п.x + п.w / 2; у.цу = п.y + п.h / 2; return; }
          у.цх = п.x + 14 + ((к % п.кол) + 0.5) * ШАГ;
          у.цу = п.y + 34 + (Math.floor(к / п.кол) + 0.5) * ШАГ;
        });
        раздел.метка.цх = п.x + 12; раздел.метка.цу = п.y + 15;
        раздел.пузырь = свёрнуты.has(раздел.ключ) ? { x: п.x + п.w / 2, y: п.y + п.h / 2 + 8 } : null;
      });
    });
  }

  // HUD: каждый раздел — своя дорожка-кольцо, кольца вращаются в разные стороны,
  // вокруг — шкала, по кругу ходит луч радара
  function разложитьHUD() {
    let R = 150 * масштабРазмера();
    разделы.forEach((раздел, i) => {
      const скрыт = свёрнуты.has(раздел.ключ);
      const n = скрыт ? 0 : раздел.узлы.length;
      const дуга = Math.PI * 2 * 0.86;
      const дорожек = Math.max(1, Math.ceil((n * 11) / (дуга * R)));
      const наДорожке = Math.ceil(n / дорожек) || 1;
      раздел.узлы.forEach((у, к) => {
        const д = к % дорожек, место = Math.floor(к / дорожек);
        у.пр = R + д * 10;
        у.пу = -Math.PI / 2 + 0.22 + (место + 0.5) * Math.min(дуга / наДорожке, 14 / R);
        if (скрыт) { у.пр = R; у.пу = -Math.PI / 2 + 0.22; }
      });
      раздел.hud = { R, ширина: дорожек * 10, скорость: (i % 2 ? -1 : 1) * (0.6 + (i % 3) * 0.25) };
      раздел.поворотHUD = раздел.поворотHUD || 0;
      раздел.метка.цх = -10; раздел.метка.цу = -(R + (дорожек - 1) * 5);
      раздел.пузырь = скрыт ? { x: 14, y: -R } : null;
      R += дорожек * 10 + 30;
    });
    радиусHUD = R;
  }
