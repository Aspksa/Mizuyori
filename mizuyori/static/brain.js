  function радиусГрафа() {
    let макс = 160;
    for (const у of узлы) {
      const [x, y] = цельУзла(у);
      if (настройки.раскладка === "сила") макс = Math.max(макс, Math.hypot(у.x, у.y));
      else if (!свёрнуты.has(у.раздел.ключ)) макс = Math.max(макс, Math.hypot(x, y));
    }
    for (const р of разделы) { const [x, y] = цельМетки(р); макс = Math.max(макс, Math.hypot(x, y) + 40); }
    if (настройки.раскладка === "плата") {
      // по ширине платы: камера считает «радиус», поэтому берём дальний угол по горизонтали
      for (const р of разделы) if (р.плата) макс = Math.max(макс, Math.abs(р.плата.x) + 20, Math.abs(р.плата.x + р.плата.w) + 20);
    }
    if (настройки.раскладка === "hud") макс = Math.max(макс, радиусHUD + 60);
    return макс;
  }

