  // «маме», «мамой» → «Мама»: совпадение по имени, другим именам или основе слова
  function упомянута(у, текст) {
    const т = ключ(текст), слова = т.split(" ");
    for (const имя of [у.имя, ...(у.другие || [])]) {
      const и = ключ(имя);
      if (!и) continue;
      if (т.includes(и)) return true;
      if (!и.includes(" ") && и.length >= 4) {
        const основа = и.slice(0, Math.max(3, и.length - 2));
        if (слова.some((с) => с.startsWith(основа))) return true;
      }
    }
    return false;
  }

  // Всё, что связано с сущностью: связи, факты, шаги, упоминания
  function связанноеС(с) {
    const итог = new Set([с]);
    for (const о of данные.отношения || []) {
      if (о.от_id === с.ид) итог.add(поId.get(`е${о.к_id}`));
      if (о.к_id === с.ид) итог.add(поId.get(`е${о.от_id}`));
    }
    for (const у of узлы) {
      if (у.тип === "факт" && у.сущности?.includes(с.ид)) итог.add(у);
      else if (у.тип === "задача" && у.цель_id === с.ид) итог.add(у);
      else if (у.тип !== "сущность" && !у.орбита && упомянута(с, у.текст)) итог.add(у);
    }
    итог.delete(undefined);
    return итог;
  }

  function обновитьПоиск() {
    const q = поиск.trim();
    if (!q) { совпадения = null; return; }
    // запрос — имя сущности? Тогда ищем всё, что с ней связано
    // точное совпадение имени — первым, иначе самое длинное подходящее имя
    const кандидаты = ключ(q).length >= 3 ? узлы.filter((у) => у.тип === "сущность" && упомянута(у, q)) : [];
    const сущность = кандидаты.find((у) => ключ(у.имя) === ключ(q))
      || кандидаты.sort((а, б) => б.имя.length - а.имя.length)[0];
    if (сущность) {
      совпадения = связанноеС(сущность);
      показатьСтатус(`Связано с «${сущность.имя}»: ${совпадения.size - 1}`);
      return;
    }
    const к = q.toLowerCase();
    совпадения = new Set(узлы.filter((у) => у.текст.toLowerCase().includes(к)));
    показатьСтатус(`Найдено: ${совпадения.size}`);
  }
