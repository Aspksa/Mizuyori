  function путьПочему(у) {
    if (!у) return [];
    const отношения = данные.отношения || [];
    const путь = [{ узел: у, отношение: "" }];
    let текущий = у.тип === "задача" && у.цель_id ? поId.get(`е${у.цель_id}`) : у.тип === "сущность" ? у : null;
    if (!текущий) return [];
    if (текущий !== у) путь.push({ узел: текущий, отношение: "шаг к" });
    const видели = new Set([текущий]);
    for (let i = 0; i < 5; i++) {
      const о = отношения.find((х) => х.от_id === текущий.ид && ПРИЧИННЫЕ.includes(ключ(х.отношение)));
      const дальше = о && поId.get(`е${о.к_id}`);
      if (!дальше || видели.has(дальше)) break;
      путь.push({ узел: дальше, отношение: о.отношение });
      видели.add(дальше);
      текущий = дальше;
    }
    return путь.length > 1 ? путь : [];
  }

