  // ---- Смысловые связи ----
  function связатьСмысл() {
    const поId = new Map(узлы.map((у) => [у.id, у]));
    смысл = [];
    соседи = new Map();
    for (const с of связиСырые) {
      const а = поId.get(с.а), б = поId.get(с.б);
      if (!а || !б) continue;
      смысл.push({ а, б, п: с.похожесть });
      for (const [x, y] of [[а, б], [б, а]]) {
        if (!соседи.has(x)) соседи.set(x, []);
        соседи.get(x).push({ узел: y, п: с.похожесть });
      }
    }
    for (const список of соседи.values()) список.sort((x, y) => y.п - x.п);
  }

  function нарисоватьСмысл() {
    if (!настройки.связи || !смысл.length) return;
    const к = кисть, z = камера.z;
    const точка = наведено?.тип === "узел" ? наведено.объект : выбран;
    const порог = настройки.порог;
    for (const { а, б, п } of смысл) {
      const ва = видимость(а), вб = видимость(б);
      if (ва < 0.05 || вб < 0.05) continue;
      const своя = точка && (а === точка || б === точка);
      const сила = Math.min(1, (п - порог) / Math.max(0.02, 1 - порог));
      let альфа = своя ? 0.9 : (0.1 + сила * 0.3) * Math.min(ва, вб);
      if (точка && !своя) альфа *= 0.35;
      к.strokeStyle = rgba(а.цвет, альфа);
      к.lineWidth = (своя ? 1.8 : 0.8 + сила) / z;
      const mx = (а.x + б.x) / 2, my = (а.y + б.y) / 2;
      к.beginPath(); к.moveTo(а.x, а.y); к.quadraticCurveTo(mx * 0.7, my * 0.7, б.x, б.y); к.stroke();
    }
  }

