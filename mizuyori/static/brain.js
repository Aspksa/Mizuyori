  function показатьКарточку() {
    const карточка = $("мозги-карточка");
    if (!выбран) { карточка.hidden = true; return; }
    const у = выбран;
    $("мозги-карточка-тип").textContent = `${у.тип} · ${у.раздел.название}`;
    $("мозги-карточка-текст").textContent = у.текст;
    const мета = [];
    if (у.тип === "задача") {
      мета.push(у.готово ? "выполнена" : "не выполнена");
      if (у.срок) мета.push(`срок ${new Date(у.срок + "T00:00").toLocaleDateString("ru-RU", { day: "numeric", month: "long" })}`);
      if (у.список) мета.push(`${у.список.значок} ${у.список.название}`);
    } else if (у.когда) {
      мета.push(дата(у.когда));
    }
    $("мозги-карточка-мета").textContent = мета.join(" · ");
    $("мозги-открыть").textContent = у.тип === "задача" ? "Открыть задачу" : у.тип === "заметка" ? "Открыть заметку"
      : у.тип === "факт" ? "Забыть этот факт" : "Открыть чат";
    $("мозги-открыть").classList.toggle("опасная-главная", у.тип === "факт");
    // похожее по смыслу
    const похожие = (соседи.get(у) || []).slice(0, 5);
    $("мозги-похожее").hidden = !похожие.length;
    $("мозги-похожее-список").replaceChildren(...похожие.map(({ узел: с, п }) =>
      создать("li", {}, создать("button", { type: "button", style: `--цвет-списка: ${с.цвет}`,
        onclick: () => { выбран = с; показатьКарточку(); камера.цх = с.x; камера.цу = с.y; камера.цz = Math.max(камера.цz, 1.4); } },
        создать("span", { класс: "точка-похожего", "aria-hidden": "true" }),
        создать("span", { класс: "текст-похожего", текст: с.подпись }),
        создать("span", { класс: "процент", текст: `${Math.round(п * 100)}%` })))));
    карточка.hidden = false;
    if (панель.classList.contains("скрыта")) переключитьПанель(true);
  }

  $("мозги-открыть").addEventListener("click", async () => {
    if (!выбран) return;
    if (выбран.тип === "факт") {
      if (!confirm(`Забыть факт «${выбран.текст}»?`)) return;
      try {
        await запрос(`/api/memory/${выбран.ид}`, { method: "DELETE" });
        выбран = null;
        показатьКарточку();
        await загрузить();
        показатьСтатус("Факт удалён из памяти");
      } catch (e) {
        показатьСтатус(e.message);
      }
      return;
    }
    const тип = выбран.тип === "задача" ? "задача" : выбран.тип === "заметка" ? "заметка" : "чат";
    location.hash = "#главная";
    document.dispatchEvent(new CustomEvent("mizuyori:открыть", { detail: { тип, ид: выбран.ид } }));
  });

