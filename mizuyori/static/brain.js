  // Кольца: разделы — секторы вокруг ядра, группы — сетки точек по дуге
  function разложитьКольца() {
    const зазор = 0.07;
    // «Понимание» (люди, цели, места…) — не сектор, а значки на внешнем кольце, как в «Сегундо Серебро»
    const внешний = разделы.find((р) => р.ключ === "знания");
    const сектора = разделы.filter((р) => р !== внешний);
    const веса = сектора.map((р) => (свёрнуты.has(р.ключ) ? 1.3 : 1 + Math.sqrt(р.узлы.length)));
    const сумма = веса.reduce((а, б) => а + б, 0) || 1;
    const всего = Math.PI * 2 - зазор * сектора.length;
    let угол = -Math.PI / 2;

    сектора.forEach((раздел, i) => {
      const сектор = всего * веса[i] / сумма;
      const середина = угол + сектор / 2;
      раздел.сектор = [угол, угол + сектор];

      if (свёрнуты.has(раздел.ключ)) {
        for (const у of раздел.узлы) { у.пр = R0 + 24; у.пу = середина; }
        раздел.метка.пр = R0 + 62; раздел.метка.пу = середина;
        раздел.пузырь = { пр: R0 + 24, пу: середина };
      } else {
        const колонокЕсть = Math.max(1, Math.floor((сектор * R0) / ШАГ));
        const группы = раздел.группы;
        // Сначала пробуем «плотную» сетку, как участки на коре: строк ≈ √n / 1.6
        // блоки как матрицы: не меньше 3 строк и 2 колонок, пустые ячейки рисуются тускло
        const колонокГруппы = (г, строк) => Math.max(2, Math.ceil(г.узлы.length / строк));
        let строк = Math.max(3, Math.round(Math.sqrt(раздел.узлы.length) / 1.6)), колонокНадо = 0;
        for (; строк < 60; строк++) {
          колонокНадо = группы.reduce((с, г) => с + колонокГруппы(г, строк), 0) + группы.length - 1;
          if (колонокНадо <= колонокЕсть) break;
        }
        const шагУгла = Math.min(ШАГ / R0, сектор / Math.max(колонокНадо, 1));
        let колонка = 0;
        const начало = угол + (сектор - колонокНадо * шагУгла) / 2;
        for (const г of группы) {
          const колонок = колонокГруппы(г, строк);
          г.узлы.forEach((у, к) => {
            у.пу = начало + (колонка + Math.floor(к / строк) + 0.5) * шагУгла;
            у.пр = R0 + (к % строк) * ШАГ;
          });
          г.ячейки = [];
          for (let к = г.узлы.length; к < колонок * строк; к++) {
            г.ячейки.push([начало + (колонка + Math.floor(к / строк) + 0.5) * шагУгла, R0 + (к % строк) * ШАГ]);
          }
          г.пу = начало + (колонка + колонок / 2) * шагУгла;
          г.пр = R0 + строк * ШАГ + 4;
          колонка += колонок + 1;
        }
        раздел.строк = строк;
        раздел.метка.пр = R0 + строк * ШАГ + 46;
        раздел.метка.пу = середина;
        раздел.пузырь = null;
      }
      угол += сектор + зазор;
    });
    if (внешний) разложитьВнешнееКольцо(внешний, сектора);
  }

  // Значки на внешнем кольце: группы (люди, цели, места…) — дугами, равномерно по кругу
  function разложитьВнешнееКольцо(раздел, сектора) {
    раздел.сектор = null;
    const Rв = Math.max(R0 + 150, ...сектора.map((р) => р.метка.пр + 70));
    раздел.внешнее = Rв;
    if (свёрнуты.has(раздел.ключ)) {
      for (const у of раздел.узлы) { у.пр = Rв; у.пу = -Math.PI / 2; }
      раздел.метка.пр = Rв + 40; раздел.метка.пу = -Math.PI / 2;
      раздел.пузырь = { пр: Rв, пу: -Math.PI / 2 };
      return;
    }
    раздел.пузырь = null;
    const шаг = 27 / Rв;                                    // значок ⌀22 + зазор
    const группы = раздел.группы;
    const наКруг = Math.floor((Math.PI * 2 * 0.9) / шаг / Math.max(группы.length, 1));
    группы.forEach((г, i) => {
      const центр = -Math.PI / 2 + Math.PI / 4 + (i / группы.length) * Math.PI * 2;
      const вРяд = Math.max(1, Math.min(г.узлы.length, наКруг));
      const рядов = Math.ceil(г.узлы.length / вРяд);
      г.узлы.forEach((у, к) => {
        const ряд = Math.floor(к / вРяд), место = к % вРяд;
        const вЭтомРяду = Math.min(вРяд, г.узлы.length - ряд * вРяд);
        у.пу = центр + (место - (вЭтомРяду - 1) / 2) * шаг * (Rв / (Rв + ряд * 26));
        у.пр = Rв + ряд * 26;
      });
      г.ячейки = [];
      г.пу = центр;
      г.пр = Rв + рядов * 26 + 6;
    });
    раздел.метка.пр = Rв + Math.max(...группы.map((г) => г.пр - Rв)) + 30;
    раздел.метка.пу = -Math.PI / 2 + Math.PI / 4;
  }

  // Круг: все точки на одной окружности, разделы — дугами
  function разложитьКруг() {
    const видимых = разделы.reduce((с, р) => с + (свёрнуты.has(р.ключ) ? 3 : р.узлы.length + 6), 0) || 1;
    const R = Math.max(220, (видимых * 9) / (Math.PI * 2)) * масштабРазмера();
    let место = 0;
    for (const раздел of разделы) {
      const начало = место;
      if (свёрнуты.has(раздел.ключ)) {
        место += 3;
        const а = ((начало + 1.5) / видимых) * Math.PI * 2 - Math.PI / 2;
        for (const у of раздел.узлы) { у.пр = R; у.пу = а; }
        раздел.пузырь = { пр: R, пу: а };
      } else {
        раздел.группы.forEach((г, ги) => {
          for (const у of г.узлы) {
            у.пу = ((место + 0.5) / видимых) * Math.PI * 2 - Math.PI / 2;
            у.пр = R + (ги % 3 - 1) * 9;
            место += 1;
          }
        });
        место += 6;
        раздел.пузырь = null;
      }
      const середина = ((начало + (место - начало - (свёрнуты.has(раздел.ключ) ? 0 : 6)) / 2) / видимых) * Math.PI * 2 - Math.PI / 2;
      раздел.метка.пр = R + 52; раздел.метка.пу = середина;
      раздел.дуга = [начало / видимых * Math.PI * 2 - Math.PI / 2, (место - 6) / видимых * Math.PI * 2 - Math.PI / 2];
      for (const г of раздел.группы) { г.пр = 0; }
    }
    раздел_радиусКруга = R;
  }
