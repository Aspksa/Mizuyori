      if (у.тип === "задача" && у.цель_id) к_узлу = поId.get(`е${у.цель_id}`);
      if (у.тип === "факт" && у.сущности?.length) { к_узлу = поId.get(`е${у.сущности[0]}`); альфа = 0.2; }
      if (!к_узлу || видимость(к_узлу) < 0.05) continue;
