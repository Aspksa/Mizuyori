  function обновитьПоиск() {
    const q = поиск.trim().toLowerCase();
    совпадения = q ? new Set(узлы.filter((у) => у.текст.toLowerCase().includes(q))) : null;
    if (совпадения) показатьСтатус(`Найдено: ${совпадения.size}`);
  }
  $("мозги-поиск").addEventListener("input", (с) => { поиск = с.target.value; обновитьПоиск(); if (!поиск) показатьСтатус(""); });
  $("мозги-поиск").addEventListener("keydown", (с) => {
    if (с.key === "Enter" && совпадения?.size) {
      const у = [...совпадения][0];
      выбран = у;
      показатьКарточку();
      камера.цz = Math.max(камера.цz, 1.8);
      камера.цх = у.x; камера.цу = у.y;
    }
    if (с.key === "Escape") { с.target.value = ""; поиск = ""; обновитьПоиск(); показатьСтатус(""); с.target.blur(); }
  });
  document.addEventListener("keydown", (с) => {
    if (!активен) return;
    const пишет = ["INPUT", "TEXTAREA", "SELECT"].includes(document.activeElement?.tagName);
    if (с.key === "/" && !пишет) { с.preventDefault(); $("мозги-поиск").focus(); }
    if (с.key === "Escape" && !пишет && $("окно-настроек").hidden) {
      фильтр = null; выбран = null; показатьКарточку();
    }
  });

