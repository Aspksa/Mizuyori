// Порядок в памяти: очередь предложений, архив с возвратом, история правок, «навести порядок».
(() => {
  const тело = $("память-порядок-тело");
  const блок = $("память-порядок");
  if (!тело || !блок) return;

  async function загрузить() {
    try {
      const д = await запрос("/api/memory/plus");
      нарисовать(д);
    } catch (е) {
      тело.replaceChildren(создать("p", { класс: "пусто", текст: `Не удалось загрузить: ${е.message}` }));
    }
  }

  const вызвать = (url, opts = { method: "POST" }) => async () => {
    try { await запрос(url, opts); await загрузить(); } catch (е) { alert(е.message); }
  };

  async function показатьИсторию(ф, ячейка) {
    if (ячейка.dataset.открыто) { ячейка.replaceChildren(); delete ячейка.dataset.открыто; return; }
    const { версии } = await запрос(`/api/memory/${ф.id}/history`);
    ячейка.dataset.открыто = "1";
    ячейка.replaceChildren(...(версии.length
      ? версии.map((в) => создать("small", { текст: `${дата(в.создано)} · ${в.причина}: ${в.текст}` }))
      : [создать("small", { текст: "Правок не было." })]));
  }

  function нарисовать(д) {
    const флажок = создать("input", { type: "checkbox",
      onchange: async (с) => { try { await запрос("/api/memory/confirmation", { method: "PUT", body: JSON.stringify({ да: с.target.checked }) }); загрузить(); } catch (е) { alert(е.message); } } });
    флажок.checked = !!д.подтверждение;
    const переключатель = создать("label", { класс: "флажок-строка" }, флажок,
      создать("span", { текст: "Спрашивать перед запоминанием: новые факты из разговора ждут вашего «Запомнить»" }));
    const кнопка = создать("button", { type: "button", класс: "кнопка второстепенная малая", текст: "Навести порядок сейчас",
      title: "Слить дубли, убрать в архив давно ненужное, предложить обобщения",
      onclick: async () => {
        кнопка.disabled = true; кнопка.textContent = "Навожу порядок…";
        try {
          const р = await запрос("/api/memory/sleep", { method: "POST" });
          alert(`Слито дублей: ${р.слито}. В архив: ${р.забыто}. Предложено обобщений: ${р.обобщений}.`);
        } catch (е) { alert(е.message); }
        загрузить();
      } });
    const предложения = д.предложения.length
      ? создать("ul", { класс: "память-список" }, ...д.предложения.map((п) => создать("li", {},
          создать("div", {}, создать("strong", { текст: п.факт }),
            создать("small", { текст: `${п.категория} · важность ${п.важность}${п.почему ? ` · ${п.почему}` : ""}${п.заменяет.length ? ` · заменит фактов: ${п.заменяет.length}` : ""}` })),
          создать("div", { класс: "роль-кнопки" },
            создать("button", { type: "button", класс: "кнопка малая главная", текст: "Запомнить", onclick: вызвать(`/api/memory/proposals/${п.id}/accept`) }),
            создать("button", { type: "button", класс: "кнопка малая второстепенная", текст: "Не надо", onclick: вызвать(`/api/memory/proposals/${п.id}/reject`) })))))
      : создать("p", { класс: "пусто", текст: "Предложений нет." });
    const архив = д.архив.length
      ? создать("ul", { класс: "память-список" }, ...д.архив.map((ф) => {
          const история = создать("div", { класс: "память-история" });
          return создать("li", {},
            создать("div", {}, создать("span", { текст: ф.факт }), создать("small", { текст: `${ф.состояние === "архив" ? "в архиве" : "устарел"} · ${дата(ф.изменено || ф.создано)}` }), история),
            создать("div", { класс: "роль-кнопки" },
              создать("button", { type: "button", класс: "кнопка малая второстепенная", текст: "Вернуть", onclick: вызвать(`/api/memory/${ф.id}/restore`) }),
              создать("button", { type: "button", класс: "кнопка малая второстепенная", текст: "История", onclick: () => показатьИсторию(ф, история) })));
        }))
      : создать("p", { класс: "пусто", текст: "Архив пуст: ничего не забыто и не слито." });
    тело.replaceChildren(переключатель, кнопка,
      создать("h4", { текст: `Ждут решения · ${д.предложения.length}` }), предложения,
      создать("h4", { текст: `Архив · ${д.архив.length}` }), архив);
  }

  блок.addEventListener("toggle", () => { if (блок.open) загрузить(); });
})();
