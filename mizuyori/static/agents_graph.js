          к.beginPath(); к.arc(у.x, у.y, у.r + 4 + т * 24, 0, Math.PI * 2); к.lineWidth = 3 * (1 - т); к.strokeStyle = прозрачный(ц, (1 - т) * .9); к.stroke();
