    let камера = { x: 0, y: 0, z: 1 }, цель = { x: 0, y: 0, z: 1 };
    let активен = false, кадр = 0, время = 0, прошлый = 0;
    let выбранКабинет = "";
    try { выбранКабинет = localStorage.getItem("mizuyori.агенты.кабинет") || ""; } catch {}
