    // ---- расклад ---------------------------------------------------------------------------------
    function расставить() {
      if (!агенты.length || !ш) return;
      R = 285;
      const сПодписями = Math.min(1, ш / (2 * (R + 172)), в / (2 * (R + 165)));
      подписиВсе = сПодписями >= .78;
      фит = подписиВсе ? сПодписями : Math.min(1, ш / (2 * (R + 96)), в / (2 * (R + 112)));
      const упор = [...агенты].sort((а, б) => (а.порядок_кабинета ?? 99) - (б.порядок_кабинета ?? 99)
        || (а.порядок_отдела ?? 99) - (б.порядок_отдела ?? 99) || Number(Boolean(б.руководитель)) - Number(Boolean(а.руководитель)));
      const группы = [];
      for (const а of упор) {
        const ключК = а.кабинет || "прочее", ключО = `${ключК}/${а.отдел || а.группа || ""}`;
        let кб = группы.find((г) => г.кабинет === ключК);
        if (!кб) группы.push(кб = { кабинет: ключК, отделы: [] });
        let отд = кб.отделы.find((о) => о.ключ === ключО);
        if (!отд) кб.отделы.push(отд = { ключ: ключО, название: а.отдел || а.группа || "", агенты: [] });
        отд.агенты.push(а);
      }
      const ЗАЗОР_КАБИНЕТА = 2.2, ЗАЗОР_ОТДЕЛА = .7;
      let мест = 0;
      for (const г of группы) { мест += г.отделы.reduce((с, о) => с + о.агенты.length + ЗАЗОР_ОТДЕЛА, 0) - ЗАЗОР_ОТДЕЛА + ЗАЗОР_КАБИНЕТА; }
      const шаг = Math.PI * 2 / мест;
      let слот = -Math.PI / 2 / шаг + ЗАЗОР_КАБИНЕТА / 2;
      узлы = []; кабинеты = [];
      for (const г of группы) {
        const нач = слот;
        for (const о of г.отделы) {
          const начО = слот;
          for (const а of о.агенты) {
            const угол = (слот + .5) * шаг;
            const лидер = Boolean(а.руководитель);
            узлы.push({ а, ключ: а.ключ, угол, x: Math.cos(угол) * R, y: Math.sin(угол) * R, r: лидер ? 15 : 11.5, лидер,
              цвет: а.цвет_кабинета || "#6aa9ff", кабинет: г.кабинет, отдел: о.ключ, отделНазвание: о.название });
            слот += 1;
          }
          о.начало = (начО) * шаг; о.конец = слот * шаг;
          слот += ЗАЗОР_ОТДЕЛА;
        }
        слот -= ЗАЗОР_ОТДЕЛА;
        const члены = узлы.filter((у) => у.кабинет === г.кабинет);
        const ц = члены[0]?.цвет || "#6aa9ff";
        const лидер = члены[0];
        кабинеты.push({ ключ: г.кабинет, название: члены[0]?.а.кабинет_название || г.кабинет, цвет: ц, угол0: нач * шаг, угол1: (слот + 1) * шаг, лидер,
          отделы: г.отделы.map((о) => ({ название: о.название, начало: о.начало, конец: о.конец, ключ: о.ключ })) });
        слот += 1 + ЗАЗОР_КАБИНЕТА;
      }
      по = new Map(узлы.map((у) => [у.ключ, у]));
    }

    function размер() {
      const р = лента.getBoundingClientRect();
      dpr = Math.min(2, window.devicePixelRatio || 1);
      ш = Math.max(300, Math.round(р.width)); в = Math.max(300, Math.round(р.height));
      холст.width = Math.round(ш * dpr); холст.height = Math.round(в * dpr);
      расставить();
      применитьФокус(true);
    }

    function применитьФокус(сразу = false) {
      const каб = кабинеты.find((c) => c.ключ === выбранКабинет);
      if (!каб) { цель = { x: 0, y: 0, z: фит }; }
      else {
        const середина = (каб.угол0 + каб.угол1) / 2;
        const z = Math.max(1.35, фит * 1.7);
        цель = { x: -Math.cos(середина) * R * z * .55, y: -Math.sin(середина) * R * z * .55, z };
      }
      if (сразу) камера = { ...цель };
      запустить();
    }

    // ---- данные и события --------------------------------------------------------------------------
    function ролиЛидеров(а) { return а.ключ === а.руководитель; }
    void ролиЛидеров;

    function путь(из, в_) {
      // кривая: середина тянется к центру, как нити между разделами в «Мозгах»
      const mx = (из.x + в_.x) / 2 * .38, my = (из.y + в_.y) / 2 * .38;
      return (t) => { const u = 1 - t; return { x: u * u * из.x + 2 * u * t * mx + t * t * в_.x, y: u * u * из.y + 2 * u * t * my + t * t * в_.y }; };
    }
    const кабинетУзла = (у) => кабинеты.find((c) => c.ключ === у.кабинет);
    function комета(от, кому, цвет, длит = 1.5, подпись = "") {
      const А = от === "ядро" ? { x: 0, y: 0 } : по.get(от), Б = по.get(кому);
      if (!А || !Б || безАнимаций()) { if (Б) эффекты.push({ тип: "вспышка", ключ: кому, t: 0, цвет, подпись }); return; }
      эффекты.push({ тип: "комета", f: путь(А, Б), t: 0, длит, цвет, кому, подпись });
      запустить();
    }
    function волна(ключ, цвет, сила = 1) { эффекты.push({ тип: "волна", ключ, t: 0, цвет, сила }); запустить(); }

    function новыеДанные(д) {
      агенты = д.агенты || [];
      const ключи = агенты.map((а) => `${а.ключ}|${а.кабинет}|${а.отдел}`).join(",");
      if (ключи !== новыеДанные.ключи) { новыеДанные.ключи = ключи; расставить(); применитьФокус(true); }
      for (const а of агенты) {
        const у = по.get(а.ключ); if (у) у.а = а;
        const было = прошлое.get(а.ключ);
        const цв = а.цвет_кабинета || "#6aa9ff";
        if (было && !было.работает && а.работает && у) {
          const каб = кабинетУзла(у);
          if (каб && каб.лидер && каб.лидер !== у) { комета("ядро", каб.лидер.ключ, цв, 1.1); setTimeout(() => комета(каб.лидер.ключ, а.ключ, цв, 1.0), 700); }
          else комета("ядро", а.ключ, цв, 1.4);
          волна(а.ключ, цв, 1.2);
        }
        if (было && было.всего < а.всего && !а.работает) {
          эффекты.push({ тип: "вспышка", ключ: а.ключ, t: 0, цвет: а.ошибка ? "#ff5b5b" : "#4ade80",
            подпись: `${а.ошибка ? "⚠" : "✓"} ${(а.последний_результат || а.последнее_действие || "готово").slice(0, 44)}` });
          запустить();
        }
        прошлое.set(а.ключ, { работает: а.работает, всего: а.всего });
      }
      разобрать(д.письма, "письмо"); разобрать(д.опыт, "опыт");
      запустить();
    }
    function разобрать(список, вид) {
      if (!список) return;
      const был = вид === "письмо" ? последнееПисьмо : последнийОпыт;
      const новыйId = список.length ? Math.max(...список.map((п) => п.id)) : (был ?? 0);
      const новые = список.filter((п) => п.id > (был ?? Infinity)).reverse();
      if (вид === "письмо") последнееПисьмо = новыйId; else последнийОпыт = новыйId;
      for (const п of новые) {
        if (!по.has(п.от)) continue;
        const кому = по.has(п.кому) ? [п.кому] : п.кому === "все" ? агенты.filter((а) => а.ключ !== п.от).slice(0, 4).map((а) => а.ключ) : [];
        const тип = вид === "опыт" ? "опыт" : (п.тип || "работа");
        const цв = тип === "опыт" ? ЦВЕТ_ОПЫТА : тип === "знание" ? ЦВЕТ_ЗНАНИЯ : по.get(п.от).цвет;
        const значок = тип === "опыт" ? "🎓" : тип === "знание" ? "💡" : "📤";
        for (const куда of кому) комета(п.от, куда, цв, 1.6, `${значок} от ${по.get(п.от).а.имя}`);
      }
    }
