// В центре — ядро Mizuyori. Вокруг — кольцо агентов: кабинеты занимают свои дуги, отделы идут подряд,
// руководитель отдела стоит первым. Линии: цепочка по отделу, хорда от начальника кабинета к
// руководителям отделов, нить от ядра к начальнику кабинета. Когда агент берётся за дело, по нитям
// бежит импульс от ядра; когда агенты передают друг другу работу, знание или опыт, импульс бежит
// между ними, а получатель вспыхивает. Колесо — приближение, перетаскивание — сдвиг, клик — окно агента.
// Данные приходят событием mizuyori:агенты из agents.js (тот же опрос /api/agents).
