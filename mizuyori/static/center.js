// «Центр»: одна полоса вкладок вместо пяти кнопок — Журнал · Обмен · Поручения · Доска · Схема · Память.
// Окна открываются боковой панелью справа, круг агентов остаётся виден слева. Старые кнопки живы (их нажимают другие модули).
(() => {
  const шапка = $("агенты-журнал-кнопка")?.parentElement;
  if (!шапка) return;
  const ОКНА = { душа: "окно-души", обмен: "окно-обмена", поручения: "окно-поручений", доска: "окно-доски", схема: "окно-схемы", раздел: "окно-раздела" };
  const СТАРЫЕ = { душа: "", журнал: "агенты-журнал-кнопка", обмен: "агенты-обмен", поручения: "агенты-поручения", доска: "агенты-доска", схема: "агенты-схема" };
  const ИМЕНА = { душа: "♡ Душа", журнал: "Журнал", обмен: "Обмен", поручения: "Поручения", доска: "Доска", схема: "Схема" };

  // ---- душа: её карточки (суть, настроение, черты, ценности, границы, голос) живут в панели «Центра» ----
  const окноДуши = создать("div", { класс: "затемнение", id: "окно-души", hidden: "" });
  const панельДуши = $("душа-панель");
  if (панельДуши) {
    окноДуши.append(создать("div", { класс: "окно душа-окно", role: "dialog", "aria-label": "Душа" },
      создать("div", { класс: "окно-шапка" }, создать("h2", { текст: "Характер и настроение" }),
        создать("button", { класс: "кнопка-значок", type: "button", "aria-label": "Закрыть", текст: "✕", onclick: () => { окноДуши.hidden = true; } })),
      панельДуши));
    document.body.append(окноДуши);
    new MutationObserver(() => { if (!окноДуши.hidden) window.загрузитьДушу?.(); }).observe(окноДуши, { attributes: true, attributeFilter: ["hidden"] });
    document.addEventListener("keydown", (с) => { if (с.key === "Escape" && !окноДуши.hidden) окноДуши.hidden = true; });
  }

  // ---- панель раздела памяти (список записей, поиск) ----
  const окноРаздела = создать("div", { класс: "затемнение", id: "окно-раздела", hidden: "" });
  const заголовокРаздела = создать("h2", { текст: "Память" });
  const поискРаздела = создать("input", { type: "search", placeholder: "Поиск по разделу…", "aria-label": "Поиск по разделу" });
  const телоРаздела = создать("div", { класс: "окно-тело раздел-тело" });
  const закрытьРаздел = создать("button", { класс: "кнопка-значок", type: "button", "aria-label": "Закрыть", текст: "✕", onclick: () => { окноРаздела.hidden = true; } });
  окноРаздела.append(создать("div", { класс: "окно раздел-окно", role: "dialog", "aria-label": "Раздел памяти" },
    создать("div", { класс: "окно-шапка" }, заголовокРаздела, закрытьРаздел),
    создать("div", { класс: "раздел-поиск" }, поискРаздела), телоРаздела));
  document.body.append(окноРаздела);
  let текущийРаздел = "", таймерПоиска = 0;
  const КОГДА = (с) => с ? new Date(с * 1000).toLocaleString("ru-RU", { day: "2-digit", month: "2-digit", hour: "2-digit", minute: "2-digit" }) : "";
  async function загрузитьРаздел() {
    try {
      const р = await запрос(`/api/memory-ring/${encodeURIComponent(текущийРаздел)}?n=80&q=${encodeURIComponent(поискРаздела.value.trim())}`);
      заголовокРаздела.textContent = `${р.значок} ${р.имя}`;
      окноРаздела.style.setProperty("--цвет-раздела", р.цвет);
      телоРаздела.replaceChildren(...(р.записи.length
        ? р.записи.map((з) => создать("div", { класс: "раздел-запись" }, создать("span", { текст: з.текст }), создать("small", { текст: КОГДА(з.создано) })))
        : [создать("p", { класс: "тихо", текст: поискРаздела.value ? "Ничего не найдено." : "Здесь пока пусто." })]));
    } catch { телоРаздела.replaceChildren(создать("p", { класс: "тихо", текст: "Раздел не загрузился." })); }
  }
  поискРаздела.addEventListener("input", () => { clearTimeout(таймерПоиска); таймерПоиска = setTimeout(загрузитьРаздел, 250); });
  document.addEventListener("keydown", (с) => { if (с.key === "Escape" && !окноРаздела.hidden) окноРаздела.hidden = true; });

  // ---- полоса вкладок ----
  const полоса = создать("div", { класс: "центр-вкладки", role: "tablist", "aria-label": "Центр" });
  const кнопки = {};
  for (const ключ of Object.keys(ИМЕНА)) {
    const б = создать("button", { type: "button", role: "tab", "aria-selected": "false", данные: { центр: ключ }, onclick: () => открыть(ключ) }, ИМЕНА[ключ]);
    кнопки[ключ] = б; полоса.append(б);
  }
  // счётчики живут в новых кнопках: agents.js обновляет их по id
  for (const [id, ключ] of [["поручения-счёт", "поручения"], ["доска-счёт", "доска"]]) { const с = $(id); if (с) кнопки[ключ].append(" ", с); }
  шапка.insertBefore(полоса, $("агенты-журнал-кнопка"));
  for (const id of Object.values(СТАРЫЕ)) { const э = id && $(id); if (э) э.hidden = true; }
  // старые кнопки скрываем насовсем: agents_graph.js больше не показывает журнальную
  const скрыть = new MutationObserver(() => { const э = $("агенты-журнал-кнопка"); if (э && !э.hidden) э.hidden = true; });
  скрыть.observe($("агенты-журнал-кнопка"), { attributes: true, attributeFilter: ["hidden"] });

  for (const [ключ, id] of Object.entries(ОКНА)) $(id)?.classList.add("центр-окно", `центр-${ключ}`);
  const подогнатьВерх = () => { document.documentElement.style.setProperty("--центр-верх", `${Math.max(0, Math.round(полоса.getBoundingClientRect().bottom + 8))}px`); };

  function открытыйСейчас() {
    for (const ключ of ["душа", "обмен", "поручения", "доска", "схема"]) if (!$(ОКНА[ключ]).hidden) return ключ;
    if (!окноРаздела.hidden) return "раздел";
    if (!$("журнал-решений").hidden) return "журнал";
    return "";
  }
  function подсветить() {
    const а = открытыйСейчас();
    for (const [ключ, б] of Object.entries(кнопки)) { const вкл = ключ === а; б.classList.toggle("активна", вкл); б.setAttribute("aria-selected", String(вкл)); }
    document.body.classList.toggle("центр-открыт", Boolean(а));
    подогнатьВерх();
  }
  function закрытьВсёКроме(ключ) {
    for (const [к, id] of Object.entries(ОКНА)) if (к !== ключ) { const э = $(id); if (э && !э.hidden) э.hidden = true; }
    if (ключ !== "журнал" && !$("журнал-решений").hidden) $("агенты-журнал-кнопка").click();
  }
  function открыть(ключ) {
    if (ключ === открытыйСейчас()) {              // повторный клик — закрыть
      закрытьВсёКроме("—");
      подсветить(); return;
    }
    закрытьВсёКроме(ключ);
    if (ключ === "душа") окноДуши.hidden = false; else $(СТАРЫЕ[ключ])?.click();
    подсветить();
  }
  // окна могут открыть и другие модули (кнопки на «Сегодня», запись на доске…) — тогда остальные закрываем
  const следить = new MutationObserver((записи) => {
    for (const з of записи) {
      const э = з.target;
      if (э.hidden) continue;
      const ключ = Object.entries(ОКНА).find(([, id]) => id === э.id)?.[0];
      if (ключ) закрытьВсёКроме(ключ);
    }
    подсветить();
  });
  for (const id of Object.values(ОКНА)) следить.observe($(id), { attributes: true, attributeFilter: ["hidden"] });
  следить.observe($("журнал-решений"), { attributes: true, attributeFilter: ["hidden"] });
  addEventListener("resize", подогнатьВерх);
  document.addEventListener("mizuyori:экран", () => setTimeout(подсветить, 50));

  // клики по кругу: ядро → душа, пузырь памяти → список раздела
  document.addEventListener("mizuyori:центр", (с) => {
    const д = с.detail || {};
    if (д.вкладка === "душа") { закрытьВсёКроме("душа"); окноДуши.hidden = false; подсветить(); return; }
    if (д.вкладка === "память" && д.раздел) {
      закрытьВсёКроме("раздел"); текущийРаздел = д.раздел; поискРаздела.value = "";
      окноРаздела.hidden = false; загрузитьРаздел(); подсветить();
    }
  });
  подсветить();
})();
