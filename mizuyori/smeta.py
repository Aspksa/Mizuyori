def _число(з):
    try:
        return None if з is None or з == "" else float(str(з).replace(" ", "").replace(",", "."))
    except ValueError:
        return None


def разобрать_ии(текст: str, настройки_ии: dict) -> dict:
    from . import ai
    ответ = ai._задание(_СИСТЕМА, {"текст_сметы": текст[:ПРЕДЕЛ_ТЕКСТА]}, настройки_ии, 4000)
    найдено = ai._ОБЪЕКТ.search(ответ)
    if not найдено:
        raise ValueError("ИИ не вернул разбор сметы")
    д = json.loads(найдено.group(0))
    позиции = []
    for п in д.get("позиции") or []:
        if not isinstance(п, dict) or not str(п.get("название") or "").strip():
            continue
        позиции.append({"название": " ".join(str(п["название"]).split())[:200],
                        "вид": "материал" if str(п.get("вид")) == "материал" else "работа",
                        "ед": str(п.get("ед") or "")[:12], "кол": _число(п.get("кол")),
                        "цена": _число(п.get("цена")), "сумма": _число(п.get("сумма"))})
    итог = {"позиции": позиции, "итого": _число(д.get("итого")), "ндс": д.get("ндс") if д.get("ндс") in ("включён", "сверху", "нет") else None,
            "ндс_сумма": _число(д.get("ндс_сумма")),
            "замечания_ии": [str(з)[:200] for з in (д.get("замечания") or []) if str(з).strip()][:8]}
    for к in ("объект", "исполнитель", "заказчик", "номер", "дата"):
        з = д.get(к)
        итог[к] = " ".join(str(з).split())[:200] if з not in (None, "", "null") else None
    return итог


def проверить(д: dict) -> list[str]:
    """Арифметика важнее ИИ: пересчитываем и сообщаем о расхождениях."""
    замечания = []
    для_суммы = []
    for п in д["позиции"]:
        к, ц, с = п["кол"], п["цена"], п["сумма"]
        if к is not None and ц is not None and с is not None and abs(к * ц - с) > max(1.0, 0.01 * abs(с)):
            замечания.append(f"«{п['название'][:40]}»: {к:g} × {ц:g} = {к * ц:,.2f}, а в смете {с:,.2f}".replace(",", " "))
        для_суммы.append(с if с is not None else (к * ц if к is not None and ц is not None else None))
    if not д["позиции"]:
        замечания.append("позиций работ и материалов найти не удалось")
    elif None in для_суммы:
        замечания.append("у некоторых позиций нет суммы — итог нельзя пересчитать полностью")
    else:
        посчитано = sum(для_суммы)
        д["посчитано"] = round(посчитано, 2)
        итого = д["итого"]
        if итого is not None:
            ндс = д.get("ндс_сумма") or 0
            if abs(посчитано - итого) > max(1.0, 0.005 * итого) and abs(посчитано + ндс - итого) > max(1.0, 0.005 * итого):
                замечания.append(f"сумма позиций {посчитано:,.2f}, а итог в смете {итого:,.2f}".replace(",", " "))
        else:
            замечания.append("итог в смете не найден — взята сумма позиций")
    return замечания + [f"ИИ: {з}" for з in д.get("замечания_ии", [])]


