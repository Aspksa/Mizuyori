def страницы_картинками(имя: str, данные: bytes, максимум: int = 6) -> list[bytes]:
    if имя.lower().endswith(".pdf"):
        import pypdfium2
        документ = pypdfium2.PdfDocument(данные)
        итог = []
        for i in range(min(len(документ), максимум)):
            буфер = io.BytesIO()
            документ[i].render(scale=1.8).to_pil().convert("RGB").save(буфер, "PNG")
            итог.append(буфер.getvalue())
        return итог
    from PIL import Image
    картинка = Image.open(io.BytesIO(данные)).convert("RGB")
    картинка.thumbnail((2200, 2200))
    буфер = io.BytesIO()
    картинка.save(буфер, "PNG")
    return [буфер.getvalue()]


def найти_авто(база, объект: str | None) -> dict | None:
    """Машина из базы по тексту «объект» сметы: сначала по госномеру, потом по марке и модели (если одна)."""
    if not объект:
        return None
    from . import printing, work
    н = printing._норм(объект).replace(" ", "")
    машины = work.список(база, "автомобили")
    for а in машины:
        номер = printing._норм(а.get("госномер") or "").replace(" ", "")
        if len(номер) >= 5 and номер[:6] in н:
            return а
    подходят = []
    для_поиска = " " + printing._норм(объект) + " "
    for а in машины:
        слова = [с for с in printing._норм(f"{а['марка']} {а['модель']}").split() if len(с) > 2]
        if слова and all(printing._основа(с) in для_поиска or printing._латиницей(printing._основа(с)) in для_поиска for с in слова):
            подходят.append(а)
    return подходят[0] if len(подходят) == 1 else None


def принять(база, настройки_ии: dict, имя: str, данные: bytes) -> dict:
    """Файл → текст → разбор → запись. Возвращает запись сметы (с номером)."""
    _БАЗА[:] = [база]
    if len(данные) > ПРЕДЕЛ_БАЙТ:
        raise СметаНеЧитается("Файл больше 15 МБ — пришлите поменьше.")
    try:
        текст = извлечь_текст(имя, данные)
    except НужноЗрение as ошибка:
        if not настройки_ии.get("модель_зрения"):
            raise СметаНеЧитается(f"{ошибка} Чтобы читать сканы и фото, выберите «Модель для сканов и фото» в настройках ИИ "
                                  "(нужна модель, которая видит картинки), либо пришлите PDF с текстом, Excel или Word.")
        from . import ai
        try:
            картинки = страницы_картинками(имя, данные)
            текст = ai.прочитать_картинки(настройки_ии, картинки, _ЗАДАНИЕ_ЗРЕНИЯ)
        except ai.ОшибкаИИ as e:
            raise СметаНеЧитается(f"Не удалось прочитать скан: {e}")
        except Exception as e:
            журнал.exception("Чтение скана")
            raise СметаНеЧитается(f"Не удалось прочитать скан ({e}). Пришлите PDF с текстом, Excel или Word.")
    if not текст.strip():
        raise СметаНеЧитается("В файле не нашлось текста.")
    ПАПКА_ВЛОЖЕНИЙ.mkdir(parents=True, exist_ok=True)
    безопасное = re.sub(r"[^\w .-]+", "_", имя)[-80:] or "файл"
    путь = ПАПКА_ВЛОЖЕНИЙ / f"{datetime.now():%Y%m%d-%H%M%S}-{безопасное}"
    путь.write_bytes(данные)
    д = разобрать_ии(текст, настройки_ии)
    д["замечания"] = проверить(д)
    авто = найти_авто(база, д.get("объект"))
    with база.соединение() as связь:
        номер = связь.execute("INSERT INTO раб_сметы (имя, файл, данные, автомобиль_id) VALUES (?, ?, ?, ?)",
                              (имя, str(путь), json.dumps(д, ensure_ascii=False), авто["id"] if авто else None)).lastrowid
    return {"id": номер, "имя": имя, "автомобиль_id": авто["id"] if авто else None, **д}


