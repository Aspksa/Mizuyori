class СметаНеЧитается(Exception):
    """Файл нельзя прочитать как текст — пользователю нужен понятный совет."""


class НужноЗрение(СметаНеЧитается):
    """Скан или фото: текст есть только на картинке, прочитать может модель зрения."""


# ---- Чтение файлов --------------------------------------------------------------------------

def _таблица_в_текст(строки) -> str:
    return "\n".join("\t".join("" if я is None else str(я).strip() for я in с).rstrip() for с in строки if any(я not in (None, "") for я in с))


def извлечь_текст(имя: str, данные: bytes) -> str:
    расширение = имя.lower().rsplit(".", 1)[-1] if "." in имя else ""
    if расширение == "pdf":
        from pypdf import PdfReader
        страницы = [(с.extract_text() or "") for с in PdfReader(io.BytesIO(данные)).pages]
        текст = "\n\n".join(страницы).strip()
        if len(re.sub(r"\s+", "", текст)) < 40:
            raise НужноЗрение("Похоже, это скан или фото: текста в PDF нет.")
        return текст
    if расширение in ("xlsx", "xlsm"):
        import openpyxl
        книга = openpyxl.load_workbook(io.BytesIO(данные), data_only=True, read_only=True)
        return "\n\n".join(f"[лист {л.title}]\n" + _таблица_в_текст(л.iter_rows(values_only=True)) for л in книга.worksheets)
    if расширение == "xls":
        import xlrd
        книга = xlrd.open_workbook(file_contents=данные)
        return "\n\n".join(f"[лист {л.name}]\n" + _таблица_в_текст(л.row_values(i) for i in range(л.nrows)) for л in книга.sheets())
    if расширение == "docx":
        import docx
        д = docx.Document(io.BytesIO(данные))
        части = [п.text for п in д.paragraphs if п.text.strip()]
        for т in д.tables:
            части.append(_таблица_в_текст([я.text for я in с.cells] for с in т.rows))
        return "\n".join(части)
    if расширение in ("txt", "csv", "md"):
        for кодировка in ("utf-8-sig", "cp1251"):
            try:
                return данные.decode(кодировка)
            except UnicodeDecodeError:
                continue
    if расширение in ("png", "jpg", "jpeg", "heic", "webp", "tif", "tiff", "bmp"):
        raise НужноЗрение("Это картинка.")
    raise СметаНеЧитается(f"Файлы «.{расширение or '?'}» я не читаю. Подойдут PDF с текстом, Excel (.xlsx/.xls), Word (.docx) и текст.")


