def последняя(база, статус: str | None = None) -> dict | None:
    with база.соединение() as связь:
        р = связь.execute(f"SELECT * FROM раб_сметы {'WHERE статус = ?' if статус else ''} ORDER BY id DESC LIMIT 1",
                          (статус,) if статус else ()).fetchone()
    if not р:
        return None
    return {"id": р["id"], "имя": р["имя"], "статус": р["статус"], "автомобиль_id": р["автомобиль_id"], **json.loads(р["данные"])}


def изменить_статус(база, номер: int, статус: str) -> None:
    with база.соединение() as связь:
        связь.execute("UPDATE раб_сметы SET статус = ? WHERE id = ?", (статус, номер))


def сохранить(база, номер: int, д: dict) -> None:
    with база.соединение() as связь:
        связь.execute("UPDATE раб_сметы SET данные = ? WHERE id = ?", (json.dumps(д, ensure_ascii=False), номер))


def _деньги(з) -> str:
    return "—" if з is None else f"{з:,.2f}".replace(",", " ").replace(".00", "") + " ₽"


def _машина_в_базе(с: dict) -> str:
    if not с.get("автомобиль_id"):
        return " — ⚠ машины в базе не нашлось, ремонт не попадёт в историю машины"
    from . import work
    try:
        из_базы = work.одна(_БАЗА[0], "автомобили", с["автомобиль_id"]) if _БАЗА else None
    except Exception:
        из_базы = None
    return f" → в базе: {work.авто_подпись(из_базы)}" if из_базы else ""


_БАЗА: list = []        # база подставляется при приёме и поправке сметы — нужна только для подписи машины


def описание(с: dict) -> str:
    """Что агент понял — для сообщения в чат."""
    строки = [f"📎 Смета «{с['имя']}» принята. Вот что я понял:", "",
              f"- **Объект:** {с['объект'] or 'не указан'}" + _машина_в_базе(с),
              f"- **Исполнитель:** {с['исполнитель'] or 'не указан'}",
              f"- **Заказчик:** {с['заказчик'] or 'не указан'}",
              f"- **Номер / дата:** {с['номер'] or '—'} / {с['дата'] or '—'}",
              f"- **Итого:** {_деньги(с['итого'] if с['итого'] is not None else с.get('посчитано'))}"
              + (f" (НДС {с['ндс']})" if с.get("ндс") else ""), ""]
    работы = [п for п in с["позиции"] if п["вид"] == "работа"]
    материалы = [п for п in с["позиции"] if п["вид"] == "материал"]
    for название, список in (("Работы", работы), ("Материалы", материалы)):
        if список:
            строки.append(f"**{название} ({len(список)}):**")
            строки += [f"- {п['название']} — {п['кол']:g} {п['ед']} × {_деньги(п['цена'])} = {_деньги(п['сумма'])}".replace("  ", " ")
                       if п["кол"] is not None else f"- {п['название']} — {_деньги(п['сумма'])}" for п in список[:12]]
            if len(список) > 12:
                строки.append(f"- …и ещё {len(список) - 12}")
            строки.append("")
    if с["замечания"]:
        строки += ["⚠ **Проверьте:**"] + [f"- {з}" for з in с["замечания"][:8]] + [""]
    строки.append("Если всё верно — напишите **«подтверждаю смету»**. Если что-то не так — поправьте словами "
                  "(«в смете исполнитель ООО Ромашка», «итого 125 000»), и я исправлю.")
    return "\n".join(строки)


_ПОПРАВКА_СИСТЕМА = (
    "Хозяин поправляет разобранную смету. Тебе дают текущий JSON сметы и его слова. Верни ТОЛЬКО изменённые поля "
    "одним JSON с теми же ключами (объект, исполнитель, заказчик, номер, дата, итого, ндс, позиции — целиком, если меняются позиции). "
    "Ничего не выдумывай сверх слов хозяина. Если поправки понять нельзя — {}."
)


def поправить(база, настройки_ии: dict, с: dict, слова: str) -> dict:
    from . import ai
    текущее = {к: с.get(к) for к in ("объект", "исполнитель", "заказчик", "номер", "дата", "итого", "ндс", "позиции")}
    ответ = ai._задание(_ПОПРАВКА_СИСТЕМА, {"смета": текущее, "слова_хозяина": слова}, настройки_ии, 3000)
    найдено = ai._ОБЪЕКТ.search(ответ)
    изменения = json.loads(найдено.group(0)) if найдено else {}
    принято = []
    for к in ("объект", "исполнитель", "заказчик", "номер", "дата"):
        if isinstance(изменения.get(к), str) and изменения[к].strip():
            с[к] = " ".join(изменения[к].split())[:200]; принято.append(к)
    if _число(изменения.get("итого")) is not None:
        с["итого"] = _число(изменения["итого"]); принято.append("итого")
    if изменения.get("ндс") in ("включён", "сверху", "нет"):
        с["ндс"] = изменения["ндс"]; принято.append("ндс")
    if isinstance(изменения.get("позиции"), list) and изменения["позиции"]:
        новые = []
        for п in изменения["позиции"]:
            if isinstance(п, dict) and str(п.get("название") or "").strip():
                новые.append({"название": " ".join(str(п["название"]).split())[:200],
                              "вид": "материал" if str(п.get("вид")) == "материал" else "работа",
                              "ед": str(п.get("ед") or "")[:12], "кол": _число(п.get("кол")),
                              "цена": _число(п.get("цена")), "сумма": _число(п.get("сумма"))})
        if новые:
            с["позиции"] = новые; принято.append("позиции")
    с["замечания_ии"] = []          # прежние замечания ИИ относились к старому разбору
    с["замечания"] = проверить(с)
    _БАЗА[:] = [база]
    if "объект" in принято:
        авто = найти_авто(база, с.get("объект"))
        с["автомобиль_id"] = авто["id"] if авто else None
        with база.соединение() as связь:
            связь.execute("UPDATE раб_сметы SET автомобиль_id = ? WHERE id = ?", (с["автомобиль_id"], с["id"]))
    сохранить(база, с["id"], {к: з for к, з in с.items() if к not in ("id", "имя", "статус", "автомобиль_id")})
    return {"принято": принято, "смета": с}


# ---- История ремонтов машины ---------------------------------------------------------------------------

def записать_ремонт(база, с: dict) -> dict | None:
    """Подтверждённая смета → запись в историю ремонтов машины (если машина найдена в базе)."""
    if not с.get("автомобиль_id"):
        return None
    from . import work
    дата = с.get("дата") if re.fullmatch(r"\d{4}-\d{2}-\d{2}", str(с.get("дата") or "")) else datetime.now().strftime("%Y-%m-%d")
    итого = с["итого"] if с.get("итого") is not None else с.get("посчитано")
    пробег = work.пробеги(база).get(с["автомобиль_id"])
    with база.соединение() as связь:
        связь.execute("DELETE FROM раб_ремонты WHERE смета_id = ?", (с["id"],))     # повторное подтверждение не дублирует
        номер = связь.execute(
            "INSERT INTO раб_ремонты (автомобиль_id, смета_id, дата, исполнитель, итого, пробег, позиции) VALUES (?, ?, ?, ?, ?, ?, ?)",
            (с["автомобиль_id"], с["id"], дата, с.get("исполнитель") or "", итого, пробег,
             json.dumps(с["позиции"], ensure_ascii=False))).lastrowid
    return {"id": номер, "дата": дата, "итого": итого}


def ремонты(база, автомобиль_id: int | None = None, месяцев: int | None = None) -> list[dict]:
    условия, параметры = [], []
    if автомобиль_id:
        условия.append("автомобиль_id = ?"); параметры.append(автомобиль_id)
    if месяцев:
        условия.append("дата >= date('now', 'localtime', ?)"); параметры.append(f"-{int(месяцев) * 31} day")
    with база.соединение() as связь:
        строки = связь.execute(f"SELECT * FROM раб_ремонты {'WHERE ' + ' AND '.join(условия) if условия else ''} "
                               "ORDER BY дата DESC, id DESC", параметры).fetchall()
    итог = []
    for р in строки:
        позиции = json.loads(р["позиции"])
        итог.append({"id": р["id"], "автомобиль_id": р["автомобиль_id"], "смета_id": р["смета_id"], "дата": р["дата"],
                     "исполнитель": р["исполнитель"], "итого": р["итого"], "пробег": р["пробег"],
                     "работы": [п["название"] for п in позиции if п["вид"] == "работа"],
                     "материалы": [п["название"] + (f" ×{п['кол']:g}" if п.get("кол") not in (None, 1, 1.0) else "")
                                   for п in позиции if п["вид"] == "материал"]})
    return итог
