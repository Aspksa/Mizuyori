"""Знания о вашей работе: личные факты агентов, общий справочник техники и контрагентов, обучение на правках.

- Факты агента («Снабженец: Для Hilux берём фильтры VIC, цену сверяем с Автодоктором») лежат у конкретного агента
  и попадают в его задание, если подходят к запросу.
- Справочник общий: машина или контрагент с другими названиями и сведениями. Если запрос называет их (по названию,
  алиасу, госномеру, модели или ИНН), любой агент получает короткую справку. Живые данные («Работа» → автомобили и
  контрагенты) подтягиваются сами, вручную нужны только алиасы и пометки.
- Правки: когда вы переписали результат шага поручения, различие записывается агенту как частая ошибка и событие
  для учёбы, а его личной памяти достаётся факт «в таких случаях хозяин хотел так».
"""
from __future__ import annotations

import logging
import re

from . import agents

журнал = logging.getLogger("mizuyori.знания")

ФАКТОВ_В_ЗАДАНИИ = 5
СПРАВОК_В_ЗАДАНИИ = 5
ВИДЫ = ("техника", "контрагент", "другое")


def _норма(текст: str) -> str:
    return " ".join(re.sub(r"[^a-zа-я0-9]+", " ", (текст or "").casefold().replace("ё", "е")).split())


def _слитно(текст: str) -> str:
    return _норма(текст).replace(" ", "")


# ---- Личные факты агента ----------------------------------------------------------------------

def факты(ключ: str) -> list[dict]:
    with agents._база.соединение() as с:
        return [dict(х) for х in с.execute(
            "SELECT id, агент, текст, источник, создано FROM агент_факты WHERE агент = ? ORDER BY id DESC", (ключ,)).fetchall()]


def добавить_факт(ключ: str, текст: str, источник: str = "вы") -> dict:
    текст = " ".join((текст or "").split())[:300]
    if not текст:
        raise ValueError("Пустой факт.")
    with agents._база.соединение() as с:
        for ид, старый in с.execute("SELECT id, текст FROM агент_факты WHERE агент = ?", (ключ,)).fetchall():
            if _норма(старый) == _норма(текст):          # lower() в SQLite не знает кириллицу — сравниваем в Python
                return {"id": ид, "агент": ключ, "текст": старый, "источник": источник, "уже_есть": True}
        номер = с.execute("INSERT INTO агент_факты (агент, текст, источник) VALUES (?, ?, ?)", (ключ, текст, источник)).lastrowid
    return {"id": номер, "агент": ключ, "текст": текст, "источник": источник, "уже_есть": False}


def удалить_факт(номер: int) -> bool:
    with agents._база.соединение() as с:
        return с.execute("DELETE FROM агент_факты WHERE id = ?", (номер,)).rowcount > 0


def факты_для(ключ: str, запрос: str = "", сколько: int = ФАКТОВ_В_ЗАДАНИИ) -> list[dict]:
    """Подходящие к запросу факты, затем самые свежие — всего не больше `сколько`."""
    все = факты(ключ)
    слова = agents._основы(запрос)
    подходят = [(len(слова & agents._основы(х["текст"])), х) for х in все]
    выбранные = [х for о, х in sorted(подходят, key=lambda п: -п[0]) if о > 0][:сколько]
    for х in все:
        if len(выбранные) >= сколько:
            break
        if х not in выбранные:
            выбранные.append(х)
    return выбранные


# ---- Общий справочник -------------------------------------------------------------------------

def _ручные() -> list[dict]:
    with agents._база.соединение() as с:
        return [dict(х) for х in с.execute("SELECT id, вид, название, алиасы, сведения, создано, изменено FROM справочник ORDER BY вид, название").fetchall()]


def список() -> list[dict]:
    return _ручные()


def _проверить(вид: str, название: str, алиасы: str, сведения: str) -> tuple[str, str, str, str]:
    название = " ".join((название or "").split())[:120]
    if not название:
        raise ValueError("Укажите название.")
    if вид not in ВИДЫ:
        raise ValueError("Вид: техника, контрагент или другое.")
    алиасы = ", ".join(а for а in (" ".join(х.split()) for х in (алиасы or "").replace(";", ",").split(",")) if а)[:300]
    return вид, название, алиасы, " ".join((сведения or "").split())[:600]


def добавить(вид: str, название: str, алиасы: str = "", сведения: str = "") -> dict:
    вид, название, алиасы, сведения = _проверить(вид, название, алиасы, сведения)
    with agents._база.соединение() as с:
        if any(_норма(н) == _норма(название) for (н,) in с.execute("SELECT название FROM справочник WHERE вид = ?", (вид,)).fetchall()):
            raise ValueError("Такая запись уже есть.")
        номер = с.execute("INSERT INTO справочник (вид, название, алиасы, сведения) VALUES (?, ?, ?, ?)",
                          (вид, название, алиасы, сведения)).lastrowid
        return dict(с.execute("SELECT id, вид, название, алиасы, сведения, создано, изменено FROM справочник WHERE id = ?", (номер,)).fetchone())


def изменить(номер: int, вид: str, название: str, алиасы: str = "", сведения: str = "") -> dict | None:
    вид, название, алиасы, сведения = _проверить(вид, название, алиасы, сведения)
    with agents._база.соединение() as с:
        if not с.execute("UPDATE справочник SET вид = ?, название = ?, алиасы = ?, сведения = ?, "
                         "изменено = datetime('now', 'localtime') WHERE id = ?", (вид, название, алиасы, сведения, номер)).rowcount:
            return None
        return dict(с.execute("SELECT id, вид, название, алиасы, сведения, создано, изменено FROM справочник WHERE id = ?", (номер,)).fetchone())


def удалить(номер: int) -> bool:
    with agents._база.соединение() as с:
        return с.execute("DELETE FROM справочник WHERE id = ?", (номер,)).rowcount > 0


def _живые() -> list[dict]:
    """Машины и контрагенты из «Работы» как записи справочника (без записи в базу)."""
    итог = []
    try:
        with agents._база.соединение() as с:
            for м in с.execute("SELECT марка, модель, госномер, топливо, заметка FROM раб_автомобили").fetchall():
                имя = " ".join(f"{м['марка']} {м['модель']}".split())
                если = [х for х in (имя, м["модель"], м["госномер"]) if х]
                сведения = ", ".join(х for х in (f"госномер {м['госномер']}" if м["госномер"] else "",
                                                 f"топливо {м['топливо']}" if м["топливо"] else "", м["заметка"]) if х)
                if если:
                    итог.append({"вид": "техника", "название": имя or м["госномер"], "имена": если, "сведения": сведения})
            for к in с.execute("SELECT название, инн, контакт, телефон, заметка FROM раб_контрагенты").fetchall():
                имена = [х for х in (к["название"], к["инн"]) if х]
                сведения = ", ".join(х for х in (f"ИНН {к['инн']}" if к["инн"] else "", f"контакт {к['контакт']}" if к["контакт"] else "",
                                                 к["телефон"], к["заметка"]) if х)
                if имена:
                    итог.append({"вид": "контрагент", "название": к["название"], "имена": имена, "сведения": сведения})
    except Exception:
        журнал.debug("Живые данные справочника недоступны", exc_info=True)
    return итог


def _все_записи() -> list[dict]:
    """Ручные записи плюс живые; одна и та же машина или контрагент (по названию) склеиваются в одну справку."""
    итог: dict[tuple[str, str], dict] = {}
    for ж in _живые():
        итог[(ж["вид"], _норма(ж["название"]))] = dict(ж)
    for р in _ручные():
        имена = [р["название"]] + [а.strip() for а in р["алиасы"].split(",") if а.strip()]
        ключ = (р["вид"], _норма(р["название"]))
        если = итог.get(ключ)
        if если:
            если["имена"] = list(dict.fromkeys(если["имена"] + имена))
            если["сведения"] = ", ".join(х for х in (если["сведения"], р["сведения"]) if х)
        else:
            итог[ключ] = {"вид": р["вид"], "название": р["название"], "имена": имена, "сведения": р["сведения"]}
    return list(итог.values())


def _назван(запрос_норма: str, запрос_слитно: str, имена: list[str]) -> bool:
    for имя in имена:
        н = _норма(имя)
        if len(н) >= 3 and re.search(rf"(?<![a-zа-я0-9]){re.escape(н)}(?![a-zа-я0-9])", запрос_норма):
            return True
        # госномер и ИНН пишут по-разному: «а123вс 25», «А 123 ВС» — сравниваем без пробелов
        с = _слитно(имя)
        if len(с) >= 6 and re.search(r"\d", с) and с in запрос_слитно:
            return True
    return False


def найти(запрос: str, сколько: int = СПРАВОК_В_ЗАДАНИИ) -> list[dict]:
    """Записи справочника, названные в запросе."""
    н, с = _норма(запрос), _слитно(запрос)
    if not н or not agents._база:
        return []
    return [з for з in _все_записи() if _назван(н, с, з["имена"])][:сколько]


def справка(запрос: str) -> str:
    найденные = найти(запрос)
    if not найденные:
        return ""
    ПОДПИСИ = {"техника": "техника", "контрагент": "контрагент", "другое": "запись"}
    return "Справочник предприятия (по тому, что названо в запросе; используй эти названия и сведения):\n" + "\n".join(
        f"- {ПОДПИСИ[з['вид']]} «{з['название']}»" + (f" (также: {', '.join(i for i in з['имена'] if _норма(i) != _норма(з['название']))})"
                                                      if len({_норма(i) for i in з['имена']}) > 1 else "")
        + (f": {з['сведения']}" if з["сведения"] else "") for з in найденные)


def контекст(ключ: str, запрос: str = "") -> str:
    """Личные факты агента и справка по названному в запросе — добавляется к заданию ИИ (agents.правила)."""
    части = []
    try:
        ф = факты_для(ключ, запрос)
        if ф:
            части.append("Что ты знаешь о работе хозяина (учитывай, если уместно):\n" + "\n".join(f"- {х['текст']}" for х in ф))
        справочная = справка(запрос)
        if справочная:
            части.append(справочная)
    except Exception:
        журнал.debug("Знания недоступны", exc_info=True)
    return "\n\n".join(части)


# ---- Правки результатов -----------------------------------------------------------------------

def _суть_правки(до: str, после: str) -> str:
    """Кратко: что хозяин изменил — для заметки об ошибке (без ИИ)."""
    слова_до, слова_после = set(_норма(до).split()), set(_норма(после).split())
    добавлено = [с for с in _норма(после).split() if с not in слова_до][:12]
    убрано = [с for с in _норма(до).split() if с not in слова_после][:12]
    части = []
    if добавлено:
        части.append("добавил: " + " ".join(добавлено))
    if убрано:
        части.append("убрал: " + " ".join(убрано))
    return "; ".join(части) or "переписал по-своему"


def записать_правку(ключ: str, поручение: str, шаг: int, до: str, после: str) -> dict:
    """Хозяин заменил результат шага. Агент запоминает различие и узнаёт, как хозяин хотел."""
    до, после = (до or "").strip(), (после or "").strip()
    if not после or _норма(до) == _норма(после):
        return {"записано": False}
    with agents._база.соединение() as с:
        с.execute("INSERT INTO правки_результатов (агент, поручение, шаг, до, после) VALUES (?, ?, ?, ?, ?)",
                  (ключ, поручение[:200], шаг, до[:4000], после[:4000]))
    суть = _суть_правки(до, после)
    agents.запомнить_ошибку(ключ, f"Хозяин переписал результат («{поручение[:60]}»): {суть}"[:200])
    добавить_факт(ключ, f"В поручении «{поручение[:50]}» хозяин принял такой результат: {' '.join(после.split())[:180]}", "правка")
    try:
        from . import learning
        learning.событие(ключ, "правка", {"поручение": поручение[:120], "я_ответил": " ".join(до.split())[:500],
                                          "хозяин_исправил_на": " ".join(после.split())[:500], "что_изменилось": суть})
    except Exception:
        журнал.exception("Не удалось передать правку в учёбу")
    return {"записано": True, "суть": суть}


def последние_правки(ключ: str, сколько: int = 10) -> list[dict]:
    with agents._база.соединение() as с:
        return [dict(х) for х in с.execute(
            "SELECT id, поручение, шаг, до, после, создано FROM правки_результатов WHERE агент = ? ORDER BY id DESC LIMIT ?",
            (ключ, сколько)).fetchall()]
