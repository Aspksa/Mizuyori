def разметить(список_агентов: list[dict]) -> None:
    """Проставляет каждому агенту кабинет, отдел и роль в нём; переименовывает тех, кто переехал.
    Меняет словари на месте: общий список agents.АГЕНТЫ и словарь agents.ИМЕНА."""
    где = _где()
    порядок = {о["название"]: н for н, о in enumerate(о for к in КАБИНЕТЫ for о in к["отделы"])}
    for а in список_агентов:
        for поле, значение in ПЕРЕИМЕНОВАНИЯ.get(а["ключ"], {}).items():
            а[поле] = значение
        agents.ИМЕНА[а["ключ"]] = а["имя"]
        место = где.get(а["ключ"])
        if место:
            каб, о = место
            а["кабинет"] = каб["ключ"]
            а["группа"] = о["название"]
            а["отдел"] = о["название"]
            а["порядок_отдела"] = порядок[о["название"]]
            а["порядок_кабинета"] = [к["ключ"] for к in КАБИНЕТЫ].index(каб["ключ"])
            а["кабинет_название"] = каб["название"]
            а["руководитель"] = о["руководитель"] == а["ключ"]
            а["цвет_кабинета"] = каб["цвет"]


