def наблюдать_дог_ведущего(база) -> list[dict]:
    итог = []
    for д in _договоры_все(база):
        if д["вид"] != "договор":
            continue
        имя = f"Договор №{д['номер'] or 'б/н'} ({д['контрагент'] or 'без контрагента'})"
        if not (д.get("предмет") or "").strip():
            итог.append(_зам(f"{имя}: не заполнен предмет", 1, "дог_архив"))
        if not д.get("сумма"):
            итог.append(_зам(f"{имя}: нет суммы или порядка цены", 0))
    return итог[:6]


def наблюдать_дог_аренды(база) -> list[dict]:
    сегодня = date.today()
    итог = []
    for д in _договоры_все(база):
        текст = f"{д.get('предмет') or ''} {д.get('заметка') or ''}".lower()
        if not any(с in текст for с in ("аренд", "лизинг")) or not д.get("окончание"):
            continue
        осталось = (date.fromisoformat(д["окончание"]) - сегодня).days
        if 30 < осталось <= 90:
            итог.append(_зам(f"Договор №{д['номер'] or 'б/н'} ({д['контрагент']}): аренда или лизинг заканчивается через {осталось} дн. Решите заранее: продлевать, менять или возвращать", 1))
    return итог[:5]


def наблюдать_дебиторку(база) -> list[dict]:
    сегодня = date.today()
    итог = []
    for д in _договоры_все(база):
        if not д.get("оплачено") and д.get("срок_оплаты"):
            дней = (сегодня - date.fromisoformat(д["срок_оплаты"])).days
            if дней >= 10:
                итог.append(_зам(f"Договор №{д['номер'] or 'б/н'} ({д['контрагент']}): просрочка {дней} дн. Пора готовить претензию", 2 if дней >= 30 else 1, "юрист"))
    return итог[:5]


