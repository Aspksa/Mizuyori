def наблюдать_парк_экономиста(база) -> list[dict]:
    машины = {m["id"]: m for m in _машины(база)}
    суммы: dict[int, tuple[float, int]] = {}
    for р in _ремонты(база):
        с, н = суммы.get(р["автомобиль_id"], (0, 0))
        суммы[р["автомобиль_id"]] = (с + (р.get("итого") or 0), н + 1)
    if len(суммы) < 3:
        return []
    средняя = sum(с for с, _ in суммы.values()) / len(суммы)
    итог = []
    for а_id, (с, н) in sorted(суммы.items(), key=lambda п: -п[1][0])[:2]:
        if средняя and с >= средняя * 1.5 and н >= 3 and а_id in машины:
            итог.append(_зам(f"{work.авто_подпись(машины[а_id])}: за всё время {н} ремонтов на {_руб(с)}, выше среднего по парку в {с / средняя:.1f} раза. Подумать о замене", 1))
    return итог


