_ИИ_ПРЕДЕЛЫ = {"температура": (0.0, 1.5), "длина": (100, 16000), "история": (0, 100)}


def проверить_ии(данные, строго: bool = False) -> dict:
    итог = dict(ИИ_ПО_УМОЛЧАНИЮ)
    if not isinstance(данные, dict):
        if строго:
            raise НеверныйВнешнийВид("Ожидался набор настроек ИИ.")
        return итог
    for ключ, значение in данные.items():
        if ключ not in ИИ_ПО_УМОЛЧАНИЮ:
            if строго:
                raise НеверныйВнешнийВид(f"Неизвестная настройка ИИ «{ключ}».")
            continue
        образец = ИИ_ПО_УМОЛЧАНИЮ[ключ]
        if isinstance(образец, bool):
            верно = isinstance(значение, bool)
        elif ключ in _ИИ_ПРЕДЕЛЫ:
            низ, верх = _ИИ_ПРЕДЕЛЫ[ключ]
            верно = isinstance(значение, (int, float)) and not isinstance(значение, bool) and низ <= значение <= верх
        else:
            верно = isinstance(значение, str) and len(значение) <= 8000
        if ключ == "адрес" and верно:
            верно = значение.startswith(("https://", "http://"))
        if not верно:
            if строго:
                raise НеверныйВнешнийВид(f"Неверное значение «{ключ}».")
            журнал.warning("ИИ: «%s» — неверное значение, беру значение по умолчанию.", ключ)
            continue
        if ключ in ("длина", "история"):
            значение = int(значение)
        elif ключ == "температура":
            значение = float(значение)
        elif isinstance(значение, str):
            значение = значение.strip() if ключ != "характер" else значение
        итог[ключ] = значение
    return итог


