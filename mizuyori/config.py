"""Настройки из config.json. Файл создаётся сам при первом запуске."""

import json
import logging
import threading
from pathlib import Path

журнал = logging.getLogger("mizuyori.настройки")

# Цвета сайта: ключ — значение в config.json, справа — название в окне настроек
ТЕМЫ = {
    "тёмно-чёрный": "Тёмно-чёрный",
    "золото": "Золото",
    "янтарь": "Янтарь",
    "нефрит": "Нефрит",
}

ПО_УМОЛЧАНИЮ = {
    "имя": "Mizuyori",
    "тема": "тёмно-чёрный",
    "порт": 8000,
    "открывать_браузер": True,
    "доступ_из_сети": False,
}

ПОЯСНЕНИЯ = {
    "имя": "название в заголовке страницы",
    "тема": "цвет сайта: " + ", ".join(ТЕМЫ),
    "порт": "с какого порта начинать; если занят, берётся следующий свободный",
    "открывать_браузер": "открывать браузер сам при запуске (true / false)",
    "доступ_из_сети": "true — открывать с телефона и других устройств в этой сети",
}


def _проверить(настройки: dict) -> dict:
    """Исправляет неверные значения на значения по умолчанию."""
    итог = dict(ПО_УМОЛЧАНИЮ)
    for ключ, значение in настройки.items():
        if ключ.startswith("_"):
            continue
        if ключ not in ПО_УМОЛЧАНИЮ:
            журнал.warning("Неизвестная настройка «%s» — пропускаю.", ключ)
            continue
        нужный_тип = type(ПО_УМОЛЧАНИЮ[ключ])
        if type(значение) is not нужный_тип:
            журнал.warning("Настройка «%s» = %r имеет неверный тип, беру %r.",
                           ключ, значение, ПО_УМОЛЧАНИЮ[ключ])
            continue
        итог[ключ] = значение

    if not 1 <= итог["порт"] <= 65535:
        журнал.warning("Порт %s вне диапазона 1–65535, беру %s.", итог["порт"], ПО_УМОЛЧАНИЮ["порт"])
        итог["порт"] = ПО_УМОЛЧАНИЮ["порт"]
    if итог["тема"] not in ТЕМЫ:
        журнал.warning("Неизвестная тема «%s», беру «%s».", итог["тема"], ПО_УМОЛЧАНИЮ["тема"])
        итог["тема"] = ПО_УМОЛЧАНИЮ["тема"]
    if not итог["имя"].strip():
        итог["имя"] = ПО_УМОЛЧАНИЮ["имя"]
    return итог


_замок = threading.Lock()


def _сохранить(файл: Path, настройки: dict) -> None:
    with _замок:
        _записать(файл, настройки)


def _записать(файл: Path, настройки: dict) -> None:
    данные = {"_пояснения": ПОЯСНЕНИЯ, **настройки}
    временный = файл.with_suffix(".tmp")
    временный.write_text(json.dumps(данные, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    временный.replace(файл)


def загрузить_настройки(файл: Path) -> dict:
    """Читает config.json, дополняет недостающее и исправляет ошибки."""
    if not файл.exists():
        журнал.info("Создаю файл настроек %s", файл.name)
        _сохранить(файл, ПО_УМОЛЧАНИЮ)
        return dict(ПО_УМОЛЧАНИЮ)

    try:
        # utf-8-sig: файл, сохранённый Блокнотом с BOM, тоже читается
        прочитано = json.loads(файл.read_text(encoding="utf-8-sig"))
        if not isinstance(прочитано, dict):
            raise ValueError("ожидался объект { ... }")
    except (ValueError, OSError) as ошибка:
        копия = файл.with_name(файл.stem + ".broken.json")
        журнал.error("Файл %s повреждён (%s). Сохраняю его как %s и создаю новый.",
                     файл.name, ошибка, копия.name)
        файл.replace(копия)
        _сохранить(файл, ПО_УМОЛЧАНИЮ)
        return dict(ПО_УМОЛЧАНИЮ)

    настройки = _проверить(прочитано)
    # Дописываем новые настройки, которых не было в старом файле
    if any(ключ not in прочитано for ключ in ПО_УМОЛЧАНИЮ) or "_пояснения" not in прочитано:
        _сохранить(файл, настройки)
    return настройки


def сохранить_настройки(файл: Path, настройки: dict) -> None:
    """Записывает изменённые настройки (например, из окна настроек на сайте)."""
    _сохранить(файл, настройки)
