ВИД_ПО_УМОЛЧАНИЮ = {ключ: о["по_умолчанию"] for ключ, о in ВНЕШНИЙ_ВИД.items()}


class НеверныйВнешнийВид(ValueError):
    pass


def проверить_внешний_вид(данные: dict, строго: bool = False) -> dict:
    """Проверяет настройки внешнего вида.

    строго=True  — при ошибке исключение (для запросов с сайта);
    строго=False — неверное заменяется значением по умолчанию (для config.json).
    """
    итог = dict(ВИД_ПО_УМОЛЧАНИЮ)
    if not isinstance(данные, dict):
        if строго:
            raise НеверныйВнешнийВид("Ожидался набор настроек внешнего вида.")
        журнал.warning("«внешний_вид» в config.json испорчен, беру значения по умолчанию.")
        return итог

    for ключ, значение in данные.items():
        описание = ВНЕШНИЙ_ВИД.get(ключ)
        if описание is None:
            if строго:
                raise НеверныйВнешнийВид(f"Неизвестная настройка «{ключ}».")
            журнал.warning("Неизвестная настройка внешнего вида «%s» — пропускаю.", ключ)
            continue
        if isinstance(описание["по_умолчанию"], bool):
            верно = isinstance(значение, bool)
        else:
            верно = isinstance(значение, str) and значение in описание["варианты"]
        if not верно:
            if строго:
                raise НеверныйВнешнийВид(f"Неверное значение «{описание['название']}»: {значение!r}.")
            журнал.warning("«%s» = %r — неверно, беру %r.", ключ, значение, описание["по_умолчанию"])
            continue
        итог[ключ] = значение
    return итог


def атрибуты_html(вид: dict) -> str:
    """data-атрибуты для <html>, чтобы страница сразу открывалась в нужном виде."""
    части = []
    for ключ, описание in ВНЕШНИЙ_ВИД.items():
        значение = вид[ключ]
        if isinstance(значение, bool):
            значение = "да" if значение else "нет"
        части.append(f'data-{описание["атрибут"]}="{html.escape(значение)}"')
    return " ".join(части)


