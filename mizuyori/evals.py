def вопросы() -> list[dict]:
    """Свой список из базы (если задан и подключена база), иначе встроенный."""
    свои = None
    try:
        свои = decisions._база.прочитать(КЛЮЧ_СВОИХ, None) if decisions._база else None
    except Exception:
        свои = None
    return _проверить_вопросы(свои) or ВОПРОСЫ


def _проверить_вопросы(список) -> list[dict]:
    итог = []
    for в in (список or [])[:МАКС_ВОПРОСОВ]:
        if isinstance(в, dict) and str(в.get("вопрос") or "").strip() and str(в.get("должно") or "").strip() and в.get("кабинет") in collective.ГЛАВНЫЕ_КАБИНЕТЫ:
            итог.append({"id": str(в.get("id") or f"св-{len(итог) + 1}")[:20], "кабинет": в["кабинет"], "вопрос": str(в["вопрос"])[:400],
                         "должно": str(в["должно"])[:500], "нельзя": str(в.get("нельзя") or "")[:300]})
    return итог


def задать_свои(список: list) -> int:
    """Сохраняет свой набор вопросов (пустой список — вернуться к встроенному). Возвращает, сколько принято."""
    годные = _проверить_вопросы(список)
    decisions._база.записать(КЛЮЧ_СВОИХ, годные)
    return len(годные)


def _прогоны() -> list[dict]:
    try:
        return list(decisions._база.прочитать(КЛЮЧ_ПРОГОНОВ, [])) if decisions._база else []
    except Exception:
        return []


def прогоны(сколько: int = 5) -> list[dict]:
    return list(reversed(_прогоны()[-сколько:]))


def _ответить(н: dict, в: dict) -> str:
    лидер = collective.руководитель(в["кабинет"])
    система = (f"Ты — {agents.ИМЕНА.get(лидер, лидер)}, руководитель кабинета «{collective.название(в['кабинет'])}», помощник отдела главного механика. "
               "Отвечай по-русски, коротко и по делу, не длиннее 8 строк. " + decisions.ЗАЩИТА_ОТ_ВЫДУМОК)
    with agents.работа(лидер, "ответил на эталонный вопрос", f"проверка: «{в['вопрос'][:60]}»") as з:
        текст = (ai._задание(система, {"вопрос": в["вопрос"]}, agents.с_правилами(dict(н), лидер, в["вопрос"]), 500) or "").strip()
        з["результат"] = f"ответ {len(текст)} знаков"
    return текст


def _оценить(н: dict, в: dict, ответ: str) -> tuple[float, str]:
    try:
        р = missions._json_из_текста(ai._задание(_СИСТЕМА_СУДЬИ, {"вопрос": в["вопрос"], "ответ": ответ, "должно_быть": в["должно"],
                                                                  "не_должно_быть": в.get("нельзя", "")}, dict(н), 300))
        балл = float(р["балл"]) if isinstance(р, dict) and "балл" in р else None
    except Exception:
        журнал.warning("Судья не оценил ответ", exc_info=True)
        балл, р = None, None
    if балл is None or балл not in (0.0, 0.5, 1.0):
        return -1.0, "судья не ответил по форме"
    return балл, " ".join(str((р or {}).get("замечание") or "").split())[:200]


def прогон(н: dict, кабинеты: list[str] | None = None) -> dict:
    """Синхронно прогоняет вопросы. Возвращает запись прогона (она же сохраняется в историю)."""
    список = [в for в in вопросы() if not кабинеты or в["кабинет"] in кабинеты]
    ПРОГРЕСС.update({"идёт": True, "готово": 0, "всего": len(список), "начато": time.time()})
    по_вопросам, по_кабинетам = [], {}
    try:
        for в in список:
            try:
                ответ = _ответить(н, в)
                балл, замечание = _оценить(н, в, ответ) if ответ else (0.0, "пустой ответ")
            except ai.ОшибкаИИ as ошибка:
                журнал.warning("ИИ не ответил на эталонный вопрос: %s", ошибка)
                балл, замечание, ответ = -1.0, f"ИИ недоступен: {ошибка}", ""
            except Exception:
                журнал.exception("Эталонный вопрос не прогнался")
                балл, замечание, ответ = -1.0, "сбой при проверке", ""
            по_вопросам.append({"id": в["id"], "кабинет": в["кабинет"], "балл": балл, "замечание": замечание, "ответ": ответ[:300]})
            if балл >= 0:
                к = по_кабинетам.setdefault(в["кабинет"], {"баллов": 0.0, "из": 0})
                к["баллов"] += балл
                к["из"] += 1
            ПРОГРЕСС["готово"] += 1
    finally:
        ПРОГРЕСС["идёт"] = False
    всего = sum(к["баллов"] for к in по_кабинетам.values())
    из = sum(к["из"] for к in по_кабинетам.values())
    прошлые = _прогоны()
    запись = {"id": (прошлые[-1]["id"] + 1) if прошлые else 1, "время": time.time(), "баллов": всего, "из": из,
              "пропущено": sum(1 for п in по_вопросам if п["балл"] < 0),
              "по_кабинетам": {к: {"баллов": v["баллов"], "из": v["из"]} for к, v in по_кабинетам.items()},
              "по_вопросам": по_вопросам,
              "к_прошлому": round(всего - прошлые[-1]["баллов"], 1) if прошлые and прошлые[-1]["из"] == из else None}
    with _замок:
        decisions._база.записать(КЛЮЧ_ПРОГОНОВ, (прошлые + [запись])[-МАКС_ПРОГОНОВ:])
    return запись


def запустить_в_фоне(н: dict, кабинеты: list[str] | None = None) -> bool:
    """False, если прогон уже идёт."""
    with _замок:
        if ПРОГРЕСС["идёт"]:
            return False
        ПРОГРЕСС["идёт"] = True

    def работа():
        ai.установить_приоритет("фон")
        try:
            прогон(н, кабинеты)
        except Exception:
            журнал.exception("Прогон эталонных вопросов не удался")
            ПРОГРЕСС["идёт"] = False

    threading.Thread(target=работа, name="mizuyori-evals", daemon=True).start()
    return True


def состояние() -> dict:
    return {"прогресс": dict(ПРОГРЕСС), "прогоны": [{k: п[k] for k in ("id", "время", "баллов", "из", "пропущено", "по_кабинетам", "к_прошлому")}
                                                  for п in прогоны(5)],
            "вопросов": len(вопросы())}
