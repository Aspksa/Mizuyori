"""Коллективная работа агентов из чата.

Совещание: хозяин просит обсудить вопрос — выступают руководители нужных кабинетов, «Собеседник» сводит мнения
и показывает расхождения. Поручение кабинету: руководитель кабинета сам разбивает задачу между своими сотрудниками
и запускает настоящее поручение (шаги, проверка, оценка). Всё идёт в фоне; итог приходит в чат отдельным сообщением.
Работа каждого видна на графе: агент «в работе», записки между участниками, импульсы по связям."""
from __future__ import annotations

import logging
import re
import threading

from . import agents, ai, audit, cabinets, chat_delegate, decisions, missions

журнал = logging.getLogger("mizuyori.коллектив")

ПРЕДСЕДАТЕЛЬ = "чат"
ГЛАВНЫЕ_КАБИНЕТЫ = ("бухгалтерия", "экономисты", "юристы", "механик")
МАКС_УЧАСТНИКОВ = 4
МАКС_ПОДЗАДАЧ = 4

_СОВЕЩАНИЕ = re.compile(r"совещани|консилиум|созови|собери (?:всех|кабинет|руководител)|обсудите|обсудим вместе|что скажут|мнение (?:всех|кабинетов|руководител)", re.I)
_СЛОВА_КАБИНЕТОВ = {
    "бухгалтерия": re.compile(r"бухгалтер|главбух"),
    "юристы": re.compile(r"юрист|юридич|договор"),
    "экономисты": re.compile(r"экономист|плановик|себестоимост"),
    "механик": re.compile(r"механик|ремзон|снабжен|техническ"),
    "штаб": re.compile(r"штаб"),
}
# «поручи кабинету …», «пускай бухгалтерии …»: кабинет назван целиком (дательный падеж или слово «кабинет»)
_ПОРУЧЕНИЕ_КАБИНЕТУ = re.compile(
    r"(?:поручи|поручить|пускай|пусть|попроси|передай|пошли|дай задание)\s+(?:всему\s+|всей\s+)?"
    r"(?:(?:кабинет\w*|управлени\w+)\s+)?(?P<каб>бухгалтери\w+|юристам|юридическ\w+\s+управлени\w+|экономистам|механик\w*|штабу)", re.I)
_ЗАДАЧА_ПОСЛЕ = re.compile(r"^[\s,:—-]*(?:чтобы\s+)?", re.I)


def _норм(текст: str) -> str:
    return " ".join((текст or "").lower().replace("ё", "е").split())


def кабинеты_в_тексте(текст: str) -> list[str]:
    низ = _норм(текст)
    return [к for к, шаблон in _СЛОВА_КАБИНЕТОВ.items() if шаблон.search(низ)]


def руководитель(кабинет: str) -> str:
    """Ключ руководителя кабинета: руководитель первого отдела."""
    for к in cabinets.КАБИНЕТЫ:
        if к["ключ"] == кабинет and к["отделы"]:
            return к["отделы"][0]["руководитель"]
    return ""


def название(кабинет: str) -> str:
    return next((к["название"] for к in cabinets.КАБИНЕТЫ if к["ключ"] == кабинет), кабинет)


def _имя(ключ: str) -> str:
    return agents.ИМЕНА.get(ключ, ключ)


def это_совещание(текст: str) -> bool:
    return bool(_СОВЕЩАНИЕ.search(_норм(текст)))


def поручение_кабинету(текст: str) -> tuple[str, str] | None:
    """(ключ кабинета, задача) или None."""
    низ = _норм(текст)
    м = _ПОРУЧЕНИЕ_КАБИНЕТУ.search(низ)
    if not м:
        return None
    названо = м.group("каб")
    if названо.startswith("механик") and "кабинет" not in м.group(0):
        return None                      # «поручи механику» — это человек, а не кабинет
    каб = кабинеты_в_тексте(названо)
    if not каб:
        return None
    задача = _ЗАДАЧА_ПОСЛЕ.sub("", низ[м.end():]).strip(" .,:;")
    return (каб[0], задача) if len(задача) >= 5 else None


def _спросить(система: str, данные: dict, н: dict, ключ: str, запрос: str, токенов: int) -> str:
    настройки = agents.с_правилами(dict(н), ключ, запрос) if ключ in agents.ИМЕНА else dict(н)
    return (ai._задание(система, данные, настройки, токенов) or "").strip()


# ---- Совещание ---------------------------------------------------------------------------------

_ВЫСТУПЛЕНИЕ = ("Ты — {имя}, руководитель кабинета «{кабинет}», на совещании у хозяина отдела главного механика. "
                "Дай мнение своего кабинета по вопросу: 3–5 строк, по существу, с точки зрения твоей области. "
                "Назови, что нужно проверить или чего не хватает. " + decisions.ЗАЩИТА_ОТ_ВЫДУМОК)
_ИТОГ = ("Ты ведёшь совещание. Ниже вопрос хозяина и мнения руководителей кабинетов. Сведи их: сначала общий вывод одной-двумя фразами, "
         "потом по строке на каждого («Бухгалтерия: …»), в конце — расхождения и что надо уточнить. Не добавляй фактов, которых нет в мнениях. "
         "Если кто-то написал «нет данных», так и отметь. Коротко, по-русски, не длиннее 14 строк.")
_ВЫБОР = ("Выбери, каких руководителей кабинетов позвать на совещание по вопросу хозяина. Выбирай только из списка, от двух до четырёх. "
          'Ответь ТОЛЬКО JSON: {"кабинеты": ["ключ", ...]}.')


def _выбрать_участников(вопрос: str, н: dict) -> list[str]:
    названные = [к for к in кабинеты_в_тексте(вопрос) if к in ГЛАВНЫЕ_КАБИНЕТЫ]
    if len(названные) >= 2:
        return названные[:МАКС_УЧАСТНИКОВ]
    try:
        ответ = ai._задание(_ВЫБОР, {"вопрос": вопрос, "кабинеты": [{"ключ": к, "название": название(к)} for к in ГЛАВНЫЕ_КАБИНЕТЫ]}, dict(н), 200)
        р = missions._json_из_текста(ответ)
        выбор = [к for к in (р or {}).get("кабинеты", []) if к in ГЛАВНЫЕ_КАБИНЕТЫ] if isinstance(р, dict) else []
    except Exception:
        журнал.warning("Выбор участников совещания не удался", exc_info=True)
        выбор = []
    итог = list(dict.fromkeys(названные + выбор))
    return (итог if len(итог) >= 2 else list(ГЛАВНЫЕ_КАБИНЕТЫ[:3]))[:МАКС_УЧАСТНИКОВ]


def провести_совещание(база, н: dict, вопрос: str, участники: list[str], запись: int = 0) -> str:
    """Синхронно проводит совещание и возвращает текст итога (в чат его пошлёт вызывающий)."""
    мнения: list[dict] = []
    for каб in участники:
        лидер = руководитель(каб)
        if not лидер:
            continue
        try:
            with agents.работа(лидер, "выступил на совещании", f"вопрос: «{вопрос[:60]}»") as з:
                текст = _спросить(_ВЫСТУПЛЕНИЕ.format(имя=_имя(лидер), кабинет=название(каб)), {"вопрос": вопрос}, н, лидер, вопрос, 450)
                з["результат"] = f"мнение {len(текст)} знаков"
                з["польза"] = 1
        except Exception:
            журнал.warning("Руководитель %s не выступил", лидер, exc_info=True)
            continue
        if not текст:
            continue
        мнения.append({"ключ": лидер, "кто": _имя(лидер), "кабинет": название(каб), "мнение": текст})
        try:
            agents.написать(лидер, ПРЕДСЕДАТЕЛЬ, текст)         # записка председателю: на графе — импульс от выступившего
        except Exception:
            журнал.exception("Записка совещания не записалась")
    if not мнения:
        decisions.обновить(запись, статус="не вышло", итог="Никто не высказался")
        return "🧭 Совещание не состоялось: никто из руководителей не смог ответить."
    try:
        with agents.работа(ПРЕДСЕДАТЕЛЬ, "свёл мнения совещания", f"вопрос: «{вопрос[:60]}»") as з:
            итог = _спросить(_ИТОГ, {"вопрос": вопрос, "мнения": [{k: м[k] for k in ("кто", "кабинет", "мнение")} for м in мнения]},
                             н, ПРЕДСЕДАТЕЛЬ, вопрос, 800)
            з["результат"] = "итог совещания"
            з["польза"] = 1
    except Exception:
        журнал.warning("Итог совещания не получился", exc_info=True)
        итог = "\n".join(f"{м['кабинет']}: {м['мнение'][:300]}" for м in мнения)
    decisions.обновить(запись, статус="нет данных" if decisions.без_данных(итог) else "принято", итог=итог)
    return f"🧭 Итог совещания: {вопрос[:120]}\n\n{итог}"


# ---- Поручение кабинету ------------------------------------------------------------------------

_РАЗБИЕНИЕ = ("Ты — {имя}, руководитель кабинета «{кабинет}». Хозяин поручил кабинету задачу. Раздели её на {мин}–{макс} последовательных шагов "
              "между своими сотрудниками (только из списка, каждому по делу его должности). Не придумывай фактов: в описание — только то, что сказал хозяин. "
              'Ответь ТОЛЬКО JSON: {{"название": "до 80 знаков", "шаги": [{{"агент": "ключ", "описание": "что сделать, самодостаточно", '
              '"ожидание": "что считать готовым"}}]}}.')


def _сотрудники(кабинет: str) -> list[dict]:
    return [{"ключ": а["ключ"], "имя": а["имя"], "умеет": а.get("что", "")} for а in agents.АГЕНТЫ
            if а.get("кабинет") == кабинет and а["ключ"] not in chat_delegate.НЕ_ИСПОЛНИТЕЛИ]


def разбить_задачу(н: dict, кабинет: str, задача: str) -> dict | None:
    """Руководитель делит задачу на шаги для своих. Возвращает {"название", "шаги"} или None."""
    лидер = руководитель(кабинет)
    люди = _сотрудники(кабинет)
    допустимые = {л["ключ"] for л in люди}
    if not лидер or not допустимые:
        return None
    try:
        with agents.работа(лидер, "раздал подзадачи кабинету", f"задача: «{задача[:60]}»") as з:
            ответ = _спросить(_РАЗБИЕНИЕ.format(имя=_имя(лидер), кабинет=название(кабинет), мин=2, макс=МАКС_ПОДЗАДАЧ),
                              {"задача": задача, "сотрудники": люди}, н, лидер, задача, 700)
            з["результат"] = "разбил задачу на шаги"
            з["польза"] = 1
    except Exception:
        журнал.warning("Руководитель кабинета не смог разбить задачу", exc_info=True)
        return None
    р = missions._json_из_текста(ответ)
    if not isinstance(р, dict):
        return None
    шаги = []
    for ш in (р.get("шаги") or [])[:МАКС_ПОДЗАДАЧ]:
        if isinstance(ш, dict) and ш.get("агент") in допустимые and str(ш.get("описание") or "").strip():
            шаги.append({"агент": ш["агент"], "описание": " ".join(str(ш["описание"]).split())[:1000],
                         "ожидание": " ".join(str(ш.get("ожидание") or "").split())[:300], "инструмент": "", "подтверждать": False})
    if not шаги:
        return None
    return {"название": " ".join(str(р.get("название") or задача).split())[:80], "шаги": шаги, "руководитель": лидер}


def запустить_кабинету(база, н: dict, кабинет: str, задача: str) -> str:
    """Синхронно: разбивает задачу, создаёт и запускает поручение. Возвращает сообщение для чата."""
    лидер = руководитель(кабинет)
    запись = decisions.записать("кабинет", задача, [лидер], [название(кабинет)], "", статус="в работе")
    план = разбить_задачу(н, кабинет, задача)
    if not план:
        decisions.обновить(запись, статус="не вышло", итог="Руководитель не смог разбить задачу")
        return f"🧭 {_имя(лидер)} не смог разбить задачу на шаги. Сформулируйте точнее или поручите конкретному агенту."
    try:
        м = missions.создать(план["название"], план["шаги"])
        chat_delegate._запомнить(м["id"])
        audit.записать("поручение кабинету из чата", план["название"], f"кабинет: {название(кабинет)}", кто="чат")
        missions.запустить(м["id"], н)
    except missions.ОшибкаПоручения as ошибка:
        decisions.обновить(запись, статус="не вышло", итог=str(ошибка))
        return f"🧭 Не получилось начать: {ошибка}"
    decisions.обновить(запись, агенты=list(dict.fromkeys([лидер] + [ш["агент"] for ш in план["шаги"]])), поручение=м["id"])
    строки = "\n".join(f"{i}. {_имя(ш['агент'])} — {ш['описание'][:140]}" for i, ш in enumerate(план["шаги"], 1))
    return (f"🧭 {_имя(лидер)} разбил задачу кабинета «{название(кабинет)}» на шаги:\n{строки}\n"
            f"Итог пришлю сюда (ход работы — в окне «Поручения», №{м['id']}).")


# ---- Вход из чата ------------------------------------------------------------------------------

def из_чата(база, н: dict, текст: str) -> tuple[str, str] | None:
    """(подсказка ИИ, готовое сообщение системы) или None, если это не совещание и не поручение кабинету."""
    if chat_delegate.НАСТРОЙКИ.get("поручения_из_чата", "авто") == "выкл" or not ai.подключён(н):
        return None
    для_кабинета = поручение_кабинету(текст)
    if для_кабинета:
        кабинет, задача = для_кабинета
        threading.Thread(target=_в_фоне, args=(база, н, "кабинет", кабинет, задача), daemon=True).start()
        return ("Хозяин поручил задачу целому кабинету, руководитель разбивает её на шаги. Скажи одной фразой.",
                f"🧭 Передаю кабинету «{название(кабинет)}»: руководитель {_имя(руководитель(кабинет))} раздаст задачу своим. Итог пришлю сюда.")
    if это_совещание(текст):
        участники = _выбрать_участников(текст, н)
        запись = decisions.записать("совещание", текст, [руководитель(к) for к in участники] + [ПРЕДСЕДАТЕЛЬ],
                                    [название(к) for к in участники], "", статус="в работе")
        threading.Thread(target=_в_фоне, args=(база, н, "совещание", участники, текст, запись), daemon=True).start()
        имена = ", ".join(_имя(руководитель(к)) for к in участники)
        return ("Хозяин созвал совещание, руководители кабинетов высказываются. Скажи одной фразой.",
                f"🧭 Созываю совещание: {имена}. Сведу мнения и пришлю итог сюда.")
    return None


def _в_фоне(база, н: dict, вид: str, *параметры) -> None:
    ai.установить_приоритет("поручение")
    try:
        if вид == "кабинет":
            текст = запустить_кабинету(база, н, параметры[0], параметры[1])
        else:
            текст = провести_совещание(база, н, параметры[1], параметры[0], параметры[2] if len(параметры) > 2 else 0)
    except Exception:
        журнал.exception("Коллективная работа не удалась")
        текст = "🧭 Не получилось: непредвиденная ошибка. Подробности в logs/mizuyori.log."
    try:
        база.добавить_сообщение("ии", текст)
    except Exception:
        журнал.exception("Итог коллективной работы не попал в чат")
