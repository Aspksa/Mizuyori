"""Общая память кабинетов, откат при падении качества и еженедельная чистка знаний.

- Общий пул: приём, который агент выучил сам, предлагается его кабинету. Руководитель кабинета (ИИ) или вы подтверждаете;
  подтверждённое видят все агенты кабинета как «общие знания».
- Откат: если у агента много исправлений от вас, последний выученный им приём за неделю снимается (в версиях профиля это видно).
- Куратор раз в неделю: рассматривает пул, убирает повторы приёмов одного агента и устаревшие приёмы, сообщает в чат."""
from __future__ import annotations

import difflib
import logging
import threading
import time

from . import agents, ai, audit, collective, decisions, missions

журнал = logging.getLogger("mizuyori.куратор")

КЛЮЧ_ПУЛА = "пул_знаний"
КЛЮЧ_СОСТОЯНИЯ = "куратор_состояние"
МАКС_ПУЛ = 200
ПОРОГ_ДУБЛЯ = 0.85
ПОРОГ_ОШИБОК = 0.4
МИН_ОТВЕТОВ = 5
НОВЫХ_ОТВЕТОВ_ДЛЯ_ПОВТОРА = 3
ДНЕЙ_ПРИЁМУ = 60
МАКС_УДАЛЕНИЙ_ЗА_РАЗ = 10
НЕДЕЛЯ_СЕК = 7 * 86400

_база = None
_замок = threading.Lock()
_поток = None


def подключить(база) -> None:
    global _база
    _база = база


def _норм(текст: str) -> str:
    return " ".join("".join(с if с.isalnum() else " " for с in (текст or "").casefold().replace("ё", "е")).split())


def _похоже(а: str, б: str) -> bool:
    а, б = _норм(а), _норм(б)
    return bool(а) and bool(б) and (а in б or б in а or difflib.SequenceMatcher(None, а, б).ratio() >= ПОРОГ_ДУБЛЯ)


def кабинет_агента(ключ: str) -> str:
    return next((а.get("кабинет", "") for а in agents.АГЕНТЫ if а["ключ"] == ключ), "")


# ---- Общий пул знаний кабинета ---------------------------------------------------------------

def _пул() -> list[dict]:
    try:
        return list(_база.прочитать(КЛЮЧ_ПУЛА, [])) if _база else []
    except Exception:
        return []


def пул(кабинет: str = "", статус: str = "") -> list[dict]:
    return [з for з in _пул() if (not кабинет or з["кабинет"] == кабинет) and (not статус or з["статус"] == статус)]


def предложить(агент: str, текст: str) -> int:
    """Агент предлагает свой приём кабинету. Возвращает номер или 0 (нет кабинета, повтор, пусто)."""
    каб = кабинет_агента(агент)
    текст = " ".join((текст or "").split())[:300]
    if not _база or not каб or len(_норм(текст).split()) < 4:
        return 0
    with _замок:
        записи = _пул()
        if any(з["кабинет"] == каб and з["статус"] != "отклонено" and _похоже(з["текст"], текст) for з in записи):
            return 0
        номер = (max((з["id"] for з in записи), default=0)) + 1
        записи.append({"id": номер, "кабинет": каб, "текст": текст, "от": агент, "время": time.time(), "статус": "предложено"})
        _база.записать(КЛЮЧ_ПУЛА, записи[-МАКС_ПУЛ:])
    return номер


def решить(номер: int, принять: bool, кто: str = "вы") -> bool:
    with _замок:
        записи = _пул()
        for з in записи:
            if з["id"] == номер and з["статус"] == "предложено":
                з["статус"] = "принято" if принять else "отклонено"
                з["решил"] = кто
                _база.записать(КЛЮЧ_ПУЛА, записи)
                audit.записать("общее знание кабинета: " + з["статус"], з["текст"][:100], f"кабинет: {з['кабинет']}", кто=кто)
                return True
    return False


def для_агента(ключ: str, сколько: int = 8) -> list[str]:
    """Подтверждённые знания кабинета агента (его собственные не повторяем)."""
    каб = кабинет_агента(ключ)
    if not каб:
        return []
    подходящие = [з for з in _пул() if з["кабинет"] == каб and з["статус"] == "принято" and з["от"] != ключ]
    return [з["текст"] for з in подходящие[-сколько:]]


_ПРОВЕРКА_ПУЛА = ("Ты — {имя}, руководитель кабинета «{кабинет}». Сотрудники предложили общие знания для всего кабинета. Прими только то, "
                  "что конкретно, полезно всем и не противоречит работе кабинета; отклони общее, спорное и дубли. "
                  'Ответь ТОЛЬКО JSON: {{"решения": [{{"номер": N, "принять": true|false}}]}}.')


def рассмотреть(н: dict) -> dict:
    """Руководители кабинетов решают по предложениям. Возвращает {"принято": n, "отклонено": m}."""
    итог = {"принято": 0, "отклонено": 0}
    if not ai.подключён(н):
        return итог
    for каб in {з["кабинет"] for з in пул(статус="предложено")}:
        лидер = collective.руководитель(каб)
        предложения = пул(каб, "предложено")[:10]
        if not лидер or not предложения:
            continue
        try:
            with agents.работа(лидер, "рассмотрел общие знания кабинета", f"предложений: {len(предложения)}") as з:
                ответ = ai._задание(_ПРОВЕРКА_ПУЛА.format(имя=agents.ИМЕНА.get(лидер, лидер), кабинет=collective.название(каб)),
                                    {"предложения": [{"номер": п["id"], "текст": п["текст"]} for п in предложения]},
                                    agents.с_правилами(dict(н), лидер), 500)
                з["результат"] = "решения по предложениям"
                з["польза"] = 1
        except Exception:
            журнал.warning("Руководитель %s не рассмотрел предложения", лидер, exc_info=True)
            continue
        р = missions._json_из_текста(ответ)
        решения = (р or {}).get("решения") if isinstance(р, dict) else None
        допустимые = {п["id"] for п in предложения}
        for д in решения or []:
            try:
                номер, принять = int(д["номер"]), bool(д["принять"])
            except (KeyError, TypeError, ValueError):
                continue
            if номер in допустимые and решить(номер, принять, кто=agents.ИМЕНА.get(лидер, лидер)):
                итог["принято" if принять else "отклонено"] += 1
    return итог


# ---- Откат при падении качества --------------------------------------------------------------

def _состояние() -> dict:
    try:
        return dict(_база.прочитать(КЛЮЧ_СОСТОЯНИЯ, {})) if _база else {}
    except Exception:
        return {}


def проверить_качество() -> list[str]:
    """Агентам, которых вы часто исправляете, снимает последний выученный приём. Возвращает описания действий."""
    if not _база:
        return []
    действия = []
    состояние = _состояние()
    откаты = состояние.setdefault("откаты", {})
    for ключ, к in decisions.качество().items():
        if ключ not in agents.ИМЕНА or к["ответов"] < МИН_ОТВЕТОВ or (к["доля_ошибок"] or 0) < ПОРОГ_ОШИБОК:
            continue
        if к["ответов"] - откаты.get(ключ, {}).get("ответов", -99) < НОВЫХ_ОТВЕТОВ_ДЛЯ_ПОВТОРА and ключ in откаты:
            continue
        свежие = agents.выучено(ключ, 7)
        if not свежие:
            continue
        последний = свежие[0]
        if agents.удалить_заметку(последний["id"]):
            откаты[ключ] = {"ответов": к["ответов"], "время": time.time()}
            for з in пул(кабинет_агента(ключ), "предложено"):
                if з["от"] == ключ and _похоже(з["текст"], последний["текст"]):
                    решить(з["id"], False, кто="откат")
            audit.записать("откат приёма из-за исправлений", f"{agents.ИМЕНА[ключ]}: {последний['текст'][:100]}",
                           f"исправлений {к['исправлено'] + к['не_вышло']} из {к['ответов']}", кто="куратор")
            действия.append(f"{agents.ИМЕНА[ключ]}: снят приём «{последний['текст'][:90]}» (исправлено {к['исправлено'] + к['не_вышло']} из {к['ответов']})")
    if действия:
        _база.записать(КЛЮЧ_СОСТОЯНИЯ, состояние)
        try:
            _база.добавить_сообщение("ии", "🧭 Куратор снял приёмы у агентов, которых вы часто исправляете:\n" + "\n".join(f"— {д}" for д in действия)
                                     + "\nВернуть можно в «Мозги → Версии».")
        except Exception:
            журнал.exception("Сообщение куратора не попало в чат")
    return действия


# ---- Еженедельная чистка ---------------------------------------------------------------------

def _возраст_дней(создано: str) -> float:
    from datetime import datetime
    try:
        return (datetime.now() - datetime.strptime(создано, "%Y-%m-%d %H:%M:%S")).total_seconds() / 86400
    except (TypeError, ValueError):
        return 0


def недельная_чистка(н: dict | None = None) -> dict:
    """Рассматривает пул, убирает повторы приёмов одного агента и устаревшие приёмы. Правила «от вас» не трогает."""
    итог = {"пул_принято": 0, "пул_отклонено": 0, "повторов": 0, "устарело": 0, "общих_повторов": 0}
    if н:
        р = рассмотреть(н)
        итог["пул_принято"], итог["пул_отклонено"] = р["принято"], р["отклонено"]
    удалено = 0
    for а in agents.АГЕНТЫ:
        приёмы = [з for з in agents.заметки(а["ключ"]) if з["вид"] == "приём"]
        приёмы.sort(key=lambda з: з["id"])
        оставлены: list[dict] = []
        for з in приёмы:
            if удалено >= МАКС_УДАЛЕНИЙ_ЗА_РАЗ:
                break
            повтор = any(_похоже(з["текст"], о["текст"]) for о in оставлены)
            старый = з["источник"] != "вы" and _возраст_дней(з["создано"]) > ДНЕЙ_ПРИЁМУ
            if (повтор or старый) and agents.удалить_заметку(з["id"]):
                итог["повторов" if повтор else "устарело"] += 1
                удалено += 1
                audit.записать("куратор убрал приём", f"{а['имя']}: {з['текст'][:100]}", "повтор" if повтор else f"старше {ДНЕЙ_ПРИЁМУ} дней", кто="куратор")
            else:
                оставлены.append(з)
    try:                                 # одинаковые приёмы у разных агентов только показываем: решать вам
        итог["общих_повторов"] = sum(1 for д in agents.проверить_знания()["дубли"] if д["разные_агенты"])
    except Exception:
        журнал.exception("Проверка общих повторов не удалась")
    return итог


def _сообщение_чистки(итог: dict) -> str:
    части = []
    if итог["пул_принято"] or итог["пул_отклонено"]:
        части.append(f"общих знаний кабинетов: принято {итог['пул_принято']}, отклонено {итог['пул_отклонено']}")
    if итог["повторов"]:
        части.append(f"убрано повторов приёмов: {итог['повторов']}")
    if итог["устарело"]:
        части.append(f"убрано устаревших приёмов (старше {ДНЕЙ_ПРИЁМУ} дней): {итог['устарело']}")
    if итог["общих_повторов"]:
        части.append(f"одинаковые приёмы у разных агентов: {итог['общих_повторов']} (смотрите «Мозги → Проверка знаний»)")
    return ("🧭 Еженедельная чистка знаний:\n" + "\n".join(f"— {ч}" for ч in части)) if части else ""


def запустить(база, получить_ии) -> None:
    """Раз в неделю: чистка знаний. Проверяет раз в час; ИИ нужен только для решений по пулу."""
    global _поток
    if _поток and _поток.is_alive():
        return

    def цикл():
        ai.установить_приоритет("фон")
        time.sleep(300)
        while True:
            try:
                состояние = _состояние()
                if time.time() - состояние.get("чистка", 0) >= НЕДЕЛЯ_СЕК:
                    н = dict(получить_ии())
                    итог = недельная_чистка(н if ai.подключён(н) else None)
                    состояние = _состояние()
                    состояние["чистка"] = time.time()
                    база.записать(КЛЮЧ_СОСТОЯНИЯ, состояние)
                    текст = _сообщение_чистки(итог)
                    if текст:
                        база.добавить_сообщение("ии", текст)
            except Exception:
                журнал.exception("Еженедельная чистка знаний")
            time.sleep(3600)

    _поток = threading.Thread(target=цикл, name="mizuyori-curator", daemon=True)
    _поток.start()
