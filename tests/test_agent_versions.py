import tempfile
import unittest
from pathlib import Path

from mizuyori import agents, audit
from mizuyori.database import База


class ВерсииИНавыки(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.db = База(Path(self.temp.name) / "t.db")
        self.db.подготовить()
        agents.подключить(self.db)
        audit.подключить(self.db)

    def tearDown(self):
        self.temp.cleanup()

    def test_первое_изменение_сохраняет_исходное_состояние(self):
        agents.сохранить_профиль("снабженец", {"роль": "снабженец"})
        в = agents.версии("снабженец")
        self.assertEqual([х["причина"] for х in в], ["профиль изменён", "исходное состояние"])
        self.assertTrue(в[0]["текущая"])

    def test_откат_возвращает_профиль_правила_и_навыки(self):
        agents.сохранить_профиль("снабженец", {"роль": "первая роль"})
        agents.добавить_заметку("снабженец", "правило", "сравнивай три магазина")
        agents.добавить_навык("снабженец", "Фильтры", "фильтр, артикул", "Ищи артикул в латинице.")
        агентская_версия = next(в for в in agents.версии("снабженец") if в["причина"] == "профиль изменён")
        agents.сохранить_профиль("снабженец", {"роль": "вторая роль"})
        agents.удалить_заметку(agents.заметки("снабженец")[0]["id"])
        итог = agents.откатить(агентская_версия["id"])
        self.assertEqual(итог["к_версии"], агентская_версия["номер"])
        self.assertEqual(agents.профиль("снабженец")["роль"], "первая роль")
        self.assertEqual([з["текст"] for з in agents.заметки("снабженец") if з["вид"] == "правило"], [])   # на момент версии правила ещё не было
        self.assertEqual(agents.навыки("снабженец"), [])
        self.assertIn("откат к версии", agents.версии("снабженец")[0]["причина"])        # откат тоже версия

    def test_без_изменений_версия_не_плодится(self):
        agents.сохранить_профиль("юрист", {"роль": "юрист"})
        n = len(agents.версии("юрист"))
        agents.сохранить_профиль("юрист", {"роль": "юрист"})
        self.assertEqual(len(agents.версии("юрист")), n)

    def test_навык_подключается_только_к_теме(self):
        agents.добавить_навык("снабженец", "Фильтры по артикулу", "фильтр, артикул", "Артикул пиши латиницей: C-111.")
        agents.добавить_навык("снабженец", "Шины", "шины, резина", "Смотри индекс нагрузки.")
        agents.добавить_навык("снабженец", "Всегда", "", "Отвечай коротко.")
        к = lambda з: [н["название"] for н in agents.навыки_для("снабженец", з)]
        self.assertEqual(к("найди фильтр для хайлюкса"), ["Фильтры по артикулу", "Всегда"])
        self.assertEqual(к("какие шины взять"), ["Шины", "Всегда"])
        self.assertEqual(к("привет"), ["Всегда"])
        self.assertIn("Артикул пиши латиницей", agents.правила("снабженец", "нужен фильтр"))
        self.assertNotIn("индекс нагрузки", agents.правила("снабженец", "нужен фильтр"))

    def test_выключенный_навык_не_подключается(self):
        н = agents.добавить_навык("снабженец", "Фильтры", "фильтр", "Текст.")
        agents.изменить_навык(н["id"], {"включён": False})
        self.assertEqual(agents.навыки_для("снабженец", "фильтр"), [])

    def test_пустой_навык_отклоняется(self):
        with self.assertRaises(ValueError):
            agents.добавить_навык("снабженец", "", "", "")

    def test_аудит_пишется_и_ищется(self):
        audit.записать("шаг подтверждён", "Закупка", "шаг 3")
        audit.записать("откат агента", "Юрист")
        self.assertEqual(len(audit.список()), 2)
        self.assertEqual([з["объект"] for з in audit.список(поиск="ЗАКУП")], ["Закупка"])


if __name__ == "__main__":
    unittest.main()
