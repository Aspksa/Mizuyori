class ТестФайрвол(unittest.TestCase):
    def test_отпечаток_привязан_к_шагу(self):
        a = tools.отпечаток("снабженец", "поиск", "найти фильтр")
        self.assertEqual(a, tools.отпечаток("снабженец", "поиск", "найти фильтр"))
        self.assertNotEqual(a, tools.отпечаток("снабженец", "поиск", "найти шины"))
        self.assertNotEqual(a, tools.отпечаток("склад", "поиск", "найти фильтр"))

    def test_аргументы(self):
        self.assertFalse(tools.проверить_аргументы("   ")[0])
        self.assertFalse(tools.проверить_аргументы("a" * 2001)[0])
        self.assertFalse(tools.проверить_аргументы("a\x00b")[0])
        self.assertTrue(tools.проверить_аргументы("фильтр VIC C-111")[0])

    def test_поиск_только_закупщикам(self):
        self.assertTrue(tools.разрешён("поиск", "снабженец")[0])
        ок, причина = tools.разрешён("поиск", "кадровик")
        self.assertFalse(ок)
        self.assertIn("нельзя", причина)
        with self.assertRaises(PermissionError):
            tools.вызвать("поиск", {"описание": "x", "агент": "кадровик"})


class ТестНаборовИПередачи(Поручения):
    def setUp(self):
        super().setUp()
        self._настройки = {}
        tools.подключить(lambda: dict(self._настройки), lambda з: self._настройки.update(з) or None)

    def tearDown(self):
        tools.подключить(lambda: {}, lambda з: None)
        super().tearDown()

    def test_только_чтение_блокирует_рискованное(self):
        @tools.инструмент("тест-запись", "пишет", рискованный=True, набор="тест")
        def _(з):
            return "ok"
        try:
            self.assertTrue(tools.разрешён("тест-запись", "инженер")[0])
            tools.сохранить_настройки({"только_чтение": True})
            ок, причина = tools.разрешён("тест-запись", "инженер")
            self.assertFalse(ок)
            self.assertIn("только чтение", причина)
            self.assertTrue(tools.разрешён("поиск", "снабженец")[0])
        finally:
            tools.ИНСТРУМЕНТЫ.pop("тест-запись", None)

    def test_выключенный_набор_и_набор_агента(self):
        tools.сохранить_настройки({"выключены": ["интернет"]})
        self.assertFalse(tools.разрешён("поиск", "снабженец")[0])
        tools.сохранить_настройки({"выключены": [], "агенты": {"снабженец": ["данные"]}})
        self.assertFalse(tools.разрешён("поиск", "снабженец")[0])
        self.assertIn("не включён набор", tools.разрешён("поиск", "снабженец")[1])
        tools.сохранить_настройки({"агенты": {}})
        self.assertTrue(tools.разрешён("поиск", "снабженец")[0])

    def test_передача_шага_коллеге(self):
        ответы = iter(["ПЕРЕДАЮ: юрист: это вопрос договора", "Готово от юриста"])
        ai._задание = lambda система, данные, н, m: (
            '{"подходит": true, "замечание": ""}' if "ТОЛЬКО JSON" in система else next(ответы))
        м = missions.создать("Т", [{"агент": "снабженец", "описание": "Проверить договор", "ожидание": "вывод"}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual(м["статус"], "готово")
        запись = м["ход"][0]
        self.assertEqual(запись["агент"], "юрист")
        self.assertEqual(запись["передачи"][0]["от"], "снабженец")
        self.assertEqual(м["итог"], "Готово от юриста")

    def test_передача_несуществующему_отклоняется(self):
        ответы = iter(["ПЕРЕДАЮ: призрак: не знаю", "Сделал сам"])
        ai._задание = lambda система, данные, н, m: (
            '{"подходит": true, "замечание": ""}' if "ТОЛЬКО JSON" in система else next(ответы))
        м = missions.создать("Т", [{"агент": "снабженец", "описание": "Сделать", "ожидание": "что-то"}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual(м["ход"][0]["агент"], "снабженец")
        self.assertFalse(м["ход"][0]["передачи"][0]["принята"])
        self.assertEqual(м["итог"], "Сделал сам")


