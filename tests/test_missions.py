import json
import tempfile
import time
import unittest
from pathlib import Path

from mizuyori import agents, ai, missions, tools, work_agents
from mizuyori.database import База

Н = {"включён": True, "ключ": "k", "модель": "m", "адрес": "https://x"}


def ждать(номер, секунд=5):
    конец = time.time() + секунд
    while time.time() < конец:
        if номер not in missions._идут:
            return missions.получить(номер)
        time.sleep(0.02)
    raise AssertionError("поручение не завершилось")


class Поручения(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.db = База(Path(self.temp.name) / "t.db")
        self.db.подготовить()
        work_agents.зарегистрировать()
        agents.подключить(self.db)
        missions.подключить(self.db)
        self.старое = ai._задание
        self.ответы = []          # что отвечает «ИИ»: по подстроке системной подсказки
        self.вызовы = []

        def ложный(система, данные, н, max_tokens):
            self.вызовы.append((система, данные))
            if "проверяющий" in система.lower() and "ТОЛЬКО JSON" in система:
                return json.dumps(self.вердикты.pop(0)) if self.вердикты else '{"подходит": true, "замечание": ""}'
            if "Стратег" in система:
                return json.dumps(self.план)
            if "Прими работу" in система:
                return "Итог принят."
            return f"результат: {данные['шаг'][:20]}"
        self.вердикты, self.план = [], {}
        ai._задание = ложный

    def tearDown(self):
        ai._задание = self.старое
        self.temp.cleanup()

    ШАГ = {"агент": "снабженец", "описание": "Найти {запчасть}", "ожидание": "Три варианта"}

    def test_параметры_подставляются_и_обязательны(self):
        with self.assertRaises(missions.ОшибкаПоручения):
            missions.создать("Закупка {запчасть}", [self.ШАГ], {})
        м = missions.создать("Закупка {запчасть}", [self.ШАГ], {"запчасть": "фильтр"})
        self.assertEqual(м["название"], "Закупка фильтр")
        self.assertEqual(м["шаги"][0]["описание"], "Найти фильтр")

    def test_плохие_шаги_отклоняются(self):
        for шаги in ([], [{"агент": "нет-такого", "описание": "x"}], [{"агент": "снабженец", "описание": ""}],
                     [{"агент": "снабженец", "описание": "x", "инструмент": "нет"}]):
            with self.assertRaises(missions.ОшибкаПоручения):
                missions.создать("Т", шаги)

    def test_цепочка_выполняется_и_считает_метрики(self):
        м = missions.создать("Т", [{"агент": "снабженец", "описание": "один", "ожидание": "ок"},
                                  {"агент": "инженер", "описание": "два"}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual(м["статус"], "готово")
        self.assertEqual(len(м["ход"]), 2)
        self.assertTrue(all(х["состояние"] == "готово" for х in м["ход"]))
        self.assertIn("результат: два", м["итог"])
        self.assertEqual(self.вызовы[2][1]["результаты_предыдущих_шагов"], ["результат: один"])   # контекст прошлого шага

    def test_не_прошло_проверку_одна_повторная_попытка(self):
        self.вердикты = [{"подходит": False, "замечание": "мало вариантов"}, {"подходит": True, "замечание": ""}]
        м = missions.создать("Т", [self.ШАГ | {"описание": "один"}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual(м["статус"], "готово")
        повтор = [в for в in self.вызовы if "замечание_проверяющего" in в[1]]
        self.assertEqual(повтор[0][1]["замечание_проверяющего"], "мало вариантов")
        self.assertEqual(м["ход"][0]["попытка"], 2)

    def test_двойной_отказ_ждёт_человека_и_можно_принять(self):
        self.вердикты = [{"подходит": False, "замечание": "нет"}, {"подходит": False, "замечание": "всё ещё нет"}]
        м = missions.создать("Т", [self.ШАГ | {"описание": "один"}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual((м["статус"], м["ход"][0]["состояние"]), ("ждёт вас", "не принято"))
        missions.подтвердить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual(м["статус"], "готово")

    def test_шаг_с_подтверждением_ждёт_кнопку(self):
        м = missions.создать("Т", [{"агент": "инженер", "описание": "отправить записку", "подтверждать": True}])
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual((м["статус"], м["ход"][0]["состояние"]), ("ждёт вас", "ждёт подтверждения"))
        self.assertEqual(self.вызовы, [])                  # без разрешения ИИ даже не спрашивали
        missions.подтвердить(м["id"], Н)
        self.assertEqual(ждать(м["id"])["статус"], "готово")

    def test_отклонение_останавливает(self):
        м = missions.создать("Т", [{"агент": "инженер", "описание": "x", "подтверждать": True}])
        missions.запустить(м["id"], Н)
        ждать(м["id"])
        self.assertEqual(missions.отклонить(м["id"])["статус"], "остановлено")

    def test_рискованный_инструмент_всегда_ждёт(self):
        @tools.инструмент("тест-отправка", "отправляет", рискованный=True)
        def _(задание):
            return "отправлено"
        try:
            м = missions.создать("Т", [{"агент": "инженер", "описание": "x", "инструмент": "тест-отправка"}])
            missions.запустить(м["id"], Н)
            self.assertEqual(ждать(м["id"])["статус"], "ждёт вас")
        finally:
            tools.ИНСТРУМЕНТЫ.pop("тест-отправка", None)

    def test_инструмент_без_ии_отдаёт_факты(self):
        @tools.инструмент("тест-факты", "факты")
        def _(задание):
            return "факт из инструмента"
        try:
            м = missions.создать("Т", [{"агент": "снабженец", "описание": "x", "инструмент": "тест-факты"}])
            missions.запустить(м["id"], {})
            м = ждать(м["id"])
            self.assertEqual((м["статус"], м["итог"]), ("готово", "факт из инструмента"))
        finally:
            tools.ИНСТРУМЕНТЫ.pop("тест-факты", None)

    def test_без_ии_и_без_инструмента_ошибка_понятная(self):
        м = missions.создать("Т", [{"агент": "инженер", "описание": "x"}])
        missions.запустить(м["id"], {})
        м = ждать(м["id"])
        self.assertEqual(м["статус"], "не вышло")
        self.assertIn("ИИ не подключён", м["итог"])

    def test_руководитель_планирует_и_принимает(self):
        self.план = {"название": "Подготовить выпуск", "шаги": [
            {"агент": "механик", "описание": "проверить ТО", "ожидание": "список", "инструмент": "замечания"},
            {"агент": "выдуманный", "описание": "лишнее"},
            {"агент": "инженер", "описание": "свести"}]}
        м = missions.спланировать("Подготовить парк к выпуску", Н)
        self.assertEqual((м["режим"], len(м["шаги"])), ("руководитель", 2))
        missions.запустить(м["id"], Н)
        м = ждать(м["id"])
        self.assertEqual((м["статус"], м["итог"]), ("готово", "Итог принят."))

    def test_готовые_шаблоны_добавляются_один_раз(self):
        missions.заполнить_готовые()
        missions.заполнить_готовые()
        имена = [ш["название"] for ш in missions.шаблоны()]
        self.assertEqual(len(имена), len(missions.ГОТОВЫЕ_ШАБЛОНЫ))
        закупка = next(ш for ш in missions.шаблоны() if ш["название"].startswith("Закупка"))
        self.assertEqual(закупка["параметры"], ["техника", "запчасть"])


if __name__ == "__main__":
    unittest.main()
