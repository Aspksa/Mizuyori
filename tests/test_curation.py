class Основа(unittest.TestCase):
    def setUp(self):
        self.t = tempfile.TemporaryDirectory()
        self.база = База(Path(self.t.name) / "t.db"); self.база.подготовить()
        work_agents.зарегистрировать(); agents.подключить(self.база); audit.подключить(self.база)
        decisions.подключить(self.база); curation.подключить(self.база)
        self.старое = ai._задание
        self.ответы = []
        self.вызовы = []

        def ложный(система, данные, н, max_tokens):
            self.вызовы.append((система[:40], данные))
            return self.ответы.pop(0) if self.ответы else "{}"
        ai._задание = ложный

    def tearDown(self):
        ai._задание = self.старое
        self.t.cleanup()


class Пул(Основа):
    def test_предложение_без_повторов_и_только_для_агента_с_кабинетом(self):
        номер = curation.предложить("главбух", "Перед сдачей отчёта сверяй остатки по счетам с банком")
        self.assertGreater(номер, 0)
        self.assertEqual(curation.предложить("главбух", "перед сдачей отчёта сверяй остатки по счетам с банком."), 0)
        self.assertEqual(curation.предложить("главбух", "коротко"), 0)
        self.assertEqual(curation.предложить("нет_такого", "Перед сдачей отчёта сверяй остатки по счетам"), 0)

    def test_принятое_видят_коллеги_но_не_автор_и_не_чужой_кабинет(self):
        номер = curation.предложить("главбух", "Перед сдачей отчёта сверяй остатки по счетам с банком")
        self.assertEqual(curation.для_агента("ос_ведущий"), [])        # пока не подтверждено
        curation.решить(номер, True)
        self.assertEqual(len(curation.для_агента("ос_ведущий")), 1)
        self.assertEqual(curation.для_агента("главбух"), [])
        self.assertEqual(curation.для_агента("юрист"), [])
        self.assertIn("Общие знания твоего кабинета", agents.правила("ос_ведущий"))
        self.assertFalse(curation.решить(номер, False))                # уже решено

    def test_руководитель_кабинета_решает_по_предложениям(self):
        а = curation.предложить("главбух", "Перед сдачей отчёта сверяй остатки по счетам с банком")
        б = curation.предложить("ос_ведущий", "Всегда пиши аккуратно и вежливо в любом ответе")
        self.ответы = [json.dumps({"решения": [{"номер": а, "принять": True}, {"номер": б, "принять": False}, {"номер": 999, "принять": True}]})]
        итог = curation.рассмотреть(Н)
        self.assertEqual(итог, {"принято": 1, "отклонено": 1})
        self.assertEqual([з["статус"] for з in curation.пул()], ["принято", "отклонено"])

    def test_приём_из_учёбы_становится_предложением(self):
        agents.добавить_заметку("главбух", "приём", "x", "сам")
        ответ = json.dumps({"приём": "Сверяй остатки по счетам с банком перед сдачей отчёта", "урок": {"кому": "", "текст": ""}, "принять": []})
        self.ответы = [ответ]
        learning._спросить = lambda н, система, данные: ответ
        старое = learning._не_прошёл_проверку
        learning._не_прошёл_проверку = lambda *а: False
        try:
            learning.разобрать("главбух", [{"вид": "поправка", "хозяин_написал": "нет"}], Н)
        finally:
            learning._не_прошёл_проверку = старое
        self.assertEqual(len(curation.пул(статус="предложено")), 1)


class Откат(Основа):
    def _испортить(self, агент, всего=6, плохих=3):
        for и in range(всего):
            decisions.записать("ответ", f"в{и}", [агент], [], "ок")
        записи = decisions._читать()
        for з in записи[:плохих]:
            decisions.обновить(з["id"], статус="исправлено")

    def test_свежий_приём_снимается_при_частых_исправлениях(self):
        agents.добавить_заметку("главбух", "приём", "Старый приём от вас", "вы")
        agents.добавить_заметку("главбух", "приём", "Свежий выученный приём про остатки", "сам")
        self._испортить("главбух")
        действия = curation.проверить_качество()
        self.assertEqual(len(действия), 1)
        тексты = [з["текст"] for з in agents.заметки("главбух")]
        self.assertNotIn("Свежий выученный приём про остатки", тексты)
        self.assertIn("Старый приём от вас", тексты)                  # «от вас» не трогаем
        self.assertEqual(curation.проверить_качество(), [])           # повторно без новых ответов — не откатывает
        self.assertTrue(any("откат" in з["действие"] for з in audit.список()))

    def test_мало_ответов_или_нет_свежих_приёмов_ничего_не_трогает(self):
        agents.добавить_заметку("главбух", "приём", "Свежий выученный приём про остатки", "сам")
        self._испортить("главбух", всего=3, плохих=3)
        self.assertEqual(curation.проверить_качество(), [])
        self._испортить("юрист")
        self.assertEqual(curation.проверить_качество(), [])           # у юриста нечего снимать


class Чистка(Основа):
    def test_повторы_убираются_а_правила_от_вас_остаются(self):
        agents.добавить_заметку("главбух", "правило", "Правило хозяина про остатки счетов", "вы")
        agents.добавить_заметку("главбух", "приём", "Сверяй остатки по счетам с банком перед отчётом", "сам")
        agents.добавить_заметку("главбух", "приём", "сверяй остатки по счетам с банком перед отчётом!", "сам")
        итог = curation.недельная_чистка()
        self.assertEqual(итог["повторов"], 1)
        виды = [(з["вид"]) for з in agents.заметки("главбух")]
        self.assertEqual(sorted(виды), ["правило", "приём"])

    def test_устаревший_приём_убирается(self):
        з = agents.добавить_заметку("главбух", "приём", "Давний приём про старый порядок отчётов", "сам")
        with self.база.соединение() as связь:
            связь.execute("UPDATE агент_заметки SET создано = datetime('now', 'localtime', '-90 days') WHERE id = ?", (з["id"],))
        self.assertEqual(curation.недельная_чистка()["устарело"], 1)

    def test_сообщение_только_если_что_то_сделано(self):
        self.assertEqual(curation._сообщение_чистки({"пул_принято": 0, "пул_отклонено": 0, "повторов": 0, "устарело": 0, "общих_повторов": 0}), "")
        self.assertIn("убрано повторов", curation._сообщение_чистки({"пул_принято": 0, "пул_отклонено": 0, "повторов": 2, "устарело": 0, "общих_повторов": 0}))


class Эталоны(Основа):
    def test_набор_вопросов_покрывает_главные_кабинеты(self):
        каб = {в["кабинет"] for в in evals.ВОПРОСЫ}
        self.assertEqual(каб, set(collective.ГЛАВНЫЕ_КАБИНЕТЫ))
        self.assertEqual(len({в["id"] for в in evals.ВОПРОСЫ}), len(evals.ВОПРОСЫ))

    def test_прогон_считает_баллы_и_сравнивает_с_прошлым(self):
        def ложный(система, данные, н, max_tokens):
            if "проверяющий ответов" in система:
                return json.dumps({"балл": 1 if "лизинг" not in данные["вопрос"] else 0.5, "замечание": ""})
            return "Нет данных: не хватает сведений."
        ai._задание = ложный
        evals.задать_свои([{"id": "а", "кабинет": "бухгалтерия", "вопрос": "Сколько налог?", "должно": "нет данных"},
                           {"id": "б", "кабинет": "юристы", "вопрос": "Брать в лизинг?", "должно": "оговорки"},
                           {"id": "плохой", "кабинет": "несуществующий", "вопрос": "?", "должно": "?"}])
        п = evals.прогон(Н)
        self.assertEqual((п["баллов"], п["из"], п["пропущено"]), (1.5, 2, 0))
        self.assertIsNone(п["к_прошлому"])
        ai._задание = lambda с, д, н, m: json.dumps({"балл": 1}) if "проверяющий ответов" in с else "Нет данных."
        п2 = evals.прогон(Н)
        self.assertEqual(п2["к_прошлому"], 0.5)
        self.assertEqual(len(evals.прогоны(5)), 2)
        self.assertFalse(evals.ПРОГРЕСС["идёт"])

    def test_сбой_судьи_не_считается_баллом(self):
        ai._задание = lambda с, д, н, m: "не json" if "проверяющий ответов" in с else "Ответ."
        evals.задать_свои([{"id": "а", "кабинет": "бухгалтерия", "вопрос": "Сколько налог?", "должно": "нет данных"}])
        п = evals.прогон(Н)
        self.assertEqual((п["из"], п["пропущено"]), (0, 1))

    def test_ошибка_ии_не_роняет_прогон(self):
        def упал(*а, **к):
            raise ai.ОшибкаИИ("лимит")
        ai._задание = упал
        evals.задать_свои([{"id": "а", "кабинет": "бухгалтерия", "вопрос": "Сколько налог?", "должно": "нет данных"}])
        п = evals.прогон(Н)
        self.assertEqual(п["пропущено"], 1)


